/** 한 줄이 «고쳐야 하는 부름»인가 */
export function 부름인가(줄) {
  if (typeof 줄 !== 'string') return null;
  if (!사라질자리.some((u) => 줄.includes(u)) && !/\.claude-u[24]\b/.test(줄)) return null;
  if (기록꼴.some((표) => 표.test(줄))) return { 부름: false, 왜: '기록이다 — 고칠 것이 아니다' };
  const 걸린것 = 부름꼴.filter((k) => k.표.test(줄));
  if (걸린것.length === 0) return { 부름: false, 왜: '이름만 적혀 있다' };
  return { 부름: true, 갈래: 걸린것.map((k) => k.이름) };
}

/** 폴더를 걸어 파일 목록을 얻는다. ⛔ git 을 안 쓴다 — 한글 경로를 따옴표로 감싸기 때문이다 */
export function 파일걸기(뿌리, 안볼 = 안볼곳, 확장자 = 볼확장자, 깊이 = 0) {
  if (깊이 > 8) return [];
  let 것들;
  try { 것들 = fs.readdirSync(뿌리, { withFileTypes: true }); } catch { return []; }
  const 낸것 = [];
  for (const it of 것들) {
    if (안볼.some((x) => it.name === x || it.name.includes(x))) continue;
    const 길 = path.join(뿌리, it.name);
    if (it.isDirectory()) 낸것.push(...파일걸기(길, 안볼, 확장자, 깊이 + 1));
    else if (확장자.includes(path.extname(it.name))) 낸것.push(길);
  }
  return 낸것;
}

