  // 부름으로 잡아야 하는 것
  본다('담당 칸에 적힌 것을 잡는다', 부름인가('| F7 | API | 담당 2번 | 10-03 |')?.부름 === true);
  본다('그 유닛이 한다를 잡는다', 부름인가('4번이 GSC 를 매일 잰다')?.부름 === true);
  본다('물으라는 안내를 잡는다', 부름인가('막히면 2번에게 물어라')?.부름 === true);
  본다('회신 대기를 잡는다', 부름인가('2번 회신을 기다린다')?.부름 === true);
  본다('자리 경로를 잡는다', 부름인가('CLAUDE_CONFIG_DIR=.claude-u4')?.부름 === true);
  본다('넘김을 잡는다', 부름인가('이 일을 4번에게 넘긴다')?.부름 === true);
  본다('갈래 이름을 함께 낸다', (부름인가('담당 2번')?.갈래 ?? []).length > 0);

  // 기록으로 빼야 하는 것
  본다('메모 머리(보낸 것)는 기록이다', 부름인가('## [2번 → 5번] 소통')?.부름 === false);
  본다('메모 머리(받는 것)도 기록이다', 부름인가('## [5번 → 4번] 회신')?.부름 === false);
  본다('그 유닛이 한 일의 기록은 뺀다', 부름인가('2번이 잡아 준 것이 맞다')?.부름 === false);
  본다('실측 기록은 뺀다', 부름인가('4번 실측 — GSC 노출 0줄')?.부름 === false);
  본다('날짜가 붙은 줄은 기록이다', 부름인가('2026-09-10 에 2번이 한다고 했다')?.부름 === false);
  본다('이름만 있으면 부름이 아니다', 부름인가('2번')?.부름 === false);

  // 아예 상관없는 줄
  본다('그 유닛 이름이 없으면 null', 부름인가('3번이 한다') === null);
  본다('글이 아니면 null', 부름인가(null) === null);
  본다('빈 줄은 null', 부름인가('') === null);
