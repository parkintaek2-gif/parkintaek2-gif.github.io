/* ── 실행 ───────────────────────────────────────────────────────── */

const 내가실행됐다 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

function 센다() {
  const 찾은것 = [];
  const 못읽은것 = [];
  let 본파일 = 0;
  const 나자신 = path.basename(fileURLToPath(import.meta.url));

  for (const 저장소 of 볼저장소) {
    if (!fs.existsSync(저장소.길)) { 못읽은것.push(`${저장소.이름} — 그 저장소가 없다`); continue; }
    for (const 파일 of 파일걸기(저장소.길)) {
      if (path.basename(파일) === 나자신) continue;              // 자기 이름을 보고 울지 않는다
      if (파일.includes('사라지는자리-부르는곳')) continue;        // 낼 파일도 세지 않는다
      본파일 += 1;
      let 글;
      try { 글 = fs.readFileSync(파일, 'utf8'); } catch { 못읽은것.push(파일); continue; }
      const 줄들 = 글.split(/\r?\n/);
      for (let i = 0; i < 줄들.length; i += 1) {
        const 답 = 부름인가(줄들[i]);
        if (답?.부름) {
          찾은것.push({
            저장소: 저장소.이름,
            파일: path.relative(저장소.길, 파일).replace(/\\/g, '/'),
            줄: i + 1,
            갈래: 답.갈래.join('·'),
            글: 줄들[i].trim().slice(0, 110),
          });
        }
      }
    }
  }
  return { 찾은것, 못읽은것, 본파일 };
}

if (내가실행됐다) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);

  const { 찾은것, 못읽은것, 본파일 } = 센다();
  console.log('■ 사라지는 자리(2번·4번)를 아직 «부르고 있는» 곳\n');
  console.log(`   본 파일 ${본파일}개 · 저장소 ${볼저장소.length}곳 · 못 읽은 것 ${못읽은것.length}개\n`);

  const 갈래별 = new Map();
  for (const r of 찾은것) 갈래별.set(r.갈래, (갈래별.get(r.갈래) ?? 0) + 1);
  for (const [k, n] of [...갈래별.entries()].sort((a, b) => b[1] - a[1])) {
    console.log(`   ${String(n).padStart(4)}곳  ${k}`);
  }

  console.log(`\n   ⇒ 모두 ${찾은것.length}곳\n`);
  for (const r of 찾은것.slice(0, 30)) {
    console.log(`   ${r.저장소}/${r.파일}:${r.줄}`);
    console.log(`      [${r.갈래}] ${r.글}`);
  }
  if (찾은것.length > 30) console.log(`   … 그리고 ${찾은것.length - 30}곳 더 (--적는다 로 전부 낸다)`);

  if (못읽은것.length) {
    console.log('\n   ⬜ 못 읽은 것 — 0 으로 세지 않는다');
    for (const x of 못읽은것.slice(0, 5)) console.log(`      ${x}`);
  }

  if (process.argv.includes('--적는다')) {
    const 줄들 = ['# 사라지는 자리를 부르는 곳 — 이 수가 0 이 될 때까지 전환이 끝나지 않았다',
      `# 잰때\t${new Date().toLocaleString('sv-SE').slice(0, 16)}\t본파일\t${본파일}\t찾은곳\t${찾은것.length}`,
      '# 저장소\t파일\t줄\t갈래\t글'];
    for (const r of 찾은것) 줄들.push([r.저장소, r.파일, r.줄, r.갈래, r.글].join('\t'));
    fs.writeFileSync('docs/사라지는자리-부르는곳.tsv', 줄들.join('\n') + '\n', 'utf8');
    console.log('\n   ✔ 적었다 — docs/사라지는자리-부르는곳.tsv');
  }

  console.log('\n🔴 사장님 지시 — 「조직 변경할 때 철저하고 꼼꼼하게 해서 어떤 문제도 생기지 않도록」');
  console.log('   ⛔ 이 수가 0 이 아니면 9/21 에 그 자리들이 «없는 사람»을 부르며 운다.');
  console.log('   ✅ 고치는 길은 하나다 — 그 줄의 담당을 «남는 넷» 가운데 하나로 다시 적는다.');
  process.exit(0);
}
