#!/usr/bin/env node
/**
 * revenue-forecast.mjs — SeoulMarkets + WikiTip 매출 계획을 계산한다.
 * ─────────────────────────────────────────────────────────────────────────
 * [왜 도구로 만드나]
 * 문서에 손으로 적으면 가정이 바뀌는 순간 문서가 조용히 틀려진다.
 * 실제로 그랬다 — `docs/사업전략-데이터제공업.md` §5.5 는 같은 문서 안에서
 * 앞에선 「AUM 5천억 × 10개 × 0.03% → 15억」이라 적고 표에선 「150억」이라 적었다.
 * 10배 차이다. 사람이 표를 손으로 채우면 이런 게 안 잡힌다.
 *
 * [2026-08-02 전면 개정 — 인력은 사장님 한 사람이다]
 * 앞 판은 「2029년 기관 계약 70곳 · 영업 12명」을 전제했다. **그 전제가 없다.**
 * 그래서 매출원을 성질로 갈랐다. 이것이 이 계획의 핵심이다.
 *
 *   사람 수에 비례하는 것   기관 직접 영업 — 1인이면 연 5~8곳이 상한. **본체로 못 쓴다**
 *   사람 수와 무관한 것     지수(AUM 비례) · 리셀러(남이 판다) · 셀프서브 · 광고
 *
 * 1인 회사의 계획은 **후자만으로 세워야 한다.** 전자를 넣으면 그 순간 거짓말이 된다.
 *
 * [무엇이 사실이고 무엇이 가정인가]
 *   사실 = 단가 구조(tools/pricing.json) · 오늘의 아카이브 규모 · 도메인 라이브 · 인력 1명
 *   가정 = AUM · 파트너 수 · 구독자 수 · 트래픽   ← 전부 ASSUMPTIONS 한 곳에 있다
 *
 * 사용
 *   node tools/revenue-forecast.mjs            표만 출력
 *   node tools/revenue-forecast.mjs --json     계산 원본값
 *   node tools/revenue-forecast.mjs --write    계획서에 직접 써 넣는다
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DOC = path.join(HERE, '..', 'docs/매출계획-2026-2029.md');
const P = JSON.parse(readFileSync(path.join(HERE, 'pricing.json'), 'utf8'));

const 억 = 1e8;
const 조 = 1e12;

/* ── 가정 — 전부 여기에 있다 ───────────────────────────────────────────
 *
 * 목표: 2029년 500억 (2026-08-02 사장님 지시)
 * 제약: **인력 1명.** 채용 계획 없음
 *
 * 아래는 「1인이 물리적으로 할 수 있는 일의 양」을 상한으로 잡은 값이다.
 * 낙관도 비관도 아니고, 계약 협상 한 건에 드는 시간에서 역산했다.
 */
const ASSUMPTIONS = {
  2026: {
    라벨: '2026 (8~12월)',
    지수상품수: 0, 상품평균AUM: 0,
    리셀러파트너: 0, 파트너당배분억: 0,
    devA: 0, bizA: 0,
    월PV: 30_000,
    커머스억: 0,
    개월: 5,
    사건: '아카이브 · 색인 · 애드센스. **지수 백테스트 착수**(12년치가 이미 있다)',
  },
  2027: {
    라벨: '2027',
    지수상품수: 1, 상품평균AUM: 0.3 * 조,
    리셀러파트너: 1, 파트너당배분억: 2,
    devA: 150, bizA: 5,
    월PV: 3_000_000,
    커머스억: 2,
    개월: 12,
    // 1인이 한 해에 제대로 붙일 수 있는 「깊은 협상」은 2~3건이다.
    // 운용사 1곳 + 벤더 1곳이면 그 해는 꽉 찬다.
    사건: '**첫 ETF 상장**(운용사 1곳) · **벤더 재판매 1곳** · 셀프서브 유료화',
  },
  2028: {
    라벨: '2028',
    지수상품수: 5, 상품평균AUM: 0.8 * 조,
    리셀러파트너: 3, 파트너당배분억: 8,
    devA: 400, bizA: 20,
    월PV: 12_000_000,
    커머스억: 12,
    개월: 12,
    사건: '상품 5개 · AUM 4조 · 재판매 3곳. **해외 상장 협의 착수**',
  },
  2029: {
    라벨: '2029',
    지수상품수: 12, 상품평균AUM: 1.0 * 조,
    리셀러파트너: 5, 파트너당배분억: 15,
    devA: 800, bizA: 40,
    월PV: 33_000_000,
    커머스억: 25,
    개월: 12,
    사건: '**AUM 12조 · 재판매 5곳.** 전부 남이 팔고 남이 굴린다',
  },
};

const TARGET_2029 = 500 * 억;
/** 1인이 직접 영업으로 딸 수 있는 기관 계약의 연간 상한. 계약당 실사·협상 3~6개월. */
const 직접영업상한_연 = 6;

/* ── 비용 — 자금이 없다. 그 해 매출 안에서만 쓴다 ──────────────────────
 *
 * 이 사업이 자금이 적게 드는 것은 사실이다. 실측으로 확인한 것부터 적는다.
 *
 *   아카이브 저장   현재 153MB · 전체 받아도 250MB 안쪽. 압축하면 12MB.
 *                   R2 무료 구간이 10GB 다  →  **0원**
 *   원천 데이터     공공데이터포털 무료 · 네이버 목록은 우리 PC 로 받는다  →  **0원**
 *   호스팅          Cloudtype 0.25GB(최소 단위). 실행 실측 47.6MB 라 더 못 줄인다
 *   도메인          Spaceship 연 2~3만원
 *
 * ⚠ 확인 안 된 것이 하나 있고, 그게 유일하게 큰 항목이다 — **지수 산출의 거버넌스 비용**.
 *   운용사는 지수 산출의 독립성·감사 가능성을 요구한다. 그 검증을 누가 어떤 비용으로
 *   하는지 아직 모른다. 2026년 4분기 법률 검토에서 같이 확인한다.
 *   아래 값은 그 자리를 비워두지 않으려고 넣은 **가정**이다.
 */
const COST = {
  2026: { 고정: 0.01, 지수거버넌스: 0, 외주: 0 },
  2027: { 고정: 0.02, 지수거버넌스: 0.5, 외주: 0.3 },
  2028: { 고정: 0.05, 지수거버넌스: 3, 외주: 3 },
  2029: { 고정: 0.1, 지수거버넌스: 8, 외주: 10 },
};

/* ── 계산 ────────────────────────────────────────────────────────────── */

function year(a) {
  const aum = a.지수상품수 * a.상품평균AUM;
  const index = aum * P.index.요율 * (a.개월 / 12);
  const resell = a.리셀러파트너 * a.파트너당배분억 * 억;
  const selfserve = a.devA * P.api.dev.월요금 * a.개월 + a.bizA * P.api.business.연요금;
  const ads = (a.월PV / 1000) * P.ads.천PV당원 * a.개월;
  const commerce = a.커머스억 * 억;
  return { aum, index, resell, selfserve, ads, commerce, total: index + resell + selfserve + ads + commerce };
}

const rows = Object.entries(ASSUMPTIONS).map(([y, a]) => ({ y, a, r: year(a) }));
const last = rows.at(-1);
const gap = TARGET_2029 - last.r.total;
const 억표 = (n) => (n / 억).toFixed(n < 억 ? 2 : 1);

/* ── 출력 ────────────────────────────────────────────────────────────── */

function markdown() {
  const L = [];
  L.push(
    '> 이 표는 `tools/revenue-forecast.mjs` 가 계산해 써 넣은 것이다. **손으로 고치지 마십시오** —',
    '> 다음 실행에 덮인다. 숫자를 바꾸려면 그 파일의 `ASSUMPTIONS` 를 고쳐 다시 돌린다.',
    '',
    '**전제: 인력 1명.** 채용을 전제한 매출원은 이 표에 없다.',
    '',
    '단위: 억원',
    '',
    '| 연도 | 지수(AUM) | 재판매 | 셀프서브 | 광고 | 커머스 | **합계** | 그 해에 일어나야 하는 일 |',
    '|---|---:|---:|---:|---:|---:|---:|---|',
  );
  for (const { a, r } of rows) {
    L.push(
      `| **${a.라벨}** | ${억표(r.index)} | ${억표(r.resell)} | ${억표(r.selfserve)} | ${억표(r.ads)} | ${억표(r.commerce)} | **${억표(r.total)}** | ${a.사건} |`,
    );
  }

  // 1인이 직접 팔았다면 얼마였을지 — 왜 구조를 바꿔야 하는지를 숫자로 보인다.
  const 직접최대 = 직접영업상한_연 * 3 * P.api.institutional.연요금; // 2027~29 3년

  // 자금이 없다. 그 해 벌어서 그 해 쓴다 — 누적이 음수로 내려가면 계획이 아니라 소망이다.
  L.push(
    '',
    '### 자금 — 벌면서 쓴다 (선투자 0원)',
    '',
    '| 연도 | 매출 | 비용 | 그 해 잔액 | **누적** |',
    '|---|---:|---:|---:|---:|',
  );
  let 누적 = 0;
  for (const { y, r } of rows) {
    const c = COST[y];
    const cost = (c.고정 + c.지수거버넌스 + c.외주) * 억;
    누적 += r.total - cost;
    L.push(`| ${y} | ${억표(r.total)} | ${억표(cost)} | ${억표(r.total - cost)} | **${억표(누적)}** |`);
  }
  L.push(
    '',
    '**누적이 한 해도 음수로 내려가지 않는다.** 이 사업은 원래 돈이 적게 든다 —',
    '아카이브 250MB 는 R2 무료 구간(10GB) 안이고, 원천 데이터는 공공데이터포털 무료이며,',
    '호스팅은 최소 단위 0.25GB 로 충분하다(실행 실측 47.6MB). **고정비가 연 몇 만원대다.**',
    '',
    '⚠ 다만 **지수 산출의 거버넌스 비용은 아직 확인 못 했다.** 운용사는 산출의 독립성과',
    '감사 가능성을 요구하는데, 그 검증을 누가 얼마에 하는지 모른다. 위 표의 그 줄은 가정이다.',
    '**2026년 4분기 법률 검토에서 같이 확인한다** — 이것이 이 계획에서 유일하게 큰 비용 항목이다.',
    '',
    '### 왜 「기관 직접 영업」이 표에 없는가',
    '',
    '| | 3년간 도달 가능 |',
    '|---|---:|',
    `| 1인 직접 영업 (연 ${직접영업상한_연}곳 상한 × 3년 × 연 ${억표(P.api.institutional.연요금)}억) | **${억표(직접최대)}억** |`,
    `| 위 표의 2029년 | **${억표(last.r.total)}억** |`,
    '',
    '**직접 영업은 1인 회사에서 계획의 본체가 될 수 없다.** 위 표의 매출원은 전부',
    '「우리가 일을 더 해서」가 아니라 **「남이 팔거나, 남의 돈이 불어나서」** 늘어나는 것이다.',
    '',
    '### 목표까지 — 감추지 않는다',
    '',
    '| | 억원 |',
    '|---|---:|',
    '| 2029년 목표 (사장님 지시) | **500.0** |',
    `| 1인 전제로 계산된 2029년 | **${억표(last.r.total)}** |`,
    `| **차이** | **${억표(gap)}** |`,
    '',
  );

  // 차액을 메우는 길 — 전부 「사람을 안 늘리고」 가능한 것만 센다.
  const 필요AUM = (TARGET_2029 - (last.r.total - last.r.index)) / P.index.요율;
  const 요율상단 = 0.001;
  const 상단AUM = (TARGET_2029 - (last.r.total - last.r.index)) / 요율상단;
  const 추가파트너 = Math.ceil(gap / (last.a.파트너당배분억 * 억));

  L.push(
    '**사람을 안 늘리고 메우는 길은 셋이다.**',
    '',
    '| 길 | 필요한 것 | 지금 가정 | 판단 |',
    '|---|---|---|---|',
    `| ① 추종 AUM 을 키운다 | **${(필요AUM / 조).toFixed(0)}조원** | ${(last.r.aum / 조).toFixed(0)}조원 | 국내만으로는 안 된다. **해외 상장 ETF 가 우리 지수를 쓰게 해야** 한다 |`,
    `| ② 요율을 업계 상단으로 | 0.10% + AUM **${(상단AUM / 조).toFixed(0)}조** | ${(P.index.요율 * 100).toFixed(2)}% · ${(last.r.aum / 조).toFixed(0)}조 | 요율은 협상 사항. 독점 데이터면 가능 |`,
    `| ③ 재판매 파트너를 늘린다 | **${last.a.리셀러파트너 + 추가파트너}곳** (곳당 연 ${last.a.파트너당배분억}억) | ${last.a.리셀러파트너}곳 | 계약은 1인이 해도 **판매는 파트너가 한다.** 가장 현실적 |`,
    '',
    '**①과 ③은 같이 간다.** 파트너가 늘면 지수 노출이 늘고, 지수 AUM 이 늘면 파트너가 붙는다.',
    '',
  );
  return L.join('\n');
}

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ 인력: 1, rows: rows.map((x) => ({ 연도: x.y, ...x.r })), 목표: TARGET_2029, 차이: gap }, null, 2));
} else if (process.argv.includes('--write')) {
  const doc = readFileSync(DOC, 'utf8');
  const A = '<!-- FORECAST:START -->';
  const B = '<!-- FORECAST:END -->';
  const i = doc.indexOf(A);
  const j = doc.indexOf(B);
  if (i < 0 || j < 0) {
    console.error(`계획서에 ${A} / ${B} 표시가 없습니다.`);
    process.exit(1);
  }
  writeFileSync(DOC, doc.slice(0, i + A.length) + '\n' + markdown() + doc.slice(j));
  console.log(`써 넣었습니다 → ${DOC}`);
  console.log(`  2029년 계산값 ${억표(last.r.total)}억 · 목표 500억 · 차이 ${억표(gap)}억`);
} else {
  console.log(markdown());
}
