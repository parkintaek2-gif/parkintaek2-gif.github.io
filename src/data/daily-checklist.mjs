/** 그 시각에 그 사이트가 볼 항목 */
export function 볼것(사이트코드, 때코드) {
  const s = 사이트[사이트코드];
  if (!s) return [];
  if (!때[때코드]) return [];
  return 항목.filter((it) => {
    if (!it.때들.includes(때코드)) return false;
    if (it.갈래 === 'all') return true;
    return it.갈래 === (s.유료 ? 'paid' : 'free');
  });
}

/** 지금 시각에 가장 가까운 «지난» 때. ⛔ toISOString() 을 쓰지 않는다 — 이 PC 는 이미 KST 다 */
export function 지금때(날 = new Date()) {
  const h = 날.getHours();
  if (h >= 때.마감.시) return '마감';
  if (h >= 때.낮.시) return '낮';
  return '아침';
}

/** 그 항목을 그 사이트에서 «자»로 잴 수 있나 */
export function 잴수있나(항목하나, 사이트코드) {
  if (항목하나.재는법 === '손') return false;
  const 길 = 항목하나.길 || {};
  return Boolean(길[사이트코드] || 길.전체);
}

export function 길찾기(항목하나, 사이트코드) {
  const 길 = 항목하나.길 || {};
  return 길[사이트코드] || 길.전체 || null;
}
