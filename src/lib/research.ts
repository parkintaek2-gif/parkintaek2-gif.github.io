/**
 * 지면에 붙일 **국책연구**를 고른다.
 *
 * ⭐ 백년지도가 내는 것은 숫자다. 부모가 다음에 묻는 것은 「왜 그렇게 되나?」인데
 *   그건 우리가 답할 수 없다. 국책연구원이 이미 썼고, 우리는 **가리키기만 한다.**
 *
 * ⛔ **「이 학교/이 학과에 대한 연구」가 아니다.** 주제가 같을 뿐이다.
 *   그 말을 지면에 반드시 붙인다. 안 붙이면 우리가 없는 관련성을 파는 것이 된다.
 *
 * ⛔ 얇은 지면을 채우려고 아무 데나 붙이지 않는다.
 *   일반고 1,353장에 같은 링크 셋을 박으면 그건 **속 빈 반복**이다.
 *   주제가 실제로 닿는 곳에만 붙인다 — 대학 지면(고등교육) · 학과 지면(직업교육·노동).
 *
 * ⚠ 순위가 아니다. 발행일이 새것부터다.
 */
import 연구자료 from '../data/100yearmap/pages-research.json';

export type 연구 = {
  제목: string;
  저자: string[];
  발행일: string | null;
  분류: string[];
  종류: string | null;
  url: string;
};

const 전체 = (연구자료 as any).자료 as 연구[];

/** 이 분류들에 걸리는 연구를 새것부터 n편 */
export function 연구고르기(분류들: string[], n = 3): 연구[] {
  return 전체.filter((r) => r.분류.some((k) => 분류들.includes(k))).slice(0, n);
}

/** 대학 지면 — 대학이라는 길 자체를 다룬 연구 */
export const 대학연구 = () => 연구고르기(['고등교육(대학)'], 3);

/** 학과 지면 — 직업계고 학과다. 직업교육과 그 뒤의 노동시장 */
export const 학과연구 = () => 연구고르기(['직업교육', '특정 노동시장', '임금·임금격차'], 3);

export const 전체편수 = 전체.length;
