/**
 * 지면에 붙일 **국책연구**를 고른다.
 *
 * ⭐ 백년지도가 내는 것은 숫자다. 부모가 다음에 묻는 것은 「왜 그렇게 되나?」인데
 *   그건 우리가 답할 수 없다. 국책연구원이 이미 썼고, 우리는 **가리키기만 한다.**
 *
 * ⛔ **「이 학교/이 학과에 대한 연구」가 아니다.** 주제가 같을 뿐이다.
 *   그 말을 지면에 반드시 붙인다. 안 붙이면 우리가 없는 관련성을 파는 것이 된다.
 *
 * ⛔ 얇은 지면을 채우려고 아무 데나 붙이지 않는다.
 *   일반고 1,353장에 같은 링크 셋을 박으면 그건 **속 빈 반복**이다.
 *   주제가 실제로 닿는 곳에만 붙인다 — 대학 지면(고등교육) · 학과 지면(직업교육·노동).
 *
 * ⚠ 순위가 아니다. 발행일이 새것부터다.
 */
import 연구자료 from '../data/100yearmap/pages-research.json';

export type 연구 = {
  제목: string;
  저자: string[];
  발행일: string | null;
  분류: string[];
  종류: string | null;
  url: string;
};

/**
 * 🔴 **저자 칸에 여럿이 `|` 로 묶여 들어 있다** (2026-08-07 실측 · 90편 중 17편).
 *
 *   ```
 *   원자료  ["김민섭", "양희승", "윤참나|최재성"]
 *   화면    김민섭, 양희승, 윤참나|최재성       ← 마지막이 **한 사람 이름**으로 나갔다
 *   ```
 *
 *   ⛔ 오류가 안 뜬다. 글자를 하나도 안 잃으니 검사도 안 잡는다. **떠서 봐야 보였다.**
 *     1번이 오늘 겪은 것과 같은 꼴이다 — 콘텐츠 렌더러에 표 갈래가 없어 220편이
 *     파이프째 손님 화면에 찍혔는데, 역시 아무도 안 죽었다. 그 말을 듣고 우리 지면을
 *     4,700장 훑어 이 한 자리를 찾았다.
 *
 *   ⚠ 고치는 자리를 **여기 한 곳**으로 둔다. 지면마다 `split` 을 흩어 놓으면
 *     한 곳만 고쳐지고 나머지는 조용히 그대로 남는다.
 */
export const 저자풀기 = (저자: string[] | null | undefined): string[] => {
  if (!Array.isArray(저자)) return [];
  const 본것 = new Set<string>();
  const 결과: string[] = [];
  for (const 한칸 of 저자) {
    for (const 이름 of String(한칸).split(/[|·,]/)) {
      const t = 이름.trim();
      /* 같은 이름이 두 번 들어오는 것을 막는다. 원자료에서 실제로 겹치는 것이 있다 */
      if (t && !본것.has(t)) {
        본것.add(t);
        결과.push(t);
      }
    }
  }
  return 결과;
};

/* ⛔ 원자료를 고치지 않는다. 읽을 때 푼다 — 다음에 다시 받아도 같은 모양으로 온다 */
const 전체 = ((연구자료 as any).자료 as 연구[]).map((r) => ({ ...r, 저자: 저자풀기(r.저자) }));

/** 이 분류들에 걸리는 연구를 새것부터 n편 */
export function 연구고르기(분류들: string[], n = 3): 연구[] {
  return 전체.filter((r) => r.분류.some((k) => 분류들.includes(k))).slice(0, n);
}

/** 대학 지면 — 대학이라는 길 자체를 다룬 연구 */
export const 대학연구 = () => 연구고르기(['고등교육(대학)'], 3);

/** 학과 지면 — 직업계고 학과다. 직업교육과 그 뒤의 노동시장 */
export const 학과연구 = () => 연구고르기(['직업교육', '특정 노동시장', '임금·임금격차'], 3);

export const 전체편수 = 전체.length;
