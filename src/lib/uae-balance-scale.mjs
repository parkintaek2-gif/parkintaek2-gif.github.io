/**
 * uae-balance-scale.mjs — **UAE 대차대조표의 «배수»를 가른다.** (5번, 2026-09-24)
 *
 * ── 🔴 왜 있나 ────────────────────────────────────────────────────────
 * UAE 재무 자료는 한 행 «안»에서 손익과 대차대조표의 단위가 다르다.
 *
 * ```
 *   손익(매출·순이익·EPS)   실제 AED — EPS × 주식수 ≈ 순이익 으로 검산된다
 *   대차(자산·부채·자본)     보고서에 적힌 그대로 — AED'000 인 곳이 많은데 안 곱했다
 * ```
 *
 * 실측(2026-09-24) — 매출이 총자산의 5배를 넘는 행이 155/224(69.2%)였고,
 * 그 수가 `unit_hint` 가 `AED'000` 인 행 수와 **정확히 같았다.**
 * 2POINTZERO 로 검산했다 — 시총 777억 AED ÷ 주가 2.25 = 345.6억 주,
 * `eps 0.206 × 345.6억 = 71.2억` ≈ 신고 순이익 77.3억. ⇒ 손익이 맞고 대차만 안 곱해졌다.
 *
 * ⚠ 이것은 «새로 찾은 결함»이 아니다. `build-screener-data.mjs` 머리글이 이미 적어 두었고,
 *   그래서 약분되는 것(부채비율)과 단위를 읽은 것(PBR)만 내고 ROE·PER 은 막아 두었다.
 *   ⇒ 손님에게 틀린 수는 나가지 않았다. 이 자는 그 «막아 둔 것을 여는» 열쇠다.
 *
 * ── ⛔ 이 자가 지키는 것 ───────────────────────────────────────────────
 * ⛔ **값을 만들지 않는다.** 배수 둘(1 또는 1000) 가운데 «고를» 뿐이다.
 *   2026-09-16 에 `주식수 = 순이익 ÷ EPS` 로 «만든» 판이 두바이 검산에서 16곳 중 2곳만
 *   맞았다. 그때의 잘못은 값을 지어낸 것이다 — 고르는 것은 지어내는 것이 아니다.
 * ⛔ **못 고르면 비운다.** 「아마 천 단위겠지」로 채우지 않는다. 천 배가 걸린 일이다.
 * ⛔ 통화를 섞지 않는다 — `unit_hint` 가 USD 계열이면 이 자는 손대지 않는다(따로 다룬다).
 *
 * ── 🔴 시가총액을 «쓰는» 것과 «싣는» 것은 다르다 ───────────────────────
 * ADX 시가총액은 2026-09-18 에 약관을 읽고 **손님 지면에 안 싣기로** 정했다
 * (`build-screener-data.mjs` 의 `ADX시총을_지면에_싣나 = false`). 거래소가 자기가 만들어
 * 파는 물건이라 상장사 법정공시와 같은 예외에 들지 않는다.
 *
 * ✅ 그 판정이 같은 자리에 이렇게 적어 두었다 — **「받는 것은 그대로 둔다 — 내부 검산용이다」.**
 *   이 자가 하는 일이 정확히 그것이다. 시총을 지면에 내지 않고, **배수 하나(1 또는 1000)만**
 *   가른다. 그 배수는 우리 판정이지 거래소의 자료가 아니다.
 * ⛔ 그러니 이 자를 근거로 「시총을 실어도 되겠네」로 넘어가지 않는다. 그 문은 아직 닫혀 있다.
 *
 * ── ⭐ 왜 시가총액으로 가를 수 있나 ────────────────────────────────────
 * 배수가 1 이냐 1000 이냐에 따라 PBR(시총÷자본)이 **정확히 1000배** 벌어진다.
 * 그래서 한쪽이 사람이 실제로 보는 범위 안이면 다른 쪽은 반드시 그 밖이다 — 겹치지 않는다.
 * ⇒ 「둘 다 말이 되는」 경우가 원리상 없으므로, 판정이 애매해질 일이 없다.
 *   둘 다 범위 밖이면 그때는 «모르는 것»이고, 그러면 비운다.
 */

/** 사람이 실제로 보는 PBR 의 범위. 이보다 넓게 잡으면 가르는 힘이 없고, 좁히면 버리는 것이 는다. */
export const PBR낮은쪽 = 0.15;
export const PBR높은쪽 = 15;

/** 대차대조표 단위 표기가 「천 단위」를 뜻하나 — AED 계열만 본다 */
export function 천단위표기인가(힌트) {
  const s = String(힌트 ?? '').trim();
  if (!s) return null;                       /* 표기가 없다 — 모르는 것이지 실단위가 아니다 */
  if (/^AED['’]?000$/i.test(s)) return true;
  if (/AED\s*million/i.test(s)) return false; /* 백만 단위는 이 자가 안 다룬다 */
  if (/^USD/i.test(s)) return false;          /* 통화가 다르다 — 이 자가 안 다룬다 */
  return null;
}

/**
 * 이 행의 대차대조표를 이 자가 다룰 수 있나 — 그리고 **못 다루면 왜인지 가른다.**
 *
 * 🔴 [2026-09-24] 처음에는 참·거짓만 냈다. 그랬더니 본 검사가 「안 다룸 164행」이라고
 *   한 덩이로 셌는데, 그 안에 성격이 아주 다른 둘이 섞여 있었다 —
 *   **자본이 아예 없는 줄**(자료가 없는 것)과 **통화가 달러인 줄**(따로 다룰 것).
 *   ⛔ 「못 쟀다」와 「자료가 없다」를 같은 칸에 넣으면 무엇을 더 해야 하는지 안 보인다.
 *     강령 ③ — 못 잰 것은 못 쟀다고 적는다. 못 잰 «까닭»까지 적어야 그 말이 쓸모가 있다.
 */
export function 다룰수있나까닭(행) {
  if (!행) return { 되나: false, 까닭: '줄이 없다' };
  const s = String(행.unit_hint ?? '').trim();
  if (/USD/i.test(s)) return { 되나: false, 까닭: '통화가 달러다' };
  if (/million/i.test(s)) return { 되나: false, 까닭: '백만 단위다' };
  const 자본 = Number(행.total_equity_aed);
  if (!Number.isFinite(자본)) return { 되나: false, 까닭: '자본 칸이 비어 있다' };
  if (자본 <= 0) return { 되나: false, 까닭: '자본이 0 이하다' };
  return { 되나: true, 까닭: null };
}

/** 이 행의 대차대조표를 이 자가 다룰 수 있나 */
export function 다룰수있나(행) {
  return 다룰수있나까닭(행).되나;
}

/** 이 PBR 이 사람이 보는 범위 안인가 */
export function 말되는PBR인가(v) {
  return Number.isFinite(v) && v >= PBR낮은쪽 && v <= PBR높은쪽;
}

/**
 * 한 행의 대차대조표 배수를 가른다.
 *
 * @param {object} 행       uae-financials-tape 의 한 줄
 * @param {number|null} 시총 그 종목의 시가총액(AED). 없으면 null
 * @returns {{배수: 1|1000|null, 어떻게: string, 왜: string|null}}
 */
export function 배수가르기(행, 시총) {
  const 볼수있나 = 다룰수있나까닭(행);
  if (!볼수있나.되나) {
    /* ⛔ 「자료가 없다」와 「따로 다뤄야 한다」를 한 칸에 넣지 않는다 — 위 주석 참고 */
    const 자료없음 = /비어 있다|0 이하|줄이 없다/.test(볼수있나.까닭);
    return { 배수: null, 어떻게: 자료없음 ? '자료 없음' : '따로 다룸', 왜: 볼수있나.까닭 };
  }

  /* ① 보고서가 «스스로» 적은 것이 가장 세다. 우리가 고르는 것보다 앞선다. */
  const 표기 = 천단위표기인가(행.unit_hint);
  if (표기 === true) return { 배수: 1000, 어떻게: '보고서 표기', 왜: null };
  if (표기 === false) return { 배수: 1, 어떻게: '보고서 표기', 왜: null };

  /* ② 표기가 없으면 시가총액으로 가른다. 두 PBR 은 1000배 떨어져 있어 겹치지 않는다. */
  const 자본 = Number(행.total_equity_aed);
  const cap = Number(시총);
  if (!Number.isFinite(cap) || cap <= 0) {
    return { 배수: null, 어떻게: '못 가름', 왜: '보고서에 단위 표기가 없고 시가총액도 없다' };
  }
  const 실단위 = 말되는PBR인가(cap / 자본);
  const 천단위 = 말되는PBR인가(cap / (자본 * 1000));
  if (실단위 && !천단위) return { 배수: 1, 어떻게: '시가총액 검산', 왜: null };
  if (천단위 && !실단위) return { 배수: 1000, 어떻게: '시가총액 검산', 왜: null };

  /* ③ 둘 다 범위 밖 — 모르는 것이다. 비운다. */
  return {
    배수: null,
    어떻게: '못 가름',
    왜: `시가총액으로도 못 갈랐다 — 실단위 PBR ${(cap / 자본).toFixed(3)}, `
      + `천단위 PBR ${(cap / (자본 * 1000)).toFixed(3)} 둘 다 ${PBR낮은쪽}~${PBR높은쪽} 밖이다`,
  };
}

/** 가른 배수로 대차대조표 세 칸을 실제 AED 로 돌려준다. 못 갈랐으면 셋 다 null */
export function 대차실값(행, 시총) {
  const { 배수, 어떻게, 왜 } = 배수가르기(행, 시총);
  const 곱 = (v) => {
    const n = Number(v);
    return (배수 === null || !Number.isFinite(n)) ? null : n * 배수;
  };
  return {
    배수, 어떻게, 왜,
    총자산: 곱(행?.total_assets_aed),
    총부채: 곱(행?.total_liabilities_aed),
    자본: 곱(행?.total_equity_aed),
  };
}
