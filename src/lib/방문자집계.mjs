/**
 * 쌓여 있는 것을 **지금 판별 규칙으로 다시 가른다.**
 * 규칙을 고치면 「바른 수치는 내일부터」가 아니라 **그 자리에서** 바뀌어야 한다.
 */
export function 다시가른다(날짜 = 오늘()) {
  const 칸 = 집계표.get(날짜);
  if (!칸) return 0;
  let 고침 = 0;
  for (const 것 of 칸.values()) {
    for (const 줄 of 것.지문들.values()) {
      /* ⛔ 이름이 안 남은 옛 줄은 다시 가르지 않는다 — 가를 재료가 없다.
         여기서 「이름이 없으니 사람이 아니다」로 밀면 옛 사람이 통째로 자동이 된다 */
      if (줄.이름 == null) continue;
      const 판 = 다시갈라본다(줄.이름);
      const 자동값 = 판 === null ? 줄.자동 : 판;
      const 불가값 = 판 === null ? 1 : 0;
      if (줄.자동 !== 자동값 || 줄.판별불가 !== 불가값) {
        줄.자동 = 자동값; 줄.판별불가 = 불가값; 고침 += 1;
      }
    }
  }
  /* 🔴 [2026-11-03] «우리»도 여기서 다시 가른다.
     목록은 서버가 뜬 «뒤에» 케이라이프맵에서 받아 온다. 그때 이미 쌓인 줄은
     우리 표시가 없는 채다 — 그대로 두면 그 날 오전치가 손님으로 남는다.
     ⛔ 주소 원본은 안 남기므로 되짚을 수 없다. 대신 **그 날 지문을 다시 만들어**
       견준다 — 지문은 (소금|날짜|주소)로 정해지므로 같은 날이면 같은 값이 나온다. */
  /* ⛔ **표를 붙이기만 하고 떼지 않는다.** 목록에 없다고 떼면 ① 다시 뜬 뒤 복원한 줄이
     손님으로 되돌아가고 ② 통신사가 주소를 바꾼 날 오전치가 통째로 손님이 된다.
     「우리였다」는 그때의 사실이지 지금 목록으로 뒤집을 것이 아니다. */
  const 우리것 = new Set(우리주소들().map((ip) => 지문(ip, 날짜)));
  if (우리것.size) {
    for (const 것 of 칸.values()) {
      for (const [값, 줄] of 것.지문들) {
        if (!줄.우리 && 우리것.has(값)) { 줄.우리 = 1; 고침 += 1; }
      }
    }
  }
  if (고침) 바뀜 = true;
  return 고침;
}

