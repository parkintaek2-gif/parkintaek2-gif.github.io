/**
 * 학교 지면에 **숫자가 하나도 없을 때, 왜 없는지**를 사실에서 계산한다.
 *
 * ## 🔴 왜 만드나 (2026-08-07 · 2번 지시)
 *
 *   *「손님이 학교를 검색해 들어왔는데 숫자가 하나도 없으면 그 지면은 없는 것과 같다.
 *     채울 자료가 없는 곳은 지면이 **왜 없는지를 글로** 말하게 한다」*
 *
 *   ⛔ **「자료가 없습니다」로 끝내지 않는다.** 그건 우리가 게을렀다는 말과 구분이 안 된다.
 *     **무엇이 막는지**까지 적어야 읽는 사람이 다음 걸음을 정할 수 있다.
 *
 * ## 채울 수 있는 것은 먼저 채웠다
 *
 *   105곳이었다. 학교알리미를 **학교급 `04` 만** 받고 있어서 `06`·`07` 에 있는 곳을 놓쳤다.
 *   그걸 고쳐 **103곳**이 됐다. 나머지는 아래 네 까닭 중 하나이고 **자료가 있을 수 없다.**
 *
 * ⛔ 짐작으로 까닭을 쓰지 않는다. 넷 다 **우리가 가진 사실**에서만 나온다 —
 *   설립일 · 학교 종류 · 학교알리미가 학생 수를 0으로 준 명단.
 */

export type 빈까닭 = {
  갈래: '신설' | '학생0' | '갈래다름' | '못찾음';
  한줄: string;
  풀이: string;
};

/**
 * @param 설립일  `20260301` 꼴. 없으면 null
 * @param 종류    `고등학교` · `각종학교(고)` · `평생학교(고)-3년6학기` · `고등기술학교`
 * @param 학생0명단 학교알리미가 **학생 수를 0으로 공시한** 학교 이름들
 * @param 공시연도 우리가 받은 공시 자료의 해 (예: `2024`)
 */
export function 빈까닭찾기(
  이름: string,
   설립일: string | null | undefined,
  종류: string | null | undefined,
  학생0명단: Set<string>,
  공시연도: string,
): 빈까닭 {
  const 연 = Number(String(설립일 ?? '').slice(0, 4));
  const 해 = Number(공시연도);

  /* ① 공시 뒤에 문을 연 학교 — 자료가 있을 수 없다. 제일 먼저 본다 */
  if (Number.isFinite(연) && 연 > 해) {
    return {
      갈래: '신설',
      한줄: `${연}년에 문을 연 학교라 ${공시연도}년 공시 자료가 없습니다`,
      풀이:
        `저희가 쓰는 숫자는 학교가 해마다 나라에 알리는 ${공시연도}년 공시 자료입니다. ` +
        `이 학교는 그 뒤에 문을 열었습니다. 빠뜨린 것이 아니라 아직 만들어진 적이 없는 숫자입니다. ` +
        `다음 공시가 나오면 이 자리에 채우겠습니다.`,
    };
  }

  /* ② 소속 학생 수가 0으로 공시된 학교 — 위탁 교육기관이 대부분이다 */
  if (학생0명단.has(이름)) {
    return {
      갈래: '학생0',
      한줄: '소속 학생 수가 0으로 공시돼 있어 비율을 낼 수 없습니다',
      풀이:
        '이런 학교는 대개 **다른 고등학교에 소속된 학생이 와서 배우는 곳**입니다. ' +
        '학생은 원래 다니던 학교 소속으로 남아 있어서, 이 학교의 학생 수는 0으로 공시됩니다. ' +
        '숫자가 0이라는 뜻이 아니라 **이 학교 이름으로 세지 않는다**는 뜻입니다.',
    };
  }

  /* ③ 갈래가 달라 공시 항목 자체가 없는 학교 */
  if (/각종학교|평생학교|고등기술/.test(String(종류 ?? ''))) {
    return {
      갈래: '갈래다름',
      한줄: `${종류}는 일반 고등학교와 공시 항목이 달라 저희가 쓰는 숫자가 없습니다`,
      풀이:
        '나라가 학교마다 알리게 하는 항목이 학교 갈래에 따라 다릅니다. ' +
        '졸업생 진로·학업중단·학급당 학생 수는 일반 고등학교 기준으로 모으는 것이라, ' +
        '이 갈래에는 애초에 그 항목이 없습니다. **저희가 못 찾은 것이 아닙니다.**',
    };
  }

  /* ④ 그 밖 — 명단에 없다. 이유를 모르면 모른다고 적는다 */
  return {
    갈래: '못찾음',
    한줄: `${공시연도}년 공시 명단에서 이 학교를 찾지 못했습니다`,
    풀이:
      '이름이 바뀌었거나, 다른 학교와 합쳐졌거나, 그해 공시에서 빠졌을 수 있습니다. ' +
      '⛔ **저희도 이유를 모릅니다.** 짐작해서 숫자를 만들지는 않겠습니다. ' +
      '이름이 바뀐 것이라면 다음 자료를 받을 때 이어 붙이겠습니다.',
  };
}
