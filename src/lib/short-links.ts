/**
 * 🔗 **밖에 적을 짧은 주소** — `/y/<이름>`
 *
 * ## 🔴 왜 (2026-08-10 06:0x · 2번 지시)
 *
 *   유튜브 227회에서 사이트 방문이 **0명**이었다. 까닭을 보다가 이걸 찾았다 —
 *   ```
 *   설명란 주소 셋 중 둘이 **잘려 보인다**
 *      https://100yearmap.com/report/area/서울특별시-종…    ← 한글이 든 주소
 *      https://100yearmap.com/school/7010125?from…
 *   딱지(?from=)는 **1/3** 에만 붙어 있었다
 *   ```
 *   ⛔ 잘린 주소는 손님이 옮겨 칠 수도 없다. **고칠 수 있는 까닭**이라 먼저 걷어낸다.
 *
 * ## ⭐ 짧은 주소가 딱지보다 나은 까닭 — **경로는 우리가 이미 적는다**
 *
 *   ```
 *   ?from=yt-100y   서버가 **물음표 뒤를 안 적는다**(server.mjs 446줄) → 지금은 못 센다
 *   /y/jongno       **경로**다. 우리 로그가 경로는 적는다 → **오늘부터 셀 수 있다**
 *   ```
 *   ⭐ 그래서 딱지도 붙이되, **세는 것은 경로로** 한다. 2번 손을 기다리지 않아도 된다.
 *
 * ## ⛔ 지키는 것
 *
 *   ```
 *   ⛔ 짧은 주소를 검색에 올리지 않는다 — noindex. 진짜 지면과 겨루면 안 된다
 *   ⛔ 이름을 늘리지 않는다. **밖에 적은 것만** 여기 둔다
 *   ⚠ 목적지가 없어지면 짧은 주소가 조용히 404 로 보낸다 → 자가 라이브에서 잰다
 *   ```
 */
export type 짧은주소 = {
  /** `/y/<키>` */
  키: string;
  /** 어디로 보내나 — ⛔ 우리 지면 안이어야 한다 */
  가는곳: string;
  /** 어디에 적어 뒀나 */
  적은곳: string;
  /** 손님에게 보일 한 줄 */
  말: string;
};

/** 딱지 — ⚠ 경로로도 세지만, 서버가 물음표 뒤를 적기 시작하면 이쪽도 살아난다 */
export const 딱지 = (at: string) => `from=yt-100y&at=${at}`;

