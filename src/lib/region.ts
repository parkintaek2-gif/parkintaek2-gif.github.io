/**
 * 시·도 이름 맞추기 — 고교(NEIS) ↔ 대학(대학알리미)
 *
 * ⚠ 두 자료의 표기가 **하나도 안 겹친다.** 17 대 17인데 겹치는 것이 0개다.
 * ```
 * NEIS      강원특별자치도 · 경상남도 · 전남광주통합특별시(광주) …
 * 대학알리미  강원         · 경남     · 광주                    …
 * ```
 *
 * ⛔ **비슷한 글자로 짐작해 잇지 않는다.** 앞서 직업명을 그렇게 이었다가
 *    「공무원」이 「행정부고위공무원」에 붙는 것을 봤다. 표로 못 박는다.
 *
 * ⚠ 「전남광주통합특별시」는 NEIS 에만 있는 표기다. 두 기관이 행정구역 개편을
 *    **서로 다른 시점**으로 반영하고 있다. 우리가 통일하는 것이 아니라,
 *    각자 표기를 그대로 두고 **잇는 표만** 갖는다. 원자료를 고치면 되돌릴 수 없다.
 */

/** NEIS 표기 → 대학알리미 표기 */
const NEIS_TO_ALIMI: Record<string, string> = {
  강원특별자치도: '강원',
  경기도: '경기',
  경상남도: '경남',
  경상북도: '경북',
  대구광역시: '대구',
  대전광역시: '대전',
  부산광역시: '부산',
  서울특별시: '서울',
  세종특별자치시: '세종',
  울산광역시: '울산',
  인천광역시: '인천',
  '전남광주통합특별시(광주)': '광주',
  '전남광주통합특별시(전남)': '전남',
  전북특별자치도: '전북',
  제주특별자치도: '제주',
  충청남도: '충남',
  충청북도: '충북',
};

/** 고교 지역명 → 대학 지역명. 표에 없으면 null (짐작하지 않는다) */
export const 고교지역_대학지역 = (neis: string | null | undefined): string | null =>
  (neis && NEIS_TO_ALIMI[neis]) ?? null;

/** 화면에 쓰기 좋은 짧은 이름. 「전남광주통합특별시(광주)」를 제목에 그대로 쓰면 읽기 어렵다 */
export const 짧은지역명 = (neis: string | null | undefined): string =>
  고교지역_대학지역(neis) ?? (neis ?? '');

/**
 * ── 학교알리미(schoolinfo.go.kr) → NEIS 표기 ─────────────────────
 *
 * 🔴 **세 번째 표기 체계다.** NEIS · 대학알리미에 이어 학교알리미가 또 다르다.
 *   2026-08-06 실측 — 학교알리미 고등학교 2,421곳을 이름+시도로 우리 지면에 이어 봤다.
 *
 * ```
 * 그냥 이었을 때        2,158 / 2,421 = 89.1%
 * 안 이어진 263곳의 정체  방송통신고 42 · 지역칸 빈 것 4 · **표기 차이 217**
 * ```
 *
 * ⭐ **217곳은 학교가 없는 게 아니라 시도 이름이 달랐을 뿐이다.**
 *   학교알리미는 `전남광주통합특별시` 한 덩어리인데, NEIS 는 `(광주)`·`(전남)` 로 갈라 적는다.
 *   샘플 40곳 중 39곳이 이것이었다(나머지 하나는 진짜 이름이 다른 계성여자상업고).
 *
 * ⚠ 그래서 **시군구로 가른다.** 광주 자치구 다섯이면 `(광주)`, 아니면 `(전남)`.
 *   우리 자료로 확인했다 — `(광주)` 73장 중 다섯 구가 아닌 것 **0장**,
 *   `(전남)` 150장 중 다섯 구인 것 **0장**. **겹치지 않는다.**
 *
 * ⛔ 이 파일 맨 위 규칙 그대로 — **비슷한 글자로 짐작해 잇지 않는다. 표로 못 박는다.**
 * ⛔ 원자료를 고치지 않는다. 각자 표기를 그대로 두고 **잇는 표만** 갖는다.
 */
const 광주자치구 = ['동구', '서구', '남구', '북구', '광산구'] as const;

/** 학교알리미 `ADRCD_NM`(예: `전남광주통합특별시 북구`) → NEIS 시도 표기. 모르면 null */
export const 알리미지역_고교지역 = (adrcdNm: string | null | undefined): string | null => {
  if (!adrcdNm) return null;
  const [시도, 시군구] = String(adrcdNm).trim().split(/\s+/);
  if (!시도) return null;
  if (시도 === '전남광주통합특별시') {
    /* ⚠ 시군구가 없으면 **찍지 않는다.** 틀린 쪽에 붙는 것보다 못 잇는 편이 낫다 */
    if (!시군구) return null;
    return (광주자치구 as readonly string[]).includes(시군구)
      ? '전남광주통합특별시(광주)'
      : '전남광주통합특별시(전남)';
  }
  /* 나머지 16개 시도는 NEIS 와 글자가 같다(실측). 표에 있는 것만 통과시킨다 */
  return Object.prototype.hasOwnProperty.call(NEIS_TO_ALIMI, 시도) ? 시도 : null;
};
