/**
 * 시·도 이름 맞추기 — 고교(NEIS) ↔ 대학(대학알리미)
 *
 * ⚠ 두 자료의 표기가 **하나도 안 겹친다.** 17 대 17인데 겹치는 것이 0개다.
 * ```
 * NEIS      강원특별자치도 · 경상남도 · 전남광주통합특별시(광주) …
 * 대학알리미  강원         · 경남     · 광주                    …
 * ```
 *
 * ⛔ **비슷한 글자로 짐작해 잇지 않는다.** 앞서 직업명을 그렇게 이었다가
 *    「공무원」이 「행정부고위공무원」에 붙는 것을 봤다. 표로 못 박는다.
 *
 * ⚠ 「전남광주통합특별시」는 NEIS 에만 있는 표기다. 두 기관이 행정구역 개편을
 *    **서로 다른 시점**으로 반영하고 있다. 우리가 통일하는 것이 아니라,
 *    각자 표기를 그대로 두고 **잇는 표만** 갖는다. 원자료를 고치면 되돌릴 수 없다.
 */

/** NEIS 표기 → 대학알리미 표기 */
const NEIS_TO_ALIMI: Record<string, string> = {
  강원특별자치도: '강원',
  경기도: '경기',
  경상남도: '경남',
  경상북도: '경북',
  대구광역시: '대구',
  대전광역시: '대전',
  부산광역시: '부산',
  서울특별시: '서울',
  세종특별자치시: '세종',
  울산광역시: '울산',
  인천광역시: '인천',
  '전남광주통합특별시(광주)': '광주',
  '전남광주통합특별시(전남)': '전남',
  전북특별자치도: '전북',
  제주특별자치도: '제주',
  충청남도: '충남',
  충청북도: '충북',
};

/** 고교 지역명 → 대학 지역명. 표에 없으면 null (짐작하지 않는다) */
export const 고교지역_대학지역 = (neis: string | null | undefined): string | null =>
  (neis && NEIS_TO_ALIMI[neis]) ?? null;

/** 화면에 쓰기 좋은 짧은 이름. 「전남광주통합특별시(광주)」를 제목에 그대로 쓰면 읽기 어렵다 */
export const 짧은지역명 = (neis: string | null | undefined): string =>
  고교지역_대학지역(neis) ?? (neis ?? '');
