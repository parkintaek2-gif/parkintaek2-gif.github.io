/**
 * 형태 문자열을 분류한다.
 *
 * ⚠ **못 알아보면 `null` 을 낸다.** 「기타」로 뭉치지 않는다 —
 *   뭉치면 새 형태가 생겨도 아무도 모른다. `null` 이 세어지면 표에 줄을 더한다.
 * ⚠ `-` 는 형태 미기재다. 수량은 있는 경우가 많다(실측 345행 중 339행).
 *   **버리지 않는다.** 「미기재」로 따로 센다.
 */
export function 분류(형태원문) {
  const s = String(형태원문 ?? '').replace(/\s/g, '').trim();
  if (!s || s === '-') return { en: 'Not stated', 갈래: '미기재', 신주: null, 미기재: true };
  return 형태표[s] ?? null;
}

/**
 * 발행가가 **액면가보다 낮은가** — 액면미달 발행은 상법상 특별한 절차가 필요하다.
 * ⚠ 둘 중 하나라도 없으면 `null` 이다. **모르는 것을 false 로 만들지 않는다.**
 */
export function 액면미달(행) {
  const 발행 = 행?.발행가, 액면 = 행?.액면가;
  if (발행 == null || 액면 == null) return null;
  return 발행 < 액면;
}

/**
 * 한 회사의 증자 행들을 갈래별로 합친다.
 * ⚠ 수량이 없는 행은 **빼고** 센다. 0 으로 치면 「증자가 없었다」와 구분이 안 된다.
 */
export function 갈래별합(행들) {
  const 합 = new Map();
  for (const x of 행들 ?? []) {
    if (x?.수량 == null) continue;
    const c = 분류(x.형태원문);
    const k = c?.갈래 ?? '(못 알아봄)';
    합.set(k, (합.get(k) ?? 0) + x.수량);
  }
  return 합;
}

/**
 * ⚠⚠ **발행가·액면가에 단위 오기가 섞여 있다.** 회사가 손으로 적는 칸이다.
 *
 * 2026-08-05 실측 (24,426행)
 * ```
 * 5%    500원      25%  1,500원    중앙  4,525원    75%  10,250원   ← 정상
 * 95%   156,758원                 최대  166,660,000,000원          ← 깨짐
 * 100만원 초과 719행 · 음수도 있다 (−2,295,000,000)
 * ```
 * 아주스틸: 액면가 **50억원** · 발행가 **1,666억원** — 100만 배 어긋났다.
 *
 * ── 어떻게 다루나 ──────────────────────────────────────────────
 * **고치지 않는다. 뺀다.** 「1,666억」이 「166,660원」인지 「16,666원」인지
 * 알 수 없다. 고치려면 신고자 의도를 추측해야 하는데, 그건 우리가 할 일이 아니다.
 * (순위표의 급여·근속을 다루는 방식과 같다 — `render-ranking.mjs` 의 `이상점검`)
 *
 * ⚠ 상한 1,000만원은 넉넉하게 잡은 것이다. 액면분할 전 삼성전자가 250만원,
 *   아모레퍼시픽이 400만원대였다. **실제 주가가 닿을 수 있는 위**에 둔다.
 */
export const 발행가한계 = [1, 10_000_000];

/** 발행가가 쓸 수 있는 값인가. 없으면 `null`(모름), 범위 밖이면 `false` */
export function 발행가정상(v) {
  if (v == null) return null;
  if (!Number.isFinite(v)) return false;
  return v >= 발행가한계[0] && v <= 발행가한계[1];
}

/**
 * 발행가 **가중평균** — 범위 밖은 빼고, 뺀 개수를 같이 낸다.
 * ⚠ 뺀 개수를 안 돌려주면 **얼마나 버렸는지 모르고 숫자를 쓰게 된다.**
 */
export function 가중발행가(행들) {
  let 합 = 0, 무게 = 0, 뺌 = 0, 없음 = 0;
  for (const x of 행들 ?? []) {
    const v = x?.발행가, w = x?.수량;
    if (v == null || w == null || w <= 0) { 없음++; continue; }
    if (!발행가정상(v)) { 뺌++; continue; }
    합 += v * w; 무게 += w;
  }
  return { 값: 무게 ? 합 / 무게 : null, 쓴행: 행들 ? 행들.length - 뺌 - 없음 : 0, 뺌, 없음 };
}
