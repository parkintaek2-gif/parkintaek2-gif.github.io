/**
 * 형태 문자열을 분류한다.
 *
 * ⚠ **못 알아보면 `null` 을 낸다.** 「기타」로 뭉치지 않는다 —
 *   뭉치면 새 형태가 생겨도 아무도 모른다. `null` 이 세어지면 표에 줄을 더한다.
 * ⚠ `-` 는 형태 미기재다. 수량은 있는 경우가 많다(실측 345행 중 339행).
 *   **버리지 않는다.** 「미기재」로 따로 센다.
 */
export function 분류(형태원문) {
  const s = String(형태원문 ?? '').replace(/\s/g, '').trim();
  if (!s || s === '-') return { en: 'Not stated', 갈래: '미기재', 신주: null, 미기재: true };
  return 형태표[s] ?? null;
}

/**
 * 발행가가 **액면가보다 낮은가** — 액면미달 발행은 상법상 특별한 절차가 필요하다.
 * ⚠ 둘 중 하나라도 없으면 `null` 이다. **모르는 것을 false 로 만들지 않는다.**
 */
export function 액면미달(행) {
  const 발행 = 행?.발행가, 액면 = 행?.액면가;
  if (발행 == null || 액면 == null) return null;
  return 발행 < 액면;
}

/**
 * 한 회사의 증자 행들을 갈래별로 합친다.
 * ⚠ 수량이 없는 행은 **빼고** 센다. 0 으로 치면 「증자가 없었다」와 구분이 안 된다.
 */
export function 갈래별합(행들) {
  const 합 = new Map();
  for (const x of 행들 ?? []) {
    if (x?.수량 == null) continue;
    const c = 분류(x.형태원문);
    const k = c?.갈래 ?? '(못 알아봄)';
    합.set(k, (합.get(k) ?? 0) + x.수량);
  }
  return 합;
}
