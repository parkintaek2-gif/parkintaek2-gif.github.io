/**
 * dataset-license.ts — **Dataset 구조화 자료의 `license` 와 `url` 을 한 곳에서 낸다.**
 *
 * ── 🔴 왜 만들었나 (2026-10-05 22:5x · 5번) ───────────────────────────
 *   사장님이 구글 메일을 넘겨 주셨다 —
 *   「**100yearmap.com에서 데이터세트 구조화된 데이터 문제가 감지됨**」
 *   「… **이러한 문제 중 일부는 향후 심각한 문제로 다시 분류될 수 있으며** …」
 *
 *   서치콘솔은 「'license' 입력란이 누락되었습니다 · 항목 1」이라고 했는데,
 *   저장소를 재 보니 **license 가 179파일, url 이 208파일** 빠져 있었다.
 *   ⭐ 구글이 세는 것은 «색인된 것»이고 우리가 고칠 것은 «내보내는 것»이다.
 *
 * ── ⛔ license 는 «우리가 실제로 주는 권리»여야 한다 ───────────────────
 *   적는 순간 **그 조건으로 쓰라고 손님에게 약속**하는 것이다.
 *   「CC BY」처럼 마음대로 가져다 쓰라는 것을 적으면 우리 자료를 그대로 퍼가도 된다는
 *   뜻이 된다 — 그것은 사장님이 정하실 일이지 내가 고를 일이 아니다.
 *
 *   ⭐ 그래서 **새 약속을 만들지 않고 이미 한 약속을 가리킨다.**
 *   이용약관이 이미 손님께 이렇게 적어 두고 있다 —
 *     「저희가 만든 구성·설명·계산값은 주식회사 케이라이프디자인에 있습니다.
 *      사신 자료는 사신 분이 보시는 데 쓰시면 됩니다.
 *      **다시 팔거나 그대로 배포하시는 것은 안 됩니다.**」
 *   `license` 에 그 약관 주소를 넣으면 schema.org 가 바라는 것이 채워지고,
 *   **손님에게 하는 말은 하나도 안 바뀐다.**
 *
 * ⚠ 세 사이트가 각자 자기 약관을 가리켜야 한다 — 한 주소로 묶으면
 *   100yearmap 손님이 seoulmarkets 약관을 보게 된다.
 */

/** 사이트마다 자기 이용약관. ⚠ 셋 다 라이브에서 200 인 것을 확인했다(2026-10-05) */
export const 약관주소 = {
  seoulmarkets: 'https://seoulmarkets.com/terms',
  '100y': 'https://100yearmap.com/terms',
  kcw: 'https://www.kculturewire.com/terms',
} as const;

export type 사이트딱지 = keyof typeof 약관주소;

/**
 * Dataset 에 넣을 `license` 와 `url` 을 만든다.
 *
 * @param 딱지  어느 사이트인가
 * @param 길   그 지면의 길(`/100y/breakfast` 처럼). 안 주면 url 을 안 넣는다
 *
 * ⛔ `url` 을 지어내지 않는다 — 길을 안 주면 아예 안 넣는다.
 *   틀린 주소를 넣으면 구글이 **다른 지면을 정본으로** 고를 수 있다.
 */
export function 자료권리(딱지: 사이트딱지, 길?: string) {
  const 밑 = 약관주소[딱지].replace(/\/terms$/, '');
  const 것: { license: string; url?: string } = { license: 약관주소[딱지] };
  if (길) 것.url = 밑 + (길.startsWith('/') ? 길 : '/' + 길);
  return 것;
}
