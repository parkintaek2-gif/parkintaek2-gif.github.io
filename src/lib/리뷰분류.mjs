/** 코드로 분류 1건을 조회한다. 미등록이면 undefined — 호출부가 차단한다 */
export function 분류조회(코드) {
  return 분류.find((c) => c.코드 === String(코드 ?? ''));
}

/** 해당 분류가 스포츠 계열인가 — 엠블럼 금지가 적용되는 구간이다 */
export function 스포츠계열인가(코드) {
  return 분류조회(코드)?.계열 === 'sports';
}
