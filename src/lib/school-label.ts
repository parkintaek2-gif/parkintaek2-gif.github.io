/**
 * 학교 딱지를 **사람이 읽는 말**로 바꾼다.
 *
 * ## 🔴 왜 (2026-08-08 05:4x · 2번 지시)
 *
 *   나이스가 주는 값이 그대로 지면에 찍히고 있었다.
 *
 *   ```
 *   남여공학   1,727곳   ← **「남녀공학」이 맞다.** 맞춤법이 틀린 채로 2,525장에 찍혔다
 *   여           407곳   ← 「서울특별시 · 일반고 · 공립 · 여」 로 나간다. 말이 안 된다
 *   남           391곳
 *   ```
 *
 *   2번 말 그대로 — *「값이 정해져 여는 날 「남여공학」이 그대로 나가면
 *   나머지가 아무리 좋아도 **그 한 글자를 봅니다**」*
 *
 * ## ⛔ 원자료를 고치지 않는다
 *
 *   `pages-school.json` 의 값은 **나이스가 준 그대로** 둔다. 고치는 것은 **보이는 말**이다.
 *   원자료를 손대면 다음에 다시 받을 때 되돌아오고, 그때 왜 달랐는지 아무도 모른다.
 *
 * ## ⚠ 「남」·「여」를 무엇으로 펴나
 *
 *   나이스의 이 칸은 **공학 구분**이다. 「남」은 남학교, 「여」는 여학교라는 뜻이다.
 *   학교 종류를 알면 「남자고등학교」처럼 펴고, 모르면 「남학교」로 둔다.
 *   ⛔ 종류를 모르는데 「고등학교」라고 지어 쓰지 않는다.
 */

/** 나이스가 주는 값 그대로 */
export type 공학값 = string | null | undefined;

/**
 * 공학 구분을 읽는 말로 편다.
 *
 * ```
 * 공학말('남여공학')                 → '남녀공학'
 * 공학말('여', '고등학교')            → '여자고등학교'
 * 공학말('남')                      → '남학교'
 * 공학말('')                        → null      ← 없으면 **아무 말도 안 만든다**
 * ```
 *
 * ⚠ 모르는 값이 오면 **그대로 돌려준다.** 지어내지 않는다 —
 *   나이스가 새 값을 넣으면 화면에 그 값이 그대로 보여야 우리가 안다.
 */
export function 공학말(공학: 공학값, 종류?: string | null): string | null {
  const v = String(공학 ?? '').trim();
  if (!v) return null;

  /* ⛔ 맞춤법 — 「남여」가 아니라 「남녀」다 */
  if (v === '남여공학' || v === '남녀공학') return '남녀공학';

  /**
   * ⚠ 종류를 **아무거나 갖다 붙이지 않는다.** 2026-08-08 07:2x 에 7장이 이렇게 나갔다.
   *
   *   ```
   *   여자평생학교(고)-2년6학기   ⛔  종류가 「평생학교(고)-2년6학기」 였다
   *   여자각종학교(고)            ⛔
   *   남자고등기술학교            ⛔
   *   ```
   *
   *   앞에 「남자·여자」를 붙여 말이 되는 것은 **「…고등학교」로 끝나는 종류뿐**이다.
   *   나머지는 붙이지 않고 **「남학교·여학교」**로 둔다. ⛔ 어색한 말을 지어내지 않는다.
   */
  const 갈래 = String(종류 ?? '').trim();
  const 붙일수있나 = /고등학교$/.test(갈래);
  if (v === '남') return 붙일수있나 ? `남자${갈래}` : '남학교';
  if (v === '여') return 붙일수있나 ? `여자${갈래}` : '여학교';

  return v;
}

/**
 * ⛔ 지면에 나가면 안 되는 말. 검사가 이 목록을 보고 지면을 훑는다.
 * **여기에 적어 두면 다시는 안 나간다** — 사람이 기억하는 데 기대지 않는다.
 */
export const 나가면안되는말 = ['남여공학', '남여 공학'] as const;
