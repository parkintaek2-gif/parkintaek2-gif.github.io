/**
 * 🗣 **학과마다 말이 달라지게 한다** — 838장이 문장까지 같던 것을 가른다.
 *
 * ## 🔴 왜 (2026-08-10 14:3x · 2번 지시)
 *
 *   닮은 지면 자를 만들어 전수를 재니 **`college-major` 가 제일 닮았다** —
 *   ```
 *   college-major  838장 · 가운데 **86%**   ← 제일 심하다
 *   major          926장 · 67.8%
 *   school       2,526장 · 65.6%
 *   ```
 *   ⛔ 그리고 그 자는 **숫자만 다른 문장을 「같은 문장」으로 본다.** 심사가 보는 눈이 그것이라서다.
 *     그러니 **수를 더 넣어도 값이 안 내려간다. 말이 갈려야 한다.**
 *
 * ## ⭐ 무엇으로 가르나 — **그 과의 제 숫자**다. 지어내지 않는다
 *
 *   ```
 *   건보밖비율   0 ~ 79.7%  (사분 5.3 · 9.7 · 18.6)   ← 과마다 제일 크게 갈린다
 *   진학률       0 ~ 34.2%  (사분 1.7 · 4.3 · 8.7)
 *   ```
 *   🔴 지금 지면은 이 둘을 **전국 값으로만** 말한다. 그 과의 값은 표에만 있고 **말에는 없다.**
 *     말로 옮기면 문장이 갈리고, 손님에게도 그게 더 낫다 — 표보다 문장이 먼저 읽힌다.
 *
 * ## ⛔ 지키는 것
 *
 *   ```
 *   ⛔ 「좋다·나쁘다」로 가르지 않는다. **많다·적다**로만 가른다
 *   ⛔ 없는 값에는 말을 붙이지 않는다 — null 이면 null 을 돌려준다
 *   ⚠ 띠 경계는 **사분위**에서 가져왔다. 우리가 고른 자리라는 것을 지면에 적는다
 *   ```
 */

/** 건보 밖(프리랜서·1인창업·개인창작)으로 간 사람이 얼마나 되나 — ⛔ 좋고 나쁨이 아니다 */
export function 건보밖말(비율: number | null | undefined): string | null {
  if (비율 == null || !Number.isFinite(비율)) return null;
  if (비율 < 5.3)
    return '이 과를 나와 일하는 사람은 **거의 다 직장가입자**입니다. 프리랜서·1인창업으로 간 사람이 스무 명에 한 명이 안 됩니다';
  if (비율 < 9.7)
    return '이 과에서 프리랜서·1인창업으로 간 사람은 **열에 한 명이 안 됩니다**. 대부분 직장에 들어갑니다';
  if (비율 < 18.6)
    return '이 과에서는 프리랜서·1인창업으로 간 사람이 **열에 한둘**입니다. 적지 않은 수입니다';
  if (비율 < 40)
    return '🔴 이 과에서는 프리랜서·1인창업으로 간 사람이 **다섯에 한 명이 넘습니다**. 직장에 들어가는 것만 길이 아닌 과입니다';
  return '🔴 이 과는 **일하는 사람의 절반 가까이가 직장가입자가 아닙니다**. 프리랜서·1인창업이 이 과의 흔한 길입니다';
}

/** 대학원 등으로 간 사람이 얼마나 되나 */
export function 진학말(비율: number | null | undefined): string | null {
  if (비율 == null || !Number.isFinite(비율)) return null;
  if (비율 < 1.7) return '이 과에서 대학원 등으로 가는 사람은 **거의 없습니다**';
  if (비율 < 4.3) return '이 과에서 대학원 등으로 가는 사람은 **드뭅니다**';
  if (비율 < 8.7) return '이 과에서는 **스무 명에 한둘**이 대학원 등으로 갑니다';
  if (비율 < 20) return '이 과에서는 **열에 한 명 넘게** 대학원 등으로 갑니다. 학부에서 끝나지 않는 과입니다';
  return '🔴 이 과는 **넷에 한 명 가까이** 대학원 등으로 갑니다. 진학이 이 과의 흔한 다음 걸음입니다';
}

/**
 * 남녀 구성 — ⛔ 「여초·남초」 같은 말을 쓰지 않는다. **몇 대 몇**으로만 적는다.
 * @param 여졸 여자 졸업자 · @param 졸업자 전체
 */
export function 남녀말(여졸: number | null | undefined, 졸업자: number | null | undefined): string | null {
  if (여졸 == null || 졸업자 == null || !졸업자) return null;
  const 여 = Math.round((여졸 / 졸업자) * 1000) / 10;
  if (여 >= 90) return '졸업생이 **열에 아홉 넘게 여자**입니다';
  if (여 >= 70) return '졸업생 **열에 일곱 넘게가 여자**입니다';
  if (여 >= 55) return '졸업생이 **여자 쪽으로 기울어** 있습니다';
  if (여 > 45) return '졸업생이 **남녀 반반**입니다';
  if (여 > 30) return '졸업생이 **남자 쪽으로 기울어** 있습니다';
  if (여 > 10) return '졸업생 **열에 일곱 넘게가 남자**입니다';
  return '졸업생이 **열에 아홉 넘게 남자**입니다';
}
