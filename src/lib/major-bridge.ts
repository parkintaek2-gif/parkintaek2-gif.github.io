/**
 * 대학 학과(837) ↔ 고등학교 학과(925) **이름 다리**.
 *
 * ## 🔴 왜 (2026-08-08 16:5x · 8번이 찾고 2번이 라이브로 확인)
 *
 *   ```
 *   /college-major/ 837장 · 표본 10장
 *      차림표 밖으로 나가는 길   0장
 *      학교 링크               0장
 *   ```
 *
 *   학과 지면이 우리 지면의 셋 중 하나다(대학 837 + 고교 925 = 1,762 / 4,768).
 *   그중 837장이 아무 데도 안 간다. 들어온 손님이 **한 장 보고 나간다.**
 *
 * ## 🔴 ⚠ 이것은 **진로가 아니라 이름이다** — 지면에 그렇게 적는다
 *
 *   2번이 주신 말은 *「이 학과로 가는 고등학교 학과 →」* 였다.
 *   ⛔ 그렇게 쓰면 **없는 자료를 있다고 말하는 것**이 된다.
 *
 *   ```
 *   우리에게 있는 것   이름이 같다 (간호학과 ↔ 간호과)
 *   ⛔ 없는 것         간호과를 나온 학생이 간호학과로 가는가 — 그 자료는 공개돼 있지 않다
 *   ```
 *
 *   `/school/[code]` 에도 이미 이렇게 적어 두었다 —
 *   *「고등학교 학과와 대학 학과를 잇는 공식 자료가 아직 공개되지 않아,
 *     지금은 지역으로만 이어 두었습니다」*. 그 자리와 말이 어긋나면 안 된다.
 *
 *   ⭐ 그래서 **길은 놓되 이름표를 정직하게 단다** — 「이름이 같은 고등학교 학과」.
 *     길이 필요하다는 2번 지적은 맞고, 그 길이 무엇인지는 우리가 정확히 적는다.
 *
 * ## ⚠ 두 지면을 섞지 않는다
 *
 *   `/major` 는 **고등학교** 학과(NEIS), `/college-major` 는 **대학** 학과(한국교육개발원)다.
 *   ⛔ 숫자를 한 지면에 섞으면 학부모가 학교급을 구분할 수 없다. **링크만 놓는다.**
 */

/**
 * 이름에서 **꼬리를 뗀 줄기**를 만든다.
 *
 * ⚠ 꼬리는 **맨 뒤에서만** 뗀다. 가운데서 떼면 「전기과」와 「전기공학부」가 같아진다 —
 *   2번이 *「억지로 맞추지 마십시오」* 하며 든 바로 그 예다. 지금 규칙에서 둘은
 *   줄기가 「전기」와 「전기공학」이라 안 만난다.
 * ⚠ `(4년제)`·`(야간)` 같은 괄호는 **학제 표시**라 뜻을 바꾸지 않아 뗀다.
 */
export function 줄기(이름: string): string {
  return String(이름 ?? '')
    .replace(/\((?:\d+년제|야간|주간)\)/g, '')
    .replace(/(?:학과|학부|전공|계열|과)$/, '')
    .replace(/\s/g, '');
}

export type 다리 = {
  /** 이름이 글자까지 똑같은가. 아니면 꼬리만 다른가 */
  같은꼴: '똑같다' | '꼬리만다르다';
  /** 이어 붙일 고등학교 학과 이름들. ⚠ 둘 이상일 수 있다(디자인과·디자인계열) */
  고교학과: string[];
};

/**
 * 대학 학과 하나에 이어 붙일 고등학교 학과를 찾는다. 없으면 `null`.
 *
 * ⛔ **지어내지 않는다.** 이름이 안 맞으면 안 맞는 것이다.
 */
export function 다리찾기(대학학과: string, 고교학과들: readonly string[]): 다리 | null {
  const 이름 = String(대학학과 ?? '');
  if (!이름) return null;

  const 똑같은 = 고교학과들.filter((g) => g === 이름);
  if (똑같은.length) return { 같은꼴: '똑같다', 고교학과: 똑같은 };

  const k = 줄기(이름);
  if (!k) return null;
  const 꼬리만 = 고교학과들.filter((g) => 줄기(g) === k);
  if (꼬리만.length) return { 같은꼴: '꼬리만다르다', 고교학과: [...new Set(꼬리만)] };

  return null;
}

