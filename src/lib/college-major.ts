/**
 * 대학 학과 지면이 쓰는 것 — **슬러그를 한 곳에서만 만든다**
 *
 * 🔴 목록 지면과 상세 지면이 슬러그를 **따로 만들면 링크가 어긋난다.**
 *   한쪽만 고치면 404 가 조용히 생긴다. 그래서 여기 한 곳에 둔다.
 *
 * ⚠ 학과 이름에 **슬래시가 든 것이 넷 있다** (2026-08-07 실측) —
 *   「상담/복지/공학계열」·「교육/경영/보건계열」·「화학공학/고분자공학부」·
 *   「호텔관광경영학전공/호텔관광외식경영학부」.
 *   슬래시는 주소를 갈라서 `[slug]` 한 칸에 안 들어간다.
 *   실제로 빌드가 **162장에서 죽었다** — `Missing parameter: slug`.
 *
 * ⛔ 이름 자체를 고치지 않는다. **주소만** 바꾸고 화면에는 원래 이름을 쓴다.
 *   원자료의 이름은 원자료의 것이다.
 */

/** 주소에 쓸 수 있게 다듬는다. 바꾼 뒤 겹치는 것이 **0개**인 것을 확인했다(837개 기준) */
export const 학과슬러그 = (이름: string): string =>
  String(이름)
    .replace(/[/\\]/g, '-')
    .replace(/[?#%&]/g, '');

/** 화면에 거는 주소. ⚠ 한글이라 `encodeURIComponent` 를 반드시 거친다 */
export const 학과주소 = (이름: string): string =>
  `/college-major/${encodeURIComponent(학과슬러그(이름))}`;
