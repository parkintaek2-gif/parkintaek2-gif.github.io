/**
 * 지역 지면이 쓰는 셈 — `/region` 과 `/region/[slug]` 가 같이 쓴다
 *
 * 왜 만드나 — 「경기도 고등학교」처럼 **지역으로 찾는 검색을 받을 지면이 없었다.**
 *   학교 2,525장·대학 377장에 지역이 다 붙어 있는데, 지역으로 들어오는 문이 없다.
 *   검색이 유일한 유통 경로라(인계 §7) 받을 자리를 만든다.
 *
 * ⛔ **지역을 취업률로 줄세우지 않는다.** 이 사이트가 「명문고 순위」를 안 만드는 것과 같은 이유다.
 *    지역 목록은 **가나다순**으로 놓는다. 크기 순도 아니다 — 크기 순은 곧 등수로 읽힌다.
 *    쓰는 것은 **전국 평균과의 차이**뿐이다.
 *
 * ⚠ **지역 평균은 「학교들의 평균」이 아니라 「사람 수로 잰 것」이다.**
 *    학교 평균으로 내면 졸업자 40명짜리 대학과 4,000명짜리 대학이 같은 무게를 갖는다.
 *    그래서 분자·분모를 각각 더해서 나눈다. 지면에 그렇게 적는다.
 */
import { 고교지역_대학지역, 짧은지역명 } from './region';

/** 🔴 반올림이 비교를 뒤집지 않게 하는 유일한 방법 — **표시할 값끼리 뺀다**
 *
 *  대학 지면에서 사장님이 직접 잡으신 것이다(2026-08-06 · 329곳 중 8곳).
 *  「62.7%인데 전국 62.8%보다 낮다」는 맞지만, 본문을 「63명」으로 반올림해 놓으면
 *  독자 눈에는 63 > 62.8 이라 말이 스스로 어긋난다.
 *
 *  여기서는 원값끼리 빼고 나서 반올림하지 **않는다.** 먼저 둘 다 반올림하고,
 *  **반올림된 두 값을 빼서** 차이를 만든다. 그러면 화면에 보이는 숫자끼리 계산이 맞는다.
 *  `scripts/check-100yearmap-launch.mjs` 의 「반올림이 비교를 뒤집나」가 이것을 지킨다.
 */
export function 견줌(값: number, 전국: number) {
  const a = Math.round(값 * 10) / 10;
  const b = Math.round(전국 * 10) / 10;
  const 차 = Math.round((a - b) * 10) / 10;
  return {
    // ⚠ **화면에는 반드시 이 문자열을 쓴다.** 숫자를 그대로 쓰면 4.5-5.5=1 이 「1%p」로 나가
    //   옆의 「4.5%·5.5%」와 자리수가 어긋난다. 자리수를 맞추려고 만든 규칙이 자기가 깨진다
    값: a.toFixed(1),
    전국: b.toFixed(1),
    차이: Math.abs(차).toFixed(1),
    방향: 차 > 0 ? ('높' as const) : 차 < 0 ? ('낮' as const) : ('같' as const),
  };
}

export type 지역요약 = ReturnType<typeof 지역요약만들기>;

/**
 * 한 지역의 숫자를 모은다.
 *
 * ⚠ 비율은 **잰 곳이 있을 때만** 만든다. 없으면 null 로 두고 지면에서 「못 쟀다」로 적는다.
 *    0 으로 채우면 「그 지역은 0%」로 읽힌다 — 시세에서 0 을 값으로 읽는 것과 같은 사고다.
 */
export function 지역요약만들기(opts: {
  고교지역: string;
  학교들: any[];
  대학들: any[];
  중단자료: any[];
  폐교자료: any[];
}) {
  const { 고교지역, 학교들, 대학들, 중단자료, 폐교자료 } = opts;
  const 짧은 = 짧은지역명(고교지역);
  const 대학지역 = 고교지역_대학지역(고교지역);

  const 이지역학교 = 학교들.filter((s) => s.지역 === 고교지역);
  const 이지역대학 = 대학지역 ? 대학들.filter((u) => u.지역 === 대학지역) : [];

  // ── 고교 유형별 ──────────────────────────────────────────────
  const 유형: Record<string, number> = {};
  for (const s of 이지역학교) 유형[s.고교유형 ?? '(미분류)'] = (유형[s.고교유형 ?? '(미분류)'] ?? 0) + 1;

  // ── 대학 취업률 — 사람 수로 잰다 ─────────────────────────────
  //    ⚠ 취업률이 null 인 곳(전국 48곳)은 분모에서도 뺀다. 안 그러면 취업률 0% 로 잡힌다
  const 취업잰곳 = 이지역대학.filter((u) => u.취업률 && u.취업대상자 > 0);
  const 취업대상 = 취업잰곳.reduce((n, u) => n + u.취업대상자, 0);
  const 취업자 = 취업잰곳.reduce((n, u) => n + u.취업자, 0);
  const 취업 =
    취업대상 > 0
      ? { ...견줌((취업자 / 취업대상) * 100, 취업잰곳[0].취업률.전국평균), 잰곳: 취업잰곳.length, 대상: 취업대상, 사람: 취업자 }
      : null;

  // ── 대학 중도탈락률 ─────────────────────────────────────────
  const 탈락잰곳 = 이지역대학.filter((u) => u.중도탈락률 && u.재적학생 > 0);
  const 재적 = 탈락잰곳.reduce((n, u) => n + u.재적학생, 0);
  const 탈락자 = 탈락잰곳.reduce((n, u) => n + u.중도탈락자, 0);
  const 탈락 =
    재적 > 0
      ? { ...견줌((탈락자 / 재적) * 100, 탈락잰곳[0].중도탈락률.전국평균), 잰곳: 탈락잰곳.length, 대상: 재적, 사람: 탈락자 }
      : null;

  // ── 고교 학업중단률 ─────────────────────────────────────────
  //    ⚠ 전국 평균도 여기서 같은 방법으로 낸다. 남이 낸 값을 가져다 쓰면 잰 자가 달라진다
  const 코드있는곳 = new Set(이지역학교.map((s) => s.code));
  const 이지역중단 = 중단자료.filter((d) => 코드있는곳.has(d.code) && d.재학생 > 0);
  const 재학 = 이지역중단.reduce((n, d) => n + d.재학생, 0);
  const 중단자 = 이지역중단.reduce((n, d) => n + d.학업중단, 0);
  const 전국재학 = 중단자료.reduce((n, d) => n + (d.재학생 > 0 ? d.재학생 : 0), 0);
  const 전국중단 = 중단자료.reduce((n, d) => n + (d.재학생 > 0 ? d.학업중단 : 0), 0);
  const 중단 =
    재학 > 0 && 전국재학 > 0
      ? { ...견줌((중단자 / 재학) * 100, (전국중단 / 전국재학) * 100), 잰곳: 이지역중단.length, 대상: 재학, 사람: 중단자 }
      : null;

  // ── 문을 닫은 대학 ──────────────────────────────────────────
  //    ⚠ 「경기 광주」가 있다. **첫 낱말만** 본다. 안 그러면 광주 지면에 경기도 학교가 붙는다
  const 폐교 = 폐교자료.filter((p) => (p.지역 ?? '').split(' ')[0] === 짧은);

  return {
    고교지역,
    짧은,
    대학지역,
    고교수: 이지역학교.length,
    유형,
    대학수: 이지역대학.length,
    취업,
    탈락,
    중단,
    폐교,
    학과있는고교: 이지역학교.filter((s) => s.학과수 > 0).length,
  };
}

/** 「0.4%p 높습니다」 / 「같습니다」 — 방향까지 한 덩어리로 만든다 */
export const 견줌말 = (c: { 차이: string; 방향: '높' | '낮' | '같' }) =>
  c.방향 === '같' ? '전국 평균과 같습니다' : `전국 평균보다 ${c.차이}%p ${c.방향 === '높' ? '높습니다' : '낮습니다'}`;
