/**
 * **층 대문** — 50대·60대. 사장님이 잡아 주신 일곱 층 중 다섯째·여섯째다.
 *
 * ## 🔴 왜 (2026-08-09 03:4x · 2번 지시)
 *
 *   사장님 — **「네 층이 넘어야지 100년 산다며」**
 *   2번 — *「오픈에 네 층뿐이면 그 말이 안 섭니다. **대문 두 장만** 8/14 까지」*
 *
 *   ⚠ 자료는 **이미 손에 있었다.** `age-axis.json` 에 50·60대 칸이 다 채워져 있는데
 *     그걸 **10대 진로 지면에만** 쓰고 있었다. 새로 모을 것이 없다.
 *
 * ## ⚠ 「한 살짜리 지면」과 다르다
 *
 *   `/age/55`·`/age/68` 은 **그 나이 한 살**을 보여 준다(이미 있다).
 *   여기는 **층**이다 — 50대 열 해를 한 장에 놓고, 그 층에서 무엇이 달라지는지를 본다.
 *   ⛔ 내가 어제 「50·60대 지면 0장」이라고 적은 것은 **층 대문 기준**이었다.
 *     한 살짜리는 둘 있었다. 수를 적을 때 무엇을 세는지 같이 적었어야 했다.
 *
 * ## ⛔ 이 층에서 특히 조심하는 것
 *
 *   ```
 *   ⛔ 「노후 준비를 하셔야 합니다」   우리가 할 말이 아니다. 조언하지 않는다
 *   ⛔ 「늦었습니다」·「이르다」        사장님 지시로 전 사이트에서 안 쓰는 말이다
 *   ⛔ 평균만 싣지 않는다             중앙값을 같이 놓는다. 평균은 몇 사람이 끌어올린다
 *   ✅ 적는 것은 「같은 나이의 사람들이 실제로 어떻게 하고 있나」뿐이다
 *   ```
 */

export type 임금칸 = { 근속년: number; 사람: number; 월급여천원: number };
export type 살림칸 = {
  경상소득_전가구평균: number;
  경상소득_보유가구중앙: number;
  자산_전가구평균: number;
  자산_보유가구중앙: number;
  부채_전가구평균: number;
  부채_보유가구중앙: number;
  /**
   * 100집 가운데 그것을 «가진» 집이 몇인가.
   * ⭐ 보유가구중앙은 «가진 집만» 놓고 잰 값이라, 이 비율을 같이 적지 않으면
   *   「딱 가운데 있는 집」으로 읽힌다. 29세 이하는 절반(50.2%)만 빚이 있다.
   */
  자산_가진집비율?: number;
  부채_가진집비율?: number;
};
export type 나이축 = {
  출처: Record<string, any>;
  임금: Record<string, 임금칸>;
  살림: Record<string, 살림칸>;
};

/** 낼 층 — ⛔ 여기 없는 것은 지면이 안 선다 */
export const 낼층 = ['50대', '60대'] as const;
export type 층 = (typeof 낼층)[number];

export type 층자료 = {
  층: 층;
  이름: string;
  물음: string;
  /** 그 층에 드는 임금 칸들 (원자료 이름 그대로) */
  임금칸: { 이름: string; 월급만원: number; 근속년: number; 사람: number }[];
  /** 살림 칸 (가구 기준) */
  살림칸: {
    이름: string;
    자산중앙만원: number;
    부채중앙만원: number;
    소득중앙만원: number;
    /** 100집 중 빚이 있는 집 (없으면 null — ⛔ 0 으로 채우지 않는다) */
    부채가진집백: number | null;
  };
  /** 앞 층과 견준 것 — ⛔ 좋고 나쁨을 말하지 않는다. 차이만 적는다 */
  앞층과: { 월급차만원: number; 근속차년: number } | null;
};

const 만원 = (천원: number) => Math.round(천원 / 10);

/**
 * 층 하나를 뽑는다. ⛔ 없는 칸은 **지어내지 않고 그대로 빼고** 돌려준다.
 * @param 앞임금칸 앞 층의 마지막 임금 칸 이름 (견줄 것이 없으면 null)
 */
export function 층뽑기(자료: 나이축, 층이름: 층): 층자료 | null {
  const 얼개: Record<층, { 임금: string[]; 살림: string; 물음: string; 앞: string | null }> = {
    '50대': {
      임금: ['50 ~ 54', '55 ~ 59'],
      살림: '50~59세',
      물음: '쉰이 넘으면 무엇이 달라지나',
      앞: '45 ~ 49',
    },
    '60대': {
      임금: ['60세 ~'],
      살림: '60세 이상',
      물음: '예순이 넘으면 무엇이 달라지나',
      앞: '55 ~ 59',
    },
  };
  const 짜임 = 얼개[층이름];
  if (!짜임) return null;

  const 임금칸 = 짜임.임금
    .filter((k) => 자료.임금?.[k])
    .map((k) => ({
      이름: k,
      월급만원: 만원(자료.임금[k].월급여천원),
      근속년: 자료.임금[k].근속년,
      사람: 자료.임금[k].사람,
    }));
  const 살림 = 자료.살림?.[짜임.살림];
  if (!임금칸.length || !살림) return null;

  const 앞 = 짜임.앞 && 자료.임금?.[짜임.앞] ? 자료.임금[짜임.앞] : null;
  const 첫 = 임금칸[0];

  return {
    층: 층이름,
    이름: 층이름,
    물음: 짜임.물음,
    임금칸,
    살림칸: {
      이름: 짜임.살림,
      자산중앙만원: Math.round(살림.자산_보유가구중앙),
      부채중앙만원: Math.round(살림.부채_보유가구중앙),
      소득중앙만원: Math.round(살림.경상소득_보유가구중앙),
      부채가진집백:
        typeof 살림.부채_가진집비율 === 'number' ? Math.round(살림.부채_가진집비율) : null,
    },
    앞층과: 앞
      ? {
          월급차만원: 첫.월급만원 - 만원(앞.월급여천원),
          근속차년: Math.round((첫.근속년 - 앞.근속년) * 10) / 10,
        }
      : null,
  };
}

/** 슬러그 ↔ 층 이름. ⚠ 한글 그대로 쓴다 — 우리 다른 지면(`/major/정보처리과`)과 같은 꼴이다 */
export const 층슬러그 = (층이름: 층) => 층이름;
export const 슬러그층 = (slug: string): 층 | null =>
  (낼층 as readonly string[]).includes(slug) ? (slug as 층) : null;

/** 차이를 말로. ⛔ 「떨어진다/오른다」까지만. 좋고 나쁨을 안 붙인다 */
export function 차이말(만원차: number): string {
  if (만원차 === 0) return '앞 자리와 같습니다';
  return 만원차 > 0
    ? `앞 자리보다 ${만원차.toLocaleString()}만원 많습니다`
    : `앞 자리보다 ${Math.abs(만원차).toLocaleString()}만원 적습니다`;
}
