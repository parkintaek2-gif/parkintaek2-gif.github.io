/** 값이 «있나» — 0 은 있는 값이다. null·undefined·빈 글자·NaN 만 없는 것이다 */
export function 있나(v) {
  if (v === null || v === undefined || v === '') return false;
  return Number.isFinite(Number(v));
}

/**
 * 한 줄이 한 조건을 지나가나.
 * 낸다 — 'pass'(맞다) · 'fail'(안 맞다) · 'missing'(그 칸이 비어 있다)
 * 🔴 'missing' 을 'fail' 과 갈라 내는 것이 이 자의 핵심이다.
 */
export function 한조건(줄, 조건) {
  const v = 줄 ? 줄[조건.key] : undefined;
  if (!있나(v)) return 'missing';
  const n = Number(v);
  if (있나(조건.min) && n < Number(조건.min)) return 'fail';
  if (있나(조건.max) && n > Number(조건.max)) return 'fail';
  return 'pass';
}

/** 그 칸에 값이 «있는» 줄이 몇인가 — 조건을 걸기 «전»에 손님에게 보인다 */
export function 칸채움(줄들, key) {
  let n = 0;
  for (const 줄 of 줄들 || []) if (있나(줄[key])) n += 1;
  return n;
}

/**
 * 거른다.
 *   거른다(줄들, { 조건들, 글자, 시장들: ['Y','ADX'], 업종 })
 * 낸다 — { 남은것, 조건에안맞음, 값이없어빠짐, 칸별없음 }
 * ⭐ 값이없어빠짐 이 손님에게 «크게» 보여야 하는 수다.
 *
 * 🔴 업종도 «값이 없을 수 있다» — ADX 는 업종을 주는 우물이 없다.
 *   업종을 고른 손님에게 「안 맞아서 빠졌다」고 하면 거짓이다. 그것도 missing 으로 센다.
 */
export function 거른다(줄들, 옵션 = {}) {
  const 조건들 = 옵션.조건들 || [];
  const 찾을글 = String(옵션.글자 || '').trim().toLowerCase();
  const 고른시장 = 옵션.시장들 || null;
  const 고른업종 = 옵션.업종 || '';

  const 남은것 = [];
  let 조건에안맞음 = 0;
  let 값이없어빠짐 = 0;
  const 칸별없음 = {};

  for (const 줄 of 줄들 || []) {
    /* 시장과 이름은 «있고 없고»가 분명하다 — 여기서 빠지는 것은 그냥 안 맞는 것이다 */
    if (고른시장 && 고른시장.length && !고른시장.includes(줄.m)) continue;
    if (찾을글) {
      const 이름 = ((줄.n || '') + ' ' + (줄.k || '') + ' ' + (줄.t || '')).toLowerCase();
      if (!이름.includes(찾을글)) continue;
    }

    let 빠진까닭 = null;

    /* 업종 — 없는 곳을 「안 맞았다」로 세지 않는다 */
    if (고른업종) {
      if (!줄.i) {
        빠진까닭 = 'missing';
        칸별없음.i = (칸별없음.i || 0) + 1;
      } else if (줄.i !== 고른업종) {
        빠진까닭 = 'fail';
      }
    }

    if (!빠진까닭) {
      for (const 조건 of 조건들) {
        if (!있나(조건.min) && !있나(조건.max)) continue;   /* 안 건 조건은 안 본다 */
        const r = 한조건(줄, 조건);
        if (r === 'pass') continue;
        if (r === 'missing') {
          빠진까닭 = 'missing';
          칸별없음[조건.key] = (칸별없음[조건.key] || 0) + 1;
          break;
        }
        빠진까닭 = 'fail';
        break;
      }
    }

    if (빠진까닭 === 'missing') { 값이없어빠짐 += 1; continue; }
    if (빠진까닭 === 'fail') { 조건에안맞음 += 1; continue; }
    남은것.push(줄);
  }
  return { 남은것, 조건에안맞음, 값이없어빠짐, 칸별없음 };
}

/**
 * 정렬한다. ⛔ 값이 «없는» 줄은 언제나 맨 아래로 보낸다 —
 * 위로 올리면 손님이 「0 인 곳이 제일 싸다」로 잘못 읽는다.
 */
export function 정렬한다(줄들, 칸, 내림차순 = true) {
  const 것 = [...(줄들 || [])];
  것.sort((A, B) => {
    const a = A[칸]; const b = B[칸];
    const aOk = 있나(a); const bOk = 있나(b);
    if (!aOk && !bOk) return 0;
    if (!aOk) return 1;          /* 없는 것은 아래로 */
    if (!bOk) return -1;
    return 내림차순 ? Number(b) - Number(a) : Number(a) - Number(b);
  });
  return 것;
}

/**
 * 달러를 손님이 읽는 꼴로 — $1.15T · $12.3B · $345M
 * ⛔ 「억·조」로 내지 않는다. 손님이 영어권이다.
 * ⛔ 통화 기호를 생략하지 않는다 — 시장을 섞는 지면이라 무슨 돈인지가 늘 붙어야 한다.
 */
export function 돈글(달러) {
  if (!있나(달러)) return '—';
  const n = Number(달러);
  const a = Math.abs(n);
  if (a >= 1e12) return '$' + (n / 1e12).toFixed(2) + 'T';
  if (a >= 1e9) return '$' + (n / 1e9).toFixed(1) + 'B';
  if (a >= 1e6) return '$' + Math.round(n / 1e6).toLocaleString('en-US') + 'M';
  return '$' + Math.round(n).toLocaleString('en-US');
}

/**
 * 줄이 «원래» 신고한 값 — 손님이 신고서와 맞대어 볼 수 있어야 한다.
 * 달러는 우리가 환산한 것이고, 이것이 회사가 실제로 적어 낸 수다.
 */
export function 원글(값, 통화) {
  if (!있나(값)) return null;
  const n = Number(값);
  const a = Math.abs(n);
  const 단위 = String(통화 || '');
  if (a >= 1e12) return (n / 1e12).toFixed(2) + 'tn ' + 단위;
  if (a >= 1e9) return (n / 1e9).toFixed(1) + 'bn ' + 단위;
  if (a >= 1e6) return Math.round(n / 1e6).toLocaleString('en-US') + 'm ' + 단위;
  return Math.round(n).toLocaleString('en-US') + ' ' + 단위;
}

