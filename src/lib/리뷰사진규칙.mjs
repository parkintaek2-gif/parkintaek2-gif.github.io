/**
 * 리뷰사진규칙.mjs — **리뷰에 게재하는 사진이 사장님이 정하신 규칙을 준수하는지 검증한다.**
 *
 * ── 🔴🔴 사장님 지시 (2026-10-26, 원문) ───────────────────────────────
 * 「사진은 많이 있을 거다. **스포츠에선 각 팀의 엠블럼을 사진으로 쓰지말고, 각 팀이나
 *   해당 협회 사이트에서 제공하는 사진을 써라. TV프로그램은 각 방송사 홈페이지에서
 *   사진을 갖다 써라. OTT 프로그램은 타사 기사 중 제공처가 OTT인 사진을 갖다가 써라.**」
 *
 * ── 문장이 아니라 검사로 두는 이유 ────────────────────────────────────
 * 강령 ④ — 「말로 하는 규칙은 잊힌다. 겪은 것은 **자가시험이 달린 검사**로 굳힌다」.
 * ⚠ 본 규칙은 이미 1회 위반됐다. **금일 오전 중부매일로 송고된 롤드컵 기사 4건이
 *   전부 팀 엠블럼(`…GENGLOGO_GOLD.png`)을 사진으로 첨부했다.** 사장님이 이를 보시고
 *   본 지시를 하신 것이다. 담당자의 기억에 의존하는 구조로 두면 재발한다.
 * ⇒ 위반 시 **빌드가 중단된다**(`src/content.config.ts` 의 superRefine 이 호출한다).
 *
 * ⛔ 「경고만 출력하고 통과」를 하지 않는다. 경고는 아무도 확인하지 않는다.
 */
import { 분류조회, 스포츠계열인가 } from './리뷰분류.mjs';

/**
 * 엠블럼·로고로 판별되는 어휘. **사진 주소와 문구(제목·대체텍스트·캡션)를 함께 본다.**
 * ⚠ 주소만 검사하면 `…/img_0423.png` 로 업로드된 엠블럼을 놓치고,
 *   문구만 검사하면 캡션을 잘 작성한 엠블럼을 놓친다. 양쪽을 모두 검사한다.
 * ⛔ 단음절 약어(ci·bi)는 포함하지 않는다 — `…/social-ci-ty.jpg` 같은 정상 주소를 오탐한다.
 */
const 엠블럼어휘 = [
  'logo', 'emblem', 'crest', 'wordmark', 'isotype', 'symbolmark', 'lockup',
  '엠블럼', '엠블렘', '로고', '심벌', '심볼', '휘장',
];

/** 주소에서 경로 부분만 추출 — 도메인에 'logo' 가 포함된 곳(예: logos.com)을 오탐하지 않게 */
function 주소경로(주소) {
  const s = String(주소 ?? '');
  return s.replace(/^[a-z]+:\/\/[^/]+/i, '').toLowerCase();
}

function 엠블럼판별(사진) {
  const 문구 = [사진?.제목, 사진?.대체텍스트, 사진?.캡션].filter(Boolean).join(' ').toLowerCase();
  const 경로 = 주소경로(사진?.src);
  const 출처경로 = 주소경로(사진?.출처주소);
  return 엠블럼어휘.filter((w) => 문구.includes(w) || 경로.includes(w) || 출처경로.includes(w));
}

/**
 * 리뷰 1건의 사진을 검증하여 **위반 사항을 문장으로 반환한다.** 빈 배열이면 통과다.
 *
 * @param {{category: string, image?: object}} 리뷰 — 프런트매터 원본
 * @returns {string[]} 위반 사항. 무엇을 어떻게 수정하면 되는지까지 기재한다
 */
export function 사진위반(리뷰) {
  const 위반 = [];
  const 분류코드 = 리뷰?.category;
  const 해당분류 = 분류조회(분류코드);
  if (!해당분류) {
    위반.push(`분류 「${분류코드}」는 미등록이다 — src/lib/리뷰분류.mjs 에 등재된 것만 사용한다`);
    return 위반;
  }

  const 사진 = 리뷰?.image;
  if (!사진) {
    /* ⛔ 사진이 없는 리뷰를 차단하지 않는다. 사장님은 「사진은 많이 있을 거다」라고 하셨지
       「없으면 게재하지 마라」고 하지 않으셨다. 다만 게재하면 규칙을 준수해야 한다. */
    return 위반;
  }

  if (!사진.src) 위반.push('사진 주소(src)가 없다');
  if (!사진.제공처) 위반.push('제공처가 없다 — 「/ 라이엇 게임즈」처럼 캡션에 부기할 명칭이다');
  if (!사진.출처주소) 위반.push('출처주소가 없다 — 어느 화면에서 입수했는지 기재한다');
  if (!사진.대체텍스트) 위반.push('대체텍스트(alt)가 없다 — 시각장애 이용자가 이 사진을 인지할 수 없다');

  /* ① 자체 서버에 보관하여 사용한다. 외부 서버를 직접 참조하면 일방적으로 중단될 수 있고,
        해당 서버에 당사 방문자 수만큼 부하를 전가한다. 내려받아 public/review/ 에 보관한다.
     ⚠ 출처주소는 «원 소재지»를 그대로 기재한다 — 내려받았다고 출처가 당사가 되지 않는다. */
  if (사진.src && !String(사진.src).startsWith('/review/')) {
    위반.push(`사진은 내려받아 자체 서버에 보관한다 — /review/… 로 기재한다 (현재: ${사진.src})`);
  }

  /* ② 제공처 유형이 해당 분류에서 허용되는가 */
  const 허용 = 해당분류.허용출처;
  if (!사진.제공처유형) {
    위반.push(`제공처유형이 없다 — ${해당분류.명칭} 에는 ${허용.join('·')} 중 하나를 기재한다`);
  } else if (!허용.includes(사진.제공처유형)) {
    위반.push(
      `${해당분류.명칭} 에 「${사진.제공처유형}」 사진은 사용하지 않는다 — `
      + `${허용.join('·')} 만 사용한다`,
    );
  }

  /* ③ 🔴 스포츠 계열의 엠블럼 금지 — 사장님이 명시적으로 금지하신 항목이다 */
  if (스포츠계열인가(분류코드)) {
    const 적출어휘 = 엠블럼판별(사진);
    if (적출어휘.length) {
      위반.push(
        `스포츠 리뷰에 엠블럼·로고를 사진으로 사용하지 않는다(적출 어휘: ${적출어휘.join(', ')}) — `
        + '구단이나 협회가 제공하는 «경기 사진»을 사용한다',
      );
    }
  }

  return 위반;
}

/* ───────────────────────────── 자가시험 ─────────────────────────────
   [실행] node src/lib/리뷰사진규칙.mjs --자가시험
   ⛔ 아래 사례는 가공한 것이 아니다. ①은 금일 오전 실제로 송고된 사진이다. */
if (process.argv.includes('--자가시험')) {
  let 총건수 = 0; let 실패건수 = 0;
  const 검증 = (항목, 성립여부) => {
    총건수 += 1;
    if (성립여부) { console.log(`  ✅ ${항목}`); } else { 실패건수 += 1; console.log(`  ❌ ${항목}`); }
  };

  const 정상 = {
    category: 'esports',
    image: {
      src: '/review/worlds-2026-hle-ig-zeus.jpg',
      대체텍스트: '한화생명e스포츠 선수가 경기 부스에서 화면을 보고 있다',
      캡션: '한화생명e스포츠가 IG에 패했다.',
      제공처: '라이엇 게임즈',
      제공처유형: 'league',
      출처주소: 'https://www.flickr.com/photos/lolesports/55611654313/',
    },
  };
  검증('정상적인 e스포츠 사진은 통과한다', 사진위반(정상).length === 0);

  /* ① 금일 오전 중부매일로 송고된 해당 사진 — 반드시 적출돼야 한다 */
  const 금일송고분 = {
    category: 'esports',
    image: {
      src: '/review/1773829250929_GENGLOGO_GOLD.png',
      대체텍스트: '젠지 e스포츠 엠블럼',
      캡션: '젠지가 8강에 진출했다.',
      제공처: '라이엇 게임즈',
      제공처유형: 'league',
      출처주소: 'https://static.lolesports.com/teams/1773829250929_GENGLOGO_GOLD.png',
    },
  };
  검증('🔴 팀 엠블럼은 스포츠 리뷰에서 차단된다', 사진위반(금일송고분).some((m) => m.includes('엠블럼')));

  검증('⛔ 외부 서버 직접 참조는 차단된다', 사진위반({
    ...정상, image: { ...정상.image, src: 'https://static.lolesports.com/a.jpg' },
  }).some((m) => m.includes('자체 서버')));

  검증('⛔ 제공처 누락은 차단된다', 사진위반({
    ...정상, image: { ...정상.image, 제공처: undefined },
  }).some((m) => m.includes('제공처가 없다')));

  검증('⛔ 출처주소 누락은 차단된다', 사진위반({
    ...정상, image: { ...정상.image, 출처주소: undefined },
  }).some((m) => m.includes('출처주소')));

  검증('⛔ 대체텍스트 누락은 차단된다', 사진위반({
    ...정상, image: { ...정상.image, 대체텍스트: undefined },
  }).some((m) => m.includes('대체텍스트')));

  /* 분류별로 허용 제공처가 상이하다 — 사장님이 분류별로 다르게 지시하셨다 */
  검증('⛔ 스포츠에 방송사 제공 사진은 사용하지 않는다', 사진위반({
    ...정상, image: { ...정상.image, 제공처유형: 'broadcaster' },
  }).some((m) => m.includes('사용하지 않는다')));

  검증('드라마에는 방송사 사진을 사용한다', 사진위반({
    category: 'drama',
    image: {
      src: '/review/some-drama-ep3.jpg', 대체텍스트: '3회의 한 장면', 캡션: '3회.',
      제공처: 'tvN', 제공처유형: 'broadcaster', 출처주소: 'https://tvn.cjenm.com/',
    },
  }).length === 0);

  검증('드라마에는 OTT 제공 사진도 사용한다', 사진위반({
    category: 'drama',
    image: {
      src: '/review/some-ott-ep1.jpg', 대체텍스트: '1회의 한 장면', 캡션: '1회.',
      제공처: '넷플릭스', 제공처유형: 'ott', 출처주소: 'https://www.example-news.com/article/1',
    },
  }).length === 0);

  검증('⛔ 드라마에 구단 사진은 사용하지 않는다', 사진위반({
    category: 'drama',
    image: {
      src: '/review/x.jpg', 대체텍스트: 'x', 캡션: 'x',
      제공처: '구단', 제공처유형: 'team', 출처주소: 'https://example.com/',
    },
  }).some((m) => m.includes('사용하지 않는다')));

  검증('⛔ 미등록 분류는 차단된다', 사진위반({ category: 'cooking' }).some((m) => m.includes('미등록')));

  검증('사진이 없는 리뷰는 차단하지 않는다', 사진위반({ category: 'show' }).length === 0);

  /* ⚠ 드라마·쇼는 스포츠가 아니므로 포스터(로고가 포함된 것)를 차단하지 않는다.
       사장님은 엠블럼 금지를 «스포츠에서» 지시하셨다. 범위를 확대하는 것도 위반이다. */
  검증('⚠ 드라마의 로고 포함 사진은 차단하지 않는다 — 금지는 스포츠 한정이다', 사진위반({
    category: 'drama',
    image: {
      src: '/review/drama-logo-poster.jpg', 대체텍스트: '포스터', 캡션: '포스터.',
      제공처: 'SBS', 제공처유형: 'broadcaster', 출처주소: 'https://programs.sbs.co.kr/',
    },
  }).length === 0);

  검증('도메인에 포함된 logo 는 적출하지 않는다', 엠블럼판별({
    src: '/review/match.jpg', 출처주소: 'https://logos-example.com/photo/match.jpg', 캡션: '경기',
  }).length === 0);

  console.log(`\n  ${총건수 - 실패건수}/${총건수} 통과`);
  process.exit(실패건수 ? 1 : 0);
}
