/**
 * 학교를 **시·군·구**로 묶는다 — 지역 한 벌(`/report/area/…`)이 서는 단위다.
 *
 * ## 🔴 왜 고쳤나 (2026-08-08 05:2x 에 내가 짚었고 2번이 정했다)
 *
 *   처음엔 **주소 둘째 낱말**만 봤다. 그러니 큰 시가 통째로 한 덩어리가 됐다.
 *
 *   ```
 *   경상남도 창원시 53곳 · 경기도 수원시 48 · 충청북도 청주시 41 · 고양시 40
 *   ```
 *
 *   ⛔ **53곳을 한 장에 넣으면 「한눈에」가 깨진다.** 강동구 14곳이 한 장에 맞는 크기였다.
 *   그런데 그 주소에는 이미 구가 들어 있다 — 「수원시 **장안구**」. 셋째 낱말이다.
 *
 *   ```
 *   둘째만 볼 때   구 230개 · 가장 큰 곳 53곳
 *   셋째까지 볼 때  구 257개 · 가장 큰 곳 26곳    ← 전부 한 장에 들어간다
 *   ```
 *
 * ## ⚠ 세종은 구가 없다
 *
 *   세종특별자치시는 아래에 구·군이 없다. 주소가 「세종특별자치시 마음안로 93」이다.
 *   ⛔ 그렇다고 **못 가른 것으로 버리지 않는다.** 시 전체가 한 단위다.
 *
 * ## ⛔ 못 가른 것은 「기타」로 뭉치지 않는다
 *
 *   뭉치면 **못 잰 것이 안 보인다.** `null` 을 주고 까닭을 같이 준다.
 */

/** 시·도 아래에 구·군이 없는 곳. 이 경우 **시·도 자체가 한 단위**다 */
export const 구가없는시도 = ['세종특별자치시'] as const;

export type 묶음 = {
  /** 묶음 이름. 「강동구」·「수원시 장안구」·「세종특별자치시」 */
  이름: string | null;
  /** 못 가르면 왜 못 갈랐는지. 가르면 null */
  못가른까닭: string | null;
};

/**
 * 주소에서 묶음 단위를 고른다.
 *
 * ```
 * 지역단위('서울특별시', '서울특별시 강동구 고덕로 227')        → 강동구
 * 지역단위('경기도',   '경기도 수원시 장안구 …')               → 수원시 장안구
 * 지역단위('경기도',   '경기도 여주시 …')                      → 여주시
 * 지역단위('세종특별자치시', '세종특별자치시 마음안로 93')       → 세종특별자치시
 * 지역단위('부산광역시', '')                                  → null (주소가 없다)
 * ```
 */
export function 지역단위(시도: string | null | undefined, 주소: string | null | undefined): 묶음 {
  const 시 = String(시도 ?? '').trim();
  const 토막 = String(주소 ?? '')
    .trim()
    .split(/\s+/)
    .filter(Boolean);

  /* 구가 없는 시·도는 시·도 자체가 단위다. ⚠ 주소를 못 읽어도 이건 성립한다 */
  if ((구가없는시도 as readonly string[]).includes(시)) return { 이름: 시, 못가른까닭: null };

  if (토막.length < 2) return { 이름: null, 못가른까닭: '주소가 없거나 너무 짧다' };

  const 둘째 = 토막[1];
  const 셋째 = 토막[2] ?? '';

  /* 🔴 「수원시 장안구」 — 큰 시는 셋째 낱말까지 봐야 한장 크기가 된다 */
  if (/시$/.test(둘째) && /구$/.test(셋째)) return { 이름: `${둘째} ${셋째}`, 못가른까닭: null };

  if (/[구군시]$/.test(둘째)) return { 이름: 둘째, 못가른까닭: null };

  return { 이름: null, 못가른까닭: `주소 둘째 낱말이 시·군·구로 안 끝난다 — 「${둘째}」` };
}

/** 주소 표기용 열쇠. ⚠ 시·도를 안 붙이면 「중구」처럼 여러 시·도에 있는 이름이 겹친다 */
export const 지역열쇠 = (시도: string, 이름: string) => `${시도} ${이름}`;

/**
 * 주소에 쓸 수 있는 꼴로 바꾼다. **띄어쓰기를 하이픈으로** 바꾼다 —
 * 「경기도-수원시-장안구」. ⛔ 주소에 공백을 그대로 넣지 않는다.
 */
export const 지역슬러그 = (시도: string, 이름: string) => `${시도} ${이름}`.replace(/\s+/g, '-');

/** 슬러그를 다시 시·도와 묶음 이름으로 푼다 */
export function 슬러그풀기(슬러그: string): { 시도: string; 이름: string } | null {
  const 토막 = String(슬러그 ?? '').split('-').filter(Boolean);
  if (토막.length < 1) return null;
  /* 「세종특별자치시」처럼 한 토막인 경우 시·도와 이름이 같다 */
  if (토막.length === 1) return { 시도: 토막[0], 이름: 토막[0] };
  return { 시도: 토막[0], 이름: 토막.slice(1).join(' ') };
}

/**
 * 한 벌로 **팔 만한 크기**인가. 2번이 정한 값 규칙과 같은 경계를 쓴다.
 * ⛔ 이 수를 지면과 스크립트에 따로 적지 않는다 — 어긋나면 값과 화면이 달라진다.
 */
export const 팔만한최소 = 10;
export const 팔만한가 = (곳수: number) => Number.isFinite(곳수) && 곳수 >= 팔만한최소;
