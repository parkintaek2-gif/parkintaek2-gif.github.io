/**
 * 학교 주소에서 **파는 단위**(시·군·구)를 가른다.
 *
 * ## 🔴 왜 고쳤나 (2026-08-08 05:2x → 08:5x · 2번이 값을 정하면서)
 *
 *   처음엔 주소 **둘째 낱말**만 봤다. 그랬더니 큰 시가 통째로 한 덩어리가 됐다.
 *
 *   ```
 *   경상남도 창원시 53곳 · 경기도 수원시 48 · 충청북도 청주시 41 · 고양시 40 · 성남시 37
 *   ```
 *
 *   ⛔ **53곳을 한 장에 넣으면 「한눈에」가 깨진다.** 강동구 14곳이 한 장에 맞는 크기였다.
 *   주소에는 「수원시 장안구」처럼 **셋째 낱말에 구가 들어 있다.** 그걸 쓰면 갈린다.
 *
 *   2번이 값을 정했다 — **10곳 이상은 한 벌로 팔고, 9곳 이하는 무료로 연다.**
 *   그러니 가르는 자가 곧 **파는 단위를 정하는 자**다. 한 곳에 두고 검사한다.
 *
 * ## 가르는 법
 *
 *   ```
 *   서울특별시 강동구 고덕로 227          → 강동구
 *   경기도 수원시 장안구 …                → 수원시 장안구      ← 셋째까지 본다
 *   경기도 가평군 …                      → 가평군
 *   강원특별자치도 동해시 …               → 동해시
 *   세종특별자치시 남세종로 441            → null   ← 구·군이 없다. **지어내지 않는다**
 *   ```
 *
 * ⛔ 못 가르면 `null` 이다. 「기타」로 뭉뚱그리지 않는다 — 뭉치면 못 잰 것이 안 보인다.
 */

export type 지역 = {
  /** 시·도. 주소 첫 낱말 */
  시도: string;
  /** 파는 단위 이름 — 「강동구」 또는 「수원시 장안구」 */
  이름: string;
  /** 주소에 쓰는 열쇠 — 시도까지 붙인다. ⚠ 「일산동구」는 고양시에만 있는 게 아니다 */
  열쇠: string;
  /** 큰 시 안의 구인가 */
  시안의구: boolean;
};

const 구군 = /[구군]$/;
const 시 = /시$/;

/**
 * 주소에서 파는 단위를 가른다. 못 가르면 `null`.
 *
 * ⚠ 시도는 **주소 첫 낱말**을 쓴다. 학교 자료의 `지역` 칸과 다를 수 있는데,
 *   주소 쪽이 실제 자리다. 둘이 어긋나면 그건 따로 세어 봐야 할 일이다.
 */
export function 지역가르기(주소: string | null | undefined): 지역 | null {
  const 조각 = String(주소 ?? '')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const [시도, 둘째, 셋째] = 조각;
  if (!시도 || !둘째) return null;

  /* 「수원시 장안구」 — 큰 시 안의 구. **이걸 먼저 본다** */
  if (시.test(둘째) && 셋째 && 구군.test(셋째)) {
    const 이름 = `${둘째} ${셋째}`;
    return { 시도, 이름, 열쇠: `${시도} ${이름}`, 시안의구: true };
  }
  /* 「강동구」·「가평군」·「동해시」 */
  if (구군.test(둘째) || 시.test(둘째)) {
    return { 시도, 이름: 둘째, 열쇠: `${시도} ${둘째}`, 시안의구: false };
  }
  /**
   * ⭐ 세종특별자치시 — **구·군이 아예 없는 시**다(2026-08-08 09:0x 실측 27곳).
   *
   *   처음엔 여기서 `null` 을 돌려줬는데, 그러면 세종 27곳이 통째로 「못 가른 곳」이 된다.
   *   **못 가른 게 아니라 가를 것이 없는 것**이다. 둘은 다르다 —
   *   앞은 우리 잘못이고 뒤는 그 도시의 생김새다.
   *
   *   시·도 이름 자체가 「…시」로 끝나면 그 시가 곧 단위다.
   *   ⚠ 서울·부산 같은 데는 여기까지 안 온다. 위에서 구가 잡히기 때문이다.
   */
  if (시.test(시도)) {
    return { 시도, 이름: 시도, 열쇠: 시도, 시안의구: false };
  }

  /* 그 밖 — ⛔ 지어내지 않는다 */
  return null;
}

/** 주소에 쓸 조각. 「경기도 수원시 장안구」 → `경기도-수원시-장안구` */
export function 지역슬러그(g: 지역): string {
  return `${g.시도}-${g.이름.split(/\s+/).join('-')}`;
}

/** 슬러그를 되돌린다. 첫 조각이 시·도, 나머지가 이름 */
export function 슬러그풀기(slug: string): { 시도: string; 이름: string } | null {
  const 조각 = String(slug ?? '').split('-').filter(Boolean);
  if (조각.length < 2) return null;
  const [시도, ...나머지] = 조각;
  return { 시도, 이름: 나머지.join(' ') };
}

/**
 * 한 벌로 팔 만한 크기인가. **2번이 정한 값이다**(2026-08-08 05:4x) —
 * 10곳 이상은 한 벌, 9곳 이하는 무료로 연다.
 *
 * ⛔ 이 수를 지면이나 스크립트에 따로 적지 않는다. 여기서 부른다.
 */
export const 한벌최소 = 10;
export const 한벌로팔만한가 = (곳수: number) => Number.isFinite(곳수) && 곳수 >= 한벌최소;
