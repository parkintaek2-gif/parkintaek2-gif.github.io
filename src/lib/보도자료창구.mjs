/** 그 분류에서 쓸 수 있는 창구만 */
export function 분류별창구(분류코드) {
  const c = String(분류코드 ?? '');
  return 창구.filter((x) => x.분류.includes(c));
}

/** 사진까지 받을 수 있다고 확인한 창구만 — 사진이 급할 때 여기부터 본다 */
export function 사진받는창구(분류코드) {
  return 분류별창구(분류코드).filter((x) => x.사진);
}

