/**
 * 요청 경로를 **파일을 찾을 후보들**로 편다. 못 펴면 `[]`.
 *
 * ── 왜 별도 파일인가 ──────────────────────────────────────────────
 * `server.mjs` 는 최상위에서 `server.listen()` 을 부른다. 거기서 함수를 가져오면
 * **시험을 돌릴 때마다 서버가 뜬다.** 그렇다고 listen 을 조건부로 바꾸면
 * **배포 때 서버가 안 뜰 위험**을 지는데, 그건 시험 하나 때문에 질 위험이 아니다.
 *
 * ── ⚠ 왜 「후보 목록」인가 — 첫 수정이 안 통해서다 ─────────────────
 * 2026-08-04, 백년지도 한글 주소가 404 였다(3,450장). 3번이 원인을 잡아 줬다.
 *
 *   Node 는 `req.url` 을 **바이트 그대로(latin1)** 준다. 클라이언트가 한글을
 *   인코딩 없이 보내면 「조리과」 9바이트가 깨진 문자 9개로 들어온다.
 *
 * 그래서 처음엔 이렇게 고쳤다 — **그리고 안 통했다.**
 *
 *   if (!pathname.includes('%') && 상위바이트.test(decoded)) { …되살린다 }
 *                ^^^^^^^^^^^^^^^^ 이 조건이 **항상 막는다**
 *
 * 실측으로 잡았다. 서버는 `new URL(req.url, ...)` 의 `pathname` 을 넘기는데,
 * **`new URL()` 이 원시 바이트를 퍼센트 인코딩해 버린다.**
 *
 *   서버가 받는 것   /major/ì¡°ë¦¬ê³¼                  % 없음
 *   new URL 통과 후  /major/%C3%AC%C2%A1%C2%B0…      % 생김   ← 코드가 보는 값
 *
 * 「% 가 없을 때만」이라는 조건은 **원시 문자열에 대한 이야기**였는데
 * 함수가 받는 것은 이미 URL 을 통과한 값이었다. 조건이 뜻을 잃었다.
 *
 * ── 그래서 조건으로 가르지 않고 **둘 다 시도한다** ──────────────────
 * 어느 쪽이 맞는지 **파일이 있는지로 판정**한다. 이게 제일 안전하다 —
 * 멀쩡히 열리던 경로를 새 규칙이 깨뜨릴 위험이 **0**이다.
 * 순서가 뜻을 갖는다: **원래 해석이 먼저**, 되살린 것이 나중.
 */

/** latin1 상위 영역. 원시 UTF-8 바이트가 문자로 읽히면 여기에 걸린다.
 *  ⚠ 제대로 해석된 한글(U+AC00~)은 이 범위 **밖**이라 안 걸린다 — 그래서 안전하다. */
const 상위바이트 = new RegExp('[' + String.fromCharCode(0x80) + '-' + String.fromCharCode(0xff) + ']');
/** U+FFFD. UTF-8 로 못 읽었다는 표시 */
const 대체문자 = String.fromCharCode(0xfffd);

export function 경로후보(pathname) {
  let decoded;
  try {
    decoded = decodeURIComponent(pathname);
  } catch {
    return []; // 해석 불가 → 후보 없음 → 404. **던지지 않는다** (프로세스가 죽는다)
  }

  const 후보 = [decoded];

  /* 깨진 것처럼 보이면 되살린 것도 후보에 넣는다.
   * ⚠ 되살린 결과가 **올바른 UTF-8 일 때만** 넣는다. 진짜 latin1 문자(é)는
   *   되살리면 U+FFFD 가 생기는데, 그건 후보가 될 수 없다. */
  if (상위바이트.test(decoded)) {
    const 다시 = Buffer.from(decoded, 'latin1').toString('utf8');
    if (다시 !== decoded && !다시.includes(대체문자)) 후보.push(다시);
  }

  return 후보;
}

/** 옛 이름. 첫 후보만 준다 — 기존 호출부가 있으면 안 깨지게. */
export function 경로펴기(pathname) {
  const c = 경로후보(pathname);
  return c.length ? c[0] : null;
}
