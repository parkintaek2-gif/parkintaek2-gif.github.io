/**
 * profit-streak.mjs — **몇 해를 잇달아 흑자였나.** (5번, 2026-09-23)
 *
 * ── 🔴 왜 (사장님이 기사를 직접 주셨다, 2026-09-23 새벽) ────────────────
 * 사장님이 연합뉴스 「**대기업 33% 5년 이상 흑자행진…'100분기 이상' 연속흑자 11곳**」
 * (2026-09-23 06:01)을 주셨다.
 *
 * ⭐ 그 조사는 **대기업**만 셌다. 우리는 **상장사 전수**를 센다 —
 *   같은 물음에 더 넓은 답을 낼 수 있다. 그것이 우리가 파는 것이다.
 * ⛔ 다만 우리 자료는 아직 3년(2023·2024·2025)뿐이라 「5년 연속」·「100분기」는 «못 잰다».
 *   못 잰다고 적는다. DART 에서 옛 해를 더 받으면 그때 늘린다.
 *
 * ── ⛔ 이 자가 지키는 것 ────────────────────────────────────────────────
 * ⛔ **등수를 매기지 않는다.** 「우량」·「알짜」 같은 말을 쓰지 않는다.
 *   잇달아 흑자였다는 것은 사실이고, 그것이 좋은 회사라는 뜻은 우리가 안 붙인다.
 * ⛔ **못 잰 해를 «적자»로 읽지 않는다.** 순이익이 없는 해가 있으면 그 회사는 세지 않는다.
 * ⛔ 0 을 흑자로 세지 않는다 — 흑자는 «0보다 큰» 것이다.
 */

/** 그 회사의 해들을 오래된 것부터. ⛔ 순이익이 없는 해가 하나라도 있으면 «못 쟀다» */
export function 해줄(행들) {
  const 것 = (행들 ?? [])
    .filter((r) => r && Number.isFinite(r.year) && Number.isFinite(r.net_profit_krw))
    .sort((a, b) => a.year - b.year);
  return 것;
}

/** 세 해가 다 있고 순이익이 다 잡혔나 — 이 자리를 넘은 회사만 센다 */
export function 셀만한가(행들, 해수 = 3) {
  return 해줄(행들).length >= 해수;
}

/**
 * **끝에서부터 몇 해를 잇달아 흑자였나.** 마지막 해가 적자면 0 이다.
 * ⚠ 「잇달아」는 «가장 최근부터» 센다 — 옛날에 흑자였다가 지금 적자면 그 줄은 끊긴 것이다.
 */
export function 이은흑자해(행들) {
  const 것 = 해줄(행들);
  let n = 0;
  for (let i = 것.length - 1; i >= 0; i -= 1) {
    if (것[i].net_profit_krw > 0) n += 1; else break;
  }
  return n;
}

/** 끝에서부터 몇 해를 잇달아 적자였나 */
export function 이은적자해(행들) {
  const 것 = 해줄(행들);
  let n = 0;
  for (let i = 것.length - 1; i >= 0; i -= 1) {
    if (것[i].net_profit_krw < 0) n += 1; else break;
  }
  return n;
}

/** 순이익이 해마다 «늘기»까지 했나 — 흑자만으로는 모자란 것을 보는 자리 */
export function 해마다늘었나(행들, 칸 = 'net_profit_krw') {
  const 것 = 해줄(행들);
  if (것.length < 2) return false;
  for (let i = 1; i < 것.length; i += 1) {
    const a = 것[i - 1][칸];
    const b = 것[i][칸];
    if (!Number.isFinite(a) || !Number.isFinite(b) || !(b > a)) return false;
  }
  return true;
}

/**
 * **첫 해와 마지막 해만** 보고 꼴을 가른다 — 「앞뒤가 어떻게 달라졌나」다.
 *
 * 🔴🔴 [2026-09-23] **이 자를 «내내 흑자»를 세는 데 썼다가 96곳을 잘못 셌다.**
 *   이름이 「줄곧 흑자」였는데 실제로 재는 것은 «첫 해와 끝 해»뿐이라,
 *   가운데 해가 적자인 회사까지 줄곧 흑자로 세어졌다(1,072 → 1,168).
 *   지면에 「Profitable every year 49.3%」로 나갈 뻔했다. 배포 전에 검산으로 잡았다.
 *   ⇒ 「내내」를 세려면 «모든 해»를 봐야 한다 — 그것은 이은흑자해() 가 한다.
 *   ⛔ 이름이 재는 것과 다르면 반드시 사고가 난다. 그래서 값도 이름도 고쳤다.
 */
export function 앞뒤꼴(행들) {
  const 것 = 해줄(행들);
  if (것.length < 2) return null;
  const 앞 = 것[0].net_profit_krw > 0;
  const 뒤 = 것[것.length - 1].net_profit_krw > 0;
  if (앞 && 뒤) return '앞뒤 다 흑자';   /* ⚠ 가운데가 적자일 수 있다 */
  if (!앞 && !뒤) return '앞뒤 다 적자';
  return 앞 ? '흑자에서 적자로' : '적자에서 흑자로';
}

/** 회사 묶음 전체를 세어 한 벌로 낸다 */
export function 통계내기(묶음, 해수 = 3) {
  const 셈 = {
    센회사: 0, 내내흑자: 0, 내내적자: 0, 흑자에서적자: 0, 적자에서흑자: 0,
    순익계속늚: 0, 매출계속늚: 0, 못센회사: 0, 흔들린회사: 0,
  };
  for (const 행들 of 묶음 ?? []) {
    if (!셀만한가(행들, 해수)) { 셈.못센회사 += 1; continue; }
    셈.센회사 += 1;
    /* 🔴 «내내»는 모든 해를 본다 — 앞뒤만 보면 가운데가 적자인 회사가 섞인다 */
    const 것 = 해줄(행들);
    const 다흑자 = 것.every((r) => r.net_profit_krw > 0);
    const 다적자 = 것.every((r) => r.net_profit_krw < 0);
    if (다흑자) 셈.내내흑자 += 1;
    else if (다적자) 셈.내내적자 += 1;
    else {
      셈.흔들린회사 += 1;                       /* 흑자와 적자를 오간 곳 */
      const 꼴 = 앞뒤꼴(행들);
      if (꼴 === '흑자에서 적자로') 셈.흑자에서적자 += 1;
      else if (꼴 === '적자에서 흑자로') 셈.적자에서흑자 += 1;
    }
    if (이은흑자해(행들) >= 해수 && 해마다늘었나(행들, 'net_profit_krw')) 셈.순익계속늚 += 1;
    if (해마다늘었나(행들, 'revenue_krw')) 셈.매출계속늚 += 1;
  }
  return 셈;
}

/** 몫(%) — 바닥이 0 이면 «못 쟀다»(null). ⛔ 0% 로 적지 않는다 */
export function 몫(위, 아래) {
  if (!Number.isFinite(위) || !Number.isFinite(아래) || 아래 === 0) return null;
  return 위 / 아래;
}

