/**
 * 🔢 **자릿수를 한 곳에서 못 박는다.**
 *
 * ## 🔴 왜 (2026-08-10 11:0x · 라이브 스무 장을 눈으로 보다 찾음 · 2번 지시로 고침)
 *
 *   ```
 *   예천여고   「학업중단률 **1%**」      ← 3 ÷ 306 = 0.98%
 *   한영고     「1.5%」 · 강화고 「3.4%」 · 화홍고 「1.3%」
 *   ```
 *   한 지면 안에서 「1%」와 「22.4명」이 같이 나오면 **자리를 안 맞춘 것으로 보인다.**
 *   틀린 값은 아니다. 그런데 **손님은 자릿수가 들쭉날쭉한 표를 안 믿는다.**
 *
 * ## 얼마나 되나 (실측)
 *
 *   ```
 *   학업중단률    2,333곳 중 **306곳**(13.1%)이 소수점 없이 나온다
 *   진학률·그밖율 1,710곳 중 **209곳**(12.2%)
 *   학급당학생    2,374곳 중 **239곳**(10.1%)
 *   교원1인당학생 2,374곳 중 **264곳**(11.1%)
 *   ```
 *   까닭은 하나다 — 만들 때 `Math.round(x*10)/10` 을 썼고, 정수가 되면 `.0` 이 사라진다.
 *
 * ## ⛔ 자료를 다시 짓지 않는다
 *
 *   수집기를 다시 돌리면 원자료를 또 받아야 하고, 그 사이 다른 창이 같은 파일을 만진다.
 *   ⭐ **값은 그대로 두고 화면에서만 자리를 맞춘다.** 한 곳을 고치면 다 바뀐다 —
 *     값(9,900)을 `price.ts` 한 곳에 둔 것과 같은 이치다.
 *
 * ⚠ **반올림하지 않는다.** 이미 반올림된 값의 **보이는 자리만** 채운다.
 *   `1` → `1.0` 이지 `0.98` → `1.0` 이 아니다. 그 반올림은 자료를 만들 때 이미 했다.
 */

/**
 * 소수 한 자리로 보이게 한다. ⛔ 없는 값을 0 으로 만들지 않는다 — `null` 은 `null` 로 돌려준다.
 *
 * ```
 * 한자리(1)     → '1.0'
 * 한자리(1.5)   → '1.5'
 * 한자리(22.44) → '22.4'      ⚠ 이건 이미 반올림된 값이 들어올 일이 없다. 그래도 안전하게 자른다
 * 한자리(null)  → null
 * ```
 */
export function 한자리(값: number | null | undefined): string | null {
  if (값 == null || !Number.isFinite(값)) return null;
  return 값.toFixed(1);
}

/**
 * 퍼센트 글자. `한자리` 에 `%` 만 붙인다.
 * ⚠ 부르는 쪽에서 `{퍼센트(x)}` 로 쓰면 `%` 를 두 번 적을 일이 없다.
 */
export function 퍼센트(값: number | null | undefined): string | null {
  const s = 한자리(값);
  return s == null ? null : `${s}%`;
}

/** 사람 수처럼 「명」이 붙는 소수 — 「22.4명」 */
export function 명(값: number | null | undefined): string | null {
  const s = 한자리(값);
  return s == null ? null : `${s}명`;
}
