/**
 * 대학 자료를 지면이 쓰기 좋게 다듬는 것들.
 *
 * ⭐ 왜 만드나 (2026-08-05 실측) —
 *   377곳 가운데 **48곳은 수치가 하나도 없다.** 취업률만이 아니라 중도탈락·재적학생까지
 *   전부 없다. 그런데 그 48곳이 **「이 지역의 다른 대학」 목록에 그대로 섞여 나가고 있었다.**
 *
 *   강원 지역 대학교 13곳 중 5곳이 그랬다 —
 *     ❌ 강원대학교 제2캠퍼스 · 경동대학교 제2·제3캠퍼스 · 국립강릉원주대학교 제2캠퍼스
 *     ❌ 한중대학교
 *
 *   학부모가 그걸 누르면 **텅 빈 지면**이 나온다. 없는 선택지를 내민 것이다.
 *
 * ⛔ **지면을 지우지는 않는다.** 지우면 「우리가 숨겼다」가 된다.
 *   검색으로 찾아온 사람에게는 「수치가 없다」는 사실 자체가 답이다.
 *   다만 **우리 쪽에서 먼저 권하지 않는다.** 그 둘은 다르다.
 *
 * ── 48곳이 왜 비었나 (재서 갈랐다) ────────────────────────────
 *   28곳  「제N캠퍼스」 — 캠퍼스 단위 공시가 아예 없다.
 *          **값이 있는 제N캠퍼스는 0곳이다.** 수치는 본교에 몰려 있다
 *          (강원대 본교 59% · 가톨릭대 62.5% · 경기대 62.7% · 명지대 65.2% 확인)
 *   20곳  본교인데 지표 호출이 전부 빈 응답
 *
 * ⚠ **20곳이 폐교·통합된 학교인지는 아직 못 쟀다.**
 *   원자료(`archive/raw/alimi/universities.json`)에 폐교·상태 필드가 **없다.**
 *   서남대학교와 강원대학교의 자료 구조가 글자 하나 다르지 않다.
 *   그래서 「폐교됐다」고 쓰지 않는다 — **「수치가 없고, 지금도 신입생을 받는지 우리가 모른다」**
 *   까지만 쓴다. 짐작을 사실처럼 적지 않는다.
 */

import 폐교자료 from '../data/100yearmap/closed-universities.json';

export type Uni = Record<string, any>;

export type 폐교 = {
  이름: string;
  폐교년도: number | null;
  법인상태: string | null;
  지역: string | null;
  구분: string | null;
};

/**
 * 🔴 **폐교한 학교인가.** 2026-08-05 에 붙였다.
 *
 * 그 전에는 수치가 없는 20곳에 「지금도 신입생을 받는지 저희는 확인하지 못했습니다」라고
 * 써 뒀는데, **그건 우리가 안 재서 못 쓴 말이지 알 수 없는 사실이 아니었다.**
 * 교육부 산하 한국사학진흥재단이 폐교 명단을 공개하고 있었다(이용허락범위 제한 없음).
 *
 * 재보니 20곳 중 **8곳이 실제로 문을 닫은 학교**였다 — 서남대(2018)·한중대(2018)·
 * 대구외대(2018)·대구미래대(2018)·동부산대(2020)·서해대(2021)·한려대(2022)·강원관광대(2024).
 *
 * ⛔ **명단에 없다고 「살아 있다」고 쓰지 않는다.** 통합·개명은 폐교가 아니라 명단에 안 들어온다.
 *    있으면 「문을 닫았다」, 없으면 **「폐교 명단에는 없다」**까지다.
 */
const 폐교목록 = new Map<string, 폐교>(
  ((폐교자료 as any).자료 as 폐교[]).map((x) => [x.이름, x]),
);

/** 이 학교가 폐교 명단에 있나. **캠퍼스는 본교 이름으로도 본다** —
 *  본교가 문을 닫으면 그 캠퍼스도 같이 닫힌다(서남대학교 제2캠퍼스가 그렇다) */
export function 폐교정보(u: Uni): 폐교 | null {
  return 폐교목록.get(u.표시명) ?? 폐교목록.get(본교이름(u)) ?? null;
}

export const 폐교출처 = (폐교자료 as any).출처 as {
  기관: string;
  이름: string;
  주소: string;
  이용허락범위: string;
  갱신주기: string;
};

/** 공시 수치가 하나라도 있나. ⚠ 취업률만 보면 안 된다 — 취업률만 없는 학교와 구분이 안 된다 */
export function 수치있음(u: Uni): boolean {
  return Boolean(u.취업률 || u.중도탈락률 || u.재학생충원율 || u.전임교원확보율 || u.재적학생 != null);
}

/** 「제N캠퍼스」인가. 전체이름은 `강원대학교 _ 제2캠퍼스` 꼴이다 */
export function 캠퍼스인가(u: Uni): boolean {
  return u.캠퍼스 != null && u.캠퍼스 !== '본교';
}

/** `강원대학교 _ 제2캠퍼스` → `강원대학교` */
export function 본교이름(u: Uni): string {
  return String(u.전체이름 ?? u.표시명).split(' _ ')[0].trim();
}

/**
 * 이 캠퍼스의 본교를 찾는다. 없으면 null.
 * ⚠ 본교도 수치가 없을 수 있다(폐교로 보이는 학교의 캠퍼스). 그때는 링크를 걸지 않는다 —
 *   빈 지면에서 빈 지면으로 보내는 것은 도움이 아니다.
 */
export function 본교찾기(u: Uni, 전체: Uni[]): Uni | null {
  if (!캠퍼스인가(u)) return null;
  const 이름 = 본교이름(u);
  const 본 = 전체.find((x) => !캠퍼스인가(x) && 본교이름(x) === 이름);
  return 본 && 수치있음(본) ? 본 : null;
}

/**
 * 목록에 **권할 만한** 학교만 남긴다.
 * ⛔ 이것은 「좋은 학교 고르기」가 아니다. **보여 줄 것이 있는 지면**만 고르는 것이다.
 *    순위와 무관하다.
 */
export function 권할만한(list: Uni[]): Uni[] {
  return list.filter(수치있음);
}
