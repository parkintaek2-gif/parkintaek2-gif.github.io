/**
 * krx-지면-한국어는-영어와-짝인가.test.mjs — **영어권 손님 화면에 홀로 선 한국어를 두지 않는다**
 * 실행: node --test tests/krx-지면-한국어는-영어와-짝인가.test.mjs
 *
 * ── 🔴 왜 이 자가 있나 (2026-10-10 · 5번) ────────────────────────────────
 *   `/data/krx-open-api-fields` 는 맨 위에 못을 박고 시작한다 —
 *   **「⛔ 화면에 한국어를 내지 않는다 — 손님이 영어권이다」**
 *   그런데 오늘 내가 약관 절을 보태면서 `재배포` · `제한 없음` · `이용허락범위` 를 넣었다.
 *
 *   ⭐ 되돌리지 않았다. 그 규칙이 막으려던 것은 «손님이 못 읽는 한국어»인데,
 *     이 셋은 손님이 KRX 약관 지면에서 **Ctrl+F 에 붙여 넣을 글자**다. 그것이 요점이다.
 *   ⛔ 그래서 선을 다시 그었다 — **한국어 낱말 옆에는 영어 뜻이 반드시 붙는다.**
 *
 *   ⚠ 이런 선은 «말»로 두면 반드시 잊힌다. 다음 사람이 한국어를 하나 더 넣을 때
 *     영어를 안 붙여도 아무도 모른다. 그래서 자로 바꾼다.
 *     (우리 강령 ④ — 「규칙은 문장이 아니라 검사로 둔다」)
 *
 * ⛔ 이 자는 «나온 지면»을 잰다. 소스가 아니다 — 소스 주석의 한국어는 손님에게 안 간다.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 지면 = path.join(뿌리, 'dist', 'data', 'krx-open-api-fields.html');

/** 손님 눈에 보이는 글만 — script·style·주석은 브라우저가 안 그린다 */
export function 보이는글(h) {
  return String(h)
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z]+;|&#\d+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** 한글이 든 덩이를 찾는다 */
export function 한국어덩이들(글) {
  return [...String(글).matchAll(/[가-힣][가-힣\s]*/g)].map((m) => m[0].trim()).filter(Boolean);
}

/**
 * 🔴 [2026-10-10 · 처음 짠 자가 «거짓 초록»을 냈다] ─────────────────────
 *   처음에는 「한국어 둘레 90자 안에 라틴 글자가 있나」로 쟀다. 자가시험은 지나갔다.
 *   그런데 **진짜 지면에 홀로 선 한국어를 일부러 넣어 보니 안 잡았다.**
 *   까닭은 뻔했다 — **이 지면은 통째로 영어다.** 어느 한국어든 둘레에 늘 영어가 있다.
 *   조건이 «항상 참»이라 무엇을 넣어도 초록이었다.
 *   ⛔ 「잡을 것이 없는 검사는 거짓 빨강만 낸다」의 쌍둥이다 —
 *     **잡을 줄 모르는 검사는 거짓 초록만 낸다.** 더 나쁘다. 지키는 줄 알게 만든다.
 *
 * ✅ 그래서 재는 법을 바꾼다. 둘레를 보지 않고 **허락한 낱말인가**를 본다.
 *   늘리려면 사람이 여기에 손으로 적어야 한다 — 그 수고가 곧 규칙을 지키는 힘이다.
 */
export const 허락한한국어 = [
  /* 손님이 KRX 약관 지면에서 Ctrl+F 에 붙여 넣을 글자. 그래서 한국어 그대로여야 뜻이 산다 */
  '재배포',          // redistribution — 약관에 이 낱말이 «없다»는 것이 이 절의 요점이다
  '이용허락범위',     // licence scope — 공공데이터포털 화면에 그렇게 적혀 있다
  '제한 없음',        // no restriction — 그 칸에 실제로 적힌 값

  /* 🔴 [2026-10-10] 이 자를 고치자마자 **내가 안 넣은 것**을 하나 물어 왔다 — 바닥글의 법인명이다.
     `Beomjin Academy (범진아카데미)` · 사이트 모든 지면에 들어간다.
     ⛔ 이것은 결함이 아니다 — 등록된 법인명이고 로마자가 «바로 앞»에 붙어 있다.
       사업자 정보는 한국법이 적으라는 것이기도 하다.
     ⭐ 그래도 자가 문 것은 옳았다. 이 자의 뜻이 「사람이 보고 판단해라」이고,
       나는 실제로 보고 판단해서 여기 적었다. 그 수고가 이 자의 값이다. */
  '범진아카데미',     // Beomjin Academy — 바닥글 법인 등록명. 로마자 표기가 앞에 붙어 있다
];

/** 허락한 낱말을 글에서 걷어 낸다. 남는 한국어가 있으면 그것이 «홀로 선 것»이다 */
export function 허락한것빼기(글) {
  let 남은 = String(글);
  for (const 낱말 of 허락한한국어) 남은 = 남은.split(낱말).join(' ');
  return 남은;
}

test('KRX 지면에 홀로 선 한국어가 없다', async (t) => {
  /* ⚠ 빌드 전에는 잴 것이 없다. 「파일이 없다」를 «초록»으로 넘기지 않는다 —
     잡을 것이 없는 검사는 거짓 초록도 낸다. 소리 내어 건너뛴다. */
  if (!fs.existsSync(지면)) {
    t.skip(`${path.relative(뿌리, 지면)} 가 없다 — 먼저 빌드해야 잴 수 있다(못 쟀다)`);
    return;
  }
  const 글 = 보이는글(fs.readFileSync(지면, 'utf8'));

  await t.test('허락한 낱말 말고는 한국어가 손님 화면에 없다', () => {
    const 홀로선것 = [...new Set(한국어덩이들(허락한것빼기(글)))];
    assert.deepEqual(홀로선것, [],
      '영어권 손님 화면에 허락하지 않은 한국어가 있습니다.\n'
      + `  홀로 선 것: ${홀로선것.join(' · ')}\n`
      + '※ 이 지면의 한국어는 «손님이 KRX 약관에서 Ctrl+F 할 글자»일 때만 허용됩니다.\n'
      + '  정말 그런 낱말이면 이 자의 `허락한한국어` 에 «손으로» 더하고, 지면에서는\n'
      + '  영어 뜻을 바로 옆에 붙이십시오. 그 수고가 규칙을 지키는 힘입니다.');
  });

  await t.test('약관 절이 «읽은 날»을 밝힌다 — 날짜 없는 인용은 거짓말이 된다', () => {
    assert.match(글, /2026-09-09/,
      '약관을 언제 읽은 것인지가 화면에 없습니다. 약관은 바뀝니다 — 날짜 없는 조항 인용은\n'
      + '「지금도 이렇다」로 읽히고, 그것은 우리가 모르는 것을 아는 척하는 것입니다.');
  });

  await t.test('⛔ 「써도 된다·안 된다」를 정해 주지 않는다', () => {
    /* 우리가 바늘을 세우지 않는다 — 지형을 그려 놓고 바늘은 읽는 분이 세운다.
       ⚠ 법률 자문으로 읽히면 자격 문제이기도 하다. */
    assert.match(글, /not legal advice/i,
      '약관을 인용하면서 「법률 자문이 아니다」를 안 적었습니다 — 읽는 사람이 판단을\n'
      + '우리에게 맡기게 됩니다. 우리는 조항을 옮기고 읽은 날을 밝힐 뿐입니다.');
  });
});

/* ── 자가시험 — 이 자가 정말 서는가 ──────────────────────────────────────
   ⛔ 「잡을 것이 없는 검사는 거짓 빨강만 낸다」의 반대도 참이다 —
     «잡을 줄 모르는 검사는 거짓 초록만 낸다». 넣어 보고 정말 우는지 본다. */
test('자가시험 — 이 자가 헛돌지 않는다', async (t) => {
  await t.test('🔴 둘레가 온통 영어여도 홀로 선 한국어를 잡는다', () => {
    /* ⚠ 이것이 처음 짠 자가 놓친 바로 그 자리다. 둘레에 영어가 넘쳐도 잡아야 한다. */
    const 글 = 'All English around here, plenty of it. 종목코드를 숫자로 읽으면 안 됩니다. '
      + 'And more English after that, lots and lots of English words.';
    assert.deepEqual([...new Set(한국어덩이들(허락한것빼기(글)))],
      ['종목코드를 숫자로 읽으면 안 됩니다'],
      '영어 바다에 떠 있는 한국어를 못 잡고 있습니다 — 처음 짠 자가 여기서 거짓 초록을 냈습니다');
  });
  await t.test('허락한 낱말은 안 잡는다', () => {
    const 글 = 'the Korean word for redistribution, 재배포, is absent from the terms';
    assert.deepEqual(한국어덩이들(허락한것빼기(글)), [],
      '허락 목록에 있는 낱말인데 빨갛게 울고 있습니다');
  });
  await t.test('허락한 낱말 옆에 허락 안 한 것이 붙어 와도 그것만 잡는다', () => {
    const 글 = 'licence scope 이용허락범위 is 제한 없음 but also 몰래넣은말 here';
    assert.deepEqual([...new Set(한국어덩이들(허락한것빼기(글)))], ['몰래넣은말'],
      '허락한 낱말에 가려 그 옆의 새 한국어를 놓치고 있습니다');
  });
  await t.test('보이는 글에서 주석과 스크립트를 걷는다', () => {
    const h = '<p>Hello</p><!-- 숨은주석 --><script>var 변수="스크립트";</script>';
    const g = 보이는글(h);
    assert.match(g, /Hello/);
    assert.doesNotMatch(g, /숨은주석/, '주석이 손님 글로 새고 있습니다');
    assert.doesNotMatch(g, /스크립트/, '스크립트 속 글이 손님 글로 새고 있습니다');
  });
  await t.test('한국어가 하나도 없으면 빈 목록이다(없는 것을 지어내지 않는다)', () => {
    assert.deepEqual(한국어덩이들('pure english only, no hangul'), []);
  });
});
