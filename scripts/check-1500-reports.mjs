#!/usr/bin/env node
/**
 * check-1500-reports.mjs — **15시 업무보고가 총괄에게 들어왔나**를 잰다. (총괄 자리 전용)
 *
 * ── 왜 이 자가 생겼나 (2026-09-01 20:3x · 5번) ──────────────────────────────
 * 사장님 전체 공지 —
 *   「업무보고 오후 4시에 정확히 내가 **ppt슬라이드의 정해진 양식**을 보고 받아야 한다.
 *    그러기 위해 **매일 15시에 업무보고를 준비해 총괄에 넘겨야 한다. 이것도 자물쇠를
 *    만들던지 해라.** 일을 제대로 하지 않는 것과 서로 소통을 잘 하지 않는게 큰 문제다」
 *
 * ⭐ 사장님 말씀의 알맹이는 「보고를 하라」가 아니라 **「기억에 맡기지 말라」**다.
 *   매뉴얼에 「15시에 낸다」고 적어 두는 것은 자물쇠가 아니다 — 바쁜 날 그냥 지나간다.
 *
 * ── 총괄이 지는 몫 둘 ───────────────────────────────────────────────────────
 *  ① 15시에 «안 들어온 유닛»을 내가 찾아가서 받아 온다. 「안 왔습니다」는 보고가 아니다.
 *  ② 16시 PPT 는 내가 만든다. 유닛이 낸 것을 그대로 붙이지 않고 종합한다.
 *
 * ── 정해진 양식 (이 자가 알아보는 꼴) ───────────────────────────────────────
 * 각 유닛은 `docs/세션간-메모.md` 에 이 머리로 시작하는 덩이를 붙인다 —
 * ```
 * ## [3번 → 총괄] 2026-09-01 15:00 · 업무보고
 * ```
 * ⛔ 분을 `15:0x` 처럼 안 채우면 «안 낸 것»으로 센다. 어림한 시각은 나중에 순서를 못 맞춘다.
 * ⚠ 다른 꼴(`[3번 → 5번]` 등)도 받는다 — 총괄 번호가 바뀌므로 이름에 매지 않는다.
 *
 * ── ⛔ 이 자가 지키는 것 ────────────────────────────────────────────────────
 * ⛔ **15시 «전»에는 빨간불을 안 켠다.** 아직 낼 때가 아닌 것은 흠이 아니다.
 *    하루 종일 빨간불이면 사람이 빨간불 자체를 안 보게 되고 자가 죽는다.
 * ⛔ 못 읽으면 「이상 없음」으로 넘기지 않는다 — 「못 쟀다」로 적는다.
 * ⛔ 사장님 화면에 아무것도 안 띄운다. 팝업·소리 없다.
 *
 * 쓰는 법
 *   node scripts/check-1500-reports.mjs            지금 상태를 낸다
 *   node scripts/check-1500-reports.mjs --체크리스트 두 시간 체크리스트가 부르는 한 줄
 *   node scripts/check-1500-reports.mjs --자가시험   통과/실패를 센다
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 메모자리 = path.join(뿌리, 'docs', '세션간-메모.md');

/** 15시 보고를 내야 하는 유닛. ⚠ 총괄(5번) 자신은 받는 쪽이라 이 셈에서 뺀다. */
const 낼유닛 = ['1', '2', '3', '4', '6'];
const 마감시 = 15;

/** 오늘 날짜(KST). ⛔ toISOString() 은 UTC 라 자정 앞뒤로 하루가 어긋난다. */
export function 오늘KST(이제 = new Date()) {
  return 이제.toLocaleDateString('sv-SE', { timeZone: 'Asia/Seoul' }); // YYYY-MM-DD
}
export function 지금시KST(이제 = new Date()) {
  return Number(이제.toLocaleString('sv-SE', { timeZone: 'Asia/Seoul', hour: '2-digit', hour12: false }).slice(0, 2));
}

/**
 * 메모 글에서 «오늘 15시 이후에 총괄에게 온 업무보고»를 유닛별로 찾는다.
 * @returns {{낸유닛:string[], 안낸유닛:string[], 어림시각:string[]}}
 */
export function 뒤진다(글, 오늘) {
  const 낸것 = new Set();
  const 어림 = [];
  /* `## [3번 → 총괄] 2026-09-01 15:00 · 업무보고` · 총괄 자리에 번호가 와도 받는다 */
  const 무늬 = /^##+\s*\[(\d{1,2})번\s*→\s*(?:총괄|\d{1,2}번(?:\([^)]*\))?)\]\s*(\d{4}-\d{2}-\d{2})\s+(\d{2}):(\d{2}|\dx|x{2})\s*·\s*업무보고/gm;
  for (const m of 글.matchAll(무늬)) {
    const [, 번호, 날, 시, 분] = m;
    if (날 !== 오늘) continue;
    if (Number(시) < 마감시) continue;      /* 15시 전에 낸 것은 그날 몫이 아니다 */
    if (!/^\d{2}$/.test(분)) { 어림.push(`${번호}번 ${시}:${분}`); continue; } /* 분을 안 채운 것 */
    낸것.add(번호);
  }
  return {
    낸유닛: 낼유닛.filter((u) => 낸것.has(u)),
    안낸유닛: 낼유닛.filter((u) => !낸것.has(u)),
    어림시각: 어림,
  };
}

function 낸다(한줄모드) {
  let 글;
  try { 글 = fs.readFileSync(메모자리, 'utf8'); }
  catch (e) {
    /* ⛔ 조용히 통과시키지 않는다 */
    console.log(`🔴 ⑨ 15시 보고    메모를 못 읽었다 — ${e.code || e.message} (${메모자리})`);
    return 1;
  }
  const 오늘 = 오늘KST();
  const 시 = 지금시KST();
  const r = 뒤진다(글, 오늘);

  /* 15시 전 — 아직 낼 때가 아니다. 흠이 아니다 */
  if (시 < 마감시) {
    const 말 = `⏳ ⑨ 15시 보고    아직 ${마감시}시 전이다(지금 ${String(시).padStart(2, '0')}시) — 흠이 아니다`;
    console.log(말);
    return 0;
  }

  if (한줄모드) {
    if (r.안낸유닛.length === 0 && r.어림시각.length === 0) {
      console.log(`✅ ⑨ 15시 보고    ${r.낸유닛.length}유닛 다 들어왔다 [${r.낸유닛.join(',')}]`);
      return 0;
    }
    const 조각 = [];
    if (r.안낸유닛.length) 조각.push(`안 온 곳 [${r.안낸유닛.map((u) => u + '번').join(' ')}]`);
    if (r.어림시각.length) 조각.push(`분을 안 채운 것 [${r.어림시각.join(' ')}]`);
    console.log(`🔴 ⑨ 15시 보고    ${조각.join(' · ')} → 내가 찾아가서 받아 온다`);
    return 1;
  }

  console.log(`■ 15시 업무보고 — ${오늘} · 지금 ${String(시).padStart(2, '0')}시`);
  console.log('');
  for (const u of 낼유닛) {
    console.log(`  ${u}번  ${r.낸유닛.includes(u) ? '✅ 들어왔다' : '🔴 안 왔다'}`);
  }
  if (r.어림시각.length) {
    console.log('');
    console.log(`⚠ 분을 안 채운 것 ${r.어림시각.length}건 — ${r.어림시각.join(' · ')}`);
    console.log('   ⛔ 「15:0x」는 시각이 아니다. 안 낸 것으로 센다 — 나중에 순서를 맞출 수 없다');
  }
  console.log('');
  if (r.안낸유닛.length === 0) {
    console.log('✅ 다 들어왔다 — 16시 PPT 를 만든다');
    return 0;
  }
  console.log(`🔴 안 온 곳 ${r.안낸유닛.length} — ${r.안낸유닛.map((u) => u + '번').join(' · ')}`);
  console.log('⭐ 총괄의 몫이다 — 내가 «찾아가서 받아 온다». 「안 왔습니다」는 보고가 아니다');
  console.log('⛔ 16시를 넘기지 않는다. 못 받았으면 «못 받았다고» PPT 에 적는다');
  return 1;
}

/* ── 자가시험 — 지어낸 글로 잡는지 잰다 ── */
function 자가시험() {
  let 통과 = 0, 실패 = 0;
  const 본다 = (참, 말) => { if (참) 통과++; else { 실패++; console.log('   🔴', 말); } };
  const 오늘 = '2026-09-01';

  /* ① 정해진 꼴을 알아본다 */
  {
    const r = 뒤진다('## [3번 → 총괄] 2026-09-01 15:00 · 업무보고\n내용\n', 오늘);
    본다(r.낸유닛.join() === '3', '정해진 꼴을 못 알아본다');
    본다(r.안낸유닛.length === 4, '안 낸 유닛 셈이 틀린다');
  }
  /* ② 총괄 자리에 번호가 와도 받는다(총괄이 바뀐다) */
  {
    const r = 뒤진다('## [6번 → 5번(2번 대행)] 2026-09-01 15:04 · 업무보고\n', 오늘);
    본다(r.낸유닛.join() === '6', '총괄 번호 꼴을 못 받는다');
  }
  /* ③ 15시 «전»에 낸 것은 그날 몫이 아니다 */
  {
    const r = 뒤진다('## [3번 → 총괄] 2026-09-01 11:00 · 업무보고\n', 오늘);
    본다(r.낸유닛.length === 0, '15시 전에 낸 것을 그날 몫으로 센다');
  }
  /* ④ 어제 것을 오늘 것으로 세지 않는다 */
  {
    const r = 뒤진다('## [3번 → 총괄] 2026-08-31 15:00 · 업무보고\n', 오늘);
    본다(r.낸유닛.length === 0, '어제 것을 오늘 것으로 센다');
  }
  /* ⑤ 분을 안 채운 것은 «안 낸 것»으로 센다 */
  {
    const r = 뒤진다('## [4번 → 총괄] 2026-09-01 15:0x · 업무보고\n', 오늘);
    본다(r.낸유닛.length === 0, '분을 안 채운 것을 낸 것으로 센다');
    본다(r.어림시각.length === 1, '분을 안 채운 것을 따로 세지 않는다');
    본다(r.어림시각[0].includes('4번'), '어림 시각이 어느 유닛인지 안 적는다');
  }
  /* ⑥ 총괄(5번) 자신은 셈에서 뺀다 */
  {
    const r = 뒤진다('', 오늘);
    본다(!r.안낸유닛.includes('5'), '총괄 자신을 안 낸 유닛으로 센다');
    본다(r.안낸유닛.length === 5, '낼 유닛 수가 5가 아니다');
  }
  /* ⑦ 업무보고가 아닌 덩이는 안 센다 */
  {
    const r = 뒤진다('## [3번 → 총괄] 2026-09-01 15:00 · 매시 소통\n', 오늘);
    본다(r.낸유닛.length === 0, '업무보고가 아닌 것을 업무보고로 센다');
  }
  /* ⑧ 여럿이 낸 것을 다 센다 */
  {
    const 글 = ['## [1번 → 총괄] 2026-09-01 15:00 · 업무보고',
      '## [3번 → 총괄] 2026-09-01 15:02 · 업무보고',
      '## [6번 → 총괄] 2026-09-01 16:30 · 업무보고'].join('\n');
    const r = 뒤진다(글, 오늘);
    본다(r.낸유닛.join(',') === '1,3,6', '여럿을 다 못 센다');
  }
  /* ⑨ 날짜·시각이 UTC 로 새지 않는가 — KST 로 뽑는다 */
  {
    const 밤 = new Date('2026-09-01T15:30:00Z'); /* KST 로는 9/2 00:30 */
    본다(오늘KST(밤) === '2026-09-02', '자정 앞뒤로 날짜가 UTC 로 어긋난다');
    본다(지금시KST(밤) === 0, '시각이 UTC 로 어긋난다');
  }

  console.log(`\n══ 자가시험 통과 ${통과} · 실패 ${실패} ══ ${실패 ? '🔴' : '✅'}`);
  return 실패;
}

const 인자 = process.argv.slice(2);
if (인자.includes('--자가시험') || 인자.includes('--selftest')) process.exit(자가시험() ? 1 : 0);
else process.exit(낸다(인자.includes('--체크리스트')));
