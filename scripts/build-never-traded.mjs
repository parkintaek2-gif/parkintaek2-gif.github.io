#!/usr/bin/env node
/**
 * build-never-traded.mjs — **거래가 한 주도 없었던 종목**을 세어 굳힌다.
 *
 * ── 🔴 왜 이 자가 있나 (2026-10-10 11:0x · 5번) ──────────────────────────
 *
 * 오늘 아침 KRX 지면을 손보다가 「그 날 한 주도 안 거래된 종목 134개」를 쟀다.
 * 그 수를 더 밀어 봤더니 **남들이 안 센 것**이 나왔다.
 * ```
 *   27거래일(2026-08-27~10-07) 내내 한 주도 거래되지 않은 종목   90개
 *   그중 종가가 한 번도 안 바뀐 것                              86개 (96%)
 *   그런데도 매겨져 있는 시가총액 합                            7.14조원
 * ```
 *
 * ⭐ 그리고 더 센 것이 걸렸다 — **거래가 0 인데 시가총액이 세 배가 된 날이 있었다.**
 * ```
 *   삼부토건  08-31  종가   347 · 상장주식수 229,681,824 · 시총   797억 · 등락률 0
 *            09-01  종가 5,820 · 상장주식수  39,139,903 · 시총 2,278억 · 등락률 0
 * ```
 *   감자(또는 병합)다. 한 주도 안 거래됐는데 시가총액이 1,481억원 늘었고,
 *   **자료는 등락률 0 · 전일비 0 으로 「아무 일도 없었다」고 적는다.**
 *   ⛔ 등락률 칸을 믿고 시계열을 만들면 이 날이 통째로 안 보인다.
 *     「빈칸을 0 으로 읽지 마라」보다 나쁘다 — **0 이 들어 있는데 그 0 이 거짓이다.**
 *
 * ── ⛔ 이 자와 이 자가 먹이는 지면이 «안» 하는 것 ────────────────────────
 * ⛔ **「거래정지인가」를 말하지 않는다.** 공개 자료에 그 칸이 없다. 거래가 0 인 것은
 *   거래정지일 수도, 호가가 안 맞은 것일 수도 있다. **우리는 못 가린다.**
 *   재 보고 안 되면 안 된다고 적는다 — 그것이 이 지면의 요점이기도 하다.
 * ⛔ 「이 종목은 위험하다」로 읽히게 쓰지 않는다. 우리가 바늘을 세우지 않는다.
 *   거래가 없었다는 «사실»만 놓고, 왜인지는 모른다고 적는다.
 *
 * ⚠ `archive/` 는 .gitignore 라 빌드 컨테이너에 없다 — 그래서 수만 담은 작은 파일을
 *   커밋해 둔다(`research-stats.json` 과 같은 수법).
 *
 * 돌리기:  node scripts/build-never-traded.mjs
 *          node scripts/build-never-traded.mjs --시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 시세방 = path.join(뿌리, 'archive', 'raw', 'stocks');
const 낼곳 = path.join(뿌리, 'src', 'data', 'never-traded.json');

/**
 * 🔴 [2026-10-10 11:0x] **회사 이름이 한국어로 손님 화면에 나갈 뻔했다.**
 *   빌드해 놓고 재 보니 「삼부토건 · 에스아이리소스 …」가 영어 지면에 그대로 찍혀 있었다.
 *   ⛔ 사장님 2026-08-05 — 「우리 손님은 영어권이다. 화면에 한국어를 안 낸다」
 *   오늘 아침 KRX 지면에도 이 규칙을 적어 두고 반나절 만에 내가 어겼다.
 *
 * ✅ 그런데 **영문 이름 사전이 이미 있었다** — `src/data/korea-financials-tape.json`
 *   의 `name_en` 이다(13,545줄 · 2,709개 코드). `/company/` 지면이 그것으로 돌고 있다.
 *   ⭐ 또 「쥐고 있는 것을 안 쓴」 것이다. 오늘만 UAE 제목에서 같은 일이 있었다.
 * ⛔ 사전에 없는 코드는 **지어내지 않는다.** `영문이름: null` 로 두고 지면이
 *   코드만 보이게 한다 — 「못 잰 것은 못 쟀다고 적는다」.
 */
export function 영문이름사전(줄들) {
  const m = new Map();
  for (const r of (줄들 ?? [])) {
    const c = String(r?.code ?? '').trim().padStart(6, '0');
    const en = String(r?.name_en ?? '').trim();
    if (c && en && !m.has(c)) m.set(c, en);
  }
  return m;
}

/** 날짜별 줄을 코드로 묶는다. ⛔ 깨진 줄 하나가 나머지를 버리게 하지 않는다 */
export function 날읽기(글) {
  const m = {};
  for (const 줄 of String(글 ?? '').split(/\r?\n/)) {
    const t = 줄.trim();
    if (!t) continue;
    let o = null;
    try { o = JSON.parse(t); } catch { continue; }
    const c = String(o['코드'] ?? '').trim();
    if (c) m[c.padStart(6, '0')] = o;
  }
  return m;
}

/**
 * 날짜별 묶음들을 받아 센다.
 * @param 날별  { '20260827': { '005930': {…} }, … }
 * @param 최소날수 이 날수보다 적게 보인 종목은 «새로 상장/상장폐지» 쪽이라 안 센다
 */
export function 세기(날별, 최소날수 = 20, 영문 = new Map()) {
  const 날들 = Object.keys(날별).sort();
  if (!날들.length) return null;
  const 마지막 = 날별[날들.at(-1)];

  const 죽은 = [];
  const 값바뀜 = [];
  let 본것 = 0;

  for (const c of Object.keys(마지막)) {
    let 날수 = 0; let 거래 = 0;
    const 흐름 = [];
    for (const d of 날들) {
      const r = 날별[d][c];
      if (!r) continue;
      날수++;
      if (!r['거래없음']) 거래++;
      흐름.push({ 날: d, 종가: r['종가'], 주식수: r['상장주식수'], 시총: r['시가총액'], 등락률: r['등락률'] });
    }
    if (날수 < 최소날수) continue;
    본것++;
    if (거래 > 0) continue;

    const 값가짓수 = new Set(흐름.map((x) => x.종가)).size;
    죽은.push({ 코드: c, 이름: 마지막[c]['이름'], 영문이름: 영문.get(c) ?? null,
      시장: 마지막[c]['시장'],
      시총: 마지막[c]['시가총액'], 종가: 마지막[c]['종가'], 값가짓수 });

    /* 🔴 거래가 0 인데 «종가가 바뀐» 날 — 감자·병합이 숨어 있는 자리다 */
    if (값가짓수 > 1) {
      for (let i = 1; i < 흐름.length; i++) {
        const 앞 = 흐름[i - 1]; const 뒤 = 흐름[i];
        if (뒤.종가 === 앞.종가) continue;
        값바뀜.push({
          코드: c, 이름: 마지막[c]['이름'], 영문이름: 영문.get(c) ?? null,
          시장: 마지막[c]['시장'], 날: 뒤.날,
          앞종가: 앞.종가, 뒤종가: 뒤.종가,
          앞주식수: 앞.주식수, 뒤주식수: 뒤.주식수,
          앞시총: 앞.시총, 뒤시총: 뒤.시총,
          /* ⛔ 자료가 뭐라고 «적었는지» 그대로 담는다. 우리가 고쳐 적지 않는다 */
          적힌등락률: 뒤.등락률,
        });
      }
    }
  }

  const 시장별 = {}; const 전체시장별 = {};
  for (const c of Object.keys(마지막)) {
    const m = 마지막[c]['시장'] ?? '(모름)';
    전체시장별[m] = (전체시장별[m] ?? 0) + 1;
  }
  for (const r of 죽은) 시장별[r.시장] = (시장별[r.시장] ?? 0) + 1;

  return {
    첫날: 날들[0], 끝날: 날들.at(-1), 거래일수: 날들.length,
    본종목: 본것,
    죽은수: 죽은.length,
    얼어붙은수: 죽은.filter((r) => r.값가짓수 === 1).length,
    시총합: 죽은.reduce((s, r) => s + (Number(r.시총) || 0), 0),
    시장별, 전체시장별,
    큰것: 죽은.slice().sort((a, b) => (b.시총 || 0) - (a.시총 || 0)).slice(0, 10),
    값바뀜: 값바뀜.sort((a, b) => Math.abs((b.뒤시총 || 0) - (b.앞시총 || 0)) - Math.abs((a.뒤시총 || 0) - (a.앞시총 || 0))),
  };
}

/* ── 자가시험 ─────────────────────────────────────────────────────────── */
if (process.argv.includes('--시험')) {
  const 틀렸다 = [];
  const 본다 = (이름, 참) => { if (!참) 틀렸다.push(이름); };

  const 줄 = (코드, 이름, 시장, 종가, 주식수, 거래없음, 등락률 = 0) =>
    ({ 코드, 이름, 시장, 종가, 상장주식수: 주식수, 시가총액: 종가 * 주식수, 거래없음, 등락률 });

  /* 스물한 날을 만든다 — 최소날수 20 을 넘겨야 세어진다 */
  const 날별 = {};
  for (let i = 0; i < 21; i++) {
    const d = `202609${String(i + 1).padStart(2, '0')}`;
    날별[d] = {
      '000001': 줄('000001', '거래되는것', 'KOSPI', 1000, 100, false),
      '000002': 줄('000002', '얼어붙은것', 'KOSDAQ', 500, 200, true),
      /* 열한째 날에 10:1 병합이 일어난 것처럼 꾸민다 — 시총은 그대로 */
      '000003': i < 10 ? 줄('000003', '병합한것', 'KOSPI', 100, 1000, true)
        : 줄('000003', '병합한것', 'KOSPI', 1000, 100, true),
    };
  }
  const r = 세기(날별);

  본다('거래되는 종목은 안 센다', !r.큰것.some((x) => x.코드 === '000001'));
  본다('거래 0 인 종목을 센다', r.죽은수 === 2);
  본다('그중 종가가 안 바뀐 것을 따로 센다', r.얼어붙은수 === 1);
  본다('🔴 거래 0 인데 종가가 바뀐 날을 잡는다', r.값바뀜.length === 1);
  본다('  그 날의 앞뒤 종가를 담는다', r.값바뀜[0].앞종가 === 100 && r.값바뀜[0].뒤종가 === 1000);
  본다('  자료가 적은 등락률을 «그대로» 담는다', r.값바뀜[0].적힌등락률 === 0);
  본다('시총 합을 센다', r.시총합 === 500 * 200 + 1000 * 100);
  본다('시장별로 가른다', r.시장별.KOSDAQ === 1 && r.시장별.KOSPI === 1);

  /* ⛔ 잡을 것이 없는 검사는 거짓 빨강만 낸다 — 정말 서는지 본다 */
  본다('날이 모자란 종목은 안 센다(새로 상장된 것을 죽었다고 하지 않는다)',
    세기({ '20260901': { '000009': 줄('000009', '새것', 'KOSPI', 10, 10, true) } }).죽은수 === 0);
  본다('빈 것에 안 터진다', 세기({}) === null);
  본다('깨진 줄을 건너뛴다', Object.keys(날읽기('{깨짐\n{"코드":"000001"}\n')).length === 1);

  /* 🔴 영문 이름 — 영어권 손님 화면에 한국어를 안 내기 위한 것이다 */
  const 사전 = 영문이름사전([
    { code: '2', name_en: 'TWO CO.,LTD' },           // 앞에 0 이 빠진 코드도 맞춘다
    { code: '000003', name_en: '  ' },               // 빈 것은 «있다»로 치지 않는다
    { code: '000004', name_en: 'FOUR INC' },
  ]);
  본다('코드를 6자리로 맞춰 찾는다', 사전.get('000002') === 'TWO CO.,LTD');
  본다('⛔ 빈 영문 이름을 «있다»로 치지 않는다', !사전.has('000003'));

  const r2 = 세기(날별, 20, 영문이름사전([{ code: '000002', name_en: 'FROZEN CO' }]));
  const 언것 = r2.큰것.find((x) => x.코드 === '000002');
  const 병합 = r2.큰것.find((x) => x.코드 === '000003');
  본다('사전에 있으면 영문 이름을 담는다', 언것?.영문이름 === 'FROZEN CO');
  본다('⛔ 사전에 없으면 «지어내지 않고» null 로 둔다', 병합?.영문이름 === null);
  본다('  값바뀜 줄에도 영문 이름을 담는다', r2.값바뀜[0]?.영문이름 === null);

  console.log(틀렸다.length ? `🔴 자가시험 ${틀렸다.length}칸 틀림\n  - ${틀렸다.join('\n  - ')}`
    : '✅ 자가시험 16칸 다 지나감');
  process.exit(틀렸다.length ? 1 : 0);
}

/* ── 실제로 재기 ──────────────────────────────────────────────────────── */
let 파일들 = [];
try { 파일들 = fs.readdirSync(시세방).filter((f) => /^\d{8}\.ndjson$/.test(f)).sort(); }
catch { 파일들 = []; }

if (파일들.length < 20) {
  /* ⛔ 못 쟀을 때 0 을 쓰지 않는다 — 있던 파일을 덮어 「없다」로 만들지 않는다 */
  console.log(`⚠ ${시세방} 에 거래일이 ${파일들.length}일뿐이다 — **못 쟀다**. 있던 파일을 그대로 둔다.`);
  process.exit(0);
}

const 날별 = {};
for (const f of 파일들) 날별[f.slice(0, 8)] = 날읽기(fs.readFileSync(path.join(시세방, f), 'utf8'));

/* 영문 이름 사전을 끌어온다. ⛔ 못 읽어도 멈추지 않는다 — 그때는 코드만 싣는다 */
let 영문 = new Map();
try {
  const 표 = JSON.parse(fs.readFileSync(path.join(뿌리, 'src', 'data', 'korea-financials-tape.json'), 'utf8'));
  영문 = 영문이름사전(Array.isArray(표) ? 표 : (표.rows ?? []));
} catch { console.log('⚠ 영문 이름 사전을 못 읽었다 — 코드만 싣는다'); }

const 잰것 = 세기(날별, 20, 영문);
fs.writeFileSync(낼곳, JSON.stringify(잰것, null, 2) + '\n', 'utf8');

console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
console.log(`   ${잰것.첫날}~${잰것.끝날} · ${잰것.거래일수}거래일 · 본 종목 ${잰것.본종목.toLocaleString()}개`);
console.log(`   한 주도 거래 안 된 것 ${잰것.죽은수}개`
  + ` (종가까지 얼어붙은 것 ${잰것.얼어붙은수}개) · 시총 합 ${(잰것.시총합 / 1e12).toFixed(2)}조원`);
console.log(`   거래 0 인데 종가가 바뀐 날 ${잰것.값바뀜.length}건`);
