#!/usr/bin/env node
/**
 * check-마감은-ASAP.mjs — **마감에 「9시」를 쓰면 잡는다.**
 * ────────────────────────────────────────────────────────────────────────────
 * [왜 있나 — 사장님 지시 원문]
 *   > 「**뭔가 지시를 하면 왜 마감시간을 저녁9시로 잡나? 마감시간 ASAP 못박아..
 *   >  다시는 9시란 말 쓰지말도록**」 (2026-09-17)
 *
 *   같은 뜻을 2026-09-16 에 이미 두 번 말씀하셨다 —
 *   「이걸 수정하는데 저녁 9시까지 마감을 줄 이유가 있나? 시간을 대폭 당기지」
 *   「마감시간을 왜 항상 길게 잡냐? 그냥 바로바로 해」
 *
 *   ⇒ **세 번 말씀하시게 했다.** 다짐으로는 못 고친 버릇이니 자로 잡는다.
 *
 * [왜 하필 21시를 자꾸 집었나]
 *   21시가 팀 업무 «종료» 시각이라서다. 머리가 자동으로 그 수를 집는다.
 *   ⛔ **업무 종료 시각은 마감이 아니다.** 그날 되는 일을 하루 끝까지 미루는 핑계다.
 *
 * [⛔ 이 자가 «잡지 않는» 것 — 21시가 늘 잘못은 아니다]
 *   · 업무시간을 말하는 줄 (07:00~21:00)
 *   · 정기 업무가 걸린 시각 (21:30 징검다리 점검 · 21:02 저녁 보고 · 21시 방송)
 *   · 지나간 일을 적은 기록 («21:47 에 했다»)
 *   ⇒ **「마감」이라는 말과 같은 줄에 있을 때만** 잡는다. 안 그러면 빨간불이 늘 켜져 있고,
 *     늘 켜진 불은 아무도 안 본다(저장소가 Riot 건에서 겪은 그대로다).
 *
 *   node scripts/check-마감은-ASAP.mjs --자가시험
 *   node scripts/check-마감은-ASAP.mjs
 */

import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 마감을 말하는 줄인가 */
const 마감말 = /마감|언제까지|until|deadline/i;
/** 금지된 시각 — 21시대 */
const 아홉시 = /(저녁\s*9\s*시|밤\s*9\s*시|\b21\s*:\s*00\b|\b21\s*시(?!\s*30)|오후\s*9\s*시)/;

/** 오늘 한국 날짜. ⚠ 이 PC 는 이미 KST 다 — 9시간을 더하지 않는다 */
export function 오늘KST(d = new Date()) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * 한 줄이 「**아직 살아 있는** 마감을 9시로 잡은 줄」인가.
 * **판정만 떼어 낸다** — 안에 박으면 죽어도 모른다(회사 강령 넷째).
 *
 * ⛔ 지나간 기록은 안 잡는다. `세션간-메모.md` 는 «덧붙이기만 하는» 일지라,
 *   옛 줄까지 잡으면 이 자는 **영영 빨간불**이 된다 — 그러면 아무도 안 본다.
 *   고칠 수 있는 것은 «오늘 이후»의 마감뿐이다.
 *
 * @returns {null | string} 잡았으면 걸린 조각, 아니면 null
 */
export function 아홉시마감인가(줄, 오늘 = 오늘KST(), 구역날 = null) {
  const t = String(줄 ?? '');
  if (!마감말.test(t)) return null;              /* 마감 얘기가 아니면 안 본다 */
  if (/ASAP/i.test(t)) return null;              /* 이미 고쳐 적은 줄이다 */
  if (/^\s*>/.test(t)) return null;              /* 인용문 — 사장님 말씀을 옮긴 줄이다 */
  if (/금지|쓰지\s*않는다|쓰지말|다시는/.test(t)) return null;  /* 규칙을 «적은» 줄이다 */
  if (/앞당김|앞당겼|완료|끝냈|늦음|넘겨/.test(t)) return null; /* 지나간 일을 적은 줄 */

  const m = 아홉시.exec(t);
  if (!m) return null;

  /* 날짜가 붙어 있으면 «오늘 이후»만 잡는다. 어제 마감은 이미 지난 일이다 */
  const 날 = /(\d{4})[-./](\d{1,2})[-./](\d{1,2})|(\d{1,2})\s*\/\s*(\d{1,2})/.exec(t);
  if (날) {
    const 해 = 날[1] ? Number(날[1]) : Number(오늘.slice(0, 4));
    const 달 = Number(날[2] ?? 날[4]);
    const 일 = Number(날[3] ?? 날[5]);
    const 그날 = `${해}-${String(달).padStart(2, '0')}-${String(일).padStart(2, '0')}`;
    return 그날 >= 오늘 ? m[0] : null;
  }
  /* 🔴 [2026-09-22] 날짜가 «줄 안»에 없어도, 덧붙이기만 하는 일지에서는 그 줄이 속한
     «구역의 날짜»가 곧 그 줄의 날짜다. 그것을 안 보면 며칠 전에 적힌 「오늘 21시」가
     영영 오늘 것으로 읽혀 이 자가 **영영 빨간불**이 된다 — 그러면 아무도 안 본다.
     ⚠ 위 주석이 이미 그 위험을 적어 두었는데, 막는 것은 «줄 안의 날짜»뿐이었다. */
  if (구역날 && 구역날 < 오늘) return null;
  /* 날짜가 없으면 「오늘 21시」 같은 살아 있는 말이다 — 잡는다 */
  return m[0];
}

/**
 * 일지의 구역 머리글(`## [5번 → 1번] 2026-09-17 12:30 …`)에서 날짜를 뽑는다.
 * 못 읽으면 null — ⛔ 「모르면 오늘」로 두지 않는다. 오늘로 두면 옛 줄을 다시 잡는다.
 */
export function 구역날짜(줄) {
  if (!/^#{1,6}\s/.test(String(줄 ?? ''))) return null;
  const m = /(\d{4})[-./](\d{1,2})[-./](\d{1,2})/.exec(줄);
  if (!m) return null;
  return `${m[1]}-${String(Number(m[2])).padStart(2, '0')}-${String(Number(m[3])).padStart(2, '0')}`;
}

/* ── 자가시험 ───────────────────────────────────────────────────────────── */
if (process.argv.includes('--자가시험')) {
  const 것들 = [];
  const 다 = (이름, 참) => 것들.push({ 이름, 참: !!참 });

  const 오늘 = '2026-09-17';

  /* 🔴 오늘 실제로 내가 적었던 줄들 */
  다('내가 적은 그 줄을 잡는다', 아홉시마감인가('언제까지 2026-09-18 21:00', 오늘) === '21:00');
  다('6번이 적은 줄도 잡는다', 아홉시마감인가('③ 지면 한 장(2026-09-19 21:00 마감)은 아직', 오늘) === '21:00');
  다('「저녁 9시」도 잡는다', !!아홉시마감인가('마감은 저녁 9시까지', 오늘));
  다('「오후 9시」도 잡는다', !!아홉시마감인가('마감 오후 9시', 오늘));
  다('「21시」도 잡는다', !!아홉시마감인가('언제까지 오늘 21시', 오늘));
  다('오늘 마감도 아직 살아 있다', !!아홉시마감인가('마감 2026-09-17 21:00', 오늘));

  /* ⛔ 안 잡아야 하는 것 — 늘 켜진 불은 아무도 안 본다 */
  다('업무시간 줄은 안 잡는다', 아홉시마감인가('업무시간은 07:00~21:00 이다', 오늘) === null);
  다('징검다리 21:30 은 안 잡는다', 아홉시마감인가('마감 전 징검다리 점검 21:30', 오늘) === null);
  다('지나간 기록은 안 잡는다', 아홉시마감인가('21:47 에 배포했다', 오늘) === null);
  다('ASAP 으로 고친 줄은 안 잡는다', 아홉시마감인가('언제까지 ASAP — 21:00 이 아니다', 오늘) === null);
  다('규칙을 적은 줄은 안 잡는다', 아홉시마감인가('마감에 21시를 쓰지 않는다', 오늘) === null);
  다('다른 시각은 안 잡는다', 아홉시마감인가('언제까지 오늘 17시', 오늘) === null);
  다('마감 얘기가 아니면 안 본다', 아홉시마감인가('21시에 저녁 보고를 낸다', 오늘) === null);

  /* ⛔ 영영 빨간불이 되지 않게 — 지나간 일지는 안 잡는다 */
  다('지난 마감은 안 잡는다', 아홉시마감인가('언제까지 2026-09-15 (월) 21시', 오늘) === null);
  다('「앞당김」이라 적힌 완료 기록은 안 잡는다',
    아홉시마감인가('완료 (마감 9/16 21:00보다 앞당김)', 오늘) === null);
  다('사장님 말씀을 옮긴 인용문은 안 잡는다',
    아홉시마감인가('> 「이걸 수정하는데 저녁 9시까지 마감을 줄 이유가 있나」', 오늘) === null);
  다('9/18 처럼 해 없는 날짜도 읽는다', !!아홉시마감인가('마감 9/18 21:00', 오늘));
  다('9/16 은 지났으니 안 잡는다', 아홉시마감인가('마감 9/16 21:00 이다', 오늘) === null);

  /* ⛔ 구역 날짜 — 며칠 전 구역의 「오늘 21시」를 오늘 것으로 읽지 않는다 */
  다('머리글에서 구역 날짜를 읽는다',
    구역날짜('## [5번 → 1번] 2026-09-15 12:30 무엇무엇') === '2026-09-15');
  다('머리글이 아니면 안 읽는다', 구역날짜('본문 2026-09-15 어쩌고') === null);
  다('날짜 없는 머리글은 null', 구역날짜('## 무엇무엇') === null);
  다('한 자리 달·일도 채워 읽는다', 구역날짜('## 2026-9-5 무엇') === '2026-09-05');
  다('🔴 지난 구역의 「오늘 21시」는 안 잡는다',
    아홉시마감인가('언제까지 오늘 21시', 오늘, '2026-09-15') === null);
  다('오늘 구역의 「오늘 21시」는 잡는다',
    !!아홉시마감인가('언제까지 오늘 21시', 오늘, '2026-09-17'));
  다('구역 날짜를 모르면 예전처럼 잡는다',
    !!아홉시마감인가('언제까지 오늘 21시', 오늘, null));

  /* 오늘 날짜는 KST 로 뽑는다 — toISOString() 을 쓰면 새벽에 하루가 어긋난다 */
  다('오늘 날짜가 KST 다', 오늘KST(new Date(2026, 8, 17, 1, 30)) === '2026-09-17');

  const 진 = 것들.filter((x) => !x.참);
  console.log(`마감은 ASAP — 자가시험 ${것들.length - 진.length}/${것들.length}`);
  for (const x of 진) console.log('   🔴 ' + x.이름);
  process.exit(진.length ? 1 : 0);
}

/* ── 실제로 훑는다 ──────────────────────────────────────────────────────── */

/* ⚠ [2026-09-17] 이 아래를 «맨 바깥»에 두었더니, 판정 함수를 import 하는 것만으로
 *   검사가 통째로 돌고 process.exit 까지 불렸다. 그래서 그 함수를 남이 못 쓴다.
 *   ⇒ 「내가 직접 돌았나」로 감싼다. **판정 함수는 언제나 side effect 없이 빌릴 수 있어야 한다.** */
const 내가직접돌았나 = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (!내가직접돌았나) { /* import 된 것이다 — 아무것도 하지 않는다 */ } else {

const 볼것 = [
  'docs/세션간-메모.md',
  'docs/6번-할일.md',
  'docs/3번-할일-전체.md',
  'docs/인계-현재상태.md',
];

const 걸린것 = [];
for (const 상대 of 볼것) {
  const p = path.join(뿌리, 상대);
  if (!existsSync(p)) continue;
  const 줄들 = readFileSync(p, 'utf8').split(/\r?\n/);
  let 구역날 = null;                       /* 머리글을 지날 때마다 갱신한다 */
  줄들.forEach((줄, i) => {
    const 새날 = 구역날짜(줄);
    if (새날) 구역날 = 새날;
    const 걸림 = 아홉시마감인가(줄, undefined, 구역날);
    if (걸림) 걸린것.push({ 파일: 상대, 줄번호: i + 1, 걸림, 글: 줄.trim().slice(0, 96) });
  });
}

console.log('■ 마감에 「9시」를 쓴 곳  (사장님: 「마감시간 ASAP 못박아..다시는 9시란 말 쓰지말도록」)');
if (!걸린것.length) {
  console.log('   ✅ 없다 — 살아 있는 마감은 다 ASAP 이거나 다른 시각이다');
  process.exit(0);
}
for (const x of 걸린것) console.log(`   🔴 ${x.파일}:${x.줄번호}  「${x.걸림}」  ${x.글}`);
console.log('');
console.log('   ✅ 고치는 길 — 그 자리를 **ASAP** 으로 바꾼다. 꼭 시각을 못박아야 하면');
console.log('      «왜 지금 당장이 아닌지»를 한 줄로 함께 적는다. 못 대면 그 마감은 게으른 것이다.');
process.exit(1);

}
