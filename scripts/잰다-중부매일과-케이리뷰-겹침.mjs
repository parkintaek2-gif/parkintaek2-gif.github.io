import fs from 'node:fs';

/** 머리말·꼬리표·꾸밈글자를 걷고 공백을 없앤다 — 글자 토막을 세기 위한 꼴 */
export function 씻는다(글) {
  return String(글 ?? '')
    .replace(/^---[\s\S]*?\n---\n/, '')   /* 리뷰 머리말(frontmatter) */
    .replace(/\[[^\]]*\]/g, ' ')          /* [제목]·[본문] 같은 꼬리표 */
    .replace(/[#*>`]/g, ' ')
    .replace(/\s+/g, '');
}

/** 새 글의 다섯 글자 토막 중 옛 글에도 그대로 있는 것의 비율(0~1) */
export function 다섯묶음겹침(새글, 옛글) {
  const a = 씻는다(새글);
  const b = 씻는다(옛글);
  if (a.length < 5) return 0;
  const 옛것 = new Set();
  for (let i = 0; i + 5 <= b.length; i += 1) 옛것.add(b.slice(i, i + 5));
  let 맞은것 = 0;
  let 전부 = 0;
  for (let i = 0; i + 5 <= a.length; i += 1) {
    전부 += 1;
    if (옛것.has(a.slice(i, i + 5))) 맞은것 += 1;
  }
  return 전부 ? 맞은것 / 전부 : 0;
}

/** 참고용 — 같은 낱말을 얼마나 쓰나 */
export function 낱말겹침(새글, 옛글) {
  const 뽑기 = (s) => new Set(String(s ?? '').replace(/^---[\s\S]*?\n---\n/, '')
    .split(/[^가-힣A-Za-z0-9]+/).filter((w) => w.length > 1));
  const a = 뽑기(새글);
  const b = 뽑기(옛글);
  let 같은것 = 0;
  for (const w of a) if (b.has(w)) 같은것 += 1;
  const 합 = new Set([...a, ...b]).size;
  return 합 ? 같은것 / 합 : 0;
}

/** 어디가 겹치나 — 길이 순으로 토막을 짚어 준다. 고칠 자리를 사람이 보게 한다 */
export function 겹치는토막(새글, 옛글, 최소 = 12) {
  const a = 씻는다(새글);
  const b = 씻는다(옛글);
  const 것 = [];
  let i = 0;
  while (i + 5 <= a.length) {
    if (b.includes(a.slice(i, i + 5))) {
      let j = i + 5;
      while (j <= a.length && b.includes(a.slice(i, j))) j += 1;
      것.push(a.slice(i, j - 1));
      i = j - 1;
    } else i += 1;
  }
  return 것.filter((t) => t.length >= 최소).sort((x, y) => y.length - x.length);
}

/** 사장님이 정하신 자를 넘었나 */
export const 한도 = 0.5;
export function 넘었나(겹침, 옛제목, 새제목) {
  const 제목바꿨나 = String(옛제목 ?? '').trim() !== String(새제목 ?? '').trim()
    && String(새제목 ?? '').trim().length > 0;
  return { 됐나: 겹침 < 한도 && 제목바꿨나, 겹침됐나: 겹침 < 한도, 제목바꿨나 };
}

