  본다('아주 다르면 0 에 가깝다', 다섯묶음겹침('가나다라마바사아자차', '하카타파차자이아사바') < 0.2);
  본다('새 글이 다섯 글자보다 짧으면 0', 다섯묶음겹침('가나', '가나다라마바사') === 0);
