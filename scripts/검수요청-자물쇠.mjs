#!/usr/bin/env node
/**
 * 검수요청-자물쇠.mjs — **검색 일을 끝냈으면 1번·2번에게 검수를 걸었나.**
 *
 * 🔴🔴 사장님 지시 (2026-10-06):
 *   「**검색관련 업무를 마무리 할 때마다 1번과 2번에게 검수를 하라고 해서
 *     오류를 줄이거나 없애라**」
 *
 * ⛔ 말로 둔 규칙은 잊힌다. 오늘만 해도 내가 검색 일을 아홉 가지 했는데
 *   사장님이 이르시기 전까지 한 번도 검수를 걸지 않았다.
 * ⇒ 이 자가 «커밋 기록»을 보고 묻는다 — 검색 일을 밀었는데 검수 요청이 없으면 빨간불.
 *
 * ── 어떻게 재나 ──────────────────────────────────────────────────────
 * ```
 * ① 마지막 「검수 요청」 글이 세션간 메모에 언제 올라갔나
 * ② 그 뒤로 «검색 관련» 커밋이 몇 개 들어갔나
 * ③ 검색 커밋이 있는데 그 뒤 검수 요청이 없으면 🔴
 * ```
 * ⛔ 「검색 관련인가」를 내가 눈으로 가르지 않는다 — 커밋 글의 낱말로 가른다.
 *   낱말 표는 아래에 있고, 자가시험이 그 표를 지킨다.
 * ⚠ 이 자는 «요청을 걸었나»만 잰다. **「검수가 돌아왔나」는 못 잰다** —
 *   그것은 1번·2번이 답글을 올려야 알 수 있다. 못 재는 것은 못 잰다고 적는다.
 *
 * 쓰는 법
 *   node scripts/검수요청-자물쇠.mjs --자가시험
 *   node scripts/검수요청-자물쇠.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
export const 뿌리 = path.resolve(여기, '..');
export const 메모길 = path.join(뿌리, 'docs', '세션간-메모.md');

/**
 * 「검색 관련 일」로 보는 낱말.
 * ⛔ 넓게 잡는다 — 덜 잡으면 자물쇠가 잠들고, 더 잡으면 한 번 더 검수를 걸 뿐이다.
 *   둘 가운데 «더 잡는 쪽»이 싸다.
 */
export const 검색낱말 = [
  '검색', '색인', 'hreflang', '사이트맵', 'sitemap', '구글', 'GSC', '서치콘솔',
  '노출', '클릭', '순위', '크롤', '로봇', 'robots', 'canonical', 'llms.txt',
  '겹침', '중복', '다국어', '유입', 'IndexNow', '인덱스', '키워드', '검색어',
];

/** 검수 요청 글을 찾는 표시 — 세션간 메모의 제목 꼴 */
export const 요청표시 = /^## \[5번 → .*\].*검수 요청/m;

/** 커밋 한 줄이 검색 일인가. ⛔ 눈으로 가르지 않는다 — 낱말로 가른다 */
export function 검색일인가(커밋글, 낱말 = 검색낱말) {
  const s = String(커밋글 ?? '');
  return 낱말.some((w) => s.includes(w));
}

/**
 * 마지막 검수 요청이 올라간 뒤의 검색 커밋들.
 * @param 커밋들 [{해시, 때, 글}] — 새것이 앞
 * @param 요청때 Date 또는 null (한 번도 안 걸었으면 null)
 */
/**
 * 🔴 [2026-10-06 07:5x · 5번] **자물쇠가 첫 판에 거짓으로 울었다.**
 *   「검수 요청」 커밋 «자신»을 「검수에 안 올린 검색 커밋」으로 잡았다 —
 *   그 커밋 글에 「검색」이 들었고, 커밋 시각(07:57)이 메모 머리 시각(07:50)보다 뒤이기 때문이다.
 * ⛔ 거짓으로 우는 자물쇠는 결국 꺼진다. 오늘만 세 번째로 겪는 자리다.
 */
export const 요청커밋표시 = '검수 요청';

export function 검수안건것(커밋들, 요청때) {
  return (커밋들 || []).filter((c) => {
    /* ⛔ 검수를 «거는» 커밋은 밀린 일이 아니다 — 그것이 곧 거는 행위다 */
    if (String(c.글 ?? '').includes(요청커밋표시)) return false;
    if (!검색일인가(c.글)) return false;
    if (!요청때) return true;                 /* 한 번도 안 걸었으면 전부 밀린 것이다 */
    return c.때 > 요청때;
  });
}

/** 세션간 메모에서 마지막 검수 요청 시각. ⛔ 못 읽으면 null — 「없다」가 아니다 */
export function 마지막요청때(글) {
  if (글 == null) return null;
  const 것 = [...String(글).matchAll(/^## \[5번 → [^\]]*\]\s*(\d{4}-\d{2}-\d{2})\s+(\d{2}:\d{2}).*검수 요청/gm)];
  if (!것.length) return { 없다: true };
  const m = 것[것.length - 1];
  return { 때: new Date(`${m[1]}T${m[2]}:00+09:00`) };   /* ⛔ 이 PC 는 KST 다 */
}

function 커밋읽기(몇 = 60) {
  try {
    const 글 = execFileSync('git', ['log', `-${몇}`, '--format=%h\u0001%cI\u0001%s'],
      { cwd: 뿌리, encoding: 'utf8' });
    return 글.split(/\r?\n/).filter(Boolean).map((줄) => {
      const [해시, 때, ...나머지] = 줄.split('\u0001');
      return { 해시, 때: new Date(때), 글: 나머지.join('\u0001') };
    });
  } catch { return null; }                 /* ⚠ git 을 못 읽으면 null — 0건이 아니다 */
}

function 자가시험() {
  let 통 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통++; console.log('✅', 이름); } else { 탈++; console.log('🔴', 이름); } };

  검('검색 낱말이 스물 넘는다 — 넓게 잡는다', 검색낱말.length >= 20);
  검('검색 커밋을 집는다', 검색일인가('색인 사슬을 고쳤다'));
  검('영문 낱말도 집는다', 검색일인가('fix hreflang on home'));
  검('⛔ 검색과 무관한 커밋은 안 집는다', !검색일인가('결제 점검 — 둘 다 팔린다'));
  검('⛔ 빈 것·null 에도 안 터진다', !검색일인가('') && !검색일인가(null));

  const 때 = (s) => new Date(s);
  const 커밋들 = [
    { 해시: 'a', 때: 때('2026-10-06T09:00:00+09:00'), 글: '색인을 고쳤다' },
    { 해시: 'b', 때: 때('2026-10-06T08:00:00+09:00'), 글: '결제 점검' },
    { 해시: 'c', 때: 때('2026-10-06T06:00:00+09:00'), 글: '겹침을 줄였다' },
  ];
  const 밀린것 = 검수안건것(커밋들, 때('2026-10-06T07:00:00+09:00'));
  검('🔴 요청 뒤의 검색 커밋만 밀린 것으로 센다', 밀린것.length === 1 && 밀린것[0].해시 === 'a');
  검('⛔ 결제 커밋은 안 센다', !밀린것.some((c) => c.해시 === 'b'));
  검('⛔ 요청 «전»의 검색 커밋은 안 센다 — 이미 검수에 올렸다',
    !밀린것.some((c) => c.해시 === 'c'));
  검('🔴 한 번도 안 걸었으면 검색 커밋이 전부 밀린 것이다',
    검수안건것(커밋들, null).length === 2);

  /* 🔴 [2026-10-06] 첫 판에 자물쇠가 거짓으로 울었다 — 검수를 거는 커밋 자신을 잡았다 */
  검('⛔ 검수를 «거는» 커밋은 밀린 일로 세지 않는다', 검수안건것([
    { 해시: 'z', 때: 때('2026-10-06T07:57:00+09:00'), 글: '[5번 → 1번·2번] 검수 요청 — 오늘 한 검색 업무 전부' },
  ], 때('2026-10-06T07:50:00+09:00')).length === 0);
  검('⛔ 커밋이 없어도 안 터진다', 검수안건것([], null).length === 0 && 검수안건것(null, null).length === 0);

  const 메모 = '## [5번 → 1번·2번] 2026-10-06 07:50 🔴 **검수 요청 — 오늘 제가 한 검색 업무 전부입니다**';
  검('메모에서 마지막 요청 시각을 읽는다',
    마지막요청때(메모).때.getTime() === 때('2026-10-06T07:50:00+09:00').getTime());
  검('⛔ 요청 글이 없으면 「없다」로 돌려준다', 마지막요청때('아무 글').없다 === true);
  검('⛔ 메모를 못 읽으면 null — 「없다」가 아니다', 마지막요청때(null) === null);
  검('⛔ 둘 있으면 «나중» 것을 집는다',
    마지막요청때('## [5번 → 1번] 2026-10-05 10:00 검수 요청\n## [5번 → 2번] 2026-10-06 07:50 검수 요청')
      .때.getTime() === 때('2026-10-06T07:50:00+09:00').getTime());

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${통} 통과`);
  process.exit(탈 ? 1 : 0);
}

function 주다() {
  if (process.argv.includes('--자가시험')) return 자가시험();

  console.log('■ 검색 일을 끝냈으면 1번·2번에게 검수를 걸었나');
  console.log('   🔴 사장님 (2026-10-06): 「검색관련 업무를 마무리 할 때마다 1번과 2번에게');
  console.log('      검수를 하라고 해서 오류를 줄이거나 없애라」\n');

  let 메모 = null;
  try { 메모 = fs.readFileSync(메모길, 'utf8'); } catch { 메모 = null; }
  const 요청 = 마지막요청때(메모);
  if (요청 === null) {
    console.log('⚠ 못 쟀다 — 세션간 메모를 못 읽었다. 「걸었다」로도 「안 걸었다」로도 읽지 않는다');
    process.exit(0);
  }

  const 커밋들 = 커밋읽기();
  if (커밋들 === null) {
    console.log('⚠ 못 쟀다 — git 기록을 못 읽었다');
    process.exit(0);
  }

  if (요청.없다) console.log('🔴 검수 요청 글이 «하나도» 없다');
  else console.log(`   마지막 검수 요청 — ${요청.때.toLocaleString('ko-KR')}`);

  const 밀린것 = 검수안건것(커밋들, 요청.없다 ? null : 요청.때);
  if (!밀린것.length) {
    console.log('\n✅ 검수에 안 올린 검색 커밋이 없다');
    console.log('⚠ 다만 이 자는 «요청을 걸었나»만 잰다 — 「검수가 돌아왔나」는 못 잰다.');
    console.log('   1번·2번의 답글은 세션간 메모에서 눈으로 본다.');
    process.exit(0);
  }

  console.log(`\n🔴 검수에 안 올린 검색 커밋 ${밀린것.length}개`);
  for (const c of 밀린것.slice(0, 12)) {
    console.log(`   ${c.해시}  ${c.때.toLocaleString('ko-KR')}  ${c.글.slice(0, 70)}`);
  }
  console.log('\n⇒ 세션간 메모에 「## [5번 → 1번·2번] YYYY-MM-DD HH:MM … 검수 요청」 글을 올린다.');
  console.log('⛔ 「잘했다」를 받으려는 것이 아니다 — «틀린 곳을 짚어 달라»고 적는다.');
  process.exit(1);
}

/* ⛔ 「걸림돌 없는 꼭대기 부름」을 만들지 않는다 */
const 내가실행됐다 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가실행됐다) 주다();
