/** 그 기사가 e스포츠인가 */
export function e스포츠인가(글) {
  const s = String(글 == null ? '' : 글);
  if (!s) return false;
  return e스포츠말.some((w) => s.includes(w));
}

/** 자국 파일 이름에서 날짜를 뽑는다 */
export function 날뽑기(이름) {
  const m = String(이름 ?? '').match(/^(\d{4}-\d{2}-\d{2})_\d{1,2}시\.txt$/);
  return m ? m[1] : null;
}

/**
 * 자국 글에서 «보낸» 덩이만 골라 제목+소재를 잇는다.
 * ⛔ [안보냄] 덩이는 세지 않는다 — 사장님이 못 받으신 것은 나간 것이 아니다.
 */
export function 보낸글만(글) {
  const 엔 = String.fromCharCode(10);
  return String(글 ?? '').split(엔 +엔)
    .filter((d) => d.split(엔).some((l) => l.startsWith('[스포츠]')))
    .join(' ');
}

/**
 * 판정. ⛔ 「못 쟀다」를 「나갔다」로도 「안 나갔다」로도 적지 않는다.
 * @param {string[]} 빈날들 e스포츠가 0건으로 보이는 날(최근 것부터)
 */
export function 판정({ 센날, 빈날들, 이어진빈날, 가장긴빈날 = 0, 가장긴자리 = null }) {
  if (!센날) return { 빛: '⬜', 말: '못 쟀다 — 셀 날이 없다' };
  if (이어진빈날 >= 2) {
    return {
      빛: '🔴',
      말: `e스포츠가 **${이어진빈날}일 이어서** 0건으로 보인다`
        + ` — 사장님 선(이틀에 한 건)을 넘었다 (${빈날들.slice(0, 3).join(' · ')})`,
    };
  }
  if (이어진빈날 === 1) {
    return { 빛: '⚠', 말: '어제 0건이다 — **오늘은 반드시 쓴다.** 이틀 연속은 안 된다' };
  }
  /* 🔴🔴 [2026-10-13 16:5x · 5번] **이 자가 거짓 초록을 냈다.**
     ────────────────────────────────────────────────────────────────────
     10-04·10-05·10-06 이 **사흘 내리** 0건인데 화면은
     「✅ 이틀 연속 0건인 날이 없다」라고 말했다.
     ⛔ 「이어진빈날」은 «오늘부터 거슬러» 센 것이라, 오늘 한 건 나가면 0 이 된다.
       그 수만 보고 ✅ 를 찍으니 **지난 사흘 구멍이 통째로 안 보였다.**
     ⭐⭐ 자가 보여 주는 것과 재는 것이 다르면 그 자는 사람을 속인다 — 스물한 번째다.
     ⇒ 「오늘부터 이어진 것」과 「본 기간 안에서 가장 길었던 것」을 **갈라서 말한다.**
     ⚠ 지난 일은 🔴 가 아니다 — 지금 고칠 수 있는 것이 아니다. 그러나 ✅ 로 덮지도 않는다. */
  if (가장긴빈날 >= 2) {
    return {
      빛: '⚠',
      말: '오늘 기준으로 이어진 0건은 없다 —'
        + ` 다만 본 기간 안에 **${가장긴빈날}일 내리 0건**인 자리가 있다`
        + (가장긴자리 ? ` (${가장긴자리})` : '')
        + '. 지난 일이라 지금 고칠 수는 없지만 ✅ 로 덮지 않는다',
    };
  }
  return { 빛: '✅', 말: '오늘 기준으로도, 본 기간 안에서도 이틀 연속 0건인 자리가 없다' };
}

/**
 * 본 기간 안에서 **가장 길게 이어진 0건**을 센다.
 * ⛔ 「오늘부터 이어진 것」과 다른 물음이다. 둘을 같게 보면 위의 거짓 초록이 난다.
 * @param {{날:string, e:boolean}[]} 줄들  최근 것부터
 */
export function 가장긴빈구간(줄들) {
  if (!Array.isArray(줄들) || !줄들.length) return { 길이: 0, 자리: null };
  let 길이 = 0; let 이번 = 0; let 이번첫 = null; let 자리 = null;
  /* 옛날 → 오늘 차례로 본다. 「2026-10-04 ~ 2026-10-06」처럼 읽히게 하려고 */
  for (const r of [...줄들].reverse()) {
    if (r.e) { 이번 = 0; 이번첫 = null; continue; }
    이번 += 1;
    if (!이번첫) 이번첫 = r.날;
    if (이번 > 길이) { 길이 = 이번; 자리 = 이번첫 === r.날 ? r.날 : `${이번첫} ~ ${r.날}`; }
  }
  return { 길이, 자리 };
}

