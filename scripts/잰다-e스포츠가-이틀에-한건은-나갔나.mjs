/* ── 본체 ──────────────────────────────────────────────────────────── */
function 잰다(날수) {
  if (!fs.existsSync(자국방)) { console.log('⬜ 자국방이 없다 — 못 쟀다'); return 0; }
  const 모음 = new Map();
  for (const f of fs.readdirSync(자국방)) {
    const 날 = 날뽑기(f);
    if (!날) continue;
    let 글 = '';
    try { 글 = fs.readFileSync(path.join(자국방, f), 'utf8'); } catch { continue; }
    const 보낸 = 보낸글만(글);
    if (!보낸.trim()) continue;                 /* 그날 그 회차는 안 나갔다 */
    const 앞 = 모음.get(날) ?? { e: false, 회차: 0 };
    앞.회차 += 1;
    if (e스포츠인가(보낸)) 앞.e = true;
    모음.set(날, 앞);
  }
  const 날들 = [...모음.keys()].sort().reverse().slice(0, 날수);
  console.log('■ e스포츠가 이틀에 한 건은 나갔나 — 최근 ' + 날들.length + '일 (사장님 2026-10-13)');
  console.log('');
  const 빈날들 = [];
  const 줄들 = [];
  let 이어진빈날 = 0;
  let 끊겼나 = false;
  for (const 날 of 날들) {
    const v = 모음.get(날);
    const 요일 = ['일', '월', '화', '수', '목', '금', '토'][new Date(날 + 'T00:00:00').getDay()];
    console.log('   ' + (v.e ? '✅' : '🔴') + ' ' + 날 + ' (' + 요일 + ')  '
      + (v.e ? 'e스포츠 나갔다' : 'e스포츠 0건으로 보인다') + '  · 그날 나간 기사 ' + v.회차 + '편');
    줄들.push({ 날, e: v.e });
    if (!v.e) { 빈날들.push(날); if (!끊겼나) 이어진빈날 += 1; } else 끊겼나 = true;
  }
  const 긴것 = 가장긴빈구간(줄들);
  const r = 판정({
    센날: 날들.length, 빈날들, 이어진빈날,
    가장긴빈날: 긴것.길이, 가장긴자리: 긴것.자리,
  });
  console.log('');
  console.log('   ' + r.빛 + ' ' + r.말);
  console.log('');
  console.log('   ⛔ 「0건이다」가 아니라 «0건으로 보인다»다 — 종목 이름이 안 든 기사는 못 잡는다.');
  console.log('   ⛔ [안보냄] 은 안 센다 — 사장님이 못 받으신 것은 나간 것이 아니다.');
  return r.빛 === '🔴' ? 1 : 0;
}

