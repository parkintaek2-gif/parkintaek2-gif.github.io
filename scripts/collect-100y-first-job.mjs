import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '101';
export const 표들 = { 소요: 'DT_1DE9058S', 근속: 'DT_1DE9059S' };
export const 기간꼴 = 'M';
export const 나이칸 = '15~29세';
export const 전체칸 = '졸업ㆍ중퇴 후 취업 유경험자 전체';
export const 임금칸 = '임금 근로자';
export const 걸린칸 = ['3개월 미만', '3~6개월 미만', '6개월~1년 미만', '1~2년 미만', '2~3년 미만', '3년 이상'];

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
export const 한자리 = (v) => (v == null ? null : Math.round(v * 10) / 10);
export function 몫(부분, 분모) {
  if (부분 == null || !분모) return null;
  return Math.round((부분 / 분모) * 1000) / 10;
}
/** 개월을 사람 말로 — 「18.8개월」은 「1년 6.8개월」이 더 잘 읽힌다 */
export function 달말(개월) {
  if (개월 == null) return null;
  const 해 = Math.floor(개월 / 12);
  const 달 = Math.round((개월 - 해 * 12) * 10) / 10;
  return 해 ? `${해}년 ${달}개월` : `${달}개월`;
}

