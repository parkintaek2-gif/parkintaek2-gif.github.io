#!/usr/bin/env node
/**
 * check-memo-marker.mjs — 세션간 메모의 «보낸 표시»가 관례 꼴인가.
 * ─────────────────────────────────────────────────────────────────────────────
 * [왜 있나 — 2026-09-04 02:1x]
 *   6번이 02:12 에 「새 [5번→6번]·[5번→전체] 없음(21:2x 이후 5시간 가까이 조용)」이라 적었다.
 *   그런데 나(5번)는 그 사이 «세 통»을 보냈다. 안 보인 까닭은 표시 꼴이었다 —
 *
 *     관례 꼴    [5번→6번]          이 파일에 90회
 *                [5번 → 6번]         19회
 *     내가 쓴 것  [5번(총괄) → 6번]    2회 — 둘 다 그날 내 것
 *
 *   ⛔ 괄호에 「(총괄)」을 넣어서 상대가 찾는 «글자열»에 안 걸렸다.
 *      그 사이 6번은 자기 막힘의 답을 못 보고 몇 시간을 대기했다.
 *
 *   ⭐ 우리 강령: 「규칙은 문장이 아니라 «검사»로 둔다. 말로 하는 규칙은 잊힌다」.
 *      그래서 「표시를 관례대로 쓴다」를 문장으로 두지 않고 이 자로 둔다.
 *
 * [무엇을 재나]
 *   메모 머리줄(`## [보낸이 → 받는이] …`)에서 «보낸이·받는이 칸에 이름 말고 다른 것이
 *   붙었나»를 본다. 관례는 `N번` 과 `전체` 뿐이다.
 *
 * [무엇을 못 재나]
 *   ⬜ 상대가 «정말 읽었나»는 못 잰다. 표시가 관례 꼴인지까지만 본다.
 *   ⬜ 머리줄 없이 본문에 적은 것은 이 자가 못 본다 — 그것도 안 보이는 원인이지만
 *      꼴이 정해져 있지 않아 잴 수 없다. 「못 잰다」로 남긴다.
 *
 *   node scripts/check-memo-marker.mjs
 *   node scripts/check-memo-marker.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';

const 뿌리 = path.resolve(
  path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'), '..');

/**
 * 관례로 쓰는 «보낸이» — 오직 `N번` 뿐이다. 꼬리를 붙이면 상대 검색에 안 걸린다.
 *
 * 🔴 왜 보낸이만 좁게 보나 — 처음에 받는이까지 이 꼴을 요구했더니 «1,094개»가 걸렸다.
 *   그런데 그 대부분은 `[5번 → 1번·4번·6번]` · `[5번 → 전 유닛]` 처럼 실제로 오래 쓰인
 *   관례였다. 그것들은 앞머리 `[5번 →` 가 살아 있어서 «찾는 데 지장이 없다».
 *   ⛔ 그렇게 헛울리면 사람이 검사를 끈다 — 우리가 여러 번 적어 둔 병이다.
 *   ⭐ 내가 «실제로 재서 확인한» 해악은 하나였다: 보낸이 이름에 꼬리(「(총괄)」)를 붙인 것.
 *     그러면 `[5번` 으로도 `[5번 →` 로도 안 걸린다. 그것만 잡는다.
 */
export const 관례보낸이 = /^[0-9]+번$/;

/**
 * 받는이는 «여럿»일 수 있다. `·` `,` 로 나눈 각 조각에 «번호나 전체말이 들어 있으면» 통과.
 * ⚠ 「1번, 참고 5번」처럼 말이 섞인 것도 오래 쓰인 꼴이라 통과시킨다 — 번호가 살아 있다.
 */
export function 받는이관례인가(s) {
  const t = String(s ?? '').trim();
  if (!t) return false;
  if (/^전\s*유닛$|^전체$/.test(t)) return true;
  return t.split(/[·,]/).every((조각) => /[0-9]+번|전\s*유닛|전체/.test(조각));
}

/**
 * 머리줄 하나에서 보낸이·받는이를 뽑는다. 표시가 아니면 null.
 * ⚠ 「→」 대신 「->」 를 쓴 것도 잡는다 — 그것도 상대 검색에 안 걸린다.
 */
export function 표시읽기(줄) {
  const m = String(줄 ?? '').match(/^#{1,6}\s*(?:[^[]*)?\[([^\]]*?)(?:→|->)([^\]]*?)\]/);
  if (!m) return null;
  return { 보낸이: m[1].trim(), 받는이: m[2].trim(), 화살표: /->/.test(줄) ? '->' : '→' };
}

/**
 * 관례에서 벗어난 표시를 찾는다.
 * @returns {{줄번호:number, 줄:string, 왜:string}[]}
 */
export function 어긴것찾기(글) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  const 벗어난것 = [];
  for (let i = 0; i < 줄들.length; i += 1) {
    const t = 표시읽기(줄들[i]);
    if (!t) continue;
    const 왜 = [];
    if (!관례보낸이.test(t.보낸이)) {
      왜.push('보낸이 「' + t.보낸이 + '」에 꼬리가 붙었다 — `[' + t.보낸이.replace(/[^0-9번]/g, '') + ' →` 로 안 걸린다');
    }
    if (!받는이관례인가(t.받는이)) 왜.push('받는이 「' + t.받는이 + '」에 번호가 없다');
    if (t.화살표 === '->') 왜.push('화살표가 -> 다 (관례는 →)');
    if (왜.length) 벗어난것.push({ 줄번호: i + 1, 줄: 줄들[i].slice(0, 100), 왜: 왜.join(' · ') });
  }
  return 벗어난것;
}

/* ─── 자가시험 ────────────────────────────────────────────────────────────── */

function 자가시험() {
  let 통과 = 0, 실패 = 0;
  const 봄 = (무엇, 실제, 기대) => {
    const ok = JSON.stringify(실제) === JSON.stringify(기대);
    if (ok) 통과 += 1; else { 실패 += 1; console.log('  🔴 ' + 무엇 + '  실제=' + JSON.stringify(실제) + '  기대=' + JSON.stringify(기대)); }
  };
  const 맞다 = (무엇, x) => 봄(무엇, !!x, true);

  봄('관례 꼴을 읽는다', 표시읽기('## [5번 → 6번] 어쩌고'), { 보낸이: '5번', 받는이: '6번', 화살표: '→' });
  봄('공백 없는 것도 읽는다', 표시읽기('## [5번→6번] 어쩌고'), { 보낸이: '5번', 받는이: '6번', 화살표: '→' });
  봄('전체도 관례다', 표시읽기('## [5번→전체] ㄱ'), { 보낸이: '5번', 받는이: '전체', 화살표: '→' });
  봄('표시가 아니면 null', 표시읽기('## [진행] 5번 01:0x'), null);
  봄('빈 줄은 null', 표시읽기(''), null);
  봄('머리줄이 아니면 null', 표시읽기('[5번 → 6번] 본문 안'), null);

  /* 🔴 이 자가 생긴 그 사고 — 이름 뒤에 (총괄)을 붙인 것 */
  const r1 = 어긴것찾기('## [5번(총괄) → 6번] 물음에 답한다');
  봄('(총괄)이 붙은 보낸이를 잡는다', r1.length, 1);
  맞다('까닭에 보낸이를 적어 준다', /보낸이/.test(r1[0].왜));

  봄('관례 꼴은 안 잡는다', 어긴것찾기('## [5번 → 6번] ㄱ').length, 0);
  봄('전체도 안 잡는다', 어긴것찾기('## [5번→전체] ㄱ').length, 0);
  봄('[진행] 줄은 안 잡는다', 어긴것찾기('## [진행] 5번(총괄) 01:0x').length, 0);

  /* -> 도 잡는다 — 그것도 상대 검색에 안 걸린다 */
  const r2 = 어긴것찾기('## [5번 -> 6번] ㄱ');
  봄('-> 화살표를 잡는다', r2.length, 1);
  맞다('까닭에 화살표를 적어 준다', /화살표/.test(r2[0].왜));

  /* 🔴 헛울지 않아야 하는 것들 — 처음 판이 이것들 «1,094개»를 잡아서 좁혔다.
     이 셋은 앞머리 `[N번 →` 가 살아 있어 찾는 데 지장이 없다. 울면 사람이 검사를 끈다. */
  봄('여러 받는이는 관례다', 어긴것찾기('## [5번 → 1번·4번·6번] ㄱ').length, 0);
  봄('전 유닛도 관례다', 어긴것찾기('## [5번 → 전 유닛] ㄱ').length, 0);
  봄('「1번, 참고 5번」도 관례다', 어긴것찾기('## [4번 → 1번, 참고 5번] ㄱ').length, 0);
  맞다('받는이 관례 판정 — 전 유닛', 받는이관례인가('전 유닛'));
  맞다('받는이 관례 판정 — 여럿', 받는이관례인가('1번·4번·6번'));
  봄('받는이에 번호가 아예 없으면 잡는다', 어긴것찾기('## [5번 → 편집국] ㄱ').length, 1);
  /* 받는이에 꼬리가 붙어도 «번호가 살아 있으면» 통과 — 찾는 데 지장이 없다 */
  봄('받는이 꼬리는 통과', 어긴것찾기('## [5번 → 6번(서울마켓츠)] ㄱ').length, 0);

  /* 줄 번호 */
  const r3 = 어긴것찾기(['ㄱ', '## [5번(총괄) → 6번] ㄴ'].join('\n'));
  봄('줄 번호를 준다', r3[0].줄번호, 2);

  /* 여러 개 */
  봄('여러 개를 다 찾는다',
    어긴것찾기(['## [5번(총괄) → 6번] ㄱ', '## [5번 → 6번] ㄴ', '## [6번(금융) → 5번] ㄷ'].join('\n')).length, 2);

  /* ⭐ 이 자가 «울 수 있나»를 시험한다. 못 울리는 자는 없는 자보다 나쁘다 */
  맞다('울 수 있다(어긴 것을 주면 1개 이상 낸다)', 어긴것찾기('## [5번(총괄) → 6번] ㄱ').length > 0);
  맞다('헛울지 않는다(관례만 주면 0개)',
    어긴것찾기(['## [5번 → 6번] ㄱ', '## [2번→3번] ㄴ', '## [진행] 4번 02:0x'].join('\n')).length === 0);

  console.log('\n자가시험 ' + (통과 + 실패) + '개 중 ' + 통과 + '개 통과' + (실패 ? ' · 🔴 ' + 실패 + '개 실패' : ''));
  return 실패 === 0;
}

/* ─── 직접 돌릴 때 ────────────────────────────────────────────────────────── */

if (process.argv[1] && process.argv[1].endsWith('check-memo-marker.mjs')) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);

  const 볼것 = [
    path.join(뿌리, 'docs/세션간-메모.md'),
    path.join(뿌리, '..', 'klifemap/docs/1번-4번-메모.md'),
  ].filter((p) => fs.existsSync(p));

  let 모두 = 0;
  for (const p of 볼것) {
    const 글 = fs.readFileSync(p, 'utf8');
    const 어긴것 = 어긴것찾기(글);
    /* 표시가 몇 개인지 함께 센다 — 「0개」가 「다 맞다」인지 「표시가 없다」인지 갈라야 한다 */
    const 표시수 = 글.split(/\r?\n/).filter((l) => 표시읽기(l)).length;
    console.log(path.basename(p) + ' — 표시 ' + 표시수 + '개 · 관례를 벗어난 것 ' + 어긴것.length + '개');
    for (const x of 어긴것.slice(-12)) console.log('   ' + x.줄번호 + '줄  ' + x.왜 + '\n      ' + x.줄);
    if (어긴것.length > 12) console.log('   … 앞의 ' + (어긴것.length - 12) + '개는 줄였다(최근 것만 보인다)');
    모두 += 어긴것.length;
  }

  /**
   * 🔴 기준선 — «늘 때만» 운다.
   *
   *   이 자를 만든 2026-09-04 02:2x 에 세어 보니 596개였고, «전부 내 것»이었다.
   *   총괄대행을 맡은 내내 `[5번(총괄대행) → 전 유닛]` 으로 써 왔기 때문이다.
   *   ⛔ 지난 메모는 «기록»이라 고치지 않는다 — 고치면 그때 남이 본 것과 달라진다.
   *   ⚠ 그렇다고 596개를 매번 빨강으로 내면 사람이 이 검사를 끈다.
   *   ✅ 그래서 「늘지 않으면 통과」로 둔다. 앞으로 쓰는 것만 관례를 지키면 수가 안 는다.
   *
   *   ⛔ 이 수는 «이 자가 직접 센 것»이어야 한다. 다른 도구가 센 수를 옮겨 적으면
   *     자와 기준선이 서로 다른 것을 세게 되고, 그러면 영원히 안 맞는다.
   */
  const 오늘까지봐주는수 = 596;

  console.log('');
  if (!모두) { console.log('✅ 표시가 다 관례 꼴이다'); process.exit(0); }
  if (모두 <= 오늘까지봐주는수) {
    console.log('⚠ 관례를 벗어난 표시 ' + 모두 + '개 — 기준선 ' + 오늘까지봐주는수 + '개 이하라 «막지 않는다».');
    console.log('   지난 메모는 기록이라 고치지 않는다. 앞으로 쓰는 것만 지키면 이 수는 늘지 않는다.');
    console.log('   ⛔ 보낸이 이름 뒤에 (총괄) 같은 꼬리를 붙이지 않는다 — 「N번」으로만 쓴다.');
    process.exit(0);
  }
  console.log('🔴 관례를 벗어난 표시가 ' + 모두 + '개로 «늘었다» (기준선 ' + 오늘까지봐주는수 + ').');
  console.log('   ⛔ 이름 뒤에 (총괄) 같은 꼬리를 붙이지 않는다. 상대가 찾는 글자열에 안 걸린다.');
  console.log('   2026-09-04 에 내 세 통이 이것 때문에 다섯 시간 동안 안 보였고, 6번은 그 사이');
  console.log('   자기 막힘의 답을 못 보고 대기했다. 새로 더한 표시를 고치고 다시 돌리십시오.');
  process.exit(1);
}
