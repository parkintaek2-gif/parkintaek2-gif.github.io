#!/usr/bin/env node
/**
 * collect-100y-home.mjs — **집을 가진 가구는 몇 살인가**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 2번 16시·17시 지시 「다음 나이 문 하나 — 지면 + 카드 + 숏영상을 한 덩어리로」.
 * 나이 줄에서 **40대가 아직 얇다**(/age 층 대문 하나뿐).
 *
 * ── 표 ─────────────────────────────────────────────────────────
 *   101/DT_1OH0403  주택소유통계 「거주지역/가구주의 성/연령대별 주택소유 가구수」 2015~2024
 *
 * ⛔⛔ 함정 둘 — 이 표의 가장 큰 위험이다.
 *   ① **ITM 이름이 거짓이다.** 칸 이름이 「일반가구수」인데 실제로는 **주택을 소유한 가구수**다.
 *      2024년 전국 총계가 12,684,099 — 일반가구(2천만대)가 아니라 소유 가구 수다.
 *      ⛔ 표의 칸 이름을 그대로 쓰면 거짓이 된다. 우리는 「소유 가구수」로 적는다.
 *   ② **이것은 「소유율」이 아니다.** 그 나이대 가구 가운데 몇 %가 집을 가졌나가 아니라,
 *      **집을 가진 가구 가운데 그 나이대가 몇 %인가**(구성비)다.
 *      ⛔ 소유율을 내려면 나이대별 «전체 일반가구수»가 있어야 하는데 이 표에 없다.
 *         다른 표에서 끌어와 나누지 않는다 — 정의가 어긋나면 몫이 거짓이 된다.
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · 나이는 **가구주**의 나이다. 집에 사는 사람들의 나이가 아니다
 * · 몇 채를 가졌는지는 이 표에 없다(다른 표다)
 * · 「소유」는 등기 기준이다 — 전세·월세로 사는 사람은 여기 안 들어간다
 *
 * 쓰는 법  node scripts/collect-100y-home.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '101';
export const TBL = 'DT_1OH0403';
/** ⛔ 「총계」는 나이칸이 아니다. 세는 데서 빼야 두 배가 안 된다 */
export const 총계칸 = '총계';
export const 나이칸들 = ['30세미만', '30~39세', '40~49세', '50~59세', '60~69세', '70~79세', '80세이상'];

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
/**
 * ⛔ 이것은 «소유율»이 아니라 «구성비»다 — 이름을 그렇게 붙여야 화면이 안 거짓말한다.
 *   집을 가진 가구 가운데 이 나이대가 몇 %인가.
 */
export function 구성비(부분, 소유전체) {
  if (부분 == null || !소유전체) return null;
  return Math.round((부분 / 소유전체) * 1000) / 10;
}
/** 가장 많은 나이칸 — ⛔ 「몇 살」로 못 쓴다. 칸 이름으로만 */
export function 가장많은칸(줄들) {
  const 산것 = 줄들.filter((r) => r.가구 != null);
  if (!산것.length) return null;
  return 산것.reduce((a, b) => (b.가구 > a.가구 ? b : a));
}
/** %p 차이 — ⛔ %와 %p 를 섞지 않는다 */
export const 퍼센트포인트 = (뒤, 앞) =>
  (뒤 == null || 앞 == null ? null : Math.round((뒤 - 앞) * 10) / 10);

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② ⛔ 「총계」는 나이칸이 아니다', !나이칸들.includes(총계칸));
  본다('③ 나이칸이 일곱이다', 나이칸들.length === 7);
  본다('④ 밑이 없으면 구성비를 안 낸다', 구성비(5, 0) === null && 구성비(null, 10) === null);
  본다('⑤ 구성비를 소수 한 자리로', 구성비(25, 200) === 12.5);
  본다('⑥ 가장 많은 칸을 찾는다',
    가장많은칸([{ 칸: 'a', 가구: 10 }, { 칸: 'b', 가구: 30 }, { 칸: 'c', 가구: null }]).칸 === 'b');
  본다('⑦ 다 비었으면 없다고 답한다', 가장많은칸([{ 칸: 'a', 가구: null }]) === null);
  본다('⑧ %p 를 따로 낸다', 퍼센트포인트(20.5, 18.1) === 2.4 && 퍼센트포인트(null, 1) === null);
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-home.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  /* ⛔ 열 해를 한 번에 받는다 — 「세 해만 받고 흐름을 못 봤다」를 두 번 겪었다 */
  const j = await (await fetch(
    `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
    + `&itmId=T001&objL1=00&objL2=ALL&objL3=ALL&format=json&jsonVD=Y`
    + `&orgId=${ORG}&tblId=${TBL}&prdSe=Y&newEstPrdCnt=20`)).json();
  if (!Array.isArray(j)) throw new Error(JSON.stringify(j).slice(0, 200));

  const 해들 = [...new Set(j.map((x) => x.PRD_DE))].sort();
  const 최신 = 해들[해들.length - 1];
  const 값 = (해, 나이, 성 = 총계칸) => 수로(j.find(
    (x) => x.PRD_DE === 해 && x.C3_NM === 나이 && x.C2_NM === 성)?.DT);

  const 소유전체 = 값(최신, 총계칸);
  const 나이별 = 나이칸들.map((칸) => {
    const 가구 = 값(최신, 칸);
    return {
      칸, 가구, 몫: 구성비(가구, 소유전체),
      남자: 값(최신, 칸, '남자'), 여자: 값(최신, 칸, '여자'),
    };
  });
  const 맨위 = 가장많은칸(나이별);

  /* 🔴 자가 대조 둘 — 표가 스스로 맞는지 내가 더해 본다 */
  const 칸합 = 나이별.reduce((s, r) => s + (r.가구 ?? 0), 0);
  const 남녀합 = 나이별.reduce((s, r) => s + (r.남자 ?? 0) + (r.여자 ?? 0), 0);
  const 대조 = {
    '나이칸을 다 더하면 총계': { 합: 칸합, 총계: 소유전체, 맞나: 칸합 === 소유전체 },
    '남자+여자 = 총계': { 합: 남녀합, 총계: 소유전체, 맞나: 남녀합 === 소유전체 },
    뜻: '두 대조가 다 맞아야 내가 칸을 빠뜨리지도, 두 번 세지도 않은 것이다',
  };

  /* 열 해 흐름 — 구성비가 어떻게 옮겨 갔나 */
  const 흐름 = 해들.map((해) => {
    const 그해전체 = 값(해, 총계칸);
    const 한줄 = { 해, 소유가구: 그해전체 };
    for (const 칸 of 나이칸들) 한줄[칸] = 구성비(값(해, 칸), 그해전체);
    return 한줄;
  }).filter((r) => r.소유가구 != null);
  const 흐름첫 = 흐름[0], 흐름끝 = 흐름[흐름.length - 1];
  const 못낸해 = 해들.filter((해) => !흐름.some((r) => r.해 === 해));

  /* ⭐ 열 해 사이에 가장 많이 오른 칸과 내린 칸 — ⛔ 줄을 세우는 것이 아니라 «움직임»을 본다 */
  const 움직임 = 나이칸들.map((칸) => ({
    칸, 앞: 흐름첫[칸], 뒤: 흐름끝[칸], 바뀜: 퍼센트포인트(흐름끝[칸], 흐름첫[칸]),
  })).filter((r) => r.바뀜 != null);
  const 가장오른칸 = 움직임.reduce((a, b) => (b.바뀜 > a.바뀜 ? b : a));
  const 가장내린칸 = 움직임.reduce((a, b) => (b.바뀜 < a.바뀜 ? b : a));

  const 낸다 = {
    무엇: '집을 가진 가구는 몇 살인가 — 가구주 나이대별 주택소유 가구수와 열 해 흐름',
    만든날: new Date().toISOString().slice(0, 10),
    최신, 해들, 해수: 해들.length, 흐름해수: 흐름.length, 못낸해,
    출처: {
      기관: '국가데이터처',
      표: '주택소유통계 「거주지역/가구주의 성/연령대별 주택소유 가구수」',
      창구: 'KOSIS', orgId: ORG, tblId: TBL,
    },
    '⛔⛔ 이것은 소유율이 아닙니다':
      '「그 나이대 가구 가운데 몇 %가 집을 가졌나」가 아닙니다. '
      + '「집을 가진 가구 가운데 그 나이대가 몇 %인가」입니다. '
      + '소유율을 내려면 나이대별 전체 가구수가 있어야 하는데 이 표에 없습니다 — '
      + '다른 표에서 끌어와 나누면 정의가 어긋나 거짓이 됩니다. 그래서 안 했습니다.',
    '⛔ 표의 칸 이름이 거짓입니다':
      '이 표의 항목 이름이 「일반가구수」인데, 실제로 들어 있는 것은 «주택을 소유한 가구수»입니다. '
      + `${최신}년 전국 총계가 ${소유전체.toLocaleString()}가구인데 일반가구는 그보다 훨씬 많습니다. `
      + '저희는 「소유 가구수」로 고쳐 적었습니다.',
    '⚠ 이 자료가 못 가르는 것': [
      '나이는 «가구주»의 나이입니다. 그 집에 사는 사람들의 나이가 아닙니다.',
      '몇 채를 가졌는지는 이 표에 없습니다.',
      '「소유」는 등기 기준입니다 — 전세·월세로 사는 사람은 여기 들어가지 않습니다.',
      '이 표로는 소유율(그 나이대의 몇 %가 집을 가졌나)을 낼 수 없습니다.',
    ],
    소유전체, 나이별, 가장많은칸: 맨위,
    흐름, 흐름첫, 흐름끝, 움직임, 가장오른칸, 가장내린칸,
    자가대조: 대조,
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/home.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)} — ${해들[0]}~${최신} (표에 ${해들.length}해 · 낸 것 ${흐름.length}해)`);
  console.log(`   ${최신}년 집을 가진 가구 ${소유전체.toLocaleString()}가구`);
  for (const r of 나이별) console.log(`   ${r.칸.padEnd(9)} ${r.가구 == null ? '—' : r.가구.toLocaleString().padStart(10)}가구  ${r.몫}%`);
  console.log(`   가장 많은 칸: ${맨위.칸} (${맨위.몫}%)`);
  console.log(`   열 해 사이 가장 오른 칸: ${가장오른칸.칸} ${가장오른칸.앞}% → ${가장오른칸.뒤}% (${가장오른칸.바뀜 > 0 ? '+' : ''}${가장오른칸.바뀜}%p)`);
  console.log(`   가장 내린 칸: ${가장내린칸.칸} ${가장내린칸.앞}% → ${가장내린칸.뒤}% (${가장내린칸.바뀜}%p)`);
  console.log(`   자가대조: 나이칸합=총계 ${대조['나이칸을 다 더하면 총계'].맞나 ? '맞다' : '🔴 안 맞다'}`
    + ` · 남+여=총계 ${대조['남자+여자 = 총계'].맞나 ? '맞다' : '🔴 안 맞다'}`
    + (못낸해.length ? ` · 🔴 못 낸 해 ${못낸해.join('·')}` : ' · 표의 해를 하나도 안 빠뜨렸다'));
}
