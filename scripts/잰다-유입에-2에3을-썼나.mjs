#!/usr/bin/env node
/**
 * 잰다-유입에-2에3을-썼나.mjs
 *   — **하루 업무의 2/3 를 «방문 유입»에 썼나.**
 *
 * ── 🔴🔴 사장님 지시 (2026-10-13 18:0x) ──────────────────────────────
 * 「**검색 색인+seo. AI geo. 커뮤니티 등 방문 유입 작업 하고있나?**」
 * 「**하루 업무의 2/3를 여기에 쓰도록**」
 *
 * 앞선 지시(2026-08-26)는 「업무분량의 50% 이상」이었다. **사장님이 올리셨다.**
 *
 * ⛔ 이 선을 «글»로만 갖지 않는다. 오늘 사장님이 물으셨을 때 나는
 *   「하고 있습니다」라고 답할 뻔했다. 그 말에는 수가 없다.
 *   ⭐ 회사 강령 ④ — 규칙은 문장이 아니라 **검사**로 둔다.
 *
 * ── ⚠ 이 자가 «못» 재는 것 ──────────────────────────────────────────
 * 커밋 수는 **일의 크기가 아니다.** 큰 일이 한 커밋이고 작은 일이 다섯 커밋일 수 있다.
 * ⛔ 그러므로 이 수를 「업무분량」이라고 부르지 않는다. **「커밋으로 본 어림」**이다.
 *   ⇒ 그래도 둔다. 어림이라도 수가 있으면 **방향은 보인다**. 수가 없으면
 *     「하고 있습니다」로 하루가 지나간다 — 오늘이 그랬다.
 * ⛔ 0 으로 채우지 않는다 — 가를 수 없는 커밋은 «모름»으로 따로 센다.
 *
 * 쓰는 법
 *   node scripts/잰다-유입에-2에3을-썼나.mjs --자가시험
 *   node scripts/잰다-유입에-2에3을-썼나.mjs
 *   node scripts/잰다-유입에-2에3을-썼나.mjs --날 2026-10-12
 */
import { execSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const 선 = 2 / 3;

/**
 * 유입 일을 가리키는 말.
 * ⚠ 사장님이 부르신 네 갈래 — 검색 색인 · SEO · AI GEO · 커뮤니티 — 를 먼저 둔다.
 * ⛔ 「기사」는 안 넣는다. 중부매일 기사는 제휴 심사용이라 **우리 사이트 방문이 아니다.**
 *   그것을 유입으로 세면 수가 저절로 커져 이 자가 나를 속인다.
 */
export const 유입말 = [
  '색인', 'indexnow', '사이트맵', 'sitemap', 'seo', 'geo', 'llms', 'AI 인용', '인용 관문',
  '커뮤니티', 'community', '유입', '방문자', '체류', '검색', '구글', '네이버', '빙', 'bing',
  '서치어드바이저', '검색콘솔', 'gsc', 'ga4', '애널리틱스', 'analytics', '노출', '클릭',
  '내부링크', '자매', '링크', '겹침', '중복 지면', 'canonical', '정본', '메타', 'og:',
  '구조화', 'json-ld', 'jsonld', '발행 주체', '스키마',
];

/** ⛔ 유입처럼 보이지만 아닌 것 — 먼저 걸러낸다 */
export const 유입아님말 = [
  '중부매일', '스포츠', '데스킹', '기사를 거둔', '보낸메일 기록', '결제', '자물쇠',
  '시세', '곳간', '아카이브', 'archive', '수집기',
];

/** 한 커밋 제목을 가른다 → '유입' · '아님' · '모름' */
export function 가른다(제목) {
  const s = String(제목 ?? '').toLowerCase();
  if (!s.trim()) return '모름';
  /* ⚠ 「대장 — 매시 기록」 같은 기록 커밋은 일이 아니다. 분모에서 뺀다 */
  if (/^대장|^보낸메일 기록|^메모 —/.test(String(제목).trim())) return '모름';
  const 아님 = 유입아님말.some((w) => s.includes(w.toLowerCase()));
  const 맞음 = 유입말.some((w) => s.includes(w.toLowerCase()));
  if (맞음 && !아님) return '유입';
  if (아님) return '아님';
  return 맞음 ? '유입' : '아님';
}

/** 판정. ⛔ 「못 쟀다」를 「지켰다」로도 「어겼다」로도 적지 않는다 */
export function 판정({ 유입, 아님, 모름 }) {
  const 센것 = (유입 ?? 0) + (아님 ?? 0);
  if (!센것) return { 빛: '⬜', 말: '못 쟀다 — 가를 수 있는 커밋이 없다', 비율: null };
  const 비율 = 유입 / 센것;
  if (비율 >= 선) {
    return { 빛: '✅', 말: `유입에 ${Math.round(비율 * 100)}% — 사장님 선(2/3)을 지켰다`, 비율 };
  }
  if (비율 >= 0.5) {
    return {
      빛: '⚠',
      말: `유입에 ${Math.round(비율 * 100)}% — 옛 선(50%)은 넘었으나 **2/3 에 못 미친다**`
        + ` (2026-10-13 에 사장님이 올리셨다)`,
      비율,
    };
  }
  return {
    빛: '🔴',
    말: `유입에 ${Math.round(비율 * 100)}%뿐이다 — 사장님 선은 **2/3**다`
      + (모름 ? ` (가를 수 없던 것 ${모름}건은 분모에서 뺐다)` : ''),
    비율,
  };
}

/* ── 자가시험 ──────────────────────────────────────────────────────── */
function 자가시험() {
  let 통과 = 0; let 실패 = 0;
  const 본다 = (말, 참) => {
    if (참) { 통과 += 1; console.log('  ✅ ' + 말); } else { 실패 += 1; console.log('  🔴 ' + 말); }
  };

  본다('🔴 색인 일을 유입으로 센다', 가른다('색인 요청 10장을 다시 골랐다') === '유입');
  본다('🔴 llms(AI GEO) 일을 유입으로 센다',
    가른다('AI 인용 관문을 메운다 — llms.txt 에 44편이 빠졌다') === '유입');
  본다('🔴 커뮤니티 일을 유입으로 센다', 가른다('커뮤니티 지면을 연다') === '유입');
  본다('🔴 사이트맵 일을 유입으로 센다', 가른다('구글이 든 사이트맵이 낡았다') === '유입');
  본다('🔴🔴 중부매일 기사는 «유입이 아니다» — 제휴 심사용이라 우리 사이트 방문이 아니다',
    가른다('중부매일 스포츠 기사가 중복으로 막혔다') === '아님');
  본다('   그 말이 유입말과 겹쳐도 아님이 이긴다 — 안 그러면 수가 저절로 커진다',
    가른다('중부매일 기사 검색 노출을 손봤다') === '아님');
  본다('🔴 결제·자물쇠는 유입이 아니다', 가른다('결제 502 를 쟀다') === '아님');
  본다('🔴 시세 곳간은 유입이 아니다', 가른다('시세 다섯 갈래 구멍이 메워졌다') === '아님');
  본다('⬜ 「대장 — 매시 기록」은 일이 아니다 — 분모에서 뺀다',
    가른다('대장 — 매시 기록') === '모름');
  본다('⬜ 보낸메일 기록도 뺀다', 가른다('보낸메일 기록 — 2026-10-13 16:01') === '모름');
  본다('⛔ 빈 값에도 안 터진다', 가른다(null) === '모름' && 가른다('') === '모름');

  본다('✅ 2/3 를 넘으면 초록', 판정({ 유입: 8, 아님: 2, 모름: 0 }).빛 === '✅');
  본다('⚠ 딱 50% 면 ⚠ — 옛 선은 넘었으나 새 선에 못 미친다',
    판정({ 유입: 5, 아님: 5, 모름: 0 }).빛 === '⚠');
  본다('   그 말에 «2/3 에 못 미친다»가 든다',
    /2\/3 에 못 미친다/.test(판정({ 유입: 5, 아님: 5, 모름: 0 }).말));
  본다('🔴 절반에 못 미치면 빨강', 판정({ 유입: 2, 아님: 8, 모름: 0 }).빛 === '🔴');
  본다('🔴 딱 2/3 는 지킨 것이다 — 선 위는 통과다',
    판정({ 유입: 2, 아님: 1, 모름: 0 }).빛 === '✅');
  본다('⬜ 가를 것이 없으면 ⬜ — ⛔ 「지켰다」가 아니다',
    판정({ 유입: 0, 아님: 0, 모름: 9 }).빛 === '⬜');
  본다('⛔ 모름은 분모에 안 넣는다 — 넣으면 비율이 가짜로 작아진다',
    판정({ 유입: 2, 아님: 1, 모름: 99 }).비율 === 2 / 3);

  console.log(String.fromCharCode(10) + '자가시험 ' + (통과 + 실패) + '개 · 통과 ' + 통과 + ' · 실패 ' + 실패);
  return 실패 === 0;
}

/* ── 본체 ──────────────────────────────────────────────────────────── */
function 잰다(날) {
  const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  let 줄들 = [];
  try {
    const out = execSync(
      `git log --since="${날} 00:00" --until="${날} 23:59" --pretty=%s`,
      { cwd: 뿌리, encoding: 'utf8' });
    줄들 = out.split(/\r?\n/).filter((l) => l.trim());
  } catch (e) {
    console.log('⬜ git 에 못 물었다 — ' + String(e?.message ?? e).slice(0, 90));
    return 0;
  }
  const 통 = { 유입: [], 아님: [], 모름: [] };
  for (const l of 줄들) 통[가른다(l)].push(l);

  console.log('■ ' + 날 + ' — 하루 업무의 2/3 를 «방문 유입»에 썼나 (사장님 2026-10-13)');
  console.log('');
  console.log('   커밋 ' + 줄들.length + '개 · 유입 ' + 통.유입.length
    + ' · 유입 아님 ' + 통.아님.length + ' · 가를 수 없음 ' + 통.모름.length);
  console.log('');
  const r = 판정({ 유입: 통.유입.length, 아님: 통.아님.length, 모름: 통.모름.length });
  console.log('   ' + r.빛 + ' ' + r.말);
  console.log('');
  console.log('   ── 유입으로 센 것 ' + '─'.repeat(30));
  for (const l of 통.유입.slice(0, 10)) console.log('      ✅ ' + l.slice(0, 84));
  if (통.유입.length > 10) console.log('      … ' + (통.유입.length - 10) + '건 더');
  console.log('   ── 유입이 «아닌» 것 ' + '─'.repeat(28));
  for (const l of 통.아님.slice(0, 10)) console.log('      · ' + l.slice(0, 84));
  if (통.아님.length > 10) console.log('      … ' + (통.아님.length - 10) + '건 더');
  console.log('');
  console.log('   ⛔ 커밋 수는 «일의 크기»가 아니다. 이것은 어림이지 업무분량이 아니다.');
  console.log('   ⭐ 그래도 수가 있으면 방향은 보인다 — 수가 없으면 「하고 있습니다」로 하루가 간다.');
  return r.빛 === '🔴' ? 1 : 0;
}

/* ── 들머리 ────────────────────────────────────────────────────────── */
const 내가진입점 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가진입점) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);
  else {
    const i = process.argv.indexOf('--날');
    const v = i >= 0 ? process.argv[i + 1] : null;
    const 오늘 = new Date();
    const 기본 = `${오늘.getFullYear()}-${String(오늘.getMonth() + 1).padStart(2, '0')}-${String(오늘.getDate()).padStart(2, '0')}`;
    process.exit(잰다(/^\d{4}-\d{2}-\d{2}$/.test(String(v)) ? v : 기본));
  }
}
