/** 「계약금액(천원)」처럼 단위가 이름에 붙어 있으면 곱한다 */
export function 단위배수(칸이름) {
  if (/천\s*원/.test(칸이름)) return 1000;
  if (/백만\s*원/.test(칸이름)) return 1000000;
  if (/억\s*원/.test(칸이름)) return 100000000;
  return 1;
}

/** 따옴표를 아는 칸 가르기 */
export function 줄가르기(줄) {
  const 칸 = []; let 담 = ''; let 따 = false;
  for (const ch of 줄) {
    if (ch === '"') { 따 = !따; continue; }
    if (ch === ',' && !따) { 칸.push(담); 담 = ''; continue; }
    담 += ch;
  }
  칸.push(담);
  return 칸.map((x) => x.trim());
}

/** 깨진 글자가 적은 쪽으로 고른다 (CP949 인지 UTF-8 인지 파일마다 다르다) */
export function 글자풀기(바이트) {
  const 셈 = (s) => (s.match(/�/g) || []).length;
  const u = new TextDecoder('utf-8', { fatal: false }).decode(바이트);
  const k = new TextDecoder('euc-kr', { fatal: false }).decode(바이트);
  return 셈(u) <= 셈(k) ? u : k;
}

/** 머리줄이 첫 줄이 아닌 파일이 있다(설명이 위에 한 줄 붙는다). 앞 다섯 줄에서 찾는다 */
export function 머리줄찾기(줄들) {
  for (let i = 0; i < Math.min(5, 줄들.length); i++) {
    const h = 줄가르기(줄들[i]);
    if (h.length < 3) continue;
    const 이 = h.findIndex((x) => /^(계약명|사업명|용역명|공고명|계약건명|건명|입찰공고명)$/.test(x));
    /* ⚠ 칸 이름을 **통째로** 맞춘다. 「이 자료는 … 계약금액 을 담습니다」 같은 설명줄이
       머리줄로 잘못 잡히기 때문이다(8/10 자가시험이 잡았다). 단위 괄호만 뒤에 붙는 것을 허락한다 */
    const 돈 = h.findIndex((x) => /^(최초계약금액|총계약금액|계약금액|낙찰금액|대가지급액)\s*(\([^)]*\))?$/.test(x));
    if (이 >= 0 && 돈 >= 0) return { 줄번호: i, 머리: h, 이름칸: 이, 돈칸: 돈 };
  }
  return null;
}

export const 돈읽기 = (s) => Number(String(s ?? '').replace(/[^0-9]/g, '')) || 0;

/** 사분위 — 나눔: 정렬한 값에서 자리 뽑기 */
export function 사분위(값들, p) {
  if (!값들.length) return null;
  const s = [...값들].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.max(0, Math.floor((s.length - 1) * p)))];
}

export function 걸리나(계약명) {
  if (!계약명) return false;
  if (자료아닌꼴.test(계약명)) return false;
  return 자료용역꼴.test(계약명);
}

