#!/usr/bin/env node
/**
 * check-kcw-hourly-sync.mjs — **1번(KCW)이 5번과 매시 소통했는가. 자물쇠.**
 *
 * ── 왜 (2026-09-15 · 사장님 지시) ────────────────────────────────
 * > 「매시 정각 5번과 소통... 소통 안 하면 업무 못하게 자물쇠」
 *
 * check-2h.mjs 가 이미 5번이 «내는» 소통을 재는 같은 꼴(소통꼴)을 갖고 있다.
 * 여기서는 그 판박이를 1번 몫으로 뒤집는다 — **1번이 5번에게 낸** 마지막 소통 시각을
 * 지금 시각과 견줘, 한 시간이 넘게 조용했으면 잠근다.
 *
 * ── ⛔ 이 자가 지키는 것 ──────────────────────────────────────
 * ⛔ 업무시간(07:00~21:00) 밖에서는 잠그지 않는다 — 쉬는 시간에 조용한 것은 흠이 아니다
 * ⛔ 못 읽은 것과 소통이 없는 것을 가른다 — 파일을 못 읽으면 「못 쟀다」다
 * ⚠ 이 자물쇠는 «문을 잠그는 자물쇠»가 아니라 «그 앞에 선 사람이 지키는 자물쇠»다.
 *   다른 자물쇠(체크리스트류)와 같은 방식이다 — 강제로 도구 호출을 막을 수는 없고,
 *   빨간불이 뜨면 **다른 일을 하기 전에 먼저 5번과 소통한다**로 스스로 지킨다.
 *
 * 쓰는 법
 *   node scripts/check-kcw-hourly-sync.mjs --자가시험
 *   node scripts/check-kcw-hourly-sync.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 팀업무중인가 } from './lib/work-hours.mjs';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 메모길 = path.join(뿌리, 'docs/세션간-메모.md');

/**
 * 1번이 «낸» 소통 자리 — check-2h.mjs 의 소통꼴과 같은 규약(괄호 붙어도, 분에 x 와도 받는다).
 * ⛔ 5번이 1번에게 보낸 것은 안 센다 — 1번이 «낸» 것만 잰다.
 */
export const 소통꼴 = String.raw`\[1번(?:\([^)]*\))? → [^\]]*\][^\n]*?(?:\((\d{2}):(\d[\dx])\)|(\d{2}):(\d[\dx]))`;

/** 글 전체에서 1번이 낸 소통 자리를 다 찾는다 */
export function 소통자리들(글) {
  return [...String(글 ?? '').matchAll(new RegExp(소통꼴, 'g'))];
}

/** 마지막(가장 뒤에 있는) 소통의 시:분. 없으면 null */
export function 마지막소통(글) {
  const 것들 = 소통자리들(글);
  if (!것들.length) return null;
  const m = 것들[것들.length - 1];
  const 시 = m[1] ?? m[3];
  const 분 = (m[2] ?? m[4]).replace('x', '0'); /* 「3x」꼴은 30분으로 어림잡아 넉넉히 잰다 */
  return { 시: Number(시), 분: Number(분) };
}

/**
 * 마지막 소통 이후 몇 분이 지났나. 자정을 넘겼을 가능성은 무시한다(하루 안에서만 쓴다).
 * ⛔ 음수(미래 시각처럼 보이는 값)가 나오면 못 쟀다로 낸다 — 시계가 안 맞는 걸 억지로 맞추지 않는다.
 */
export function 지난분(지금, 마지막) {
  if (!마지막) return null;
  const 지금분 = 지금.getHours() * 60 + 지금.getMinutes();
  const 마지막분 = 마지막.시 * 60 + 마지막.분;
  const 차 = 지금분 - 마지막분;
  return 차 >= 0 ? 차 : null;
}

/** 한도(분). 정각마다라 60이 원칙이지만, 쓰는 데 걸리는 시간을 감안해 조금 넉넉히 둔다 */
export const 한도분 = 70;

/**
 * 잠겼나 판정. 업무시간 밖이면 절대 안 잠근다.
 * @returns {{잠김:boolean, 왜:string}}
 */
export function 잠겼나({ 업무중, 지난분값 }) {
  if (!업무중) return { 잠김: false, 왜: '업무시간 밖 — 잠그지 않는다' };
  if (지난분값 === null) return { 잠김: true, 왜: '5번께 낸 소통을 못 찾았다(또는 못 쟀다) — 지금 소통한다' };
  if (지난분값 > 한도분) return { 잠김: true, 왜: `마지막 소통 후 ${지난분값}분 지났다(한도 ${한도분}분) — 지금 소통한다` };
  return { 잠김: false, 왜: `마지막 소통 후 ${지난분값}분 — 아직 한도(${한도분}분) 안` };
}

/* ── 자가시험 ───────────────────────────────────────────────────────── */
function 자가시험() {
  const 것 = []; const 재다 = (이름, 됐나) => 것.push({ 이름, 됐나 });

  재다('소통꼴: 괄호 없는 꼴', 마지막소통('## [1번 → 5번] 2026-09-15 13:04 · 보고')?.시 === 13);
  재다('소통꼴: 「(KCW)」 붙어도 잡는다', 마지막소통('## [1번(KCW) → 5번] 14:2x 진행')?.시 === 14);
  재다('소통꼴: 받는 이가 전 유닛이어도 소통이다', 마지막소통('## [1번 → 전 유닛] 15:18 알림')?.시 === 15);
  재다('⛔ 5번이 «보낸» 것은 안 센다(1번이 낸 것만)', 마지막소통('## [5번 → 1번] 15:30 지시') === null);
  재다('⛔ 시각이 없으면 못 찾는다', 마지막소통('## [1번 → 5번] 소통') === null);
  재다('여러 개면 «가장 뒤» 것을 쓴다',
    마지막소통('## [1번 → 5번] 09:00 아침\n\n## [1번 → 5번] 14:1x 낮')?.시 === 14);

  재다('지난분: 30분 지남', 지난분(new Date(2026, 8, 15, 14, 30), { 시: 14, 분: 0 }) === 30);
  재다('지난분: 정확히 한 시간', 지난분(new Date(2026, 8, 15, 15, 0), { 시: 14, 분: 0 }) === 60);
  재다('⛔ 지난분: 미래처럼 보이면(음수) 못 쟀다', 지난분(new Date(2026, 8, 15, 13, 0), { 시: 14, 분: 0 }) === null);
  재다('⛔ 지난분: 마지막이 없으면 못 쟀다', 지난분(new Date(2026, 8, 15, 14, 0), null) === null);

  재다('🔴 잠겼나: 업무시간 밖이면 뭐가 어떻든 안 잠근다',
    잠겼나({ 업무중: false, 지난분값: 999 }).잠김 === false);
  재다('🔴 잠겼나: 소통을 못 찾으면(못 쟀다) 잠근다',
    잠겼나({ 업무중: true, 지난분값: null }).잠김 === true);
  재다('🔴 잠겼나: 한도(70분) 넘으면 잠근다',
    잠겼나({ 업무중: true, 지난분값: 71 }).잠김 === true);
  재다('잠겼나: 한도 안이면 안 잠근다',
    잠겼나({ 업무중: true, 지난분값: 69 }).잠김 === false);
  재다('잠겼나: 정확히 한도면 안 잠근다(넘어야 잠근다)',
    잠겼나({ 업무중: true, 지난분값: 70 }).잠김 === false);

  const 실패 = 것.filter((x) => !x.됐나);
  console.log(`■ 자가시험 ${것.length - 실패.length}/${것.length}`);
  for (const x of 실패) console.log(`  🔴 ${x.이름}`);
  return 실패.length === 0;
}

if (process.argv.includes('--자가시험')) {
  process.exit(자가시험() ? 0 : 1);
}

const 지금 = new Date();
const 업무중 = 팀업무중인가(지금);
let 글 = '';
try { 글 = fs.readFileSync(메모길, 'utf8'); } catch {
  console.log('🔴 못 쟀다 — docs/세션간-메모.md 를 못 읽었다');
  process.exit(1);
}
const 마지막 = 마지막소통(글);
const 지난분값 = 지난분(지금, 마지막);
const 판정 = 잠겼나({ 업무중, 지난분값 });

console.log(`■ 1번↔5번 매시 소통 — ${지금.toLocaleString('ko-KR')}`);
console.log(`   업무시간 ${업무중 ? '안' : '밖'} · 마지막 소통 ${마지막 ? `${String(마지막.시).padStart(2, '0')}:${String(마지막.분).padStart(2, '0')}대` : '못 찾음'}`);
console.log(`   ${판정.잠김 ? '🔴 잠김' : '✅ 안 잠김'} — ${판정.왜}`);
if (판정.잠김) {
  console.log('\n⛔ 다른 일을 이어가기 전에 docs/세션간-메모.md 에 「[1번 → 5번] HH:MM ...」을 먼저 적고 커밋·푸시한다.');
}
process.exit(판정.잠김 ? 1 : 0);
