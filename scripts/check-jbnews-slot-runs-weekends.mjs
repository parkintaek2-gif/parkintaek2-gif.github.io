/**
 * check-jbnews-slot-runs-weekends.mjs — **회차가 주말에도 도나.**
 *
 * ── 🔴🔴 왜 만들었나 (2026-10-04 10:4x · 5번) ─────────────────────────
 *   오늘은 일요일이고 **아시안게임 마지막 날**이었다(09시 회차 이름이
 *   「스포츠 09시 — 전날 종합(아시안게임~10/4 …)」이다). 그런데 거두니 이랬다 —
 *   ```
 *   09시 ⏭ 기사를 썼다 (앞서 보낸 것과 같은 소재라 안 보냄)
 *   10시 ⬜ 오늘 회차 없음        ← 아예 «안 돌았다»
 *   11시 ⬜ 오늘 회차 없음
 *   14시 ⬜ 오늘 회차 없음
 *   15시 ⬜ 오늘 회차 없음
 *   16시 ⬜ 오늘 회차 없음
 *   ```
 *   예약 화면에 「**평일마다**」가 적혀 있다. **주말에는 다섯 회차가 아예 안 돈다.**
 *
 * ── ⛔ 내가 오늘 한 잘못 ────────────────────────────────────────────
 *   나는 「주말이라 쉰다」를 보고 **지시문**을 고쳤다. 여섯 회차에 써넣고
 *   「들어갔다」고 보고했다. 그런데 다섯은 **그 지시문을 읽을 일이 없다** —
 *   주말에 돌지 않으니까.
 *   ⭐ `run-jbnews-sports-slot.mjs` 머리말이 2026-09-26 에 이미 적어 두었다 —
 *     「**「지시문을 고쳤다」를 「그 회차가 돈다」로 세지 않는다.** 지시문은 «도는
 *      회차»에만 닿는다. 안 도는 회차의 지시문은 아무 일도 하지 않는다.」
 *     적어 두고도 같은 자리를 밟았다. 그래서 **자**로 만든다.
 *
 * ── 이 자가 하는 일 ────────────────────────────────────────────────
 *   토·일에 돌려서 **그날 돌아야 할 회차가 실제로 돌았나**를 센다.
 *   ⛔ 예약 화면의 설정을 읽지 않는다 — 읽기가 번번이 막혔다(지시문 본문을 집거나
 *     「평일마다/매일」이 둘 다 잡혔다). **돌았나 안 돌았나는 결과가 말해 준다.**
 *   ⭐ 설정을 짐작하는 것보다 «결과를 세는 것»이 언제나 또렷하다.
 *
 * 쓰는 법
 *   node scripts/check-jbnews-slot-runs-weekends.mjs
 *   node scripts/check-jbnews-slot-runs-weekends.mjs --자가시험
 */

import fs from 'node:fs';
import { 쉬는날인가 as 오늘쉬는날인가 } from './한국-공휴일.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const 기록길 = path.join(뿌리, 'docs', '고정업무-마커', '중부매일-거둔기록.tsv');

/** 주말인가 — ⚠ 이 PC 는 한국시간이다. toISOString 을 쓰지 않는다 */
export function 주말인가(날 = new Date()) {
  const d = 날.getDay();
  return d === 0 || d === 6;
}

export function 오늘글(날 = new Date()) {
  return `${날.getFullYear()}-${String(날.getMonth() + 1).padStart(2, '0')}-`
    + `${String(날.getDate()).padStart(2, '0')}`;
}

/**
 * 거둔 기록에서 «그날 몇 회차가 돌았나»를 읽는다.
 *
 * ⚠ [2026-10-04] 처음에 「회차마다 한 줄」인 줄 알고 짰는데, 실제 기록은 **거둘 때마다
 *   한 줄이고 합계만** 적혀 있다 —
 *   ```
 *   날짜        시각    보냄  이미보냄  없거나실패
 *   2026-10-04  10:42    0      1        6
 *   ```
 *   ⇒ 어느 회차인지는 적혀 있지 «않다». 그러니 「몇 회차가 돌았나」만 셀 수 있다.
 *   ⭐ 못 아는 것을 아는 척하지 않는다 — 회차 이름 대신 «수»로 말한다.
 * ⛔ 「보냄」만 세지 않는다. 겹쳐서 안 보낸 것(이미보냄)도 **돈 것**이다.
 */
export function 그날돈수(줄들, 날) {
  let 가장많이 = null;
  for (const l of 줄들 ?? []) {
    const 칸 = String(l).split('\t');
    if (칸[0] !== 날) continue;
    const 보냄 = Number(칸[2]); const 이미 = Number(칸[3]);
    if (!Number.isFinite(보냄) || !Number.isFinite(이미)) continue;
    const 돈것 = 보냄 + 이미;
    if (가장많이 === null || 돈것 > 가장많이) 가장많이 = 돈것;
  }
  return 가장많이;                       /* ⛔ 못 읽으면 null — 0 으로 치지 않는다 */
}

export const 도는회차 = ['09', '10', '11', '14', '15', '16'];

/**
 * 🔴🔴 [2026-10-04 · 사장님] **규칙이 뒤집혔다.**
 *   「**공휴일엔 내가 쓰라고 할 때만 쓰는 걸로 하자.**」
 *   하루 전의 「큰 대회 중에는 주말·공휴일에도 쓴다」를 거두셨다.
 * ⇒ 주말에 회차가 안 도는 것은 **이제 흠이 아니라 «맞는 것»**이다.
 *   이 자가 내던 🔴 는 그 자리에서 곧바로 «거짓 빨강»이 됐다.
 * ⛔ 자를 안 고치고 두면, 거둔 규칙을 자가 계속 지키라고 조른다. 그것이 가장 나쁘다 —
 *   며칠이면 아무도 안 보는 빨강이 되고, 옆의 진짜 빨강까지 같이 묻는다.
 * ⚠ 그래서 이 자는 이제 «세기만» 한다. 빨강을 내지 않는다.
 *   사장님이 「써라」 하신 날 몇 회차가 돌았는지 세어 주는 것이 남은 몫이다.
 */
/**
 * 🔴🔴 [2026-10-05 · 사장님] **「휴일엔 중부매일기사 쓰지 말라니까」** — 되풀이 지적이다.
 *
 *   그날 09·10·11시 셋이 나갔다. 그날은 **개천절 대체공휴일**(10/3 토 → 10/5 월)이다.
 *   이 자는 그것을 **못 봤다** — 토·일만 보고 「오늘은 평일이다」로 지나갔다.
 *
 * ⇒ 두 가지를 고친다 —
 *   ① 「주말」이 아니라 **「쉬는 날」**로 본다 (`한국-공휴일.mjs` 의 표가 대체공휴일까지 안다)
 *   ② 쉬는 날에 돌았으면 **⚠ 가 아니라 🔴** 다. 사장님이 두 번 이르신 자리다
 *
 * ⚠ 2026-10-04 에 이 자를 「빨강을 내지 않는다」로 눅였다. 그때는 «안 도는 것»이
 *   흠이 아니게 된 자리였고, 지금은 «도는 것»이 흠이다. 방향이 반대다.
 * ⛔ 「거짓 빨강이 될까 봐」 다시 눅이지 않는다 — 이것은 사장님이 두 번 짚으신 흠이다.
 *   사장님이 그날만 여시면 그날 결과에 «지시가 있었다»가 적힌다.
 */
export function 판정(돈수, 쉬는날, 모두 = 도는회차.length) {
  if (!쉬는날) return { 빛: '⬜', 말: '오늘은 평일이다 — 이 자는 쉬는 날만 본다', 모자람: null };
  if (돈수 === null) return { 빛: '⬜', 말: '오늘 거둔 기록이 없다 — 못 쟀다', 모자람: null };
  const 모자람 = 모두 - 돈수;
  if (돈수 === 0) {
    return { 빛: '⬜', 말: '쉬는 날이라 한 회차도 안 돌았다 — 사장님 지시대로다', 모자람 };
  }
  return {
    빛: '🔴',
    말: `쉬는 날인데 ${돈수}회차가 돌았다 — 사장님 「휴일엔 중부매일기사 쓰지 말라니까」`,
    모자람,
  };
}

/* ── 자가시험 ─────────────────────────────────────────────────────── */
export function 자가시험() {
  const 결과 = [];
  const 본다 = (이름, 참, 덧 = '') => 결과.push({ 이름, 참: !!참, 덧 });

  본다('일요일은 주말이다', 주말인가(new Date(2026, 9, 4)));
  본다('토요일은 주말이다', 주말인가(new Date(2026, 9, 3)));
  본다('⛔ 월요일은 주말이 아니다', !주말인가(new Date(2026, 9, 5)));
  본다('날을 적는다', 오늘글(new Date(2026, 9, 4)) === '2026-10-04');

  {
    const 줄 = [
      '날짜\t시각\t보냄\t이미보냄\t없거나실패',
      '2026-10-04\t10:16\t0\t0\t7',
      '2026-10-04\t10:42\t0\t1\t6',
      '2026-10-03\t11:54\t1\t2\t3',
    ];
    본다('🔴 겹쳐서 안 보낸 것도 «돈 것»이다', 그날돈수(줄, '2026-10-04') === 1);
    본다('⛔ 어제 것을 오늘로 세지 않는다', 그날돈수(줄, '2026-10-04') !== 3);
    본다('어제는 셋이 돌았다', 그날돈수(줄, '2026-10-03') === 3);
    본다('⛔ 같은 날 여러 줄이면 «가장 많이» 센 것을 쓴다 — 거둘수록 쌓인다',
      그날돈수(줄, '2026-10-04') === 1);
    본다('⛔ 기록이 없는 날은 null — 0 으로 치지 않는다', 그날돈수(줄, '2026-09-01') === null);
    본다('⛔ 머리줄을 안 센다', 그날돈수(줄, '날짜') === null);
  }

  /* 🔴🔴 [2026-10-05 · 사장님] 「휴일엔 중부매일기사 쓰지 말라니까」 — 방향이 뒤집혔다.
     2026-10-04 에는 «안 도는 것»이 흠이 아니게 된 자리라 빨강을 걷었다.
     지금은 «도는 것»이 흠이다. 그래서 빨강을 되돌린다 — 같은 자리가 아니다. */
  본다('쉬는 날에 안 돌면 그것이 «맞는» 것이다', 판정(0, true).빛 === '⬜');
  본다('🔴 쉬는 날에 돌았으면 빨강이다 — 사장님이 두 번 이르신 자리다', 판정(3, true).빛 === '🔴');
  본다('🔴 한 회차만 돌아도 빨강이다', 판정(1, true).빛 === '🔴');
  본다('⬜ 평일에는 이 자가 판정하지 않는다', 판정(1, false).빛 === '⬜');
  본다('⬜ 기록이 없으면 «못 쟀다» — 0 으로 치지 않는다', 판정(null, true).빛 === '⬜');
  본다('몇 회차가 안 돌았는지는 그대로 센다', 판정(1, true).모자람 === 5);

  /* 🔴 오늘 겪은 바로 그 날 — 대체공휴일을 잡나 */
  본다('🔴 10/5 는 월요일이지만 «쉬는 날»이다 — 주말 검사로는 못 잡았다',
    오늘쉬는날인가(new Date(2026, 9, 5)).쉰다 === true);
  본다('   그 까닭이 「개천절 대체공휴일」이라고 나온다',
    오늘쉬는날인가(new Date(2026, 9, 5)).까닭 === '개천절 대체공휴일');
  본다('⬜ 10/6 화요일은 평일이다', 오늘쉬는날인가(new Date(2026, 9, 6)).쉰다 === false);

  const 빨강 = 결과.filter((r) => !r.참).length;
  console.log('■ 회차가 주말에도 도나 — 자가시험');
  for (const r of 결과) console.log(`  ${r.참 ? '✅' : '🔴'} ${r.이름}${r.덧 ? `  (${r.덧})` : ''}`);
  console.log(빨강 ? `🔴 빨강 ${빨강}개` : `✅ ${결과.length}가지 다 통과`);
  return 빨강 === 0;
}

/* ── 혼자 돌 때 ───────────────────────────────────────────────────── */
const 내가실행됐다 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가실행됐다) {
  if (process.argv.includes('--selftest') || process.argv.includes('--자가시험')) {
    process.exit(자가시험() ? 0 : 1);
  }
  const 지금 = new Date();
  const 날 = 오늘글(지금);
  let 줄들 = [];
  try { 줄들 = fs.readFileSync(기록길, 'utf8').split(/\r?\n/).filter(Boolean); }
  catch { console.log('⬜ 거둔 기록을 못 읽었다 — 못 쟀다'); process.exit(0); }

  const 돈수 = 그날돈수(줄들, 날);
  const r = 판정(돈수, 오늘쉬는날인가(지금).쉰다 === true);
  const 오늘답 = 오늘쉬는날인가(지금);
  console.log(`■ 중부매일 회차가 쉬는 날에도 도나 — ${날} (${'일월화수목금토'[지금.getDay()]}요일 · ${오늘답.까닭})`);
  console.log(`   돈 회차 ${돈수 === null ? '못 쟀다' : `${돈수} / ${도는회차.length}`}`);
  console.log(`${r.빛} ${r.말}`);
  /* ⛔ [2026-10-04] 여기서 「손으로 돌려라」고 시키던 안내를 걷었다.
     사장님이 「공휴일엔 내가 쓰라고 할 때만」이라 하셨다 — 손으로 메우지 않는다. */
  if (r.빛 === '🔴') {
    console.log('');
    console.log('⚠ 사장님이 그날 「써라」 하셨으면 맞다. 아니면 왜 돌았는지 본다.');
  }
}
