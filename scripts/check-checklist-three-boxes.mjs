#!/usr/bin/env node
/**
 * check-checklist-three-boxes.mjs — 체크리스트가 **세 칸**을 갖추고 **살아 있나**를 잰다.
 *
 * ── 사장님 지시 (2026-09-21, 원문) ────────────────────────────────────────
 *   「**체크리스트에 꾸준히 리스트를 추가해.**」
 *   「**그리고 체크리스트마다 <한 것, 진행 중, 포기한 것> 세 항목에 체크를 업데이트하면 되잖아.**」
 *   「**뭔가 일을 마무리할 때마다, 업무시간이 끝날 때마다 업데이트를 해.**」
 *
 * ── 왜 「포기한 것」 칸이 핵심인가 — 수로 답한다 ──────────────────────────
 * 저장소에서 「같은 잘못을 또 했다」류 자책을 세니 **311번**이었다
 * (세션간 메모 293 · CLAUDE.md 6 · 나머지 12). 원인을 아는 것만 골라 보면 —
 *
 * ```
 * 인터넷신문 등록   27일 전 끝난 결정을 「답 기다림」으로 다시 올렸다
 * 유튜브 업로드 도구 사흘 전 「안 한다」로 정한 것을 하루에 «두 번» 만들었다
 * 구독 월 4,900원   어제 버린 값으로 다시 셈해 「1000억 불가능」을 올렸다
 * EDINET 열쇠       열쇠가 나온 뒤에도 「막혔다」를 그대로 올렸다 (2026-09-21, 나)
 * ```
 *
 * 넷 다 똑같다 — **끝났거나 버린 일이 목록에 그냥 남아 있어서, 다음 사람이
 * 「아직 안 한 일」로 읽었다.** 「포기한 것」 칸이 그 구멍을 메운다.
 *
 * ⛔ 다만 칸을 두는 것만으로는 또 낡는다. **문서는 스스로 갱신되지 않는다** —
 *   오늘 EDINET 이 그것을 보여 줬다. 그래서 이 자가 「너무 오래 안 고쳐졌나」까지 본다.
 *
 * 쓰는 법
 *   node scripts/check-checklist-three-boxes.mjs
 *   node scripts/check-checklist-three-boxes.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * 세 칸의 표준 이름 — 이 글자가 제목줄에 있어야 한다.
 *
 * ⚠ 이모지를 `🔄?` 처럼 «맨몸으로» 쓰지 않는다 — 🔄(U+1F504)는 서로게이트 페어라
 *   `?` 가 «뒤쪽 반 코드유닛»에만 걸려, 이모지 없는 제목을 못 알아본다.
 *   2026-09-21 에 이 자를 만들자마자 자가시험 4개가 그것 때문에 떨어졌다.
 *   ⇒ `(?:…)?` 로 감싼다. ✅(U+2705)·⛔(U+26D4)는 BMP 라 괜찮지만 꼴을 맞춘다.
 */
export const 세칸 = [
  { 이름: '한 것', 무늬: /^#{1,4}\s*(?:✅)?\s*한 것/m },
  { 이름: '진행 중', 무늬: /^#{1,4}\s*(?:🔄)?\s*진행 중/m },
  { 이름: '포기한 것', 무늬: /^#{1,4}\s*(?:⛔)?\s*포기한 것/m },
];

/** 세 칸을 다 갖췄나 — 없는 칸 이름을 돌려준다 */
export function 빠진칸(글) {
  const s = String(글 || '');
  return 세칸.filter((c) => !c.무늬.test(s)).map((c) => c.이름);
}

/**
 * 며칠째 안 고쳐졌나.
 * ⚠ 파일 수정시각이 아니라 **git 이 기억하는 마지막 손댄 날**로 잰다 —
 *   git pull 이나 줄끝 바꿈으로 파일 시각은 쉽게 흔들린다.
 */
export function 며칠묵었나(마지막날, 오늘 = new Date()) {
  if (!마지막날) return null;
  const t = new Date(마지막날 + 'T00:00:00');
  if (Number.isNaN(t.getTime())) return null;
  const 오 = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate());
  return Math.round((오 - t) / 86400000);
}

/** 판정 — 빨간불인가 */
export function 판정(빠진, 묵은날, 참는날 = 7) {
  if (빠진.length === 3) return { 등급: '⬜', 말: '세 칸이 아직 없다 — 틀을 넣는다' };
  if (빠진.length) return { 등급: '🔴', 말: `칸이 빠졌다: ${빠진.join(' · ')}` };
  if (묵은날 === null) return { 등급: '⚠', 말: '언제 고쳤는지 못 쟀다' };
  if (묵은날 > 참는날) return { 등급: '🔴', 말: `${묵은날}일째 안 고쳤다 (참는 선 ${참는날})` };
  return { 등급: '✅', 말: `세 칸 다 있고 ${묵은날}일 전에 고쳤다` };
}

/** 보는 체크리스트들 */
export const 보는것 = [
  'docs/체크판.md',
  'docs/비즈니스-체크리스트.md',
  'docs/오픈-점검표.md',
  'docs/5번-업무매뉴얼.md',
];

/* ── 자가시험 ──────────────────────────────────────────────── */
const 내가진입점 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가진입점 && (process.argv.includes('--자가시험') || process.argv.includes('--selftest'))) {
  const 잰다 = [];
  const 검 = (이름, 참) => 잰다.push([이름, !!참]);
  const 다갖춤 = '# 문서\n\n## ✅ 한 것\n- a\n\n## 🔄 진행 중\n- b\n\n## ⛔ 포기한 것\n- c\n';

  검('세 칸을 다 갖추면 빠진 것이 없다', 빠진칸(다갖춤).length === 0);
  검('이모지가 없어도 알아본다', 빠진칸('## 한 것\n## 진행 중\n## 포기한 것').length === 0);
  검('제목 깊이가 달라도 알아본다', 빠진칸('#### 한 것\n# 진행 중\n### 포기한 것').length === 0);
  검('⭐ 포기한 것이 없으면 잡는다',
    빠진칸('## 한 것\n## 진행 중').join() === '포기한 것');
  검('한 것이 없으면 잡는다', 빠진칸('## 진행 중\n## 포기한 것').join() === '한 것');
  검('빈 문서는 셋 다 없다', 빠진칸('').length === 3);
  검('⛔ 본문에 낱말만 있는 것은 칸이 아니다',
    빠진칸('포기한 것은 없다고 본문에 적었다').length === 3);

  검('묵은 날을 센다', 며칠묵었나('2026-09-14', new Date(2026, 8, 21)) === 7);
  검('오늘 고쳤으면 0일', 며칠묵었나('2026-09-21', new Date(2026, 8, 21)) === 0);
  검('⛔ 날짜가 없으면 null — 0 으로 메꾸지 않는다', 며칠묵었나(null) === null);
  검('⛔ 엉뚱한 날짜도 null', 며칠묵었나('어제') === null);

  검('셋 다 없으면 ⬜ (아직 틀이 없는 것이다)', 판정(['한 것', '진행 중', '포기한 것'], 0).등급 === '⬜');
  검('하나만 빠지면 🔴', 판정(['포기한 것'], 0).등급 === '🔴');
  검('그때 무엇이 빠졌는지 말한다', 판정(['포기한 것'], 0).말.includes('포기한 것'));
  검('다 갖추고 새것이면 ✅', 판정([], 1).등급 === '✅');
  검('⭐ 다 갖춰도 오래 묵으면 🔴 — 문서는 스스로 안 고쳐진다', 판정([], 30).등급 === '🔴');
  검('참는 선을 바꿀 수 있다', 판정([], 30, 60).등급 === '✅');
  검('못 쟀으면 ⚠ 이지 ✅ 가 아니다', 판정([], null).등급 === '⚠');
  검('보는 것이 비어 있지 않다', 보는것.length >= 3);

  const 진 = 잰다.filter(([, v]) => !v);
  for (const [이름, v] of 잰다) console.log(`${v ? '✅' : '🔴'} ${이름}`);
  console.log(진.length ? `\n🔴 ${진.length}/${잰다.length} 떨어졌다` : `\n✅ 자가시험 ${잰다.length} 통과`);
  process.exit(진.length ? 1 : 0);
}

if (내가진입점) {
  console.log('■ 체크리스트 — 세 칸(한 것 · 진행 중 · 포기한 것)을 갖추고 살아 있나\n');
  let 흠 = 0, 틀없음 = 0;
  for (const p of 보는것) {
    let 글;
    try { 글 = fs.readFileSync(path.join(뿌리, p), 'utf8'); }
    catch { console.log(`   ⬜ ${p} — 파일이 없다`); continue; }
    let 마지막 = null;
    try {
      마지막 = execFileSync('git', ['log', '-1', '--format=%ad', '--date=short', '--', p],
        { cwd: 뿌리, encoding: 'utf8' }).trim() || null;
    } catch { /* 못 쟀다 */ }
    const 빠진 = 빠진칸(글);
    const p2 = 판정(빠진, 며칠묵었나(마지막));
    if (p2.등급 === '🔴') 흠++;
    if (p2.등급 === '⬜') 틀없음++;
    console.log(`   ${p2.등급} ${p}`);
    console.log(`      ${p2.말}${마지막 ? ` · 마지막 손댄 날 ${마지막}` : ''}`);
  }
  console.log(`\n${흠 ? `🔴 손볼 것 ${흠}개` : '✅ 세 칸이 다 서 있다'}`
    + (틀없음 ? ` · 틀을 아직 안 넣은 것 ${틀없음}개` : ''));
  console.log('\n⭐ 사장님 지시 — 「일을 마무리할 때마다, 업무시간이 끝날 때마다 업데이트」');
  process.exit(흠 ? 1 : 0);
}
