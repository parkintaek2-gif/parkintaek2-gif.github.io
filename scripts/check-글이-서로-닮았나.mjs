export const 못박은_거의같은몫 = 0;
/* 2026-10-05 제대로 잰 값 — 같은 말끼리 27쌍의 가운뎃값 46%. 선은 50%로 둔다.
   ⚠ 「선 아래니 괜찮다」가 아니다 — 올라가는지를 본다. */

/**
 * 글에서 «견줄 조각»을 뽑는다.
 *
 * 🔴🔴 [2026-10-05 16:3x · 5번] **한자·가나를 통째로 버리고 있었다.**
 *   처음에 `[^가-힣A-Za-z0-9]` 로 갈랐더니 중국어·일본어 본문이 **하나도 안 남았다.**
 *   중국어 글 두 편을 재니 「겹친 낱말 61 · A만 1 · B만 1」 이 나왔는데,
 *   그 63개는 전부 숫자와 로마자였다 — **본문은 재지도 않고 97% 라고 적고 있었다.**
 *   ⛔ 오늘 자를 의심해서 고친 것이 이것으로 다섯 번째다.
 *
 * ⚠ 중국어·일본어는 **낱말 사이에 빈칸이 없다.** 그래서 낱말로 못 가른다.
 *   ⇒ 한자·가나는 **두 글자씩 겹쳐 가며**(2-gram) 조각을 낸다. 글 비교의 흔한 방법이다.
 *   한글·로마자는 빈칸이 있으므로 낱말 그대로 쓴다.
 */
export function 낱말뽑기(글) {
  const s = String(글 ?? '');
  const 것 = new Set();

  /* ① 빈칸으로 갈리는 말 — 한글·로마자·숫자 */
  for (const w of s.split(/[^가-힣A-Za-z0-9]+/)) if (w.length > 1) 것.add(w);

  /* ② 빈칸이 없는 말 — 한자·히라가나·가타카나는 두 글자씩 겹쳐 가며 자른다 */
  const 씨제이케이 = /[぀-ヿ㐀-䶿一-鿿豈-﫿]/;
  for (const 덩이 of s.match(/[぀-ヿ㐀-䶿一-鿿豈-﫿]+/g) ?? []) {
    if (덩이.length === 1) { 것.add(덩이); continue; }
    for (let i = 0; i + 2 <= 덩이.length; i++) 것.add(덩이.slice(i, i + 2));
  }
  void 씨제이케이;
  return 것;
}

/**
 * 두 글이 얼마나 겹치나 — 자카드(겹친 것 ÷ 합친 것).
 * ⛔ 「한쪽에 든 몫」으로 재면 짧은 글이 늘 닮아 보인다. 합집합으로 나눈다.
 */
export function 닮은몫(가, 나) {
  const a = 낱말뽑기(가); const b = 낱말뽑기(나);
  if (!a.size || !b.size) return null;          /* ⛔ 못 재면 null. 0 이 아니다 */
  let 겹침 = 0;
  for (const w of a) if (b.has(w)) 겹침 += 1;
  return Math.round((겹침 / (a.size + b.size - 겹침)) * 100);
}

/** 가운뎃값 — 평균은 유난히 닮은 한 쌍에 끌려간다 */
export function 가운뎃값(수들) {
  const s = (수들 ?? []).filter((n) => Number.isFinite(n)).sort((a, b) => a - b);
  if (!s.length) return null;
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : Math.round((s[m - 1] + s[m]) / 2);
}

/** 글자가 아닌 것을 걷고 손님이 읽는 글만 남긴다 */
export function 본글(글) {
  return String(글 ?? '')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/* ─────────────────────────── 자가시험 ─────────────────────────── */
function 자가시험() {
  let 흠 = 0;
  const 본다 = (이름, 맞나) => { console.log(`  ${맞나 ? '✅' : '🔴'} ${이름}`); if (!맞나) 흠 += 1; };

  본다('한 글자는 버린다', !낱말뽑기('가 나다 라').has('가'));
  /* 🔴🔴 한자·가나를 안 버린다 — 이것이 없어서 중국어·일본어 글을 재지도 않고 있었다 */
  본다('🔴 한자를 두 글자씩 자른다',
    낱말뽑기('八字命理').has('八字') && 낱말뽑기('八字命理').has('字命'));
  본다('🔴 가나도 자른다', 낱말뽑기('しちゅう').has('しち'));
  본다('⛔ 한자가 든 글이 빈손으로 나오지 않는다', 낱말뽑기('这是一篇中文文章').size > 3);
  본다('🔴 한자 글 둘이 다르면 100%가 아니다',
    닮은몫('这是甲子年的说明', '这是乙丑年的说明') < 100);
  본다('같은 글은 100%', 닮은몫('가나 다라 마바', '가나 다라 마바') === 100);
  본다('아주 다른 글은 0%', 닮은몫('가나 다라', '마바 사아') === 0);
  /* 🔴 짧은 글이 늘 닮아 보이면 안 된다 — 합집합으로 나누는 까닭 */
  본다('🔴 짧은 글이 긴 글에 통째로 들어도 100% 가 아니다',
    닮은몫('가나 다라', '가나 다라 마바 사아 자차 카타') < 50);
  본다('⛔ 못 재면 null 이다 — 0 이 아니다', 닮은몫('', '가나') === null && 닮은몫(null, null) === null);

  본다('가운뎃값을 센다', 가운뎃값([10, 50, 90]) === 50);
  본다('짝수면 가운데 둘의 평균', 가운뎃값([10, 20, 30, 40]) === 25);
  본다('⛔ 빈 것이면 null', 가운뎃값([]) === null && 가운뎃값(null) === null);
  /* 🔴 평균이면 90 에 끌려간다 — 가운뎃값을 쓰는 까닭 */
  본다('🔴 유난한 한 쌍에 안 끌려간다', 가운뎃값([10, 10, 10, 90]) === 10);

  본다('표와 대본을 걷는다',
    본글('<p>가나</p><script>var x="다라";</script>') === '가나');
  본다('주석을 걷는다', 본글('<!-- 다라 --><p>가나</p>') === '가나');

  /* 🔴 말 가리기 — 말이 다른 글끼리 견주면 수가 거짓으로 내려간다 */
  const 말보기 = (길) => (/-(en|zh|ja)$/.exec(길)?.[1] ?? 'ko');
  본다('🔴 글 주소에서 말을 가린다',
    말보기('/content/star-q1-saju-ja') === 'ja' && 말보기('/content/star-q1-saju') === 'ko');
  본다('⛔ 말 이름이 가운데 있는 것에 속지 않는다', 말보기('/content/japan-saju') === 'ko');

  console.log(흠 ? `\n🔴 흠 ${흠}` : '\n✅ 자가시험 전부 통과');
  process.exit(흠 ? 1 : 0);
}

