import process from 'node:process';

/** 🔴 못 박은 선 — 이보다 «닮아지면» 빨간불이다. 좋아지면 내려 적는다 */
export const 못박은_닮은몫 = 60;

/**
 * 🔴🔴 **가운뎃값만 보면 「사실상 같은 글」을 놓친다.**
 *   2026-10-05 실측 — 가운뎃값은 53% 로 선 아래인데,
 *   zh·ja 의 스타 글끼리는 **94~95%** 였다. 사실상 같은 글이다.
 *   구글은 그런 묶음에서 한 장만 남기고 나머지를 버린다 — 나머지는 수집조차 안 온다.
 * ⇒ 가운뎃값과 **따로** 「거의 같은 쌍이 몇이나 되나」를 센다.
 */
export const 거의같은선 = 85;
/**
 * 거의 같은 쌍의 몫 — 이보다 많으면 빨간불.
 * 🔴 2026-10-05 첫 실측 **22%** (같은 말끼리 27쌍 가운데 6쌍) — **여섯 쌍이 다 ja·zh 였다.**
 *   한국어 글끼리는 거의 같은 쌍이 없었다. 바깥말 글이 틀을 더 그대로 쓰고 있다는 뜻이다.
 * ⛔ 이 수를 올리려면 까닭을 여기에 적는다.
 */
export const 못박은_거의같은몫 = 22;
/* 2026-10-05 첫 실측 — 틀로 찍은 글끼리 가운뎃값 54%. 아직 선 아래다.
   ⚠ 「선 아래니 괜찮다」가 아니다. 50%대도 낮지 않다 — 내려가는지를 본다. */

/** 글에서 낱말을 뽑는다 — 두 글자 아래는 버린다(조사·관사가 다 겹친다) */
export function 낱말뽑기(글) {
  return new Set(String(글 ?? '')
    .split(/[^가-힣A-Za-z0-9]+/)
    .filter((w) => w.length > 1));
}

/**
 * 두 글이 얼마나 겹치나 — 자카드(겹친 것 ÷ 합친 것).
 * ⛔ 「한쪽에 든 몫」으로 재면 짧은 글이 늘 닮아 보인다. 합집합으로 나눈다.
 */
export function 닮은몫(가, 나) {
  const a = 낱말뽑기(가); const b = 낱말뽑기(나);
  if (!a.size || !b.size) return null;          /* ⛔ 못 재면 null. 0 이 아니다 */
  let 겹침 = 0;
  for (const w of a) if (b.has(w)) 겹침 += 1;
  return Math.round((겹침 / (a.size + b.size - 겹침)) * 100);
}

/** 가운뎃값 — 평균은 유난히 닮은 한 쌍에 끌려간다 */
export function 가운뎃값(수들) {
  const s = (수들 ?? []).filter((n) => Number.isFinite(n)).sort((a, b) => a - b);
  if (!s.length) return null;
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : Math.round((s[m - 1] + s[m]) / 2);
}

/** 글자가 아닌 것을 걷고 손님이 읽는 글만 남긴다 */
export function 본글(글) {
  return String(글 ?? '')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/* ─────────────────────────── 자가시험 ─────────────────────────── */
