  /* 🔴 짧은 글이 늘 닮아 보이면 안 된다 — 합집합으로 나누는 까닭 */
  본다('🔴 짧은 글이 긴 글에 통째로 들어도 100% 가 아니다',
    닮은몫('가나 다라', '가나 다라 마바 사아 자차 카타') < 50);
  본다('⛔ 못 재면 null 이다 — 0 이 아니다', 닮은몫('', '가나') === null && 닮은몫(null, null) === null);

  본다('가운뎃값을 센다', 가운뎃값([10, 50, 90]) === 50);
  본다('짝수면 가운데 둘의 평균', 가운뎃값([10, 20, 30, 40]) === 25);
  본다('⛔ 빈 것이면 null', 가운뎃값([]) === null && 가운뎃값(null) === null);
  /* 🔴 평균이면 90 에 끌려간다 — 가운뎃값을 쓰는 까닭 */
  본다('🔴 유난한 한 쌍에 안 끌려간다', 가운뎃값([10, 10, 10, 90]) === 10);

  본다('표와 대본을 걷는다',
    본글('<p>가나</p><script>var x="다라";</script>') === '가나');
