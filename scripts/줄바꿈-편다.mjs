/**
 * 줄바꿈펴기.mjs — 문단 «안»의 줄바꿈을 없애 한 문단을 한 줄로 만든다.
 *
 * 🔴 사장님 2026-10-22 「문장 줄바꿈 똑바로 해」
 * 중부매일 지침 v7 8번 — 「복사해 붙여 넣을 때 문단이 하나로 뭉치는 현상을 방지하기 위해
 *   모든 본문 문단과 요소 사이에 명확한 이중 개행을 적용」
 * ⇒ 문단 사이에는 빈 줄, 문단 «안»에는 줄바꿈이 없어야 한다.
 *   내가 80자쯤에서 손으로 끊어 놓으면 그 줄바꿈이 그대로 지면에 들어간다.
 *
 * ⛔ 목록(· 로 시작), 머리(■ [ ), 들여쓴 줄은 건드리지 않는다 — 거기는 줄바꿈이 뜻을 가진다.
 */
import fs from 'node:fs';

export function 편다(글) {
  const 문단 = String(글).split(/\n\s*\n/);
  return 문단.map((p) => {
    const 줄 = p.split('\n');
    /* 한 줄이면 그대로 */
    if (줄.length <= 1) return p;
    /* 목록·머리·들여쓰기가 섞인 덩어리는 손대지 않는다 */
    /* ⚠ 머리글은 «줄 전체»가 대괄호인 것만이다 — [본문] · [제목].
       `[중부매일 박인택 기자] 축구대표팀…` 처럼 뒤에 글이 이어지면 그것은 본문이다.
       그 줄을 건너뛰는 바람에 첫 문단만 안 펴졌다(2026-10-22 실측). */
    const 손대지않나 = 줄.some((l) => /^\s*[·\-*>#■⚠①②③④⑤]|^\s{2,}\S|^\[[^\]]*\]\s*$/.test(l));
    if (손대지않나) return p;
    return 줄.map((l) => l.trim()).filter(Boolean).join(' ');
  }).join('\n\n');
}

if (process.argv.includes('--자가시험')) {
  let 통 = 0; let 탈 = 0;
  const 참 = (이름, v) => { if (v) { 통++; } else { 탈++; console.log('🔴 ' + 이름); } };
  참('문단 안 줄바꿈을 편다', 편다('가나다\n라마바') === '가나다 라마바');
  참('문단 사이 빈 줄은 지킨다', 편다('가나\n다라\n\n마바\n사아') === '가나 다라\n\n마바 사아');
  참('⛔ 목록은 손대지 않는다', 편다('· 하나\n· 둘') === '· 하나\n· 둘');
  참('⛔ 머리글은 손대지 않는다', 편다('■ 제목\n내용') === '■ 제목\n내용');
  참('⛔ 줄 전체가 대괄호면 머리글이다', 편다('[제목]\n내용') === '[제목]\n내용');
  /* 🔴 [2026-10-22] 기자 크레딧이 `[` 로 시작한다는 이유로 첫 문단만 안 펴졌다 */
  참('✅ 기자 크레딧으로 시작하는 문단은 편다',
    편다('[중부매일 박인택 기자] 가나\n다라') === '[중부매일 박인택 기자] 가나 다라');
  참('⛔ 들여쓴 줄도', 편다('앞\n  들여쓴 것') === '앞\n  들여쓴 것');
  참('한 줄은 그대로', 편다('한 줄뿐') === '한 줄뿐');
  console.log(탈 ? '🔴 자가시험 ' + 탈 + '건 탈' : '✅ 자가시험 ' + 통 + ' 통과');
  process.exit(탈 ? 1 : 0);
}

const p = process.argv[2];
const 전 = fs.readFileSync(p, 'utf8');
const 후 = 편다(전);
fs.writeFileSync(p, 후, 'utf8');
const 센다 = (s) => s.split('\n').filter((l) => l.trim()).length;
console.log('글줄 ' + 센다(전) + ' → ' + 센다(후) + ' · 가장 긴 줄 ' +
  Math.max(...후.split('\n').map((l) => l.length)) + '자');
