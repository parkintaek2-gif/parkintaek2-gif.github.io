export const 표본선 = 20;        /* 10위 안 지면이 스무 장은 돼야 판정한다 */

/**
 * 🔴 [2026-10-06 · 1번 검수 반영] **「기대 120인데 0」을 그대로 외치지 않는다.**
 *
 * 1번: 「"기대 120명"이라는 구체적 숫자를 보고에 그대로 쓰면 실제보다 더 확정적으로
 *       들립니다. 새 도메인·브랜드 신뢰 없음을 감안하면 업계 평균보다 훨씬 낮을 수 있습니다」
 *
 * ⇒ 바깥에서 가져온 클릭률에 기대지 않는 수를 함께 낸다 —
 *   **「클릭이 0인 것이 이상하지 않으려면 참 클릭률이 얼마 아래여야 하나」**.
 *   이 수는 우리 노출만으로 나온다. 빌려 온 어림이 없다.
 *   (1-p)^노출 ≥ 0.05 를 푼 것이다. 즉 스무 번에 한 번은 이런 일이 나는 선.
 * ⛔ 노출이 0이면 null — 「0%」가 아니다.
 */
export function 영이자연스러운클릭률(노출, 선 = 0.05) {
  if (!노출 || 노출 <= 0) return null;
  return 1 - Math.pow(선, 1 / 노출);
}


/**
 * 한 사이트를 뭐라고 적을 것인가.
 * ⛔ 표본이 작으면 «판단 보류»다 — 「좋다」도 「나쁘다」도 아니다.
 */
export function 판정말(잰것, 선 = 표본선) {
  if (!잰것 || !잰것.장수) return '⚠ 못 쟀다';
  if (잰것.장수 < 선) return `⚠ 판단 보류 (10위 안이 ${잰것.장수}장뿐)`;
  const 필요 = 영이자연스러운클릭률(잰것.노출);
  if (잰것.클릭 === 0 && 필요 != null) {
    return `🔴 클릭 0 — 참 클릭률이 ${(필요 * 100).toFixed(2)}% 아래여야 자연스럽다`;
  }
  const 몫 = 잰것.기대 > 0 ? 잰것.클릭 / 잰것.기대 : null;
  if (몫 != null && 몫 < 0.5) return '🔴 기대의 절반에도 못 미친다';
  return '⬜ 기대 언저리';
}

