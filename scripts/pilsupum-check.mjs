/** 글에서 표식이 몇 번 나오나 — 겹치지 않게 센다 */
export function 세기(글, 표식) {
  if (!글 || !표식) return 0;
  let 수 = 0, i = 0;
  for (;;) {
    const j = 글.indexOf(표식, i);
    if (j < 0) return 수;
    수++; i = j + 표식.length;
  }
}

/**
 * 🔴🔴 교차 검증 — 사장님(2026-08-14):
 *   *「**교차 검증을 해. 아주 중요한 업무다. 이런 걸 실수하면 우린 시즌2, 3 등으로 발전할 수 없다**」*
 *
 * ⛔ 오늘 여덟 건이 **그때마다 검사를 통과했다.** 까닭은 하나다 —
 *    **만든 자리가 자기 검사를 만들어 자기를 통과시켰다.**
 * ⭐ 교차 검증의 핵심은 「다른 사람」이 아니라 **「다른 방법」**이다.
 *    같은 자를 남이 돌리면 결과가 똑같다. 만든 쪽은 소스를 보고, **재는 쪽은 결과물을 본다.**
 */
export function 교차됐나(줄) {
  const 만든 = (줄['만든 자리'] || '').trim();
  const 잰 = (줄['잰 자리'] || '').trim();
  if (!만든 || !잰) return { 됐나: false, 까닭: '만든 자리·잰 자리를 안 적었다' };
  if (만든 === 잰) return { 됐나: false, 까닭: `만든 자리가 자기를 쟀다(${만든})` };
  return { 됐나: true, 까닭: '' };
}

/**
 * 한 줄을 판정한다.
 *
 * 🔴🔴 [2026-08-17 · 사장님] 「**규칙을 제대로 바꿔라**」 · 「1번과 2번은 규칙이 아니면 뭐지?」
 *   ⛔ 2번이 처음에 ①을 「셈 오류」로 잘못 갈랐습니다. 사장님이 바로잡으셨습니다.
 *      **일곱 중 다섯이 한 병입니다 — 「손님이 무엇을 보는지 만든 자리가 제 맘대로 정했다」.**
 *        ①③④⑤  보여야 할 것을 **제 맘대로 감췄다**
 *        ②       안 보여야 할 것을 **제 맘대로 내보냈다**
 *   ⭐ 그러니 자물쇠는 **양쪽**을 막아야 합니다. 한쪽만 막으면 반대쪽으로 샙니다.
 *
 * 표의 「눈에」 칸
 *   (빈칸)   판에 있기만 하면 된다      — 예전과 같다
 *   보여야   **손님 눈에 보여야** 한다   — 접힘·숨김·모드로 막힘은 0 이다
 *   없어야   **손님 눈에 없어야** 한다   — 하나라도 보이면 빨간불
 */
export function 재기(글, 줄) {
  const 눈에 = (줄['눈에'] || '').trim();
  const 최소 = Number(줄['최소 개수'] || 1);
  if (글 == null) return { 됐나: false, 센것: 0, 최소, 까닭: '결과물을 못 가져왔다' };
  const 센것 = 세기(글, 줄['세는 표식']);

  if (눈에 === '없어야') {
    if (센것 > 0) return { 됐나: false, 센것, 최소: 0, 까닭: '**없어야 하는데 보인다**' };
    return { 됐나: true, 센것: 0, 최소: 0, 까닭: '' };
  }
  if (센것 < 최소) return { 됐나: false, 센것, 최소, 까닭: 센것 === 0 ? '아예 없다' : '모자란다' };
  return { 됐나: true, 센것, 최소, 까닭: '' };
}

