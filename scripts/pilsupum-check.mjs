/** 결과물을 가져온다 — 주소면 두드리고, 아니면 파일을 읽는다 */
async function 가져오기(곳) {
  if (/^https?:\/\//.test(곳)) {
    try {
      const r = await fetch(곳, { redirect: 'follow' });
      if (!r.ok) return null;              // 500·404 면 「안 나간 것」이다
      return await r.text();
    } catch { return null; }
  }
  try { return fs.readFileSync(곳, 'utf8'); } catch { return null; }
}

/**
 * 🔴 **모자랄 때만 진짜 크롬으로 다시 잰다.**
 *
 * ⛔ 이 자의 원래 흠 — `fetch` 로만 재서 **JS 가 그리는 것을 못 봤습니다.**
 *    푸터·다국어·이벤트 배너가 다 JS 로 그려집니다.
 *    그래서 오늘 제가 「0곳」이라고 네 번 잘못 알렸습니다.
 *
 * ⭐ 그렇다고 늘 크롬을 띄우지는 않습니다 —
 *    이 기계는 램이 1.3GB 밖에 안 남고, 관문은 배포마다 돕니다.
 *    **빠른 것으로 먼저 재고, 모자랄 때만** 크롬을 띄웁니다.
 *    있으면 빨리 끝나고, 없다고 할 때만 값을 치릅니다. 헛경보는 그때 나기 때문입니다.
 */
async function 다시재기(곳, 줄) {
  if (!/^https?:\/\//.test(곳)) return null;      // 파일은 JS 가 없다. 다시 잴 것 없다
  try {
    const { 재기: 화면재기 } = await import('./live-check.mjs');
    const r = await 화면재기(곳, [줄['세는 표식']]);
    const v = r.셈[줄['세는 표식']];

    /* 🔴🔴 [2026-08-17 · 사장님] 「**규칙을 제대로 바꿔라**」
       ─────────────────────────────────────────────────────────
       [뚫린 구멍] 여기서 `Math.max(보이는곳, 판에)` 를 썼다.
         ⛔ 그래서 **접혀 있어도 통과**했다. 판에만 있으면 실린 것으로 쳤다.
         🔴 사장님이 화내신 셋이 정확히 그 구멍으로 빠져나갔다 —
            ③ 대운 그래프가 눌러야 보임
            ④ 「궁으로 본 가족운」·「세운 3년치」가 전문가 모드에서만 보임
            ⑤ 전문용어해설이 사라짐
         ⭐ 셋 다 **글자는 판에 있었다.** 손님 눈에만 없었다.
       [바꾼 규칙] 표의 **「눈에」 칸**이 「보여야」면 **innerText 만** 센다.
         접힌 것·숨긴 것·모드로 막은 것은 **0** 이다.
       ⛔ 이 자리를 다시 Math.max 로 되돌리지 말 것. 되돌리는 순간 같은 일이 난다. */
    const 눈에 = (줄['눈에'] || '').trim();
    const 센것 = (눈에 === '보여야' || 눈에 === '없어야') ? v.보이는곳 : Math.max(v.보이는곳, v.판에);
    return { 센것, 잰법: 눈에 ? '눈' : '화면' };
  } catch {
    return null;                                   // 크롬을 못 띄우면 첫판 그대로 간다
  }
}

const 고른유닛 = (() => {
  const i = process.argv.indexOf('--유닛');
  return i > 0 ? process.argv[i + 1] : null;
})();

const 글 = fs.readFileSync('docs/필수품-표.tsv', 'utf8').trim().split('\n');
