let 줄들 = 글.slice(1)
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => Object.fromEntries(l.split('\t').map((v, i) => [머리[i], v])));
if (고른유닛) 줄들 = 줄들.filter((r) => r.유닛 === 고른유닛);

console.log(`\n필수품 ${줄들.length}가지 — **결과물에서** 셉니다\n`);
