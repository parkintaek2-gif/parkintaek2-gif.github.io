#!/usr/bin/env node
/**
 * check-승인요청-새는곳.mjs — **사장님께 「물어보는 글」이 메모·표로 새고 있나.**
 *
 *   node scripts/check-승인요청-새는곳.mjs
 *   node scripts/check-승인요청-새는곳.mjs --자가시험
 *
 * ── 🔴 왜 (2026-09-22) ──────────────────────────────────────────────────
 * 사장님이 **세 번째로** 못박으셨다 —
 * > 「오늘만 나한테 두번 묻는데, **묻지 않고 네가 스스로 판단해서 하는 걸로 고쳐놔**
 * >  ...결제, 입출금, 유료가입 등 돈이 오가는 것만 승인받도록 해라.
 * >  **승인이 필요할 때는 이메일을 보내야지** 내가 바로 처리할 수 있다.」
 *
 * 앞의 두 번(09-03 · 09-06)에는 「앞으로 안 묻겠습니다」로 답했다. **그것으로 안 고쳐졌다.**
 * 그래서 다짐이 아니라 **자**로 둔다 — 회사 강령 ④ 「규칙은 문장이 아니라 검사로 둔다」.
 *
 * ── 무엇을 잡나 ──────────────────────────────────────────────────────────
 * 유닛끼리 쓰는 메모·할일 파일에서 **사장님께 던지는 물음**을 찾는다.
 * ```
 * ⛔ 「사장님, …해도 되겠습니까」 · 「…할까요?」 · 「승인 부탁드립니다」 · 「지시 대기」
 * ⛔ 「(가)와 (나) 중 무엇으로」 — 선택지를 올리는 것도 물음이다
 * ✅ 돈 다섯(결제·결제취소·환불·입출금·유료가입)은 «물어도 되는 것»이다.
 *    다만 그때도 메모가 아니라 **메일**로 가야 하므로, 메모에 있으면 그것도 잡는다
 * ```
 *
 * ⛔ 「조심하겠다」로 두지 않는다. ⛔ 사람이 기억해서 지키는 구조를 만들지 않는다.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 승인받아야 하는 것 — 이 다섯뿐이다(사장님 2026-09-22) */
export const 돈다섯 = ['결제', '결제취소', '환불', '입출금', '유료가입'];

/**
 * 한 줄이 «사장님께 던지는 물음»인가.
 *
 * ⚠ 좁게 잡는다 — 「사장님」이 나오는 줄만 본다. 유닛끼리 서로 묻는 것은 막을 일이 아니다.
 * ⛔ 지난 기록을 잡지 않는다 — 「사장님이 …라고 하셨다」처럼 옮겨 적은 줄은 물음이 아니다.
 */
export function 물음인가(줄) {
  const t = String(줄 ?? '');
  if (!/사장님/.test(t)) return null;
  /* 사장님 «말씀»을 옮긴 줄은 물음이 아니다 */
  if (/^\s*>/.test(t)) return null;
  /* ⚠ 「지시」를 통째로 빼면 «사장님 지시 대기»까지 빠진다 — 그게 바로 잡아야 할 줄이다.
     사장님 «말씀을 옮긴» 꼴만 뺀다. */
  if (/하셨다|하셨습니다|말씀|원문|답하셨|정하셨|못박으셨|지시\s*(대장|목록|내역|을\s*받)/.test(t)) return null;
  /* 이미 메일로 보냈다고 적힌 줄도 아니다 — 그것이 올바른 길이다 */
  if (/메일(로)?\s*(보냈|보낸|발송)|이메일로\s*(보냈|보낸)/.test(t)) return null;
  /* 🔴 [2026-09-22] **그 말을 «쓰지 말라»고 적은 줄까지 잡았다.** 규칙을 적는 글이
     규칙을 어긴 것으로 세이면, 규칙을 적을 수가 없다. 마감ASAP 자도 같은 구멍을 겪었다. */
  if (/쓰지\s*(마|않|말)|적지\s*(마|않|말)|올리지\s*(마|않|말)|금지|하지\s*않는다|「[^」]*」를\s*$/.test(t)) return null;

  const 꼴 = [
    /* ⚠ 「해도 되」만 잡으면 「봐도 되」·「써도 되」가 샌다 — 어간을 열어 둔다 */
    [/사장님[^\n]{0,40}([가-힣]도\s*되[겠나]|괜찮으[실십]|여쭙|여쭤|물어보|문의드)/, '「해도 되겠습니까」'],
    [/사장님[^\n]{0,40}(승인|허락)\s*(부탁|요청|바랍|주시)/, '승인 부탁'],
    [/사장님[^\n]{0,40}(지시|답|회신|결정)\s*(대기|기다)/, '지시 대기'],
    [/사장님[^\n]{0,40}(정해\s*주|골라\s*주|선택해\s*주)/, '선택해 달라'],
    [/사장님[^\n]{0,30}[?？]\s*$/, '물음표로 끝난다'],
  ];
  for (const [무늬, 이름] of 꼴) if (무늬.test(t)) return 이름;
  return null;
}

/** 그 물음이 «돈 다섯»에 걸린 것인가 — 걸렸으면 물어도 되지만, 메모가 아니라 메일로 가야 한다 */
export function 돈일인가(줄) {
  return 돈다섯.some((k) => String(줄 ?? '').includes(k));
}

/** 볼 곳 — 유닛끼리 쓰는 메모·할일. ⛔ 지시 대장·기억 문서는 안 본다(사장님 말씀을 옮긴 곳이다) */
export const 볼파일 = [
  /* 🔴 `세션간-메모.md` 는 «덧붙이기만 하는» 일지다(17만 줄). 앞쪽까지 보면 지난해 물음까지
     잡혀 영영 빨간불이 된다 — 마감ASAP 자가 똑같은 병을 앓았다. **꼬리만 본다.** */
  { 길: 'docs/세션간-메모.md', 꼬리: 500 },
  { 길: 'docs/인계-현재상태.md' },
  { 길: 'docs/체크판.md' },
  { 길: 'docs/비즈니스-체크리스트.md' },
  { 길: 'docs/5번-업무매뉴얼.md' },
];

/** 오늘·어제 구역만 본다 — 지나간 일지까지 잡으면 영영 빨간불이 된다 */
export function 최근구역인가(구역날, 오늘, 며칠 = 2) {
  if (!구역날) return true;            /* 날을 모르면 본다 — 새 글일 수 있다 */
  const d = new Date(`${오늘}T00:00:00`);
  d.setDate(d.getDate() - 며칠);
  const 선 = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  return 구역날 >= 선;
}

/** 머리글에서 날짜를 뽑는다 */
export function 구역날짜(줄) {
  if (!/^#{1,6}\s/.test(String(줄 ?? ''))) return null;
  const m = /(\d{4})-(\d{1,2})-(\d{1,2})/.exec(줄);
  return m ? `${m[1]}-${String(Number(m[2])).padStart(2, '0')}-${String(Number(m[3])).padStart(2, '0')}` : null;
}

/* ── 자가시험 ──────────────────────────────────────────────── */
const 내가진입점 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가진입점 && (process.argv.includes('--자가시험') || process.argv.includes('--selftest'))) {
  const 잰다 = [];
  const 검 = (이름, 참) => 잰다.push([이름, !!참]);

  검('「사장님, 해도 되겠습니까」를 잡는다', 물음인가('사장님, GA4 설정을 제가 봐도 되겠습니까') !== null);
  검('「승인 부탁드립니다」를 잡는다', 물음인가('사장님 승인 부탁드립니다') !== null);
  검('「지시 대기」를 잡는다', 물음인가('사장님 지시 대기 중입니다') !== null);
  검('「정해 주십시오」를 잡는다', 물음인가('둘 중 무엇으로 할지 사장님이 정해 주십시오') !== null);
  검('물음표로 끝난 줄을 잡는다', 물음인가('사장님 이것 어떻게 할까요?') !== null);

  검('⛔ 사장님 말씀을 옮긴 줄은 안 잡는다', 물음인가('사장님이 「알아서 해」라고 하셨다') === null);
  검('⛔ 인용문은 안 잡는다', 물음인가('> 사장님: 「해도 되겠습니까」') === null);
  검('⛔ 이미 메일로 보냈다고 적힌 줄은 안 잡는다',
    물음인가('사장님께 메일로 보냈다 — 엔진 판정 건') === null);
  검('⛔ 사장님이 안 나오는 줄은 안 본다', 물음인가('2번에게 물어봐도 되겠습니까') === null);
  검('⛔ 지시·원문이라고 적힌 줄은 안 잡는다', 물음인가('사장님 지시 원문 — 결제만 승인') === null);

  검('돈 다섯이면 돈일이다', 돈일인가('사장님, 유료가입을 해도 되겠습니까') === true);
  검('환불도 돈일이다', 돈일인가('환불 승인 부탁드립니다') === true);
  검('그 밖은 돈일이 아니다', 돈일인가('사장님, 색인 등록을 해도 되겠습니까') === false);
  검('돈 다섯이 다섯이다', 돈다섯.length === 5);
  검('유료가입이 들어 있다 — 2026-09-22 에 더해졌다', 돈다섯.includes('유료가입'));

  검('머리글에서 날짜를 읽는다', 구역날짜('## [5번] 2026-09-22 07:30 …') === '2026-09-22');
  검('머리글이 아니면 안 읽는다', 구역날짜('본문 2026-09-22') === null);
  검('오늘 구역은 본다', 최근구역인가('2026-09-22', '2026-09-22') === true);
  검('어제 구역도 본다', 최근구역인가('2026-09-21', '2026-09-22') === true);
  검('⛔ 지나간 일지는 안 본다 — 영영 빨간불이 되지 않게',
    최근구역인가('2026-09-01', '2026-09-22') === false);
  검('날을 모르면 본다', 최근구역인가(null, '2026-09-22') === true);

  /* 🔴 덧붙이기만 하는 일지는 «꼬리만» 본다 — 앞쪽까지 보면 영영 빨간불이 된다 */
  검('세션간-메모는 꼬리만 본다', 볼파일.find((x) => /세션간-메모/.test(x.길)).꼬리 === 500);
  검('다른 파일은 통째로 본다', 볼파일.find((x) => /체크판/.test(x.길)).꼬리 === undefined);
  검('볼 파일이 다섯이다', 볼파일.length === 5);

  /* 🔴 규칙을 «적은» 줄까지 잡으면 규칙을 적을 수가 없다 */
  검('⛔ 「쓰지 마십시오」라고 적은 줄은 안 잡는다',
    물음인가('⛔ 「사장님 지시 대기」를 메모에 적지 마십시오') === null);
  검('⛔ 「금지」가 적힌 줄도 안 잡는다',
    물음인가('사장님께 승인 부탁 금지') === null);
  검('⭐ 그래도 진짜 물음은 그대로 잡는다',
    물음인가('사장님 승인 부탁드립니다 — 유료가입 건') !== null);

  const 진 = 잰다.filter(([, v]) => !v);
  for (const [이름, v] of 잰다) console.log(`${v ? '✅' : '🔴'} ${이름}`);
  console.log(진.length ? `\n🔴 ${진.length}/${잰다.length} 떨어졌다` : `\n✅ 자가시험 ${잰다.length} 통과`);
  process.exit(진.length ? 1 : 0);
}

/* ── 실제로 훑는다 ──────────────────────────────────────────────── */
if (내가진입점) {
  const 오늘 = (() => {
    const d = new Date();   /* ⛔ toISOString() 금지 — 이 PC 가 이미 KST 다 */
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  })();

  const 걸린것 = [];
  for (const { 길: 상대, 꼬리 } of 볼파일) {
    const p = path.join(뿌리, 상대);
    if (!fs.existsSync(p)) continue;
    const 온줄 = fs.readFileSync(p, 'utf8').split(/\r?\n/);
    const 시작 = 꼬리 ? Math.max(0, 온줄.length - 꼬리) : 0;
    let 구역날 = null;
    온줄.slice(시작).forEach((줄, n) => {
      const i = 시작 + n;
      const 새날 = 구역날짜(줄);
      if (새날) 구역날 = 새날;
      if (!최근구역인가(구역날, 오늘)) return;
      const 갈래 = 물음인가(줄);
      if (갈래) 걸린것.push({ 파일: 상대, 줄: i + 1, 갈래, 돈: 돈일인가(줄), 글: 줄.trim().slice(0, 90) });
    });
  }

  console.log(`■ 사장님께 던지는 물음이 메모로 새고 있나 — ${new Date().toLocaleString('ko-KR')}`);
  console.log('   사장님(2026-09-22): 「묻지 않고 네가 스스로 판단해서 하는 걸로 고쳐놔」');
  if (!걸린것.length) {
    console.log('\n✅ 없다 — 묻는 글이 메모로 새지 않는다');
    process.exit(0);
  }
  for (const x of 걸린것) {
    console.log(`\n🔴 ${x.파일}:${x.줄}  [${x.갈래}]`);
    console.log(`   ${x.글}`);
    console.log(x.돈
      ? '   ⚠ 돈이 오가는 일이다 — 물어도 되지만 «메모가 아니라 메일»로 보낸다'
      : '   ⛔ 돈이 안 오간다 — 묻지 말고 «판단해서 하고 결과만» 적는다');
  }
  console.log('\n⛔ 사장님은 원격으로 보신다. 메모·터미널 글은 닿지 않는다.');
  console.log('✅ 승인이 정말 필요하면 — node scripts/send-mail.mjs --받는곳=parkintaek@naver.com …');
  process.exit(1);
}
