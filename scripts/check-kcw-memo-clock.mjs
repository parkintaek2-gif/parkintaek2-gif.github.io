#!/usr/bin/env node
/**
 * check-kcw-memo-clock.mjs — **메모에 적은 시각이 «시계»와 맞나.**
 *
 * ── 🔴 왜 (2026-09-01) ───────────────────────────────────────
 * 오늘 하루에 **세 번** 시각을 어림으로 적었다가 고쳤다.
 * ```
 * 「14:2x」로 써 두고 14:26 으로 채웠다 → 실제 14:21
 * 「14:5x」→ 14:51 로 채웠다          → 실제 14:49
 * 「15:2x」→ 15:25 로 채웠다          → 실제 15:23
 * ```
 * 세 번 다 **앞당겨** 적었다. 글을 쓰기 «전»에 본 시각을 쓰고, 다 쓰고 나서 안 고쳤다.
 *
 * ⛔ 왜 나쁜가 — 여섯 유닛이 한 메모에 시간순으로 쌓는다. 내 줄이 앞당겨져 있으면
 *   2번이 순서를 맞출 때 어긋나고, 「누가 먼저 알렸나」가 뒤집힌다.
 *   ⚠ 2번은 「전 유닛 활동 9~34분 이내」처럼 «시각으로» 우리가 살아 있는지 본다.
 *
 * ⭐ 내 기억에 「date 를 먼저 돌린다」가 이미 있었는데도 세 번 틀렸다.
 *   **기억으로 지키는 규칙은 또 어긴다. 검사로 옮긴다.**
 *
 * ── ⛔ 이 자가 지키는 것 ─────────────────────────────────────
 * ⛔ 고치지 «않는다» — 어긋난 줄을 보여 준다. 남의 유닛 줄은 손대지 않는다.
 * ⛔ 5번 줄만 본다. 남이 적은 시각을 내가 판정하지 않는다.
 * ⚠ 「몇 분까지 어긋나면 흠인가」를 한 곳에만 적는다.
 *
 * 쓰는 법
 *   node scripts/check-kcw-memo-clock.mjs --자가시험
 *   node scripts/check-kcw-memo-clock.mjs            (오늘 내 줄을 본다)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 이만큼 넘게 어긋나면 흠으로 본다. ⛔ 여기 한 곳에만 적는다 */
export const 봐주는분 = 5;

/** 아직 안 채운 자리 — 이건 «반드시» 흠이다 */
export const 빈자리꼴 = /\d{2}:\d?[xX×]/;

/**
 * 🔴 [2026-09-10 18:38 · 5번] **기준선.** 이 시각 뒤에 «새로» 적힌 것만 흠으로 센다.
 *
 * 까닭 — 이 자가 잡은 여덟 개가 전부 16:38 «전»에 적은 것이었다(12:0x ~ 15:4x).
 *   그 시각에 나는 습관을 바꿨다: 글을 다 쓴 «뒤»에 시각을 찍어 그 수를 적는다.
 *   ⛔ 지난 기록을 고쳐 쓰지 않는다 — 역사를 위조하는 일이다.
 *   ⛔ 그러나 다 지나간 일로 빨간불을 영원히 켜 두지도 않는다. 영원한 빨간불은
 *     그 옆의 «새 빨간불»을 안 보이게 만든다(같은 날 버전업 몫에서 겪었다).
 * ✅ 기준선 앞의 것은 ⬜ 기록으로 세어 보이기만 한다.
 *   감수 도장의 「기준선(이미 라이브)」과 같은 꼴이다.
 */
export const 기준선 = '16:38';

/** 그 줄의 시각이 기준선 뒤인가. 시각을 못 읽으면 null — 못 쟀다이고 흠으로 세지 않는다 */
export function 기준선뒤인가(줄, 기준 = 기준선) {
  const m = String(줄 ?? '').match(/(\d{2}):(\d?[\dxX×])/);
  if (!m) return null;
  const 시 = Number(m[1]);
  const 분 = Number(String(m[2]).replace(/[xX×]/, '0'));
  const [기준시, 기준분] = 기준.split(':').map(Number);
  if (!Number.isFinite(시) || !Number.isFinite(분)) return null;
  return 시 * 60 + 분 >= 기준시 * 60 + 기준분;
}

/** 줄에 찍힌 날짜 도장(YYYY-MM-DD). 없으면 null */
export const 날짜꼴 = /(20\d{2}-\d{2}-\d{2})/;
export function 줄의날짜(줄) {
  const m = String(줄 ?? '').match(날짜꼴);
  return m ? m[1] : null;
}

/**
 * 🔴🔴 [2026-09-05] **이 자가 넉 달치를 「오늘」로 세고 있었다.**
 *
 * 고치기 «전» 코드는 이랬다 —
 * ```js
 * const 시작 = 메모.indexOf(오늘);      // ⛔ «첫» 등장
 * const 줄들 = 메모.slice(시작).split('\n');
 * ```
 * `indexOf` 는 첫 등장을 잡는다. 그런데 우리 메모는 **과거 글이 미래 날짜를 미리
 * 적는 일이 흔하다**(「9/5 에 다시 잰다」·「9/25 전에 손대지 않는다」 같은 예고).
 * 그 한 줄 때문에 **그 지점부터 파일 끝까지 전부가 「오늘」이 됐다.**
 * ⇒ 9/5 에 재니 「안 채운 자리 98개」가 나왔는데 **98개가 다 옛날 것**이었고,
 *   이 자는 그 뒤로 **영영 빨간불**이라 매시 체크에서 헛일을 시켰다.
 *
 * ⭐ 고친 법 — 자리를 자르지 않고 **줄마다 「지금 어느 날짜 구역인가」를 따라간다.**
 *   날짜 도장이 나오면 구역을 바꾸고, 구역이 오늘일 때만 센다.
 * ⚠ 날짜 도장이 나오기 «전»의 줄은 어느 날인지 모른다 — **오늘로 안 친다.**
 *   못 잰 것을 오늘로 세면 이 결함이 그대로 돌아온다.
 */
/**
 * 이 줄이 «구역을 바꿀 자격»이 있나.
 *
 * ⭐ 메모의 날짜 도장은 늘 제목에 있다 — `## [5번] 2026-09-07 …`.
 *   글 한가운데(표·목록·따옴글)에 적힌 날짜는 «이야기»다. 구역이 아니다.
 * ⛔ 넓게 잡지 않는다. 「#」로 시작하는 줄과, «날짜로 시작하는» 줄만이다.
 */
export function 구역바꾸는줄인가(줄) {
  const s = String(줄 ?? '');
  /**
   * 🔴 [2026-09-07 20:1x] **제목 줄이면 다 되는 것도 아니었다.**
   *   내가 쓴 소제목이 이랬다 —
   *     `### … **A/B 를 걸었습니다** (다시잴날 2026-09-28)`
   *   제목 줄이고 날짜가 들어 있으니 구역이 9/28 로 넘어갔고,
   *   **그 뒤 제목 18개가 통째로** 오늘에서 빠졌다. 내 시각 실수 셋이 그래서 안 잡혔다.
   *
   * ⭐ 구역 도장은 «제목의 머리»에 있다 — `## [5번] 2026-09-07 …` 꼴.
   *   제목 «뒤쪽»에 이야기로 끼어든 날짜는 도장이 아니다.
   * ⛔ 그래서 날짜 앞에 올 수 있는 것을 못박는다 — 우물표(#), 공백, 그리고 [ … ] 딱지뿐.
   */
  if (/^\s*#+\s*(\[[^\]]*\]\s*)?20\d{2}-\d{2}-\d{2}/.test(s)) return true;
  if (/^\s*20\d{2}-\d{2}-\d{2}/.test(s)) return true;  /* 날짜로 시작하는 줄 */
  return false;
}

export function 오늘줄만(메모줄들, 오늘) {
  const 뽑음 = [];
  let 지금구역 = null;
  for (const 줄 of 메모줄들) {
    /**
     * 🔴 [2026-09-07] **구역은 «제목 줄»에서만 바뀐다.**
     *   전에는 아무 줄에 날짜가 보이면 구역을 바꿨다. 그래서 내가 본문에
     *   「다시잴날 2026-09-28」 이라고 적은 한 줄이 **그 뒤 파일 끝까지를 9/28 구역으로**
     *   만들었고, 그 뒤에 쓴 오늘 줄이 전부 빠졌다. 시각 실수 셋이 그렇게 안 잡혔다.
     * ⚠ 이 함수 주석에 그 결함이 이미 적혀 있었다(9/5). 자리 자르기는 고쳤는데
     *   «구역을 바꾸는 조건»은 그대로여서 같은 결함이 다른 문으로 돌아왔다.
     */
    if (구역바꾸는줄인가(줄)) {
      const d = 줄의날짜(줄);
      if (d) 지금구역 = d;
    }
    if (지금구역 === 오늘) 뽑음.push(줄);
  }
  return 뽑음;
}

/**
 * 이 줄이 «내가 낸 제목»인가 — 한 자리에서만 판정한다.
 *
 * 🔴 [2026-09-07] 전에는 CLI 안에 무늬가 따로 굳어 있었고(`\[5번`),
 *   내줄시각() 의 무늬와 «서로 달랐다». 그래서 한쪽을 넓혀도 다른 쪽이 막았다.
 * ⛔ 같은 판정을 두 곳에 두지 않는다.
 */
export function 내가낸제목인가(줄) {
  const s = String(줄 ?? '').trim();
  if (!/^#{1,4}\s/.test(s)) return false;
  return /\[5번?(\s*→|\]|\()/.test(s);
}

/** 5번이 낸 줄에서 시각을 뽑는다. 없으면 null */
export function 내줄시각(줄) {
  const s = String(줄 ?? '');
  if (!s) return null;
  /**
   * 🔴 [2026-09-07 20:0x] **이 자가 내 줄을 «0개»로 셌다.**
   *   무늬가 「[5번」 만 봤는데, 나는 오늘부터 「[5 → 전체]」 꼴로 적고 있었다.
   *   ⇒ 그날 하루치 스물 몇 줄을 하나도 안 보고 「내가 낸 줄 0개」라고 냈다.
   *   그 사이 내가 시각을 «한 시간» 앞당겨 적은 것이 세 줄 있었고, 이 자가 못 잡았다.
   * ⛔ 「0개」를 「깨끗하다」로 읽으면 안 된다 — 이 자가 오늘 그 꼴이었다.
   */
  if (!/\[5번?(\s*→|\])/.test(s)) return null;          /* 5번이 «낸» 줄만 — 「[5 →」 꼴도 본다 */
  const m = s.match(/(\d{2}):(\d{2})/);
  if (!m) return null;
  const 시 = Number(m[1]); const 분 = Number(m[2]);
  if (시 > 23 || 분 > 59) return null;
  return { 시, 분, 분합: 시 * 60 + 분 };
}

/** 두 시각이 몇 분 어긋났나. 앞선 쪽이 음수 */
export function 어긋남분(적은분합, 진짜분합) {
  if (!Number.isFinite(적은분합) || !Number.isFinite(진짜분합)) return null;
  return 적은분합 - 진짜분합;
}

/** 흠인가. ⛔ 「앞당김」과 「늦춤」을 갈라 말한다 */
export function 흠인가(어긋남, 봐줌 = 봐주는분) {
  if (!Number.isFinite(어긋남)) return null;
  if (Math.abs(어긋남) <= 봐줌) return null;
  return 어긋남 > 0 ? '앞당겨 적었다' : '늦춰 적었다';
}

