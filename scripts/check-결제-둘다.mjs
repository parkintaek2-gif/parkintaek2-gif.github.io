import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
const 뿌리 = path.join(여기, '..');
const 마커방 = path.join(뿌리, 'docs', '고정업무-마커');
const 지난판 = path.join(뿌리, 'docs', '고정업무-마커', '.결제둘다-지난판.json');

/* ── 시각 — 이 PC 가 이미 KST 다 ────────────────────────────────────────────
   ⛔ toISOString() 을 쓰지 않는다. UTC 라 새벽에 날짜가 하루 어긋난다. */
export function 날짜글(d = new Date()) {
  return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0')
    + '-' + String(d.getDate()).padStart(2, '0');
}
export function 시각글(d = new Date()) {
  return String(d.getHours()).padStart(2, '0') + ':' + String(d.getMinutes()).padStart(2, '0');
}

/* ── 두 결제사 ────────────────────────────────────────────────────────────
   마커 이름이 서로 달라서 한쪽만 보고 「안 쟀다」로 읽혔다. 여기 한곳에 모은다. */
export const 결제사들 = [
  { 키: '토스', 이름: '토스 (KLifeMap)', 자: 'check-klifemap-payment.mjs',
    옛마커: /^(\d{4}-\d{2}-\d{2})-(\d{1,2})시-결제점검\.txt$/ },
  { 키: '페이팔', 이름: '페이팔 (SeoulMarkets)', 자: 'check-seoulmarkets-payment.mjs',
    옛마커: /^(\d{4}-\d{2}-\d{2})-(\d{1,2})시-서울마켓츠결제점검\.txt$/ },
];
const 함께마커 = /^(\d{4}-\d{2}-\d{2})-(\d{1,2})시-결제둘다\.txt$/;

/* ── 오늘 어느 시각에 쟀나 ────────────────────────────────────────────────
   ⚠ 묶기 «전»에 남은 옛 마커도 센다. 안 세면 오늘 오전이 통째로 빵꾸로 보인다. */
export function 잰시각(파일들, 오늘, 결제사) {
  const 잰것 = new Set();
  for (const f of 파일들) {
    for (const 틀 of [결제사.옛마커, 함께마커]) {
      const m = 틀.exec(f);
      if (m && m[1] === 오늘) 잰것.add(Number(m[2]));
    }
  }
  return [...잰것].sort((a, b) => a - b);
}

/** 오늘 «이미 지난» 시각 가운데 안 잰 것. 아직 오지 않은 시각은 빵꾸가 아니다. */
export function 빈시각(잰것, 지금시) {
  const 빈 = [];
  for (let h = 0; h <= 지금시; h += 1) if (!잰것.includes(h)) 빈.push(h);
  return 빈;
}

/* ── 사장님께 알릴 때인가 ─────────────────────────────────────────────────
   두 번 잇따라 막혔을 때만이다. 한 번은 그물이 흔들린 것일 수 있다. */
export function 알릴때인가(이번막힘, 지난막힘) {
  const 이번 = new Set(이번막힘);
  const 지난 = new Set(지난막힘 ?? []);
  return [...이번].filter((k) => 지난.has(k));
}

/* ── 한 자를 돌린다 ─────────────────────────────────────────────────────
 *
 * 🔴🔴 [2026-10-16 · 5번] **「시간이 모자라 확인하지 못한 것」을 「막혔다」로 읽고 있었다.**
 *
 *   21:41 과 21:50 두 판 모두 「페이팔이 두 번 잇따라 막혔다 — 매출이 0 이다」가 찍혔다.
 *   그 길로 사장님께 알릴 참이었다. 그런데 `check-seoulmarkets-payment.mjs` 를
 *   «직접» 돌려 보니 결과가 달랐다 —
 *   ```
 *   주문 만들기  ✅ 된다 (8XS16968CX717800W)
 *   손님 화면    ✅ 페이팔 단추 2개가 그려진다 · Total $2,990
 *   → ✅ 팔린다
 *   ```
 *   ⇒ 까닭은 아래 `timeout: 180000` 이었다. 페이팔 점검은 브라우저를 띄워 상품을
 *     눌러 보므로 3분을 넘긴다(실측 7분). 시간이 다 되면 spawnSync 가 프로세스를 죽이고
 *     `status` 를 null 로 둔다. 그것을 `status === 0` 이 아니라는 이유로 「막혔다」로 셌다.
 *
 * ⛔ **「확인하지 못했다」와 「막혔다」는 다른 말이다.** 섞으면 멀쩡한 결제를 두고
 *   사장님께 「매출 0」이라고 알리게 된다 — 늑대가 왔다고 두 번 외치면 세 번째를 안 믿으신다.
 * ✅ 그래서 ① 시간을 넉넉히 주고 ② 시간이 다 된 것은 «못 쟀다»로 따로 돌려준다.
 */
export const 넉넉한시간 = 15 * 60 * 1000;   /* 브라우저를 띄워 눌러 보는 자가 있다 */

function 돌린다(자, 밀리초 = 넉넉한시간) {
  const r = spawnSync(process.execPath, [path.join(여기, 자)], {
    cwd: 뿌리, encoding: 'utf8', timeout: 밀리초, maxBuffer: 32 * 1024 * 1024,
  });
  const 글 = String(r.stdout ?? '') + String(r.stderr ?? '');
  /* ⭐ 시간이 다 되어 죽었나 — 그때 status 는 null 이고 signal 이 찍힌다 */
  const 시간다됨 = r.status === null && (r.signal != null || /ETIMEDOUT/.test(String(r.error ?? '')));
  /* ⭐ 자가 스스로 「확인하지 못했다」고 댄 것 — 종료코드 2.
     🔴 [2026-10-16] 페이팔 점검이 SocketError 로 죽어 1 을 내고 있었다. 1 은 「막혔다」다.
       ⇒ 그 자에 전역 오류 처리기를 두어 «못 쟀다»를 2 로 내게 했다. 여기서 그것을 받는다. */
  const 제가못쟀다 = r.status === 2;
  return {
    됐나: r.status === 0,
    못쟀나: 시간다됨 || 제가못쟀다,
    글,
    끝줄: 글.trim().split('\n').filter(Boolean).slice(-1)[0] ?? '',
  };
}

async function 잰다() {
  const 이제 = new Date();
  const 오늘 = 날짜글(이제);
  const 지금시 = 이제.getHours();
  console.log('■ 결제 점검 (둘 다) — ' + 오늘 + ' ' + 시각글(이제));
  console.log('   ⭐ 재는 것은 「서버가 떠 있나」가 아니라 «손님이 살 수 있나»다\n');

  const 결과 = [];
  for (const p of 결제사들) {
    const r = 돌린다(p.자);
    결과.push({ ...p, ...r });
    /* 자식 자의 «판정 줄»만 뽑아 보인다 — 화면을 두 번 쏟지 않는다 */
    const 판정줄 = r.글.split('\n').filter((x) => /팔린다|매출0|줄었다|🔴/.test(x)).slice(-3);
    /* ⭐ 세 갈래로 가른다 — 팔린다 / 확인하지 못했다 / 막혔다 */
    console.log('   ' + (r.됐나 ? '✅' : (r.못쟀나 ? '⬜' : '🔴')) + ' ' + p.이름);
    for (const l of 판정줄) console.log('      ' + l.trim());
    if (r.못쟀나) {
      console.log('      ⬜ 시간이 다 되어 «확인하지 못했다» — 막힌 것이 아니다');
      console.log('      ⚠ 이 자는 브라우저를 띄워 눌러 본다. 오래 걸리면 다시 재야 한다');
    } else if (!r.됐나) {
      console.log('      ⛔ 이 자가 1 로 끝났다 — 위 줄을 그대로 읽는다');
    }
  }

  /* ── 마커 ──────────────────────────────────────────────────────────── */
  fs.mkdirSync(마커방, { recursive: true });
  const 이름 = 오늘 + '-' + String(지금시).padStart(2, '0') + '시-결제둘다.txt';
  const 파일들 = fs.readdirSync(마커방);
  const 빈칸 = {};
  for (const p of 결제사들) 빈칸[p.키] = 빈시각(잰시각(파일들, 오늘, p), 지금시 - 1);

  /* 지난 시각을 놓쳤나 — 조용히 넘어가지 않는다 */
  const 지난시 = 지금시 - 1;
  const 놓친것 = 지난시 >= 0
    ? 결제사들.filter((p) => 빈칸[p.키].includes(지난시)).map((p) => p.키) : [];

  const 줄 = [
    '결제 점검 (둘 다) — ' + 오늘 + ' ' + 시각글(이제),
    /* 🔴🔴 [2026-10-26 23:5x · 5번] **마커가 「확인하지 못했다」를 「막혔다」로 적었다.**
       사장님: 「결제, 로그인이 가장 중요한데 왜 페이팔을 방치하나」
       23시 05분 마커에 「페이팔 : 🔴 막혔다」가 적혔고 나는 그대로 업무보고에 올렸다.
       그런데 바로 위 화면에는 「⬜ 시간이 다 되어 확인하지 못했다」가 찍혀 있었다 —
       **화면은 세 갈래인데 마커만 두 갈래였다.** 뒤에 읽는 사람은 마커만 본다.
       ⇒ 2026-10-16 에 화면에서 고친 그 잘못이 마커에 그대로 남아 있었다.
         한 곳을 고치면 그 값을 «적는 곳»까지 따라간다. */
    ...결과.map((r) => '  ' + r.이름 + ' : ' + (r.됐나 === true ? '팔린다'
      : (r.됐나 === false ? '🔴 막혔다' : '⬜ 확인하지 못했다 (막힌 것이 아니다)'))),
    ...결제사들.map((p) => '  오늘 빠진 시각 [' + p.키 + '] : '
      + (빈칸[p.키].length ? 빈칸[p.키].join('·') + '시' : '없다')),
    놓친것.length ? '  ⚠ 지난 ' + 지난시 + '시를 놓쳤다 — ' + 놓친것.join('·') : '  지난 시각까지 이어졌다',
    '  ⛔ 승인(capture)은 부르지 않았다',
  ].join('\n') + '\n';
  fs.writeFileSync(path.join(마커방, 이름), 줄);

  console.log('\n   오늘 빠진 시각');
  for (const p of 결제사들) {
    console.log('      ' + p.키 + ' : ' + (빈칸[p.키].length ? 빈칸[p.키].join('·') + '시' : '없다 ✅'));
  }
  console.log('   ✅ 마커 — docs/고정업무-마커/' + 이름);

  /* ── 두 번 잇따라 막혔으면 사장님께 ────────────────────────────────────
   * 🔴 [2026-10-16] **「확인하지 못했다」를 막힘으로 세지 않는다.**
   *   시간이 다 되어 죽은 것을 막힘으로 세어 「매출 0」을 두 번 알릴 뻔했다.
   *   멀쩡한 결제를 두고 그렇게 알리면, 정말 막혔을 때 그 알림을 안 믿게 된다. */
  const 이번막힘 = 결과.filter((r) => !r.됐나 && !r.못쟀나).map((r) => r.키);
  const 이번못잼 = 결과.filter((r) => r.못쟀나).map((r) => r.키);
  if (이번못잼.length) {
    console.log('\n   ⬜ ' + 이번못잼.join('·') + ' 는 «확인하지 못했다» — 막힘으로 세지 않는다');
    console.log('   ⇒ 그 자를 따로 돌려서 다시 잰다. 그 전에는 「막혔다」고 적지 않는다');
  }
  let 지난막힘 = [];
  try { 지난막힘 = JSON.parse(fs.readFileSync(지난판, 'utf8')).막힘 ?? []; } catch (e) { /* 첫 판 */ }
  fs.writeFileSync(지난판, JSON.stringify({ 때: 오늘 + ' ' + 시각글(이제), 막힘: 이번막힘 }));

  const 알릴것 = 알릴때인가(이번막힘, 지난막힘);
  if (알릴것.length) {
    console.log('\n   🔴🔴 ' + 알릴것.join('·') + ' 가 «두 번 잇따라» 막혔다 — 매출이 0 이다');
    console.log('   ⇒ 사장님께 알린다. 그리고 그 자리에서 진단·고침·배포한다(다음 시간으로 안 미룬다)');
    fs.writeFileSync(path.join(뿌리, 'docs', '결제-빨간불.txt'),
      오늘 + ' ' + 시각글(이제) + ' — ' + 알릴것.join('·') + ' 두 번 잇따라 막힘\n');
  } else if (이번막힘.length) {
    console.log('\n   ⚠ ' + 이번막힘.join('·') + ' 가 한 번 막혔다 — 다음 판에서 또 막히면 알린다');
  } else {
    try { fs.unlinkSync(path.join(뿌리, 'docs', '결제-빨간불.txt')); } catch (e) { /* 원래 없다 */ }
    console.log('\n   ✅ 둘 다 팔린다');
  }
  return 이번막힘.length ? 1 : 0;
}

/* ── 자가시험 ─────────────────────────────────────────────────────────── */
