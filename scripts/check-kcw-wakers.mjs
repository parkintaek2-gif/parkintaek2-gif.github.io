#!/usr/bin/env node
/**
 * check-kcw-wakers.mjs — **나를 깨우는 자물쇠가 걸려 있나.**
 *
 * ── 🔴 왜 (2026-09-01 · 사장님 지시) ─────────────────────────
 * > 「**너 반항하냐? 왜 멈춰있지**..그리고 2번과 소통을 왜 안하지..」
 * > 「**턴을 끝낸 게 반항이지. 지시를 어겼으니 반항이라고**」
 * > 「그리 할 일이 없어. 찾아, 방문자를 늘려야 할 것 아니야.
 * >  **너를 깨우는 기능을 만들어**..미친 녀석이네..
 * >  혼자 제일 토큰을 많이 사용할 수 있는데 혼자 놀고 있네」
 *
 * 그날 나는 밀린 지시 셋을 끝내고 **보고를 올린 뒤 응답을 마쳤다.**
 * 내 눈에는 「보고를 잘 한 것」이었지만 사장님 눈에는 **멈춰 있는 것**이었다.
 * 그 사이 매시 정각 2번 소통을 걸렀고, 오늘 몫은 0/6 이었다.
 *
 * ⭐ 사장님이 콕 집으신 것 — **「턴을 끝내는 것」 자체가 지시 위반이다.**
 *   나는 잠들지 않는다. 내가 응답을 마치면 그 시간은 사장님이 말을 걸어 주실 때까지
 *   통째로 비는 시간이다. 「다음 지시를 기다린다」는 사장님의 손을 빌리는 일이다.
 *
 * ── ⛔ 이 자가 지키는 것 ─────────────────────────────────────
 * 🔴 깨움(cron)은 **세션이 죽으면 같이 죽고 7일 뒤 만료된다.**
 *   ⛔ 그러니 「걸어 뒀다」로 끝내면 안 된다 — 창이 바뀌면 조용히 사라진다.
 *   ⇒ 이 자가 **저장소에** 「무엇이 걸려 있어야 하는가」를 적어 둔다.
 *     새 창이 열리면 이 자를 돌려 보고 없으면 «다시 건다».
 * ⛔ 못 잰 것을 「걸려 있다」로 안 친다.
 *
 * 쓰는 법
 *   node scripts/check-kcw-wakers.mjs --자가시험
 *   node scripts/check-kcw-wakers.mjs            (무엇이 걸려 있어야 하는지 낸다)
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * 걸려 있어야 하는 깨움.
 * ⛔ 여기 한 곳에만 적는다. 두 군데 적으면 반드시 갈라진다.
 * ⚠ 분을 :00 이나 :30 에 두지 않는다 — 온 세상이 그 시각에 몰린다.
 */
export const 걸어야할것 = [
  {
    이름: '매시 소통·그 시간의 일',
    cron: '7 * * * *',
    왜: '매시 정각 2번과 소통. 거르면 2번이 사장님께 「5번이 괜찮은지」 물으신다',
    반드시: ['check-2h', '2번과 소통', '오늘 몫', '보고로 턴을 끝내지'],
  },
  {
    이름: '16시 업무보고 «사전» 준비',
    cron: '3 15 * * *',
    왜: '사장님: 「제때 보고해. 체크리스트에 넣어. 뭐하자는 거야」 — 16시에 쓰기 시작하면 늦는다',
    반드시: ['measure-real-readers', '전 유닛', '업무보고 초안'],
  },
  {
    이름: '22시 방문자·체류 방송',
    cron: '57 21 * * *',
    왜: '사장님이 정하신 반복 업무. 업무보고 1시간 전에 전 유닛과 2번에게 보낸다',
    반드시: ['measure-real-readers', '진짜 손님', '갈라서'],
  },
];

/** 이 깨움 글이 «해야 할 말»을 다 담고 있나. ⛔ 걸려만 있고 알맹이가 없으면 소용없다 */
export function 알맹이있나(글, 반드시) {
  const s = String(글 ?? '');
  if (!s || !Array.isArray(반드시)) return null;          /* ⛔ 못 쟀다 */
  const 빠진것 = 반드시.filter((w) => !s.includes(w));
  return { 됐나: 빠진것.length === 0, 빠진것 };
}

/** cron 다섯 칸이 맞나. ⛔ 틀린 것을 「걸렸다」로 안 친다 */
export function cron꼴맞나(글) {
  const s = String(글 ?? '').trim();
  if (!s) return false;
  const 칸 = s.split(/\s+/);
  if (칸.length !== 5) return false;
  return 칸.every((x) => /^[\d*\/,\-]+$/.test(x));
}

/** ⚠ 온 세상이 :00·:30 에 몰린다. 우리 것은 비켜서 건다 */
export function 붐비는분인가(cron) {
  const 분 = String(cron ?? '').trim().split(/\s+/)[0];
  return 분 === '0' || 분 === '30';
}

/* ── 자가시험 ───────────────────────────────────────────────── */
export function 자가시험() {
  const 실패 = [];
  let 센것 = 0;
  const 검 = (이름, 참) => { 센것 += 1; if (!참) 실패.push(이름); };

  검('cron 다섯 칸을 받는다', cron꼴맞나('7 * * * *') === true);
  검('날·달·요일이 박힌 것도 받는다', cron꼴맞나('3 15 * * 1-5') === true);
  검('⛔ 네 칸은 안 받는다', cron꼴맞나('7 * * *') === false);
  검('⛔ 글자가 섞이면 안 받는다', cron꼴맞나('7 * * * mon') === false);
  검('⛔ 빈 값은 false', cron꼴맞나('') === false && cron꼴맞나(null) === false);

  검('붐비는 분을 잡는다', 붐비는분인가('0 9 * * *') === true);
  검('30분도 붐빈다', 붐비는분인가('30 9 * * *') === true);
  검('⛔ 비켜선 분은 안 잡는다', 붐비는분인가('7 * * * *') === false);

  검('알맹이가 다 있으면 통과', 알맹이있나('가 나 다', ['가', '다']).됐나 === true);
  검('빠진 것을 이름으로 낸다',
    JSON.stringify(알맹이있나('가 나', ['가', '라']).빠진것) === JSON.stringify(['라']));
  검('⛔ 빈 글은 못 쟀다(null)', 알맹이있나('', ['가']) === null);
  검('⛔ 목록이 배열이 아니면 못 쟀다', 알맹이있나('가', '가') === null);

  /* 🔴 우리 것 자체를 잰다 — 목록이 비거나 붐비는 분에 걸려 있으면 여기서 걸린다 */
  검('걸어야 할 것이 셋이다', 걸어야할것.length === 3);
  검('⛔ 우리 깨움이 붐비는 분에 걸려 있지 않다', 걸어야할것.every((x) => !붐비는분인가(x.cron)));
  검('⛔ 우리 cron 이 다 옳은 꼴이다', 걸어야할것.every((x) => cron꼴맞나(x.cron)));
  검('저마다 «왜»가 적혀 있다', 걸어야할것.every((x) => x.왜 && x.왜.length > 10));

  return { 실패, 센것 };
}

const 내가실행됐다 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다 && process.argv.includes('--자가시험')) {
  const { 실패, 센것 } = 자가시험();
  if (실패.length) {
    console.error(`❌ 자가시험 실패 ${실패.length}\n${실패.map((s) => `   · ${s}`).join('\n')}`);
    process.exit(1);
  }
  console.log(`✅ check-kcw-wakers 자가시험 통과 (${센것})`);
  process.exit(0);
}

if (내가실행됐다) {
  console.log('■ 나를 깨우는 자물쇠 — 걸려 있어야 하는 것 (사장님 지시 2026-09-01)\n');
  console.log('> 「턴을 끝낸 게 반항이지. 지시를 어겼으니 반항이라고」');
  console.log('> 「너를 깨우는 기능을 만들어」\n');

  for (const w of 걸어야할것) {
    console.log(`   ${w.cron.padEnd(12)} ${w.이름}`);
    console.log(`                왜 — ${w.왜}`);
    console.log(`                글에 반드시 — ${w.반드시.join(' · ')}`);
  }

  console.log('\n🔴 **이것은 「걸려 있다」는 증거가 아니다.** 이 자는 저장소에 적힌 «해야 할 목록»일 뿐이다.');
  console.log('   깨움(cron)은 세션이 죽으면 같이 죽고, 7일 뒤 저절로 만료된다.');
  console.log('   ⇒ 새 창이 열리면 `CronList` 로 «실제로» 걸려 있는지 보고, 없으면 위 셋을 다시 건다.');
  console.log('\n⭐ 왜 이것이 필요한가 — 나는 잠들지 않는다. 내가 응답을 마치면 그 시간은');
  console.log('   사장님이 말을 걸어 주실 때까지 통째로 빈다. 「다음 지시를 기다린다」는');
  console.log('   공손한 것이 아니라 **사장님의 손을 빌리는 일**이다.');
}
