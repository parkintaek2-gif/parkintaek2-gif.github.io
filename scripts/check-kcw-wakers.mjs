/**
 * 오늘 그 몫을 했나.
 * @returns {{했나:boolean|null, 까닭:string}}  ⛔ 못 쟀으면 null — false 로 만들지 않는다
 */
export function 했나(몫, 날, 메일글, 마커있나) {
  if (!몫 || !날) return { 했나: null, 까닭: '몫이나 날이 없다' };
  /* 마커가 먼저다 — 몫을 끝낸 자가 직접 남긴 것이라 가장 확실하다 */
  if (typeof 마커있나 === 'function' && 마커있나(`${날}-${몫.키}.txt`)) {
    return { 했나: true, 까닭: '마커가 있다' };
  }
  if (몫.메일무늬) {
    if (메일글 === null || 메일글 === undefined) return { 했나: null, 까닭: '메일 기록을 못 읽었다' };
    for (const 줄 of String(메일글).split(/\r?\n/)) {
      if (줄.startsWith('#') || !줄.trim()) continue;
      const 칸 = 줄.split('\t');
      const 때 = (칸[0] ?? '').trim();
      const 제목 = (칸[3] ?? '').trim();
      if (때.startsWith(날) && 몫.메일무늬.test(제목)) return { 했나: true, 까닭: `메일이 나갔다 (${때})` };
    }
    return { 했나: false, 까닭: '오늘 그 제목으로 나간 메일이 없다' };
  }
  return { 했나: false, 까닭: '마커가 없다' };
}

/**
 * 지금 시각에 «밀린» 몫을 낸다.
 * ⛔ 아직 시각이 안 된 것은 밀린 것이 아니다 — 재촉하지 않는다.
 */
export function 밀린것(지금 = new Date(), 메일글 = null, 마커있나 = null, 목록 = 하루몫) {
  const 날 = 날글(지금);
  const 시 = 지금.getHours();
  const 것 = [];
  for (const m of 목록 ?? []) {
    if (시 < m.늦으면) continue;                     /* 아직 때가 아니다 */
    if (m.시작날 && 날 < m.시작날) continue;          /* 🔴 아직 «시작 안 한» 몫이다 */
    const r = 했나(m, 날, 메일글, 마커있나);
    if (r.했나 === true) continue;
    것.push({ ...m, 상태: r.했나 === null ? '못쟀다' : '밀렸다', 까닭: r.까닭 });
  }
  return 것;
}

/** 이 깨움 글이 «해야 할 말»을 다 담고 있나. ⛔ 걸려만 있고 알맹이가 없으면 소용없다 */
export function 알맹이있나(글, 반드시) {
  const s = String(글 ?? '');
  if (!s || !Array.isArray(반드시)) return null;          /* ⛔ 못 쟀다 */
  const 빠진것 = 반드시.filter((w) => !s.includes(w));
  return { 됐나: 빠진것.length === 0, 빠진것 };
}

/** cron 다섯 칸이 맞나. ⛔ 틀린 것을 「걸렸다」로 안 친다 */
export function cron꼴맞나(글) {
  const s = String(글 ?? '').trim();
  if (!s) return false;
  const 칸 = s.split(/\s+/);
  if (칸.length !== 5) return false;
  return 칸.every((x) => /^[\d*\/,\-]+$/.test(x));
}

/** ⚠ 온 세상이 :00·:30 에 몰린다. 우리 것은 비켜서 건다 */
export function 붐비는분인가(cron) {
  const 분 = String(cron ?? '').trim().split(/\s+/)[0];
  return 분 === '0' || 분 === '30';
}

