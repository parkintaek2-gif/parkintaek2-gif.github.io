/** 제때로 보는 선 — 회차 시각으로부터 몇 분 안이면 「맞춰서 준 것」인가 */
export const 제때선 = 20;

/**
 * 🔴 [2026-10-09 · 5번] 회차 예약 여섯이 맡은 시각.
 *   (예약은 08:25·09:25·10:25·13:25·14:25·15:25 KST 이고, 그것이 맡는 회차가 이 여섯이다)
 * ⛔ 여기 적힌 것은 «회차 이름»이지 예약 분(分)이 아니다. 예약 분은 claude.ai 목록에서 본다 —
 *   2026-10-06 에 분을 박아 두었다가 낡아서 거짓을 말한 적이 있다.
 */
export const 정규회차 = new Set([9, 10, 11, 14, 15, 16]);

/**
 * 자국 파일 이름에서 날과 회차를 집는다.
 * ⛔ 이름이 안 맞으면 null 이다 — 0 시로 때려 넣지 않는다.
 */
export function 이름풀기(이름) {
  const m = String(이름 ?? '').match(/^(\d{4}-\d{2}-\d{2})_(\d{1,2})시\.txt$/);
  if (!m) return null;
  const 시 = Number(m[2]);
  if (!Number.isInteger(시) || 시 < 0 || 시 > 23) return null;
  return { 날: m[1], 시 };
}

/**
 * 자국 첫 줄의 한국어 시각을 분으로 집는다.
 *   「2026. 10. 6. 오전 10:03:51」 → 603
 * ⚠ 오후 12시는 12시이고 오전 12시는 0시다 — 12를 더하면 안 되는 자리가 있다.
 * ⛔ 못 읽으면 null. 「0분」이 아니다.
 */
export function 찍힌분(글) {
  const m = String(글 ?? '').match(/(오전|오후)\s*(\d{1,2}):(\d{2})/);
  if (!m) return null;
  let 시 = Number(m[2]);
  const 분 = Number(m[3]);
  if (시 < 1 || 시 > 12 || 분 > 59) return null;
  if (m[1] === '오전' && 시 === 12) 시 = 0;
  else if (m[1] === '오후' && 시 !== 12) 시 += 12;
  return 시 * 60 + 분;
}

/**
 * 한 회차를 잰다.
 * ⛔ 「늦음 0」과 「못 쟀다」를 같은 칸에 넣지 않는다.
 */
export function 한회차재기(이름, 글) {
  const 것 = 이름풀기(이름);
  if (!것) return { 판정: '못잼', 까닭: '자국 이름을 못 읽었다' };
  const 분 = 찍힌분(글);
  if (분 == null) return { ...것, 판정: '못잼', 까닭: '자국에 시각이 없다' };
  const 늦음 = 분 - 것.시 * 60;
  /* ⚠ 회차 시각 «앞»에 찍힌 것이 실제로 있다 — 밤 회차(22·23시)와 빌려 쓴 18시가 그렇고,
       사장님 주문으로 손으로 당겨 거둔 날도 있다.
     ⛔ 그것을 「0분 늦음」으로 세면 «제때 나갔다»는 거짓 초록이 난다.
     ⛔ 「자국이 깨졌다」고 단정하지도 않는다 — 내가 그 까닭을 못 가렸다. 셋째 칸에 둔다. */
  /* 🔴🔴 [2026-10-09 · 5번] **「앞서 찍힌 것」을 통째로 「못 쟀다」로 센 것이 이제 틀렸다.**
     ─────────────────────────────────────────────────────────────────────
     10-06 에 회차 예약 여섯을 **35분 당겼다.** 그러자 글이 정시 «앞»에 끝나는 날이 생겼다 —
     그것이 바로 우리가 바라던 것이다. 그런데 이 자는 그것을 「확인 못 함」으로 ⬜ 에 넣어
     **잘된 날을 안 셌다.** 10-07 11시가 그렇게 빠졌고, 그날 가운데값이 실제보다 나쁘게 보였다.
     ⭐ 가른다 — 여섯 예약이 맡은 회차가 앞서 찍혔으면 **「일찍」**(바라던 것)이고,
       그 밖의 회차(18·22·23시처럼 빌려 쓴 자리)가 앞서 찍혔으면 여전히 **「못 쟀다」**다.
     ⛔ 「일찍」을 「늦음 0분」으로 뭉개지 않는다 — 칸을 따로 둔다. 셋이 아니라 넷이다. */
  if (늦음 < 0) {
    if (정규회차.has(것.시)) {
      return { ...것, 늦음, 판정: '일찍', 까닭: `정시보다 ${-늦음}분 앞서 끝났다` };
    }
    return { ...것, 늦음, 판정: '못잼', 까닭: '여섯 예약 밖 회차가 앞서 찍혔다 — 빌려 쓴 자리로 보인다(확인 못 함)' };
  }
  return { ...것, 늦음, 판정: 늦음 <= 제때선 ? '제때' : '늦음' };
}

/** 최근 며칠치 자국 이름을 고른다 */
export function 요즘자국(모든이름, 오늘 = new Date(), 날수 = 7) {
  const 날들 = new Set();
  for (let i = 0; i < 날수; i += 1) {
    const d = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate() - i);
    const p = (n) => String(n).padStart(2, '0');
    날들.add(`${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`);
  }
  return 모든이름.filter((이름) => {
    const 것 = 이름풀기(이름);
    return 것 && 날들.has(것.날);
  }).sort();
}

export function 모아재기(날수 = 7, 방 = 자국방, 오늘 = new Date()) {
  if (!fs.existsSync(방)) return { 잰것: [], 못읽음: '자국 방이 없다' };
  const 이름들 = 요즘자국(fs.readdirSync(방), 오늘, 날수);
  const 잰것 = [];
  for (const 이름 of 이름들) {
    let 글 = null;
    try { 글 = fs.readFileSync(path.join(방, 이름), 'utf8'); } catch { /* 아래에서 못잼으로 센다 */ }
    if (글 == null) { 잰것.push({ 이름, 판정: '못잼', 까닭: '자국을 못 읽었다' }); continue; }
    잰것.push({ 이름, ...한회차재기(이름, 글) });
  }
  return { 잰것 };
}

/** 가운데값 — 평균은 한 번의 큰 늦음에 끌려간다 */
export function 가운데값(수들) {
  const 것 = [...수들].filter((n) => Number.isFinite(n)).sort((a, b) => a - b);
  if (!것.length) return null;
  const 가 = Math.floor(것.length / 2);
  return 것.length % 2 ? 것[가] : Math.round((것[가 - 1] + 것[가]) / 2);
}

