#!/usr/bin/env node
/**
 * 🔴🔴 **기사가 예약 시각에 맞춰 나갔나를 «잰다»**
 *
 * 사장님 (2026-10-06): 「**스포츠기사 예약시간에 맞춰서 줘라**」
 *
 * 그 말씀을 듣고 자국을 재 보니 —
 *   09시 회차 → 10:03 (63분)   10시 회차 → 10:52 (52분)
 *   11시 회차 → 11:54 (54분)   14시 회차 → 14:47 (47분)
 * 스물넷 가운데 거의 다가 30~90분 늦었다.
 *
 * 까닭은 거두기 예약(:22)을 매시 점검(:13)이 «깔고 앉은» 것이었다.
 * 예약은 REPL 이 한가할 때만 뜨는데, 점검이 길게 돌면 거두기가 통째로 밀린다.
 * ⇒ 거두기를 :07·:12·:26 세 번으로 늘리고, 점검을 :34·:49 로 물렸다.
 *
 * ⛔ **「고쳤다」로 끝내지 않는다.** 겹침 고침이 61%→62%로 거꾸로 간 적이 있다.
 *   고쳤으면 다시 잰다. 이 자가 그 자다.
 *
 * ⭐ **세는 칸을 셋으로 둔다** — 제때 / 늦음 / **못 잼**.
 *   둘로만 세면 반드시 한쪽으로 거짓이 난다. 자국을 못 읽은 회차를
 *   「제때」로도 「늦음」으로도 세지 않는다.
 *
 * 쓰기 —
 *   node scripts/잰다-기사가-제때-나갔나.mjs            최근 7일
 *   node scripts/잰다-기사가-제때-나갔나.mjs --날수 14
 *   node scripts/잰다-기사가-제때-나갔나.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
export const 뿌리 = path.resolve(여기, '..');
export const 자국방 = path.join(뿌리, 'docs', '고정업무-마커', '중부매일-스포츠-보낸자국');

/** 제때로 보는 선 — 회차 시각으로부터 몇 분 안이면 「맞춰서 준 것」인가 */
export const 제때선 = 20;

/**
 * 자국 파일 이름에서 날과 회차를 집는다.
 * ⛔ 이름이 안 맞으면 null 이다 — 0 시로 때려 넣지 않는다.
 */
export function 이름풀기(이름) {
  const m = String(이름 ?? '').match(/^(\d{4}-\d{2}-\d{2})_(\d{1,2})시\.txt$/);
  if (!m) return null;
  const 시 = Number(m[2]);
  if (!Number.isInteger(시) || 시 < 0 || 시 > 23) return null;
  return { 날: m[1], 시 };
}

/**
 * 자국 첫 줄의 한국어 시각을 분으로 집는다.
 *   「2026. 10. 6. 오전 10:03:51」 → 603
 * ⚠ 오후 12시는 12시이고 오전 12시는 0시다 — 12를 더하면 안 되는 자리가 있다.
 * ⛔ 못 읽으면 null. 「0분」이 아니다.
 */
export function 찍힌분(글) {
  const m = String(글 ?? '').match(/(오전|오후)\s*(\d{1,2}):(\d{2})/);
  if (!m) return null;
  let 시 = Number(m[2]);
  const 분 = Number(m[3]);
  if (시 < 1 || 시 > 12 || 분 > 59) return null;
  if (m[1] === '오전' && 시 === 12) 시 = 0;
  else if (m[1] === '오후' && 시 !== 12) 시 += 12;
  return 시 * 60 + 분;
}

/**
 * 한 회차를 잰다.
 * ⛔ 「늦음 0」과 「못 쟀다」를 같은 칸에 넣지 않는다.
 */
export function 한회차재기(이름, 글) {
  const 것 = 이름풀기(이름);
  if (!것) return { 판정: '못잼', 까닭: '자국 이름을 못 읽었다' };
  const 분 = 찍힌분(글);
  if (분 == null) return { ...것, 판정: '못잼', 까닭: '자국에 시각이 없다' };
  const 늦음 = 분 - 것.시 * 60;
  /* ⚠ 회차 시각 «앞»에 찍힌 것이 실제로 있다 — 밤 회차(22·23시)와 빌려 쓴 18시가 그렇고,
       사장님 주문으로 손으로 당겨 거둔 날도 있다.
     ⛔ 그것을 「0분 늦음」으로 세면 «제때 나갔다»는 거짓 초록이 난다.
     ⛔ 「자국이 깨졌다」고 단정하지도 않는다 — 내가 그 까닭을 못 가렸다. 셋째 칸에 둔다. */
  if (늦음 < 0) return { ...것, 늦음, 판정: '못잼', 까닭: '회차 시각보다 앞서 찍혔다 — 당겨 거둔 회차로 보인다(확인 못 함)' };
  return { ...것, 늦음, 판정: 늦음 <= 제때선 ? '제때' : '늦음' };
}

/** 최근 며칠치 자국 이름을 고른다 */
export function 요즘자국(모든이름, 오늘 = new Date(), 날수 = 7) {
  const 날들 = new Set();
  for (let i = 0; i < 날수; i += 1) {
    const d = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate() - i);
    const p = (n) => String(n).padStart(2, '0');
    날들.add(`${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`);
  }
  return 모든이름.filter((이름) => {
    const 것 = 이름풀기(이름);
    return 것 && 날들.has(것.날);
  }).sort();
}

export function 모아재기(날수 = 7, 방 = 자국방, 오늘 = new Date()) {
  if (!fs.existsSync(방)) return { 잰것: [], 못읽음: '자국 방이 없다' };
  const 이름들 = 요즘자국(fs.readdirSync(방), 오늘, 날수);
  const 잰것 = [];
  for (const 이름 of 이름들) {
    let 글 = null;
    try { 글 = fs.readFileSync(path.join(방, 이름), 'utf8'); } catch { /* 아래에서 못잼으로 센다 */ }
    if (글 == null) { 잰것.push({ 이름, 판정: '못잼', 까닭: '자국을 못 읽었다' }); continue; }
    잰것.push({ 이름, ...한회차재기(이름, 글) });
  }
  return { 잰것 };
}

/** 가운데값 — 평균은 한 번의 큰 늦음에 끌려간다 */
export function 가운데값(수들) {
  const 것 = [...수들].filter((n) => Number.isFinite(n)).sort((a, b) => a - b);
  if (!것.length) return null;
  const 가 = Math.floor(것.length / 2);
  return 것.length % 2 ? 것[가] : Math.round((것[가 - 1] + 것[가]) / 2);
}

function 주다(날수 = 7) {
  const { 잰것, 못읽음 } = 모아재기(날수);
  console.log(`\n⏱  기사가 예약 시각에 맞춰 나갔나 — 최근 ${날수}일\n`);
  if (못읽음) { console.log(`  ⬜ ${못읽음}`); return 0; }
  if (!잰것.length) { console.log('  ⬜ 잴 자국이 없다 — 「제때 나갔다」가 아니라 「못 쟀다」다'); return 0; }

  for (const x of 잰것) {
    const 표 = x.판정 === '제때' ? '✅' : x.판정 === '늦음' ? '🔴' : '⬜';
    const 말 = x.판정 === '못잼' ? `못 쟀다 — ${x.까닭}` : `${x.늦음}분 늦음`;
    console.log(`  ${표} ${x.이름.replace('.txt', '')}  ${말}`);
  }

  const 제때 = 잰것.filter((x) => x.판정 === '제때').length;
  const 늦음 = 잰것.filter((x) => x.판정 === '늦음');
  const 못잼 = 잰것.filter((x) => x.판정 === '못잼').length;
  const 가 = 가운데값(잰것.filter((x) => x.판정 !== '못잼').map((x) => x.늦음));

  console.log(`\n  제때(${제때선}분 안) ${제때}  ·  늦음 ${늦음.length}  ·  ⬜ 못 쟀다 ${못잼}`);
  console.log(`  늦음 가운데값 ${가 == null ? '— (못 쟀다)' : `${가}분`}`);
  console.log('  ⛔ 「못 쟀다」를 「제때」로 세지 않는다. 셋째 칸이 있어야 거짓이 안 난다.');

  if (늦음.length) {
    console.log('\n  🔴 늦은 회차가 있다. 볼 곳 둘 —');
    console.log('     ① 거두기 예약이 매시 점검에 깔렸나 (지금 거두기 :07·:19·:27 / 점검 :34·:49)');
    console.log('     ② 회차 대화가 늦게 기사를 냈나 — 그러면 거두기를 당겨도 안 끝난다');
    console.log('        node scripts/잰다-회차가-몇분에-떴나.mjs 로 가른다. ⛔ 어림으로 예약을 옮기지 않는다');
    return 1;
  }
  console.log('\n  ✅ 재 본 회차가 다 제때 나갔다');
  return 0;
}

/* ── 자가시험 ────────────────────────────────────────────────── */
function 자가시험() {
  let 통과 = 0; let 탈 = 0;
  const 본다 = (말, 참) => { if (참) { 통과 += 1; console.log('✅ ' + 말); } else { 탈 += 1; console.log('🔴 ' + 말); } };

  본다('자국 이름에서 날과 회차를 집는다',
    이름풀기('2026-10-06_09시.txt')?.날 === '2026-10-06' && 이름풀기('2026-10-06_09시.txt')?.시 === 9);
  본다('한 자리 회차도 읽는다', 이름풀기('2026-10-06_9시.txt')?.시 === 9);
  본다('⛔ 엉뚱한 이름은 null 이다 — 0시로 때려 넣지 않는다',
    이름풀기('아무거나.txt') === null && 이름풀기('') === null);
  본다('⛔ 없는 시각은 안 받는다', 이름풀기('2026-10-06_99시.txt') === null);

  본다('오전을 읽는다', 찍힌분('2026. 10. 6. 오전 10:03:51') === 10 * 60 + 3);
  본다('오후를 읽는다', 찍힌분('2026. 10. 6. 오후 2:47:22') === 14 * 60 + 47);
  본다('🔴 오후 12시는 12시다 — 24시가 아니다', 찍힌분('2026. 10. 6. 오후 12:05:12') === 12 * 60 + 5);
  본다('🔴 오전 12시는 0시다', 찍힌분('2026. 10. 6. 오전 12:30:00') === 30);
  본다('⛔ 시각이 없으면 null 이다 — 0분이 아니다',
    찍힌분('시각이 없는 줄') === null && 찍힌분(null) === null);

  본다('🔴 63분 늦은 것을 늦음으로 센다',
    한회차재기('2026-10-06_09시.txt', '2026. 10. 6. 오전 10:03:51').판정 === '늦음');
  본다('✅ 7분이면 제때다',
    한회차재기('2026-10-06_09시.txt', '2026. 10. 6. 오전 9:07:10').판정 === '제때');
  본다('⭐ 선 위에 꼭 걸치면 제때로 센다',
    한회차재기('2026-10-06_09시.txt', `2026. 10. 6. 오전 9:${제때선}:00`).판정 === '제때');
  본다('⬜ 시각을 못 읽으면 못잼이다 — 「제때」가 아니다',
    한회차재기('2026-10-06_09시.txt', '시각 없음').판정 === '못잼');
  본다('⬜ 이름을 못 읽어도 못잼이다',
    한회차재기('엉뚱.txt', '2026. 10. 6. 오전 9:05:00').판정 === '못잼');
  본다('⬜ 회차보다 앞서 찍힌 것은 못잼이다 — 자국이 깨진 것이다',
    한회차재기('2026-10-06_14시.txt', '2026. 10. 6. 오전 9:05:00').판정 === '못잼');

  const 오늘 = new Date(2026, 9, 6);
  const 모든 = ['2026-10-06_09시.txt', '2026-10-05_09시.txt', '2026-09-20_09시.txt', '읽을수없는이름'];
  본다('최근 날짜만 고른다', 요즘자국(모든, 오늘, 7).length === 2);
  본다('⛔ 이름이 안 맞는 것은 아예 안 담는다', !요즘자국(모든, 오늘, 90).includes('읽을수없는이름'));
  본다('⭐ 오늘치가 들어간다', 요즘자국(모든, 오늘, 1).includes('2026-10-06_09시.txt'));

  본다('가운데값은 가운데를 준다', 가운데값([1, 5, 100]) === 5);
  본다('짝수면 두 가운데의 평균이다', 가운데값([2, 4]) === 3);
  본다('⛔ 잴 것이 없으면 null 이다 — 0 이 아니다', 가운데값([]) === null);
  본다('⛔ 못 잰 칸(null)은 셈에서 빠진다', 가운데값([null, 3, null]) === 3);

  본다('자국 방이 없으면 못읽음을 준다', !!모아재기(7, path.join(뿌리, '없는방')).못읽음);

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${통과} 통과`);
  return 탈 ? 1 : 0;
}

/* ⛔ 걸림돌 없는 꼭대기 부름을 두지 않는다 — import 한 쪽의 걸음을 가로챈다 */
const 내가실행됐다 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험());
  const m = process.argv.join(' ').match(/--날수\s+(\d+)/);
  process.exit(주다(m ? Number(m[1]) : 7));
}
