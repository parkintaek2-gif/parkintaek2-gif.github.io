#!/usr/bin/env node
/**
 * 근속연수 파서 시험.
 *
 * ⚠ **실제 DART 원문에서 본 표기**로 시험한다. 지어낸 것이 아니다.
 *   2026-08-04 에 순위표 근속 채움률이 63.5% 였는데, 원인이 회사의 미공시가 아니라
 *   **내 파서가 「5년 8월」을 못 읽고 버린 것**이었다. 그 표기들을 여기 박아 둔다.
 */
import { 근속연수, 수 } from './collect-tenure.mjs';

const 표 = [
  /* ⭐ 실제 DART 원문 (2025 사업보고서에서 그대로 가져왔다) */
  [' 5년 8월', 5.67, '지오엠씨 남'],
  [' 4년 3월 ', 4.25, '지오엠씨 여 (앞뒤 공백)'],
  ['7년6월', 7.5, '우진플라임 (공백 없음)'],
  ['7년8개월', 7.67, '삼보판지'],
  ['04년 04개월', 4.33, '티로보틱스 (앞의 0)'],
  ['12년 10개월', 12.83, '조광피혁'],
  ['4년 2개월', 4.17, '하나기술'],
  /* 그냥 숫자로 적는 회사도 있다 — 원래 되던 것이 안 깨지는지 본다 */
  ['10.5', 10.5, '소수'],
  ['12', 12, '정수'],
  ['9,5', 95, '쉼표는 천단위로 본다 (기존 동작 유지)'],
  /* 년만 */
  ['15년', 15, '년만'],
  ['15 년', 15, '년만 (공백)'],
  /* 개월만 */
  ['8개월', 0.67, '개월만'],
  /* ⚠ 없는 것은 **null 이어야 한다.** 0 으로 만들면 순위 맨 아래가 오염된다 */
  [null, null, 'null'],
  ['', null, '빈 문자열'],
  ['-', null, '대시'],
  ['해당사항없음', null, '해당사항없음'],
  ['미공시', null, '미공시'],
  ['알 수 없음', null, '읽을 수 없는 문자열'],
];

let 실패 = 0;
console.log('근속연수 파서');
for (const [입력, 기대, 설명] of 표) {
  const 결과 = 근속연수(입력);
  if (결과 !== 기대) {
    실패++;
    console.log(`  ✕ ${설명}`);
    console.log(`      입력 ${JSON.stringify(입력)} → ${JSON.stringify(결과)} (기대 ${JSON.stringify(기대)})`);
  }
}

/* ⚠ 옛 파서로는 대부분이 null 이었다는 것을 남겨 둔다 — 회귀하면 여기서 걸린다 */
const 한글표기 = [' 5년 8월', '7년6월', '04년 04개월'];
for (const s of 한글표기) {
  if (수(s) !== null) { 실패++; console.log(`  ✕ 전제가 바뀌었다: 수(${JSON.stringify(s)}) 가 null 이 아니다`); }
  if (근속연수(s) === null) { 실패++; console.log(`  ✕ 근속연수(${JSON.stringify(s)}) 가 여전히 null 이다`); }
}

if (실패) { console.error(`\n${표.length + 6 - 실패} 통과 · ${실패} 실패`); process.exit(1); }
console.log(`  ${표.length + 6} 통과 · 0 실패`);
