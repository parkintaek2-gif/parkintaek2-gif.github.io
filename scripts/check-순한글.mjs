/** 기사 본문만 본다 — 자료 줄·키워드 줄은 기사가 아니다 */
export function 본문만(글) {
  const g = String(글 ?? '');
  const 시작 = g.indexOf('[본문]');
  let 본 = 시작 >= 0 ? g.slice(시작 + 4) : g;
  for (const 끝표 of ['[추천 키워드]', '\n자료 —']) {
    const i = 본.indexOf(끝표);
    if (i >= 0) 본 = 본.slice(0, i);
  }
  return 본;
}

/** 제목·부제도 함께 본다 — 거기 순한글이 더 눈에 띈다 */
export function 제목부제(글) {
  const g = String(글 ?? '');
  const 집 = (표) => {
    const i = g.indexOf(표);
    if (i < 0) return '';
    return (g.slice(i + 표.length).split('\n').find((x) => x.trim()) || '').trim();
  };
  return `${집('[제목]')}\n${집('[부제목]')}`;
}

export function 잰다(글) {
  const 볼것 = `${제목부제(글)}\n${본문만(글)}`;
  const 걸린것 = [];
  /* ① **정본이 먼저다** — scripts/순한글-금지어.mjs
     2026-10-24 에 내 목록만 보다가 「벼랑」·「맞붙」을 놓쳤고, 기사가 send-mail
     자물쇠에서 섰다. 정본이 「목록은 여기 하나뿐」이라 못박아 둔 것을 내가 어겼다. */
  for (const x of 정본재기(볼것)) 걸린것.push({ 찾: x.말, 바꿀: x.대신 });
  /* ② 정본에 없는 것만 내 목록이 덧붙인다 — 같은 말을 두 번 세지 않는다 */
  for (const [찾, 바꿀] of 바꿀말) {
    if (!볼것.includes(찾)) continue;
    if (걸린것.some((y) => y.찾 === 찾)) continue;
    걸린것.push({ 찾, 바꿀 });
  }
  return 걸린것;
}

