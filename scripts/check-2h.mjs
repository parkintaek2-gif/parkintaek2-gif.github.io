/**
 * 🔴 [2026-09-10] **이 꼴이 이 파일에 «두 벌» 있었다.** 내보낸 함수와 실행부가 각자 사본을 썼다.
 *   그래서 내가 함수만 고쳤을 때 자가시험은 통과하고 «화면은 안 바뀌었다».
 *   이 파일 주석이 스스로 경고해 둔 그 자리다 — 「결함은 옆줄에도 있다」.
 * ✅ 꼴을 한 곳에 두고 두 쪽이 같은 것을 쓴다. 사본을 만들지 않는다.
 */
export const 소통꼴 = String.raw`\[5번(?:\([^)]*\))? → [^\]]*\][^\n]*?(?:\((\d{2}):(\d[\dx])\)|(\d{2}):(\d[\dx]))`;

/** 글에서 5번이 «낸» 소통 자리를 다 찾는다 */
export function 소통자리들(글) {
  return [...String(글 ?? '').matchAll(new RegExp(소통꼴, 'g'))];
}
export function 소통줄찾기(글) {
  const s = String(글 ?? '');
  if (!s) return null;
  /**
   * 🔴 [2026-09-10] **「[5번(총괄) → 2번]」 을 못 알아봤다.** 나는 이 꼴로 쓴다.
   *   그래서 16:38 에 2번께 물음을 올렸는데도 화면은 「마지막 08:29」로 멈춰 있었다.
   *   ⇒ 나는 소통을 «하고도» 안 한 것으로 세었고, 2번은 그 물음을 못 봤다고 적었다.
   * ⛔ 오늘 이 병을 여덟 번째로 고친다 — 이름·꼴을 좁게 보고 판정한 것들이다.
   * ✅ 5번 뒤에 괄호가 붙어도(총괄 등) 받는다. 분에 x 가 와도 받는다.
   */
  const m = s.match(new RegExp(소통꼴));
  if (!m) return null;
  return { 시: m[1] ?? m[3], 분: m[2] ?? m[4] };
}

/** 한 줄로 낸다. ⛔ 못 잰 것은 ✗ 가 아니라 ⬜ 다 */
export function 줄(번호, 이름, 값) {
  const 표 = 값 === null ? '⬜' : (값.됐나 ? '✅' : '🔴');
  return `${표} ${번호} ${이름.padEnd(14)} ${값 === null ? '못 쟀다' : 값.말}`;
}

