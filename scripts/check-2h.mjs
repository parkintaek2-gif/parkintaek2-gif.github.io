export function 남은무음(잰것, 오늘) {
  /* 🔴 이름으로 세지 않는다 — 무음이냐는 음량을 재야 안다.
     check-kcw-silent-video.mjs 가 재서 src/data/kcw-video-sound.json 에 적는다.
     ⛔ 그 파일이 없거나 «오늘 잰 것이 아니면» null 이다 — 못 쟀다이고, 0 이 아니다. */
  if (!잰것 || typeof 잰것.소리없는편 !== 'number') return null;
  if (오늘 && !String(잰것.잰때 ?? '').startsWith(오늘)) return null;
  return 잰것.소리없는편;
}
export function 오늘낸영상(원부, 오늘) {
  const v = 원부?.videos;
  if (!Array.isArray(v)) return null;
  const 바탕이름 = new Set(
    v.map((x) => String(x?.set ?? '')).filter((n) => n && !n.endsWith('-voiced')),
  );
  const 오늘것 = v.filter((x) => x?.uploadDate === 오늘);
  const 버전업인가 = (x) => {
    const n = String(x?.set ?? '');
    if (!n.endsWith('-voiced')) return false;
    return 바탕이름.has(n.slice(0, -7));   // 무음 바탕이 원부에 «있을 때만» 버전업이다
  };
  return {
    버전업: 오늘것.filter(버전업인가).length,
    새것: 오늘것.filter((x) => !버전업인가(x)).length,
  };
}

