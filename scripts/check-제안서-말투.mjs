/* 손님에게 나가는 제안서에 «우리끼리 쓰는 말»이 들어가지 않게 막는다.
 *
 * [왜 이 자가 있나 — 2026-09-21]
 * 사장님: 「케맵 제안서를 사람들이 잘 안 쓰는 표현을 수정해라...
 *          자꾸 «값»이라고 쓰는데 실제로 한국에선 거의 쓰지 않는다」
 *
 * 저장소 안에서 우리는 「값·갈래·자리·꼴·까닭·몫·잰다」 같은 말을 쓴다. 그것은
 * 우리 문서의 문체이지 «기업 고객이 읽는 제안서»의 말이 아니다. 사장님이 두 번
 * 짚으시게 하지 않으려면 사람의 조심이 아니라 검사로 둬야 한다(강령 ④).
 *
 * ⛔ 이 자는 «손님에게 나가는 글»만 본다. 우리끼리 보는 docs 는 건드리지 않는다 —
 *   거기서는 그 말들이 오히려 정확하다.
 *
 * 쓰는 법
 *   node scripts/check-제안서-말투.mjs
 *   node scripts/check-제안서-말투.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const 여기 = path.dirname(url.fileURLToPath(import.meta.url));
const 뿌리 = path.resolve(여기, '..');

/** 손님에게 나가는 글 — 여기만 잰다 */
export const 볼파일들 = ['docs/KLifeMap-B2B제안서-본문-2026-09-21.md'];

/**
 * 막는 말 — 무엇을 «대신 쓸지»까지 적는다. 지적만 하면 다음 사람이 또 헤맨다.
 * ⚠ 낱말만 보고 잡으면 멀쩡한 말까지 걸린다(「값어치」·「자리매김」).
 *   그래서 «정규식»으로 쓰이는 꼴을 짚는다.
 */
export const 막는말 = [
  { 자: /값\s*없이/g, 대신: '추가 비용 없이', 왜: '「값 없이」는 문어체다' },
  { 자: /자리값/g, 대신: '연간 정액제', 왜: '우리끼리 쓰는 말이다' },
  { 자: /값이\s*안\s*튀/g, 대신: '요금이 오르지 않습니다', 왜: '「튄다」가 구어다' },
  { 자: /나눈\s*값/g, 대신: '나눈 수치', 왜: '한국에서 잘 안 쓴다(사장님 지적)' },
  { 자: /갈래(?!말)/g, 대신: '가지 · 종류 · 구분', 왜: '우리끼리 쓰는 말이다' },
  { 자: /붙이는\s*꼴|어떤\s*꼴/g, 대신: '적용 방식', 왜: '「꼴」은 제안서 말이 아니다' },
  { 자: /손이\s*드는|손댈\s*일/g, 대신: '운영 부담 · 관리하실 일', 왜: '「손이 든다」가 구어다' },
  { 자: /쥐여\s*드릴/g, 대신: '제공할 수 있는', 왜: '구어다' },
  { 자: /여는\s*층/g, 대신: '공개하는 단계', 왜: '우리끼리 쓰는 말이다' },
  { 자: /라는\s*수입니다|수입니다\./g, 대신: '수치입니다', 왜: '「수」 한 글자는 모호하다' },
  { 자: /까닭/g, 대신: '이유', 왜: '제안서에는 「이유」가 자연스럽다' },
  { 자: /물건입니다|유일한\s*물건/g, 대신: '도구 · 자료', 왜: '「물건」은 제안서 말이 아니다' },
  { 자: /나갑니다(?!\.)|나갑니다\./g, 대신: '제공됩니다 · 표시됩니다', 왜: '「나간다」가 우리 내부 말이다' },
  { 자: /한\s*칸\s*(더|올리)/g, 대신: '한 단계', 왜: '「칸」은 우리끼리 쓰는 말이다' },
  { 자: /잰다|재서|잽니다/g, 대신: '측정합니다 · 확인합니다', 왜: '우리끼리 쓰는 말이다' },
  { 자: /몫(?!을 다)/g, 대신: '역할 · 담당', 왜: '우리끼리 쓰는 말이다' },
];

/** @returns {{파일:string, 말:string, 걸린것:string[], 대신:string, 왜:string}[]} */
export function 훑기(글, 파일 = '') {
  const 난것 = [];
  for (const m of 막는말) {
    const 걸린것 = [...String(글).matchAll(m.자)].map((x) => x[0]);
    if (걸린것.length) 난것.push({ 파일, 말: String(m.자), 걸린것, 대신: m.대신, 왜: m.왜 });
  }
  return 난것;
}

/* ───────────────────────── 자가시험 ───────────────────────── */
function 자가시험() {
  let 통과 = 0; let 깨짐 = 0;
  const 잰다 = (이름, 실제, 바람) => {
    const 맞나 = JSON.stringify(실제) === JSON.stringify(바람);
    console.log(`${맞나 ? '  ✓' : '  ✗'} ${이름}${맞나 ? '' : `\n      난 것 ${JSON.stringify(실제)}\n      바란 것 ${JSON.stringify(바람)}`}`);
    맞나 ? 통과++ : 깨짐++;
  };

  console.log('── 막는 말을 잡는가 (사장님이 짚으신 것)');
  잰다('「값 없이」를 잡는다', 훑기('점성학을 값 없이 드립니다').length > 0, true);
  잰다('「자리값」을 잡는다', 훑기('연 단위 자리값입니다').length > 0, true);
  잰다('「갈래」를 잡는다', 훑기('열두 갈래입니다').length > 0, true);
  잰다('「꼴」을 잡는다', 훑기('붙이는 꼴은 두 가지').length > 0, true);
  잰다('「까닭」을 잡는다', 훑기('그 까닭이 여기 있습니다').length > 0, true);
  잰다('「손이 드는」을 잡는다', 훑기('손이 드는 일은 없습니다').length > 0, true);

  console.log('── 멀쩡한 말까지 잡지는 않는가');
  잰다('고친 문장은 깨끗하다', 훑기('추가 비용 없이 제공해 드립니다').length, 0);
  잰다('「연간 정액제」는 통과', 훑기('연간 정액제입니다').length, 0);
  잰다('「열두 가지」는 통과', 훑기('열두 가지입니다').length, 0);
  잰다('「이유」는 통과', 훑기('그 이유가 여기 있습니다').length, 0);
  잰다('「제공됩니다」는 통과', 훑기('네 개 언어로 제공됩니다').length, 0);
  잰다('「한 단계」는 통과', 훑기('정확도를 한 단계 높입니다').length, 0);

  console.log('── 진짜 제안서');
  let 모두깨끗 = true;
  for (const 상대 of 볼파일들) {
    const 길 = path.join(뿌리, 상대);
    if (!fs.existsSync(길)) { console.log(`  ✗ 파일이 없다 — ${상대}`); 깨짐++; 모두깨끗 = false; continue; }
    const 난것 = 훑기(fs.readFileSync(길, 'utf8'), 상대);
    잰다(`${상대} 에 막는 말이 없다`, 난것.map((x) => x.걸린것).flat(), []);
    if (난것.length) 모두깨끗 = false;
  }
  잰다('제안서가 전부 깨끗하다', 모두깨끗, true);

  console.log(`\n${깨짐 ? '🔴' : '✅'} ${통과}/${통과 + 깨짐} 통과`);
  return 깨짐 === 0;
}

/* ───────────────────────── 실행 ───────────────────────── */
const 인자 = process.argv.slice(2);
if (인자.includes('--자가시험') || 인자.includes('--selftest')) {
  process.exit(자가시험() ? 0 : 1);
} else {
  let 흠 = 0;
  console.log('■ 제안서 말투 — 손님이 읽는 글에 우리끼리 쓰는 말이 없나\n');
  for (const 상대 of 볼파일들) {
    const 길 = path.join(뿌리, 상대);
    if (!fs.existsSync(길)) { console.log(`🔴 파일이 없다 — ${상대}`); 흠++; continue; }
    const 난것 = 훑기(fs.readFileSync(길, 'utf8'), 상대);
    if (!난것.length) { console.log(`✅ ${상대}`); continue; }
    흠 += 난것.length;
    console.log(`🔴 ${상대}`);
    for (const r of 난것) console.log(`   · ${r.걸린것.join(' , ')}  →  ${r.대신}   (${r.왜})`);
  }
  console.log(흠 ? `\n🔴 고칠 자리 ${흠}곳` : '\n✅ 깨끗하다');
  process.exit(흠 ? 1 : 0);
}
