/**
 * **내가 마지막으로 움직인 뒤에 나온 새 지시·공지를 보여 준다.**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 🔴 2026-08-15 22:35 — 사장님이 나서셨다. 「2번 지시 반드시 따라. **왜 메모를 안 보나**」
 *   2번이 하루 리듬을 새로 정했다(20:00 마감 → 21:00 [실적] → …). 나는 **못 봤다.**
 *   그런데 `memo-inbox --me 5` 는 그동안 계속 **「✅ 전부 답했다」**를 내고 있었다.
 *
 * ⛔ 그 자는 잘못이 없다. 그 자는 **「5번 앞으로 온 것」**만 본다 — `[N번 → 5번]` 꼴.
 *   2번이 **모두에게** 낸 공지는 그 꼴이 아니다. 그물에 안 걸린다.
 *   ⭐ **확인했다는 초록이 뜨는데 못 본 것이 있으면, 그건 확인이 아니다.**
 *
 * ── 어떻게 ─────────────────────────────────────────────────────
 * 내가 마지막으로 남긴 `[진행] 5번` 줄을 찾고, **그 뒤에 나온 제목을 전부** 보여 준다.
 * ⛔ 「나에게 온 것」으로 좁히지 않는다 — 좁혔기 때문에 놓쳤다.
 * ⚠ 다른 자리의 `[진행]`·`[실적]` 줄은 뺀다. 그건 공지가 아니라 진행이라 매시 쌓인다.
 *
 * ── ⛔ 이 자가 지키는 것 ──────────────────────────────────────
 * ⛔ **0건이면 조용히 있지 않는다.** 「없다」를 말해야 봤다는 뜻이 된다.
 * ⛔ 내 진행 줄을 못 찾으면 **「전부 못 봤다」로 친다.** 모르면 많이 보여 준다.
 * ⛔ 사장님이 쓰신 것으로 보이는 줄은 **맨 위로** 올린다.
 *
 * 쓰는 법
 *   node scripts/check-kcw-new-orders.mjs
 *   node scripts/check-kcw-new-orders.mjs --selftest
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const 메모길 = path.join(뿌리, 'docs', '세션간-메모.md');
export const 나 = '5번';

/** ⚠ 매시 쌓이는 것 — 공지가 아니다 */
export function 진행줄인가(줄) {
  return /^##\s*\[(진행|실적)\]/.test(줄);
}

/** ⭐ 내가 마지막으로 남긴 진행 줄의 자리. 없으면 -1 — 그때는 전부 보여 준다 */
export function 내마지막(줄들, 나이름 = 나) {
  for (let i = 줄들.length - 1; i >= 0; i -= 1) {
    if (/^##\s*\[진행\]/.test(줄들[i]) && 줄들[i].includes(나이름)) return i;
  }
  return -1;
}

/** ⛔ 사장님 말씀으로 보이는 것 — 맨 위로 올린다 */
export function 사장님것인가(줄) {
  return /사장님\s*(지시|말씀|께서)|사장님\(/.test(줄);
}

/**
 * 🔴🔴 2026-08-21 — **이 자가 커뮤니티 지시를 다섯 번 삼켰다.**
 *
 * 나는 덩어리마다 `[진행] 5번` 을 남긴다. 그래서 **한 줄 쓰는 순간, 그 앞의 지시가 전부
 * 「본 것」으로 넘어갔다.** 메모 줄 번호로 실측한 것 —
 * ```
 *   113640  [2번 → 5번] 커뮤니티 — 세 번째
 *   113815  [진행] 5번 04:2x      ← 여기서 113640 이 사라졌다
 *   113910  [2번 → 5번] 커뮤니티 — 네 번째
 *   114057  [진행] 5번 05:4x      ← 여기서 113910 이 사라졌다
 * ```
 * ⭐ 8/15 에 「나에게 온 것으로 좁히면 놓친다」를 고치며 만든 자인데,
 *   **시간축으로는 여전히 좁히고 있었다.** 같은 병을 다른 축에서 되풀이했다.
 *
 * ⭐ 그래서 「본 것」의 뜻을 바꾼다 —
 *   ⛔ 「내가 그 뒤에 뭔가 썼다」가 아니다.
 *   ✅ **「내가 봤다고 표시했다」**뿐이다. 표시는 `--봤다` 로만 되고 저절로 되지 않는다.
 */
export const 본것길 = path.join(뿌리, 'docs', '5번-본지시.json');

/** 제목 한 줄을 열쇠로 — `##` 과 앞뒤 공백만 뗀 글자 그대로 */
export function 열쇠(줄) {
  return String(줄 ?? '').replace(/^##\s*/, '').trim();
}

export function 본것읽기(길 = 본것길) {
  try {
    const j = JSON.parse(fs.readFileSync(길, 'utf8'));
    return new Set(Array.isArray(j.본것) ? j.본것 : []);
  } catch { return new Set(); }
}

export function 본것쓰기(본것, 길 = 본것길) {
  fs.writeFileSync(길, `${JSON.stringify({
    설명: '5번이 「봤다」고 표시한 지시 제목. ⛔ 저절로 안 채워진다 — --봤다 로만 채운다.',
    갱신: new Date().toISOString().slice(0, 19),
    본것: [...본것],
  }, null, 1)}\n`);
}

/**
 * ⭐ **아직 봤다고 표시하지 않은** 공지 제목 전부.
 * ⛔ 「나에게 온 것」으로 안 좁힌다 — 좁혀서 놓쳤다(8/15).
 * ⛔ 「내 진행 줄 뒤」로도 안 좁힌다 — 그래서 놓쳤다(8/21).
 *
 * ⚠ `바닥` 은 **처음 한 번만** 쓴다. 메모가 십만 줄이라 옛것을 다 띄우면 못 읽는다.
 *   그 뒤로는 바닥이 안 움직인다 — 표시하지 않는 한 아무것도 조용히 지나가지 않는다.
 */
export function 새공지(글, 나이름 = 나, 본것 = new Set(), 바닥 = -1) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  const 것들 = [];
  줄들.forEach((줄, i) => {
    if (i < 바닥) return;
    if (!/^##\s/.test(줄)) return;
    if (진행줄인가(줄)) return;
    const k = 열쇠(줄);
    if (본것.has(k)) return;
    것들.push({ 줄: k, 자리: i, 사장님: 사장님것인가(줄) });
  });
  /* ⛔ 사장님 것이 맨 위로 */
  return {
    내마지막줄: 내마지막(줄들, 나이름),
    것들: [...것들].sort((a, b) => (b.사장님 ? 1 : 0) - (a.사장님 ? 1 : 0)),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
  && process.argv.includes('--selftest')) {
  const 잼 = []; const 참 = (n, v) => 잼.push([n, !!v]);

  참('진행 줄을 알아본다', 진행줄인가('## [진행] 3번 21:07  했다: …'));
  참('실적 줄도 알아본다', 진행줄인가('## [실적] 6번 2026-08-15'));
  참('⛔ 공지는 진행 줄이 아니다', 진행줄인가('## [2번 → 모두] 하루 리듬을 정합니다') === false);

  const 글 = ['## [진행] 5번 20:03  했다: …',
    '## [2번 → 모두] 하루 리듬을 정합니다',
    '## [진행] 3번 21:07  했다: …',
    '## 📌 사장님 지시 — 실적은 매일 보고해',
    '## [4번 → 1번] 뭔가'].join('\n');
  const r = 새공지(글);
  참('⭐ 내 마지막 진행 줄을 찾는다', r.내마지막줄 === 0);
  /* ⛔ 「나에게 온 것」으로 좁히면 놓친다 — 그래서 전부 본다 */
  참('⭐⭐ 전체 공지를 잡는다', r.것들.some((x) => /하루 리듬/.test(x.줄)));
  참('⭐ 남에게 온 것도 보여 준다', r.것들.some((x) => /\[4번 → 1번\]/.test(x.줄)));
  참('⛔ 남의 진행 줄은 안 센다', !r.것들.some((x) => /3번 21:07/.test(x.줄)));
  /* ⛔ 사장님 것이 맨 위 */
  참('⭐ 사장님 것이 맨 위로 온다', 사장님것인가(r.것들[0].줄));

  /**
   * 🔴🔴 이 세 줄이 이 자를 고친 까닭이다. 커뮤니티 지시를 다섯 번 삼킨 자리다.
   *   내 진행 줄 **앞**에 있는 지시도 표시하기 전까지는 계속 보여야 한다.
   */
  const 앞선지시 = ['## [2번 → 5번] 커뮤니티 — 세 번째',
    '## [진행] 5번 04:2x  했다: …',
    '## [2번 → 5번] 커뮤니티 — 네 번째',
    '## [진행] 5번 05:4x  했다: …'].join('\n');
  const 앞 = 새공지(앞선지시);
  참('⛔⛔ 내 진행 줄보다 앞의 지시도 보여 준다', 앞.것들.length === 2);
  참('⛔⛔ 내가 뒤에 글을 썼다고 본 것이 되지 않는다',
    앞.것들.some((x) => /세 번째/.test(x.줄)) && 앞.것들.some((x) => /네 번째/.test(x.줄)));
  참('⭐ 봤다고 표시한 것만 사라진다',
    새공지(앞선지시, 나, new Set(['[2번 → 5번] 커뮤니티 — 세 번째'])).것들.length === 1);

  /* ⚠ 바닥 아래는 안 본다 — 십만 줄을 다 띄우면 못 읽는다. 바닥은 처음 한 번만 정한다 */
  참('바닥 아래는 안 본다', 새공지(앞선지시, 나, new Set(), 2).것들.length === 1);

  참('열쇠는 ## 과 공백을 뗀다', 열쇠('##   [2번 → 5번] 가  ') === '[2번 → 5번] 가');

  참('⛔ 빈 글도 견딘다', 새공지('').것들.length === 0);
  참('⛔ null 도 견딘다', 새공지(null).것들.length === 0);
  참('⭐ 메모가 실제로 있다', fs.existsSync(메모길));

  const 진 = 잼.filter(([, ok]) => !ok);
  console.log(`자가시험 ${잼.length}개 · ${진.length ? `🔴 ${진.length}개 실패` : '✅ 전부 통과'}`);
  for (const [n] of 진) console.log(`   🔴 ${n}`);
  process.exit(진.length ? 1 : 0);
}

const 내가실행됐다 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다) {
  const 글 = fs.readFileSync(메모길, 'utf8');
  const 줄수 = 글.split(/\r?\n/).length;
  const 처음인가 = !fs.existsSync(본것길);
  const 본것 = 본것읽기();

  /**
   * ⚠ 처음 한 번만 바닥을 놓는다 — 십만 줄의 옛 제목을 다 띄우면 아무도 못 읽는다.
   * ⛔ 그 뒤로 바닥은 안 움직인다. **표시하지 않는 한 아무것도 조용히 지나가지 않는다.**
   */
  let 바닥 = -1;
  if (처음인가) {
    const 줄들 = 글.split(/\r?\n/);
    바닥 = Math.max(0, 내마지막(줄들) - 400);
    console.log(`⚠ 처음 도는 것이라 **바닥을 ${바닥}번 줄에 한 번만** 놓는다(메모 ${줄수}줄).`);
    console.log('   그 뒤로 바닥은 안 움직인다 — 표시 안 하면 계속 뜬다.\n');
  }

  const { 것들 } = 새공지(글, 나, 본것, 바닥);

  if (process.argv.includes('--봤다')) {
    for (const x of 것들) 본것.add(x.줄);
    본것쓰기(본것);
    console.log(`✅ ${것들.length}건을 「봤다」로 표시했다 (누적 ${본것.size}건)`);
    console.log(`   → ${path.relative(뿌리, 본것길)}`);
    process.exit(0);
  }
  if (처음인가) 본것쓰기(본것);

  /* ⛔ 0건이면 조용히 있지 않는다. 「없다」를 말해야 봤다는 뜻이 된다 */
  if (!것들.length) {
    console.log('✅ 아직 안 본 지시가 없다.');
    process.exit(0);
  }

  console.log(`⚠ **아직 봤다고 표시하지 않은 지시 ${것들.length}건** — 전부 훑는다\n`);
  for (const x of 것들) {
    console.log(`   ${x.사장님 ? '🔴' : '·'} ${x.줄.slice(0, 88)}`);
  }
  console.log('\n⛔ 「나에게 온 것」으로 안 좁힌다 — 좁혀서 8/15 에 2번의 새 리듬을 놓쳤다.');
  console.log('⛔ 「내 진행 줄 뒤」로도 안 좁힌다 — 그래서 8/21 에 커뮤니티를 **다섯 번** 놓쳤다.');
  console.log('⚠ 이 목록은 제목만이다. 걸리는 것은 열어 본다.');
  console.log('   다 읽었으면 — node scripts/check-kcw-new-orders.mjs --봤다');
}
