/**
 * sitemap-new-urls.mjs — **사이트맵에서 「오늘 «새로 생긴» 지면」을 센다.**
 * (5번, 2026-09-23)
 *
 * ── 🔴 왜 만들었나 ────────────────────────────────────────────────────
 * 매시 점검이 「1번 몫 — 텍스트 1469 대 24」라고 말하고 있었다. 실제로 1번이 낸 글은
 * 한 편이었다. 나머지 1,468 은 **내가** 어제 찍은 생일 지면이고, 그것도 «새로 낸»
 * 것이 아니라 사이트맵의 `<lastmod>` 가 날마다 오늘로 바뀌고 있어서 세어진 것이다.
 *
 * ⛔ **`<lastmod>` 는 「새로 냈다」가 아니다.** 「내용이 바뀌었다(고 우리가 말한)」다.
 *   한 자료로 찍은 롱테일 수천 장이 한꺼번에 오늘로 찍히면 셈이 통째로 부푼다.
 *   그 수로 사장님께 「1번이 몫을 세 배 넘겼다」가 올라갈 뻔했다.
 *
 * ✅ 「새로 냈다」의 정직한 정의는 **어제 없던 `<loc>` 가 오늘 있는 것**이다.
 *   날짜를 믿지 않고 «주소»를 맞대어 센다.
 *
 * ── ⚠ 하루에 여러 번 돌아도 수가 사라지지 않게 ──────────────────────
 * 매시 점검이 하루 열몇 번 돈다. 잴 때마다 기준을 갈아끼우면 두 번째부터 0 이 되어
 * **오늘 낸 글이 화면에서 사라진다.** 그래서 두 가지를 함께 쌓는다 —
 *   ① 기준 목록(마지막으로 본 주소들)   ② 오늘까지 더해 온 셈
 * 잴 때마다 `오늘셈 += |지금 − 기준|` 하고 기준을 지금으로 옮긴다. 날이 바뀌면 셈만 0 으로.
 *
 * ⛔ 기준이 없으면(처음 재는 날) **null 을 낸다.** 0 으로 메꾸지 않는다 —
 *   0 으로 메꾸면 「오늘 아무도 안 냈다」는 «틀린 사실»이 보고에 올라간다.
 */
import fs from 'node:fs';
import path from 'node:path';

/** 사이트맵에서 `<loc>` 주소를 모두 뽑는다. 사이트맵이 아니면 null */
export function 주소뽑기(글) {
  if (글 == null) return null;
  const s = String(글);
  if (!/<urlset|<sitemapindex|<url>/i.test(s)) return null;
  const 것 = s.match(/<loc>\s*([^<\s]+)\s*<\/loc>/gi) || [];
  return 것.map((x) => x.replace(/<\/?loc>/gi, '').trim()).filter(Boolean);
}

/** 기준에 없던 주소가 몇 개인가. 기준이 없으면 null — 0 으로 메꾸지 않는다 */
export function 늘어난수(지금주소, 기준주소) {
  if (!Array.isArray(지금주소)) return null;
  if (!Array.isArray(기준주소) || !기준주소.length) return null;
  const 본것 = new Set(기준주소);
  return 지금주소.filter((u) => !본것.has(u)).length;
}

/**
 * 쌓아 둔 기준 파일을 읽는다.
 * 꼴 — 첫 두 줄이 `# 잰날 <날짜>` · `# 오늘셈 <수>`, 그 뒤로 주소 한 줄에 하나.
 */
export function 기준읽기(글) {
  if (글 == null) return null;
  const 줄 = String(글).split(/\r?\n/);
  const 날 = (줄.find((l) => l.startsWith('# 잰날')) || '').split(/\s+/)[2] || null;
  const 셈글 = (줄.find((l) => l.startsWith('# 오늘셈')) || '').split(/\s+/)[2];
  const 셈 = Number.isFinite(Number(셈글)) ? Number(셈글) : 0;
  const 주소 = 줄.map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  if (!주소.length) return null;
  return { 날, 셈, 주소 };
}

export function 기준쓰기(날, 셈, 주소) {
  return [`# 잰날 ${날}`, `# 오늘셈 ${셈}`,
    '# ⛔ 이 파일을 지우면 「오늘 새로 난 지면」을 하루 동안 못 센다',
    ...주소].join('\n') + '\n';
}

/**
 * ⭐ 알맹이 — 기준과 지금을 맞대어 «오늘까지 더해 온 셈»과 «새 기준»을 함께 낸다.
 * 날이 바뀌었으면 셈을 0 부터 다시 센다.
 */
export function 더해세기(기준, 지금주소, 오늘) {
  if (!Array.isArray(지금주소) || !오늘) return { 셈: null, 새기준: null };
  if (!기준) return { 셈: null, 새기준: 기준쓰기(오늘, 0, 지금주소) };   /* 처음 재는 날 */
  const 앞선셈 = 기준.날 === 오늘 ? 기준.셈 : 0;
  const 늘 = 늘어난수(지금주소, 기준.주소);
  const 셈 = 앞선셈 + (늘 ?? 0);
  return { 셈, 새기준: 기준쓰기(오늘, 셈, 지금주소) };
}

/**
 * 파일까지 다뤄 한 번에 잰다. 못 재면 null 을 내고 파일을 건드리지 않는다.
 * @returns {number|null} 오늘 새로 난 지면 수
 */
export function 오늘새로난지면(글, 오늘, 기준길) {
  const 지금 = 주소뽑기(글);
  if (!지금) return null;
  let 기준 = null;
  try { 기준 = 기준읽기(fs.readFileSync(기준길, 'utf8')); } catch { 기준 = null; }
  const { 셈, 새기준 } = 더해세기(기준, 지금, 오늘);
  if (새기준) {
    try {
      fs.mkdirSync(path.dirname(기준길), { recursive: true });
      fs.writeFileSync(기준길, 새기준, 'utf8');
    } catch { /* 못 써도 셈은 낸다 */ }
  }
  return 셈;
}

