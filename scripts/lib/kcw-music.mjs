/**
 * kcw-music.mjs — **배경음악을 «우리가 직접» 만든다.** 남의 음원을 안 쓴다.
 *
 * ── 왜 (2026-08-29) ───────────────────────────────────────────
 * 사장님 지시 — 「**자연스러운 목소리와 음성, 또는 배경음악을 너희들이 직접 만들어서
 * 사용하고**」·「**무성 콘텐트 다신 만들지 말 것**」
 *
 * ⛔ 남의 음원을 쓰지 않는 까닭은 「공짜인가」가 아니다. **소리 하나가 채널 전체를
 *   위태롭게 한다.** 우리가 만든 것이면 그 위험이 0 이다.
 * ⭐ 그리고 우리 것이어야 편마다 같은 소리를 써서 **채널의 목소리**가 생긴다.
 *
 * ── 무엇을 만드나 ─────────────────────────────────────────────
 * 표본을 하나씩 계산해 16비트 PCM WAV 로 낸다. 바깥 음원도, 악기 파일도 안 쓴다.
 * ```
 *   ① 깔개(pad)   으뜸음·5도·옥타브를 겹친 긴 음. 아주 여리게 깔린다
 *   ② 점점(motif) 5음 음계에서 고른 짧은 음 몇 개. 말소리 사이에 떨어진다
 *   ③ 숨결        아주 작은 잡음. 완전한 무음은 「끊긴 것」처럼 들린다
 * ```
 * ⛔ 5음 음계만 쓴다 — 어느 음을 겹쳐도 불협이 안 난다. 우리가 작곡가가 아니기 때문이다.
 * ⛔ 말소리를 이기지 않는다. 이 소리는 «배경»이고, 앞에 나오는 것은 목소리다.
 *
 * ── ⛔ 이 자가 지키는 것 ──────────────────────────────────────
 * ⛔ **Math.random 을 안 쓴다.** 같은 편은 언제 다시 만들어도 같은 소리여야 한다.
 *   씨앗은 편 이름이다 — 편이 다르면 소리도 조금 다르다.
 * ⛔ 표본이 -1~1 을 넘지 않게 깎는다. 넘으면 «찢어지는» 소리가 난다.
 */

/** 씨앗 문자열 → 0~1 을 내는 자. ⛔ Math.random 금지 — 같은 편은 같은 소리여야 한다 */
export function 씨앗난수(씨) {
  let h = 2166136261;
  for (const ch of String(씨 ?? '')) {
    h ^= ch.charCodeAt(0);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h ^= h << 13; h >>>= 0;
    h ^= h >> 17;
    h ^= h << 5; h >>>= 0;
    return h / 4294967296;
  };
}

/** 5음 음계(단조 계열). ⛔ 여기 밖의 음은 안 쓴다 — 겹쳐도 불협이 안 난다 */
export const 반음 = [0, 3, 5, 7, 10];

/** 반음 수 → 헤르츠. 기준은 A4 = 440 */
export function 음높이(반음수, 기준 = 220) {
  return 기준 * (2 ** (반음수 / 12));
}

/**
 * 여린 시작과 끝. ⛔ 갑자기 시작하면 「딱」 하고 튄다.
 * @returns 0~1
 */
export function 감쌈(위치, 오름 = 0.15, 내림 = 0.35) {
  const t = Math.min(Math.max(위치, 0), 1);
  if (t < 오름) return t / 오름;
  if (t > 1 - 내림) return (1 - t) / 내림;
  return 1;
}

/** 표본 하나를 -1~1 안으로. ⛔ 넘으면 찢어진다 */
export function 깎기(v) {
  if (!Number.isFinite(v)) return 0;
  return v > 1 ? 1 : (v < -1 ? -1 : v);
}

/**
 * 음 하나를 표본 배열에 «더한다».
 * ⚠ 배음을 조금 섞는다 — 순수 사인파만 쓰면 「삐-」 하는 시험 신호처럼 들린다.
 */
export function 음더하기(표본, 초당, { 시작, 길이, 헤르츠, 크기 }) {
  const 처음 = Math.max(0, Math.floor(시작 * 초당));
  const 끝 = Math.min(표본.length, Math.floor((시작 + 길이) * 초당));
  for (let i = 처음; i < 끝; i += 1) {
    const t = (i - 처음) / 초당;
    const 위치 = t / 길이;
    const e = 감쌈(위치);
    const w = Math.sin(2 * Math.PI * 헤르츠 * t)
      + 0.32 * Math.sin(2 * Math.PI * 헤르츠 * 2 * t)
      + 0.12 * Math.sin(2 * Math.PI * 헤르츠 * 3 * t);
    표본[i] += w * e * 크기 * 0.5;
  }
  return 표본;
}

/**
 * 한 편의 배경음악을 표본으로 짓는다.
 * @param 초 길이(초) · @param 씨 편 이름(같은 편 = 같은 소리)
 */
export function 음악표본(초 = 14, 씨 = 'kcw', 초당 = 44100) {
  const n = Math.max(1, Math.floor(초 * 초당));
  const 표본 = new Float32Array(n);
  const 난수 = 씨앗난수(씨);

  /* ① 깔개 — 으뜸음·5도·옥타브. 처음부터 끝까지 아주 여리게 */
  const 뿌리 = 반음[Math.floor(난수() * 반음.length)];
  for (const [간격, 크기] of [[0, 0.16], [7, 0.10], [12, 0.07]]) {
    음더하기(표본, 초당, { 시작: 0, 길이: 초, 헤르츠: 음높이(뿌리 + 간격, 110), 크기 });
  }

  /* ② 점점 — 말소리 사이에 떨어지는 짧은 음. 2.2초마다 하나 */
  const 사이 = 2.2;
  for (let t = 1.0; t < 초 - 1.0; t += 사이) {
    const 반 = 반음[Math.floor(난수() * 반음.length)];
    const 옥타브 = 난수() < 0.35 ? 12 : 0;
    음더하기(표본, 초당, {
      시작: t, 길이: 1.5, 헤르츠: 음높이(뿌리 + 반 + 옥타브, 440), 크기: 0.09,
    });
  }

  /* ③ 숨결 — 완전한 무음은 「끊겼다」로 들린다. 아주 작게 */
  let 앞 = 0;
  for (let i = 0; i < n; i += 1) {
    const r = (난수() * 2 - 1) * 0.012;
    앞 = 앞 * 0.96 + r * 0.04;                 /* 문질러서 「치-」 소리를 없앤다 */
    표본[i] = 깎기(표본[i] + 앞);
  }
  return 표본;
}

/** 표본 → 16비트 PCM WAV 바이트. ⛔ 바깥 라이브러리를 안 쓴다 */
export function wav바이트(표본, 초당 = 44100) {
  const n = 표본.length;
  const 몸 = Buffer.alloc(n * 2);
  for (let i = 0; i < n; i += 1) 몸.writeInt16LE(Math.round(깎기(표본[i]) * 32767), i * 2);
  const 머리 = Buffer.alloc(44);
  머리.write('RIFF', 0);
  머리.writeUInt32LE(36 + 몸.length, 4);
  머리.write('WAVE', 8);
  머리.write('fmt ', 12);
  머리.writeUInt32LE(16, 16);
  머리.writeUInt16LE(1, 20);            /* PCM */
  머리.writeUInt16LE(1, 22);            /* 채널 하나 */
  머리.writeUInt32LE(초당, 24);
  머리.writeUInt32LE(초당 * 2, 28);
  머리.writeUInt16LE(2, 32);
  머리.writeUInt16LE(16, 34);
  머리.write('data', 36);
  머리.writeUInt32LE(몸.length, 40);
  return Buffer.concat([머리, 몸]);
}
