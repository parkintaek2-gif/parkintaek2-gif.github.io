/**
 * 일주.mjs — 날짜 하나를 육십갑자 «일주(日柱)»로 옮긴다
 *
 * 🔴 왜 «일주만» 하나 —
 *   사주 여덟 글자는 년·월·일·시 네 기둥에 두 자씩이다.
 *   · 년주·월주는 «절기»에서 바뀐다(입춘·경칩…). 절입 시각을 천문으로 풀어야 한다
 *   · 시주는 **태어난 시각**이 있어야 선다. 스타의 출생 «시각»은 어디에도 공개돼 있지 않다
 *   · 일주만이 날짜 하나로 **셈이 딱 떨어진다** — 육십 날이 끊김 없이 돈다
 *   ⇒ 그래서 이 자는 일주까지만 낸다. 나머지는 «못 센다»고 적는다. 짐작으로 채우지 않는다.
 *
 * 기준점  1900-01-01 = 갑술(甲戌) — 육십갑자 10번(갑자를 0번으로 셀 때)
 *         아래 자가시험에서 널리 알려진 두 날로 이 기준점을 되짚는다.
 *
 * ⚠ 야자시(夜子時) — 밤 11시부터를 «다음 날»로 치는 학파가 있다.
 *   태어난 시각을 모르면 그 한 시간에 걸린 사람은 일주가 하루 어긋날 수 있다.
 *   이 자는 그것을 **숨기지 않는다** — 지면에 함께 적는다.
 */
export const 천간 = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
export const 천간한자 = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
export const 지지 = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];
export const 지지한자 = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
export const 십이동물 = ['쥐', '소', '호랑이', '토끼', '용', '뱀', '말', '양', '원숭이', '닭', '개', '돼지'];
export const 오행 = ['나무', '나무', '불', '불', '흙', '흙', '쇠', '쇠', '물', '물'];
export const 음양 = ['양', '음', '양', '음', '양', '음', '양', '음', '양', '음'];

const 기준 = Date.UTC(1900, 0, 1), 기준번호 = 10;   // 1900-01-01 = 갑술

/** 「1993-05-16」 → 육십갑자 번호(갑자=0 … 계해=59) */
export function 일진번호(날짜글) {
  const [y, m, d] = String(날짜글).split('-').map(Number);
  const 지난날 = Math.round((Date.UTC(y, m - 1, d) - 기준) / 86400000);
  return ((기준번호 + 지난날) % 60 + 60) % 60;
}

/** 날짜 하나를 일주 한 벌로 편다 */
export function 일주(날짜글) {
  const n = 일진번호(날짜글);
  const g = n % 10, z = n % 12;
  return {
    번호: n,
    일주: 천간[g] + 지지[z],
    일주한자: 천간한자[g] + 지지한자[z],
    일간: 천간[g], 일간한자: 천간한자[g],
    일지: 지지[z], 일지한자: 지지한자[z],
    오행: 오행[g], 음양: 음양[g],
    /* ⚠ 이것은 «띠»가 아니다. 띠는 년지에서 나오고 이것은 일지다.
       정국은 소띠(1997)인데 일지는 오(말)다 — 그대로 «띠»라 적으면 화면이 거짓말을 한다.
       이름을 «일지동물»로 못박아 둔다. 지면에 «띠»로 내보내지 않는다. */
    일지동물: 십이동물[z],
  };
}

/* ── 자가시험 ─────────────────────────────────────────── */
/* ⚠ 정규식을 셸로 옮기면 백슬래시가 먹힌다(8/20 또 겪었다). 셈 없이 끝만 견준다 */
const 내가직접불렸나 = !!process.argv[1] && process.argv[1].endsWith('일주.mjs');
if (내가직접불렸나 || process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };

  // 🔴 기준점을 «내가 정한 것»으로 두지 않는다. 널리 적혀 있는 두 날로 되짚는다
  본다('① 1900-01-01 이 갑술(甲戌)이다', 일주('1900-01-01').일주한자 === '甲戌');
  본다('② 2000-01-01 이 무오(戊午)다 — 널리 적힌 날', 일주('2000-01-01').일주한자 === '戊午');
  본다('③ 1949-10-01 이 갑자(甲子)다 — 널리 적힌 날', 일주('1949-10-01').일주한자 === '甲子');
  본다('④ 육십 날마다 되돌아온다', 일주('2000-01-01').일주 === 일주('2000-03-01').일주);
  본다('⑤ 하루 뒤는 한 칸 뒤다',
    (일진번호('2026-08-20') + 1) % 60 === 일진번호('2026-08-21'));
  본다('⑥ 윤달(2월 29일)을 건너뛰지 않는다',
    (일진번호('2024-02-28') + 2) % 60 === 일진번호('2024-03-01'));
  본다('⑦ 백 년을 돌려도 안 어긋난다',
    Array.from({ length: 40000 }, (_, i) => i).every((i) => {
      const d = new Date(Date.UTC(1900, 0, 1) + i * 86400000).toISOString().slice(0, 10);
      return 일진번호(d) === (10 + i) % 60;
    }));
  본다('⑧ ⛔ 시주를 세우지 않는다 — 이 자에는 시(時)가 없다',
    !Object.keys(일주('2000-01-01')).some((k) => k.includes('시')));

  console.log('\n2026-08-20 →', 일주('2026-08-20').일주, `(${일주('2026-08-20').일주한자})`);
}
