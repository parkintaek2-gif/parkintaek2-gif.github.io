/**
 * **지은 날을 영어 손님에게 보이는 꼴로** 바꾼다.
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 *   손님으로 걸어 보니 영어 지면에 **「Updated 2026. 8. 9. 오전 8:40:57 KST」** 가 박혀 있었다.
 *   「오전」은 한국어다. 영어권 손님을 받는 사이트에서 그 한 낱말이 화면에 있다.
 *
 * ── ⛔ 시각을 아예 안 보인다 ───────────────────────────────────
 *   ⛔ 그건 **빌드 시각**이지 자료의 날이 아니다. 손님에게 아무 뜻이 없고,
 *      빌드마다 바뀌어서 **같은 지면이 어제와 다른 수를 보인다.**
 *   ⭐ 그래서 **날짜만** 남긴다. 시·분·초는 버린다.
 */

/**
 * 한국 말투 날짜 문자열에서 **날짜만** 뽑아 `YYYY-MM-DD` 로 준다.
 * ⛔ 못 읽으면 **지어내지 않고 null** 을 준다. 지면이 그때는 아무것도 안 적는다.
 * @param 값 예: `2026. 8. 9. 오전 8:40:57` · `2026-08-09T…` · `2026. 12. 25.`
 */
export function 지은날(값) {
  const s = String(값 ?? '').trim();
  if (!s) return null;
  /* ISO 꼴이면 앞 열 글자가 곧 날짜다 */
  const iso = /^(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if (iso) return `${iso[1]}-${iso[2]}-${iso[3]}`;
  /* `2026. 8. 9.` 꼴 */
  const ko = /^(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\./.exec(s);
  if (ko) return `${ko[1]}-${String(ko[2]).padStart(2, '0')}-${String(ko[3]).padStart(2, '0')}`;
  return null;
}

/**
 * 지면에 그대로 넣을 한 조각. 못 읽으면 **빈 글자**라 아무것도 안 나간다.
 * ⛔ 「Updated unknown」 같은 것을 안 낸다 — 모르면 말을 안 한다.
 */
export function 지은날글(값) {
  const d = 지은날(값);
  return d ? `Updated ${d} (KST).` : '';
}
