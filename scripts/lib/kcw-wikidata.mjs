/**
 * kcw-wikidata.mjs — **위키데이터 원자료를 «Q로 열리는 하나의 꼴»로 읽는다.**
 *
 * ── 왜 만들었나 (2026-08-28 새벽) ──────────────────────────────
 * 네 파일의 열쇠 꼴이 **서로 다르다.**
 * ```
 *   korean-entertainers-birth.json    🔴 번호 열쇠(0,1,2…) · Q 는 줄 «안»에
 *   korean-entertainers-school.json   🔴 번호 열쇠
 *   korean-groups.json                🔴 번호 열쇠
 *   korean-entertainers-roles.json    ✅ Q 열쇠
 * ```
 * 🔴 **하룻밤에 이것으로 두 번 넘어졌다.**
 *   ① 학교 × 그룹소속을 교차했더니 **모든 학교의 아이돌이 0명**으로 나왔다.
 *      그대로 「학교와 아이돌은 상관없다」는 기사를 쓸 뻔했다.
 *   ② 한 시간 뒤 생일 × 그룹소속을 교차했더니 **또 0명**이 나왔다.
 *
 * ⚠ **두 번째가 중요하다.** 한 번은 실수지만 두 번은 «구조»다.
 *   조심해서 될 일이 아니라, **읽는 자리를 하나로 만들어야 하는 일**이다.
 *   ⭐ 그래서 이 파일이 있다. 앞으로 원자료는 여기로만 읽는다.
 *
 * ── ⛔ 이 자가 지키는 것 ──────────────────────────────────────
 * ⛔ **줄 안의 `q` 를 믿는다.** 열쇠가 Q 처럼 생겨도 줄 안에 `q` 가 있으면 그것을 쓴다.
 *    두 값이 어긋나면 **줄 안의 것**이 원본이다(파일을 만든 자가 거기에 적었다).
 * ⛔ **q 가 없는 줄은 버리고, 몇 줄 버렸는지 돌려준다.** 조용히 빠뜨리지 않는다.
 * ⚠ 이 자는 파일을 «고치지» 않는다. 원자료는 그대로 두고 읽는 쪽만 맞춘다 —
 *   원자료를 손대면 다시 캘 때 또 어긋난다.
 */
import fs from 'node:fs';
import path from 'node:path';

/** 원자료가 사는 곳 */
export const 원자료방 = 'archive/raw/wikidata';

/**
 * `{사람:{…}}` 이든 `{그룹:{…}}` 이든, **Q → 줄** 인 Map 으로 바꾼다.
 * @param {object} 덩어리  파일에서 읽은 객체(또는 그 안의 사람/그룹 부분)
 * @returns {{표: Map<string, object>, 버린줄: number, 열쇠꼴: '번호'|'Q'|'빈것'}}
 */
export function Q로열기(덩어리) {
  const 뿌리 = (덩어리 && (덩어리.사람 ?? 덩어리.그룹)) ?? 덩어리 ?? {};
  const 열쇠들 = Object.keys(뿌리);
  const 표 = new Map();
  let 버린줄 = 0;
  for (const k of 열쇠들) {
    const 줄 = 뿌리[k];
    if (!줄 || typeof 줄 !== 'object') { 버린줄 += 1; continue; }
    /* ⛔ 줄 안의 q 를 먼저 본다. 없으면 열쇠가 Q 인지 보고, 그것도 아니면 버린다 */
    const q = 줄.q ?? (/^Q\d+$/.test(k) ? k : null);
    if (!q) { 버린줄 += 1; continue; }
    표.set(String(q), 줄);
  }
  const 열쇠꼴 = 열쇠들.length === 0 ? '빈것'
    : (/^\d+$/.test(열쇠들[0]) ? '번호' : 'Q');
  return { 표, 버린줄, 열쇠꼴 };
}

/**
 * 파일 이름으로 읽어 Q Map 을 준다.
 * ⚠ 파일이 없으면 **빈 Map 과 함께 「못 읽었다」를 돌려준다.** 서지 않는다 —
 *   빌더 하나가 다른 자료에 목숨을 걸면 순서가 바뀔 때 둘 다 못 돈다.
 */
export function 원자료읽기(파일이름, 뿌리 = process.cwd()) {
  const 길 = path.join(뿌리, 원자료방, 파일이름);
  if (!fs.existsSync(길)) return { 표: new Map(), 버린줄: 0, 열쇠꼴: '빈것', 못읽음: `없다: ${파일이름}` };
  try {
    return { ...Q로열기(JSON.parse(fs.readFileSync(길, 'utf8'))), 못읽음: null };
  } catch (e) {
    return { 표: new Map(), 버린줄: 0, 열쇠꼴: '빈것', 못읽음: e.message };
  }
}

/**
 * 두 자료를 Q 로 맞춘다. **겹친 수를 같이 돌려준다 — 0 이면 부른 쪽이 알아야 한다.**
 * ⭐ 오늘 두 번 넘어진 자리가 정확히 여기다. 겹친 수를 «돌려주는 것»이 이 함수의 핵심이다.
 */
export function 맞추기(왼쪽, 오른쪽) {
  const 겹친것 = new Map();
  for (const [q, a] of 왼쪽) {
    const b = 오른쪽.get(q);
    if (b === undefined) continue;
    겹친것.set(q, { ...a, ...b });
  }
  return { 표: 겹친것, 겹친수: 겹친것.size, 왼쪽수: 왼쪽.size, 오른쪽수: 오른쪽.size };
}

/* ── 자가시험 ─────────────────────────────────────────────── */
const 직접 = process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('kcw-wikidata.mjs');
if (직접) {
  let 통과 = 0;
  const T = (이름, 참) => { if (참) { 통과 += 1; return; } console.error(`  ✗ ${이름}`); process.exitCode = 1; };

  const 번호꼴 = { 사람: { 0: { q: 'Q1', born: '1993-05-16' }, 1: { q: 'Q2', born: '1980-01-02' } } };
  const Q꼴 = { 사람: { Q1: { grp: true }, Q2: { grp: false } } };

  const a = Q로열기(번호꼴);
  T('번호 열쇠라도 Q 로 열린다', a.표.get('Q1')?.born === '1993-05-16');
  T('열쇠 꼴을 알려 준다', a.열쇠꼴 === '번호');
  const b = Q로열기(Q꼴);
  T('Q 열쇠도 그대로 열린다', b.표.get('Q1')?.grp === true);
  T('Q 열쇠 꼴을 알려 준다', b.열쇠꼴 === 'Q');

  const 맞춘것 = 맞추기(a.표, b.표);
  T('🔴 두 꼴이 달라도 맞는다 — 오늘 두 번 넘어진 자리다', 맞춘것.겹친수 === 2);
  T('맞춘 줄이 양쪽 칸을 다 갖는다',
    맞춘것.표.get('Q1').born === '1993-05-16' && 맞춘것.표.get('Q1').grp === true);
  T('겹친 수를 돌려준다 — 0 이면 부른 쪽이 알아야 한다', 맞춘것.왼쪽수 === 2 && 맞춘것.오른쪽수 === 2);

  const 안맞는것 = 맞추기(a.표, Q로열기({ 사람: { Q99: { grp: true } } }).표);
  T('안 겹치면 0 을 «말해» 준다', 안맞는것.겹친수 === 0);

  const 흠난것 = Q로열기({ 사람: { 0: { born: '없다' }, 1: null, 2: { q: 'Q3' } } });
  T('q 없는 줄을 버린다', 흠난것.표.size === 1);
  T('버린 줄 수를 돌려준다 — 조용히 빠뜨리지 않는다', 흠난것.버린줄 === 2);

  T('줄 안의 q 가 열쇠보다 앞선다',
    Q로열기({ 사람: { Q7: { q: 'Q8' } } }).표.has('Q8'));
  T('빈 것도 안 깨진다', Q로열기({}).표.size === 0 && Q로열기(null).열쇠꼴 === '빈것');

  console.log(`자가시험 ${통과}개 통과`);
}
