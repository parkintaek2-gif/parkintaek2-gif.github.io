/**
 * work-hours.mjs — **업무 시간과 쉬는 시간을 가른다.**
 *
 * ── 왜 (2026-08-30) ───────────────────────────────────────────
 * 사장님이 5번의 시간을 정해 주셨다.
 * > 「**너도 지금부터 하루 13시간 업무를 한다. 11시~01시가 업무 시간,
 * >  01시~10시59분까지 쉬는 시간이다.**」
 *
 * 🔴 그런데 `check-no-idle-hours.mjs` 는 그것을 모른다. 그래서 02:17 에 돌리니
 *   **❌ 쉬었다** 가 나왔다 — **쉬라고 하신 시간에 쉰 것을 흠으로 잡은 것**이다.
 * ⛔ 그대로 두면 **매일 밤 거짓 경보**가 난다. 늘 우는 자는 아무도 안 듣게 되고,
 *   그러면 **정말 쉬었을 때도 못 잡는다.** 자가 쓸모를 잃는 길이다.
 *
 * ⭐ 그래서 「몇 시간 조용했나」가 아니라 **「그중 «일해야 했던» 시간이 몇 분인가」**를 센다.
 *
 * ── ⛔ 이 자가 지키는 것 ──────────────────────────────────────
 * ⛔ 쉬는 시간을 «없던 일»로 만들지 않는다. 겹친 분을 «빼는» 것뿐이다.
 * ⛔ 자정을 넘는 업무 시간(11:00~01:00)을 한 덩어리로 다룬다 — 날짜로 자르지 않는다.
 * ⚠ 시간표가 바뀌면 여기 한 곳만 고친다. 두 군데 적으면 반드시 갈라진다.
 */

/** 사장님이 정해 주신 업무 시간. ⛔ 두 군데 적지 않는다 */
export const 업무시작시 = 11;   /* 11:00 */
export const 업무끝시 = 1;      /* 다음 날 01:00 */

/** 이 시각이 업무 시간인가. 11:00~24:00 과 00:00~01:00 이 업무다 */
export function 업무시간인가(때) {
  const d = 때 instanceof Date ? 때 : new Date(때);
  if (Number.isNaN(d.getTime())) return null;      /* ⛔ 모르면 null — 참도 거짓도 아니다 */
  const h = d.getHours();
  return h >= 업무시작시 || h < 업무끝시;
}

/** 쉬는 시간인가 — 업무시간인가()의 반대. ⛔ null 은 그대로 null */
export function 쉬는시간인가(때) {
  const v = 업무시간인가(때);
  return v === null ? null : !v;
}

/**
 * 두 시각 «사이»에서 업무 시간에 해당하는 **분**을 센다.
 * ⭐ 이것이 이 파일의 알맹이다 — 「열 시간 조용했다」가 아니라
 *   「그중 일해야 했던 것은 몇 분인가」를 답한다.
 * ⛔ 못 세면 null 이다. 0 이 아니다 — 0 은 「일해야 할 시간이 없었다」는 뜻이다.
 */
export function 업무분(시작, 끝) {
  const a = 시작 instanceof Date ? 시작 : new Date(시작);
  const b = 끝 instanceof Date ? 끝 : new Date(끝);
  if (Number.isNaN(a.getTime()) || Number.isNaN(b.getTime())) return null;
  if (b <= a) return 0;
  /* ⚠ 분 단위로 훑는다. 우리가 재는 틈은 길어야 하루라 이 값이면 넉넉하다.
     ⛔ 너무 길면 세다가 멈추지 말고 «못 쟀다»로 답한다 — 틀린 수보다 낫다. */
  const 분수 = Math.round((b - a) / 60000);
  if (분수 > 60 * 24 * 3) return null;
  let n = 0;
  const t = new Date(a.getTime());
  for (let i = 0; i < 분수; i += 1) {
    if (업무시간인가(t)) n += 1;
    t.setMinutes(t.getMinutes() + 1);
  }
  return n;
}

/**
 * 「HH:MM」 두 시각 사이의 «업무» 분. 진행 줄의 틈을 잴 때 쓴다.
 *
 * 🔴 [2026-08-31] **틈만 벽시계로 재고 있었다.**
 *   14:17 에 자물쇠를 돌리니 「진행 줄 사이 가장 큰 틈 553분」으로 ❌ 가 났다.
 *   그 553분은 **사장님이 쉬라고 하신 01:00~10:59** 이다(마지막 줄 00:5x → 다음 11:3x).
 * ⛔ 이 파일이 만들어진 까닭이 바로 그 거짓 경보인데, 「마지막 이후」에만 쓰이고
 *   **틈에는 안 쓰이고 있었다.** 반만 고친 것이다 — 그래서 매일 오후마다 또 울렸다.
 * ⚠ 시간표를 여기 다시 적지 않는다 — `업무시간인가()` 에게 물어서 센다.
 * ⛔ 못 읽으면 null 이다. 0 이 아니다.
 */
export function 업무틈분(앞, 뒤) {
  const 분으로 = (t) => {
    const m = String(t ?? '').match(/^(\d{1,2}):(\d{2})$/);
    if (!m) return null;
    const h = Number(m[1]); const i = Number(m[2]);
    if (h > 23 || i > 59) return null;
    return h * 60 + i;
  };
  const a = 분으로(앞); const b = 분으로(뒤);
  if (a === null || b === null) return null;
  if (b <= a) return 0;                     /* 뒤로 가는 걸음 — 날이 바뀐 것이라 안 센다 */
  /* ⚠ 날짜는 아무 날이나 좋다. 우리 시간표는 매일 같으므로 요일을 안 본다 */
  const 기준 = new Date(2026, 0, 5, 0, 0, 0, 0);
  const 때 = (분) => new Date(기준.getTime() + 분 * 60000);
  return 업무분(때(a), 때(b));
}

/** 사람이 읽는 말로. ⛔ 못 잰 것은 「0분」이라 안 쓴다 */
export function 업무분말(분) {
  if (분 === null || 분 === undefined) return '못 쟀다';
  if (분 < 60) return `${분}분`;
  const h = Math.floor(분 / 60);
  const m = 분 % 60;
  return m ? `${h}시간 ${m}분` : `${h}시간`;
}

/* ── 자가시험 ─────────────────────────────────────────────── */
export function 자가시험() {
  const 실패 = [];
  const 검 = (이름, 참) => { if (!참) 실패.push(이름); };
  const 때 = (s) => new Date(`2026-08-30T${s}:00`);

  검('11:00 은 업무다', 업무시간인가(때('11:00')) === true);
  검('정오는 업무다', 업무시간인가(때('12:00')) === true);
  검('23:59 는 업무다', 업무시간인가(때('23:59')) === true);
  검('00:30 은 업무다 — 자정을 넘어간다', 업무시간인가(때('00:30')) === true);
  검('🔴 01:00 은 쉼이다', 업무시간인가(때('01:00')) === false);
  검('02:17 은 쉼이다 — 이 자를 세운 까닭이다', 쉬는시간인가(때('02:17')) === true);
  검('10:59 는 쉼이다', 쉬는시간인가(때('10:59')) === true);
  검('⛔ 모르는 시각은 null — 참도 거짓도 아니다',
    업무시간인가('아무거나') === null && 쉬는시간인가('아무거나') === null);

  검('업무 시간 한복판 한 시간은 60분',
    업무분(때('13:00'), 때('14:00')) === 60);
  검('🔴 쉬는 시간 한복판은 «0분» — 일해야 할 시간이 없었다',
    업무분(때('03:00'), 때('05:00')) === 0);
  검('⭐ 01:00 을 걸치면 앞쪽만 센다',
    업무분(때('00:30'), 때('01:30')) === 30);
  검('⭐ 11:00 을 걸치면 뒤쪽만 센다',
    업무분(때('10:30'), 때('11:30')) === 30);
  검('⭐⭐ 어젯밤 20:30 부터 오늘 02:17 까지 — 쉼을 뺀 것이 나온다', (() => {
    const 시작 = new Date('2026-08-29T20:30:00');
    const 끝 = new Date('2026-08-30T02:17:00');
    /* 20:30~01:00 이 업무(270분) · 01:00~02:17 은 쉼 */
    return 업무분(시작, 끝) === 270;
  })());
  검('⛔ 거꾸로 주면 0', 업무분(때('14:00'), 때('13:00')) === 0);
  검('⛔ 못 읽으면 null 이지 0 이 아니다', 업무분('아무거나', 때('13:00')) === null);
  검('⛔ 너무 길면 «못 쟀다» — 틀린 수보다 낫다',
    업무분(new Date('2026-01-01T00:00:00'), new Date('2026-08-30T00:00:00')) === null);

  검('말로 바꾼다', 업무분말(0) === '0분' && 업무분말(90) === '1시간 30분' && 업무분말(120) === '2시간');
  검('⛔ 못 잰 것을 「0분」이라 안 쓴다', 업무분말(null) === '못 쟀다');

  /* ⭐ 오늘 실제로 난 틈이다 — 마지막 진행 줄 00:5x, 다음 11:3x. 벽시계로는 640분인데
     업무로는 40분뿐이다(00:50~01:00 의 10분 + 11:00~11:30 의 30분).
     ⚠ 이 시험을 처음엔 80 으로 적었다가 자가시험에 걸렸다 — 내 셈이 틀렸던 것이다. */
  검('⭐ 쉬는 시간을 걸친 긴 틈은 «업무 분»만 남는다', 업무틈분('00:50', '11:30') === 40);
  검('업무 시간 안의 틈은 그대로 센다', 업무틈분('13:00', '14:30') === 90);
  검('⭐ 01:00 을 걸친 틈은 앞쪽만 센다', 업무틈분('00:30', '02:00') === 30);
  검('⛔ 뒤로 가는 걸음은 0', 업무틈분('23:00', '01:00') === 0);
  검('⛔ 못 읽으면 null 이지 0 이 아니다', 업무틈분('아무거나', '13:00') === null);
  검('⛔ 25:00 같은 것도 null', 업무틈분('25:00', '26:00') === null);

  return 실패;
}

if (process.argv[1] && process.argv[1].endsWith('work-hours.mjs')) {
  const 실패 = 자가시험();
  if (실패.length) {
    console.error(`❌ work-hours 자가시험 실패 ${실패.length}\n${실패.map((s) => `   · ${s}`).join('\n')}`);
    process.exit(1);
  }
  console.log('✅ work-hours 자가시험 통과 (24)');
}
