/**
 * 🔴 그 자리의 **설정폴더**. 단추(.cmd)가 `CLAUDE_CONFIG_DIR` 로 이것을 심어야 한다.
 *
 * ⛔ 안 심으면 기본값 `.claude` 가 열린다 — 그러면 사장님이 단추를 눌렀을 때
 *   «그 자리의 대화가 없는 빈 창»이 뜬다. 2026-08 에 그렇게 나흘치를 잃었다.
 */
export function 설정폴더(번호) {
  return `C:\\Users\\USER\\.claude-u${번호}`;
}

/** 그 자리의 대화록 뿌리 — 지킴이와 사장님 한 줄 확인이 여기를 훑는다 */
export function 대화록뿌리(번호) {
  return `C:/Users/USER/.claude-u${번호}/projects`;
}

/**
 * 훑을 대화록 뿌리들.
 * ⚠ 옛 폴더(`.claude`)는 그대로 둔다 — 2026-08-21 에 여섯이 «전부» 거기서 자라고 있었다.
 *   자리가 잘못된 폴더를 쓰는 것을 잡으려면 그 폴더도 봐야 한다.
 */
export function 대화록뿌리들({ 옛폴더 = true } = {}) {
  const 것 = 자리번호.map(대화록뿌리);
  return 옛폴더 ? ['C:/Users/USER/.claude/projects', ...것] : 것;
}

/** 지금 도는 자리인가 */
export function 도나(번호) {
  return Object.prototype.hasOwnProperty.call(도는자리, Number(번호));
}
