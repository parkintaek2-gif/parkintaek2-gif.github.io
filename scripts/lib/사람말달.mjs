/**
 * 사람말달.mjs — 「2026-06」을 「2026년 6월」로.
 *
 * 🔴 왜 따로 두나 — 카드 자가시험이 «06» 을 「자료에 없는 수」로 셌다.
 *   맞는 지적이다. 0 이 앞에 붙은 06 은 자료 어디에도 없는 글자다.
 *   ⇒ 사람이 읽는 말로 바꾸면 6 이 되어 쪽번호와 함께 걸러지고, **화면도 이쪽이 낫다.**
 *
 * ⚠ 이 정규식을 셸(heredoc·sed)로 옮기다 백슬래시가 네 번 먹혔다(8/20).
 *   그래서 아예 파일로 떼어 둔다 — 다음 사람이 셸로 옮길 일이 없게.
 */
export function 사람말달(값) {
  return String(값).replace(/^(\d{4})-0?(\d+)$/, '$1년 $2월');
}
