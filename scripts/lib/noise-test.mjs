export function 재기() {
  const 참 = []; const 거 = [];
  const 봄 = (이름, 값) => (값 ? 참 : 거).push(이름);

  봄('빈 값에서 분위는 null (0 으로 채우지 않는다)', 분위([], 0.5) === null);
  /* [1,null,'x',3,2] → 걸러 [1,2,3] → floor(3*0.5)=1 자리 → 2.
     ⚠ 처음에 3 이라 적었다가 자가시험에 잡혔다. 자리 고르는 법을 한 곳에 둔 값이 이것이다 */
  봄('숫자 아닌 것을 걸러낸다', 분위([1, null, 'x', 3, 2], 0.5) === 2);
  봄('수로 는 빈 문자열을 null 로', 수로('') === null && 수로('3') === 3);

  const a = 난수기(1)(); const b = 난수기(1)();
  봄('같은 씨앗은 같은 수를 낸다 (다시 잴 수 있다)', a === b);
  봄('다른 씨앗은 다른 수를 낸다', 난수기(1)() !== 난수기(2)());

  /* ⭐ 자가 «울릴 수 있음»을 보인다 — 안 울리는 자는 자가 아니다 */
  const 같은무리 = Array.from({ length: 400 }, (_, i) => (i % 7) + 1);
  const 울림 = 잡음시험(같은무리, 3, 8, 2000);
  봄('작은 표본이면 잡음시험이 «울린다»', 울림.이하비율 > 문턱 && 울림.못쟀다고적어야하나 === true);
  const 안울림 = 잡음시험(같은무리, 0.0001, 300, 2000);
  봄('폭이 정말 좁으면 «안 울린다»', 안울림.이하비율 <= 문턱 && 안울림.못쟀다고적어야하나 === false);

  봄('결과에 씨앗을 실어 돌려준다', 울림.씨앗 === 씨앗 && 울림.문턱 === 문턱);
  봄('같은 입력이면 같은 답 (두 번 돌려도)',
    잡음시험(같은무리, 3, 8, 2000).이하비율 === 울림.이하비율);

  const w = 윌슨구간(5, 10);
  봄('윌슨구간이 0~1 안에 있다', w.아래 > 0 && w.위 < 1);
  봄('윌슨구간은 작은 n 에서도 0 아래로 안 내려간다', 윌슨구간(0, 5).아래 >= 0);
  봄('전체가 0 이면 null (나누지 않는다)', 윌슨구간(0, 0) === null);

  봄('겹치는 구간을 겹친다고 한다', 겹치나({ 아래: 0, 위: 2 }, { 아래: 1, 위: 3 }) === true);
  봄('안 겹치는 구간을 안 겹친다고 한다', 겹치나({ 아래: 0, 위: 1 }, { 아래: 2, 위: 3 }) === false);
  봄('한쪽이 없으면 null (짐작하지 않는다)', 겹치나(null, { 아래: 0, 위: 1 }) === null);

  const 양끝 = 양끝잡음시험([{ n: 20 }, { n: 20 }, { n: 20 }, { n: 20 }, { n: 20 }, { n: 20 }, { n: 20 }, { n: 20 }], 0.5, 600);
  봄('여덟을 굴리면 양끝 헛경보가 «생긴다»', 양끝.헛경보비율 > 0);
  봄('양끝잡음시험도 씨앗을 실어 돌려준다', 양끝.씨앗 === 씨앗);

  const 구간 = 중간구간([1, 2, 3, 4, 5, 6, 7, 8], 500);
  봄('중간구간이 아래<=위 로 나온다', 구간.아래 <= 구간.위);
  봄('빈 값이면 중간구간은 null', 중간구간([], 100) === null);
  return { 참: 참.length, 거: 거.length, 틀린것: 거 };
}

