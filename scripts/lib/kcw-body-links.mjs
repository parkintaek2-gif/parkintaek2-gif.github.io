/**
 * kcw-body-links.mjs — **기사 본문에 나가는 문이 있나**를 판정하는 **한 곳**.
 *
 * ── 왜 파일을 따로 뽑나 (2026-08-22) ─────────────────────────
 * 이 규칙이 두 곳에 베껴져 있었다 — `fix-kcw-body-doors.mjs` 와 `check-visitor-walk.mjs`.
 * 그날 앞엣것만 고쳤다(「전체 주소로 건 링크도 문이다」). 뒤엣것은 그대로여서
 * **멀쩡한 기사 열 편을 「문이 없다」고 거짓으로 울렸다.**
 *
 * ⭐ 회사 규칙 ⑤ — 하나를 고치면 인용한 곳까지 따라간다. 베낀 규칙은 반드시 갈라진다.
 *   그래서 규칙을 **파일 하나**에 두고 둘이 가져다 쓴다. 한 곳을 고치면 둘이 같이 산다.
 * ⛔ CLI 를 여기에 두지 않는다 — 가져다 쓰는 쪽이 명령줄 검사에 걸려 서면 안 된다.
 */

/** 앞말을 뗀다. ⚠ CRLF 로 저장된 편이 섞여 있다 — `\n` 만 보면 한 편을 놓친다 */
export const 본문떼기 = (원본) => String(원본).replace(/^---[\s\S]*?\r?\n---/, '');

/**
 * 본문에 우리 집으로 가는 문이 하나라도 있나.
 *
 * 🔴 2026-08-22 — 처음엔 `](/경로)` **만** 셌다. 그래서 전체 주소로 문을 걸어 둔 편을
 *   「문이 0개」로 보고 같은 문을 하나 더 붙였다(11편 중 10편이 겹쳤다).
 *   ⭐ 우리 집 주소로 건 링크도 문이다. 둘 다 센다.
 * ⛔ 앞말 안의 링크는 문이 아니다 — 그건 지면이 거는 것이고 손님이 누르는 것이 아니다.
 */
export const 본문에링크있나 = (원본) => {
  const 본문 = 본문떼기(원본);
  const 상대 = [...본문.matchAll(/\]\((\/[^)]*)\)/g)].length;
  const 절대 = [...본문.matchAll(/\]\(https?:\/\/(?:www\.)?kculturewire\.com(\/[^)]*)?\)/g)].length;
  return 상대 + 절대 > 0;
};
