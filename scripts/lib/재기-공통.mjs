/**
 * 재기-공통 — **급조한 자가 늘 같은 데서 틀린다.** 그 셋을 한 곳에 둔다.
 *
 * 🔴 왜 있나 — 2026-08-13 하루에만 **아홉 번** 헛경보를 냈다. 셈은 맞고 **뜻이 틀렸다**.
 * ```
 * ① <head> 를 본문으로 읽었다        설명(description)에 있는 숫자를 「지면에 있다」로 읽음
 * ② 주소·<style> 속 수를 셌다        100yearmap.com 의 「100」, 1080·1920 이 「근거 없는 수」로 잡힘
 * ③ 우리 «다짐»을 위반으로 읽었다     「늦었다거나 이르다고 **말하지 않겠습니다**」를 금지말 위반으로,
 *                                  「**등수를 매기지 않습니다**」를 「등수」 위반으로 잡음
 * ```
 * ⛔ 새 자를 지을 때 이 파일에서 가져다 쓴다. 다시 짓지 않는다.
 *
 *   import { 본문만, 숫자캐기, 다짐줄지우기, 금지말찾기 } from './lib/재기-공통.mjs';
 *   node scripts/lib/재기-공통.mjs --자가시험
 */

/** 지면에서 **손님이 읽는 몸**만. ⛔ head·script·style 은 본문이 아니다 */
export function 본문만(글) {
  const s = String(글 ?? '');
  const h = /<head>[\s\S]*?<\/head>/i.exec(s);
  let 몸 = h ? s.slice(h.index + h[0].length) : s;
  return 몸
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

/** 손님이 **읽는 수**만. ⛔ 주소·꾸밈값은 수가 아니다 */
export function 숫자캐기(글) {
  const 알맹이 = String(글 ?? '')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]*>/g, ' ')
    .replace(/https?:\/\/\S+/g, ' ')
    .replace(/\b[\w-]+\.(?:com|kr|net|org|io)\S*/g, ' ');
  return (알맹이.match(/\d[\d,]*(?:\.\d+)?/g) ?? []).map((s) => Number(s.replace(/,/g, '')));
}

/**
 * 우리가 **「안 한다」고 적어 둔 줄**을 지운다.
 * ⚠ 이걸 안 지우면 **다짐이 위반으로 잡힌다.** 오늘 두 자에서 같은 흠이 났다.
 *
 * 🔴 **금지말 볼 때만 쓴다.** 이 자는 줄을 통째로 지우므로,
 *   같은 줄에 있던 **주소·수까지 같이 사라진다**(8/14 에 「데려올 주소가 있다」가 그렇게 걸렸다).
 *   주소·수를 볼 때는 **원래 글**로 봐야 한다.
 */
export function 다짐줄지우기(글) {
  return String(글 ?? '')
    .replace(/[^.。]*말하지 않[^.。]*[.。]?/g, ' ')
    .replace(/[^.。]*매기지 않[^.。]*[.。]?/g, ' ')
    .replace(/[^.。]*세우지 않[^.。]*[.。]?/g, ' ')
    .replace(/[^.。]*쓰지 않[^.。]*[.。]?/g, ' ')
    .replace(/[^.。]*자격이 없[^.。]*[.。]?/g, ' ')
    .replace(/\s+/g, ' ');
}

/** 집 규칙으로 못 쓰는 말 — 한 곳에 둔다 */
export const 금지말 = ['등수', '순위', '몇 위', '1등', '일등', '상위', '꼴찌', '명문', '랭킹',
                      '해야 한다', '늦었다', '서둘러'];

/** 금지말이 **정말** 있나. 다짐 줄은 먼저 지우고 본다 */
export function 금지말찾기(글, 말들 = 금지말) {
  const 볼것 = 다짐줄지우기(본문만(글));
  return 말들.filter((w) => 볼것.includes(w));
}

