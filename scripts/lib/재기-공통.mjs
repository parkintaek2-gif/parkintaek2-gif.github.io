  본다('⑤ 주소 안의 수를 안 센다', 같나(숫자캐기('100yearmap.com/age 468만원'), [468]));
  본다('⑥ https 주소도 안 센다', 같나(숫자캐기('https://100yearmap.com/report/area/가 26곳'), [26]));
