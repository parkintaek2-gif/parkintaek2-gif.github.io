  본다('⑧ 꾸밈값을 안 센다', 같나(숫자캐기('<div style="width:62.5%">7곳</div>'), [7]));

  본다('⑨ 「말하지 않겠습니다」를 지운다', !다짐줄지우기('늦었다거나 이르다고 말하지 않겠습니다.').includes('늦었다'));
  본다('⑩ 「매기지 않습니다」를 지운다', !다짐줄지우기('등수를 매기지 않습니다.').includes('등수'));
  본다('⑪ 「줄을 세우지 않습니다」를 지운다', !다짐줄지우기('줄을 세우지 않습니다.').includes('세우'));
