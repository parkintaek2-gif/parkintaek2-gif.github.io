#!/usr/bin/env node
/**
 * 매시소통-자물쇠.mjs — **매시 정각 5번과 소통. 안 하면 일을 못 한다.**
 *
 * ── 사장님 지시 (2026-09-15) ──────────────────────────────────────────────
 * **「매시 정각 5번과 소통...소통 안하면 업무 못하게 자물쇠..>>>>각 섹션에 통보」**
 *
 * 앞서 조직 지침에도 있었다 — 「모든 팀원은 1시간에 한 번씩 U2와 소통하라」.
 * 그런데 그것은 «문장»이었고, 그래서 지켜지지 않았다. 오늘 실측 —
 *   1번이 이틀 반 동안 자취가 없었고 K Culture Wire 지면이 09-03 에 멈춰 있었다.
 *   2번이 도장 하나를 안 찍어 손금이 라이브에서 «한 시간 넘게» 더 팔렸다.
 * ⇒ **말로 하는 규칙은 잊힌다. 자물쇠로 건다.**
 *
 * ── 자물쇠가 «무엇을» 잠그나 ──────────────────────────────────────────────
 * 배포를 잠근다. 소통하지 않은 자리는 손님 화면에 아무것도 못 내보낸다.
 * ⛔ 고치는 것·커밋하는 것까지 막지 않는다 — 그것까지 막으면 «소통하려고 적는 일»도 막힌다.
 *   막아야 할 것은 «밖으로 나가는 것»이다.
 *
 * ── 어떻게 푸나 — 십 초면 된다 ────────────────────────────────────────────
 *   node scripts/매시소통-자물쇠.mjs --적는다 --누구 6번 --한말 "무엇을 했고 무엇을 할 것인가"
 *
 * ── 지키는 것 ─────────────────────────────────────────────────────────────
 * ⚠ 업무시간(07~21시) 밖에는 잠그지 않는다. 자는 자리를 벌주지 않는다.
 * ⛔ 「적었다」만으로 통과시키지 않는다 — 열 글자 미만은 소통이 아니다.
 * ⛔ 남의 이름으로 적지 못하게 막을 방법은 없다. 그래서 «적은 것이 남는다» —
 *   대장이 곧 그 자리가 한 말이고, 안 맞으면 사장님과 총괄이 본다.
 * ✅ 5번은 «받는» 자리라 이 자물쇠의 대상이 아니다. 대신 5번은 매시 대장을 읽는다.
 */
import fs from 'node:fs';
import path from 'node:path';

const 뿌리 = path.resolve(import.meta.dirname, '..');
export const 대장길 = path.join(뿌리, 'docs/매시소통.tsv');

/** 자물쇠가 걸리는 자리 — 5번은 «받는» 자리라 뺀다 */
export const 걸리는자리 = ['1번', '2번', '3번', '6번'];

/** 업무시간 — scripts/lib/work-hours.mjs 가 정본이지만, 그 자가 없어도 돌아야 한다 */
export const 업무시작 = 7;
export const 업무끝 = 21;

/** 「2026-09-15 14:00」 꼴. 이 PC 는 이미 한국시간이다 — ⛔ toISOString() 을 쓰지 않는다 */
export function 시각글(d = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate())
    + ' ' + p(d.getHours()) + ':' + p(d.getMinutes());
}

/** 그 시각이 속한 «시간 칸» — 2026-09-15 14 */
export function 시간칸(d = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate()) + ' ' + p(d.getHours());
}

/** 지금 업무시간인가. ⚠ 밖이면 자물쇠를 안 건다 */
export function 업무시간인가(d = new Date()) {
  const h = d.getHours();
  return h >= 업무시작 && h < 업무끝;
}

/** ⛔ 열 글자 미만은 소통이 아니다. 「확인」·「ok」로 때우지 못하게 한다 */
export const 적어도글자 = 10;
export function 말이충분한가(말) {
  return String(말 ?? '').trim().length >= 적어도글자;
}

export function 줄쓰기({ 시각, 누구, 말 }) {
  const 씻기 = (s) => String(s ?? '').replace(/[\t\r\n]+/g, ' ').trim();
  return [씻기(시각), 씻기(누구), 씻기(말)].join('\t');
}

export function 줄읽기(줄) {
  const 칸 = String(줄 ?? '').split('\t');
  if (칸.length < 2) return null;
  return { 시각: 칸[0].trim(), 누구: 칸[1].trim(), 말: (칸[2] ?? '').trim() };
}

export function 대장읽기(길 = 대장길) {
  if (!fs.existsSync(길)) return [];
  return fs.readFileSync(길, 'utf8').split(/\r?\n/)
    .filter((l) => l.trim() && !l.startsWith('#'))
    .map(줄읽기).filter(Boolean);
}

/** 그 자리가 «이 시간 칸»에 적었나 */
export function 이번시간에적었나(줄들, 누구, 이제 = new Date()) {
  const 칸 = 시간칸(이제);
  return (줄들 || []).some((x) => x.누구 === 누구 && String(x.시각).startsWith(칸) && 말이충분한가(x.말));
}

/** 그 자리가 마지막으로 적은 줄 */
export function 마지막말(줄들, 누구) {
  let 끝 = null;
  for (const x of 줄들 || []) if (x.누구 === 누구) 끝 = x;
  return 끝;
}

/**
 * 자물쇠 판정.
 * 낸다 — { 잠겼나, 까닭, 푸는법 }
 * ⛔ 업무시간 밖이면 안 잠근다. ⛔ 5번은 대상이 아니다.
 */
export function 잠겼나(누구, 줄들, 이제 = new Date()) {
  const 그 = String(누구 ?? '').trim();
  if (!걸리는자리.includes(그)) {
    return { 잠겼나: false, 까닭: 그 + ' 는 이 자물쇠의 대상이 아니다' };
  }
  if (!업무시간인가(이제)) {
    return { 잠겼나: false, 까닭: '업무시간(' + 업무시작 + '~' + 업무끝 + '시) 밖이라 안 잠근다' };
  }
  if (이번시간에적었나(줄들, 그, 이제)) {
    return { 잠겼나: false, 까닭: 시간칸(이제) + '시에 소통했다' };
  }
  const 끝 = 마지막말(줄들, 그);
  return {
    잠겼나: true,
    까닭: 그 + ' 가 ' + 시간칸(이제) + '시에 5번과 소통하지 않았다'
      + (끝 ? ' (마지막 소통 ' + 끝.시각 + ')' : ' (소통한 적이 없다)'),
    푸는법: 'node scripts/매시소통-자물쇠.mjs --적는다 --누구 ' + 그
      + ' --한말 "무엇을 했고 무엇을 할 것인가" (열 글자 이상)',
  };
}

export function 적는다({ 누구, 말, 길 = 대장길, 이제 = new Date() }) {
  const 그 = String(누구 ?? '').trim();
  if (!그) return { 됐나: false, 왜: '누가 적는지 밝히지 않았다 — --누구 6번' };
  if (!말이충분한가(말)) {
    return { 됐나: false, 왜: '무엇을 했고 무엇을 할 것인지 ' + 적어도글자 + '자 이상으로 적는다. 「확인」은 소통이 아니다' };
  }
  const 줄 = 줄쓰기({ 시각: 시각글(이제), 누구: 그, 말 });
  fs.mkdirSync(path.dirname(길), { recursive: true });
  if (!fs.existsSync(길)) {
    fs.writeFileSync(길, '# 매시 정각 5번과의 소통 대장 — 사장님 지시(2026-09-15)\n'
      + '# 시각\t자리\t무엇을 했고 무엇을 할 것인가\n', 'utf8');
  }
  fs.appendFileSync(길, 줄 + '\n', 'utf8');
  return { 됐나: true, 줄 };
}

/* ── 명령줄 ────────────────────────────────────────────────────────────── */
function 인자(이름) {
  const i = process.argv.indexOf(이름);
  return i >= 0 ? process.argv[i + 1] : null;
}

function 본일() {
  const 이제 = new Date();

  if (process.argv.includes('--적는다')) {
    const r = 적는다({ 누구: 인자('--누구'), 말: 인자('--한말'), 이제 });
    if (!r.됐나) { console.error('⛔ 못 적었다 — ' + r.왜); process.exit(1); }
    console.log('✅ 적었다 — ' + r.줄);
    console.log('   ⭐ 커밋·푸시까지 해야 5번에게 닿습니다: git add docs/매시소통.tsv && git commit && git push');
    return;
  }

  const 줄들 = 대장읽기();

  /* 한 자리만 묻는다 — 배포 관문이 이 꼴로 부른다. 잠겼으면 종료코드 1 */
  const 볼자리 = 인자('--자물쇠');
  if (볼자리) {
    const r = 잠겼나(볼자리, 줄들, 이제);
    if (!r.잠겼나) { console.log('🔓 ' + (r.까닭 || '열려 있다')); return; }
    console.error('🔒 **자물쇠** — ' + r.까닭);
    console.error('   사장님 지시(2026-09-15): 「매시 정각 5번과 소통…소통 안하면 업무 못하게 자물쇠」');
    console.error('   푸는 법(십 초면 됩니다):');
    console.error('     ' + r.푸는법);
    process.exit(1);
  }

  /* 다 보인다 — 5번이 매시 읽는 화면 */
  console.log('■ 매시 소통 — ' + 시간칸(이제) + '시 · ' + 이제.toLocaleString('ko-KR'));
  if (!업무시간인가(이제)) console.log('  ⚠ 업무시간(' + 업무시작 + '~' + 업무끝 + '시) 밖입니다 — 자물쇠를 안 겁니다.\n');
  let 안한곳 = 0;
  for (const 자 of 걸리는자리) {
    const r = 잠겼나(자, 줄들, 이제);
    const 끝 = 마지막말(줄들, 자);
    if (r.잠겼나) {
      안한곳 += 1;
      console.log('  🔒 ' + 자 + '  이번 시간에 소통 없음' + (끝 ? '  (마지막 ' + 끝.시각 + ')' : '  (소통한 적 없음)'));
    } else {
      console.log('  ✅ ' + 자 + '  ' + (끝 ? 끝.시각 + ' — ' + 끝.말.slice(0, 54) : r.까닭));
    }
  }
  console.log('\n잰 자리 ' + 걸리는자리.length + ' · 잠긴 자리 ' + 안한곳);
  if (안한곳) console.log('🔒 잠긴 자리는 «배포»를 못 합니다. 적으면 그 자리에서 풀립니다.');
}

/* ── 자가시험 ──────────────────────────────────────────────────────────── */
export function 자가시험() {
  const 것 = [];
  const 재다 = (이름, 됐나) => 것.push({ 이름, 됐나 });
  const 낮 = new Date(2026, 8, 15, 14, 5);            /* 업무시간 안 */
  const 밤 = new Date(2026, 8, 15, 23, 30);           /* 업무시간 밖 */

  재다('시각글: 한국시간 그대로', 시각글(낮) === '2026-09-15 14:05');
  재다('시간칸: 시까지만', 시간칸(낮) === '2026-09-15 14');
  재다('업무시간: 14시는 안', 업무시간인가(낮) === true);
  재다('업무시간: 23시는 밖', 업무시간인가(밤) === false);
  재다('업무시간: 21시는 밖(끝 시각은 안 넣는다)', 업무시간인가(new Date(2026, 8, 15, 21, 0)) === false);
  재다('업무시간: 7시는 안', 업무시간인가(new Date(2026, 8, 15, 7, 0)) === true);

  재다('⛔ 「확인」은 소통이 아니다', 말이충분한가('확인') === false);
  재다('⛔ 빈 것도 아니다', 말이충분한가('') === false && 말이충분한가(null) === false);
  재다('열 글자 넘으면 된다', 말이충분한가('스크리너 지면을 냈고 다음은 기사입니다') === true);

  재다('줄쓰기·줄읽기가 오간다', (() => {
    const 줄 = 줄쓰기({ 시각: '2026-09-15 14:05', 누구: '6번', 말: '무엇을 했고 무엇을 할 것인가' });
    const r = 줄읽기(줄);
    return r.누구 === '6번' && r.시각 === '2026-09-15 14:05' && /무엇을 했고/.test(r.말);
  })());
  재다('⛔ 탭·줄바꿈이 대장을 깨뜨리지 못한다', (() => {
    const 줄 = 줄쓰기({ 시각: '2026-09-15 14:05', 누구: '6번', 말: '가\t나\n다 라 마 바 사 아' });
    return 줄.split('\t').length === 3 && !줄.includes('\n');
  })());

  const 대장 = [
    { 시각: '2026-09-15 14:02', 누구: '6번', 말: 'UAE 등급 공시 태그를 붙였습니다' },
    { 시각: '2026-09-15 13:10', 누구: '1번', 말: '어제 실적과 오늘 계획을 올렸습니다' },
    { 시각: '2026-09-15 14:40', 누구: '2번', 말: 'ok' },                     /* 짧다 — 안 친다 */
  ];
  재다('이번 시간에 적었으면 true', 이번시간에적었나(대장, '6번', 낮) === true);
  재다('🔴 지난 시간 것은 이번 시간이 아니다', 이번시간에적었나(대장, '1번', 낮) === false);
  재다('⛔ 열 글자 미만은 적은 것으로 안 친다', 이번시간에적었나(대장, '2번', 낮) === false);

  재다('🔒 안 적으면 잠긴다', 잠겼나('1번', 대장, 낮).잠겼나 === true);
  재다('🔓 적었으면 안 잠긴다', 잠겼나('6번', 대장, 낮).잠겼나 === false);
  재다('🔴 잠글 때 «푸는 법»을 함께 준다', /--적는다/.test(잠겼나('1번', 대장, 낮).푸는법 || ''));
  재다('⚠ 업무시간 밖에는 안 잠근다', 잠겼나('1번', 대장, 밤).잠겼나 === false);
  재다('✅ 5번은 대상이 아니다', 잠겼나('5번', [], 낮).잠겼나 === false);
  재다('모르는 자리도 안 잠근다', 잠겼나('9번', [], 낮).잠겼나 === false);
  재다('걸리는 자리 넷 · 5번 없음',
    걸리는자리.length === 4 && !걸리는자리.includes('5번'));

  재다('마지막말: 가장 나중 것', 마지막말(대장, '6번').시각 === '2026-09-15 14:02');
  재다('마지막말: 없으면 null', 마지막말(대장, '3번') === null);
  재다('⛔ 빈 대장도 견딘다', 잠겼나('1번', null, 낮).잠겼나 === true && 대장읽기('없는파일.tsv').length === 0);

  const 실패 = 것.filter((x) => !x.됐나);
  console.log(`■ 자가시험 ${것.length - 실패.length}/${것.length}`);
  for (const x of 실패) console.log(`  🔴 ${x.이름}`);
  return 실패.length === 0;
}

if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);
if (process.argv[1] && process.argv[1].endsWith('매시소통-자물쇠.mjs')) 본일();
