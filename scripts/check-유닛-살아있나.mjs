#!/usr/bin/env node
/**
 * check-유닛-살아있나.mjs — **커밋이 없는 자리가 «안 하는» 것인지 «멈춘» 것인지 가른다.**
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴🔴 [2026-09-17] 왜 만들었나 — 내가 사장님께 틀리게 보고했다
 *
 *   그날 사장님이 「2번이 불안불안하다」 하셔서 재 보고 이렇게 올렸다 —
 *   「2번은 오늘 커밋 5건이 «전부 점검 마커»이고 만든 것이 0건이다. 저에게 답도 0건이다」
 *
 *   ⛔ 그런데 까닭이 게으름이 아니었다. 사장님이 그 세션 화면을 보여 주셨다 —
 *     **「Context limit reached · /compact or /clear to continue」**
 *     ⇒ 2번은 «안 한» 것이 아니라 **컨텍스트 한도에 걸려 멈춰 있었다.**
 *
 *   ⭐ 내가 유닛이 도는지를 **커밋으로만** 재고 있었기 때문이다.
 *     멈춘 자리와 안 하는 자리는 **커밋이 없다는 점에서 똑같이 보인다.**
 *     그 둘을 못 가르면 멈춘 사람을 게으르다고 보고하게 된다. 오늘 내가 그랬다.
 *
 * [그래서 무엇을 재나 — 두 가지를 «따로» 본다]
 *   ① 말했나   설정 뿌리의 대화 기록(.jsonl)이 마지막으로 바뀐 때
 *              = 그 자리가 마지막으로 «숨 쉰» 때. 커밋이 없어도 살아 있으면 여기가 움직인다
 *   ② 냈나     git log — 그 자리가 마지막으로 «결과»를 낸 때
 *
 *   ```
 *   ① 최근 · ② 최근    ✅ 돈다
 *   ① 최근 · ② 오래     ⚠ 살아는 있는데 결과가 안 나온다 — 독려할 자리
 *   ① 오래 · ② 오래     🔴 멈췄다 — 독려가 아니라 «깨워야» 한다 (한도·크래시·종료)
 *   ```
 *
 * ⛔ 대화 «내용»을 읽지 않는다. 파일이 언제 바뀌었는지만 본다.
 *
 *   node scripts/check-유닛-살아있나.mjs --자가시험
 *   node scripts/check-유닛-살아있나.mjs
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

export const 유닛뿌리 = {
  1: '.claude-u1', 2: '.claude-u2', 3: '.claude-u3',
  5: '.claude-u5', 6: '.claude-u6',
};

/** 오래됐다고 보는 선 — 업무시간에 이만큼 조용하면 살펴본다 */
export const 조용한선분 = 90;

/**
 * 두 수(말한 지 몇 분·낸 지 몇 분)로 한 자리를 판정한다. **판정만 떼어 낸다.**
 * @returns {{판정:'돈다'|'결과없음'|'멈췄다'|'못잼', 말:string}}
 */
export function 자리판정(말한분, 낸분, 선 = 조용한선분) {
  if (말한분 === null || 말한분 === undefined) return { 판정: '못잼', 말: '대화 기록을 못 읽었다' };
  const 조용 = 말한분 > 선;
  if (조용 && (낸분 === null || 낸분 > 선)) {
    return { 판정: '멈췄다', 말: `${말한분}분째 아무 말이 없다 — 독려가 아니라 «깨워야» 한다(한도·크래시)` };
  }
  if (!조용 && (낸분 === null || 낸분 > 선)) {
    return { 판정: '결과없음', 말: `살아는 있다(${말한분}분 전) — 그런데 낸 것이 없다. 독려할 자리다` };
  }
  return { 판정: '돈다', 말: `말한 지 ${말한분}분 · 낸 지 ${낸분}분` };
}

/** 그 뿌리가 마지막으로 «말한» 때까지 몇 분인가. 못 읽으면 null(0 이 아니다) */
export function 말한지몇분(뿌리, 집 = os.homedir(), 지금 = Date.now()) {
  let 최근 = 0;
  const 훑 = (p) => {
    let 것들;
    try { 것들 = fs.readdirSync(p, { withFileTypes: true }); } catch { return; }
    for (const f of 것들) {
      const q = path.join(p, f.name);
      if (f.isDirectory()) 훑(q);
      else if (f.name.endsWith('.jsonl')) {
        try { const t = fs.statSync(q).mtimeMs; if (t > 최근) 최근 = t; } catch { /* 지나간다 */ }
      }
    }
  };
  훑(path.join(집, 뿌리, 'projects'));
  return 최근 ? Math.round((지금 - 최근) / 60000) : null;
}

/* ── 자가시험 ───────────────────────────────────────────────────────────── */
if (process.argv.includes('--자가시험')) {
  const 것들 = [];
  const 다 = (이름, 참) => 것들.push({ 이름, 참: !!참 });

  /* 🔴 그날 실제로 있었던 일 — 2번은 말도 없고 낸 것도 없었다 */
  다('둘 다 오래면 «멈췄다»', 자리판정(200, 300).판정 === '멈췄다');
  다('멈췄다에는 «깨워라»가 적힌다', /깨워야/.test(자리판정(200, 300).말));

  /* 살아는 있는데 결과가 없는 자리 — 이때만 독려다 */
  다('말은 하는데 안 내면 «결과없음»', 자리판정(5, 300).판정 === '결과없음');
  다('결과없음에는 «독려»가 적힌다', /독려/.test(자리판정(5, 300).말));

  /* 잘 도는 자리 */
  다('둘 다 최근이면 «돈다»', 자리판정(5, 10).판정 === '돈다');
  다('선 위아래를 정확히 가른다', 자리판정(90, 10).판정 === '돈다' && 자리판정(91, 300).판정 === '멈췄다');

  /* ⛔ 못 쟀으면 «안 한다»로 몰지 않는다 — 오늘 내가 한 잘못이 그것이다 */
  다('대화 기록을 못 읽으면 «못잼»', 자리판정(null, 10).판정 === '못잼');
  다('낸 것이 없어도 말하고 있으면 멈춘 게 아니다', 자리판정(1, null).판정 === '결과없음');

  /* 선을 바꿀 수 있다 */
  다('선을 주면 그것을 쓴다', 자리판정(100, 500, 200).판정 === '결과없음');

  다('유닛은 다섯이다(4번은 없어진 자리·7번은 자리가 아니다)', Object.keys(유닛뿌리).length === 5);

  const 진 = 것들.filter((x) => !x.참);
  console.log(`유닛이 살아 있나 — 자가시험 ${것들.length - 진.length}/${것들.length}`);
  for (const x of 진) console.log('   🔴 ' + x.이름);
  process.exit(진.length ? 1 : 0);
}

/* ── 실제로 잰다 ────────────────────────────────────────────────────────── */
const 뿌리 = path.resolve(path.dirname(new URL(import.meta.url).pathname.slice(1)), '..');

function 낸지몇분(번호) {
  try {
    const 낸것 = execFileSync('git', ['log', '--all', '-1', '--format=%ct', '--grep', `^${번호}번`],
      { cwd: 뿌리, encoding: 'utf8' }).trim();
    if (!낸것) return null;
    return Math.round((Date.now() - Number(낸것) * 1000) / 60000);
  } catch { return null; }
}

console.log(`■ 유닛이 살아 있나 — ${new Date().toLocaleString('ko-KR')}`);
console.log('   ⭐ 「커밋이 없다」를 「안 한다」로 읽지 않는다. 멈춘 자리와 안 하는 자리는 다르다\n');

let 깨울것 = 0;
for (const [번호, 뿌리이름] of Object.entries(유닛뿌리)) {
  const 말 = 말한지몇분(뿌리이름);
  const 냄 = 낸지몇분(번호);
  const p = 자리판정(말, 냄);
  const 표 = p.판정 === '돈다' ? '✅' : p.판정 === '결과없음' ? '⚠' : p.판정 === '멈췄다' ? '🔴' : '⬜';
  console.log(`  ${표} ${번호}번  ${p.판정.padEnd(6)} — ${p.말}`);
  if (p.판정 === '멈췄다') 깨울것++;
}

if (깨울것) {
  console.log('');
  console.log('🔴 멈춘 자리가 있다 — **독려하지 말고 깨운다.** 대개 컨텍스트 한도다');
  console.log('   그 창에서 `/compact` 를 친다. `/clear` 는 안 된다 — 받은 지시가 통째로 사라진다');
  console.log('   ✅ 자동 컴팩트는 일곱 뿌리 전부 켜 뒀다(2026-09-17). 이미 뜬 창에는 안 먹을 수 있다');
}
process.exit(0);
