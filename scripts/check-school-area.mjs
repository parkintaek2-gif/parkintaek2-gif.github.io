#!/usr/bin/env node
/**
 * 학교를 시·군·구로 묶는 자를 **시험하고**, 실제 자료로 몇 묶음이 나오는지 센다.
 *
 *   node scripts/check-school-area.mjs
 *
 * ## 왜 (2026-08-08 09:0x · 2번 지시 ②)
 *
 *   큰 시가 통째로 한 덩어리가 돼 「한눈에」가 깨지고 있었다(창원 53곳).
 *   주소 셋째 낱말까지 보게 고쳤는데, **고친 자가 맞는지 스스로 시험한다.**
 *
 * ⛔ 검사가 통과했다는 것이 「이상 없음」인지 **「못 재고 있음」**인지 갈려야 한다.
 *   그래서 자가시험이 먼저 돌고, 하나라도 깨지면 세는 것을 안 한다.
 */
import fs from 'node:fs';
import path from 'node:path';
import { 지역단위, 지역슬러그, 슬러그풀기, 팔만한가, 팔만한최소 } from '../src/lib/school-area.ts';

const 뿌리 = path.resolve(path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'), '..');
const 학교자료 = path.join(뿌리, 'src', 'data', '100yearmap', 'pages-school.json');

const 검사 = [];
const 확인 = (이름, 실제, 기대) => 검사.push({ 이름, 통과: JSON.stringify(실제) === JSON.stringify(기대) });

확인('서울 강동구', 지역단위('서울특별시', '서울특별시 강동구 고덕로 227').이름, '강동구');
확인('⭐ 큰 시는 셋째까지 — 수원시 장안구', 지역단위('경기도', '경기도 수원시 장안구 조원로 18').이름, '수원시 장안구');
확인('구가 없는 시는 시까지', 지역단위('경기도', '경기도 여주시 세종로 1').이름, '여주시');
확인('군도 묶는다', 지역단위('전라남도', '전라남도 고흥군 고흥읍 1').이름, '고흥군');
확인('⭐ 세종은 구가 없어 시·도가 단위', 지역단위('세종특별자치시', '세종특별자치시 마음안로 93').이름, '세종특별자치시');
확인('세종은 주소가 짧아도 선다', 지역단위('세종특별자치시', '').이름, '세종특별자치시');
확인('⛔ 주소가 없으면 null — 기타로 안 뭉친다', 지역단위('부산광역시', '').이름, null);
확인('못 가르면 까닭을 준다', typeof 지역단위('부산광역시', '').못가른까닭, 'string');
확인('⛔ 시로 안 끝나면 셋째를 안 붙인다', 지역단위('경기도', '경기도 광주시 도척면 도척윗로').이름, '광주시');

확인('슬러그 — 공백을 하이픈으로', 지역슬러그('경기도', '수원시 장안구'), '경기도-수원시-장안구');
확인('슬러그를 되푼다', 슬러그풀기('경기도-수원시-장안구'), { 시도: '경기도', 이름: '수원시 장안구' });
확인('한 토막 슬러그', 슬러그풀기('세종특별자치시'), { 시도: '세종특별자치시', 이름: '세종특별자치시' });
확인('⭐ 슬러그는 왕복해도 같다', 슬러그풀기(지역슬러그('서울특별시', '강동구')), { 시도: '서울특별시', 이름: '강동구' });

확인('10곳이면 판다', 팔만한가(10), true);
확인('9곳이면 안 판다', 팔만한가(9), false);
확인('경계가 한 곳에 있다', 팔만한최소, 10);

for (const c of 검사) console.log(`${c.통과 ? '✅' : '⛔'} ${c.이름}`);
const 실패 = 검사.filter((c) => !c.통과).length;
console.log(`\n자가시험 ${검사.length}개 · 실패 ${실패}개`);
if (실패) {
  console.log('⛔ **자를 못 믿으니 세지 않는다.**');
  process.exit(1);
}

/* ── 실제 자료로 센다 ─────────────────────────────────────── */
const 학교들 = JSON.parse(fs.readFileSync(학교자료, 'utf8'));
const 묶음 = new Map();
const 못가른것 = [];
for (const x of 학교들) {
  const r = 지역단위(x.지역, x.주소);
  if (!r.이름) {
    못가른것.push({ 학교: x.title, 시도: x.지역, 까닭: r.못가른까닭 });
    continue;
  }
  const k = 지역슬러그(x.지역, r.이름);
  묶음.set(k, (묶음.get(k) ?? 0) + 1);
}
const 값 = [...묶음.values()];
const 파는것 = 값.filter(팔만한가).length;
const 무료 = 값.length - 파는것;

console.log(`\n■ 실제 자료 — 학교 ${학교들.length.toLocaleString()}곳`);
console.log(`  묶음 ${묶음.size}개 · 가장 큰 곳 ${Math.max(...값)}곳 · 가장 작은 곳 ${Math.min(...값)}곳`);
console.log(`  ${팔만한최소}곳 이상 ${파는것}개 · ${팔만한최소 - 1}곳 이하 ${무료}개`);
console.log(`  ⛔ 못 가른 학교 ${못가른것.length}곳`);
for (const x of 못가른것.slice(0, 5)) console.log(`     ${x.시도} ${x.학교} — ${x.까닭}`);

console.log('\n■ 큰 묶음 여덟');
for (const [k, n] of [...묶음.entries()].sort((a, b) => b[1] - a[1]).slice(0, 8))
  console.log(`  ${k.replace(/-/g, ' ')} ${n}곳`);
