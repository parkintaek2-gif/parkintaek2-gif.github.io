#!/usr/bin/env node
/**
 * collect-100y-pets.mjs — **몇 %가 반려동물을 기르나, 나이대로 다른가**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 사장님(2026-08-07, docs/백년지도-남들은-어떻게.md 「열두 고민」) —
 *   「사업은? 건강은? 반려견은? 반려묘는? … 너무 많은 고민들을 안고 사는 게 사람이지」
 * 열두 고민 중 반려동물·여행·승진 셋이 아직 지면이 없었다. 표 id는 이미 그 문서에 있다 —
 *   ⚠ 실제로 받아 보니 그 문서가 적어 둔 「양육 경험 DT_114063_002」는 **파라미터가 안 맞는
 *   표였다**(err 21). `statisticsSearch.do` 로 다시 찾아 **DT_114063_001(현재 양육 여부)**을 썼다.
 *   문서의 표 id도 실제로 안 맞을 수 있다 — 받아보지 않고 문서만 옮기면 헛일이 된다.
 *
 * ── 표 둘을 함께 받는다. 둘이 다른 모집단을 잰다 ────────────────
 *   ① DT_114063_001  «전체 3,000가구» 중 지금 기르는지 여부         ← 양육률
 *   ② DT_114063_006  «기르는 가구(867)» 안에서 종류별 비중(중복응답) ← 종류 비중
 * ⛔⛔ ②의 «개 80.5%»는 «가구 중 80.5%가 개를 기른다»가 아니다.
 *    ②의 모집단은 이미 **반려동물을 기르는 가구뿐**이다. ①과 ②를 같은 분모로 읽으면 거짓이 된다.
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · 표본조사다(전수조사 아님) — 전체 3,000가구. 연령대는 95~1,346가구로 갈려 작은 칸은 오차가 크다
 * · 2025년 **한 해뿐**이다 — 이 표로는 흐름(늘었는지 줄었는지)을 못 본다
 * · ②는 중복응답이라 종류별 비중을 다 더하면 100을 넘는다
 * · 「기른다」는 응답자의 자기 신고다 — 등록 여부(동물등록제)와는 다른 것을 잰다
 *
 * 쓰는 법  node scripts/collect-100y-pets.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '114';
export const 표들 = { 양육여부: 'DT_114063_001', 종류: 'DT_114063_006' };

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
export const 한자리 = (v) => (v == null ? null : Math.round(v * 10) / 10);

/** ⭐ 나이대별 「개 비중」이 나이가 들수록 오르고 「고양이 비중」은 내리는지 — 이 지면의 답 한 줄 */
export function 나이따라뒤집히나(연령별) {
  const 순 = ['20대', '30대', '40대', '50대', '60대 이상'];
  const 개들 = 순.map((c) => 연령별.find((r) => r.칸 === c)?.개몫).filter((v) => v != null);
  const 고들 = 순.map((c) => 연령별.find((r) => r.칸 === c)?.고양이몫).filter((v) => v != null);
  if (개들.length < 순.length || 고들.length < 순.length) return null;
  const 개오름 = 개들.every((v, i) => i === 0 || v >= 개들[i - 1]);
  const 고내림 = 고들.every((v, i) => i === 0 || v <= 고들[i - 1]);
  return { 개오름, 고내림, 뒤집힘: 개오름 && 고내림 };
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② 콤마 있는 수를 읽는다', 수로('1,346') === 1346);
  본다('③ 개는 오르고 고양이는 내리면 뒤집힘', 나이따라뒤집히나([
    { 칸: '20대', 개몫: 50, 고양이몫: 35 }, { 칸: '30대', 개몫: 60, 고양이몫: 30 },
    { 칸: '40대', 개몫: 70, 고양이몫: 20 }, { 칸: '50대', 개몫: 80, 고양이몫: 15 },
    { 칸: '60대 이상', 개몫: 90, 고양이몫: 8 },
  ]).뒤집힘 === true);
  본다('④ 한 칸이라도 거스르면 뒤집힘이 아니다', 나이따라뒤집히나([
    { 칸: '20대', 개몫: 50, 고양이몫: 35 }, { 칸: '30대', 개몫: 40, 고양이몫: 30 },
    { 칸: '40대', 개몫: 70, 고양이몫: 20 }, { 칸: '50대', 개몫: 80, 고양이몫: 15 },
    { 칸: '60대 이상', 개몫: 90, 고양이몫: 8 },
  ]).뒤집힘 === false);
  본다('⑤ 칸이 모자라면 못 잰다(null)', 나이따라뒤집히나([{ 칸: '20대', 개몫: 50, 고양이몫: 35 }]) === null);
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-pets.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  /** ⚠ 이 표들은 objL2 를 안 받는 것과 받는 것이 갈린다 — 표마다 꼬리를 따로 준다 */
  const 받기 = async (tbl, 꼬리) => {
    const j = await (await fetch(
      `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
      + `&format=json&jsonVD=Y&orgId=${ORG}&tblId=${tbl}&${꼬리}`)).json();
    if (!Array.isArray(j)) throw new Error(`${tbl}: ${JSON.stringify(j).slice(0, 150)}`);
    return j;
  };

  const 양육여부 = await 받기(표들.양육여부, 'itmId=ALL&objL1=ALL&prdSe=Y&newEstPrdCnt=10');
  const 종류 = await 받기(표들.종류, 'itmId=ALL&objL1=ALL&objL2=ALL&prdSe=Y&newEstPrdCnt=10');

  const 최신 = [...new Set(양육여부.map((x) => x.PRD_DE))].sort().at(-1);
  const 양육값 = (칸, 항) => 수로(양육여부.find((x) => x.PRD_DE === 최신 && x.C1_NM === 칸 && x.ITM_NM === 항)?.DT);
  const 종류값 = (칸, 종) => 수로(종류.find((x) => x.PRD_DE === 최신 && x.C1_NM === 칸 && x.C2_NM === 종)?.DT);

  /** 한 갈래(성별·연령대·주거형태 …)를 표 둘에서 한 줄로 합친다 */
  const 갈래한줄 = (칸) => ({
    칸,
    사례수: 양육값(칸, '사례수'),
    양육몫: 양육값(칸, '현재 거주지에서 양육하고 있다'),
    안기름몫: 양육값(칸, '반려동물을 양육하지 않는다'),
    기르는가구사례수: 종류값(칸, '사례수'),
    개몫: 종류값(칸, '개'),
    고양이몫: 종류값(칸, '고양이'),
  });

  const 성별 = ['남성', '여성'].map(갈래한줄);
  const 연령별 = ['20대', '30대', '40대', '50대', '60대 이상'].map(갈래한줄);
  const 주거형태별 = ['단독주택', '아파트', '다세대/빌라/기타'].map(갈래한줄);
  const 가구원수별 = ['1명', '2명', '3명 이상'].map(갈래한줄);
  const 소득별 = ['300만 원 이하', '301~500만 원', '501만 원 이상'].map(갈래한줄);
  const 지역별 = ['도시지역', '농어촌 지역(읍면지역)'].map(갈래한줄);
  const 권역별 = ['서울/강원권', '경인권', '충청권', '호남권', '대경권', '동남권'].map(갈래한줄);
  const 전체 = 갈래한줄('전체');

  /* 🔴 자가 대조 — 갈래마다 사례수를 더하면 전체 사례수(3,000)가 되는가 */
  const 더함 = (arr) => arr.reduce((s, r) => s + (r.사례수 ?? 0), 0);
  const 자가대조 = {
    '성별 합 = 전체': { 합: 더함(성별), 전체: 전체.사례수, 맞나: 더함(성별) === 전체.사례수 },
    '연령대 합 = 전체': { 합: 더함(연령별), 전체: 전체.사례수, 맞나: 더함(연령별) === 전체.사례수 },
    '주거형태 합 = 전체': { 합: 더함(주거형태별), 전체: 전체.사례수, 맞나: 더함(주거형태별) === 전체.사례수 },
    '가구원수 합 = 전체': { 합: 더함(가구원수별), 전체: 전체.사례수, 맞나: 더함(가구원수별) === 전체.사례수 },
    '권역 합 = 전체': { 합: 더함(권역별), 전체: 전체.사례수, 맞나: 더함(권역별) === 전체.사례수 },
    뜻: '다섯 대조가 다 맞아야 내가 칸을 빠뜨리지도, 두 번 세지도 않은 것이다',
  };

  const 뒤집힘 = 나이따라뒤집히나(연령별);

  const 낸다 = {
    무엇: '몇 %가 반려동물을 기르나, 나이대로 다른가 — 양육 여부와 기르는 종류',
    만든날: new Date().toISOString().slice(0, 10),
    최신, 해들: [최신], 해수: 1,
    출처: {
      기관: '농림축산식품부',
      표: '① 현재 반려동물 양육 여부 · ② 현재 기르고 있는 반려동물 종류(중복응답)',
      창구: 'KOSIS', orgId: ORG, tblId: `${표들.양육여부} · ${표들.종류}`,
    },
    '⛔⛔ 두 표를 같은 분모로 읽으면 거짓이 된다':
      '②(종류별 비중)의 모집단은 «전체 가구»가 아니라 «이미 반려동물을 기르는 가구»입니다. '
      + '그래서 «개 80.5%»는 «전체 가구의 80.5%가 개를 기른다»가 아니라 '
      + '«기르는 가구 가운데 80.5%가 개를 포함한다»입니다(중복응답이라 합이 100을 넘습니다).',
    '⚠ 이 자료가 못 가르는 것': [
      '표본조사입니다(전수조사 아님) — 전체 3,000가구. 20대는 95가구뿐이라 작은 칸일수록 오차가 큽니다.',
      '2025년 한 해만 있습니다 — 이 표로는 늘었는지 줄었는지(흐름)를 못 봅니다.',
      '②는 중복응답이라 종류별 비중을 다 더하면 100을 넘습니다.',
      '「기른다」는 응답자의 자기 신고입니다 — 동물등록제 등록 여부와는 다른 것을 잽니다.',
    ],
    전체, 성별, 연령별, 주거형태별, 가구원수별, 소득별, 지역별, 권역별,
    뒤집힘, 자가대조,
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/pets.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
  console.log(`   ${최신}년 · 전체 ${전체.양육몫}% 양육중 (사례수 ${전체.사례수})`);
  console.log(`   연령대: ${연령별.map((r) => `${r.칸} ${r.양육몫}%`).join(' · ')}`);
  console.log(`   종류(기르는 가구 안에서): ${연령별.map((r) => `${r.칸} 개${r.개몫}%/고양이${r.고양이몫}%`).join(' · ')}`);
  console.log(`   나이 들수록 개↑고양이↓: ${뒤집힘 ? (뒤집힘.뒤집힘 ? '맞다' : '아니다') : '못 쟀다'}`);
  console.log(`   자가대조: ${Object.entries(자가대조).filter(([k]) => k !== '뜻')
    .map(([k, v]) => `${k} ${v.맞나 ? '맞다' : '🔴 안 맞다'}`).join(' · ')}`);
}
