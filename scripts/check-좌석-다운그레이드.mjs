/* 좌석 다운그레이드가 적용되는 날 «배정된 멤버»가 좌석보다 많으면 사고가 난다.
 *
 * [왜 이 자가 있나 — 2026-09-21]
 * 사장님 지시 「연필로 줄여」로 스탠다드 2→1 다운그레이드를 예약했다. 예약은 갱신일
 * (2026-10-20)에 적용된다. 그런데 «이번 달 몫은 이미 결제됐고 환불되지 않으므로»
 * 그때까지 좌석을 비워 두면 값을 치른 자리를 버리는 것이다. 그래서 u1(1번)을 다시 앉혔다.
 * ⇒ 갱신일에 좌석 2 < 배정 3 이 된다. 그 전에 한 자리를 떼야 한다.
 *
 * ⛔ 이것을 «기억»에 걸지 않는다. 기억에 건 것은 한 달 뒤에 아무도 안 본다.
 *    강령 ④ — 「규칙은 문장이 아니라 검사로 둔다」.
 * ⛔ 마감 훨씬 전부터 빨간불을 켜지 않는다 — 열흘 내내 빨간불이면 사람이 빨간불 자체를
 *    안 보게 된다(check-2h ⑧ 이 같은 까닭으로 그렇게 지어져 있다).
 *
 * 쓰는 법
 *   node scripts/check-좌석-다운그레이드.mjs                  사람이 읽는 꼴
 *   node scripts/check-좌석-다운그레이드.mjs --체크리스트      check-2h 가 쓰는 한 줄
 *   node scripts/check-좌석-다운그레이드.mjs --자가시험        스스로를 잰다
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const 여기 = path.dirname(url.fileURLToPath(import.meta.url));
const 뿌리 = path.resolve(여기, '..');
export const 대장길 = path.join(뿌리, 'docs', '좌석-다운그레이드-2026-10-20.json');

/* ⚠ 시각은 한국시간(KST). 이 PC 가 이미 KST 다 —
   toISOString() 은 UTC 라 새벽에 하루가 어긋난다. 쓰지 않는다. */
export function 날짜글(d = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}
export function 날수차(가, 나) {
  const [a, b] = [가, 나].map((s) => { const [y, m, d] = s.split('-').map(Number); return Date.UTC(y, m - 1, d); });
  return Math.round((a - b) / 86400000);
}

/** 며칠 전부터 빨간불을 켤 것인가 — 한 주 앞 */
export const 미리알림날수 = 7;

/**
 * ⛔ 기다리는 동안 빨간불을 켜지 않는다 — 며칠 내내 빨간불이면 사람이 빨간불 자체를
 *    안 보게 되고 자가 죽는다(check-2h ⑧ 이 같은 까닭으로 그렇게 지어져 있다).
 *    다만 «한없이» 기다리지도 않는다 — 한계 날수를 넘기면 그때 빨간불이다.
 * @returns {{등급:'✅'|'⏳'|'🔴', 말:string}}
 */
export function 판정(대장, 오늘 = 날짜글()) {
  if (!대장) return { 등급: '🔴', 말: '대장을 못 읽었다' };
  if (대장.끝났나) return { 등급: '✅', 말: `끝냈다 (${대장.끝낸때 || '때 미기록'})` };

  const 같나 = 대장.목표구성 && 대장.지금구성
    && 대장.목표구성.프리미엄 === 대장.지금구성.프리미엄
    && 대장.목표구성.스탠다드 === 대장.지금구성.스탠다드;
  if (같나) return { 등급: '✅', 말: `구성이 목표와 같다 (${대장.목표월액})` };

  if (대장.상태 === '지원팀답기다림') {
    if (!대장.기다림시작) return { 등급: '🔴', 말: '기다린다는데 언제부터인지가 없다' };
    const 기다린날 = 날수차(오늘, 대장.기다림시작);
    const 한계 = Number(대장.기다림한계일수 ?? 5);
    if (기다린날 > 한계)
      return { 등급: '🔴', 말: `${기다린날}일째 답이 없다 (한계 ${한계}일) — 다시 채근하거나 우리가 직접 줄인다` };
    return { 등급: '⏳', 말: `지원팀 답을 ${기다린날}일째 기다린다 (${한계}일까지) · 대화 ${대장.지원팀대화ID || '?'}` };
  }

  /* 🔴 [2026-09-29] 「갱신일에 처리한다」 갈래를 넣었다.
     ── 왜 ────────────────────────────────────────────────────────────
     지원팀에 여덟 번 보냈고 8일째 사람 답이 없다. 대장이 스스로 적어 두었듯
     **메일(support@anthropic.com)은 Fin 봇만 답한다.** 그러니 「다시 채근하라」는
     처방은 이미 여덟 번 해 본 문이고, 그 문으로는 안 열린다.
     ⭐ 그런데 진짜 기한은 지원팀이 아니라 **갱신일(재청구)**이다 —
       그날까지 좌석을 안 줄이면 다음 달도 옛 금액으로 또 청구된다.
     ⇒ 기다리는 날수가 아니라 «그 기한»을 잰다. 기한이 다가오면 그때 빨강이다.
     ⛔ 빨간불을 끄려고 이 갈래로 옮기지 않는다 — 옮기면 «기한»이 대신 감시한다.
        기한이 없으면 그 자리에서 빨강이다. */
  if (대장.상태 === '갱신일에처리') {
    if (!대장.처리기한) return { 등급: '🔴', 말: '갱신일에 처리한다는데 기한이 없다' };
    const 남은날 = 날수차(대장.처리기한, 오늘);
    const 미리 = Number(대장.며칠전에하나 ?? 3);
    if (남은날 < 0) return { 등급: '🔴', 말: `기한이 ${-남은날}일 지났다 (${대장.처리기한}) — 옛 금액으로 또 청구된다` };
    if (남은날 <= 미리)
      return { 등급: '🔴', 말: `${남은날}일 뒤가 기한이다 (${대장.처리기한}) — 지금 ${대장.뗄자리} 을 떼고 예약을 건다` };
    return { 등급: '✅', 말: `갱신일에 처리한다 — ${대장.처리기한} 까지 ${남은날}일 (${미리}일 전에 빨강)` };
  }

  /* 기다리는 중이 아닌데 구성이 다르면 우리가 할 일이 남은 것이다 */
  return { 등급: '🔴', 말: `구성이 목표와 다르다 — 지금 ${대장.지금월액}, 목표 ${대장.목표월액}. 뗄 자리 ${대장.뗄자리}` };
}

export function 대장읽기(길 = 대장길) {
  try { return JSON.parse(fs.readFileSync(길, 'utf8')); } catch { return null; }
}

/* ───────────────────────── 자가시험 ───────────────────────── */
function 자가시험() {
  let 통과 = 0; let 깨짐 = 0;
  const 잰다 = (이름, 실제, 바람) => {
    const 맞나 = JSON.stringify(실제) === JSON.stringify(바람);
    console.log(`${맞나 ? '  ✓' : '  ✗'} ${이름}${맞나 ? '' : `\n      난 것 ${JSON.stringify(실제)}\n      바란 것 ${JSON.stringify(바람)}`}`);
    맞나 ? 통과++ : 깨짐++;
  };
  const 본 = {
    상태: '지원팀답기다림', 기다림시작: '2026-09-21', 기다림한계일수: 5,
    목표구성: { 프리미엄: 1, 스탠다드: 1 }, 지금구성: { 프리미엄: 1, 스탠다드: 2 },
    목표월액: 'US$165', 지금월액: 'US$192.50', 뗄자리: 'u1@klifedesign.net', 끝났나: false,
  };

  console.log('── 날짜 셈');
  잰다('같은 날은 0', 날수차('2026-10-20', '2026-10-20'), 0);
  잰다('하루 뒤는 1', 날수차('2026-10-20', '2026-10-19'), 1);
  잰다('달을 넘어도 센다', 날수차('2026-10-01', '2026-09-21'), 10);
  잰다('지났으면 음수', 날수차('2026-10-20', '2026-10-25'), -5);
  잰다('날짜글은 두 자리로 채운다', 날짜글(new Date(2026, 0, 5)), '2026-01-05');

  console.log('── 기다리는 동안');
  잰다('첫날은 기다림', 판정(본, '2026-09-21').등급, '⏳');
  잰다('닷새째도 기다림', 판정(본, '2026-09-26').등급, '⏳');
  잰다('엿새째부터 빨강', 판정(본, '2026-09-27').등급, '🔴');
  잰다('언제부터인지 없으면 빨강', 판정({ ...본, 기다림시작: null }, '2026-09-21').등급, '🔴');

  console.log('── 구성으로 판정');
  잰다('구성이 같아지면 초록', 판정({ ...본, 지금구성: { 프리미엄: 1, 스탠다드: 1 } }, '2026-10-30').등급, '✅');
  잰다('구성이 같으면 기다림보다 앞선다', 판정({ ...본, 지금구성: { 프리미엄: 1, 스탠다드: 1 } }, '2026-12-01').등급, '✅');
  잰다('안 기다리는데 다르면 빨강', 판정({ ...본, 상태: '우리차례' }, '2026-09-21').등급, '🔴');
  잰다('끝냈으면 초록', 판정({ ...본, 끝났나: true }, '2026-12-01').등급, '✅');

  console.log('── 못 읽을 때');
  잰다('대장이 없으면 빨강', 판정(null).등급, '🔴');

  /* 🔴 [2026-09-29] 「갱신일에처리」 갈래 — 빨간불을 «끄는» 갈래가 아니라 «기한»을 재는 갈래다 */
  const 갱 = { ...본, 상태: '갱신일에처리', 처리기한: '2026-10-19', 며칠전에하나: 3 };
  잰다('기한이 멀면 초록', 판정(갱, '2026-09-29').등급, '✅');
  잰다('🔴 기한이 사흘 안이면 빨강', 판정(갱, '2026-10-16').등급, '🔴');
  잰다('🔴 기한 당일도 빨강', 판정(갱, '2026-10-19').등급, '🔴');
  잰다('🔴 기한이 지나면 빨강', 판정(갱, '2026-10-21').등급, '🔴');
  잰다('⛔ 기한 없이 이 갈래로 옮기면 그 자리에서 빨강',
    판정({ ...본, 상태: '갱신일에처리' }, '2026-09-29').등급, '🔴');
  잰다('⛔ 구성이 이미 목표면 갈래와 상관없이 초록',
    판정({ ...갱, 지금구성: { 프리미엄: 1, 스탠다드: 1 } }, '2026-10-21').등급, '✅');

  console.log('── 진짜 대장');
  const 진짜 = 대장읽기();
  잰다('대장 파일이 읽힌다', 진짜 !== null, true);
  잰다('목표구성이 1+1 이다', [진짜?.목표구성?.프리미엄, 진짜?.목표구성?.스탠다드], [1, 1]);
  잰다('뗄 자리가 적혀 있다', (진짜?.뗄자리 || '').includes('@'), true);
  잰다('지원팀 대화 ID 가 있다', typeof 진짜?.지원팀대화ID, 'string');

  console.log(`\n${깨짐 ? '🔴' : '✅'} ${통과}/${통과 + 깨짐} 통과`);
  return 깨짐 === 0;
}

/* ───────────────────────── 실행 ───────────────────────── */
const 인자 = process.argv.slice(2);
if (인자.includes('--자가시험') || 인자.includes('--selftest')) {
  process.exit(자가시험() ? 0 : 1);
} else {
  const 대장 = 대장읽기();
  const r = 판정(대장);
  if (인자.includes('--체크리스트')) {
    console.log(`${r.등급} ⑧-2 좌석 구성    ${r.말}`);
  } else {
    console.log('■ Anthropic 좌석 구성 — 프리미엄1 + 스탠다드1 로 맞추는 일\n');
    if (!대장) { console.log('🔴 대장을 못 읽었다 —', 대장길); process.exit(1); }
    console.log(`   지금        프리미엄 ${대장.지금구성.프리미엄} · 스탠다드 ${대장.지금구성.스탠다드}   ${대장.지금월액}`);
    console.log(`   목표        프리미엄 ${대장.목표구성.프리미엄} · 스탠다드 ${대장.목표구성.스탠다드}   ${대장.목표월액}`);
    console.log(`   상태        ${대장.상태} (${대장.기다림시작}부터)`);
    console.log(`   대화        ${대장.지원팀대화ID}`);
    console.log(`   뗄 자리      ${대장.뗄자리}`);
    if (Array.isArray(대장.두번청구됨)) {
      console.log('\n   두 번 청구된 것');
      for (const c of 대장.두번청구됨) console.log(`     ${c.때}  ${c.영수증}  ${c.금액}`);
    }
    console.log(`\n   ${대장['⛔손대지말것']}`);
    console.log(`\n${r.등급} ${r.말}`);
  }
  /* ⏳ 는 흠이 아니다 — 기다리는 것은 우리 잘못이 아니다 */
  process.exit(r.등급 === '🔴' ? 1 : 0);
}
