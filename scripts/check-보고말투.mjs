/** 글에서 걸린 말을 찾는다. ⛔ 못 읽으면 null — 「없다」가 아니다 */
export function 걸린말찾기(글, 목록 = 바꿀말) {
  if (typeof 글 !== 'string') return null;
  const 것 = [];
  const 줄들 = 글.split(/\r?\n/);
  for (let i = 0; i < 줄들.length; i += 1) {
    for (const w of 목록 ?? []) {
      if (줄들[i].includes(w.쓴다)) {
        것.push({ 줄번호: i + 1, 쓴다: w.쓴다, 대신: w.대신, 까닭: w.까닭, 줄: 줄들[i].trim().slice(0, 70) });
      }
    }
  }
  return 것;
}

/* ── 자체 테스트 ─────────────────────────────────────────── */
export function 테스트() {
  const 결과 = [];
  const 본다 = (이름, 참) => 결과.push({ 이름, 참: !!참 });

  본다('「지면」을 잡는다', 걸린말찾기('파는 지면 유입 0').some((x) => x.쓴다 === '지면'));
  본다('한 줄에 둘이 있으면 둘 다 잡는다', 걸린말찾기('파는 지면 유입 0').length === 2);
  본다('줄 번호를 준다 — 어디를 고칠지 알아야 한다',
    걸린말찾기('첫 줄\n둘째 지면')[0].줄번호 === 2);
  본다('바꿔 쓸 말을 함께 준다 — 잡기만 하면 또 틀린다',
    걸린말찾기('지면')[0].대신 === '페이지');
  본다('깨끗한 글은 빈 배열', 걸린말찾기('페이지 방문자 0명').length === 0);
  본다('⛔ 글이 아니면 null — 「없다」가 아니다', 걸린말찾기(null) === null);
  본다('⛔ 빈 글은 빈 배열이지 null 이 아니다', 걸린말찾기('').length === 0);

  return 결과;
}

/* ── 실제로 본다 ───────────────────────────────────────────── */
const 이파일이진입점 =
  process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (이파일이진입점) {
  const 인자 = process.argv.slice(2);
  if (인자.includes('--자가시험') || 인자.includes('--테스트')) {
    const 결과 = 테스트();
    let 빨강 = 0;
    console.log('■ 보고 말투 — 자체 테스트');
    for (const r of 결과) { if (!r.참) 빨강++; console.log(`  ${r.참 ? '✅' : '🔴'} ${r.이름}`); }
    console.log(빨강 ? `🔴 실패 ${빨강}개` : `✅ ${결과.length}가지 다 통과`);
    process.exit(빨강 ? 1 : 0);
  }

  const 파일 = 인자.find((a) => !a.startsWith('--'));
  let 글 = null;
  if (파일 === '-' || !파일) {
    try { 글 = fs.readFileSync(0, 'utf8'); } catch { 글 = null; }
  } else {
    try { 글 = fs.readFileSync(파일, 'utf8'); } catch { 글 = null; }
  }
  if (글 === null) {
    console.log('⬜ 글을 못 읽었다 — 「문제 없다」가 아니다');
    process.exit(0);
  }

  const 걸린것 = 걸린말찾기(글);
  if (!걸린것.length) {
    console.log('✅ 사장님께 쓰면 안 되는 말이 없다');
    process.exit(0);
  }
  console.log(`🔴 고쳐야 할 말 ${걸린것.length}곳`);
  for (const x of 걸린것) {
    console.log(`   ${String(x.줄번호).padStart(4)}줄  「${x.쓴다}」 → ${x.대신}`);
    console.log(`         ${x.까닭}`);
    console.log(`         ${x.줄}`);
  }
  console.log('\n⛔ 사장님: 「몇 번 말했잖아」·「아직도 이러고 있어」 — 보내기 전에 고친다');
  process.exit(1);
}
