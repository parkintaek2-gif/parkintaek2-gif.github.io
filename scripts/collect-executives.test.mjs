#!/usr/bin/env node
/**
 * 임원 재직기간 파서 시험.
 *
 * ⚠ **실제 DART 원문의 꼴**로 시험한다. 지어낸 것이 아니다.
 *   2026-08-05 에 대표재직 채움률이 64.1% 였는데, 원인이 회사의 미기재가 아니라
 *   **`~` 로 끝나는 꼴(= 아직 재직 중)을 파서가 통째로 버린 것**이었다.
 *   대표 3,589명 중 1,190명(33.2%)이 여기서 떨어졌고, **1,190명 전부 원문은 있었다.**
 */
import { 개월, 연도네자리 } from './collect-executives.mjs';

/* ⚠ 「오늘」을 고정한다. 안 그러면 내일 시험이 깨진다 */
const 오늘 = new Date(2026, 7, 5);   // 2026-08-05 KST

const 표 = [
  /* ⭐ 이번에 고친 것 — `~` 뒤에 아무것도 없다 (실측 상위 꼴) */
  ['1991.9.28~', (2026 - 1991) * 12 + (7 - 8), '열린 기간 (일 있음)'],
  ['2015.03~', (2026 - 2015) * 12 + (7 - 2), '열린 기간 (일 없음)'],
  ['2020.03.02 ~ ', (2026 - 2020) * 12 + (7 - 2), '열린 기간 (뒤 공백)'],
  /* ⭐ 2자리 연도 */
  ['91.9.28~', (2026 - 1991) * 12 + (7 - 8), '2자리 연도 (지난 세기)'],
  ['05.3.1~', (2026 - 2005) * 12 + (7 - 2), '2자리 연도 (이번 세기)'],
  /* 원래 되던 것 — 안 깨졌는지 본다 */
  ['2012.12.18~현재', (2026 - 2012) * 12 + (7 - 11), '현재 명시'],
  ['2015.03.02 ~ 현재', (2026 - 2015) * 12 + (7 - 2), '현재 (공백 있음)'],
  ['3년 2개월', 38, '회사가 계산해 준 것'],
  ['12년', 144, '년만'],
  ['46개월', 46, '개월만'],
  /* ⭐ 처음 고칠 때 월을 필수로 둬서 **42건을 도로 잃었던** 꼴들. 회귀 방지 */
  ['1986~현재', (2026 - 1986) * 12 + 7, '연도만 (월 없음)'],
  ['2016~\n현재', (2026 - 2016) * 12 + 7, '연도만 + 줄바꿈'],
  ['2015.12.\n~현재', (2026 - 2015) * 12 + (7 - 11), '월 뒤에 점이 남는다'],
  ['2023. 3. ~ 현재', (2026 - 2023) * 12 + (7 - 2), '점 + 공백'],
  /* ⚠ 2자리 연도인데 월이 없으면 **읽지 않는다** — 2012년인지 12개월인지 모른다 */
  ['12~', null, '2자리 + 월 없음 → 모른다'],
  /* ⚠ 못 읽으면 **null.** 0 으로 만들면 순위 맨 아래가 쓰레기로 찬다 */
  ['0년', null, '0년은 값이 아니다 (총<=0 은 버린다)'],
  ['-', null, '대시'],
  ['해당없음', null, '해당없음'],
  ['', null, '빈 값'],
  [null, null, 'null'],
  ['12', null, '단위 없는 숫자 — 년인지 월인지 모른다'],
];

let 실패 = 0;
console.log('임원 재직기간 파서');
for (const [입력, 기대, 설명] of 표) {
  const 결과 = 개월(입력, 오늘);
  if (결과 !== 기대) {
    실패++;
    console.log(`  ✕ ${설명}`);
    console.log(`      ${JSON.stringify(입력)} → ${결과} (기대 ${기대})`);
  }
}

/* 2자리 연도 규칙 */
for (const [입력, 기대] of [['91', 1991], ['05', 2005], ['26', 2026], ['27', 1927], ['2015', 2015]]) {
  const r = 연도네자리(입력, 오늘);
  if (r !== 기대) { 실패++; console.log(`  ✕ 연도네자리(${입력}) → ${r} (기대 ${기대})`); }
}

/* ⚠ 시작이 끝보다 뒤면 **버린다.** 음수 개월이 순위에 들어가면 안 된다 */
if (개월('2030.01~2020.01', 오늘) !== null) { 실패++; console.log('  ✕ 거꾸로 된 기간을 받아들였다'); }

const 총 = 표.length + 5 + 1;
if (실패) { console.error(`\n${총 - 실패} 통과 · ${실패} 실패`); process.exit(1); }
console.log(`  ${총} 통과 · 0 실패`);
