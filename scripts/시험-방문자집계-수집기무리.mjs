#!/usr/bin/env node
/**
 * 시험-방문자집계-수집기무리.mjs
 *   — **주소를 바꿔 가며 도는 한 대를 수백 명으로 세지 않는가.**
 *
 * ── 🔴 왜 지었나 (2026-11-04 · 사장님 「왜 바뀐게 없지?」) ──────────────
 * 사장님이 「방문자 381, 조회 608 맞아?」라고 물으셨다. 재 보니 수집기였다.
 * 그런데 나는 **화면에 진단 칸만 붙이고 수는 그대로 475명으로 두었다.**
 * 사장님이 다시 「왜 바뀐게 없지?」라고 물으셨다 —
 *   **틀린 줄 알면서 내보낸 수는, 재지 않은 수와 같다.**
 *
 * ── 무엇으로 가르나 ────────────────────────────────────────────────
 * 브라우저 이름표 하나를 «몇 개의 주소»가 나눠 썼나.
 *   2026-11-04 klifemap.ai 실측 —
 *     126주소/158조회 · 111/122 · 106/136 · 105/145 · 87/122 · 81/111 · 80/112
 *   사람 696명이면 이름표가 수십 가지로 흩어진다. 크롬은 잔버전까지 제각각이다.
 *   글자 하나 안 틀리고 똑같은 이름표를 주소 126개가 같은 날 쓰는 일은 없다.
 *
 * ⚠ 부속(그림·모양표) 자로는 못 거른다 — 이들은 부속까지 받아 간다.
 *   11-03 에 깐 부속 자가 이들을 그대로 통과시켰고, 그래서 수가 안 줄었다.
 *
 * ⚠ klifemap/server/방문자집계.js 와 «같은 규칙»이다. 한쪽만 고치지 않는다.
 *
 * 쓰는 법
 *   node scripts/시험-방문자집계-수집기무리.mjs
 */
import * as 방문 from '../src/lib/방문자집계.mjs';

const T = [];
const 재다 = (이름, 참) => T.push([이름, !!참]);

console.log('■ 수집기 무리 — 주소를 바꿔 가며 도는 한 대를 수백 명으로 세지 않는가\n');

/* ── ① 가르는 자 그 자체 ─────────────────────────────────────────── */
재다('126주소 158조회 는 무리다 (2026-11-04 실측)', 방문.무리인가(126, 158) === true);
재다('111주소 122조회 도 무리다', 방문.무리인가(111, 122) === true);
재다('80주소 112조회 도 무리다', 방문.무리인가(80, 112) === true);
재다('⛔ 주소 열아홉이면 안 건드린다 — 바닥은 스물이다', 방문.무리인가(19, 19) === false);
재다('⛔ 주소가 많아도 여러 장 보면 사람이다', 방문.무리인가(100, 300) === false);
재다('⛔ 딱 두 배는 사람 쪽에 남긴다 — 금은 «미만»이다', 방문.무리인가(50, 100) === false);
재다('1.99배는 무리다', 방문.무리인가(100, 199) === true);
재다('빈 값에 안 터진다', 방문.무리인가(null, undefined) === false);
재다('바닥 20 · 비 2 — klifemap 쪽과 같은 수다',
  방문.무리주소바닥 === 20 && 방문.무리조회비 === 2);

/* ── ② 🔴 수가 «실제로» 내려가는가 ──────────────────────────────────
   이름표 하나를 주소 스물다섯이 나눠 쓰고, 그 밖에 다섯이 제각각 다른
   이름표를 쓴다. 사람으로 남을 것은 그 다섯이다. */
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36';
const 날 = '2099-04-04';   /* 실제 수치를 더럽히지 않는 날 */
방문.시작일을바꾼다('2099-01-01');
for (let i = 1; i <= 25; i += 1) {
  방문.기록('seoulmarkets.com', '8.8.1.' + i, UA, 날, '/x');
  /* ⚠ 부속까지 받아 간다 — 그래도 무리다. 부속 자로는 이들을 못 거른다 */
  방문.부속기록('seoulmarkets.com', '8.8.1.' + i, 날);
}
for (let i = 1; i <= 5; i += 1) {
  방문.기록('seoulmarkets.com', '8.8.2.' + i, UA + ' Edg/1' + i + '.0', 날, '/x');
  방문.부속기록('seoulmarkets.com', '8.8.2.' + i, 날);
}
const r = 방문.집계(날)['seoulmarkets.com'];
재다('🔴 사람 수에서 무리를 실제로 뺐다 — 30이 아니라 5다', r.방문자 === 5);
재다('🔴 뺀 몫을 «무리» 칸에 그대로 적는다 — 지우지 않는다',
  r.무리방문자 === 25 && r.무리조회수 === 25);
재다('⛔ 부속을 받아 갔어도 무리는 무리다 — 부속 자로는 못 거른다', r.부속받은사람 === 30);
재다('⛔ 「자동」으로 밀지 않는다 — 제 이름을 밝힌 수집기와 섞으면 둘 다 못 읽는다',
  r.자동 === 0);
재다('어느 이름표가 무리였는지 화면에 낼 수 있다',
  Array.isArray(r.무리이름표) && r.무리이름표.length === 1 && r.무리이름표[0][1] === 25);

T.forEach(([이름, 참]) => console.log((참 ? '  ✅ ' : '  ❌ ') + 이름));
const 깨짐 = T.filter((x) => !x[1]).length;
console.log(깨짐 ? '\n■ ' + 깨짐 + '건 실패' : '\n■ 모두 통과 (' + T.length + '가지)');
process.exit(깨짐 ? 1 : 0);
