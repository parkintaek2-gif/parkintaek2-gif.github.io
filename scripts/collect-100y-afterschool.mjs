export const 다듬 = (s) => String(s).replace(/\s+/g, ' ').trim();
export const 유형전체 = '늘봄학교 및 방과후학교(유상+무상)';

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
export const 한자리 = (v) => (v == null ? null : Math.round(v * 10) / 10);

/** 빠진 해를 찾는다 — ⛔ 「자료가 없다」가 아니라 «표에 그 해가 없다»로 적으려고 */
export function 빠진해(해들) {
  const ns = 해들.map(Number).sort((a, b) => a - b);
  const 낸다 = [];
  for (let y = ns[0]; y <= ns[ns.length - 1]; y++) if (!ns.includes(y)) 낸다.push(String(y));
  return 낸다;
}

