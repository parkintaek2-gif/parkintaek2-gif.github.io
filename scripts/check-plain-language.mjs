/** 풀이가 붙었다고 볼 수 있는 꼴 — 괄호 안에 있거나, 괄호로 풀어 놓았거나 */
const 괄호쌍 = [['(', ')'], ['（', '）'], ['「', '」'], ['[', ']'], ['《', '》'], ['«', '»']];

/**
 * 그 말이 «풀린 채로» 쓰였는가.
 * ⭐ 두 가지 중 하나면 풀린 것으로 본다 —
 *   ① 그 말 자체가 괄호 안에 있다      「하늘 전체(원국)」
 *   ② 그 말 바로 뒤에 괄호 풀이가 온다  「원국(Natal Chart)」
 * ⛔ 「글 어딘가에 설명이 있겠지」로 봐주지 않는다 — 그러면 아무것도 안 걸린다.
 */
export function 풀렸나(글, 말) {
  const s = String(글 ?? '');
  const w = String(말 ?? '');
  if (!w) return true;
  const 자리 = s.indexOf(w);
  if (자리 < 0) return true; /* 아예 없으면 걸 것도 없다 */
  /* 🔴 [2026-09-06] 처음엔 «모든» 자리가 풀려야 통과로 했다. 너무 엄격했다 —
     「서양 별자리(태양궁)… 태양궁은 …」처럼 **첫머리에서 제대로 풀어 준 좋은 글**까지 걸렸다.
     ⛔ 검사가 잘 쓴 글을 걸면 사람이 검사를 끈다(배포 관문이 스스로 경고하는 그 위험이다).
     ⭐ 손님은 글을 위에서 아래로 읽는다. **첫 등장에서 풀어 주면 그 뒤는 그 말로 불러도 된다.**
        그래서 「첫 등장이 풀렸나」만 본다. */
  return 이자리가풀렸나(s, 자리, w);
}

function 이자리가풀렸나(s, 자리, w) {
  const 끝 = 자리 + w.length;
  /* ② 바로 뒤에 괄호 풀이가 오나 — 사이에 조사 한두 글자는 허용한다 */
  const 뒤 = s.slice(끝, 끝 + 4);
  for (const [여, 닫] of 괄호쌍) if (뒤.trimStart().startsWith(여)) return true;
  /* ① 그 말이 괄호 «안»에 있나 — 앞쪽에서 가장 가까운 여는 괄호를 찾는다 */
  for (const [여, 닫] of 괄호쌍) {
    const 연자리 = s.lastIndexOf(여, 자리);
    if (연자리 < 0) continue;
    const 닫자리 = s.indexOf(닫, 연자리);
    if (닫자리 >= 끝) return true;
  }
  return false;
}

/**
 * 안 풀린 채로 쓰인 «첫 자리»를 돌려준다. 없으면 -1.
 * 🔴 [2026-09-06] 처음엔 `indexOf` 로 «맨 앞» 자리를 보여 줬다. 그런데 그 자리는
 *   대개 «풀려 있는» 자리다(첫 등장에서 괄호로 풀고 뒤에서 맨몸으로 쓰니까).
 *   그래서 화면에 「부점 → 옛 책이 쓰던 특별한 지점(부점)」처럼 **이미 고친 것이 걸린 것처럼**
 *   보였다. ⛔ 검사가 사람을 헷갈리게 하면 사람이 검사를 끈다. 안 풀린 자리를 짚어 준다.
 */
export function 안풀린자리(글, 말) {
  const s = String(글 ?? ''); const w = String(말 ?? '');
  if (!w) return -1;
  const i = s.indexOf(w);
  if (i < 0) return -1;
  /* ⭐ 「첫 등장이 풀렸나」만 본다 — 풀렸나() 와 같은 규칙을 쓴다.
     ⛔ 두 함수가 «다른 규칙»을 쓰면 「걸렸다는데 자리가 -1」 같은 모순이 난다 */
  return 이자리가풀렸나(s, i, w) ? -1 : i;
}

/** 글 한 토막을 재서 «안 풀린» 어려운 말을 돌려준다 */
export function 잰다(글, 표 = 어려운말표) {
  const s = String(글 ?? '');
  const 걸린 = [];
  for (const r of 표) {
    if (!s.includes(r.말)) continue;
    const i = 안풀린자리(s, r.말);
    if (i < 0) continue;
    /* ⭐ «안 풀린» 그 자리의 앞뒤를 준다 — 사람이 바로 그곳을 고칠 수 있게 */
    const 몇번째 = s.slice(0, i).split(r.말).length;
    걸린.push({
      ...r,
      자리: s.slice(Math.max(0, i - 30), i + r.말.length + 30).replace(/\s+/g, ' '),
      몇번째,
    });
  }
  return 걸린;
}

/** 지면 HTML 에서 «손님이 읽는 글»만 뽑는다 — 코드·주석은 뺀다 */
export function 화면글만(html) {
  return String(html ?? '')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

