#!/usr/bin/env node
/**
 * 한시간동안-한일.mjs — **그 한 시간에 «실제로» 무엇을 했는지 한 줄로 뽑는다.**
 *
 * ── 🔴🔴 왜 (2026-10-10 18:2x · 사장님) ────────────────────────────
 * > 「**1시간에 한번씩 소통하라고 몇 번을 말하냐, ai라는 것들이 이렇게 무성의하니**」
 * > 「**소통하라고 미친놈아**」
 *
 * 대장을 열어 보니 내 줄은 매시 «들어가 있었다». 그런데 내용이 이랬다 —
 * ```
 * 13:06  서울마켓츠 결제 점검 — 팔린다. 주문 … · 승인은 안 불렀다. 다음: 이어서 맡은 일.
 * 14:06  서울마켓츠 결제 점검 — 팔린다. 주문 … · 승인은 안 불렀다. 다음: 이어서 맡은 일.
 * 15:06  (같은 문장)   16:06  (같은 문장)   17:04  (같은 문장)   18:06  (같은 문장)
 * ```
 * **여섯 시간 동안 같은 문장이었다.** 그 사이 나는 애드센스를 풀고 토스 거짓을 지우고
 * 번역 스물넷을 고치고 배포를 두 번 했는데 **한 줄도 안 적혀 있었다.**
 *
 * ⛔ 까닭은 게으름이 아니라 **구조**였다. `check-seoulmarkets-payment.mjs` 가 재면서
 *   그 시간 칸에 먼저 적어 버리고, 그 뒤에는 「이미 이 시간에 적었다」로 막힌다.
 *   ⇒ **자동 도장이 사람 소통 자리를 차지하고 있었다.**
 * ⭐ 줄이 있다고 소통이 된 것이 아니다. **읽는 사람이 무엇이 달라졌는지 알아야** 소통이다.
 *
 * ⇒ 이 자가 «지난 한 시간의 커밋 제목»을 모아 한 줄로 만든다. 커밋은 지어낼 수 없다.
 *   한 일이 없으면 없다고 적는다 — 그것도 사실이다.
 *
 * ⛔ 커밋이 없다고 「한 일 없음」으로 끝내지 않는다. 배포·점검처럼 커밋이 안 남는 일도 있다.
 *   그래서 부르는 쪽이 «잰 결과»를 함께 넘기고, 이 자는 그 뒤에 커밋을 붙인다.
 *
 * 쓰는 법
 *   node scripts/한시간동안-한일.mjs                  지난 한 시간
 *   node scripts/한시간동안-한일.mjs --시간 3         지난 세 시간
 *   node scripts/한시간동안-한일.mjs --자가시험
 */
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 커밋 제목에서 군더더기를 덜어 낸다 — 대장은 한 줄이라 좁다 */
export function 제목다듬기(줄) {
  return String(줄 ?? '')
    .replace(/^[0-9a-f]{7,40}\s+/, '')          /* 해시가 앞에 붙어 오면 뗀다 */
    .replace(/\s*\(#\d+\)\s*$/, '')             /* (#123) 따위 */
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 커밋 제목들을 한 줄로 묶는다.
 * ⛔ 너무 길면 대장이 못 읽는다 — 앞에서부터 담고 넘치면 「외 N건」으로 접는다.
 */
export function 한줄로(제목들, 길이한도 = 420) {
  const 것 = (제목들 ?? []).map(제목다듬기).filter(Boolean);
  if (!것.length) return '';
  const 담은것 = [];
  let 길이 = 0;
  for (const t of 것) {
    /* 「외 N건」이 붙을 자리를 남겨 둔다 */
    if (길이 + t.length + 3 > 길이한도 - 12 && 담은것.length) break;
    담은것.push(t);
    길이 += t.length + 3;
  }
  const 남은수 = 것.length - 담은것.length;
  return 담은것.join(' · ') + (남은수 > 0 ? ` 외 ${남은수}건` : '');
}

/**
 * 지난 N시간 동안 «내가» 민 커밋 제목을 읽는다.
 * ⛔ 남의 유닛 커밋을 내 한 일로 적지 않는다 — 글쓴이로 거른다.
 * ⚠ 못 읽으면 빈 배열이다. 0 으로 채우듯 지어내지 않는다.
 */
export function 커밋제목들(시간 = 1, { 돌리는이 = 참으로돌린다, 글쓴이 = '' } = {}) {
  try {
    const 인자 = ['log', `--since=${시간} hours ago`, '--pretty=%s', '--no-merges'];
    if (글쓴이) 인자.push(`--author=${글쓴이}`);
    return String(돌리는이(인자) ?? '').split('\n').map((s) => s.trim()).filter(Boolean);
  } catch { return []; }
}

function 참으로돌린다(인자) {
  return execFileSync('git', 인자, { cwd: 뿌리, encoding: 'utf8', timeout: 30000 });
}

/**
 * 대장에 적을 한 줄을 만든다.
 * @param {string} 잰것  부르는 쪽이 방금 «실제로 잰» 결과(결제 점검 따위). 없으면 빈 글
 */
export function 소통줄(잰것, 제목들, { 할일 = '이어서 맡은 일' } = {}) {
  const 한일 = 한줄로(제목들);
  const 앞 = String(잰것 ?? '').trim();
  const 가운데 = 한일 ? `한 일: ${한일}` : '한 일: 커밋으로 남은 것 없음';
  return [앞, 가운데, `할 일: ${할일}`].filter(Boolean).join(' / ');
}

/* ── 자가시험 ─────────────────────────────────────────────────── */
function 자가시험() {
  let 통 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통++; console.log('✅', 이름); } else { 탈++; console.log('🔴', 이름); } };

  검('제목에서 해시를 뗀다', 제목다듬기('a1b2c3d 사이트맵 고침') === '사이트맵 고침');
  검('여러 칸 띄기를 하나로', 제목다듬기('가   나') === '가 나');
  검('⛔ 빈 것에 안 터진다', 제목다듬기(null) === '' && 제목다듬기('') === '');

  검('🔴 여러 제목을 한 줄로 묶는다', 한줄로(['가', '나']) === '가 · 나');
  검('⛔ 없으면 빈 글이다 — 지어내지 않는다', 한줄로([]) === '' && 한줄로(null) === '');
  const 긴것 = Array.from({ length: 30 }, (_, i) => `아주 긴 커밋 제목입니다 ${i}`);
  const 접힘 = 한줄로(긴것);
  검('🔴 길면 「외 N건」으로 접는다', /외 \d+건$/.test(접힘));
  검('⛔ 접어도 한도를 안 넘는다', 접힘.length <= 420);
  검('⛔ 하나도 안 담기는 일은 없다', 접힘.split(' · ')[0].length > 0);

  const 가짜 = () => '사이트맵 고침\n토스 거짓 지움\n';
  검('🔴 커밋 제목을 읽는다', 커밋제목들(1, { 돌리는이: 가짜 }).length === 2);
  검('⛔ 터지면 빈 배열이다', 커밋제목들(1, { 돌리는이: () => { throw new Error('x'); } }).length === 0);
  검('⛔ 글쓴이를 주면 인자에 넣는다', (() => {
    let 본것 = null;
    커밋제목들(1, { 돌리는이: (a) => { 본것 = a; return ''; }, 글쓴이: 'me@x' });
    return 본것.includes('--author=me@x');
  })());

  /* 🔴🔴 오늘 당한 그 꼴 — 잰 결과만 있고 한 일이 없는 줄 */
  검('🔴 커밋이 없으면 «없다»고 적는다 — 빈 채로 두지 않는다',
    소통줄('결제 점검 — 팔린다', []).includes('커밋으로 남은 것 없음'));
  검('🔴 잰 결과와 한 일이 «둘 다» 들어간다 — 오늘은 앞엣것만 있었다', (() => {
    const 줄 = 소통줄('결제 점검 — 팔린다', ['애드센스 풀었다', '토스 거짓 지움']);
    return 줄.includes('결제 점검 — 팔린다') && 줄.includes('애드센스 풀었다') && 줄.includes('토스 거짓 지움');
  })());
  검('⛔ 잰 것이 없어도 한 일은 적힌다', 소통줄('', ['가']).startsWith('한 일: 가'));
  검('할 일이 끝에 붙는다', 소통줄('', ['가']).endsWith('할 일: 이어서 맡은 일'));
  검('⛔ 여섯 시간 같은 문장이 되지 않는다 — 커밋이 다르면 줄이 다르다',
    소통줄('같은 점검', ['A']) !== 소통줄('같은 점검', ['B']));

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${통} 통과`);
  process.exit(탈 ? 1 : 0);
}

/* ── 실제로 돈다 ─────────────────────────────────────────────── */
if (process.argv.includes('--자가시험')) 자가시험();

const 내가실행됐다 = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (내가실행됐다) {
  const i = process.argv.indexOf('--시간');
  const 시간 = i > -1 ? Number(process.argv[i + 1]) || 1 : 1;
  const 제목들 = 커밋제목들(시간);
  console.log(`■ 지난 ${시간}시간 커밋 ${제목들.length}건`);
  console.log(소통줄('', 제목들));
}
