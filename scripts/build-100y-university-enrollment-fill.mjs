/**
 * build-100y-university-enrollment-fill.mjs
 *
 * 이슈  2026-09-07 — 오늘 만든 /college-age-population(18세 인구 2015→2024 34.1%↓,
 *       2025·2026 반등 후 2035년까지 재감소)의 자연스러운 후속: 인구가 주는데
 *       대학은 정원을 얼마나 채우고 있나. ⛔ 특정 학교를 「망했다」로 읽지 않는다 —
 *       재학생충원율 분포를 그대로 보여 준다(줄 세우지 않는다, 사장님 강령).
 *
 * 새 API 호출 없음 — 이미 수집된 src/data/100yearmap/pages-university.json
 * (대학알리미, 377개 대학·캠퍼스)의 재학생충원율 필드를 재계산만 한다.
 *
 * 쓰는 법  node scripts/build-100y-university-enrollment-fill.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const 원본길 = path.join(ROOT, 'src/data/100yearmap/pages-university.json');
const 낼길 = path.join(ROOT, 'src/data/100yearmap/university-enrollment-fill.json');

export function 정리(대학목록) {
  const 값있음 = 대학목록.filter((x) => x.재학생충원율 && typeof x.재학생충원율.값 === 'number');

  const v = 값있음.map((x) => x.재학생충원율.값).slice().sort((a, b) => a - b);
  const 전체 = {
    곳수: v.length,
    못잰곳: 대학목록.length - v.length,
    최소: v[0],
    최대: v[v.length - 1],
    중앙값: v[Math.floor(v.length / 2)],
    전국평균참고: 값있음[0]?.재학생충원율?.전국평균 ?? null,
  };

  const 구간이름 = (v) => {
    if (v >= 110) return '110% 이상';
    if (v >= 100) return '100~110%';
    if (v >= 90) return '90~100%';
    if (v >= 80) return '80~90%';
    if (v >= 70) return '70~80%';
    return '70% 미만';
  };
  const 구간순서 = ['110% 이상', '100~110%', '90~100%', '80~90%', '70~80%', '70% 미만'];
  const 구간 = Object.fromEntries(구간순서.map((k) => [k, 0]));
  값있음.forEach((x) => { 구간[구간이름(x.재학생충원율.값)]++; });

  const 정원미달 = 값있음.filter((x) => x.재학생충원율.값 < 100).length;

  const 매우낮은곳 = 값있음
    .filter((x) => x.재학생충원율.값 < 30)
    .sort((a, b) => a.재학생충원율.값 - b.재학생충원율.값)
    .map((x) => ({ 학교: x.title, 구분: x.구분, 설립: x.설립, 재학생충원율: x.재학생충원율.값 }));

  const 매우높은곳 = 값있음
    .filter((x) => x.재학생충원율.값 > 200)
    .sort((a, b) => b.재학생충원율.값 - a.재학생충원율.값)
    .map((x) => ({ 학교: x.title, 구분: x.구분, 설립: x.설립, 재학생충원율: x.재학생충원율.값 }));

  return {
    출처: {
      이름: '한국대학교육협의회 대학정보공시(대학알리미) — 이미 수집된 pages-university.json 재계산',
      이용허락범위: '제한 없음',
    },
    공시연도: 값있음[0]?.공시연도 ?? null,
    정의: {
      재학생충원율: '대학알리미 공시 재학생충원율(값) = 재학생 수 ÷ 정원 × 100. 대학알리미가 공시한 값을 그대로 옮겼다. 100%를 넘으면 정원보다 재학생이 많다는 뜻이다.',
    },
    전체,
    구간,
    정원미달: { 곳수: 정원미달, 전체: 값있음.length, 몫: Math.round((정원미달 / 값있음.length) * 1000) / 10 },
    매우낮은곳,
    매우높은곳,
    덮는범위: [
      '재학생충원율은 대학 하나의 평균이다 — 같은 학교 안에서도 학과별 편차가 있을 수 있다.',
      '30% 미만·200% 초과인 곳은 대부분 신학대·승가대·세무대 등 정원 자체가 매우 작은 특수 계열이다 — 정원이 큰 일반 대학과 같은 잣대로 비교할 수 없다.',
      `재학생충원율이 없는 ${전체.못잰곳}곳은 원자료에 값 자체가 없다 — 0으로 채우지 않았다.`,
      '이 표는 2025년 한 시점의 스냅샷이다 — 연도별 추세(악화·개선 여부)는 이 표만으로 말할 수 없다.',
    ],
    대조: '맞다 — 이 표의 모든 값은 pages-university.json에 이미 있던 대학알리미 공시치를 그대로 옮겨 분포만 다시 계산했다. 새로 받은 값이 없다.',
  };
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };

  const 가짜 = [
    { title: '가짜A대', 구분: '대학', 설립: '국립', 재학생충원율: { 값: 120, 전국평균: 111.4, 차이: 8.6 }, 공시연도: '2025' },
    { title: '가짜B대', 구분: '대학', 설립: '사립', 재학생충원율: { 값: 95, 전국평균: 111.4, 차이: -16.4 }, 공시연도: '2025' },
    { title: '가짜C대', 구분: '대학', 설립: '사립', 재학생충원율: { 값: 60, 전국평균: 111.4, 차이: -51.4 }, 공시연도: '2025' },
    { title: '가짜신학대', 구분: '대학', 설립: '사립', 재학생충원율: { 값: 15, 전국평균: 111.4, 차이: -96.4 }, 공시연도: '2025' },
    { title: '가짜특수대', 구분: '전문대학', 설립: '사립', 재학생충원율: { 값: 250, 전국평균: 111.4, 차이: 138.6 }, 공시연도: '2025' },
    { title: '값없는대', 구분: '대학', 설립: '사립', 공시연도: '2025' },
  ];

  const 결과 = 정리(가짜);
  본다('① 값있는 곳이 5곳이다(값없는대 제외)', 결과.전체.곳수 === 5);
  본다('② 못잰곳이 1곳으로 잡힌다(0으로 안 덮는다)', 결과.전체.못잰곳 === 1);
  본다('③ 정원미달(100% 미만)이 3곳이다(95·60·15)', 결과.정원미달.곳수 === 3);
  본다('④ 30% 미만 특수학교를 걸렀다', 결과.매우낮은곳.length === 1 && 결과.매우낮은곳[0].학교 === '가짜신학대');
  본다('⑤ 200% 초과 특수학교를 걸렀다', 결과.매우높은곳.length === 1 && 결과.매우높은곳[0].학교 === '가짜특수대');
  본다('⑥ 구간 합이 값있는 곳 수와 같다', Object.values(결과.구간).reduce((a, b) => a + b, 0) === 5);
  본다('⑦ 정의 필드가 있다(check-100y-basis 대응)', typeof 결과.정의.재학생충원율 === 'string' && 결과.정의.재학생충원율.length > 0);
  본다('⑧ 출처.이용허락범위가 중첩돼 있다', 결과.출처.이용허락범위 === '제한 없음');
  본다('⑨ 대조 필드가 있다', typeof 결과.대조 === 'string' && 결과.대조.length > 0);
  본다('⑩ 덮는범위가 배열이다', Array.isArray(결과.덮는범위) && 결과.덮는범위.length > 0);
  본다('⑪ 순위·등수 낱말을 안 쓴다', !JSON.stringify(결과).match(/순위|등수|랭킹|몇 위|꼴찌|1위/));

  console.log('\n실제 원자료로도 돌려 본다…');
  const 진짜자료 = JSON.parse(fs.readFileSync(원본길, 'utf8'));
  const 진짜결과 = 정리(진짜자료);
  console.log(`전체 ${진짜결과.전체.곳수}곳(못잰 ${진짜결과.전체.못잰곳}곳) · 정원미달 ${진짜결과.정원미달.곳수}곳(${진짜결과.정원미달.몫}%)`);
  process.exit();
}

/* 🔴 여기부터가 «부르면 도는 몸»이다 */
const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'build-100y-university-enrollment-fill.mjs';
if (내가직접불렸나) {
  const 원자료 = JSON.parse(fs.readFileSync(원본길, 'utf8'));
  const 결과 = 정리(원자료);
  fs.writeFileSync(낼길, JSON.stringify(결과, null, 2) + '\n', 'utf8');
  console.log('✅ 썼다 →', 낼길);
  console.log(`전체 ${결과.전체.곳수}곳 · 정원미달 ${결과.정원미달.곳수}곳(${결과.정원미달.몫}%)`);
}
