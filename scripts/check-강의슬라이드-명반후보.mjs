#!/usr/bin/env node
/**
 * check-강의슬라이드-명반후보.mjs — **어느 절에 사주명반을 띄울 수 있나**를 가려 적는다.
 *
 * 🔴 사장님 지시 (2026-10-03, 원문)
 *   「**대부분 예시 사주명반을 넣어. 사주명반이 없으면 내용을 반영하게 이미지를 만들아.**」
 *
 * ⚠ 2026-10-03 16:3x 에 내가 2번에게 「57장 가운데 23장이 명반 후보」라고 말만 하고
 *   **목록을 안 줬다.** 2번이 원고를 다 뒤지고도 못 찾아 되물었다 —
 *   「분류결과(어느 원고파일의 몇 번째 절인지)를 적어두신 파일을 못 찾았습니다」
 *   ⇒ 수를 말했으면 **그 수를 만든 목록도 함께** 내야 한다. 그러려고 이 자를 만든다.
 *   ⛔ 다음부터 「기계로 갈라 놓았다」고 적을 때는 이 자처럼 «다시 돌릴 수 있는 꼴»로 둔다.
 *     한 번 쓰고 버리는 명령줄로 가르면 그 결과는 아무도 다시 못 본다.
 *
 * 무엇을 보고 가르나 — **원고 본문에 사주 글자가 실제로 나오는가**.
 *   천간 열 · 지지 열둘 · 「○○ 일간」·「○월」 같은 자리 이름이 있으면 명반을 띄울 수 있다.
 *   ⛔ 판정하지 않는다. «글자가 나오나»만 센다. 무엇을 채울지는 사람이 원고를 읽고 정한다.
 *
 * 쓰는 법
 *   node scripts/check-강의슬라이드-명반후보.mjs            # 화면에 목록
 *   node scripts/check-강의슬라이드-명반후보.mjs --적는다    # docs/ 에 표로 적는다
 *   node scripts/check-강의슬라이드-명반후보.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
const 뿌리 = path.resolve(여기, '..');
export const 원고방 = path.resolve(뿌리, '..', 'klifemap', 'docs', '교재');
export const 낼길 = path.join(뿌리, 'docs', '셀프사주2-명반후보-절목록.md');

/* ── 사주 글자 ─────────────────────────────────────────────────────
   ⛔ 여기 적힌 것은 «글자»이지 판정 규칙이 아니다. 판정은 엔진의 일이다. */
export const 천간 = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
export const 지지 = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];

/**
 * 이 글에 **사주 자리를 가리키는 말**이 있나 — 있으면 명반을 띄울 수 있다.
 *
 * ⚠ 외글자(「신」·「사」)는 보통 낱말과 겹친다. 그래서 외글자만으로는 안 세고
 *   **자리 이름이 붙은 꼴**만 센다 — 「계수 일간」·「진술축미 월」처럼.
 */
export function 사주말찾기(글) {
  const s = String(글 ?? '');
  const 찾음 = new Set();
  /* ① 「○○ 일간」·「○ 일간」 — 일간은 명반의 가운데 기둥이다 */
  for (const m of s.matchAll(/([갑을병정무기경신임계])(수|목|화|토|금)?\s*일간/g)) 찾음.add(`${m[1]}${m[2] ?? ''} 일간`);
  /* ② 「○월」·「○○월」 — 월지는 조후·격국이 서는 자리다 */
  for (const m of s.matchAll(/([자축인묘진사오미신유술해])월(?![요간])/g)) 찾음.add(`${m[1]}월`);
  /* ③ 「진술축미」처럼 지지를 여러 자 이어 적은 꼴 */
  for (const m of s.matchAll(/[자축인묘진사오미신유술해]{3,4}/g)) 찾음.add(m[0]);
  /* ④ 「갑목」·「계수」처럼 천간에 오행을 붙여 적은 꼴 */
  for (const m of s.matchAll(/([갑을병정무기경신임계])(수|목|화|토|금)/g)) 찾음.add(`${m[1]}${m[2]}`);
  /* ⑤ 자리 이름 자체 */
  for (const m of s.matchAll(/(년주|월주|일주|시주|일지|월지|년지|시지|일간|월간|년간|시간)/g)) 찾음.add(m[0]);
  return [...찾음];
}

/** 명반을 띄울 만한가 — 서로 «다른» 사주말이 둘 이상이어야 칸을 채울 수 있다 */
export const 명반문턱 = 2;
export function 명반후보인가(글, 문턱 = 명반문턱) {
  return 사주말찾기(글).length >= 문턱;
}

/**
 * 원고 한 편을 절(`##`)로 가른다.
 * ⚠ 장(`#`)은 겉장이고 절이 슬라이드 한 장의 단위다.
 */
export function 절로가르기(글) {
  const 줄 = String(글 ?? '').replace(/\r/g, '').split('\n');
  const 절 = [];
  let 이번 = null;
  for (const s of 줄) {
    const m = s.match(/^##\s+(.+?)\s*$/);
    if (m && !/^###/.test(s)) {
      if (이번) 절.push(이번);
      이번 = { 제목: m[1].trim(), 줄: [] };
      continue;
    }
    if (이번) 이번.줄.push(s);
  }
  if (이번) 절.push(이번);
  return 절.map((x) => ({ 제목: x.제목, 글: x.줄.join('\n').trim() }));
}

export function 원고읽기(방 = 원고방) {
  if (!fs.existsSync(방)) return [];
  return fs.readdirSync(방)
    .filter((n) => /^2권-원고-\d+-.*\.md$/.test(n))
    .sort()
    .map((n) => ({ 파일: n, 글: fs.readFileSync(path.join(방, n), 'utf8') }));
}

export function 가르기(원고들) {
  const 것 = [];
  for (const { 파일, 글 } of 원고들) {
    for (const [i, 절] of 절로가르기(글).entries()) {
      const 말 = 사주말찾기(절.제목 + '\n' + 절.글);
      것.push({
        파일, 몇째: i + 1, 제목: 절.제목,
        사주말: 말,
        명반후보: 말.length >= 명반문턱,
        글자수: 절.글.replace(/\s/g, '').length,
      });
    }
  }
  return 것;
}

/* ── 자가시험 ─────────────────────────────────────────────────────── */
function 자가시험() {
  let 통과 = 0; const 실패 = [];
  const 본다 = (이름, 참) => { if (참) { 통과 += 1; console.log('✅ ' + 이름); } else { 실패.push(이름); console.log('❌ ' + 이름); } };

  본다('🔴 「계수 일간」을 집는다', 사주말찾기('계수 일간은 약하다').includes('계수 일간'));
  본다('🔴 「진술축미」를 집는다', 사주말찾기('진술축미 월에 태어나면').includes('진술축미'));
  본다('🔴 「갑목」을 집는다', 사주말찾기('갑목이 뿌리를 내린다').includes('갑목'));
  본다('🔴 자리 이름을 집는다', 사주말찾기('월지를 먼저 본다').includes('월지'));
  본다('🔴 「인월」을 집는다', 사주말찾기('인월에 난 사람').includes('인월'));
  /* ⚠ 외글자가 보통 낱말과 겹치는 자리 — 여기서 헛집으면 목록이 엉킨다 */
  본다('⛔ 「신경」을 사주말로 보지 않는다', !사주말찾기('신경을 쓴다').length);
  본다('⛔ 「사월」의 「월요일」은 안 집는다', !사주말찾기('수요일과 월요일').length);
  본다('⛔ 사주말이 없는 글은 명반 후보가 아니다',
    !명반후보인가('운은 10년을 묶어 본다. 그것이 대운이다.'));
  본다('⭐ 사주말 둘이면 명반 후보다', 명반후보인가('계수 일간이 진술축미 월에 났다'));
  본다('⛔ 하나뿐이면 아직 아니다 — 칸을 못 채운다', !명반후보인가('갑목 이야기만 있다'));

  본다('절을 ## 로 가른다', 절로가르기('# 장\n\n## 1. 가\n본문가\n\n## 2. 나\n본문나').length === 2);
  본다('절 제목을 제대로 읽는다', 절로가르기('## 1. 조후에서 볼 것\n글').at(0).제목 === '1. 조후에서 볼 것');
  본다('⛔ ### 은 절이 아니다', 절로가르기('## 1. 가\n### 1-1. 속\n글').length === 1);
  본다('⛔ 빈 글은 빈 목록', 절로가르기('').length === 0 && 절로가르기(null).length === 0);

  const 보기 = [{ 파일: 'ㄱ.md', 글: '## 1. 계수 일간이 진술축미 월에 났다\n글\n\n## 2. 운은 10년이다\n글' }];
  const r = 가르기(보기);
  본다('가르기가 절마다 한 줄을 낸다', r.length === 2);
  본다('🔴 첫 절은 명반 후보다', r[0].명반후보 === true);
  본다('⛔ 둘째 절은 아니다', r[1].명반후보 === false);
  본다('몇째 절인지 적는다', r[0].몇째 === 1 && r[1].몇째 === 2);
  본다('파일 이름을 적는다', r[0].파일 === 'ㄱ.md');

  console.log(`\n${실패.length ? '❌' : '✅'} 자가시험 ${통과}${실패.length ? ' · 실패 ' + 실패.length : ' 통과'}`);
  return !실패.length;
}

const 내가진입점 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가진입점 && process.argv.includes('--자가시험')) {
  process.exit(자가시험() ? 0 : 1);
} else if (내가진입점) {
  const 원고들 = 원고읽기();
  if (!원고들.length) { console.error(`🔴 원고를 못 찾았다 — ${원고방}`); process.exit(1); }
  const 것 = 가르기(원고들);
  const 후보 = 것.filter((x) => x.명반후보);
  console.log(`■ 원고 ${원고들.length}편 · 절 ${것.length}개`);
  console.log(`■ 명반 후보 ${후보.length}개 · 그 밖 ${것.length - 후보.length}개\n`);
  for (const x of 후보) {
    console.log(`  ${x.파일.replace('2권-원고-', '').replace('.md', '')} · ${x.몇째}절`);
    console.log(`     ${x.제목}`);
    console.log(`     사주말 — ${x.사주말.slice(0, 8).join(' · ')}${x.사주말.length > 8 ? ' …' : ''}`);
  }
  if (process.argv.includes('--적는다')) {
    const 줄 = [];
    줄.push('# 셀프사주 2권 강의 — **명반 후보 절 목록**', '');
    줄.push('🔴 사장님 (2026-10-03): 「**대부분 예시 사주명반을 넣어. 사주명반이 없으면 내용을 반영하게 이미지를 만들아.**」', '');
    줄.push(`이 표는 \`scripts/check-강의슬라이드-명반후보.mjs\` 가 짓는다. 손으로 고치지 않는다 — 자를 고친다.`, '');
    줄.push(`원고 ${원고들.length}편 · 절 ${것.length}개 · **명반 후보 ${후보.length}개**`, '');
    줄.push('## 🔴 채워 주실 곳 — 이 절들입니다', '');
    줄.push('절마다 원고를 읽고 **원문이 말한 사주 조건만** 적습니다.', '');
    줄.push('⛔ 원문이 안 말한 글자는 **비워 둡니다.** 지어내면 강의가 틀려집니다.', '');
    줄.push('⬜ 원문에 조건이 아예 없으면 「명반 안 만든다」고 적습니다 — 그것도 결과입니다.', '');
    줄.push('| 원고 | 절 | 제목 | 자가 집은 사주말 | 채울 칸 (사람이 적는다) |');
    줄.push('| --- | --- | --- | --- | --- |');
    for (const x of 후보) {
      줄.push(`| ${x.파일.replace('2권-원고-', '').replace('.md', '')} | ${x.몇째} | ${x.제목} | ${x.사주말.slice(0, 6).join(' · ')} | |`);
    }
    줄.push('', '## ⬜ 명반을 안 띄우는 절 — 짧은 글이나 표로 간다', '');
    줄.push('| 원고 | 절 | 제목 | 글자수 |');
    줄.push('| --- | --- | --- | --- |');
    for (const x of 것.filter((y) => !y.명반후보)) {
      줄.push(`| ${x.파일.replace('2권-원고-', '').replace('.md', '')} | ${x.몇째} | ${x.제목} | ${x.글자수} |`);
    }
    줄.push('');
    fs.writeFileSync(낼길, 줄.join('\n'), 'utf8');
    console.log(`\n✔ 적었다 — ${path.relative(뿌리, 낼길)}`);
  }
}
