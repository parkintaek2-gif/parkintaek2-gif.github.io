/**
 * 이 글에 **사주 자리를 가리키는 말**이 있나 — 있으면 명반을 띄울 수 있다.
 *
 * ⚠ 외글자(「신」·「사」)는 보통 낱말과 겹친다. 그래서 외글자만으로는 안 세고
 *   **자리 이름이 붙은 꼴**만 센다 — 「계수 일간」·「진술축미 월」처럼.
 */
export function 사주말찾기(글) {
  const s = String(글 ?? '');
  const 찾음 = new Set();
  /* ① 「○○ 일간」·「○ 일간」 — 일간은 명반의 가운데 기둥이다 */
  for (const m of s.matchAll(/([갑을병정무기경신임계])(수|목|화|토|금)?\s*일간/g)) 찾음.add(`${m[1]}${m[2] ?? ''} 일간`);
  /* ② 「○월」·「○○월」 — 월지는 조후·격국이 서는 자리다 */
  for (const m of s.matchAll(/([자축인묘진사오미신유술해])월(?![요간])/g)) 찾음.add(`${m[1]}월`);
  /* ③ 「진술축미」처럼 지지를 여러 자 이어 적은 꼴 */
  for (const m of s.matchAll(/[자축인묘진사오미신유술해]{3,4}/g)) 찾음.add(m[0]);
  /* ④ 「갑목」·「계수」처럼 천간에 오행을 붙여 적은 꼴 */
  for (const m of s.matchAll(/([갑을병정무기경신임계])(수|목|화|토|금)/g)) 찾음.add(`${m[1]}${m[2]}`);
  /* ⑤ 자리 이름 자체 */
  for (const m of s.matchAll(/(년주|월주|일주|시주|일지|월지|년지|시지|일간|월간|년간|시간)/g)) 찾음.add(m[0]);
  return [...찾음];
}

/** 명반을 띄울 만한가 — 서로 «다른» 사주말이 둘 이상이어야 칸을 채울 수 있다 */
export const 명반문턱 = 2;
export function 명반후보인가(글, 문턱 = 명반문턱) {
  return 사주말찾기(글).length >= 문턱;
}

/**
 * 원고 한 편을 절(`##`)로 가른다.
 * ⚠ 장(`#`)은 겉장이고 절이 슬라이드 한 장의 단위다.
 */
export function 절로가르기(글) {
  const 줄 = String(글 ?? '').replace(/\r/g, '').split('\n');
  const 절 = [];
  let 이번 = null;
  for (const s of 줄) {
    const m = s.match(/^##\s+(.+?)\s*$/);
    if (m && !/^###/.test(s)) {
      if (이번) 절.push(이번);
      이번 = { 제목: m[1].trim(), 줄: [] };
      continue;
    }
    if (이번) 이번.줄.push(s);
  }
  if (이번) 절.push(이번);
  return 절.map((x) => ({ 제목: x.제목, 글: x.줄.join('\n').trim() }));
}

export function 원고읽기(방 = 원고방) {
  if (!fs.existsSync(방)) return [];
  return fs.readdirSync(방)
    .filter((n) => /^2권-원고-\d+-.*\.md$/.test(n))
    .sort()
    .map((n) => ({ 파일: n, 글: fs.readFileSync(path.join(방, n), 'utf8') }));
}

export function 가르기(원고들) {
  const 것 = [];
  for (const { 파일, 글 } of 원고들) {
    for (const [i, 절] of 절로가르기(글).entries()) {
      const 말 = 사주말찾기(절.제목 + '\n' + 절.글);
      것.push({
        파일, 몇째: i + 1, 제목: 절.제목,
        사주말: 말,
        명반후보: 말.length >= 명반문턱,
        글자수: 절.글.replace(/\s/g, '').length,
      });
    }
  }
  return 것;
}

/* ── 채워진 표를 «생성기가» 읽는다 ──────────────────────────────────
   ⭐ 사람이 채우는 칸과 기계가 읽는 자리를 «한 파일»로 둔다.
     두 파일로 두면 채운 것이 안 옮겨져 또 어긋난다 — 오늘 그 병을 두 번 겪었다. */

/** 「명반 안 만든다」라고 적었나 — 그것도 결과다. 빈칸(아직 안 봄)과 다르다 */
export function 안만든다인가(칸) {
  return /명반\s*안\s*만든다|안\s*만듦|해당\s*없음/.test(String(칸 ?? ''));
}

/**
 * 채울 칸 한 개를 네 기둥으로 읽는다.
 *   「-, 甲/, /酉, -」  →  시주 없음 · 일간 甲 · 월지 酉 · 연주 없음
 *
 * ⛔ 원문이 말하지 않은 자리는 «비운다». 아무 글자로 메우지 않는다 (사장님 2026-10-01).
 * ⚠ 넷이 아니면 안 받는다 — 셋만 적으면 어느 기둥이 빠졌는지 알 수 없다.
 */
export function 채운칸읽기(칸) {
  const s = String(칸 ?? '').trim();
  if (!s || 안만든다인가(s)) return null;
  const 조각 = s.split(/\s*[,，]\s*/).map((x) => x.trim());
  if (조각.length !== 4) return null;
  return 조각;
}

/**
 * 🔴🔴 [2026-10-04 08:5x · 5번] **한 절에 명반이 «여러 벌»인 자리가 많다.**
 *
 *   조후론 여덟 절의 제목이 「진술축미(辰戌丑未) 월에 태어난 을목」이다.
 *   원문이 넷을 «묶어» 말하므로 —
 *   ```
 *   ⛔ 辰 하나를 골라 적는다        → 원문이 안 고른 것을 내가 고른 것이다. 지어낸 것이다
 *   ⛔ 월지를 통째로 비운다          → 원문이 말한 것을 버린 것이다. 일간 한 글자만 남는다
 *   ✅ 辰·戌·丑·未 네 벌을 다 띄운다  → 원문 그대로다
 *   ```
 *   그리고 09-종격처럼 **원전 명반이 두세 벌 나란히 나오는 절**도 같은 꼴이다.
 *
 * ⇒ 벌과 벌은 세미콜론으로 가른다. 한 벌 안은 전과 같이 쉼표 넷이다.
 *   「, 乙/, /辰, ; , 乙/, /戌, 」  →  두 벌
 * ⚠ 한 벌만 적어도 그대로 읽힌다 — 옛 표를 안 깨뜨린다.
 */
export function 채운칸들읽기(칸) {
  const s = String(칸 ?? '').trim();
  if (!s || 안만든다인가(s)) return null;
  const 벌들 = s.split(/\s*[;；]\s*/).map(채운칸읽기).filter(Boolean);
  return 벌들.length ? 벌들 : null;
}

/** 표 한 줄에서 필요한 것만 — 원고·절·제목·채운 칸 */
export function 배정줄읽기(줄) {
  const s = String(줄 ?? '');
  if (!/^\s*\|/.test(s)) return null;
  const 칸 = s.split('|').slice(1, -1).map((x) => x.trim());
  if (칸.length < 5) return null;
  if (/^-+$/.test(칸[0])) return null;                 /* 표 구분줄 */
  if (!/^\d+$/.test(칸[1])) return null;               /* 머리줄 */
  /**
   * 🔴🔴 [2026-10-04 08:5x · 5번] **배정표가 꽉 차 있는데 한 줄도 안 읽히고 있었다.**
   *
   *   사람이 「채울 칸」에 적어 준 것은 **근거를 밝힌 글**이었다 —
   *   「원문에 완전한 명반 3벌이 이미 있음(그대로 쓴다) — ①일간甲·월지酉·천간丁…」
   *   그런데 `채운칸읽기` 는 **쉼표로 갈린 기둥 넷**을 바란다. 그래서 전부 null 이 됐고,
   *   슬라이드의 「볼 것 있는 장」이 25% 에 머물렀다(이마트 69% · 참는 선 50%).
   *
   * ⇒ 칸을 **둘로 가른다.**
   *   ```
   *   채울 칸   사람이 적는 «근거» — 원문 어디에 무엇이 있나. 글로 적는다
   *   기둥      기계가 읽는 «꼴»  — 시주, 일주, 월주, 연주 (각 「천간/지지」, 모르면 빈칸)
   *   ```
   * ⛔ 근거 칸을 없애지 않는다. 그 글이 「이 기둥을 어디서 가져왔나」의 자취다 —
   *   자취 없는 기둥은 지어낸 것과 구별이 안 된다.
   * ⚠ 기둥 칸이 비면 근거 칸을 본다 — 옛 표가 그 꼴로 적혀 있을 수 있다.
   */
  const 기둥칸 = 칸[5] ?? '';
  return {
    원고: 칸[0], 몇째: Number(칸[1]), 제목: 칸[2],
    채운칸: 칸[4] ?? '',
    기둥칸,
    /* 한 벌만 쓰던 자리를 안 깨뜨린다 — 기둥 은 첫 벌, 기둥들 은 전부다 */
    기둥: (채운칸들읽기(기둥칸) ?? 채운칸들읽기(칸[4]))?.[0] ?? null,
    기둥들: 채운칸들읽기(기둥칸) ?? 채운칸들읽기(칸[4]),
    안만든다: 안만든다인가(칸[4]),
  };
}

export function 배정표읽기(글) {
  return String(글 ?? '').split('\n').map(배정줄읽기).filter(Boolean);
}

/** 그 절에 띄울 명반을 찾는다. 없으면 null — ⛔ 지어내지 않는다 */
export function 절의명반(원고, 몇째, 배정 = []) {
  const 짧게 = String(원고 ?? '').replace('2권-원고-', '').replace('.md', '');
  const x = 배정.find((r) => r.원고 === 짧게 && r.몇째 === Number(몇째));
  return x?.기둥 ?? null;
}

/** 그 절에 띄울 명반 «전부». 원문이 여러 벌을 말하면 여러 벌이다 */
