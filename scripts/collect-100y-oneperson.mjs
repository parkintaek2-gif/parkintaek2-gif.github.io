#!/usr/bin/env node
/**
 * collect-100y-oneperson.mjs — **나이대별 1인가구 비중 · 어느 나이대에 가장 몰려 있나**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 사장님(2026-08-22) — 「0~100세 × 다섯 분야」 기획서 1단계 로드맵 2번째, 사회 분야 첫 지면.
 *
 * ── 표 ────────────────────────────────────────────────────────
 *   DT_1PL1502  org 101(국가데이터처)  「성 및 연령별 1인가구 - 시군구」
 *   전국(C1=전국) · 5세 단위 나이칸(C2) · 항목(ITM) 1인가구/남자/여자
 *
 * ── ⭐ 실측으로 찾은 것 ──────────────────────────────────────────
 * ⛔ 처음엔 "청년·노년 두 봉우리(25~29세, 65~69세)"일 거라 짐작했다 — 5세 단위 원자료에서는
 *   맞았지만, 사이트 전체가 쓰는 열 살 단위로 묶으니 **다른 그림**이 나왔다. 40대가 가장
 *   적고(12.1%), 그 앞(30대 17.5%)·그 뒤(70세 이상 20.7%, 전체 최고)가 높다 — "40대가
 *   움푹 꺼진 다음 나이 들수록 다시 는다"가 정직한 설명이다. 짐작을 자료로 고쳤다.
 * ⭐ 성비도 나이대마다 뒤집힌다 — 20~50대는 남자가 많고, 60대부터는 여자가 많다.
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · "1인가구"는 가구 형태다 — 왜 혼자 사는지(미혼·이혼·사별·독립)는 이 표가 못 가른다
 * · 전국 총조사 집계다. 표본조사가 아니라 등록에 가깝지만, 신고 시점 차이는 있을 수 있다
 * · 몇 %가 "그 나이대 인구 중" 혼자 사는지가 아니라, "1인가구 전체 중" 몇 %가 그 나이대인지다
 *   (분모가 다르다 — 인구 대비 비율은 별도 인구총조사와 맞대야 하는데, 이번엔 안 했다)
 *
 * 쓰는 법  node scripts/collect-100y-oneperson.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '101';
export const TBL = 'DT_1PL1502';

/** ⚠ KOSIS 원 나이칸은 5세 단위다. 20세미만은 따로 두고(뒤섞으면 뜻이 흐려진다),
 *   나머지는 열 살 단위로 묶는다 — 사이트 전체 나이칸 표기와 맞춘다 */
export const 나이칸들 = ['20세 미만', '20대', '30대', '40대', '50대', '60대', '70세 이상'];
export const 원칸모음 = {
  '20세 미만': ['20세미만'],
  '20대': ['20~24세', '25~29세'],
  '30대': ['30~34세', '35~39세'],
  '40대': ['40~44세', '45~49세'],
  '50대': ['50~54세', '55~59세'],
  '60대': ['60~64세', '65~69세'],
  '70세 이상': ['70~74세', '75~79세', '80~84', '85세이상'],
};

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/** ⭐ 묶은 칸들의 값을 더한다. 하나라도 못 재면(null) 그 칸 전체를 못 잰 것으로 둔다 */
export function 더하기(원값들, 묶을칸들) {
  const 값들 = 묶을칸들.map((c) => 원값들[c]);
  if (값들.some((v) => v == null)) return null;
  return 값들.reduce((a, b) => a + b, 0);
}

/** ⭐ 봉우리(가장 큰 칸)와 골(가장 작은 칸, 20세미만 제외)을 찾는다 — 두 봉우리인지 살핀다 */
export function 봉우리들(칸들, 키) {
  const 후보 = 칸들.filter((r) => r.칸 !== '20세 미만' && r[키] != null);
  if (!후보.length) return null;
  const 정렬 = [...후보].sort((a, b) => b[키] - a[키]);
  return { 최고: 정렬[0], 둘째: 정렬[1] ?? null, 최저: 정렬.at(-1) };
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② 콤마 섞인 수를 읽는다', 수로('1,234') === 1234);
  본다('③ 원칸을 더한다', 더하기({ a: 3, b: 4 }, ['a', 'b']) === 7);
  본다('④ 하나라도 없으면 못 잰다(null)', 더하기({ a: 3 }, ['a', 'b']) === null);
  본다('⑤ 20대~70세이상 여섯 칸이 20세미만 뺀 나머지다', 나이칸들.length === 7 && 나이칸들[0] === '20세 미만');
  const 표본 = [
    { 칸: '20세 미만', 값: 5 }, { 칸: '20대', 값: 88 }, { 칸: '30대', 값: 40 },
    { 칸: '40대', 값: 30 }, { 칸: '50대', 값: 35 }, { 칸: '60대', 값: 55 }, { 칸: '70세 이상', 값: 45 },
  ];
  const 봉 = 봉우리들(표본, '값');
  본다('⑥ 20세 미만은 봉우리 후보에서 뺀다', 봉.최고.칸 === '20대');
  본다('⑦ 둘째 봉우리를 찾는다', 봉.둘째.칸 === '60대');
  본다('⑧ 최저칸을 찾는다', 봉.최저.칸 === '40대');
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-oneperson.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  const j = await (await fetch(
    `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
    + `&format=json&jsonVD=Y&orgId=${ORG}&tblId=${TBL}&itmId=ALL&objL1=ALL&objL2=ALL&prdSe=Y&newEstPrdCnt=2`)).json();
  if (!Array.isArray(j)) throw new Error(`${TBL}: ${JSON.stringify(j).slice(0, 200)}`);

  const 최신 = [...new Set(j.map((x) => x.PRD_DE))].sort().at(-1);
  const 값 = (칸, 항) => 수로(j.find((x) => x.PRD_DE === 최신 && x.C1_NM === '전국' && x.C2_NM === 칸 && x.ITM_NM === 항)?.DT);
  const 합계 = 값('합계', '1인가구');

  const 나이별 = 나이칸들.map((칸) => {
    const 묶을칸 = 원칸모음[칸];
    const 전체값 = {}; const 남값 = {}; const 여값 = {};
    for (const 원칸 of 묶을칸) { 전체값[원칸] = 값(원칸, '1인가구'); 남값[원칸] = 값(원칸, '남자'); 여값[원칸] = 값(원칸, '여자'); }
    const 가구수 = 더하기(전체값, 묶을칸);
    const 남자 = 더하기(남값, 묶을칸);
    const 여자 = 더하기(여값, 묶을칸);
    return { 칸, 가구수, 남자, 여자, 비중: 가구수 != null && 합계 ? Number(((가구수 / 합계) * 100).toFixed(1)) : null };
  });

  /* 🔴 자가대조 — 일곱 칸을 더하면 전국 1인가구 합계와 같아야 한다 */
  const 칸합 = 나이별.reduce((a, r) => (r.가구수 != null ? a + r.가구수 : a), 0);
  const 자가대조_전체 = { 칸합, 합계, 차이: Math.abs(칸합 - 합계), 맞나: Math.abs(칸합 - 합계) <= 합계 * 0.001 };
  /* 🔴 자가대조 — 칸마다 남자+여자 = 가구수 */
  const 어긋난성비 = 나이별.filter((r) => r.남자 != null && r.여자 != null && r.가구수 != null && Math.abs(r.남자 + r.여자 - r.가구수) > 1);
  const 자가대조 = {
    '나이 일곱 칸 합 = 전국 합계': 자가대조_전체,
    '칸마다 남자+여자 = 가구수': { 어긋난칸수: 어긋난성비.length, 맞나: 어긋난성비.length === 0 },
  };

  const 봉 = 봉우리들(나이별, '가구수');
  const 최저찾기 = 나이별.filter((r) => r.칸 !== '20세 미만').reduce((a, b) => (b.가구수 < a.가구수 ? b : a));
  const 남녀뒤집힘 = 나이칸들
    .filter((칸) => 칸 !== '20세 미만')
    .map((칸) => 나이별.find((r) => r.칸 === 칸))
    .map((r) => ({ 칸: r.칸, 많은쪽: r.남자 > r.여자 ? '남자' : '여자' }));

  const 낸다 = {
    무엇: '나이대별 1인가구 비중 — 어느 나이대에 가장 몰려 있나',
    만든날: new Date().toISOString().slice(0, 10),
    최신,
    출처: {
      기관: '국가데이터처(통계청)', 표: '성 및 연령별 1인가구 - 시군구(전국)',
      창구: 'KOSIS', orgId: ORG, tblId: TBL,
    },
    합계, 나이별,
    '⭐ 40대가 움푹 꺼진다': {
      최고칸: 봉.최고, 최저칸: 최저찾기,
      뜻: '20세 미만을 뺀 여섯 칸 중, 1인가구가 가장 많은 칸(최고칸)과 가장 적은 칸(최저칸)',
    },
    남녀뒤집힘,
    '⚠ 이 자료가 못 가르는 것': [
      '"1인가구"는 가구 형태입니다. 왜 혼자 사는지(미혼·이혼·사별·독립)는 이 표로 못 가릅니다.',
      '"1인가구 전체 중 몇 %가 그 나이대인가"입니다 — "그 나이대 인구 중 몇 %가 혼자 사는가"와는 분모가 다릅니다.',
    ],
    자가대조,
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/oneperson.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
  console.log(`   ${최신}년 · 1인가구 나이별: ${나이별.map((r) => `${r.칸} ${r.가구수}(${r.비중}%)`).join(' · ')}`);
  console.log(`   두 봉우리: ${봉.최고.칸}(${봉.최고.가구수}) · ${봉.둘째.칸}(${봉.둘째.가구수})`);
  console.log(`   자가대조: 칸합-합계 차이 ${자가대조_전체.차이} · 성비 어긋난 칸 ${어긋난성비.length}개`);
}
