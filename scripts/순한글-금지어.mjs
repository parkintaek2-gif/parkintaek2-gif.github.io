/** 한 글에서 금지어를 찾는다 → [{말, 대신, 갈래, 수, 보기}] */
export function 재기(글, { 주석도본다 = false } = {}) {
  let g = String(글 ?? '');
  if (!주석도본다) {
    const 줄나눔 = String.fromCharCode(10);
    g = g.split(줄나눔).filter((l) => !/^\s*(\/\/|\*|\/\*|#)/.test(l)).join(줄나눔);
  }
  const 걸린것 = [];
  for (const x of 금지어) {
    if (!g.includes(x.말)) continue;
    /* 🔴 [2026-10-22] 낱말 «안»에 우연히 든 것까지 잡고 있었다.
       「따지면」의 '지면' · 「무너지면서」의 '지면' 이 걸려서, 고칠 것이 없는데 빨간불이 떴다.
       ⛔ 헛빨간불이 쌓이면 사람이 이 자를 안 보게 된다 — 그러면 진짜 하나도 같이 묻힌다.
       ⇒ 금지어 «앞»에 한글이 붙어 있으면 다른 낱말의 일부로 보고 세지 않는다.
       ⚠ 뒤는 안 본다 — 「까닭을」·「짚은」처럼 조사·어미가 붙는 것이 정상이기 때문이다. */
    const 자리 = [];
    let i = -1;
    while ((i = g.indexOf(x.말, i + 1)) !== -1) {
      const 앞 = i > 0 ? g[i - 1] : ' ';
      if (/[가-힣]/.test(앞)) continue;
      자리.push(i);
    }
    if (!자리.length) continue;
    걸린것.push({ ...x, 수: 자리.length,
      보기: g.slice(Math.max(0, 자리[0] - 36), 자리[0] + 36).replace(/\s+/g, ' ') });
  }
  return 걸린것;
}

