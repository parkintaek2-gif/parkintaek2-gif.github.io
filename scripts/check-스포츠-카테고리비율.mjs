#!/usr/bin/env node
/**
 * check-스포츠-카테고리비율.mjs — **스포츠가 전체 기사의 5%를 채우고 있나.**
 *
 * ── 🔴 왜 (2026-09-29 · 5번) ─────────────────────────────────────────
 * 사장님 — 「중부매일이 **가장 문제가 있는게 정치, 경제, 사회, 문화, 스포츠의
 * 전체기사 대비 비율 5% 이상**을 채우는 거야. 여기에 **스포츠 심층보도를 딱히 하는
 * 담당자가 없어서 내가 신경쓰는거야**」
 *
 * ⭐ 사장님이 «직접 신경 쓰고 계신» 일이다. 그 몫을 기계가 대신 세게 한다.
 *
 * 규정 원문 — 제8조 제4항 다)호 (14쪽)
 * ```
 * 다) 기준 : 월별로 각각 제출한 전체 기사의 수가 <표.6>의 월 최소 기사 생산량과
 *            본 호 (ㄱ),(ㄴ),(ㄷ)목을 모두 충족
 *   (ㄱ) '제휴 심사' 신청 시 선택한 '카테고리'마다 **전체 기사 수의 최소 5% 이상**
 * 라) 배점 : 충족하면 오(5)점, 미충족하면 영(0)점
 * <표.6> 일간지 · 카테고리 5개 이상 → 월 최소 400건
 * ```
 *
 * 🔴 이 항목은 «전부 아니면 전무»다. 카테고리 하나라도 5%에 못 미치면 5점이 통째로 0이다.
 *   그래서 사장님이 「가장 문제」라고 하셨다.
 *
 * ⛔ 5%는 «절대 건수»가 아니라 «전체 대비 비율»이다 — 전체 기사가 늘면 필요 편수도 는다.
 *   400건일 때 20건이면 되지만, 1,000건이면 50건이 있어야 한다.
 *
 * ⚠ **중부매일 전체 기사 수는 우리가 모른다.** 그래서 이 자는 «두 가지»를 함께 낸다 —
 *   ① 우리가 실제로 낸 편수 (자국으로 센다 — 이건 확실하다)
 *   ② 전체 기사 수를 넣으면 나오는 필요 편수 (`--전체 1200`)
 *   ⛔ 모르는 수를 짐작해 「채웠다」고 적지 않는다.
 *
 * 쓰는 법
 *   node scripts/check-스포츠-카테고리비율.mjs
 *   node scripts/check-스포츠-카테고리비율.mjs --달 2026-09 --전체 1200
 *   node scripts/check-스포츠-카테고리비율.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const 자국방 = path.join(뿌리, 'docs', '고정업무-마커', '중부매일-스포츠-보낸자국');

/** 규정 <표.6> — 일간지·카테고리 5개 이상 */
export const 월최소전체 = 400;
/** 제8조 제4항 다)호 (ㄱ) */
export const 카테고리최소비율 = 0.05;

/**
 * 그 달에 우리가 보낸 스포츠 기사 편수를 센다.
 * ⚠ 한 자국 파일에 «여러 건»이 이어 붙을 수 있다(한 회차에 둘 나온 날). 줄로 센다.
 */
export function 보낸편수(글들) {
  let 수 = 0;
  for (const 글 of 글들 ?? []) {
    for (const 줄 of String(글 ?? '').split(/\r?\n/)) {
      if (/^\[스포츠/.test(줄.trim())) 수 += 1;
    }
  }
  return 수;
}

/**
 * 판정 — ⛔ 「모자란다」와 「못 쟀다」를 가른다.
 * @param {number} 우리편수  우리가 낸 스포츠 기사 수
 * @param {number|null} 전체기사수  중부매일 «전체» 기사 수. 모르면 null
 */
export function 판정(우리편수, 전체기사수 = null) {
  const 낸것 = { 우리편수, 전체기사수 };
  if (전체기사수 === null || transitNaN(전체기사수)) {
    /* 전체를 모르면 «규정 하한(400건)»으로만 말할 수 있다. 그것도 «최소»일 뿐이다 */
    const 하한필요 = Math.ceil(월최소전체 * 카테고리최소비율);
    return {
      ...낸것,
      갈래: '못쟀다',
      필요편수: null,
      말: `전체 기사 수를 모른다 — 전체가 규정 하한(${월최소전체}건)이면 스포츠는 ${하한필요}건이 필요하다. `
        + `전체가 늘면 필요 편수도 는다. --전체 <수> 로 알려 주면 정확히 잰다`,
      하한필요,
    };
  }
  const 필요편수 = Math.ceil(전체기사수 * 카테고리최소비율);
  const 찼나 = 우리편수 >= 필요편수;
  return {
    ...낸것,
    갈래: 찼나 ? '찼다' : '모자란다',
    필요편수,
    모자란수: 찼나 ? 0 : 필요편수 - 우리편수,
    비율: 전체기사수 ? 우리편수 / 전체기사수 : null,
    말: 찼나
      ? `${우리편수}건 / 필요 ${필요편수}건 (전체 ${전체기사수}건의 5%) — 찼다`
      : `${우리편수}건 / 필요 ${필요편수}건 — ${필요편수 - 우리편수}건 모자란다`,
  };
}

/** NaN 을 따로 본다 — 0 은 「모른다」가 아니라 「없다」다 */
function transitNaN(n) { return typeof n !== 'number' || Number.isNaN(n); }

/** 인자 — ⛔ 값이 없을 때 argv[0] 를 집지 않는다 */
export function 인자(이름, argv = process.argv) {
  const i = argv.indexOf(`--${이름}`);
  return i >= 0 && i + 1 < argv.length ? argv[i + 1] : null;
}

/* ── 자가시험 ─────────────────────────────────────────────────────── */
export function 자가시험() {
  const 것 = [];
  const 본다 = (이름, 참, 덧 = '') => 것.push({ 이름, 참: !!참, 덧 });

  본다('한 파일에 여러 건이 있어도 다 센다',
    보낸편수(['때\n[스포츠] 가\n받는곳 a\n\n때\n[스포츠] 나\n받는곳 a']) === 2);
  본다('⛔ 기사 줄이 아닌 것은 안 센다', 보낸편수(['받는곳 a\n소재 가 나']) === 0);
  본다('⛔ 빈 것에 안 터진다', 보낸편수(null) === 0 && 보낸편수([null]) === 0);

  본다('🔴 전체를 모르면 «못 쟀다»지 «찼다»가 아니다', 판정(30, null).갈래 === '못쟀다');
  본다('전체를 모를 때도 규정 하한은 알려 준다', 판정(30, null).하한필요 === 20);
  본다('🔴 전체 1,000건이면 50건이 필요하다', 판정(60, 1000).필요편수 === 50);
  본다('그때 60건이면 찼다', 판정(60, 1000).갈래 === '찼다');
  본다('🔴 40건이면 10건 모자란다', 판정(40, 1000).모자란수 === 10);
  본다('⛔ 전체가 늘면 필요 편수도 는다 — 절대 건수가 아니다',
    판정(30, 400).필요편수 === 20 && 판정(30, 1200).필요편수 === 60);
  본다('⛔ 0건은 «모른다»가 아니라 «없다»다', 판정(0, 400).갈래 === '모자란다');
  본다('경계 — 딱 맞으면 찼다', 판정(20, 400).갈래 === '찼다');
  본다('🔴 값 없는 인자에 노드 경로를 집지 않는다', 인자('전체', ['node', 'x', '--전체']) === null);

  const 빨강 = 것.filter((x) => !x.참);
  console.log(`■ check-스포츠-카테고리비율 자가시험 ${것.length - 빨강.length}/${것.length}`);
  for (const x of 것) console.log(`  ${x.참 ? '✅' : '🔴'} ${x.이름}${x.덧 ? `  (${x.덧})` : ''}`);
  return 빨강.length === 0;
}

/* ── 진입점 ───────────────────────────────────────────────────────── */
const 내가진입점 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가진입점) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);

  const 이번달 = new Date().toLocaleDateString('sv-SE').slice(0, 7);   /* KST. toISOString 안 쓴다 */
  const 달 = 인자('달') || 이번달;
  const 전체값 = 인자('전체');
  const 전체기사수 = 전체값 === null ? null : Number(전체값);

  let 글들 = [];
  try {
    글들 = fs.readdirSync(자국방)
      .filter((n) => n.startsWith(달) && /_\d{1,2}시\.txt$/.test(n))
      .map((n) => fs.readFileSync(path.join(자국방, n), 'utf8'));
  } catch { /* 폴더가 없으면 0건이다 */ }

  const 우리편수 = 보낸편수(글들);
  const p = 판정(우리편수, 전체기사수);

  console.log(`■ ${달} 스포츠 카테고리 비율 — 규정 제8조 제4항 다)호 (ㄱ)`);
  console.log(`   「'카테고리'마다 전체 기사 수의 최소 5% 이상」 · 충족 5점 / 미충족 0점\n`);
  console.log(`   우리가 보낸 스포츠 기사   ${우리편수}건 (자국 ${글들.length}일치)`);
  const 딱지 = { 찼다: '✅', 모자란다: '🔴', 못쟀다: '⬜' }[p.갈래];
  console.log(`   ${딱지} ${p.말}\n`);

  if (p.갈래 === '못쟀다') {
    console.log('   ⚠ 중부매일 «전체» 기사 수를 우리가 모른다. 그것을 알아야 5%가 정해진다.');
    console.log('     ⛔ 모르는 수를 짐작해 「채웠다」고 적지 않는다.');
  }
  console.log('   🔴 이 항목은 «전부 아니면 전무»다 — 다섯 카테고리 가운데 하나라도');
  console.log('      5%에 못 미치면 C항목 5점이 통째로 0이 된다.');
  process.exit(p.갈래 === '모자란다' ? 1 : 0);
}
