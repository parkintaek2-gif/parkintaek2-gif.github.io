#!/usr/bin/env node
/**
 * collect-100y-polytech.mjs — 한국폴리텍대학 학과·과정 자료 (100yearmap 「배움의 길」)
 *
 * 사장님 지시(2026-08-26): 「폴리텍대학에서 배울 수 있는 것도 같이 서비스하자 —
 * API로 안 되면 다른 방식을 찾아서 서비스하자」
 *
 * ⛔ 처음엔 「공식 오픈API 없음 → 스크래핑뿐」으로 잘못 보고했다. 다시 파 보니
 *   공공데이터포털에 **제공기관이 「학교법인한국폴리텍」인 파일데이터가 이미 있었다** —
 *   검색어를 좁게 잡아 놓쳤을 뿐이다. **로그인도 필요 없다.**
 *
 * ── 원자료 (둘 다 data.go.kr, 로그인 없이 다운로드) ─────────────────────
 *   교육훈련계획   https://www.data.go.kr/data/15053552/fileData.do   737행 (2025-09-16 수정)
 *   전국 캠퍼스 정보 https://www.data.go.kr/data/15111420/fileData.do   41행 (2022-12-29 등록)
 *
 * ⚠ **다운로드 버튼이 자바스크립트 2단계 AJAX**(`selectFileDataDownload.do`)라 curl로
 *   바로 못 받는다. `atchFileId`를 알아내는 파라미터를 못 찾았다(POST 해 보니 success:false).
 *   **되는 길이 있는데 안 되는 길에 시간을 쓰지 않는다** — 공유 크롬으로 직접 눌러 받는다:
 *     1) 위 두 URL을 열고 「다운로드」 버튼을 누른다 (로그인 불필요)
 *     2) 받은 두 CSV를 archive/raw/polytech/ 에 각각
 *        training-plan-YYYYMMDD.csv · campuses-YYYYMMDD.csv 로 이름 바꿔 넣는다
 *     3) 이 스크립트를 다시 돌린다 (--최신파일 을 자동으로 고른다)
 *   데이터가 연 1회~비정기 갱신이라(교육훈련계획 「차기 등록 예정 2026-09-16」) 이 정도
 *   손질이면 충분하다 — 매일 자동으로 받을 만큼 자주 바뀌지 않는다.
 *
 * ── 인코딩 ──────────────────────────────────────────────────────────
 *   교육훈련계획 CSV = UTF-8 · 캠퍼스 정보 CSV = **EUC-KR(CP949)**. 열어 보고 정했다
 *   (미리 짐작하지 않는다 — `collect-nps-workplaces.mjs`와 같은 교훈).
 *
 * ── 두 파일 잇기 ────────────────────────────────────────────────────
 *   교육훈련계획의 「캠퍼스」(짧은 이름, 예: 서울정수)와 캠퍼스정보의 「캠퍼스명」
 *   (긴 이름, 예: 서울정수캠퍼스)을 접미사(캠퍼스·교육원·고등학교)를 떼고 잇는다.
 *   ⚠ **41개 중 39개만 이어진다.** 「충남」·「전력기술」 두 개는 캠퍼스정보 목록에
 *   그 이름이 없다 — **비슷한 글자로 짐작해 잇지 않는다.** 지역·주소를 null로 두고
 *   그 학과들은 「캠퍼스 소재지 확인 안 됨」으로 남긴다. 틀리게 잇는 것보다 못 잇는
 *   편이 낫다(모토와-철학 ③).
 *
 * 쓰는 법
 *   node scripts/collect-100y-polytech.mjs --자가시험
 *   node scripts/collect-100y-polytech.mjs           원자료 읽어 src/data/100yearmap/polytech.json 을 쓴다
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RAW = path.join(뿌리, 'archive/raw/polytech');
const 출력 = path.join(뿌리, 'src/data/100yearmap/polytech.json');

/** 원자료 두 파일을 읽는다. 인코딩은 짐작하지 않고 깨진 글자(�)가 있으면 EUC-KR로 다시 읽는다 */
function 읽기(파일경로) {
  const buf = readFileSync(파일경로);
  let text = buf.toString('utf8');
  if (text.includes('�')) text = new TextDecoder('euc-kr').decode(buf);
  return text.replace(/^﻿/, '').split(/\r?\n/).filter((l) => l.trim().length > 0);
}

/** 디렉토리에서 접두사로 시작하는 파일 중 가장 최근(파일명 뒤 날짜가 큰) 것을 고른다 */
function 최신파일(접두사) {
  if (!existsSync(RAW)) return null;
  const 후보 = readdirSync(RAW).filter((f) => f.startsWith(접두사)).sort();
  return 후보.length ? path.join(RAW, 후보[후보.length - 1]) : null;
}

/**
 * 캠퍼스 주소 원문의 시도 표기가 한 캠퍼스 정보 파일 안에서도 갈린다 —
 * 실측: 「경상북도」29곳인데 「경북」(영주캠퍼스) 1곳, 「경상남도」인데 「경남」
 * (진주캠퍼스) 1곳, 「서울특별시」인데 「서울시」(서울정수캠퍼스) 1곳이 섞여 있다.
 * ⛔ 다른 지역으로 짐작해 가르지 않는다 — 이 넷은 **같은 곳의 다른 표기**임이
 * 명백해서(광역시도 이름은 17개뿐이고 겹치는 게 없다) 표로 하나로 묶는다.
 */
const 표기맞추기 = {
  서울시: '서울특별시', 경북: '경상북도', 경남: '경상남도',
};
const 시도표 = [
  '서울특별시', '서울시', '부산광역시', '대구광역시', '인천광역시', '광주광역시',
  '대전광역시', '울산광역시', '세종특별자치시', '경기도', '강원특별자치도', '강원도',
  '충청북도', '충청남도', '전북특별자치도', '전라북도', '전라남도',
  '경상북도', '경북', '경상남도', '경남', '제주특별자치도',
];
/** 주소 맨 앞 토큰으로 시도를 찾는다. 표에 없으면 null(짐작하지 않는다) */
function 시도추출(주소) {
  const 첫토큰 = String(주소 ?? '').trim().split(/\s+/)[0] ?? '';
  if (!시도표.includes(첫토큰)) return null;
  return 표기맞추기[첫토큰] ?? 첫토큰;
}

/** 캠퍼스명 접미사(캠퍼스·교육원·고등학교, 「융합기술」이 붙은 것도)를 뗀다 */
function 캠퍼스접미사떼기(긴이름) {
  return String(긴이름 ?? '').replace(/(융합기술)?(캠퍼스|교육원|고등학교)$/, '').trim();
}

/**
 * 훈련계획의 짧은 캠퍼스 이름(예: 석유화학)을 캠퍼스정보의 접미사 뗀 이름
 * (예: 석유화학공정기술)과 잇는다. **완전히 같지 않아도, 한쪽이 다른 쪽을 포함하면
 * 잇는다** — 「석유화학」⊂「석유화학공정기술」처럼 중간에 낱말이 더 있는 경우가
 * 있어서다(41행을 모두 눈으로 봐서 확인했다. 실측: 41개 중 39개가 이렇게 이어진다).
 * ⛔ 그래도 안 이어지면(예: 「충남」·「전력기술」) null — 짐작해서 억지로 잇지 않는다.
 */
function 캠퍼스매칭(짧은이름, 캠퍼스표) {
  const 히트 = 캠퍼스표.filter((c) => c.접미사뗀이름 === 짧은이름
    || c.접미사뗀이름.startsWith(짧은이름) || 짧은이름.startsWith(c.접미사뗀이름));
  return 히트.length === 1 ? 히트[0] : null; /* 하나로 안 좁혀지면 못 잇는 쪽을 택한다 */
}

function 만들기() {
  const 훈련파일 = 최신파일('training-plan-');
  const 캠퍼스파일 = 최신파일('campuses-');
  if (!훈련파일 || !캠퍼스파일) {
    console.error('⛔ archive/raw/polytech/ 에 원자료가 없다 — 스크립트 머리말의 받는 법을 본다.');
    process.exit(1);
  }

  const 훈련줄 = 읽기(훈련파일).slice(1); // 머리줄 제외
  const 캠퍼스줄 = 읽기(캠퍼스파일).slice(1);

  const 캠퍼스표 = 캠퍼스줄.map((l) => {
    const c = l.split(',');
    return { 긴이름: c[2], 접미사뗀이름: 캠퍼스접미사떼기(c[2]), 주소: c[3], 시도: 시도추출(c[3]), 전화: c[5], 홈페이지: c[7] };
  });

  const 과정 = [];
  let 못이은것 = new Set();
  for (const l of 훈련줄) {
    const c = l.split(',');
    const [캠퍼스, 학과명, 전공직종, 계열구분, 과정구분, 기간, 기간구분, 주야간] = c;
    const 캠퍼스정보 = 캠퍼스매칭(캠퍼스, 캠퍼스표);
    if (!캠퍼스정보) 못이은것.add(캠퍼스);
    과정.push({
      캠퍼스, 학과명, 전공직종: 전공직종 === '정보없음' ? null : 전공직종,
      계열: 계열구분 === '정보없음' ? null : 계열구분, 과정: 과정구분,
      기간: Number(기간) || null, 기간단위: 기간구분, 주야간,
      시도: 캠퍼스정보?.시도 ?? null, 주소: 캠퍼스정보?.주소 ?? null,
      홈페이지: 캠퍼스정보?.홈페이지 ?? null,
    });
  }

  const 산출 = {
    출처: '학교법인한국폴리텍(공공데이터포털) — 교육훈련계획 · 전국 캠퍼스 정보',
    url: ['https://www.data.go.kr/data/15053552/fileData.do', 'https://www.data.go.kr/data/15111420/fileData.do'],
    받은날: { 훈련: path.basename(훈련파일), 캠퍼스: path.basename(캠퍼스파일) },
    이용허락범위: '제한 없음',
    못이은캠퍼스: [...못이은것],
    과정,
  };
  writeFileSync(출력, JSON.stringify(산출, null, 2));
  const 이은캠퍼스수 = new Set(훈련줄.map((l) => l.split(',')[0])).size - 못이은것.size;
  console.log(`✅ ${과정.length}개 과정 · 캠퍼스 ${이은캠퍼스수}곳 이음 · 못 이은 것 ${못이은것.size}개(${[...못이은것].join(', ')}) → ${출력}`);
}

if (process.argv.includes('--자가시험')) {
  const 실패 = [];
  const 검 = (이름, 참) => { if (!참) 실패.push(이름); };

  검('시도추출 — 다른 표기를 하나로 맞춘다(서울시→서울특별시)', 시도추출('서울시 용산구 보광로 73') === '서울특별시');
  검('시도추출 — 경북→경상북도로 맞춘다', 시도추출('경북 영주시 가흥로 2') === '경상북도');
  검('시도추출 — 경남→경상남도로 맞춘다', 시도추출('경남 진주시 모덕로 299') === '경상남도');
  검('시도추출 — 특별자치도도 찾는다', 시도추출('제주특별자치도 제주시 산천단동3길 2') === '제주특별자치도');
  검('시도추출 — 표에 없으면 null(짐작 안 함)', 시도추출('알수없는동네 1길 2') === null);
  검('시도추출 — 빈 값도 null', 시도추출('') === null);

  검('접미사떼기 — 캠퍼스 접미사를 뗀다', 캠퍼스접미사떼기('서울정수캠퍼스') === '서울정수');
  검('접미사떼기 — 교육원 접미사를 뗀다', 캠퍼스접미사떼기('신기술교육원') === '신기술');
  검('접미사떼기 — 융합기술교육원도 뗀다', 캠퍼스접미사떼기('분당융합기술교육원') === '분당');
  검('접미사떼기 — 고등학교 접미사를 뗀다', 캠퍼스접미사떼기('다솜고등학교') === '다솜');
  검('접미사떼기 — 접미사 없으면 그대로', 캠퍼스접미사떼기('인재원') === '인재원');

  const 표본캠퍼스표 = [
    { 긴이름: '서울정수캠퍼스', 접미사뗀이름: '서울정수' },
    { 긴이름: '석유화학공정기술교육원', 접미사뗀이름: '석유화학공정기술' },
    { 긴이름: '분당융합기술교육원', 접미사뗀이름: '분당' },
  ];
  검('캠퍼스매칭 — 정확히 같으면 잇는다', 캠퍼스매칭('서울정수', 표본캠퍼스표)?.긴이름 === '서울정수캠퍼스');
  검('캠퍼스매칭 — 한쪽이 포함하면 잇는다(석유화학 ⊂ 석유화학공정기술)',
    캠퍼스매칭('석유화학', 표본캠퍼스표)?.긴이름 === '석유화학공정기술교육원');
  검('캠퍼스매칭 — 없으면 null(짐작해서 잇지 않는다)', 캠퍼스매칭('충남', 표본캠퍼스표) === null);

  검('EUC-KR 판별 — utf-8로 읽어 깨지면 다시 읽는다',
    Buffer.from([0xbc, 0xad, 0xbf, 0xef]).toString('utf8').includes('�'));
  검('EUC-KR 디코드가 실제로 맞는 글자를 낸다',
    new TextDecoder('euc-kr').decode(Buffer.from([0xbc, 0xad, 0xbf, 0xef])) === '서울');

  if (실패.length) { console.error('❌ 자가시험 실패\n' + 실패.map((s) => `   · ${s}`).join('\n')); process.exit(1); }
  console.log(`✅ collect-100y-polytech 자가시험 통과 (${16})`);
  process.exit(0);
}

만들기();
