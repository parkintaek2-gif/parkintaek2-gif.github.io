async function 의뢰한다(주문길, 보낼까) {
  const 주문글 = fs.readFileSync(path.resolve(뿌리, 주문길), 'utf8');
  const 글 = 의뢰문(주문글);
  if (!글) { console.log('⛔ 주문이 비었다 — 아무것도 안 보냈다'); return 1; }

  const puppeteer = (await import('puppeteer-core')).default;
  const D = await import('./desk-jbnews-article.mjs');
  let b;
  try {
    b = await puppeteer.connect({ browserURL: (process.env.KLM_CHROME_PORT ? 'http://127.0.0.1:' + process.env.KLM_CHROME_PORT : 'http://127.0.0.1:9222'), defaultViewport: null });
    const page = await b.newPage();
    await page.goto('https://claude.ai/recents', { waitUntil: 'domcontentloaded', timeout: 45000 });
    await new Promise((r) => setTimeout(r, 3000));

    console.log('■ 특별 기사를 «기사 쓰는 계정»에 의뢰한다 — 내가 쓰지 않는다');
    console.log('');
    const 이름 = `[특별 기사 의뢰] ${new Date().toLocaleString('ko-KR')}`;
    /* 데스킹 자의 대화 길을 그대로 빌려 쓴다 — 같은 계정·같은 프로젝트다 */
    const 결과 = await D.데스킹하기(page, 주문글, 이름, false);
    if (!결과?.됐나) {
      console.log('🔴 의뢰를 못 넣었다 — ' + (결과?.까닭 ?? '까닭 모름'));
      console.log('   ⛔ 「못 넣었다」를 「기사가 없다」로 읽지 않는다. 예약 회차는 그대로 돈다.');
      return 1;
    }
    console.log('✅ ① 의뢰가 들어갔고 기사가 왔다');
    console.log('   대화 ' + (결과.주소 ?? '(주소 없음)'));
    console.log('   제목 ' + String(결과.제목 ?? '(제목 없음)').slice(0, 70));
    const 기사 = 기사만뽑기(결과.기사);
    if (!기사) { console.log('🔴 기사 본문을 못 집었다'); return 1; }

    const 저장 = path.join(뿌리, 'docs', '고정업무-마커', '특별기사-최근.txt');
    fs.writeFileSync(저장, 기사, 'utf8');
    console.log('   ✔ 받은 기사를 적어 뒀다 — docs/고정업무-마커/특별기사-최근.txt');

    /* 🔴🔴 [2026-10-14 · 사장님] 「데스킹 결과에 대한 내용은 꼭 포함하도록.
         앞으로는 오늘 이강인 기사처럼 급하다고 대충하지마」
       ⛔ 오늘 나는 이 단계를 **통째로 건너뛰었다.** 급하다는 것이 까닭이 못 된다.
         데스킹은 사장님이 「팩트가 틀리는 경우가 많다」고 하셔서 둔 관문이다.
       ⚠ 데스킹이 실패해도 기사를 «버리지» 않는다 — 실패를 밝혀서 보낸다. */
    console.log('');
    console.log('■ ② 데스킹을 거친다 — ⛔ 급해도 건너뛰지 않는다 (사장님 2026-10-14)');
    const 데스킹 = await D.데스킹하기(page, 기사, `[특별 기사 데스킹] ${new Date().toLocaleString('ko-KR')}`);
    if (데스킹?.됐나) {
      console.log('   ✅ 데스킹 ' + (데스킹.차수 ?? '?') + '차 · ' + String(데스킹.판정 ?? '').slice(0, 60));
      console.log('   대화 ' + (데스킹.주소 ?? '(주소 없음)'));
    } else {
      console.log('   🔴 데스킹을 못 거쳤다 — ' + (데스킹?.까닭 ?? '까닭 모름'));
      console.log('   ⛔ 그래도 기사를 버리지 않는다. **실패를 밝혀서** 보낸다.');
    }

    const 편지 = 보낼편지(데스킹, { 기사: 데스킹?.됐나 && 데스킹.기사 ? 데스킹.기사 : 기사 });
    if (!편지) { console.log('🔴 보낼 편지를 못 지었다'); return 1; }
    const 보낼길 = path.join(뿌리, 'docs', '고정업무-마커', '특별기사-보낼것.txt');
    fs.writeFileSync(보낼길, 편지 + '\n', 'utf8');
    console.log('');
    console.log('■ ③ 보낼 편지 — docs/고정업무-마커/특별기사-보낼것.txt');
    console.log('   데스킹 결과가 들었나: '
      + (/■ 데스킹 메모/.test(편지) ? '✅ 들었다' : '🔴 안 들었다 — 사장님이 꼭 넣으라 하신 것이다'));
    console.log('');
    console.log(편지.slice(0, 900));
    console.log('');
    console.log('⚠ 보내기는 send-mail.mjs 로 따로 한다 — 이 자는 편지를 «짓는» 데까지 한다.');
    console.log('   ⛔ 보내기 전에 눈으로 본다. 오늘 급하다고 건너뛰어 사장님께 지적받았다.');
    return 0;
  } catch (e) {
    console.log('🔴 못 했다 — ' + String(e?.message ?? e).slice(0, 180));
    return 1;
  } finally {
    if (b) b.disconnect();        /* ⛔ close() 금지 — 사장님 창이 닫힌다 */
  }
}

