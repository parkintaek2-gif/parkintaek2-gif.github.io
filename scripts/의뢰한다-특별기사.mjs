/** 답에서 기사 본문만 집는다. ⚠ 데스킹 답과 달리 표지가 없을 수 있다 */
export function 기사만뽑기(답) {
  const s = String(답 ?? '').trim();
  if (!s) return null;
  /* 코드블록으로 감싸 왔으면 벗긴다 */
  const m = s.match(/```(?:\w+)?\n([\s\S]*?)```/);
  const 글 = (m ? m[1] : s).trim();
  return 글 || null;
}

/**
 * 틀 표시(마크다운)를 걷는다.
 * 🔴 [2026-10-14] 보낼 때 `**[부제목]**` 이 그대로 남아 있었다. 중부매일은 받은 글을
 *   그대로 싣는다 — 틀 표시가 지면에 찍힌다.
 */
export function 틀표시걷기(글) {
  return String(글 ?? '')
    .replace(/^\s*\*\*\[(제목|부제목|본문|사진[^\]]*)\]\*\*\s*$/gm, '')
    .replace(/^\s*\[(제목|부제목|본문)\]\s*$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * 🔴🔴 [2026-10-14 · 사장님] 「아무데나 개행처리하면 어떡하나」 · 「다시 써...」
 * ─────────────────────────────────────────────────────────────────────
 * **메일로 나가는 꼴을 바로잡는다.** 받은 글은 대화창에서 온 마크다운이라
 * 그대로 편지에 부으면 사장님 메일함에서 이렇게 보인다 —
 *   · 추천 키워드가 **한 줄에 하나씩** 빈 줄을 끼고 흩어진다
 *   · `---` `##` `**` 같은 **마크다운 기호가 글자 그대로** 나간다
 *   · 제목·부제·사진 캡션·본문이 구분 없이 똑같은 문단으로 늘어서
 *     어디가 제목이고 어디가 본문인지 모른다
 * ⛔ 「기사가 맞다」와 「기사가 읽히게 나간다」는 다른 일이다.
 *
 * ⚠ 글자는 **한 자도 고치지 않는다.** 꼴만 바로잡는다 —
 *   기사 내용에 손대는 것은 쓰는 계정의 몫이다(사장님 「쓰는 계정은 바꾸지 마」).
 */
export function 메일꼴로(글) {
  const 줄들 = String(글 ?? '').split('\n');
  const 낸다 = [];
  let 자리 = 0;                 /* 0 제목 · 1 부제 · 2 그 뒤 */
  let 키워드모음 = [];
  let 키워드칸 = false;

  const 민다 = (s) => { if (s === '' && (낸다.length === 0 || 낸다[낸다.length - 1] === '')) return; 낸다.push(s); };

  for (const 원줄 of 줄들) {
    let t = 원줄.trim();

    /* 마크다운 가로줄은 버린다 — 메일에서는 뜻 없는 기호다 */
    if (/^-{3,}$|^\*{3,}$|^_{3,}$/.test(t)) { 민다(''); continue; }

    /* `## 추천 키워드` 같은 머리말 — 기호를 떼고 글자만 남긴다 */
    const 머리 = t.match(/^#{1,6}\s*(.*)$/);
    if (머리) t = 머리[1].trim();

    /* 굵게 표시를 뗀다. ⚠ 글자는 남기고 기호만 뗀다 */
    t = t.replace(/\*\*(.+?)\*\*/g, '$1').replace(/^\*+$/, '');

    if (!t) { if (!키워드칸) 민다(''); continue; }

    /* 추천 키워드 칸 — 한 줄에 하나씩 떨어지던 것을 «한 줄»로 모은다.
       ⚠ 머리말 꼴이 여럿이다 — 「추천 키워드」·「3. 추천 키워드」·「<추천 키워드>」.
         처음에 `^추천` 만 봤다가 앞의 번호와 꺾쇠에 걸려 못 잡았다(실측). */
    if (/^[<\[(]?\s*\d*\.?\s*추천\s*키워드\s*[>\])]?\s*:?\s*$/.test(t)) { 키워드칸 = true; continue; }
    if (키워드칸) {
      if (/^(지금 낼 수 있음|원본 대화|■|데스킹)/.test(t)) {
        키워드칸 = false;
        if (키워드모음.length) { 민다(''); 민다('추천 키워드  ' + 키워드모음.join(' · ')); 키워드모음 = []; }
      } else { 키워드모음.push(t); continue; }
    }

    if (자리 === 0) { 민다('【제목】 ' + t); 자리 = 1; continue; }
    if (자리 === 1) { 민다('【부제】 ' + t); 자리 = 2; continue; }

    /* 사진 캡션 — 출처가 붙은 줄은 캡션으로 본다 */
    if (/\/\s*(연합뉴스|뉴시스|뉴스1|AP|AFP|로이터|EPA)\s*$/.test(t)) { 민다('【사진】 ' + t); continue; }

    민다(t);
  }
  if (키워드모음.length) { 민다(''); 민다('추천 키워드  ' + 키워드모음.join(' · ')); }

  return 낸다.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * **보낼 편지를 짓는다 — 데스킹 결과를 «반드시» 붙인다.**
 *
 * ── 🔴🔴 사장님 (2026-10-14) ────────────────────────────────────────
 * 「**데스킹 결과에 대한 내용은 꼭 포함하도록.
 *   앞으로는 오늘 이강인 기사처럼 급하다고 대충하지마**」
 *
 * ⛔ 오늘 내가 그것을 빠뜨렸다. 특별 기사를 **데스킹도 안 거치고** 보냈고,
 *   그러니 데스킹 결과도 당연히 없었다. 급한 것이 절차를 건너뛸 까닭이 되지 않는다.
 * ⚠ 평소 회차(`collect-jbnews-sports-articles.mjs` 2816줄)는 이 꼴로 붙인다 —
 *   판정 · 기사 · 가름줄 · 데스킹 메모(차수) · 요약 · 원본 대화 주소.
 *   **특별 기사도 같은 꼴로 보낸다.** 받는 쪽이 둘을 다르게 읽을 까닭이 없다.
 *
 * @returns {string|null} 데스킹 결과가 없으면 **null** — ⛔ 그냥 기사만 보내지 않는다
 */
export function 보낼편지(데스킹, { 기사 = null } = {}) {
  /* 🔴 [2026-10-14 · 사장님 「아무데나 개행처리하면 어떡하나」] 꼴을 바로잡아 담는다 */
  const 본문 = 메일꼴로(틀표시걷기(기사 ?? 데스킹?.기사 ?? ''));
  if (!본문) return null;
  /* 🔴 데스킹을 못 거쳤으면 **그 사실을 적어서** 보낸다 — 조용히 빼지 않는다 */
  if (!데스킹 || !데스킹.됐나) {
    const 까닭 = 데스킹?.까닭 ?? '데스킹을 돌리지 않았다';
    return [
      `🔴 데스킹을 못 거쳤습니다 — ${까닭}`,
      '   아래는 데스킹 «전» 글입니다. 데스크에서 한 번 봐 주십시오.',
      '',
      본문,
    ].join('\n');
  }
  const 줄 = '─'.repeat(40);
  const 머리 = 데스킹.판정 ? String(데스킹.판정).trim() : '(판정 줄이 없다)';
  return [
    머리,
    '',
    본문,
    '',
    줄,
    '',
    `■ 데스킹 메모 (${데스킹.차수 ?? '?'}차)`,
    '',
    /* ⚠ 데스킹 메모도 마크다운으로 온다 — 기호만 떼고 글자는 그대로 둔다 */
    String(데스킹.요약 ?? '(요약이 없다)').trim()
      .replace(/^\s*#{1,6}\s*/gm, '').replace(/\*\*(.+?)\*\*/g, '$1')
      .replace(/^\s*-{3,}\s*$/gm, '').replace(/\n{3,}/g, '\n\n').trim(),
    '',
    `원본 대화 ${데스킹.주소 ?? '(주소 없음)'}`,
    '',
  ].join('\n');
}

