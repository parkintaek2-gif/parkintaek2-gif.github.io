#!/usr/bin/env node
/* 메모에 적은 «수»가 자가 내는 수와 다른가. (5번 2026-10-12 07:2x)
 *
 * 🔴🔴 왜 있나 — 2026-10-12 에 내가 그랬다.
 *   메모에 「색인 요청은 **하루 한 장**」이라고 **일곱 번** 적었다. 실제로는 **열 장**이다.
 *   그 수를 내는 자가 바로 옆에 있었다 —
 *     node scripts/날마다-색인요청.mjs --오늘몫을썼나
 *       ■ 오늘 넣은 색인 요청 0개 / 하루 몫 10개
 *   그 자 머리에는 이렇게까지 적혀 있다 —
 *     「날마다 쓰면 한 해에 3,600장이다. 안 쓰면 0장이다」
 *   ⇒ 내가 「한 장」으로 알고 돈 날들은 **하루에 아홉 장씩 버린 것**이다.
 *
 * ⭐⭐ 이 꼴이 가장 조용하다.
 *   다른 흠들은 무언가 어긋나서 눈에 띈다. 이것은 **틀린 수로도 일이 굴러가서**
 *   아무 데서도 빨간불이 안 뜬다. 그래서 영영 안 들킨다.
 *   ⇒ 글로 두면 또 그런다. 자로 둔다.
 *
 * ⚠ 이 자가 할 수 있는 것과 못 하는 것
 *   할 수 있다 — **겪은 수**가 메모에 틀리게 적혀 있나
 *   못 한다   — 메모의 모든 수. 그건 셀 수 없고, 넓히면 거짓 빨강이 쏟아진다
 *   ⛔ 그래서 «겪은 자리만» 못 박는다. 하나 겪을 때마다 한 줄 더한다.
 *
 * 돌리기   node scripts/check-메모의-수가-자와-다른가.mjs
 * 자가시험 node scripts/check-메모의-수가-자와-다른가.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 겪은 자리 — 「메모에 이렇게 적히면 틀린 것이다」 */
export const 못박은것 = [
  {
    무엇: '색인 요청 하루 몫',
    틀린꼴: /색인\s*요청(은|이)?\s*하루\s*한\s*(장|개)/g,
    맞음: '하루 열 장',
    /* ⭐ 바로잡는 글에는 틀린 수가 «반드시» 나온다 — 무엇이 틀렸는지 적어야 하기 때문이다.
       그 줄 둘레에 이 꼴이 같이 있으면 흠이 아니라 바로잡음이다.
       ⚠ 「하루 열 장」으로 좁게 잡았더니 「… 열 장이다」와 「하루 **열 장**」을 둘 다 놓쳤다.
          꾸밈표(**)와 앞말이 사람마다 달라서다. ⇒ 「열 장」만으로 가린다. */
    맞는꼴: /(열|10)\s*\**\s*(장|개)/,
    자: 'node scripts/날마다-색인요청.mjs --오늘몫을썼나',
    겪은날: '2026-10-12',
    값: '「한 장」으로 알고 돈 날마다 아홉 장씩 버렸다. 날마다 쓰면 한 해 3,600장',
  },
];

/** 그 글에서 틀린 꼴이 몇 곳인가 */
export function 틀린곳(글, 꼴) {
  return (String(글 ?? '').match(꼴) ?? []).length;
}

/** 이 줄 둘레에 맞는 수가 같이 적혀 있나 — 그러면 바로잡는 글이다.
 *  ⚠ 둘레를 보는 까닭: 「틀림 … 한 장」 줄에는 맞는 수가 없고 «다음 줄»에 있다. */
export function 바로잡는글인가(줄들, 자리, 맞는꼴, 창 = 2) {
  if (!맞는꼴) return false;
  const 처음 = Math.max(0, 자리 - 창);
  const 끝 = Math.min(줄들.length, 자리 + 창 + 1);
  return 줄들.slice(처음, 끝).some((l) => 맞는꼴.test(l));
}

/** 바로잡는 글을 뺀 «진짜» 흠의 수.
 *  ⛔ 옛 자는 `- 2` 로 깎았다. 바로잡는 글을 한 줄 더 쓰면 또 빨개지는 자였다. */
export function 흠센다(글, x) {
  return 걸린줄들(글, x).reduce((a, b) => a + b.몇, 0);
}

/** 어느 «줄»이 걸렸나 — 수만 내면 사람이 또 뒤져야 한다.
 *  ⭐ 자가 내는 탈은 «다음 걸음»을 가리켜야 한다. */
export function 걸린줄들(글, x, 줄오프셋 = 0) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  const 걸린 = [];
  for (let i = 0; i < 줄들.length; i++) {
    const 꼴 = new RegExp(x.틀린꼴.source, 'g');
    const 몇 = (줄들[i].match(꼴) ?? []).length;
    if (!몇) continue;
    if (바로잡는글인가(줄들, i, x.맞는꼴)) continue;
    걸린.push({ 줄: i + 1 + 줄오프셋, 몇, 글: 줄들[i].trim().slice(0, 100) });
  }
  return 걸린;
}

/* ─────────────────────────────── 자가시험 ─────────────────────────────── */
async function 자가시험() {
  const { test } = await import('node:test');
  const A = (await import('node:assert/strict')).default;

  test('🔴 틀린 꼴을 세어 낸다 — 실제로 적혔던 글이다', () => {
    const 꼴 = 못박은것[0].틀린꼴;
    A.equal(틀린곳('색인 요청은 하루 한 장이라 문 한 장에 썼다', 꼴), 1);
    A.equal(틀린곳('색인요청 하루 한 개', 꼴), 1);
  });
  test('⛔ 맞게 적은 글은 안 걸린다', () => {
    const 꼴 = 못박은것[0].틀린꼴;
    A.equal(틀린곳('색인 요청은 하루 열 장이다', 꼴), 0);
    A.equal(틀린곳('하루 한 장씩 글을 낸다', 꼴), 0, '색인 요청 이야기가 아닌 것을 걸었다');
  });
  test('🔴 못 박은 것마다 «그 수를 내는 자»가 적혀 있다', () => {
    /* ⭐ 이 자의 핵심이다. 「틀렸다」만 말하고 어디서 맞는 수를 얻는지 안 적으면,
       다음 사람은 또 기억으로 적는다. */
    for (const x of 못박은것) {
      A.ok(x.자 && x.자.startsWith('node '), x.무엇 + ' 에 «수를 내는 자»가 없다');
      A.ok(x.값 && x.값.length > 10, x.무엇 + ' 에 «얼마나 값이 큰가»가 없다');
    }
  });
  test('⚠ 못 박은 자가 실제로 저장소에 있다 — 없으면 이 자가 헛돈다', () => {
    for (const x of 못박은것) {
      const 파일 = (x.자.match(/node\s+(\S+)/) || [])[1];
      A.ok(fs.existsSync(path.join(뿌리, 파일)), 파일 + ' 이 없다 — 자 이름이 바뀌었으면 여기도 고친다');
    }
  });
  test('빈 글·null 에도 안 터진다', () => {
  test('🔴 바로잡는 글은 흠이 아니다 — 2026-10-12 에 거짓 빨강을 냈다', () => {
    const 글 = [
      '틀림   색인 요청은 하루 한 장',
      '맞음   색인 요청은 하루 열 장',
    ].join('\n');
    A.equal(흠센다(글, 못박은것[0]), 0);
  });
  test('🔴 꾸밈표와 앞말이 달라도 바로잡는 글로 본다 — 2026-10-12 에 셋을 놓쳤다', () => {
    const 글들 = [
      '… 「색인 요청은 하루 한 장」이 일곱 번 적혀 있다. 열 장이다',
      '틀림   색인 요청은 하루 한 장\n맞음   색인 요청은 하루 **열 장**',
      '메모에 「색인 요청은 하루 한 장」이라고 적었다. **열 장**이다.',
    ];
    for (const g of 글들) A.equal(흠센다(g, 못박은것[0]), 0, g.slice(0, 30));
  });
  test('⭐ 어느 줄인지 돌려준다 — 수만 내면 사람이 또 뒤진다', () => {
    const 글 = ['첫 줄', '색인 요청은 하루 한 장이다', '셋째 줄'].join('\n');
    const r = 걸린줄들(글, 못박은것[0]);
    A.equal(r.length, 1);
    A.equal(r[0].줄, 2);
    A.ok(r[0].글.includes('하루 한 장'));
  });
  test('⚠ 줄오프셋을 주면 메모 전체 기준으로 센다', () => {
    const r = 걸린줄들('색인 요청은 하루 한 장', 못박은것[0], 100);
    A.equal(r[0].줄, 101);
  });

  test('🔴 맞는 수가 둘레에 없으면 흠으로 센다', () => {
    A.equal(흠센다('오늘도 색인 요청은 하루 한 장만 넣었다.', 못박은것[0]), 1);
  });
  test('⛔ 마법의 수가 사라졌나 — `- 2` 로 깎지 않는다', () => {
    const 나 = fs.readFileSync(path.join(뿌리, 'scripts/check-메모의-수가-자와-다른가.mjs'), 'utf8');
    A.ok(!/틀린곳\(볼글[^)]*\)\s*-\s*\d/.test(나), '아직 손으로 꼽아 깎고 있다');
  });
  test('⚠ 이 자가 헛돌지 않나 — 맞는꼴이 비어 있으면 아무것도 안 가린다', () => {
    /* ⛔ 맞는꼴 을 빠뜨리면 바로잡는 글까지 다 흠이 된다. 그 자리를 못 박는다. */
    A.equal(바로잡는글인가(['하루 열 장'], 0, null), false);
    A.ok(못박은것.every((x) => x.맞는꼴 instanceof RegExp), '맞는꼴 이 빠진 줄이 있다');
  });

    A.equal(틀린곳('', 못박은것[0].틀린꼴), 0);
    A.equal(틀린곳(null, 못박은것[0].틀린꼴), 0);
  });
}

const 내가실행됐다 = Boolean(process.argv[1]) && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다 && (process.argv.includes('--자가시험') || process.argv.includes('--selftest'))) {
  await 자가시험();
} else if (내가실행됐다) {
  console.log('■ 메모에 적은 «수»가 자가 내는 수와 다른가');
  console.log('   ⭐ 이 꼴이 가장 조용하다 — **틀린 수로도 일이 굴러가서** 아무 데서도 빨간불이 안 뜬다.');
  console.log('');

  /* ⚠ 바로잡는 줄 «뒤»만 본다. 그 앞은 「그때 무엇을 알았나」의 기록이라 고치지 않는다. */
  const 메모길 = path.join(뿌리, 'docs', '세션간-메모.md');
  const 온글 = fs.readFileSync(메모길, 'utf8');

  let 흠 = 0;
  for (const x of 못박은것) {
    const 바로잡은자리 = 온글.lastIndexOf('바로잡음 — 이 문서에 「' + '색인 요청은 하루 한 장');
    const 볼글 = 바로잡은자리 >= 0 ? 온글.slice(바로잡은자리) : 온글;
    /* 바로잡는 글 자체에 틀린 꼴이 «보기»로 적혀 있다 — 그건 센다고 흠이 아니다 */
    /* 🔴 [2026-10-12 07:5x · 5번] 여기 `- 2` 가 있었다 — 보기가 둘이라고 손으로 꼽은 것이다.
       ⛔ 바로잡는 글을 한 줄 더 쓰면 또 빨개지고, 두 줄 지우면 음수가 된다.
       ⭐ **마법의 수로 깎는 자는 자가 아니라 눈가림이다.** 줄 둘레를 보고 가린다. */
    /* 바로잡는 줄 «앞»이 몇 줄인지 세어, 찍는 줄 번호를 메모 전체 기준으로 맞춘다 */
    const 앞줄수 = 바로잡은자리 >= 0 ? 온글.slice(0, 바로잡은자리).split(/\r?\n/).length - 1 : 0;
    const 걸린 = 걸린줄들(볼글, x, 앞줄수);
    const 몇 = 걸린.reduce((a, b) => a + b.몇, 0);
    const 전체 = 틀린곳(온글, x.틀린꼴);
    console.log('   ' + (몇 ? '🔴' : '✅') + ' ' + x.무엇);
    console.log('      맞는 수  ' + x.맞음 + '   — ' + x.자);
    console.log('      왜 큰가  ' + x.값);
    console.log('      메모 전체 ' + 전체 + '곳 · **바로잡은 뒤** ' + 몇 + '곳'
      + (바로잡은자리 < 0 ? '  ⚠ 바로잡는 줄을 못 찾았다 — 전체를 셌다' : ''));
    for (const g of 걸린) console.log('        🔴 docs/세션간-메모.md:' + g.줄 + '  ' + g.글);
    if (몇) 흠 += 몇;
    console.log('');
  }

  if (흠) {
    console.log('🔴 바로잡은 뒤에도 ' + 흠 + '곳에 틀린 수가 적혔다 — 그 자를 돌려 보고 다시 적는다.');
    process.exit(1);
  }
  console.log('✅ 못 박은 수가 바로잡은 뒤로는 틀리게 안 적혔다');
  console.log('⭐ 수를 적기 전에 — `ls scripts/ | grep <그 일>` 을 먼저 친다. 자가 있으면 그것이 정본이다.');
  process.exit(0);
}
