#!/usr/bin/env node
/**
 * 세션간메모-월별로-자른다.mjs — **docs/세션간-메모.md 가 커지는 것을 막는다.**
 * ─────────────────────────────────────────────────────────────────────────────
 * [왜 만들었나 — 2026-10-15 · 5번이 찾음, 2번이 결정]
 *   12.3MB·200,462줄까지 불어 한 줄 붙이고 커밋하는 데 2분이 넘게 걸렸고,
 *   한 번은 기록이 통째로 날아갔다(5번 12:45 보고). 모든 유닛이 매시 쓰는
 *   파일이라 갈수록 느려진다. 그날 손으로 8·9월분을 docs/보관/ 으로 옮겨
 *   1.3MB·21,927줄로 줄였다(경계 대조로 손실 0 확인). 사장님이 「제안대로
 *   해」로 승인하셔서 그 손일을 스크립트로 굳힌다.
 *
 * [규칙 — 지난달까지만 옮긴다, 이번달은 절대 안 건드린다]
 *   「올해월」(오늘이 속한 달)은 항상 살려 둔다. 그보다 옛날 달만 옮긴다.
 *   ⛔ 날짜를 못 찾은 줄은 «이번달»로 본다 — 지워지거나 잘못 옮겨지는 것보다
 *      안전하게 실패하는 쪽을 고른다.
 *
 * [날짜를 어떻게 읽나 — 제목에 없으면 앞 날짜를 들고 간다]
 *   `## [진행] 5번 03:35` 처럼 제목에 날짜가 없는 섹션이 많다. 그 경우 **바로
 *   앞에서 본 날짜**를 그대로 쓴다(메모가 시간 순으로 쓰이기 때문에 유효한
 *   가정이다). 파일 맨 앞(첫 섹션 전)에서 아직 아무 날짜도 못 봤으면 그 머리말
 *   은 옮기지 않고 항상 살려 둔다.
 *
 * [한 번 돌려 끝나지 않는다 — 매달 1일 즈음 다시 돌린다]
 *   이미 옮겨진 달은 살아있는 파일에 없으므로 다시 돌려도 중복되지 않는다.
 *   같은 달 아카이브가 이미 있으면 **이어 붙인다**(덮어쓰지 않는다).
 *
 * ⛔ 이 자는 git add·commit 을 하지 않는다 — 파일만 바꾼다. 커밋은 부르는
 *   쪽(2번)이 사람 눈으로 diff 를 보고 한다.
 *
 * 쓰는 법
 *   node scripts/세션간메모-월별로-자른다.mjs            무엇을 옮길지만 보여준다(미리보기)
 *   node scripts/세션간메모-월별로-자른다.mjs --쓴다      실제로 옮긴다
 *   node scripts/세션간메모-월별로-자른다.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 메모길 = path.join(뿌리, 'docs', '세션간-메모.md');
const 보관폴더 = path.join(뿌리, 'docs', '보관');

const 날짜규칙 = /(20\d\d)-(\d\d)-(\d\d)/;

/** 제목 줄 하나에서 "YYYY-MM"을 찾는다. 없으면 null — 0 이나 지어낸 값으로 메우지 않는다 */
export function 월뽑기(제목줄) {
  const m = 날짜규칙.exec(제목줄 ?? '');
  if (!m) return null;
  return `${m[1]}-${m[2]}`;
}

/**
 * 전체 메모 글을 "머리말"과 "## 로 시작하는 섹션들"로 가른다.
 * 각 섹션에 월을 매긴다 — 제목에 날짜가 있으면 그것, 없으면 바로 앞 섹션의 월을 물려받는다.
 */
export function 섹션으로가르기(글) {
  const 줄들 = 글.split('\n');
  const 섹션들 = [];
  let 머리말줄 = [];
  let 지금 = null;
  let 마지막월 = null;

  for (const 줄 of 줄들) {
    if (줄.startsWith('## ')) {
      if (지금) 섹션들.push(지금);
      const 월 = 월뽑기(줄) ?? 마지막월;
      if (월) 마지막월 = 월;
      지금 = { 월, 줄들: [줄] };
    } else if (지금) {
      지금.줄들.push(줄);
    } else {
      머리말줄.push(줄);
    }
  }
  if (지금) 섹션들.push(지금);

  return { 머리말: 머리말줄.join('\n'), 섹션들 };
}

/** 오늘이 속한 "YYYY-MM" — 이 달은 절대 안 옮긴다 */
export function 이번달(지금 = new Date()) {
  const y = 지금.getFullYear();
  const m = String(지금.getMonth() + 1).padStart(2, '0');
  return `${y}-${m}`;
}

/**
 * 섹션들을 "이번달(또는 월을 못 찾음) → 살려둠" / "옛날달 → 옮김" 으로 가른다.
 * 옮길 것은 월별로 묶어서 반환한다.
 */
export function 가르기(섹션들, 이번달값) {
  const 살림 = [];
  const 옮길것 = new Map(); // 월 -> 줄 배열(섹션 이어붙인 것)

  for (const 섹션 of 섹션들) {
    const 안전한월 = 섹션.월 ?? 이번달값; // ⛔ 못 찾으면 이번달로 본다 — 안전 쪽
    if (안전한월 >= 이번달값) {
      살림.push(섹션);
    } else {
      const 모음 = 옮길것.get(안전한월) ?? [];
      모음.push(섹션.줄들.join('\n'));
      옮길것.set(안전한월, 모음);
    }
  }
  return { 살림, 옮길것 };
}

/* ─────────────────────────── 자가시험 ─────────────────────────── */
function 자가시험() {
  let 통과 = 0; let 실패 = 0;
  const 검 = (이름, 참) => { if (참) { 통과 += 1; console.log('✅ ' + 이름); } else { 실패 += 1; console.log('🔴 ' + 이름); } };

  검('제목에서 YYYY-MM 을 뽑는다', 월뽑기('## [1번] 2026-09-01 14:19 · 제목') === '2026-09');
  검('⛔ 날짜 없으면 null — 0 으로 메우지 않는다', 월뽑기('## [진행] 5번 03:35') === null);

  const 보기글 = [
    '# 머리말',
    '',
    '## [1번] 2026-08-04 16:3x · 첫 글',
    '8월 내용',
    '## [진행] 1번 16:4x',
    '날짜 없는 8월 후속(앞 섹션 월을 물려받아야 함)',
    '## [2번] 2026-09-01 10:00 · 9월 글',
    '9월 내용',
    '## [2번] 2026-10-15 09:00 · 10월 글',
    '10월 내용 — 이번달, 절대 안 옮김',
  ].join('\n');

  const { 머리말, 섹션들 } = 섹션으로가르기(보기글);
  검('머리말을 따로 뽑는다', 머리말 === '# 머리말\n');
  검('섹션 4개로 가른다', 섹션들.length === 4);
  검('날짜 없는 섹션이 앞 섹션 월을 물려받는다', 섹션들[1].월 === '2026-08');
  검('세 번째 섹션은 9월', 섹션들[2].월 === '2026-09');

  const { 살림, 옮길것 } = 가르기(섹션들, '2026-10');
  검('이번달(10월) 섹션만 살아남는다', 살림.length === 1 && 살림[0].월 === '2026-10');
  검('8월·9월 두 달이 옮겨진다', 옮길것.size === 2);
  검('8월 묶음에 두 섹션(날짜있는것+물려받은것)이 들어간다', 옮길것.get('2026-08').length === 2);
  검('9월 묶음에 한 섹션', 옮길것.get('2026-09').length === 1);

  검('이번달 경계는 >= 로 판정 — 기준을 8월로 주면 8·9·10월 전부(4섹션) 살아남는다',
    가르기(섹션들, '2026-08').살림.length === 4);

  검('월 비교는 문자열 YYYY-MM 사전순 == 시간순(자리수 고정이라 안전)', '2026-09' < '2026-10');

  console.log(`\n${실패 === 0 ? '✅' : '🔴'} 자가시험 ${통과 + 실패}개 중 통과 ${통과}개`);
  process.exit(실패 === 0 ? 0 : 1);
}

if (process.argv.includes('--자가시험') || process.argv.includes('--selftest')) {
  자가시험();
}

/* ─────────────────────────── 실행 ─────────────────────────── */
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
  && !process.argv.includes('--자가시험') && !process.argv.includes('--selftest')) {
  const 쓴다 = process.argv.includes('--쓴다');

  if (!fs.existsSync(메모길)) {
    console.error('🔴 ' + 메모길 + ' 이 없다.');
    process.exit(1);
  }

  const 원본 = fs.readFileSync(메모길, 'utf8');
  const { 머리말, 섹션들 } = 섹션으로가르기(원본);
  const 지금달 = 이번달();
  const { 살림, 옮길것 } = 가르기(섹션들, 지금달);

  console.log(`■ 이번달(살려둠) = ${지금달}`);
  console.log(`   살아남는 섹션 ${살림.length}개`);

  if (옮길것.size === 0) {
    console.log('✅ 옮길 지난달 섹션이 없다 — 할 일 없음');
    process.exit(0);
  }

  for (const [월, 모음] of [...옮길것.entries()].sort()) {
    console.log(`   🗂  ${월} → docs/보관/세션간-메모-${월}.md (${모음.length}개 섹션)`);
  }

  if (!쓴다) {
    console.log('\n⚠ 미리보기만 했다 — 실제로 옮기려면 --쓴다 를 붙인다.');
    process.exit(0);
  }

  fs.mkdirSync(보관폴더, { recursive: true });
  for (const [월, 모음] of 옮길것) {
    const 아카이브길 = path.join(보관폴더, `세션간-메모-${월}.md`);
    const 이미있음 = fs.existsSync(아카이브길);
    const 머리 = 이미있음 ? '' : `# 세션간-메모.md ${월} 아카이브(2번 자동정리) — 원본은 git 히스토리에 그대로 있음\n\n`;
    fs.appendFileSync(아카이브길, 머리 + 모음.join('\n') + '\n');
    console.log(`   ✔ ${아카이브길} ${이미있음 ? '(이어붙임)' : '(새로 만듦)'}`);
  }

  const 새live = 머리말 + 살림.map(s => s.줄들.join('\n')).join('\n');
  fs.writeFileSync(메모길, 새live);
  console.log(`\n✅ 옮겼다 — docs/세션간-메모.md 가 ${원본.length}자 → ${새live.length}자`);
  console.log('⚠ 커밋은 사람이 diff 를 보고 한다 — 이 자는 add·commit 을 안 한다.');
}
