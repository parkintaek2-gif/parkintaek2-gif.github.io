#!/usr/bin/env node
/**
 * collect-100y-marriage-age.mjs — **서른 살에 사람들은 결혼했을까, 아직일까**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 2번이 짚은 자리 — 나이 문이 0~9세와 50세 위에 몰려 있고 **20~40대가 비어 있다.**
 * /first-job 으로 20대를 냈다. 그 다음이 30대다.
 * 사장님이 좋다 하신 카피의 결이 바로 이 물음이다 —
 *   「서른둘에 사람들은 / 결혼했을까요, 아직일까요」
 *
 * ── 표 둘을 함께 받는다. 둘이 서로 다른 것을 잰다 ──────────────
 *   ① DT_1MR2060  성·연령·혼인상태별 인구      **모든 사람**을 나이칸으로 갈라 센다 (2022~2025)
 *   ② DT_1B83A05  시도별 평균초혼연령          **그 해 결혼한 사람**만의 평균     (1990~2025)
 *
 * ⛔⛔ 이 둘을 같은 말로 쓰면 거짓이 된다 — 이 자료의 가장 큰 함정이다.
 *   ②의 「평균 초혼 33.9세」는 **결혼한 사람들 사이의 평균**이다.
 *   안 한 사람은 그 평균에 아예 안 들어간다. 그래서 ②만 보면
 *   「서른넷쯤 되면 다들 했겠구나」로 읽히는데, ①로 세어 보면 그렇지 않다.
 *   ⇒ 지면에서 ①을 먼저 놓고 ②를 「다른 것을 재는 자」로 뒤에 놓는다.
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · 나이칸이 **다섯 살 묶음**이다. 「서른둘」 한 살은 못 가른다 — 30~34세로만 말한다
 * · 「미혼」은 **법적 상태**다. 사실혼·동거는 이 표에서 미혼으로 잡힌다
 * · 18세 이상 **내국인**만이다. 외국인은 빠져 있다
 * · ①은 2022~2025 네 해뿐이다(등록센서스). 긴 흐름은 ②로만 볼 수 있다
 *
 * 쓰는 법  node scripts/collect-100y-marriage-age.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '101';
export const 표들 = { 상태: 'DT_1MR2060', 초혼: 'DT_1B83A05' };
/** ⛔ 「합계」는 나이칸이 아니다. 세는 데서 빼야 두 배가 안 된다 */
export const 합계칸 = '합계';

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
export const 한자리 = (v) => (v == null ? null : Math.round(v * 10) / 10);
export function 몫(부분, 분모) {
  if (부분 == null || !분모) return null;
  return Math.round((부분 / 분모) * 1000) / 10;
}
/** 「30~34세」 → 30. ⛔ 「합계」·「20세미만」·「85세이상」은 따로 다룬다 */
export function 칸시작(칸) {
  const m = String(칸).match(/^(\d+)~/);
  return m ? Number(m[1]) : null;
}
/**
 * ⭐ **어느 나이칸에서 미혼이 절반 아래로 내려가나** — 이 지면의 답 한 줄.
 * ⛔ 「몇 살에」로 못 쓴다. 다섯 살 묶음이라 **칸 이름으로만** 말한다.
 */
export function 절반아래첫칸(줄들) {
  const 순 = 줄들.filter((r) => 칸시작(r.칸) != null).sort((a, b) => 칸시작(a.칸) - 칸시작(b.칸));
  return 순.find((r) => r.미혼몫 != null && r.미혼몫 < 50) || null;
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② 분모가 없으면 몫을 안 낸다', 몫(5, 0) === null);
  본다('③ 나이칸에서 시작 나이를 뽑는다', 칸시작('30~34세') === 30 && 칸시작('합계') === null && 칸시작('85세이상') === null);
  본다('④ ⛔ 「합계」는 나이칸이 아니다', 칸시작(합계칸) === null);
  본다('⑤ 미혼이 절반 아래로 처음 내려간 칸을 나이 차례로 찾는다',
    절반아래첫칸([{ 칸: '35~39세', 미혼몫: 30 }, { 칸: '25~29세', 미혼몫: 90 },
      { 칸: '30~34세', 미혼몫: 49.9 }, { 칸: '합계', 미혼몫: 1 }]).칸 === '30~34세');
  본다('⑥ 아무 칸도 절반 아래가 아니면 없다고 답한다',
    절반아래첫칸([{ 칸: '25~29세', 미혼몫: 90 }]) === null);
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-marriage-age.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  const 받기 = async (tbl, 꼬리) => {
    const j = await (await fetch(
      `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
      + `&format=json&jsonVD=Y&orgId=${ORG}&tblId=${tbl}&${꼬리}`)).json();
    if (!Array.isArray(j)) throw new Error(`${tbl}: ${JSON.stringify(j).slice(0, 150)}`);
    return j;
  };

  /* ① 모든 사람을 나이칸으로 갈라 센다 — ⛔ 네 해를 다 받는다(세 해만 받고 흐름을 못 본 적이 있다) */
  const 상태날 = await 받기(표들.상태, 'itmId=ALL&objL1=00&objL2=ALL&prdSe=Y&newEstPrdCnt=10');
  const 해들 = [...new Set(상태날.map((x) => x.PRD_DE))].sort();
  const 최신 = 해들[해들.length - 1];
  const 값 = (해, 칸, 항) => 수로(상태날.find(
    (x) => x.PRD_DE === 해 && x.C2_NM === 칸 && x.ITM_NM === 항)?.DT);

  const 나이칸들 = [...new Set(상태날.map((x) => x.C2_NM))].filter((c) => c !== 합계칸);
  const 성별 = [
    { 성: '전체', 계: '내국인(18세이상)_계', 미혼: '내국인_미혼', 유배우: '내국인_유배우', 헤어짐: '내국인_사별·이혼' },
    { 성: '남자', 계: '남자_계', 미혼: '남자_미혼', 유배우: '남자_유배우', 헤어짐: '남자_사별·이혼' },
    { 성: '여자', 계: '여자_계', 미혼: '여자_미혼', 유배우: '여자_유배우', 헤어짐: '여자_사별·이혼' },
  ];

  const 나이별 = 나이칸들.map((칸) => {
    const 한칸 = { 칸, 시작: 칸시작(칸) };
    for (const s of 성별) {
      const 계 = 값(최신, 칸, s.계), 미 = 값(최신, 칸, s.미혼);
      const 유 = 값(최신, 칸, s.유배우), 헤 = 값(최신, 칸, s.헤어짐);
      한칸[s.성] = { 계, 미혼: 미, 유배우: 유, 헤어짐: 헤, 미혼몫: 몫(미, 계), 유배우몫: 몫(유, 계) };
    }
    한칸.미혼몫 = 한칸.전체.미혼몫;
    return 한칸;
  }).sort((a, b) => (a.시작 ?? (a.칸 === '20세미만' ? -1 : 999)) - (b.시작 ?? (b.칸 === '20세미만' ? -1 : 999)));

  /* 🔴 자가 대조 셋 — 표가 스스로 맞는지 내가 더해 본다 */
  const 한칸 = 나이별.find((r) => r.칸 === '30~34세');
  const 세조각합 = 나이별.reduce((s, r) => s + (r.전체.미혼 + r.전체.유배우 + r.전체.헤어짐), 0);
  const 계합 = 나이별.reduce((s, r) => s + r.전체.계, 0);
  const 남녀합 = 나이별.reduce((s, r) => s + r.남자.계 + r.여자.계, 0);
  const 합계행 = 값(최신, 합계칸, '내국인(18세이상)_계');
  const 대조 = {
    '미혼+유배우+사별이혼 = 계': { 합: 세조각합, 계: 계합, 맞나: 세조각합 === 계합 },
    '남자+여자 = 내국인': { 합: 남녀합, 계: 계합, 맞나: 남녀합 === 계합 },
    '나이칸을 다 더하면 합계행': { 합: 계합, 합계행, 맞나: 계합 === 합계행 },
    뜻: '세 대조가 다 맞아야 내가 칸을 빠뜨리지도, 두 번 세지도 않은 것이다',
  };

  /* ② 그 해 «결혼한 사람»의 평균 — 다른 것을 재는 자다 */
  const 초혼날 = await 받기(표들.초혼, 'itmId=T1+T2&objL1=00&prdSe=Y&newEstPrdCnt=40');
  const 초혼해들 = [...new Set(초혼날.map((x) => x.PRD_DE))].sort();
  const 초혼흐름 = 초혼해들.map((해) => ({
    해,
    남편: 한자리(수로(초혼날.find((x) => x.PRD_DE === 해 && x.ITM_NM === '남편')?.DT)),
    아내: 한자리(수로(초혼날.find((x) => x.PRD_DE === 해 && x.ITM_NM === '아내')?.DT)),
  })).filter((r) => r.남편 != null);
  const 초혼첫 = 초혼흐름[0], 초혼끝 = 초혼흐름[초혼흐름.length - 1];

  /* 네 해 사이 30~34세 미혼 몫이 어떻게 움직였나 */
  const 흐름 = 해들.map((해) => ({
    해,
    '30~34세미혼몫': 몫(값(해, '30~34세', '내국인_미혼'), 값(해, '30~34세', '내국인(18세이상)_계')),
    '35~39세미혼몫': 몫(값(해, '35~39세', '내국인_미혼'), 값(해, '35~39세', '내국인(18세이상)_계')),
  }));

  const 넘김 = 절반아래첫칸(나이별);

  const 낸다 = {
    무엇: '서른 살에 사람들은 결혼했을까, 아직일까 — 나이칸별 혼인 상태와 평균 초혼 연령',
    만든날: new Date().toISOString().slice(0, 10),
    최신, 해들, 해수: 해들.length,
    출처: {
      기관: '국가데이터처',
      표: '① 인구총조사 「성, 연령 및 혼인상태별 인구」 · ② 인구동향조사 「시도별 평균초혼연령」',
      창구: 'KOSIS', orgId: ORG, tblId: `${표들.상태} · ${표들.초혼}`,
    },
    '⛔⛔ 두 표를 같은 말로 쓰면 거짓이 된다':
      '평균 초혼 연령은 «그 해 결혼한 사람»들 사이의 평균입니다 — 안 한 사람은 그 평균에 아예 들어가지 않습니다. '
      + '그래서 「평균이 서른넷이니 서른넷이면 다들 했겠다」로 읽으면 어긋납니다. 나이칸별로 세어 보면 다릅니다.',
    '⚠ 이 자료가 못 가르는 것': [
      '나이칸이 다섯 살 묶음입니다. 「서른둘」 한 살은 이 표로 못 가릅니다 — 30~34세로만 말했습니다.',
      '「미혼」은 법적 상태입니다. 사실혼·동거는 이 표에서 미혼으로 잡힙니다.',
      '18세 이상 내국인만입니다. 외국인은 빠져 있습니다.',
      '①은 2022~2025 네 해뿐입니다(등록센서스). 긴 흐름은 ②로만 볼 수 있습니다.',
      '②는 시도까지만 있고 시군구가 없습니다. 동네별로는 못 말합니다.',
    ],
    나이별, 서른칸: 한칸, 미혼이절반아래로내려간첫칸: 넘김,
    흐름, 자가대조: 대조,
    초혼: { 흐름: 초혼흐름, 첫: 초혼첫, 끝: 초혼끝, 해수: 초혼흐름.length },
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/marriage-age.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
  console.log(`   ① ${해들[0]}~${최신} (${해들.length}해) · 나이칸 ${나이별.length}칸`);
  console.log(`      30~34세 미혼 ${한칸.전체.미혼몫}% (남 ${한칸.남자.미혼몫}% · 여 ${한칸.여자.미혼몫}%)`);
  console.log(`      미혼이 절반 아래로 처음 내려가는 칸: ${넘김 ? `${넘김.칸} (${넘김.미혼몫}%)` : '없다'}`);
  console.log(`   ② ${초혼첫.해}~${초혼끝.해} (${초혼흐름.length}해) · 평균 초혼 남편 ${초혼끝.남편}세 · 아내 ${초혼끝.아내}세`);
  console.log(`      ${초혼첫.해}년엔 남편 ${초혼첫.남편}세 · 아내 ${초혼첫.아내}세였다`);
  console.log(`   자가대조: 세조각=계 ${대조['미혼+유배우+사별이혼 = 계'].맞나 ? '맞다' : '🔴 안 맞다'}`
    + ` · 남+여=내국인 ${대조['남자+여자 = 내국인'].맞나 ? '맞다' : '🔴 안 맞다'}`
    + ` · 나이칸합=합계행 ${대조['나이칸을 다 더하면 합계행'].맞나 ? '맞다' : '🔴 안 맞다'}`);
}
