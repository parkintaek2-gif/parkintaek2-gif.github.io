/**
 * 글을 보고 상태를 정한다.
 * ⛔ 「모른다」를 「로그아웃」으로 치지 않는다 — 둘은 다르다.
 *   모르면 사람이 한 번 봐야 하고, 로그아웃이면 로그인하면 된다.
 */
export function 상태정하기(글, 곳) {
  const t = String(글 ?? '');
  if (!t.trim()) return { 상태: '모름', 까닭: '글이 비었다 — 화면을 못 읽었다' };
  const 들어갔나 = (곳.들어간표 ?? []).some((r) => r.test(t));
  const 밀렸나 = (곳.로그인표 ?? []).some((r) => r.test(t));
  if (들어갔나 && !밀렸나) return { 상태: '로그인', 까닭: '내 정보가 보인다' };
  if (밀렸나 && !들어갔나) return { 상태: '로그아웃', 까닭: '로그인 화면으로 밀려났다' };
  if (들어갔나 && 밀렸나) return { 상태: '모름', 까닭: '두 표가 같이 나왔다 — 사람이 본다' };
  return { 상태: '모름', 까닭: '아는 표가 하나도 없다 — 화면이 바뀌었을 수 있다' };
}

export function 표(상태) {
  return 상태 === '로그인' ? '✅' : 상태 === '로그아웃' ? '🔴' : '⚠';
}

/* ── 자가시험 ─────────────────────────────────────────────── */
export function 자가시험() {
  let 통과 = 0; let 깨짐 = 0;
  const 본다 = (말, 참) => { if (참) { 통과++; console.log(`  ✅ ${말}`); } else { 깨짐++; console.log(`  🔴 ${말}`); } };
  const 네이버 = 볼곳.find((c) => c.이름 === '네이버');

  console.log('\n■ 바깥채널 로그인 — 자가시험\n');

  /* 🔴 실제로 두 번 속은 그 글이다. 네이버 첫 화면에서 긁은 것. */
  const 속은글 = '상단영역 바로가기 서비스 메뉴 바로가기 새소식 블록 바로가기 쇼핑 블록 '
    + '바로가기 관심사 블록 바로가기 MY 영역 바로가기 위젯 보드 바로가기 보기 설정 바로가기';
  본다('🔴 「MY 영역」이 들어 있어도 로그인으로 보지 않는다 — 두 번 속은 글이다',
    상태정하기(속은글, 네이버).상태 !== '로그인');
  본다('   그것은 「모름」이다 — 아는 표가 없다',
    상태정하기(속은글, 네이버).상태 === '모름');

  /* 실제로 nid.naver.com 에서 긁은 글 */
  const 진짜글 = '본문 바로가기 네이버 아이디 또는 전화번호 삭제 비밀번호 비밀번호 표시 삭제 '
    + '로그인 상태 유지 IP 보안 ON 패스키 로그인 아이디 찾기 비밀번호 찾기 회원가입';
  본다('🔴 로그인 화면으로 밀려나면 «로그아웃»이다',
    상태정하기(진짜글, 네이버).상태 === '로그아웃');

  본다('내 정보가 보이면 «로그인»이다',
    상태정하기('회원정보 수정 이름 이메일', 네이버).상태 === '로그인');
  본다('⛔ 글이 비면 «모름»이다 — 로그아웃으로 치지 않는다',
    상태정하기('', 네이버).상태 === '모름');
  본다('⛔ 두 표가 같이 나오면 «모름»이다',
    상태정하기('회원정보 아이디 찾기', 네이버).상태 === '모름');
  본다('표가 셋 다 다르다',
    표('로그인') === '✅' && 표('로그아웃') === '🔴' && 표('모름') === '⚠');
  /* ⛔ 여기 _myCafe 가 적혀 있었다 — 내가 지어낸 주소였고 404 를 받았다.
     첫 화면의 「내카페」 링크를 눌러 받은 my_cafe 가 진짜다. */
  본다('볼 곳이 셋이고 모두 «로그인해야 열리는» 주소다',
    볼곳.length === 3 && 볼곳.every((c) => /nid\.naver|my_cafe|auth\/login/.test(c.열쇠자리)));
  본다('⛔ 첫 화면 주소를 보지 않는다 — 두 번 속은 자리다',
    볼곳.every((c) => !/^https:\/\/(www\.naver\.com|top\.cafe\.daum\.net|www\.tistory\.com)\/?$/.test(c.열쇠자리)));

  console.log(`\n  통과 ${통과} · 깨짐 ${깨짐}\n`);
  return 깨짐 === 0;
}

/* ── 혼자 돌 때 ───────────────────────────────────────────── */
const 내가실행됐다 = Boolean(process.argv[1]) && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다 && (process.argv.includes('--자가시험') || process.argv.includes('--selftest'))) {
  process.exit(자가시험() ? 0 : 1);
}

if (내가실행됐다) {
  const puppeteer = createRequire(import.meta.url)('puppeteer-core');
  let b = null;
  try {
    b = await puppeteer.connect({ browserURL: 'http://127.0.0.1:9222', defaultViewport: null });
  } catch (e) {
    console.log('⚠ 크롬(9222)에 못 붙었다 — 못 쟀다. ' + String(e.message).slice(0, 60));
    process.exit(0);                       /* ⛔ 못 잰 것으로 막지 않는다 */
  }

  console.log('■ 바깥 커뮤니티 계정이 로그인돼 있나');
  console.log('   사장님 2026-10-05 — 「순위를 무조건 높여......커뮤니티 잘 활용해서」\n');

  const 탭 = [];
  const 결과 = [];
  try {
    for (const 곳 of 볼곳) {
      const p = await b.newPage();
      탭.push(p);
      let 글 = '';
      try {
        await p.goto(곳.열쇠자리, { waitUntil: 'domcontentloaded', timeout: 25000 });
        await new Promise((r) => setTimeout(r, 2500));
        글 = await p.evaluate(() => document.body.innerText.replace(/\s+/g, ' ').slice(0, 1200));
      } catch (e) {
        글 = '';
      }
      const r = 상태정하기(글, 곳);
      결과.push({ 이름: 곳.이름, ...r, 쓸모: 곳.쓸모 });
      console.log(`  ${표(r.상태)} ${곳.이름.padEnd(10, ' ')} ${r.상태} — ${r.까닭}`);
      console.log(`     ${곳.쓸모}`);
    }
  } finally {
    for (const p of 탭) { try { await p.close(); } catch { /* 내가 연 것만 */ } }
    await b.disconnect();                  /* ⛔ close() 가 아니다 */
  }

  const 로그아웃 = 결과.filter((r) => r.상태 === '로그아웃');
  const 모름 = 결과.filter((r) => r.상태 === '모름');
  console.log('');
  if (로그아웃.length) {
    console.log(`🔴 로그인 안 된 곳 ${로그아웃.length} — ${로그아웃.map((r) => r.이름).join(' · ')}`);
    console.log('   커뮤니티로 링크를 만들려면 여기가 먼저 풀려야 한다.');
  }
  if (모름.length) {
    console.log(`⚠ 못 잰 곳 ${모름.length} — ${모름.map((r) => r.이름).join(' · ')}`);
    console.log('   ⛔ 「못 쟀다」를 「로그아웃」으로 치지 않는다. 화면이 바뀌었으면 표를 고친다.');
  }
  if (!로그아웃.length && !모름.length) console.log('✅ 셋 다 로그인돼 있다');
}
