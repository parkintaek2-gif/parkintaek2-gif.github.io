    /* ⛔ _myCafe 를 지어냈다가 404 를 받았다 — 주소를 지어내지 않는다.
       첫 화면의 「내카페」 링크를 눌러서 받은 진짜 주소다. */
    열쇠자리: 'https://top.cafe.daum.net/_c21_/my_cafe',
    /* 다음은 카카오 계정으로 넘어간다 — 실제로 긁은 글에서 뽑은 표다 */
    로그인표: [/Kakao 계정 정보 입력/, /간편로그인/, /로그인이 필요합니다/],
    들어간표: [/내가 가입한 카페/, /가입한 카페/, /내 카페 목록/],
