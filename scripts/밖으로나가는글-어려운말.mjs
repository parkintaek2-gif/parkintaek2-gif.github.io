/** 손님이 보거나 밖으로 나가는 파일만 본다. ⛔ 코드 주석은 보지 않는다 */
export const 볼확장자 = ['.html', '.astro', '.jsx', '.tsx', '.vue', '.md', '.txt'];
export const 건너뛸폴더 = ['node_modules', 'dist', 'out', '.git', 'archive', 'logs',
  'tmp', 'coverage', '.astro', 'build', '사진', 'scripts', 'tests', 'docs'];

export function 파일모으기(뿌리, 모은것 = []) {
  let 것들;
  try { 것들 = fs.readdirSync(뿌리, { withFileTypes: true }); } catch { return 모은것; }
  for (const 것 of 것들) {
    const 온길 = path.join(뿌리, 것.name);
    if (것.isDirectory()) {
      if (건너뛸폴더.includes(것.name) || 것.name.startsWith('.')) continue;
      파일모으기(온길, 모은것);
    } else if (볼확장자.includes(path.extname(것.name).toLowerCase())) {
      모은것.push(온길);
    }
  }
  return 모은것;
}

