/** 한 글에서 걸린 말을 찾는다. 사진 캡션·본문을 가리지 않는다 — 다 밖으로 나간다 */
export function 걸린말찾기(글) {
  const g = String(글 ?? '');
  const 걸림 = [];
  for (const [말, 대신] of 바꿔쓸말) {
    /* ⚠ 줄 번호를 같이 내야 고치러 갈 수 있다 */
    const 줄들 = g.split('\n');
    const 자리 = [];
    줄들.forEach((줄, i) => { if (줄.includes(말)) 자리.push(i + 1); });
    if (자리.length) 걸림.push({ 말, 대신, 줄: 자리, 번: 자리.length });
  }
  return 걸림;
}

/* ── 자가시험 ─────────────────────────────────────────────────────── */
export function 자가시험() {
  const 것 = [];
  const 검 = (이름, 참) => 것.push({ 이름, 참: !!참 });

  const 나쁜글 = '케이라이프맵은 격국·용신을 분석하고 점성학 네이탈 차트를 그린다.';
  const 걸림 = 걸린말찾기(나쁜글);
  검('🔴 격국을 잡는다', 걸림.some((x) => x.말 === '격국'));
  검('🔴 용신을 잡는다', 걸림.some((x) => x.말 === '용신'));
  검('🔴 점성학을 잡는다', 걸림.some((x) => x.말 === '점성학'));
  검('🔴 네이탈을 잡는다', 걸림.some((x) => x.말 === '네이탈'));
  검('줄 번호를 낸다', 걸림[0].줄[0] === 1);
  검('바꿔 쓸 말을 함께 낸다', 걸림.every((x) => x.대신 && x.대신.length > 1));

  /* ⛔ 대조군 — 쉬운 말로만 쓴 글은 하나도 안 걸려야 한다.
     이것이 없으면 「전부 걸린다」는 자도 통과한다. */
  const 좋은글 = '케이라이프맵은 사주를 풀이하고 태어난 순간의 하늘을 그려 별자리 운세를 보여 준다.';
  검('⛔ 대조군 — 쉬운 글은 안 걸린다', 걸린말찾기(좋은글).length === 0);
  검('⛔ 빈 글은 안 걸린다', 걸린말찾기('').length === 0);

  /* ⭐ 「별자리 운세」가 금지어 「점성학」의 대체어인데 그 자체가 걸리면 길이 막힌다 */
  검('⭐ 대체어가 스스로 걸리지 않는다',
    바꿔쓸말.every(([, 대신]) => 걸린말찾기(대신).length === 0));

  /* 🔴 실물 — 지금 나갈 보도자료가 깨끗한가 */
  const 보도 = 'C:/Users/User/OneDrive/KLifeMap/보도자료/보도자료-20261017.md';
  if (fs.existsSync(보도)) {
    const 실 = 걸린말찾기(fs.readFileSync(보도, 'utf8'));
    검(`🔴 실물 보도자료가 깨끗하다 (걸린 말 ${실.length})`, 실.length === 0);
    for (const x of 실) console.log(`      ↳ ${x.말} — ${x.줄.join(',')}줄 ⇒ ${x.대신}`);
  }

  for (const x of 것) console.log(`${x.참 ? '✅' : '🔴'} ${x.이름}`);
  const 탈 = 것.filter((x) => !x.참).length;
  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${것.length} 통과`);
  return 탈 === 0;
}

/* ── 손으로 돌릴 때 ───────────────────────────────────────────────── */
const 나인가 = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (나인가) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);
  const 길 = process.argv[2];
  if (!길 || !fs.existsSync(길)) { console.log('⛔ 검사할 글의 길을 준다'); process.exit(1); }
  const 걸림 = 걸린말찾기(fs.readFileSync(길, 'utf8'));
  if (!걸림.length) { console.log(`✅ 어려운 말이 없다 — ${path.basename(길)}`); process.exit(0); }
  console.log(`🔴 어려운 말 ${걸림.length}가지 — ${path.basename(길)}\n`);
  for (const x of 걸림) console.log(`  ${x.말}  (${x.줄.join(', ')}줄 · ${x.번}번)\n    ⇒ ${x.대신}`);
  console.log('\n⛔ 기자는 이 말을 모른다. 고치기 전에 내보내지 않는다.');
  process.exit(1);
}
