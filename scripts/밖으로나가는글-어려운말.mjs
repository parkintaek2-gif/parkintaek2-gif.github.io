/** 한 글에서 걸린 말을 찾는다. `어디` 는 '밖으로' | '화면' */
export function 걸린말찾기(글, 어디 = '밖으로') {
  const g = String(글 ?? '');
  const 재는것 = 잣대[어디] || 잣대.밖으로;
  const 걸림 = [];
  const 줄들 = g.split(String.fromCharCode(10));
  for (const x of 바꿔쓸말) {
    if (!재는것.막는갈래.includes(x.갈래)) continue;
    const 자리 = [];
    줄들.forEach((줄, i) => { if (줄.includes(x.말)) 자리.push(i + 1); });
    if (자리.length) 걸림.push({ ...x, 줄: 자리, 번: 자리.length });
  }
  return 걸림;
}

