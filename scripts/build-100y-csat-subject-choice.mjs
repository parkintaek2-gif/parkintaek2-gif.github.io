/**
 * 탐구 갈래 한 칸(인원·비율·전년대비)을 만든다.
 *
 * 🔴 [2026-09-09 · 3번] 처음엔 비율을 인원÷전체(551,864명)로 직접 셈했는데, 그러면
 *   66.5%가 나와 KICE 보도자료를 인용한 기사들의 69.6%와 안 맞았다. 세 갈래 합이
 *   전체보다 24,609명 적은 것(덮는범위 참고)과 같은 원인 — 기사들은 탐구 «전체
 *   응시자»(더 작은 분모)를 기준으로 %를 냈는데 그 분모 자체가 이번 보도자료·인용
 *   기사 어디에도 안 나온다. 우리가 없는 분모로 다시 셈해 만든 값보다, KICE가 이미
 *   낸(기사가 인용한) 비율을 그대로 옮기는 편이 정직하다 — 그래서 비율은 «주어진
 *   값»을 받는다. 안 주면 전체 지원자 기준으로 참고삼아 셈하고 그렇다고 밝힌다.
 */
export function 탐구칸(인원, 전체, 전년인원, 발표비율 = null) {
  return {
    인원,
    비율: 발표비율 ?? Math.round((인원 / 전체) * 1000) / 10,
    비율기준: 발표비율 != null ? 'KICE 보도자료 인용 기사가 밝힌 값' : '전체 지원자 대비 참고 셈(KICE 분모와 다를 수 있다)',
    전년대비: 전년인원 == null ? null : 인원 - 전년인원,
  };
}

/** 사탐만 선택한 인원이 과탐만 선택한 인원의 몇 배인지(소수 한 자리) */
export function 사탐과탐배수(사탐인원, 과탐인원) {
  return Math.round((사탐인원 / 과탐인원) * 10) / 10;
}

