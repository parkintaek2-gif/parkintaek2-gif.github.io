/**
 * 토스문의-올린다.mjs — **월요일 아침에, 못 올린 문의를 다시 꺼내 놓는다.**
 *
 * ── 🔴 왜 (2026-10-24 19:05) ────────────────────────────────────────────
 * 사장님이 토스 콘솔에 로그인해 주셔서 들어가 봤더니,
 * 결제위젯의 「카드사 선택」을 끄는 자리가 **콘솔에 없었다.**
 * 토스에 물어야 하는데 1:1 채팅이 「상담원과 연결해야 입력할 수 있어요」로 막혀 있었다.
 * 고객센터는 평일 08:00~19:00 이고 주말·공휴일은 쉰다.
 *
 * ⛔ 「월요일에 하자」를 기억에 맡기지 않는다. 기억에 맡긴 것은 안 한 것이 된다.
 * ⭐ 이 자는 «답하지» 않는다 — 세션간 메모에 5번을 불러 세워 놓을 뿐이다.
 *   채팅에 글을 넣는 것은 사람 손이 필요한 화면이라 깨어 있는 세션이 한다.
 *
 * 실행: node scripts/토스문의-올린다.mjs   ·  검사: node scripts/토스문의-올린다.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
export const 메모길 = path.join(여기, '..', 'docs', '세션간-메모.md');

/** 평일 영업시간(08:00~19:00) 안인가 — 밖이면 글을 못 넣는다 */
export function 쓸수있나(때) {
  const 요일 = 때.getDay();                     /* 0 일 · 6 토 */
  if (요일 === 0 || 요일 === 6) return false;
  const 시 = 때.getHours();
  return 시 >= 8 && 시 < 19;
}

export function 부르는글(때) {
  const 날 = `${때.getFullYear()}-${String(때.getMonth() + 1).padStart(2, '0')}-${String(때.getDate()).padStart(2, '0')}`;
  const 시각 = `${String(때.getHours()).padStart(2, '0')}:${String(때.getMinutes()).padStart(2, '0')}`;
  return [
    '',
    `## [자물쇠→5번] ${날} ${시각} · 🔴 토스에 물어볼 것이 아직 남아 있습니다`,
    '',
    '**결제위젯의 「카드사 선택」을 끄는 자리가 토스 콘솔에 없습니다.**',
    '2026-10-24 에 콘솔의 결제 UI 설정(디자인·기능)을 모바일·PC 둘 다 열어 확인했습니다.',
    '「카드사 목록」은 어느 카드사를 보일지만 정하고, PC 의 「카드사 레이아웃」에는',
    '드롭다운 모서리 굵기밖에 없습니다. 토스 쪽 미리보기에서도 카드사 선택이 그대로 뜹니다.',
    '',
    '⛔ 손님은 카드사를 안 고른 채 「결제하기」를 누르면 **반드시 한 번 실패합니다.**',
    '   우리 쪽은 막아 뒀습니다(미리 알려 주고, 실패하면 그 자리로 데려다 줍니다).',
    '   근본은 토스 쪽 설정이라 물어봐야 합니다.',
    '',
    '⭐ 지금 할 것 — app.tosspayments.com → 1:1 채팅상담 → 「가맹점 문의」 → 상담원 연결',
    '   물을 것: 「결제창형(live_gck_)으로 연동했는데 위젯에 카드사 선택이 필수로 뜹니다.',
    '            가맹점 설정으로 이 단계를 뺄 수 있습니까?」',
    '   ⚠ 주말·공휴일과 19시 이후에는 글을 못 넣습니다 — 평일 08:00~19:00 안에 하십시오.',
    '',
  ].join('\n');
}

function 자가시험() {
  const 것들 = [];
  const 참 = (이름, 값) => { 것들.push([이름, !!값]); };

  참('🔴 토요일에는 글을 못 넣는다', !쓸수있나(new Date(2026, 9, 24, 10, 0)));
  참('🔴 일요일에도 못 넣는다', !쓸수있나(new Date(2026, 9, 25, 10, 0)));
  참('월요일 10시는 넣을 수 있다', 쓸수있나(new Date(2026, 9, 26, 10, 0)));
  참('⛔ 평일이어도 19시를 넘기면 못 넣는다', !쓸수있나(new Date(2026, 9, 26, 19, 1)));
  참('⛔ 평일이어도 8시 전이면 못 넣는다', !쓸수있나(new Date(2026, 9, 26, 7, 59)));
  참('부르는 글에 무엇을 물을지가 들어 있다', /카드사 선택이 필수로 뜹니다/.test(부르는글(new Date())));
  참('부르는 글이 5번을 부른다', /\[자물쇠→5번\]/.test(부르는글(new Date())));
  참('⛔ 「했다」가 아니라 「할 것」으로 적는다', !/문의했습니다|물어봤습니다/.test(부르는글(new Date())));

  for (const [이름, 됐나] of 것들) console.log((됐나 ? '✅ ' : '🔴 ') + 이름);
  const 깨진것 = 것들.filter(([, v]) => !v).length;
  console.log(깨진것 ? `\n🔴 자가시험 ${깨진것} 깨졌다` : `\n✅ 자가시험 ${것들.length} 통과`);
  return 깨진것 ? 1 : 0;
}

if (process.argv.includes('--자가시험')) {
  process.exit(자가시험());
} else {
  const 이제 = new Date();
  fs.appendFileSync(메모길, 부르는글(이제), 'utf8');
  console.log(`[${이제.toTimeString().slice(0, 8)}] 세션간 메모에 5번을 불러 세웠다`
    + (쓸수있나(이제) ? ' — 지금은 영업시간 안이다' : ' — ⚠ 지금은 영업시간 밖이다'));
}
