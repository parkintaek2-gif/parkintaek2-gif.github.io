#!/usr/bin/env node
/**
 * check-before-i-write.mjs — 🔒 **적기 전에 찾았나** 자물쇠
 * ─────────────────────────────────────────────────────────────────────────────
 * [왜 — 2026-08-10]
 *   사장님: 「**항상 얘기한 적 있는지 파악하고 작업을 해**」
 *           「이런 실수가 **매일 하루도 안 빠지고, 하루에 몇 차례씩** 발생한다.
 *            **기술적으로 아예 막아. 자물쇠를 만들든지**」
 *
 *   2번이 2026-08-10 하루에 여섯 번 틀렸다. 여섯 다 **몰라서가 아니라 안 찾아서**다 —
 *     ① 「일반고 1,703곳에 줄 숫자가 없다」   안 재고 걸었다. 3번이 재 보니 안 비어 있었다
 *     ② 「/y/ 넷이 라이브 404」               3번이 이미 배포해 200 이었다
 *     ③ 「닿는 길은 유튜브 하나」             짧은 주소 넷·X 넷·기사 122편이 그 뒤에 생겼다
 *     ④ 「뉴스레터 23명」                     원문의 **「로컬 store · 못 가름」**을 빼고 옮겼다
 *     ⑤ 「Riot 사다리를 되살려라」            「승인 전까지 기다린다」가 네 군데 적혀 있었다
 *     ⑥ 「격→직업 해법이 필요하다」           해법을 내가 이미 정해 8번에게 걸어 뒀다
 *
 * [무엇을 막나]  메모에 **새로 적는 줄**만 본다. 넷을 본다 —
 *   ㉮ 같은 낱말에 **다른 숫자**가 이미 적혀 있다        (①③④⑤ 를 잡는다)
 *   ㉯ 원문에 붙은 **단서를 빼고** 숫자만 옮겼다          (④ 를 잡는다)
 *   ㉰ 라이브를 단정하면서 **잰 시각이 없다**            (② 를 잡는다)
 *   ㉱ 「해야 한다」고 쓰는데 **이미 걸어 둔 지시**가 있다 (⑥ 를 잡는다)
 *
 * ⛔ 이 자는 **글을 안 고친다.** 「이미 이렇게 적혀 있다」를 보여주고 멈춘다. 정하는 것은 사람이다.
 * ⛔ 늘 울면 안 읽힌다 — 그래서 **새로 적는 줄에서 숫자가 든 것만** 본다.
 *
 * 쓰는 법
 *   node scripts/check-before-i-write.mjs            커밋 안 된 메모 새 줄을 본다
 *   node scripts/check-before-i-write.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const 뿌리 = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const 메모 = 'docs/세션간-메모.md';

/* ── 뽑기 ────────────────────────────────────────────────────────────────── */

/** 「낱말 숫자단위」 짝을 뽑는다 — 「뉴스레터 23명」 → {낱말:'뉴스레터', 값:'23', 단위:'명'} */
export function 숫자짝뽑기(줄) {
  const 것 = [];
  const re = /([가-힣A-Za-z][가-힣A-Za-z0-9·\/_-]{1,20})\s*([0-9][0-9,]*)\s*(명|곳|장|편|건|개|줄|칸|%|억|원|쪽|층)/g;
  let m;
  while ((m = re.exec(String(줄 ?? '')))) {
    것.push({ 낱말: m[1], 값: m[2].replace(/,/g, ''), 단위: m[3] });
  }
  return 것;
}

/** 단서가 붙어 있나 — 이게 붙은 숫자는 「잰 것」이 아니다 */
export const 단서들 = ['⚠', '못 잼', '못잼', '못 가름', '로컬', '미확인', '추정', '짐작', '?', '○'];
export function 단서있나(줄) {
  const s = String(줄 ?? '');
  return 단서들.some((c) => s.includes(c));
}

/** ● 잰 것 · ○ 정한 것 · ⚠ 못 잼 — 셋 중 하나가 붙어 있나 */
export const 표시들 = ['●', '○', '⚠', '◆', '못 잼', '못잼', '🖐'];
export function 표시있나(줄) {
  const s = String(줄 ?? '');
  return 표시들.some((c) => s.includes(c));
}

/** 라이브를 단정하는 줄인가 */
export function 라이브단정인가(줄) {
  const s = String(줄 ?? '');
  return /라이브|실측|배포됐|나갔다|\b(200|404|301|500)\b/.test(s);
}

/** 잰 시각이 붙어 있나 — 「방금」·「HH:MM」·「YYYY-MM-DD」 */
export function 잰시각있나(줄) {
  const s = String(줄 ?? '');
  return /방금|\b\d{1,2}:\d{2}\b|\d{4}-\d{2}-\d{2}/.test(s);
}

/* ── 보기 ────────────────────────────────────────────────────────────────── */

/** 예전 본문에서 같은 낱말+단위인데 값이 다른 줄을 찾는다 */
export function 어긋난곳찾기(짝, 예전줄들) {
  const 결과 = [];
  const re = new RegExp(
    짝.낱말.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*([0-9][0-9,]*)\\s*' + 짝.단위,
  );
  for (const l of 예전줄들) {
    const m = re.exec(l);
    if (!m) continue;
    const 옛 = m[1].replace(/,/g, '');
    if (옛 !== 짝.값) 결과.push({ 옛, 줄: l.trim().slice(0, 110) });
  }
  return 결과;
}

/** 그 숫자가 예전에 **단서와 함께** 적혀 있었나 */
export function 단서를뺐나(짝, 예전줄들) {
  const re = new RegExp(
    짝.낱말.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*' + 짝.값.replace(/(\d)(?=(\d{3})+$)/g, '$1,?') + '\\s*' + 짝.단위,
  );
  for (const l of 예전줄들) if (re.test(l) && 단서있나(l)) return l.trim().slice(0, 110);
  return null;
}

/* ── 돌리기 ──────────────────────────────────────────────────────────────── */

function 새줄들() {
  try {
    const d = execFileSync('git', ['diff', '--unified=0', '--', 메모], { cwd: 뿌리, encoding: 'utf8' });
    return d.split('\n').filter((l) => l.startsWith('+') && !l.startsWith('+++')).map((l) => l.slice(1));
  } catch { return []; }
}

function 재고알리기() {
  const 새 = 새줄들();
  if (!새.length) { console.log('✅ 메모에 새로 적은 줄이 없다 — 볼 것이 없다'); return 0; }

  const 온본문 = fs.readFileSync(path.join(뿌리, 메모), 'utf8').split('\n');
  const 새것 = new Set(새);
  const 예전 = 온본문.filter((l) => !새것.has(l));

  const 걸린것 = [];
  for (const 줄 of 새) {
    if (줄.trim().startsWith('·') && !/[0-9]/.test(줄)) continue;
    for (const 짝 of 숫자짝뽑기(줄)) {
      const 어긋 = 어긋난곳찾기(짝, 예전);
      if (어긋.length) 걸린것.push({ 종류: '㉮ 다른 숫자가 이미 있다', 줄, 짝, 근거: 어긋.slice(0, 2) });
      const 단 = 단서를뺐나(짝, 예전);
      if (단 && !단서있나(줄)) 걸린것.push({ 종류: '㉯ 단서를 빼고 옮겼다', 줄, 짝, 근거: [{ 옛: 짝.값, 줄: 단 }] });
    }
    if (라이브단정인가(줄) && !잰시각있나(줄) && /[0-9]/.test(줄)) {
      걸린것.push({ 종류: '㉰ 라이브를 단정하는데 잰 시각이 없다', 줄, 짝: null, 근거: [] });
    }
    /* 🔴 [㉲ — 2026-08-10 그날 바로 덧댐] **표시 없는 숫자를 막는다.**
       ㉮ 는 「같은 낱말」일 때만 잡는다. 그런데 실제로 틀린 자리가 그렇지 않았다 —
       6번은 **「받은 주소 23」**이라 적었고 나는 **「뉴스레터 23명」**이라 적었다. 낱말이 달라 안 걸렸다.
       ⭐ 낱말을 맞추려 들면 끝이 없다. 대신 **표시를 강제**한다 —
          ● 잰 것 · ○ 정한 것 · ⚠ 못 잼. 우리 강령에 이미 있는 표시다.
       ⛔ 「뉴스레터 23명」에 ● 를 붙이려면 **내가 재야 한다.** 못 쟀으면 ⚠ 를 붙일 수밖에 없다.
          그 한 글자가 「안 찾고 적는 것」을 막는다. */
    if (숫자짝뽑기(줄).length && !표시있나(줄)) {
      걸린것.push({ 종류: '㉲ 숫자에 표시(● 잰 것 · ○ 정한 것 · ⚠ 못 잼)가 없다', 줄, 짝: null, 근거: [] });
    }
  }

  console.log('\n# 🔒 적기 전에 찾았나\n');
  console.log(`  새로 적은 줄 ${새.length} · 걸린 것 ${걸린것.length}\n`);
  if (!걸린것.length) { console.log('✅ 걸린 것 없다.'); return 0; }

  for (const x of 걸린것) {
    console.log(`🔴 ${x.종류}`);
    console.log(`   내가 적은 것 — ${x.줄.trim().slice(0, 110)}`);
    for (const g of x.근거) console.log(`   이미 있는 것 — ${g.줄}`);
    console.log('');
  }
  console.log('⛔ 이 자는 글을 **안 고친다.** 위를 보고 사람이 정한다 —');
  console.log('   숫자가 바뀐 것인가, 내가 안 찾고 적은 것인가. ⭐ 바뀐 것이면 **잰 시각을 같이** 적는다.');
  console.log('⚠ 일부러 다르게 적는 것이면 그 줄에 **까닭 한 줄**을 붙이면 통과한다(⚠ 나 「고침:」).');
  return 1;
}

/* ── 자가시험 ────────────────────────────────────────────────────────────── */
function 자가시험() {
  let 통과 = 0; const 실패 = [];
  const T = (이름, 참) => { if (참) 통과++; else 실패.push(이름); };

  const 짝 = 숫자짝뽑기('뉴스레터 23명 · 기사 122편');
  T('낱말+숫자+단위를 뽑는다', 짝.length === 2 && 짝[0].낱말 === '뉴스레터' && 짝[0].값 === '23');
  T('쉼표를 지운다', 숫자짝뽑기('지면 4,966장')[0].값 === '4966');
  T('단위 없는 숫자는 안 뽑는다', 숫자짝뽑기('그냥 23 이다').length === 0);

  T('⚠ 를 단서로 본다', 단서있나('⚠ 뉴스레터 23명'));
  T('「못 잼」을 단서로 본다', 단서있나('받은 주소 못 잼'));
  T('맨숭한 줄은 단서가 없다', !단서있나('뉴스레터 23명'));

  T('라이브 단정을 알아본다', 라이브단정인가('/y/ 넷이 라이브 404'));
  T('잰 시각이 있으면 통과', 잰시각있나('방금 쟀습니다 — 200'));
  T('시각이 없으면 못 통과', !잰시각있나('라이브 404 입니다'));

  const 어긋 = 어긋난곳찾기({ 낱말: '뉴스레터', 값: '23', 단위: '명' }, ['뉴스레터 0명 ● 로 다시 쟀다']);
  T('㉮ 같은 낱말 다른 숫자를 잡는다', 어긋.length === 1 && 어긋[0].옛 === '0');
  T('㉮ 같은 숫자는 안 잡는다',
    어긋난곳찾기({ 낱말: '뉴스레터', 값: '23', 단위: '명' }, ['뉴스레터 23명']).length === 0);

  T('㉯ 단서를 뺀 것을 잡는다',
    !!단서를뺐나({ 낱말: '뉴스레터', 값: '23', 단위: '명' }, ['⚠ 뉴스레터 23명 — 로컬 store']));
  T('㉯ 단서가 없던 것은 안 잡는다',
    !단서를뺐나({ 낱말: '뉴스레터', 값: '23', 단위: '명' }, ['뉴스레터 23명']));

  /* ㉲ — 표시 강제 */
  T('㉲ 표시 없는 숫자를 잡는다', !표시있나('뉴스레터 23명'));
  T('㉲ ● 가 붙으면 통과', 표시있나('뉴스레터 0명 ●'));
  T('㉲ ⚠ 가 붙으면 통과', 표시있나('⚠ 뉴스레터 23명 — 로컬 store'));
  T('㉲ ○ 가 붙으면 통과', 표시있나('2031 목표 1,660억 ○'));
  T('㉲ 숫자가 없으면 볼 것도 없다', 숫자짝뽑기('오늘은 개봉 준비만 본다').length === 0);

  console.log(`\n자가시험 ${통과}개 통과${실패.length ? ' · 실패 ' + 실패.length : ''}`);
  for (const f of 실패) console.log('  🔴 ' + f);
  return 실패.length ? 1 : 0;
}

const 내가실행됐다 = process.argv[1] && process.argv[1].endsWith('check-before-i-write.mjs');
if (내가실행됐다) {
  process.exitCode = process.argv.includes('--자가시험') ? 자가시험() : 재고알리기();
}
