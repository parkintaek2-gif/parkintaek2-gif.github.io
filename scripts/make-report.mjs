#!/usr/bin/env node
/**
 * 업무보고를 만든다 — **작업목록 + 가로 진도 막대**.
 *
 * 사장님 지시(2026-08-08 08:2x):
 *   *「업무보고때 작업목록을 만들고 진도율을 가로축을 그래프로 만들자.
 *     지금 업무보고는 너무 단편적이어서 확 와닿지 않아」*
 *
 * ## 🔴 막대마다 **현재/목표**가 있어야 한다
 *
 *   ⛔ %만 적으면 그건 느낌이다. 「80% 됐습니다」는 아무 뜻이 없다.
 *   ✅ **「2,525 / 2,525장」** 처럼 **센 수와 세야 할 수**를 같이 적는다.
 *      그러면 사장님이 그 자리에서 되물을 수 있다 — 그게 보고다.
 *
 * ⚠ 진도를 손으로 적지 않는다. 잰 것을 `--실측` 파일에서 읽는다.
 *   못 잰 것은 **못 쟀다고 적는다.** 지어내지 않는다.
 *
 * 쓰는 법
 *   node scripts/make-report.mjs --실측 progress.json --낼곳 보고.md
 *   node scripts/make-report.mjs --selftest
 */

import fs from 'node:fs';

/* ────────────────────────────────────────────────────────── */

/**
 * 가로 막대 한 줄. **폭은 고정**이라 여러 줄이 나란히 읽힌다.
 * ⚠ 0%도 1%도 빈칸으로 보이면 「아직 아무것도 안 했다」와 구별이 안 된다.
 *   그래서 **0보다 크면 최소 한 칸**은 채운다.
 */
export function 막대(현재, 목표, 폭 = 24) {
  if (!Number.isFinite(현재) || !Number.isFinite(목표) || 목표 <= 0) return '─'.repeat(폭);
  const 비율 = Math.max(0, Math.min(1, 현재 / 목표));
  let 찬칸 = Math.round(비율 * 폭);
  if (비율 > 0 && 찬칸 === 0) 찬칸 = 1;
  if (비율 < 1 && 찬칸 === 폭) 찬칸 = 폭 - 1;  // 다 안 됐는데 꽉 차 보이지 않게
  return '█'.repeat(찬칸) + '░'.repeat(폭 - 찬칸);
}

/** 백분율. 못 재면 null — 「0%」로 적지 않는다. 0% 와 「못 쟀다」는 다르다 */
export function 퍼센트(현재, 목표) {
  if (!Number.isFinite(현재) || !Number.isFinite(목표) || 목표 <= 0) return null;
  return Math.round(Math.min(1, 현재 / 목표) * 100);
}

/** 「2,525 / 2,525장」 꼴 */
export function 수표기(현재, 목표, 단위 = '') {
  const ㄱ = (n) => (Number.isFinite(n) ? n.toLocaleString('ko-KR') : '?');
  return `${ㄱ(현재)} / ${ㄱ(목표)}${단위}`;
}

/** 한 줄 그리기 */
export function 한줄(일, 폭 = 24) {
  const p = 퍼센트(일.현재, 일.목표);
  const 표 = p === null ? '⬜ 못 쟀다' : `${String(p).padStart(3)}%`;
  return `${일.이름.padEnd(26)} ${막대(일.현재, 일.목표, 폭)} ${표}  ${수표기(일.현재, 일.목표, 일.단위 ?? '')}`;
}

/**
 * 여러 일의 **묶음 진도**. ⚠ %의 평균이 아니라 **합계 대비 합계**다.
 * ⛔ %를 평균 내면 작은 일 하나가 큰 일 하나와 같은 무게가 된다.
 *   「기사 1편 더 쓴 것」과 「지면 2,525장 고친 것」이 같아지면 그 수는 거짓이다.
 */
export function 묶음진도(일들) {
  const 잰것 = 일들.filter((x) => Number.isFinite(x.현재) && Number.isFinite(x.목표) && x.목표 > 0);
  if (!잰것.length) return null;
  const 현 = 잰것.reduce((a, b) => a + Math.min(b.현재, b.목표) * (b.무게 ?? 1), 0);
  const 목 = 잰것.reduce((a, b) => a + b.목표 * (b.무게 ?? 1), 0);
  return { 현재: 현, 목표: 목, 퍼센트: 퍼센트(현, 목), 못잰것: 일들.length - 잰것.length };
}

/* ────────────────────────────────────────────────────────── */

function 셀프테스트() {
  const 검사 = [];
  const 봄 = (이름, 본것, 바란것) => {
    const 같다 = JSON.stringify(본것) === JSON.stringify(바란것);
    검사.push(같다);
    console.log(`  ${같다 ? '✅' : '⛔'} ${이름}${같다 ? '' : `  본 것 ${JSON.stringify(본것)}`}`);
  };

  봄('다 됐으면 꽉 찬다', 막대(10, 10, 4), '████');
  봄('반이면 반이다', 막대(5, 10, 4), '██░░');
  봄('⭐ 0 이면 한 칸도 안 찬다 — 0과 조금은 다르다', 막대(0, 10, 4), '░░░░');
  봄('⭐ 아주 조금이라도 했으면 한 칸은 찬다', 막대(1, 1000, 4), '█░░░');
  봄('⭐ 99.9% 는 꽉 차 보이지 않는다', 막대(999, 1000, 4), '███░');
  봄('목표가 0 이면 못 그린다', 막대(1, 0, 4), '────');
  봄('넘겨도 꽉 찬 것까지다', 막대(20, 10, 4), '████');

  봄('백분율', 퍼센트(1, 4), 25);
  봄('⭐ 못 재면 null — 0% 가 아니다', 퍼센트(1, 0), null);
  봄('넘겨도 100 까지', 퍼센트(20, 10), 100);

  봄('수표기', 수표기(2525, 2525, '장'), '2,525 / 2,525장');

  const 일들 = [{ 이름: 'ㄱ', 현재: 2525, 목표: 2525 }, { 이름: 'ㄴ', 현재: 0, 목표: 1 }];
  봄('⭐ 묶음은 %의 평균이 아니라 합계 대비 합계다', 묶음진도(일들).퍼센트, 100);
  봄('못 잰 것은 세어 둔다', 묶음진도([...일들, { 이름: 'ㄷ', 현재: null, 목표: null }]).못잰것, 1);
  봄('다 못 재면 null', 묶음진도([{ 이름: 'ㄱ', 현재: null, 목표: null }]), null);

  const 실패 = 검사.filter((x) => !x).length;
  console.log(`\n검사 ${검사.length}개 · 실패 ${실패}개`);
  process.exit(실패 ? 1 : 0);
}

if (process.argv.includes('--selftest')) 셀프테스트();
