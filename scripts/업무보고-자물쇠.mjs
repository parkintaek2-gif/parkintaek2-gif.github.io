#!/usr/bin/env node
/**
 * 업무보고-자물쇠.mjs — **업무보고를 안 내면 배포를 못 한다. 세 자리 다.**
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 [2026-09-19 · 사장님] **「자물쇠를 세 세션에 다 채워 의무적으로 소통하고
 *    업무보고 하게 해」**
 *
 * [왜 필요했나 — 재 보니 자물쇠가 «하나뿐»이었다]
 *   · 매시 소통은 자물쇠가 있었다. 그런데 총괄(5번)만 대상에서 빠져 있었다(오늘 고쳤다).
 *   · 업무보고는 **자물쇠가 없었다.** `check-6번-15시보고-자물쇠.mjs` 가 있긴 한데
 *     ① 이름이 접힌 자리(6번)이고 ② 배포 관문이 그 자를 «부르지 않는다»(0곳).
 *     ⇒ 안 내도 아무 일도 안 일어났다. 자물쇠가 아니라 «자물쇠라고 적힌 종이»였다.
 *
 * [무엇을 잠그나]
 *   배포를 잠근다. ⛔ 커밋은 안 막는다 — 커밋을 막으면 «보고를 적는 일»까지 막힌다.
 *
 * [무엇을 보고로 세나]
 *   docs/세션간-메모.md 의  `## [업무보고] N번 YYYY-MM-DD …`
 *   ⚠ 이 꼴은 collect-1600-report.mjs 가 찾는 꼴과 «같다». 두 자가 다른 꼴을 찾으면
 *     보고를 냈는데 자물쇠가 안 풀리거나, 그 반대가 된다.
 *
 * [지키는 것]
 *   ⚠ 업무시간 밖에는 안 잠근다. 자는 자리를 벌주지 않는다.
 *     🔴 [2026-09-19 · 사장님 「너는 24시간 풀로 일해야해」] 업무시간은 «자리마다 다르다» —
 *       5번(총괄) 24시간 · 1번·2번 07~21시. 그래서 밤에도 총괄에게는 걸린다.
 *   ⚠ 보고 시각 전에는 안 잠근다 — 「기다림」과 「안 낸 것」은 다르다.
 *   ⛔ 열 글자 미만은 보고가 아니다. 제목만 적고 비우는 것을 통과시키지 않는다.
 *   ⛔ 울타리(```) 안의 «보기»를 진짜 보고로 세지 않는다 — 이웃 자가 그 함정에 빠져
 *     「다 들어왔다」는 거짓 초록을 낸 적이 있다. 빨강보다 나쁘다.
 *
 * 쓰는 법
 *   node scripts/업무보고-자물쇠.mjs                 지금 누가 잠겼나
 *   node scripts/업무보고-자물쇠.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 도는자리 } from './lib/도는자리.mjs';
import { 울타리지우기, 시각글 } from './매시소통-자물쇠.mjs';
/* 업무시간은 자리마다 다르다 — 5번 24시간 · 나머지 07~21시 (work-hours.mjs 가 정본) */
import { 자리업무중인가 } from './lib/work-hours.mjs';

const 뿌리 = path.resolve(import.meta.dirname, '..');
export const 메모길 = path.join(뿌리, 'docs/세션간-메모.md');

/** 자물쇠가 걸리는 자리 — 사장님 「세 세션에 다 채워」. 목록은 정본에서 읽는다 */
export const 걸리는자리 = [...도는자리];

/** 보고를 내야 하는 시각(시). 사장님 — 업무보고 16시 한 번. 재료는 15시에 준비한다 */
export const 보고시 = 16;

/** ⛔ 열 글자 미만은 보고가 아니다 */
export const 적어도글자 = 10;

/** 오늘(KST) YYYY-MM-DD. ⚠ 이 PC 는 이미 KST 다 — toISOString() 을 쓰지 않는다 */
export function 오늘글(d = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
}

/**
 * 메모에서 업무보고를 읽는다.
 * 찾는 꼴 — `## [업무보고] 5번 2026-09-19 제목…`  (자리와 날짜 사이 순서는 바뀌어도 받는다)
 */
export function 보고읽기(글) {
  const 벗긴것 = 울타리지우기(글 ?? '');
  const 결 = [];
  const 자 = /^##\s*\[\s*업무보고\s*\][^\n]*$/gim;
  let m;
  while ((m = 자.exec(벗긴것))) {
    const 줄 = m[0];
    const 자리 = (줄.match(/(\d)\s*번/) || [])[1];
    const 날짜 = (줄.match(/(\d{4}-\d{2}-\d{2})/) || [])[1];
    /* 제목 뒤 본문 — 다음 「## 」 앞까지를 그 보고의 몸으로 본다 */
    const 뒤 = 벗긴것.slice(m.index + 줄.length);
    const 끝 = 뒤.search(/^##\s/m);
    const 몸 = (끝 < 0 ? 뒤 : 뒤.slice(0, 끝)).trim();
    if (자리) 결.push({ 자리: 자리 + '번', 날짜: 날짜 || null, 몸 });
  }
  return 결;
}

export function 메모에서읽기(길 = 메모길) {
  if (!fs.existsSync(길)) return [];
  return 보고읽기(fs.readFileSync(길, 'utf8'));
}

/** 그 자리가 오늘 보고를 냈나 */
export function 오늘냈나(보고들, 누구, 이제 = new Date()) {
  const 오늘 = 오늘글(이제);
  return (보고들 || []).some((x) => x.자리 === 누구
    && (x.날짜 === 오늘 || x.날짜 == null)          /* 날짜를 안 적었으면 오늘 것으로 본다(관대하게) */
    && String(x.몸 || '').trim().length >= 적어도글자);
}

/**
 * 자물쇠 판정.
 * @returns {{잠겼나:boolean, 까닭:string, 푸는법?:string}}
 */
export function 잠겼나(누구, 보고들, 이제 = new Date()) {
  const 그 = String(누구 ?? '').trim();
  if (!걸리는자리.includes(그)) {
    return { 잠겼나: false, 까닭: 그 + ' 는 이 자물쇠의 대상이 아니다' };
  }
  if (!자리업무중인가(그, 이제)) {
    return { 잠겼나: false, 까닭: '업무시간 밖이라 안 잠근다 (' + 그 + ' 는 07~21시)' };
  }
  if (이제.getHours() < 보고시) {
    return { 잠겼나: false, 까닭: '아직 ' + 보고시 + '시 전이다 — 기다리는 것은 흠이 아니다' };
  }
  if (오늘냈나(보고들, 그, 이제)) {
    return { 잠겼나: false, 까닭: 오늘글(이제) + ' 업무보고를 냈다' };
  }
  return {
    잠겼나: true,
    까닭: 그 + ' 가 ' + 오늘글(이제) + ' 업무보고를 안 냈다 (' + 보고시 + '시까지다)',
    푸는법: 'docs/세션간-메모.md 에 「## [업무보고] ' + 그 + ' ' + 오늘글(이제) + ' — 한 줄 요약」으로 '
      + '적고 커밋·푸시하십시오. 1.한 것(숫자로) 2.못한 것(왜·언제까지) 3.막힌 것',
  };
}

function 낸다() {
  const 이제 = new Date();
  const 보고들 = 메모에서읽기();
  console.log('■ 업무보고 자물쇠 — ' + 시각글(이제));
  let 잠긴수 = 0;
  for (const 자리 of 걸리는자리) {
    const r = 잠겼나(자리, 보고들, 이제);
    if (r.잠겼나) { 잠긴수 += 1; console.log('  🔒 ' + 자리 + '  ' + r.까닭); }
    else console.log('  ✅ ' + 자리 + '  ' + r.까닭);
  }
  console.log('\n잰 자리 ' + 걸리는자리.length + ' · 잠긴 자리 ' + 잠긴수);
  if (잠긴수) console.log('🔒 잠긴 자리는 «배포»를 못 합니다. 보고를 내면 그 자리에서 풀립니다.');
  return 잠긴수;
}

/* ── 자가시험 ───────────────────────────────────────────────────────────── */
function 자가시험() {
  let 통과 = 0, 실패 = 0;
  const 본다 = (말, 참) => { if (참) { 통과 += 1; console.log('  ✅ ' + 말); } else { 실패 += 1; console.log('  ✕ ' + 말); } };

  const 낮 = new Date(2026, 8, 19, 17, 0);
  const 아침 = new Date(2026, 8, 19, 10, 0);
  const 밤 = new Date(2026, 8, 19, 23, 0);
  const 글 = ['## [업무보고] 5번 2026-09-19 — 오늘 한 것',
    '1. 한 것 — 궁합 눈금을 하나로 맞췄다', ''].join('\n');

  본다('🔴 보고를 읽는다', 보고읽기(글).length === 1 && 보고읽기(글)[0].자리 === '5번');
  본다('🔴 안 내면 잠긴다', 잠겼나('1번', [], 낮).잠겼나 === true);
  본다('🔓 냈으면 안 잠긴다', 잠겼나('5번', 보고읽기(글), 낮).잠겼나 === false);
  본다('🔴 잠글 때 푸는 법을 함께 준다', /업무보고/.test(잠겼나('1번', [], 낮).푸는법 || ''));
  본다('⚠ 보고 시각 전에는 안 잠근다 — 기다림은 흠이 아니다', 잠겼나('1번', [], 아침).잠겼나 === false);
  본다('⚠ 밤에는 1번·2번을 안 잠근다 — 자는 자리를 벌주지 않는다', 잠겼나('1번', [], 밤).잠겼나 === false);
  본다('🔴 밤에도 총괄(5번)은 잠긴다 — 사장님 「너는 24시간 풀로 일해야해」', 잠겼나('5번', [], 밤).잠겼나 === true);
  본다('🔓 밤이라도 총괄이 냈으면 안 잠긴다', 잠겼나('5번', 보고읽기(글), 밤).잠겼나 === false);
  본다('⛔ 제목만 있고 비면 보고로 안 센다',
    잠겼나('5번', 보고읽기('## [업무보고] 5번 2026-09-19\n\n'), 낮).잠겼나 === true);
  본다('⛔ 울타리 안의 보기를 보고로 세지 않는다',
    보고읽기(['```', '## [업무보고] 1번 2026-09-19 보기입니다', '본문이 열 글자는 넘습니다', '```'].join('\n')).length === 0);
  본다('⛔ 접힌 자리는 잠그지 않는다', 잠겼나('6번', [], 낮).잠겼나 === false);
  본다('🔴 세 자리가 다 걸린다 — 사장님 「세 세션에 다 채워」',
    도는자리.every((자리) => 걸리는자리.includes(자리)));
  본다('🔴 총괄도 빠지지 않는다', 걸리는자리.includes('5번'));
  본다('⛔ 어제 보고로 오늘을 때우지 못한다',
    잠겼나('5번', 보고읽기('## [업무보고] 5번 2026-09-18 — 어제 것\n어제 한 일입니다'), 낮).잠겼나 === true);

  console.log(`\n══ 자가시험 통과 ${통과} · 실패 ${실패} ══ ` + (실패 ? '🔴' : '✅'));
  return 실패 === 0;
}

const 내가실행됐다 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (내가실행됐다) {
  if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 0 : 1);
  낸다();
}
