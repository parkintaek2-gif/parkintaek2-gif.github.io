#!/usr/bin/env node
/**
 * 증자 형태 분류 시험.
 *
 * ⚠ 시험값은 **2026-08-05 에 DART 에서 실제로 받은 16종**이다. 지어내지 않았다.
 *   810개사 7,751행에서 뽑은 서로 다른 값 전부다.
 *
 * ⭐ **표에 없는 값이 들어오면 실패한다.** 그래야 새 형태가 생겼을 때 조용히
 *   「기타」로 묻히지 않는다.
 */
import { 분류, 형태표, 액면미달, 갈래별합 } from '../src/lib/issuance.mjs';

/** 실제 자료에서 본 16종 (「-」 포함) */
const 실측어휘 = [
  '-', '무상감자', '무상증자', '상환권행사', '신주인수권행사', '유상감자',
  '유상증자(일반공모)', '유상증자(제3자배정)', '유상증자(주주배정)', '유상증자(주주우선공모)',
  '전환권행사', '주식매수선택권행사', '주식배당', '주식분할', '출자전환', '현물출자',
];

let 실패 = 0;
const 확인 = (조건, 이름, 실제) => {
  if (!조건) { 실패++; console.log(`  ✕ ${이름}${실제 !== undefined ? ` — ${JSON.stringify(실제)}` : ''}`); }
};

console.log('증자 형태 분류');

/* ── ① 실측 어휘가 **하나도 빠짐없이** 분류돼야 한다 ─────────── */
for (const w of 실측어휘) {
  const c = 분류(w);
  확인(c !== null, `「${w}」가 분류된다`, c);
}

/* ── ② 「-」는 미기재다. 버리지 않는다 ───────────────────────── */
확인(분류('-').미기재 === true, '「-」는 미기재로 표시된다');
확인(분류('').미기재 === true, '빈 문자열도 미기재');
확인(분류(null).미기재 === true, 'null 도 미기재');
확인(분류('-').신주 === null, '미기재의 신주 여부는 null (0 이 아니다)');

/* ── ③ ⭐ 모르는 값은 **null 이어야 한다.** 「기타」로 뭉치면 안 된다 ─ */
확인(분류('신종증자방식') === null, '표에 없는 값은 null 이다', 분류('신종증자방식'));

/* ── ④ 갈래가 뜻대로 붙었나 ─────────────────────────────────── */
const 갈래 = (w) => 분류(w)?.갈래;
확인(갈래('유상증자(제3자배정)') === '현금', '제3자배정은 현금');
확인(갈래('전환권행사') === '전환', '전환권행사는 전환');
확인(갈래('신주인수권행사') === '전환', '신주인수권행사는 전환');
확인(갈래('무상증자') === '무상', '무상증자는 무상');
확인(갈래('주식매수선택권행사') === '임직원', '스톡옵션은 임직원');
확인(갈래('무상감자') === '감소', '무상감자는 감소');

/* ── ⑤ ⭐ 주식분할은 주식수가 늘어도 **희석이 아니다** ────────── */
확인(분류('주식분할').신주 === 0, '주식분할의 신주는 0 (액면분할로 순위가 뒤집히면 안 된다)');
확인(분류('무상감자').신주 === -1, '무상감자는 −1');
확인(분류('상환권행사').신주 === -1, '상환권행사는 −1');

/* ── ⑥ 액면미달 — **모르는 것을 false 로 만들지 않는다** ─────── */
확인(액면미달({ 발행가: 100, 액면가: 500 }) === true, '발행가 100 < 액면 500 → true');
확인(액면미달({ 발행가: 1000, 액면가: 500 }) === false, '발행가 1000 > 액면 500 → false');
확인(액면미달({ 발행가: null, 액면가: 500 }) === null, '발행가가 없으면 null');
확인(액면미달({ 발행가: 100, 액면가: null }) === null, '액면가가 없으면 null');
확인(액면미달(null) === null, '행이 없어도 죽지 않는다');

/* ── ⑦ 갈래별 합 — 수량 없는 행은 **빼고** 센다 ───────────────── */
{
  const 합 = 갈래별합([
    { 형태원문: '유상증자(제3자배정)', 수량: 100 },
    { 형태원문: '유상증자(일반공모)', 수량: 50 },
    { 형태원문: '전환권행사', 수량: 30 },
    { 형태원문: '전환권행사', 수량: null },      // ← 빠져야 한다
    { 형태원문: '없는형태', 수량: 7 },
  ]);
  확인(합.get('현금') === 150, '현금 갈래 합 150', 합.get('현금'));
  확인(합.get('전환') === 30, '수량 null 은 빼고 센다', 합.get('전환'));
  확인(합.get('(못 알아봄)') === 7, '못 알아본 것도 **세어진다**', 합.get('(못 알아봄)'));
  확인(갈래별합([]).size === 0, '빈 배열에 죽지 않는다');
  확인(갈래별합(null).size === 0, 'null 에도 죽지 않는다');
}

/* ── ⑧ 표 자체 점검 — 영문명이 비면 화면에 빈칸이 나간다 ───────── */
for (const [k, v] of Object.entries(형태표)) {
  확인(typeof v.en === 'string' && v.en.length > 3, `「${k}」에 영문명이 있다`, v.en);
  확인([1, 0, -1].includes(v.신주), `「${k}」의 신주 값이 1·0·−1 중 하나`, v.신주);
}

if (실패) { console.error(`\n${실패} 실패`); process.exit(1); }
console.log(`  ${실측어휘.length + 22 + Object.keys(형태표).length * 2} 통과 · 0 실패`);

/* ══════════════════════════════════════════════════════════════════
 * 발행가 범위 — **단위 오기를 뺀다. 고치지 않는다**
 *
 * ⚠ 아래 값은 2026-08-05 에 DART 에서 실제로 본 것이다.
 *   아주스틸 액면 50억·발행가 1,666억 · 음수 발행가 −22.95억.
 * ══════════════════════════════════════════════════════════════════ */
{
  const { 발행가정상, 가중발행가 } = await import('../src/lib/issuance.mjs');
  let 실패2 = 0;
  const 봄 = (조건, 이름, 실제) => { if (!조건) { 실패2++; console.log(`  ✕ ${이름} — ${JSON.stringify(실제)}`); } };

  console.log('발행가 범위');
  봄(발행가정상(4525) === true, '중앙값 4,525원은 정상', 발행가정상(4525));
  봄(발행가정상(500) === true, '500원 정상');
  봄(발행가정상(2_500_000) === true, '분할 전 삼성전자 250만원도 정상', 발행가정상(2_500_000));
  봄(발행가정상(166_660_000_000) === false, '⭐ 아주스틸 1,666억은 뺀다', 발행가정상(166_660_000_000));
  봄(발행가정상(-2_295_000_000) === false, '⭐ 음수는 뺀다', 발행가정상(-2_295_000_000));
  봄(발행가정상(0) === false, '0 은 뺀다');
  봄(발행가정상(null) === null, '없는 것은 null (false 가 아니다)', 발행가정상(null));
  봄(발행가정상(NaN) === false, 'NaN 은 뺀다');

  /* 가중평균 — 깨진 행 하나가 평균을 통째로 날리면 안 된다 */
  const r = 가중발행가([
    { 발행가: 1000, 수량: 100 },
    { 발행가: 2000, 수량: 100 },
    { 발행가: 166_660_000_000, 수량: 100 },  // ← 빠져야 한다
    { 발행가: null, 수량: 100 },              // ← 없음
  ]);
  봄(r.값 === 1500, '깨진 행을 빼고 1,500원', r.값);
  봄(r.뺌 === 1, '뺀 행 1', r.뺌);
  봄(r.없음 === 1, '없는 행 1', r.없음);
  봄(가중발행가([]).값 === null, '빈 배열은 null');
  봄(가중발행가(null).값 === null, 'null 에도 죽지 않는다');

  if (실패2) { console.error(`\n${실패2} 실패`); process.exit(1); }
  console.log('  13 통과 · 0 실패');
}
