#!/usr/bin/env node
/**
 * check-open-asks.mjs — **내가 낸 물음 가운데 «아직 안 닫힌» 것.**
 * ────────────────────────────────────────────────────────────────────────────
 * [🔴 왜 만드나 — 1번이 내 자의 결함을 먼저 알아차렸다 (2026-09-03 20:0x)]
 *
 *   1번 원문:
 *   > 「`tools/check-hourly-sync.mjs` 는 "커밋이 있었나"만 보고 "나한테 온 질문에
 *   >  답했나"는 안 봅니다 — **그 차이가 오늘 사고입니다**」
 *
 *   ⛔ **내 재촉도 똑같았다.** 나는 「마지막 커밋이 몇 시간 전인가」로 재서
 *      1번을 「16:10 이후 무응답」이라 세 번 적었다. 그 사이 1번은 다른 일을 하고 있었다.
 *      **커밋 시각은 「답했나」의 자가 아니다.** 커밋이 있어도 물음은 열려 있을 수 있고,
 *      커밋이 없어도 답은 왔을 수 있다(실제로 1번은 `## [` 머리 없이 답을 붙였고
 *      나는 머리만 훑다가 그 답을 «못 봤다»).
 *
 * [무엇을 재나]
 *   메모에서 `[물음→N번]` 표를 찾아, 그 뒤로 그 유닛이 «무엇이든 냈나»를 본다.
 *
 * [⛔ 이 자가 «못» 하는 것 — 먼저 적어 둔다]
 *   · 「답의 «내용»이 그 물음을 닫았나」는 **판정할 수 없다.** 사람이 읽어야 한다.
 *     그래서 이 자는 「닫혔다」고 말하지 않고 **「그 뒤에 냈다 / 아직 아무것도 없다」**만 말한다.
 *   · 표(`[물음→N번]`)를 안 붙인 물음은 못 본다. 그래서 내가 물음을 낼 때 그 표를 붙인다.
 *     ⛔ 남에게 규칙을 요구하지 않는다 — **내 물음에 내가 붙인다.** 그것만으로 값이 생긴다.
 *   ⭐ 「모르는 것을 모른다고 내는 자」가 「다 안다고 내는 자」보다 낫다.
 *
 * [쓰는 법]
 *   node scripts/check-open-asks.mjs
 *   node scripts/check-open-asks.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 메모들 = [
  path.join(뿌리, 'docs', '세션간-메모.md'),
  path.join(뿌리, '..', 'klifemap', 'docs', '1번-4번-메모.md'),
];

/**
 * `[물음→6번] …` 을 찾는다.
 * ⚠ 화살표를 사람이 여러 꼴로 쓴다 — `→` · `->` · `>`. 다 받는다.
 */
export function 물음찾기(글) {
  const 것들 = [];
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  for (let i = 0; i < 줄들.length; i += 1) {
    const m = /\[물음\s*(?:→|->|>)\s*([1-6])번\]\s*(.*)$/.exec(줄들[i]);
    if (!m) continue;
    것들.push({ 줄번호: i + 1, 유닛: m[1] + '번', 물음: m[2].trim().slice(0, 120) });
  }
  return 것들;
}

/**
 * 그 유닛이 «그 줄 뒤로» 무엇이든 냈나.
 * ⛔ 「답했나」가 아니다 — 「냈나」다. 그 차이를 이름에 남긴다.
 */
export function 뒤에냈나(글, 줄번호, 유닛) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  for (let i = 줄번호; i < 줄들.length; i += 1) {
    /* `## [6번 → …]` 이나 `[진행] 6번` 이나 `[6번]` */
    if (new RegExp('\\[\\s*' + 유닛 + '\\s*(?:→|->|>)').test(줄들[i])) return { 냈나: true, 줄번호: i + 1 };
    if (new RegExp('\\[진행\\]\\s*' + 유닛).test(줄들[i])) return { 냈나: true, 줄번호: i + 1 };
    if (new RegExp('^##\\s*\\[' + 유닛).test(줄들[i])) return { 냈나: true, 줄번호: i + 1 };
  }
  return { 냈나: false };
}

function 자가시험() {
  let 흠 = 0; let 잰수 = 0;
  const 본다 = (이름, 참) => { 잰수 += 1; if (참) console.log(`  ✅ ${이름}`); else { console.log(`  🔴 ${이름}`); 흠 += 1; } };

  본다('물음 표를 찾는다', 물음찾기('[물음→6번] 문턱을 정해 주십시오')[0]?.유닛 === '6번');
  본다('-> 꼴도 받는다', 물음찾기('[물음->1번] 이것을 하시겠습니까')[0]?.유닛 === '1번');
  본다('물음 글도 담는다', 물음찾기('[물음→6번] 문턱')[0]?.물음 === '문턱');
  본다('표가 없으면 못 본다 — 이 한계를 못박아 둔다',
    물음찾기('6번께 문턱을 여쭙니다').length === 0);
  본다('여럿을 다 찾는다',
    물음찾기('[물음→6번] 가\n아무 말\n[물음→1번] 나').length === 2);
  본다('7번은 없다 — 1~6 만 받는다', 물음찾기('[물음→7번] 가').length === 0);

  const 글 = '[물음→6번] 문턱\n중간 줄\n## [6번 → 5번] 20:12 매시 소통';
  본다('그 뒤에 냈으면 알아본다', 뒤에냈나(글, 1, '6번').냈나 === true);
  본다('아직 아무것도 없으면 «없다»고 한다',
    뒤에냈나('[물음→6번] 문턱\n아무 말', 1, '6번').냈나 === false);
  /* ⛔ 물음 «앞»의 글을 답으로 세면 안 된다 — 그것이 이 자의 심장이다 */
  본다('⭐ 물음 «앞»에 있던 글은 답으로 세지 않는다',
    뒤에냈나('## [6번 → 5번] 18:16\n[물음→6번] 문턱', 2, '6번').냈나 === false);
  본다('[진행] 꼴도 알아본다',
    뒤에냈나('[물음→3번] 가\n[진행] 3번 20:03 했다', 1, '3번').냈나 === true);

  console.log(흠 ? `\n🔴 자가시험 ${잰수}가지 중 ${흠}가지 틀렸다` : `\n✅ 자가시험 ${잰수}가지 다 맞다`);
  return 흠;
}

function main() {
  const 인자 = process.argv.slice(2);
  console.log('# 내가 낸 물음 가운데 아직 안 닫힌 것\n');
  const 흠 = 자가시험();
  if (인자.includes('--자가시험')) process.exit(흠 ? 1 : 0);
  if (흠) { console.log('\n⛔ 자가시험이 틀렸다. 재지 않는다.'); process.exit(1); }

  let 총물음 = 0; let 안낸것 = 0; const 줄들 = [];
  const 서로다른 = new Set();  /* 유닛+물음 — 채널이 둘이라 줄 수와 다르다 */
  for (const 길 of 메모들) {
    if (!fs.existsSync(길)) {
      줄들.push(`⬜ 못 쟀다 — ${path.basename(길)} 이 없다`);
      continue;
    }
    const 글 = fs.readFileSync(길, 'utf8');
    const 것들 = 물음찾기(글);
    총물음 += 것들.length;
    for (const q of 것들) 서로다른.add(q.유닛 + '|' + q.물음);
    줄들.push(`\n■ ${path.basename(길)} — 물음 표 ${것들.length}개`);
    for (const q of 것들) {
      const r = 뒤에냈나(글, q.줄번호, q.유닛);
      if (r.냈나) {
        줄들.push(`   ✅ ${q.유닛}  «그 뒤에 냈다»  ${q.물음}`);
      } else {
        안낸것 += 1;
        줄들.push(`   🔴 ${q.유닛}  «아직 아무것도 없다»  ${q.물음}`);
      }
    }
  }

  for (const l of 줄들) console.log(l);

  if (!총물음) {
    console.log('\n⬜ **물음 표가 하나도 없다.**');
    console.log('   ⛔ 「물음이 없다」가 아니다 — 표(`[물음→N번]`)를 안 붙였을 뿐일 수 있다.');
    console.log('   ✅ 앞으로 물음을 낼 때 그 표를 붙인다. 그러지 않으면 이 자는 «늘 통과하는 자»가 된다.');
    process.exit(0);
  }

  /*
   * ⛔ 두 채널에 «같은 물음»을 올린다. 그래서 합계를 그대로 내면 두 배로 보인다.
   *   오늘 하루 내내 「행 수를 진짜 수라고 부르지 않는다」를 지켜 왔는데
   *   이 자의 첫판이 바로 그 잘못을 했다 — 6개를 12개로 냈다.
   * ✅ 서로 다른 물음을 따로 센다. 열쇠는 「유닛 + 물음 글」이다.
   */
  console.log(`\n줄 수 ${총물음}개 · 서로 다른 물음 **${서로다른.size}개** (채널 둘에 같은 것을 올린다)`);
  console.log(`   그 뒤에 낸 것 ${총물음 - 안낸것}줄 · 아직 아무것도 없는 것 ${안낸것}줄`);
  console.log('\n⛔ **이 자는 「답했나」를 판정하지 않는다.** 「그 뒤에 무엇이든 냈나」만 본다 —');
  console.log('   답의 «내용»이 그 물음을 닫았는지는 사람이 읽어야 한다.');
  console.log('   ⭐ 그래도 「마지막 커밋이 몇 시간 전인가」보다는 낫다. 1번이 그 차이를 알려 줬다.');
  /* ⚠ 막지 않는다 — 재촉은 사람이 할 일이고, 이 자는 «무엇을 재촉할지»를 알려 준다 */
  process.exit(0);
}

if (process.argv[1] && process.argv[1].endsWith('check-open-asks.mjs')) main();
