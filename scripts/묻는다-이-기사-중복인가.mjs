#!/usr/bin/env node
/**
 * 묻는다-이-기사-중복인가.mjs — **손으로 쓴 기사도 같은 중복 검사를 거치게 한다.**
 *
 * ── 🔴 왜 만드나 (2026-10-16) ──────────────────────────────────────────
 * 사장님 —
 *   「**롤드컵 기사 아침에 준 것과 같은 내용을 주면 어떡하나? 앞으로 중복되지 않게 잘해.
 *     주제도 같고, 경기도 같으면 중복 기사잖아**」
 *
 * 재 보니 **중복 장치는 제대로 일하고 있었다.**
 *
 *   10:00  중부매일 회차가 썼다 — 「'칸나' 김창동의 카르민 코프, 롤드컵 개막전서 C9에 역전승」
 *   14:00  회차가 또 썼다 → 수집기가 «같은 경기»로 막았다  ✅
 *   12:xx  🔴 **내가 손으로 같은 기사를 써서 사장님께 드렸다** — 아무것도 안 거쳤다
 *
 * ⭐ **구멍은 장치가 아니라 나였다.** 수집기를 거치는 글만 검사를 받고,
 *   내가 손으로 쓴 글은 그 검사를 통째로 건너뛴다. 그래서 같은 자리를 또 밟는다.
 *
 * ⇒ 수집기가 쓰는 «바로 그 함수»를 불러 쓴다. 검사를 두 벌로 만들지 않는다 —
 *   두 벌이면 한쪽만 고쳐져 또 어긋난다.
 *
 * 쓰는 법
 *   node scripts/묻는다-이-기사-중복인가.mjs --글 docs/기사-….txt
 *   node scripts/묻는다-이-기사-중복인가.mjs --제목 "…" --본문 docs/….txt
 *   node scripts/묻는다-이-기사-중복인가.mjs --자가시험
 *
 * ⛔ 「아니다」가 나와도 «사람이» 한 번 더 본다. 이 자는 낱말로만 잰다.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  소재낱말, 같은경기인가, 같은소재인가, 같은소재인가_소재로, 자국소재, 안보낸자국인가,
} from './collect-jbnews-sports-articles.mjs';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
const 뿌리 = path.resolve(여기, '..');
const 자국방 = path.join(뿌리, 'docs', '고정업무-마커', '중부매일-스포츠-보낸자국');

/** 글 파일에서 제목과 본문을 가른다 — 첫 줄이 제목, 나머지가 본문 */
export function 제목과본문(글) {
  const 줄 = String(글 ?? '').split(/\r?\n/);
  let i = 0;
  while (i < 줄.length && !줄[i].trim()) i += 1;
  /* 「[제목] …」 꼴도 받는다 — 데스킹을 거친 글이 그렇게 생겼다 */
  let 제목 = (줄[i] ?? '').trim();
  const m = /^\[제목\]\s*(.*)$/.exec(제목);
  if (m) 제목 = m[1].trim();
  if (!제목 && 줄[i + 1]) 제목 = (줄[i + 1] ?? '').trim();
  return { 제목, 본문: 줄.slice(i + 1).join('\n') };
}

/** 자국 하나에서 제목을 뽑는다 */
export function 자국제목(글) {
  const 줄 = String(글 ?? '').split(/\r?\n/).find((l) => /^\[(스포츠|안보냄)\]|^\[스포츠\]/.test(l.trim()));
  if (!줄) return null;
  return 줄.replace(/^\[안보냄\]\s*/, '').replace(/^\[스포츠\]\s*/, '').trim() || null;
}

/** 요 며칠 보낸 자국을 읽어 온다 */
export function 앞서보낸것들(날수 = 3, 방 = 자국방, 이제 = new Date()) {
  if (!fs.existsSync(방)) return [];
  const 문턱 = 이제.getTime() - 날수 * 24 * 60 * 60 * 1000;
  const 모은것 = [];
  for (const 이름 of fs.readdirSync(방)) {
    const 길 = path.join(방, 이름);
    let 통계;
    try { 통계 = fs.statSync(길); } catch { continue; }
    if (!통계.isFile() || 통계.mtimeMs < 문턱) continue;
    let 글;
    try { 글 = fs.readFileSync(길, 'utf8'); } catch { continue; }
    /* ⛔ 「안 보낸 것」도 센다 — 막혀서 안 나간 글을 내가 손으로 또 쓰면 똑같다 */
    const 제목 = 자국제목(글);
    if (!제목) continue;
    모은것.push({ 제목, 소재: 자국소재(글), 안보냈나: 안보낸자국인가(글) === true, 때: 통계.mtime });
  }
  return 모은것.sort((a, b) => b.때 - a.때);
}

/**
 * 중복인가 — 수집기와 «같은» 판정을 쓴다.
 * @returns {{중복인가: boolean, 까닭: string|null, 앞선제목: string|null}}
 */
export function 중복판정(제목, 본문, 앞선것들) {
  const 새소재 = 소재낱말(제목, 본문);
  const 목록 = 앞선것들 ?? [];

  /* ① 같은 경기인가 — 날짜와 장소가 같으면 제목이 달라도 같은 기사다 */
  for (const 앞 of 목록) {
    if (같은경기인가(새소재, 앞.소재)) {
      return { 중복인가: true, 까닭: '같은 경기다', 앞선제목: 앞.제목 };
    }
  }
  /* ② 소재 낱말이 겹치나 */
  const 겹침 = 같은소재인가_소재로(새소재, 목록);
  if (겹침) {
    return { 중복인가: true, 까닭: '소재가 겹친다', 앞선제목: 겹침.제목 ?? null };
  }
  /* ③ 제목이 닮았나 */
  for (const 앞 of 목록) {
    if (같은소재인가(제목, 앞.제목)) {
      return { 중복인가: true, 까닭: '제목이 닮았다', 앞선제목: 앞.제목 };
    }
  }
  return { 중복인가: false, 까닭: null, 앞선제목: null };
}

/* ── 자가시험 ────────────────────────────────────────────────────── */
const 곧바로부른것 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (곧바로부른것 && process.argv.includes('--자가시험')) {
  let 통과 = 0; let 깨짐 = 0;
  const 참 = (이름, 맞나) => { if (맞나) { 통과 += 1; } else { 깨짐 += 1; console.log('  ⛔ ' + 이름); } };

  참('첫 줄을 제목으로 읽는다', 제목과본문('제목이다\n본문이다').제목 === '제목이다');
  참('앞의 빈 줄을 건너뛴다', 제목과본문('\n\n제목이다\n본문').제목 === '제목이다');
  참('[제목] 꼴도 읽는다', 제목과본문('[제목] 진짜 제목\n본문').제목 === '진짜 제목');
  참('본문을 가른다', 제목과본문('제목\n한 줄\n두 줄').본문.includes('두 줄'));
  참('빈 글에 안 터진다', 제목과본문('').제목 === '' && 제목과본문(null).제목 === '');

  참('자국에서 제목을 뽑는다',
    자국제목('2026. 10. 16.\n[스포츠] 롤드컵 개막전\n받는곳 x') === '롤드컵 개막전');
  참('안 보낸 자국에서도 뽑는다',
    자국제목('2026. 10. 16.\n[안보냄] [스포츠] 막힌 제목\n까닭 중복') === '막힌 제목');
  참('그런 줄이 없으면 null', 자국제목('아무 글') === null && 자국제목(null) === null);

  /* 🔴 오늘 실제로 난 일 — 이 시험이 그때의 내 글을 잡아야 한다 */
  const 아침제목 = "'칸나' 김창동의 카르민 코프, 롤드컵 개막전서 C9에 역전승";
  const 아침본문 = '한국시간 16일 새벽 미국 로스앤젤레스 라이엇 게임즈 아레나에서 열린 2026 롤드컵 '
    + '플레이-인 스테이지 개막전에서 카르민 코프가 클라우드 나인 기아를 세트 스코어 3대 2로 꺾었다. '
    + '카르민 코프의 탑 김창동과 미드 강예후가 활약했다.';
  const 내제목 = '롤드컵 개막, 첫 판은 카르민 코프가 가져갔다';
  const 내본문 = '2026 리그 오브 레전드 월드 챔피언십이 16일 미국 로스앤젤레스 라이엇 게임즈 '
    + '아레나에서 플레이-인 스테이지로 막을 올렸다. 개막전에서 카르민 코프가 클라우드 나인 기아를 '
    + '세트 스코어 3대 2로 꺾었다. 카르민 코프는 탑 김창동과 미드 강예후가 맡았다.';
  const 앞선것 = [{ 제목: 아침제목, 소재: 소재낱말(아침제목, 아침본문) }];
  const 판정 = 중복판정(내제목, 내본문, 앞선것);
  참('🔴 오늘 내가 쓴 롤드컵 글을 중복으로 잡는다', 판정.중복인가 === true);
  참('🔴 무엇과 겹치는지 알려 준다', String(판정.앞선제목).includes('카르민'));

  /* ⛔ 대조군 — 다른 종목·다른 경기는 안 걸려야 한다. 다 막으면 기사가 영영 안 나간다 */
  const 야구제목 = 'KIA 네일·LG 톨허스트, 준PO 1차전 선발 맞대결';
  const 야구본문 = '프로야구 준플레이오프 1차전이 17일 오후 2시 광주기아챔피언스필드에서 열린다. '
    + 'KIA 타이거즈는 제임스 네일을, LG 트윈스는 앤더스 톨허스트를 선발로 내세운다.';
  참('⛔ 대조군 — 다른 종목은 안 걸린다',
    중복판정(야구제목, 야구본문, 앞선것).중복인가 === false);
  참('⛔ 앞선 것이 없으면 안 걸린다',
    중복판정(내제목, 내본문, []).중복인가 === false);
  참('⛔ 빈 입력에 안 터진다',
    중복판정('', '', null).중복인가 === false);

  console.log((깨짐 ? '⛔ ' + 깨짐 + '개 깨짐 · ' : '✅ ') + 통과 + '개 통과');
  process.exit(깨짐 ? 1 : 0);
}

/* ── 실제로 묻는다 ────────────────────────────────────────────────── */
if (곧바로부른것 && !process.argv.includes('--자가시험')) {
  const 인자 = (이름) => process.argv.find((a) => a.startsWith('--' + 이름 + '='))?.split('=').slice(1).join('=')
    ?? (() => { const i = process.argv.indexOf('--' + 이름); return i >= 0 ? process.argv[i + 1] : undefined; })();

  const 글길 = 인자('글');
  let 제목 = 인자('제목');
  let 본문 = '';

  if (글길) {
    const 글 = fs.readFileSync(path.resolve(뿌리, 글길), 'utf8');
    const 가른것 = 제목과본문(글);
    제목 = 제목 || 가른것.제목;
    본문 = 가른것.본문;
  } else if (인자('본문')) {
    본문 = fs.readFileSync(path.resolve(뿌리, 인자('본문')), 'utf8');
  }

  if (!제목) {
    console.log('⛔ 쓰는 법: node scripts/묻는다-이-기사-중복인가.mjs --글 docs/기사-….txt');
    process.exit(2);
  }

  const 앞선것들 = 앞서보낸것들(3);
  console.log('■ 이 기사가 요 사흘 것과 겹치나');
  console.log('  제목: ' + 제목.slice(0, 70));
  console.log('  맞대어 볼 앞선 기사 ' + 앞선것들.length + '건 (안 보낸 것도 센다)');
  console.log('');

  const 판정 = 중복판정(제목, 본문, 앞선것들);

  if (판정.중복인가) {
    console.log('🔴 **중복이다 — ' + 판정.까닭 + '**');
    console.log('   앞선 기사: ' + String(판정.앞선제목).slice(0, 70));
    console.log('');
    console.log('   ⛔ 이대로 내지 마십시오. 각도를 바꾸거나 다른 소재를 고르십시오.');
    console.log('   ⭐ 2026-10-16 에 바로 이 자리에서 사장님께 같은 기사를 두 번 드렸습니다.');
    process.exit(1);
  }

  console.log('✅ 겹치는 것을 못 찾았다');
  console.log('   ⬜ 다만 이 자는 «낱말»로만 잽니다. 내기 전에 사람이 한 번 더 보십시오.');
  if (앞선것들.length) {
    console.log('');
    console.log('   요 사흘 나간 것 —');
    for (const x of 앞선것들.slice(0, 8)) {
      console.log('     ' + (x.안보냈나 ? '[안보냄] ' : '          ') + x.제목.slice(0, 62));
    }
  }
}
