#!/usr/bin/env node
/**
 * check-지시문이-진팀을-중심에-놓나.mjs
 *   — **중부매일 계정에 보내는 지시문이 기사의 중심을 지역으로 뒤집지 않나.**
 *
 * ── 🔴 왜 지었나 (2026-11-05 · 사장님) ──────────────────────────────
 * 사장님: 「**여자배구 기사에서 왜 진 팀이 중심인가? 지역 따지지 말라고**」
 *
 * 그날 내가 지시문에 이렇게 적어 보냈다 —
 *   「정관장은 대전을 연고로 하는 팀입니다. 중부매일 독자가 읽는 기사이므로
 *    정관장 쪽에서 본 시각을 중심에 놓아 주십시오」
 * 그래서 제목이 「정관장 종휘 24점에도 흥국생명에 0대 3 완패」로 나갔다.
 * 3대 0으로 이긴 팀이 있는데 **진 팀이 주어**가 됐다.
 *
 * ⛔ 충청권을 억지로 끼워 넣지 말라는 지시를 어긴 것이 이번이 «세 번째»다.
 *   앞의 두 번은 데스크가 그랬고, 이번은 **내가 쓴 지시문**이었다.
 *   데스킹을 아무리 조여도 내가 지시문에 적어 보내면 그대로 기사가 된다.
 *   ⇒ 막을 자리는 데스킹이 아니라 **지시문을 보내기 직전**이다.
 *
 * ── 무엇을 막고 무엇을 막지 않나 ────────────────────────────────────
 * ⛔ 막는다      연고·지역을 근거로 «중심·시각·주어»를 그 팀으로 옮기라는 말
 * ✅ 안 막는다   그 팀 이야기를 본문에 충실히 쓰라는 말, 지역명 표기 지시
 *   (프로농구 「대구 한국가스공사」처럼 «지역명을 떼지 말라»는 지시는 정반대의 일이다)
 *
 * 쓰는 법
 *   node scripts/check-지시문이-진팀을-중심에-놓나.mjs docs/지시/어떤것.txt
 *   node scripts/check-지시문이-진팀을-중심에-놓나.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** 「중심에 놓아라」 쪽 말 */
const 중심말 = ['중심에', '중심으로', '시각을 중심', '주인공으로', '제목에 세워', '앞세워 주십시오', '주어로'];
/** 「지역 때문에」 쪽 말 */
const 지역말 = ['연고', '충청', '충북', '충남', '대전', '세종', '청주', '중부매일 독자'];

/**
 * 지역을 근거로 기사의 중심을 옮기라고 적었나.
 * ⚠ 한 문장 안에 둘이 같이 있을 때만 잡는다 — 따로 떨어져 있으면 서로 다른 말이다.
 */
export function 중심을옮기라고했나(글) {
  const 문장들 = String(글 ?? '').split(/(?<=[.。!?])\s*|\n/);
  const 걸린것 = [];
  문장들.forEach((문장, i) => {
    const t = String(문장);
    if (!중심말.some((w) => t.includes(w))) return;
    if (!지역말.some((w) => t.includes(w))) return;
    걸린것.push({ 줄: i + 1, 문장: t.trim().slice(0, 140) });
  });
  return 걸린것;
}

const 이파일이진입점 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (이파일이진입점 && process.argv.includes('--자가시험')) {
  let 탈 = 0;
  const 재 = (이름, 참) => { console.log((참 ? '  ✅ ' : '  🔴 ') + 이름); if (!참) 탈 += 1; };
  console.log('■ 자가시험');
  재('🔴 그날 내가 적어 보낸 그 문장을 잡는다',
    중심을옮기라고했나('정관장은 대전을 연고로 하는 팀입니다. 중부매일 독자가 읽는 기사이므로 정관장 쪽에서 본 시각을 중심에 놓아 주십시오.').length > 0);
  재('🔴 「충청권 팀을 주인공으로」도 잡는다',
    중심을옮기라고했나('충북 팀을 주인공으로 써 주십시오.').length === 1);
  재('⛔ 지역명 표기 지시는 안 잡는다 — 정반대의 일이다',
    중심을옮기라고했나('팀 이름은 반드시 지역명을 앞에 붙여 쓰십시오. 대구 한국가스공사입니다.').length === 0);
  재('⛔ 그냥 중심을 정하라는 말은 안 잡는다',
    중심을옮기라고했나('승부가 갈린 2세트를 중심에 놓아 주십시오.').length === 0);
  재('⛔ 지역명만 있는 줄은 안 잡는다',
    중심을옮기라고했나('대전 정관장은 아시아쿼터 종휘가 24점을 올렸습니다.').length === 0);
  재('⛔ 둘이 다른 문장에 떨어져 있으면 안 잡는다',
    중심을옮기라고했나('정관장은 대전 팀입니다.\n이긴 팀을 중심에 놓아 주십시오.').length === 0);
  재('빈 것에 안 터진다',
    중심을옮기라고했나('').length === 0 && 중심을옮기라고했나(null).length === 0);
  console.log(탈 ? '\n🔴 ' + 탈 + '가지 떨어졌다' : '\n✅ 모두 통과');
  process.exit(탈 ? 1 : 0);
}

if (이파일이진입점) {
  const 길 = process.argv[2];
  if (!길) { console.log('쓰는 법: node scripts/check-지시문이-진팀을-중심에-놓나.mjs <지시문파일>'); process.exit(1); }
  let 글 = '';
  try { 글 = fs.readFileSync(길, 'utf8'); } catch (e) {
    console.log('⬜ 지시문을 못 읽었다 — **못 쟀다**. 「없다」가 아니다');
    process.exit(0);
  }
  const 걸린것 = 중심을옮기라고했나(글);
  if (!걸린것.length) { console.log('✅ 지역으로 기사의 중심을 옮기라고 적지 않았다'); process.exit(0); }
  console.log('🔴 지역을 근거로 기사의 «중심»을 옮기라고 적었다 — **이대로 보내지 않는다**');
  걸린것.forEach((c) => console.log('   ' + c.줄 + '줄  ' + c.문장));
  console.log('\n   사장님 2026-11-05 「여자배구 기사에서 왜 진 팀이 중심인가? 지역 따지지 말라고」');
  console.log('   ⭐ 경기 기사의 중심은 이긴 쪽이다. 진 팀이 충청권이면 «본문에서» 충실히 쓰면 된다.');
  process.exit(1);
}

export default { 중심을옮기라고했나 };
