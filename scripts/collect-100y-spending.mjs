    물었는데없는칸, 못낸해,
    '⛔ 이 표의 단위 이름이 거짓이다':
      '가구원수·가구주연령·가구분포에도 단위가 「원」으로 붙어 있습니다. 실제로는 명·세·%입니다. 저희가 갈라 적었습니다.',
