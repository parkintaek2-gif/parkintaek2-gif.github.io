      칸, 짧은이름: 칸.replace(' 가구', ''),
      가계지출: 값(최신, 칸, '가계지출'), 소비지출: 소비,
      가구원수: 원수, 가구주연령: 값(최신, 칸, '가구주연령'), 가구분포: 값(최신, 칸, '가구분포'),
