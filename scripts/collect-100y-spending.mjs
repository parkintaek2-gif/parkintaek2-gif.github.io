    '⚠⚠ 한 번에 부르면 잘린다':
      'objL2=ALL 로 부르면 1,000행에서 잘려 뒤쪽 칸이 조용히 사라집니다(「소득」이 없는 것처럼 보였습니다). '
      + '저희는 항목을 골라 해마다 나눠 받고, 받은 뒤 해마다 몇 칸을 받았는지 세었습니다.',
