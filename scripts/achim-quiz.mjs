/** 그 자리가 풀 문제 — 자기 것 + 모두 것 */
export function 문제뽑기(자리, 전부 = 모든문제) {
  const n = String(자리 ?? '');
  return 전부.filter((q) => q.자리 === n || q.자리 === '*');
}

/** 답을 맞춰 본다. `낸답` 은 "3,2,1,…" */
export function 채점(문제들, 낸답) {
  const 준 = String(낸답 ?? '').split(',').map((x) => Number(String(x).trim()));
  if (준.length !== 문제들.length) return { 됨: false, 까닭: `답이 ${문제들.length}개여야 하는데 ${준.filter((x) => !Number.isNaN(x)).length}개다`, 틀린것: [] };
  const 틀린것 = 문제들.map((q, i) => (준[i] === q.답 ? null : i)).filter((x) => x !== null);
  return { 됨: 틀린것.length === 0, 까닭: 틀린것.length ? `${틀린것.length}개 틀렸다` : '', 틀린것 };
}

