/**
 * 🔴 사장님(2026-08-09 00:2x) — *「퀴즈 답이 너무 뻔한데. **문장 길면 대부분 답**이야」*
 *
 * 재 보니 사장님 말씀대로였다 —
 * ```
 * 정답이 제일 긴 보기      31/37 = 84%
 * 정답에 ** 강조가 붙은 것  10건      ← 내가 답에 굵게 표시까지 해 놨다
 * 답이 2번인 것            25/37 = 68%
 * ```
 * ⛔ 안 읽어도 맞힌다. 그러면 퀴즈가 아니라 통과 의식이다.
 *
 * ⭐ 셋으로 막는다
 *   ① 보기에서 `**` 를 떼고 낸다 — 답에 표시가 남지 않게
 *   ② **날마다 보기 차례를 섞는다** — 「2번을 찍으면 된다」가 안 통한다
 *   ③ 자가시험이 **정답이 제일 긴 보기인 비율**을 재서 너무 높으면 죽는다
 */
export const 강조떼기 = (글) => String(글 ?? '').replace(/\*\*/g, '').trim();

/** 글자에서 숫자 하나를 만든다 — 같은 씨앗이면 늘 같은 차례가 나온다 */
export function 씨앗(글) {
  let h = 2166136261;
  for (const c of String(글 ?? '')) { h ^= c.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}

/** 보기를 날마다 섞는다. 답 번호도 따라 옮긴다 */
export function 섞기(문제, 오늘) {
  const 보기 = (문제.보기 ?? []).map(강조떼기);
  const 정답글 = 보기[문제.답 - 1];
  let h = 씨앗(String(문제.물음) + '|' + String(오늘 ?? ''));
  const 순 = 보기.map((b, i) => i);
  for (let i = 순.length - 1; i > 0; i -= 1) {          // 피셔–예이츠, 씨앗으로만 돈다
    h = (Math.imul(h, 1103515245) + 12345) >>> 0;
    const j = h % (i + 1);
    [순[i], 순[j]] = [순[j], 순[i]];
  }
  const 새보기 = 순.map((i) => 보기[i]);
  return { ...문제, 보기: 새보기, 답: 새보기.indexOf(정답글) + 1 };
}

/** 그 자리가 풀 문제 — 자기 것 + 모두 것. 오늘을 주면 보기를 섞어 준다 */
export function 문제뽑기(자리, 전부 = 모든문제, 오늘 = null) {
  const n = String(자리 ?? '');
  const 것 = 전부.filter((q) => q.자리 === n || q.자리 === '*');
  return 오늘 ? 것.map((q) => 섞기(q, 오늘)) : 것;
}

/** 답을 맞춰 본다. `낸답` 은 "3,2,1,…" */
export function 채점(문제들, 낸답) {
  const 준 = String(낸답 ?? '').split(',').map((x) => Number(String(x).trim()));
  if (준.length !== 문제들.length) return { 됨: false, 까닭: `답이 ${문제들.length}개여야 하는데 ${준.filter((x) => !Number.isNaN(x)).length}개다`, 틀린것: [] };
  const 틀린것 = 문제들.map((q, i) => (준[i] === q.답 ? null : i)).filter((x) => x !== null);
  return { 됨: 틀린것.length === 0, 까닭: 틀린것.length ? `${틀린것.length}개 틀렸다` : '', 틀린것 };
}

