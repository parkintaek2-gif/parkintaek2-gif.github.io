#!/usr/bin/env node
/**
 * **「0건」이 포털 탓인가 우리 탓인가 — 이미 받은 날로 대조해서 가린다.**
 *
 * ── 🔴 왜 (2026-10-11 14:4x · 5번) ──────────────────────────────────
 * 시세 다섯 갈래가 2026-10-07 에서 멎었다. 돌려 보면 0건이 온다.
 * 어제까지 네 번 재 봤고 네 번 다 「포털에 없었다」로 적었다 — **그런데 그 판정의 근거가
 * 「0건이 왔다」뿐이었다.** 0건은 두 가지를 똑같이 말한다:
 * ```
 *   ① 포털이 그날 치를 아직 안 올렸다        ← 우리가 할 수 있는 것이 없다
 *   ② 수집기·열쇠·경로가 깨졌다              ← 우리가 당장 고쳐야 한다
 * ```
 * ⛔ 둘을 가르지 않고 ①로 적으면, 수집기가 죽은 날에도 조용히 「포털 탓」이 쌓인다.
 *
 * ⭐ 가르는 길은 하나뿐이다 — **이미 받아 둔 날을 다시 받아 본다.**
 *   그날이 오면 수집기는 살아 있는 것이고, 그날도 0이면 우리 쪽이 깨진 것이다.
 *   (2026-10-11 실측: 10-08·10-10 은 0건인데 10-07 은 330건, 10-06 은 336건이 왔다
 *    ⇒ 수집기는 멀쩡하고 포털이 나흘째 안 올린 것이다.)
 *
 * ⚠ 나는 오늘 이 대조를 **손으로** 했다. 손으로 하는 것은 다음 사람이 안 한다.
 *   ⛔ 사람이 기억해서 지키는 구조를 만들지 않는다 — 이 저장소의 오래된 규칙이다.
 *
 * ── ⛔ 이 자가 지키는 것 ────────────────────────────────────────────
 * ⛔ **인터넷을 탄다.** 그래서 `npm test` 본 실행에는 «안» 물린다 — 자가시험만 문다.
 *   남의 사정으로 전 유닛 배포가 막히면 그것은 고친 것이 아니라 옮긴 것이다.
 * ⛔ 받은 것을 **적지 않는다.** 이 자는 «재는» 자다. 쌓는 것은 수집기의 몫이다.
 * ⚠ 대조에 쓸 날은 **곳간에 실제로 있는 날**에서 고른다. 손으로 박지 않는다 —
 *   박아 두면 그 날이 지워졌을 때 이 자가 거짓으로 운다.
 *
 *   node scripts/check-0건이-포털탓인가.mjs --갈래 bonds
 *   node scripts/check-0건이-포털탓인가.mjs --갈래 bonds --빈날 20261008
 *   node scripts/check-0건이-포털탓인가.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 갈래 이름 → 수집기 파일. ⚠ 여기 없는 갈래는 「모른다」고 말한다 — 짐작해서 부르지 않는다 */
export const 수집기 = {
  bonds: 'collect-bonds.mjs',
  commodities: 'collect-commodities.mjs',
  derivatives: 'collect-derivatives.mjs',
  indices: 'collect-indices.mjs',
};

/**
 * 곳간에서 「이미 받아 둔 날」을 고른다 — 가장 최근 것.
 * ⛔ 손으로 박지 않는다. 박아 두면 그 날이 지워졌을 때 거짓으로 운다.
 */
export function 받아둔날고르기(파일이름들) {
  const 날들 = [...new Set(
    (파일이름들 ?? [])
      .map((f) => (/^(\d{8})/.exec(String(f)) ?? [])[1])
      .filter(Boolean),
  )].sort();
  return 날들.length ? 날들[날들.length - 1] : null;
}

/** 수집기 출력에서 받은 건수를 읽는다. 못 읽으면 null — 0 으로 읽지 않는다 */
export function 건수읽기(글) {
  const m = String(글 ?? '').match(/([0-9][0-9,]*)\s*건/);
  if (!m) return null;
  const n = Number(m[1].replace(/,/g, ''));
  return Number.isFinite(n) ? n : null;
}

/**
 * 빈 날과 받아 둔 날의 건수로 판정한다.
 * ⛔ 못 읽은 것(null)은 0 으로 보지 않는다 — 「없다」와 「못 쟀다」를 가른다.
 */
export function 판정(빈날건수, 대조건수) {
  if (대조건수 === null) return { 꼴: '못쟀다', 말: '대조한 날의 건수를 못 읽었다 — 수집기 출력 꼴이 바뀌었나 본다' };
  if (대조건수 === 0) return { 꼴: '우리탓', 말: '이미 받아 둔 날도 0건이다 — **수집기·열쇠·경로가 깨졌다**. 포털 탓이 아니다' };
  if (빈날건수 === null) return { 꼴: '못쟀다', 말: '빈 날의 건수를 못 읽었다' };
  if (빈날건수 > 0) return { 꼴: '이제온다', 말: '빈 날이 이제 들어온다 — 받아서 곳간에 넣는다' };
  return { 꼴: '포털탓', 말: '이미 받아 둔 날은 오는데 그 날만 0건이다 — **포털이 아직 안 올렸다**' };
}

function 자가시험() {
  let 탈 = 0;
  const 검 = (이름, 참, 덧 = '') => { if (!참) { 탈 += 1; console.log(`🔴 ${이름} ${덧}`); } };

  검('🔴 곳간에서 가장 최근 날을 고른다',
    받아둔날고르기(['20261006.json', '20261007.json', '20260930.json']) === '20261007');
  검('⛔ 같은 날이 여럿이어도 한 번만 센다',
    받아둔날고르기(['20261007.json', '20261007-2.json']) === '20261007');
  검('⛔ 날짜 아닌 파일은 거른다', 받아둔날고르기(['_설명.md', '20261007.json']) === '20261007');
  검('⛔ 빈 곳간이면 null — 아무 날이나 지어내지 않는다',
    받아둔날고르기([]) === null && 받아둔날고르기(null) === null);

  검('건수를 읽는다', 건수읽기('✅ 330건 받았다') === 330);
  검('쉼표가 든 수도 읽는다', 건수읽기('12,345건') === 12345);
  검('0건을 읽는다', 건수읽기('⬜ 0건') === 0);
  검('⛔ 못 읽으면 null — 0 으로 읽지 않는다', 건수읽기('받은 것이 없다') === null && 건수읽기('') === null);

  /* ⭐ 이 자의 핵심 — 0건 둘을 가른다 */
  검('🔴🔴 이미 받은 날이 오면 «포털 탓»이다', 판정(0, 330).꼴 === '포털탓');
  검('🔴🔴 이미 받은 날도 0이면 «우리 탓»이다 — 조용히 포털 탓으로 적지 않는다',
    판정(0, 0).꼴 === '우리탓');
  검('🔴 빈 날이 이제 들어오면 그렇게 말한다', 판정(171, 171).꼴 === '이제온다');
  검('⛔ 대조한 날을 못 읽으면 «못 쟀다» — 둘 중 하나로 우기지 않는다',
    판정(0, null).꼴 === '못쟀다');
  검('⛔ 빈 날을 못 읽어도 «못 쟀다»', 판정(null, 330).꼴 === '못쟀다');
  검('🔴 판정마다 까닭이 붙는다', ['포털탓', '우리탓', '이제온다', '못쟀다']
    .every((k) => [판정(0, 330), 판정(0, 0), 판정(171, 171), 판정(0, null)]
      .some((r) => r.꼴 === k && r.말.length > 10)));

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : '\n✅ 자가시험 14개 통과');
  if (탈) process.exit(1);
}

function 돌린다(파일, 날) {
  const r = spawnSync(process.execPath, [path.join(뿌리, 'scripts', 파일), '--date', 날],
    { cwd: 뿌리, encoding: 'utf8', timeout: 180000 });
  return `${r.stdout ?? ''}${r.stderr ?? ''}`;
}

function 본실행() {
  const 갈래 = process.argv[process.argv.indexOf('--갈래') + 1];
  if (!갈래 || !수집기[갈래]) {
    console.log(`⛔ --갈래 를 주십시오 — 아는 갈래: ${Object.keys(수집기).join(' · ')}`);
    console.log('   ⚠ 여기 없는 갈래는 «모른다»고 말한다. 짐작해서 수집기를 부르지 않는다.');
    process.exit(1);
  }
  const 곳간 = path.join(뿌리, 'archive/raw', 갈래);
  if (!fs.existsSync(곳간)) {
    console.log(`⬜ ${곳간} 이 없다 — 못 쟀다`);
    return;
  }
  const 대조날 = 받아둔날고르기(fs.readdirSync(곳간));
  if (!대조날) {
    console.log(`⬜ ${갈래} 곳간에 날짜 파일이 하나도 없다 — 대조할 날이 없어 «못 쟀다»`);
    return;
  }

  const 빈날 = process.argv[process.argv.indexOf('--빈날') + 1];
  console.log(`■ ${갈래} — 대조할 날 ${대조날}(곳간에 있다)${빈날 ? ` · 빈 날 ${빈날}` : ''}`);

  const 대조건수 = 건수읽기(돌린다(수집기[갈래], 대조날));
  const 빈날건수 = 빈날 ? 건수읽기(돌린다(수집기[갈래], 빈날)) : null;
  console.log(`   대조한 날 ${대조날} → ${대조건수 === null ? '못 읽음' : `${대조건수}건`}`);
  if (빈날) console.log(`   빈 날   ${빈날} → ${빈날건수 === null ? '못 읽음' : `${빈날건수}건`}`);

  const r = 판정(빈날건수, 대조건수);
  const 표 = { 포털탓: '✅', 이제온다: '🔴', 우리탓: '🔴🔴', 못쟀다: '⬜' }[r.꼴];
  console.log(`\n${표} ${r.말}`);
  if (r.꼴 === '포털탓') {
    console.log('   ⚠ 「포털에 없다」고 docs/못받은날-기록.tsv 에 적되, **이 대조를 했다는 것도 함께** 적는다.');
    console.log('     0건만으로 적으면 다음 사람이 그 판정을 믿을 근거가 없다.');
  }
  if (r.꼴 === '우리탓') process.exit(1);
}

if (process.argv.includes('--자가시험')) 자가시험();
else 본실행();
