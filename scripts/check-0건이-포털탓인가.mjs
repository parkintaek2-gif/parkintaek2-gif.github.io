/**
 * 🔴 [2026-10-13 09:4x · 5번] **대조가 성립하지 않는 수집기가 있다.**
 *   collect-stock-plus 류는 「이미 있는 1일은 건너뛴다」고 적고 0건을 낸다.
 *   그 0건을 «못 받았다»로 읽으면 이 자는 멀쩡한 날을 두고 🔴🔴 우리 탓을 외친다.
 *   ⇒ 건너뛴 것은 **「0건」이 아니라 「안 쟀다」**다. 그렇게 말하게 한다.
 *   ⛔ 지금 이 자가 아는 네 갈래에는 그 꼴이 없다. 그래도 미리 막는다 —
 *     갈래가 늘 때 이 함정을 사람이 기억해서 피하게 두지 않는다.
 */
export function 건너뛰었나(글) {
  return /이미 있는.*건너뛴다/.test(String(글 == null ? "" : 글));
}

/**
 * 🔴🔴 [2026-10-13 09:3x · 5번] **이 자가 거짓 ✅ 를 냈다.**
 *   `--날 20261012` 로 불렀더니(참 이름은 `--빈날`) indexOf 가 -1 을 주고,
 *   argv[0] 인 **node.exe 경로**가 「빈 날」이 되어 그대로 수집기에 넘어갔다.
 *   그리고 「그 날만 0건이다 — 포털이 아직 안 올렸다」고 ✅ 를 냈다.
 *   ⛔ 날짜 자리에 node.exe 가 들어간 채 «판정»이 나온 것이다.
 *   ⭐ 자가 보여 주는 것과 재는 것이 다르면 그 자는 사람을 속인다 — 열다섯 번째다.
 * ⇒ 깃발은 «있나·꼴이 맞나»를 함께 본다. 모르면 판정하지 않고 멈춘다.
 */
export function 깃발(이름, argv) {
  const 줄 = Array.isArray(argv) ? argv : [];
  const i = 줄.indexOf(이름);
  if (i < 0) return { 있나: false, 값: null, 탈: null };
  const v = 줄[i + 1];
  if (v === undefined) return { 있나: true, 값: null, 탈: 이름 + ' 뒤에 값이 없다' };
  if (String(v).startsWith('--')) return { 있나: true, 값: null, 탈: 이름 + ' 뒤에 온 것이 또 다른 깃발이다(' + v + ')' };
  return { 있나: true, 값: String(v), 탈: null };
}

/** 날짜는 YYYYMMDD 여덟 자다 — 수집기가 그 꼴만 받는다 */
export function 날맞나(값) { return /^[0-9]{8}$/.test(String(값 == null ? "" : 값)); }

/** 갈래 칸은 글자 하나일 수도, { 파일, 덧 } 일 수도 있다 — 둘 다 받는다 */
export function 수집기풀기(칸) {
  if (typeof 칸 === 'string') return { 파일: 칸, 덧: [] };
  if (칸 && 칸.파일) return { 파일: 칸.파일, 덧: Array.isArray(칸.덧) ? 칸.덧 : [] };
  return null;
}

function 돌린다(칸, 날) {
  const 푼 = 수집기풀기(칸);
  if (!푼) return '';
  const r = spawnSync(process.execPath, [path.join(뿌리, 'scripts', 푼.파일), '--date', 날, ...푼.덧],
    { cwd: 뿌리, encoding: 'utf8', timeout: 300000 });
  return `${r.stdout ?? ''}${r.stderr ?? ''}`;
}

function 본실행() {
  const 갈래깃 = 깃발('--갈래', process.argv);
  const 갈래 = 갈래깃.값;
  if (갈래깃.탈) console.log('⛔ ' + 갈래깃.탈);
  if (!갈래 || !수집기[갈래]) {
    console.log(`⛔ --갈래 를 주십시오 — 아는 갈래: ${Object.keys(수집기).join(' · ')}`);
    console.log('   ⚠ 여기 없는 갈래는 «모른다»고 말한다. 짐작해서 수집기를 부르지 않는다.');
    process.exit(1);
  }
  const 곳간 = path.join(뿌리, 'archive/raw', 갈래);
  if (!fs.existsSync(곳간)) {
    console.log(`⬜ ${곳간} 이 없다 — 못 쟀다`);
    return;
  }
  const 대조날 = 받아둔날고르기(fs.readdirSync(곳간));
  if (!대조날) {
    console.log(`⬜ ${갈래} 곳간에 날짜 파일이 하나도 없다 — 대조할 날이 없어 «못 쟀다»`);
    return;
  }

  const 빈날깃 = 깃발('--빈날', process.argv);
  if (빈날깃.탈 || (빈날깃.있나 && !날맞나(빈날깃.값))) {
    console.log('⛔ --빈날 은 YYYYMMDD 여덟 자다 — 받은 것: ' + (빈날깃.값 === null ? '(없다)' : 빈날깃.값));
    console.log('   ⚠ 2026-10-13 에 여기서 node.exe 경로가 «빈 날»이 되어 거짓 ✅ 가 났다.');
    console.log('   ⛔ 모르면 판정하지 않는다. 짐작해서 ✅ 를 내지 않는다.');
    process.exit(1);
  }
  /* ⚠ 사람이 자주 틀리는 꼴을 짚어 준다 — 「--날」·「2026-10-12」 둘 다 오늘 내가 틀렸다 */
  if (!빈날깃.있나 && process.argv.some((a) => a === '--날')) {
    console.log('⛔ 깃발 이름은 «--빈날» 이다(「--날」이 아니다). 그대로 두면 판정이 거짓이 된다.');
    process.exit(1);
  }
  const 빈날 = 빈날깃.값;
  console.log(`■ ${갈래} — 대조할 날 ${대조날}(곳간에 있다)${빈날 ? ` · 빈 날 ${빈날}` : ''}`);

  const 대조글 = 돌린다(수집기[갈래], 대조날);
  if (건너뛰었나(대조글)) {
    console.log('⬜ 대조할 날을 수집기가 «건너뛰었다»(이미 있는 날이라) — 0건이 아니라 «안 쟀다»다');
    console.log('   ⛔ 이 상태로는 포털 탓인지 우리 탓인지 못 가린다. 판정하지 않는다.');
    return;
  }
  const 대조건수 = 건수읽기(대조글);
  const 빈날글 = 빈날 ? 돌린다(수집기[갈래], 빈날) : null;
  if (빈날글 !== null && 건너뛰었나(빈날글)) {
    console.log('⬜ 빈 날을 수집기가 건너뛰었다 — 곳간에 이미 있는 날이다. 빈 날이 아니다');
    return;
  }
  const 빈날건수 = 빈날글 === null ? null : 건수읽기(빈날글);
  console.log(`   대조한 날 ${대조날} → ${대조건수 === null ? '못 읽음' : `${대조건수}건`}`);
  if (빈날) console.log(`   빈 날   ${빈날} → ${빈날건수 === null ? '못 읽음' : `${빈날건수}건`}`);

  const r = 판정(빈날건수, 대조건수);
  const 표 = { 포털탓: '✅', 이제온다: '🔴', 우리탓: '🔴🔴', 못쟀다: '⬜' }[r.꼴];
  console.log(`\n${표} ${r.말}`);
  if (r.꼴 === '포털탓') {
    console.log('   ⚠ 「포털에 없다」고 docs/못받은날-기록.tsv 에 적되, **이 대조를 했다는 것도 함께** 적는다.');
    console.log('     0건만으로 적으면 다음 사람이 그 판정을 믿을 근거가 없다.');
  }
  if (r.꼴 === '우리탓') process.exit(1);
}

