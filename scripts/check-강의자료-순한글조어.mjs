/**
 * 🔴🔴 [2026-10-03] **역슬래시 하나를 담은 글자(`'\\'`)에서 따옴표 추적이 깨졌다.**
 *   「앞 글자가 역슬래시면 닫는 따옴표가 아니다」로 보고 있었는데,
 *   `'\\'` 는 «역슬래시 하나»를 담은 멀쩡한 글자다. 그 닫는 따옴표를 안 닫아 버리니
 *   그 뒤 파일 전체가 「글자 속」이 되고 **주석이 하나도 안 지워졌다.**
 *   그래서 `/** 자리표(placeholder) 하나 *\/` 같은 주석이 흠으로 잡혔다.
 * ⇒ 역슬래시를 만나면 «다음 한 글자를 건너뛴다». 그래야 `\\` 가 제대로 닫힌다.
 * ⚠ 같은 손으로 쓴 다른 검사자에도 같은 병이 있다 — 찾아가서 함께 고친다.
 */
function 글자건너뛰기(s, i, 따옴표) {
  for (; i < s.length; i++) {
    if (s[i] === '\\') { i += 1; continue; }   /* 다음 한 글자는 무조건 글자다 */
    if (s[i] === 따옴표) return i;
  }
  return s.length;
}

/**
 * 🔴🔴 [2026-10-03] **정규식 리터럴 속 백틱에 속고 있었다.**
 *   `if (/^```/.test(t))` — 정규식 안에 백틱이 «세 개»다. 홀수라 하나가 열린 채 남고,
 *   그 뒤 파일 전체가 「글자 속」이 되어 주석이 하나도 안 지워졌다.
 *   그래서 주석 열다섯 곳이 흠으로 잡혔다.
 * ⇒ 정규식 리터럴을 통째로 건너뛴다.
 * ⚠ `/` 가 나누기인지 정규식인지는 «앞 글자»로 가른다 — 완벽하진 않지만,
 *   우리 코드에서 나누기 뒤에 따옴표가 오는 일은 없다.
 */
function 정규식인가(s, i) {
  for (let j = i - 1; j >= 0; j--) {
    const c = s[j];
    if (c === ' ' || c === '\t') continue;
    if (c === '\n' || c === '\r') return true;
    return '(,=:[!&|?{};+'.includes(c);
  }
  return true;
}

function 정규식건너뛰기(s, i) {
  let 꺾쇠안 = false;
  for (let j = i + 1; j < s.length; j++) {
    const c = s[j];
    if (c === '\\') { j += 1; continue; }
    if (c === '\n') return i;              /* 한 줄을 넘으면 정규식이 아니었다 */
    if (c === '[') 꺾쇠안 = true;
    else if (c === ']') 꺾쇠안 = false;
    else if (c === '/' && !꺾쇠안) return j;
  }
  return i;
}

/** 따옴표 속 글자만 뽑는다 — 주석과 코드 이름은 버린다 */
export function 화면글자뽑기(소스) {
  const s = String(소스 ?? '');
  /* 주석을 먼저 지운다. 자리는 빈칸으로 메워 줄 번호가 안 어긋나게 한다 */
  const 쪼갠 = s.split('');
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '/' && s[i + 1] !== '/' && s[i + 1] !== '*' && 정규식인가(s, i)) {
      const 끝 = 정규식건너뛰기(s, i);
      if (끝 > i) { i = 끝; continue; }
    }
    if (c === '"' || c === "'" || c === '`') { i = 글자건너뛰기(s, i + 1, c); continue; }
    if (c === '/' && s[i + 1] === '/') { while (i < s.length && s[i] !== '\n') { 쪼갠[i] = ' '; i++; } i--; continue; }
    if (c === '/' && s[i + 1] === '*') {
      const 끝 = s.indexOf('*/', i + 2);
      const 여기까지 = 끝 < 0 ? s.length : 끝 + 2;
      for (let j = i; j < 여기까지; j++) if (쪼갠[j] !== '\n') 쪼갠[j] = ' ';
      i = 여기까지 - 1;
      continue;
    }
  }
  const 주석없음 = 쪼갠.join('');

  /* 이제 따옴표 «속»만 모은다 — 자리(줄 번호)를 함께 들고 간다 */
  const 모은것 = [];
  for (let i = 0; i < 주석없음.length; i++) {
    const c = 주석없음[i];
    if (c === '/' && 정규식인가(주석없음, i)) {
      const 끝 = 정규식건너뛰기(주석없음, i);
      if (끝 > i) { i = 끝; continue; }
    }
    if (c !== '"' && c !== "'" && c !== '`') continue;
    const 끝 = 글자건너뛰기(주석없음, i + 1, c);
    모은것.push({ 글: 주석없음.slice(i + 1, 끝), 자리: i + 1 });
    i = 끝;
  }
  return { 주석없음, 모은것 };
}

/**
 * 🔴 [2026-10-03] **자가시험 이름과 콘솔 글은 화면에 안 나간다.**
 *   `검('⛔ 표지가 자리표로 돌아가지 않았다', …)` 의 「자리표」가 흠으로 잡혔다.
 *   그것은 손님이 아니라 «내가» 읽는 글이다.
 * ⛔ 흠이 아닌 것을 흠으로 세면 진짜 흠이 묻힌다 — 그래서 가른다.
 */
export function 안보이는줄인가(주석없음, 자리) {
  let 줄시작 = 주석없음.lastIndexOf('\n', 자리);
  줄시작 = 줄시작 < 0 ? 0 : 줄시작 + 1;
  let 줄끝 = 주석없음.indexOf('\n', 자리);
  줄끝 = 줄끝 < 0 ? 주석없음.length : 줄끝;
  const 줄 = 주석없음.slice(줄시작, 줄끝);
  return /(^|[^가-힣A-Za-z0-9_])검\s*\(|console\s*\./.test(줄);
}

export function 줄번호(글, 자리) {
  let n = 1;
  for (let i = 0; i < 자리 && i < 글.length; i++) if (글[i] === '\n') n++;
  return n;
}

export function 파일재기(길, 소스) {
  const { 주석없음, 모은것 } = 화면글자뽑기(소스);
  const 나온것 = [];
  for (const 덩이 of 모은것) {
    if (안보이는줄인가(주석없음, 덩이.자리)) continue;
    for (const b of 바꿀말) {
      let i = 덩이.글.indexOf(b.꼴);
      while (i >= 0) {
        나온것.push({
          길, 줄: 줄번호(주석없음, 덩이.자리 + i), 꼴: b.꼴, 대신: b.대신,
          둘레: 덩이.글.slice(Math.max(0, i - 24), i + b.꼴.length + 24),
        });
        i = 덩이.글.indexOf(b.꼴, i + b.꼴.length);
      }
    }
  }
  return 나온것;
}

