/**
 * **장 여는 장의 제목을 한 줄에 앉힌다.**
 *
 * 🔴🔴 [2026-10-01 · 사장님] 「**누가 슬라이드 제목을 두 줄로 하나? 뒷부분은 뭐지?
 *   필요없는 내용이면 삭제해**」
 *   걸린 제목 — 「제6장 뒷부분. 성격(成格)과 패격(敗格) · 상신(相神) · 기신(忌神)」
 *
 * 세 걸음으로 줄인다. ⛔ 한 걸음에 다 쳐내지 않는다 — 뜻이 날아간다.
 *   ① 군더더기를 뗀다 — 「뒷부분」·「보충」·「N절」. 수강생에게 아무 뜻이 없는 말이다
 *   ② 한자 괄호를 뗀다 — 여는 장은 표지다. 한자는 본문에서 만난다
 *   ③ 그래도 길면 줄표 뒤를 뗀다
 * ⚠ 그러고도 길면 «글자를 줄인다»(아래 장제목크기). 두 줄로는 안 넘긴다.
 */
export const 장제목한줄 = 20;
export function 장제목다듬기(원래) {
  let s = String(원래 ?? '').trim();
  s = s.replace(/제(\d+)장\s*(뒷부분|보충|\d+절)\s*\.?/g, '제$1장.');
  s = s.replace(/\s*\(\s*[一-鿿]+\s*\)/g, '');
  s = s.replace(/[「」『』]/g, '').replace(/\s{2,}/g, ' ').trim();
  if ([...s].length > 장제목한줄) {
    const 잘라 = s.replace(/\s*[—–-]\s*.*$/, '').trim();
    if (잘라 && [...잘라].length >= 6) s = 잘라;
  }
  return s.replace(/\s*[·,]\s*$/, '').trim();
}

/** 다듬고도 긴 제목은 «글자를» 줄인다. 두 줄로 넘기지 않는다 */
export function 장제목크기(제목) {
  const n = [...String(제목 ?? '')].length;
  if (n <= 장제목한줄) return 4000;
  if (n <= 26) return 3200;
  if (n <= 34) return 2600;
  return 2200;
}

