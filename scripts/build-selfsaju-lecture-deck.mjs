/**
 * 그 이름표 한 줄만 담고 있던 장을 걷는다.
 *
 * 🔴 [2026-10-03] 명반의 이름표가 «앞 장 한 장»을 통째로 차지하고 있었다.
 *   두 꼴이 있었다 — 「정관격 — 일간과 월지만」과 「(1) 왕십만(王十萬) 명 — 종재」.
 *   처음엔 앞 꼴만 고쳤더니 뒤 꼴이 그대로 남았다. ⇒ 지우는 일은 한 자리에 모은다.
 *
 * ⛔ 그 줄 «말고 다른 것»도 담고 있으면 안 지운다 — 본문을 잃는다.
 */
export function 이름표낸장지우기(장들, 이름줄) {
  const 끝 = 장들[장들.length - 1];
  if (!끝 || (끝.종류 !== '내용' && 끝.종류 !== '강조')) return false;
  const 담긴것 = [...(끝.줄들 || []).map((r) => r.글 ?? r), ...(끝.글들 || [])]
    .map((r) => 표시이모지벗기기(표시벗기기(r)));
  if (담긴것.length !== 1 || 담긴것[0] !== 이름줄) return false;
  장들.pop();
  return true;
}

