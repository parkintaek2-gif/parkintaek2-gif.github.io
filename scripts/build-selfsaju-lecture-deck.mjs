  const 명반수 = 장들.filter((s) => s.종류 === '명반').length;
  console.log(`   명반 ${명반수}장`);
  if (잘린것.length) {
    console.log(`\n🔴 잘린 문장 ${잘린것.length}곳 — 보내기 «전»에 고친다`);
    for (const t of 잘린것.slice(0, 15)) console.log(`   · ${t.번호}장 「${t.제목}」 ${t.글}`);
  } else {
    console.log('   ✅ 잘린 문장 없음');
  }
