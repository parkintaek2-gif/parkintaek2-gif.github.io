export const 화면줄상한 = 35;

/**
 * 긴 줄을 «화면 몫»과 «노트 몫»으로 가른다.
 * @returns {{화면: string, 노트: string|null}}
 */
export function 줄가르기(글, 상한 = 화면줄상한) {
  const s = String(글 ?? '').trim();
  if (s.length <= 상한) return { 화면: s, 노트: null };
  /* 문장 끝으로 가른다 — 「…다.」 「!」 「?」 뒤의 빈칸 */
  const 토막 = s.split(/(?<=[.!?。])\s+/).filter(Boolean);
  if (토막.length < 2) return { 화면: s, 노트: null };   /* 가를 데가 없다 — 그대로 둔다 */
  let 앞 = 토막[0];
  let i = 1;
  /* 첫 문장이 «상한의 절반에도» 못 미칠 때만 한 문장 더 붙인다 — 화면이 허전해진다.
     ⛔ 예전에는 「상한 안이면」 계속 붙였다. 그래서 거의 모든 장이 상한까지 꽉 차고
       가운데값이 상한과 같아졌다. 허전함을 막으려던 규칙이 빽빽함을 만들었다. */
  while (i < 토막.length && 앞.length < 상한 / 2
         && (앞 + ' ' + 토막[i]).length <= 상한) { 앞 = `${앞} ${토막[i]}`; i++; }
  const 뒤 = 토막.slice(i).join(' ').trim();
  return { 화면: 앞, 노트: 뒤 || null };
}

