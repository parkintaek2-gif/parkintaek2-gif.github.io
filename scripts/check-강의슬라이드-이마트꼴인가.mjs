import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const 우리것 = path.join(뿌리, 'archive/out/셀프사주2-강의/셀프사주2-강의용-2026-10-03.pptx');
export const 이마트 = 'C:/Users/User/OneDrive/문서/셀프사주 1권-이마트 세종.pptx';

/**
 * 🔴 넘으면 안 되는 선 — 이마트 1권을 실측해서 정한 값이다.
 * ⛔ 내가 편한 쪽으로 늘리지 않는다. 늘리려면 이마트를 다시 재서 근거를 바꾼다.
 */
export const 참는선 = {
  글자가운데값: 40,      /* 이마트 16자. 우리가 조금 길 수는 있어도 40자를 넘으면 교재다 */
  긴장비율: 20,         /* 100자 넘는 장이 20% 를 넘으면 안 된다 (이마트 11%) */
  그림있는장비율: 50,    /* 「대부분 명반」이므로 절반은 넘어야 한다 (이마트 69%) */
};
export const 긴장기준 = 100;

/* ───────────────────────────── zip 읽기 ───────────────────────────── */

export function 집목록(묶음) {
  const 것 = [];
  for (let i = 0; i < 묶음.length - 4; i++) {
    if (묶음.readUInt32LE(i) !== 0x04034b50) continue;
    const 이름길 = 묶음.readUInt16LE(i + 26);
    것.push(묶음.slice(i + 30, i + 30 + 이름길).toString());
  }
  return 것;
}

export function 집에서꺼내기(묶음, 이름) {
  for (let i = 0; i < 묶음.length - 4; i++) {
    if (묶음.readUInt32LE(i) !== 0x04034b50) continue;
    const 압축 = 묶음.readUInt16LE(i + 8);
    const 크기 = 묶음.readUInt32LE(i + 18);
    const 이름길 = 묶음.readUInt16LE(i + 26);
    const 더 = 묶음.readUInt16LE(i + 28);
    if (묶음.slice(i + 30, i + 30 + 이름길).toString() !== 이름) continue;
    const z = 묶음.slice(i + 30 + 이름길 + 더, i + 30 + 이름길 + 더 + 크기);
    return (압축 === 8 ? zlib.inflateRawSync(z) : z).toString('utf8');
  }
  return null;
}

/** 슬라이드 XML 한 장에서 손님이 보는 글자만 뽑는다 */
export function 글자뽑기(xml) {
  return [...String(xml ?? '').matchAll(/<a:t>([^<]*)<\/a:t>/g)].map((m) => m[1]).join('');
}

/**
 * 🔴 한문 원문인가 — 한자가 이어서 넷 넘게 나오면 원문으로 본다.
 * ⛔ 한자 한둘은 용어 병기(甲木·正財)라 원문이 아니다. 그것까지 집으면 가짜가 는다.
 */
export function 한문원문인가(글) {
  const s = String(글 ?? '');
  return /[\u4e00-\u9fff]{5,}/.test(s);
}

export function 꾸러미재기(파일) {
  if (!fs.existsSync(파일)) return null;              /* 못 쟀다 — 0 으로 채우지 않는다 */
  const 묶음 = fs.readFileSync(파일);
  const 것들 = 집목록(묶음);
  const 장이름 = 것들.filter((n) => /^ppt\/slides\/slide\d+\.xml$/.test(n));
  const 글자수 = [];
  let 표있는장 = 0;
  let 그림있는장 = 0;
  for (const n of 장이름) {
    const x = 집에서꺼내기(묶음, n) || '';
    글자수.push(글자뽑기(x).length);
    if (/<a:tbl>/.test(x)) 표있는장++;
    if (/<p:pic>/.test(x)) 그림있는장++;
  }
  /* 노트에 한문 원문이 들어갔나 */
  const 노트이름 = 것들.filter((n) => /^ppt\/notesSlides\/notesSlide\d+\.xml$/.test(n));
  let 원문든노트 = 0;
  for (const n of 노트이름) {
    const 글 = 글자뽑기(집에서꺼내기(묶음, n) || '');
    if (한문원문인가(글)) 원문든노트++;
  }
  const 정렬 = [...글자수].sort((a, b) => a - b);
  return {
    장수: 장이름.length,
    글자가운데값: 정렬.length ? 정렬[Math.floor(정렬.length / 2)] : null,
    가장많은장: 정렬.length ? 정렬[정렬.length - 1] : null,
    긴장: 글자수.filter((v) => v > 긴장기준).length,
    표있는장, 그림있는장,
    노트수: 노트이름.length,
    원문든노트,
  };
}

export function 비율(위, 아래) { return 아래 ? Math.round((위 / 아래) * 100) : null; }

/* ───────────────────────────── 자가시험 ───────────────────────────── */

function 자가시험() {
  let 흠 = 0;
  const 검 = (이름, 됐나, 덧말 = '') => {
    console.log((됐나 ? '  ✅ ' : '  🔴 ') + 이름 + (덧말 ? ' — ' + 덧말 : ''));
    if (!됐나) 흠++;
  };
  console.log('■ 자가시험');

  검('① 슬라이드 글자를 뽑는다', 글자뽑기('<a:t>가</a:t><a:t>나</a:t>') === '가나');
  검('⛔ ② 태그 이름은 글자가 아니다', 글자뽑기('<p:sp><a:bodyPr/></p:sp>') === '');
  검('③ 한문 원문을 집는다', 한문원문인가('特運以方為重，如寅卯辰東方') === true);
  검('⛔ ④ 용어 병기는 원문이 아니다 — 甲木·正財 같은 것', 한문원문인가('갑목(甲木)과 정재(正財)') === false);
  검('⑤ 비율을 센다', 비율(1, 4) === 25);
  검('⛔ ⑥ 아래가 0 이면 «못 쟀다»로 낸다. 0% 로 채우지 않는다', 비율(1, 0) === null);
  검('⑦ 참는 선이 이마트 실측에서 나왔다 — 글자 가운데값 40자 이하',
    참는선.글자가운데값 === 40 && 참는선.그림있는장비율 === 50);
  검('⑧ 없는 파일은 «못 쟀다»로 낸다', 꾸러미재기(path.join(뿌리, '__없는파일__.pptx')) === null);

  console.log(흠 === 0 ? '\n✅ 자가시험 8개 통과' : '\n🔴 자가시험 ' + 흠 + '개 실패');
  return 흠;
}

