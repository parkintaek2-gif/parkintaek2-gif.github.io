  console.log('   ' + 긴장기준 + '자 넘는 장 ' + 잰것.긴장 + '장(' + 비율(잰것.긴장, 잰것.장수) + '%)'
    + ' · 그림 있는 장 ' + 잰것.그림있는장 + '장(' + 비율(잰것.그림있는장, 잰것.장수) + '%)'
    + ' · 표 있는 장 ' + 잰것.표있는장 + '장(' + 비율(잰것.표있는장, 잰것.장수) + '%)');
