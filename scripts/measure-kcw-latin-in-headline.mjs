#!/usr/bin/env node
/**
 * measure-kcw-latin-in-headline.mjs — **한국 지면 제목에 로마자가 얼마나 섞이나.** (5번, 2026-09-11)
 *
 *   node scripts/measure-kcw-latin-in-headline.mjs --자가시험
 *   node scripts/measure-kcw-latin-in-headline.mjs            재서 src/data 에 낸다
 *
 * ── 왜 이 축인가 ─────────────────────────────────────────────────────
 *
 * 우리 손님은 «한국어를 못 읽는 영어권»이다. 그 손님이 한국 지면을 열면 눈에 들어오는
 * 것은 로마자 조각뿐이다 — 「BTS」·「MV」·「OTT」·「Netflix」. 그러면 물음이 하나 생긴다:
 * **한국 제목의 몇 편에 로마자가 들어 있나, 그리고 그것은 어느 낱말인가.**
 *
 * ⭐ 같은 밑감(우리가 매일 받는 첫 화면 제목)을 쓰지만 **재는 것이 다르다** —
 *   나이(따옴표 든 수) · 돈(원) 을 이미 냈고, 이것은 «글자 체계»다.
 * ⛔ 「한국어가 영어에 오염됐다」는 말을 하지 않는다. 그것은 우리가 잴 수 있는 것이 아니고,
 *   우리 자리도 아니다. 세는 것은 «몇 편에 · 어느 낱말이»다.
 *
 * ── ⛔ 이 자가 지키는 것 ─────────────────────────────────────────────
 * ```
 * ⛔ 한 글자 로마자는 안 센다 — 「A형」·「S급」은 낱말이 아니다. 두 글자부터 본다
 * ⛔ 뜻을 가르지 않는다. 「Netflix」(회사) · 「MV」(줄임말) · 「comeback」(들온말)을
 *   한 칸에 넣고, 가른 것은 «글자 꼴»뿐이다(다 대문자 / 첫 글자만 대문자 / 다 소문자)
 * ⛔ 「손님이 그 낱말을 아나」는 안 쟀다. 그것은 사람에게 물어야 아는 것이다
 * ⛔ 0 을 「없다」로 적지 않는다 — 그 매체에서 «안 보였다»고 적는다
 * ⛔ 하루 한 번 받은 것이라 그날 첫 화면에 있던 것만 본다. 그날 지면 전체가 아니다
 * ```
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 하루읽기, 밑감방 } from './measure-kcw-money-vs-age-in-headline.mjs';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const 낼곳 = path.join(뿌리, 'src', 'data', 'kcw-latin-in-headline.json');

/** ⛔ 두 글자부터가 낱말이다 — 한 글자는 「A형」·「S급」처럼 등급 표시로 쓰인다 */
export const 로마자무늬 = /[A-Za-z][A-Za-z'’.&-]*[A-Za-z]/g;

/** 제목에서 로마자 조각을 꺼낸다. ⛔ 두 글자 미만은 버린다 */
export function 로마자조각(제목) {
  const s = String(제목 ?? '');
  const 것 = s.match(로마자무늬) || [];
  return 것.map((x) => x.replace(/^[^A-Za-z]+|[^A-Za-z]+$/g, '')).filter((x) => x.length >= 2);
}

/**
 * 글자 꼴을 가른다 — 뜻이 아니라 «꼴»이다.
 *   다대문자  BTS · MV · OTT      (줄임말이 대개 여기 온다)
 *   첫대문자  Netflix · Disney    (이름이 대개 여기 온다)
 *   다소문자  comeback · vs       (들온말·이음말이 대개 여기 온다)
 *   섞임      iPhone · YouTube    (⛔ 「대개」라고 적는 까닭이다 — 꼴은 뜻이 아니다)
 */
export function 글자꼴(낱말) {
  const s = String(낱말 ?? '').replace(/[^A-Za-z]/g, '');
  if (!s) return null;
  if (/^[A-Z]+$/.test(s)) return '다대문자';
  if (/^[a-z]+$/.test(s)) return '다소문자';
  if (/^[A-Z][a-z]+$/.test(s)) return '첫대문자';
  return '섞임';
}

/**
 * 🔴 매체가 «자기 이름»을 제목에 박는다 — 이것을 안 빼면 로마자 수가 부풀려진다.
 *   실측(10일): 매일경제의 으뜸 로마자가 「MK」 31개였다. 그 매체의 영문 약칭이다.
 *   스타뉴스의 「TView」·텐아시아의 「TEN」도 자기 지면 이름이다.
 * ⛔ 지어내지 않는다 — 이 넷은 그 매체가 스스로 쓰는 약칭이고, 실제 제목에서 확인했다.
 * ⚠ 빼고 센 값도 «함께» 낸다. 하나만 내면 어느 쪽이 답인지 우리가 정해 버리는 것이다.
 */
export const 제몸약칭 = {
  매일경제: ['MK'],
  스타뉴스: ['TView', 'STAR'],
  텐아시아: ['TEN', 'TenAsia'],
  동아일보: ['DA'],
};

/** 그 낱말이 그 매체의 «자기 이름»인가 */
export function 제몸인가(매체, 낱말) {
  const 것 = 제몸약칭[String(매체 ?? '')] || [];
  return 것.some((x) => x.toLowerCase() === String(낱말 ?? '').toLowerCase());
}

/** 매체별로 센다 */
export function 재기(하루들) {
  const 표 = new Map();
  const 날들 = [];
  for (const 하루 of 하루들 ?? []) {
    if (!Array.isArray(하루?.매체들) || !하루.매체들.length) continue;
    날들.push(하루.날);
    for (const o of 하루.매체들) {
      if (!표.has(o.매체)) {
        표.set(o.매체, {
          매체: o.매체, 갈래: o.갈래 ?? null, 제목수: 0, 로마자든제목: 0,
          제몸뺀제목: 0, 제몸조각: 0,
          조각수: 0, 꼴: { 다대문자: 0, 첫대문자: 0, 다소문자: 0, 섞임: 0 },
          낱말: new Map(),
          /* 🔴 우리가 세는 단위는 «제목-날»이다 — 같은 제목이 이튿날도 첫 화면에 있으면 두 번 센다.
             그것을 숨기면 「제목 1,388편」이 편수처럼 읽힌다. 낱개도 함께 센다. */
          낱개: new Set(),
        });
      }
      const t = 표.get(o.매체);
      for (const 제목 of o.제목들 ?? []) {
        t.제목수 += 1;
        t.낱개.add(제목);
        const 것 = 로마자조각(제목);
        if (!것.length) continue;
        t.로마자든제목 += 1;
        t.조각수 += 것.length;
        const 남 = 것.filter((w) => !제몸인가(o.매체, w));
        t.제몸조각 += 것.length - 남.length;
        if (남.length) t.제몸뺀제목 += 1;
        for (const w of 것) {
          const k = 글자꼴(w);
          if (k) t.꼴[k] += 1;
          /* ⚠ 낱말은 «적힌 그대로» 센다 — 대소문자를 뭉개면 MV 와 mv 가 섞인다 */
          t.낱말.set(w, (t.낱말.get(w) || 0) + 1);
        }
      }
    }
  }
  const 매체들 = [...표.values()].map((t) => ({
    매체: t.매체, 갈래: t.갈래, 제목수: t.제목수, 낱개제목수: t.낱개.size,
    로마자든제목: t.로마자든제목,
    몫: t.제목수 ? t.로마자든제목 / t.제목수 : null,
    /* ⭐ 자기 이름을 뺀 값. 이것과 위의 값을 «둘 다» 낸다 */
    제몸뺀제목: t.제몸뺀제목,
    제몸뺀몫: t.제목수 ? t.제몸뺀제목 / t.제목수 : null,
    제몸조각: t.제몸조각,
    조각수: t.조각수,
    제목당조각: t.로마자든제목 ? t.조각수 / t.로마자든제목 : null,
    꼴: t.꼴,
    으뜸낱말: [...t.낱말.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
      .slice(0, 8).map(([낱말, 수]) => ({ 낱말, 수, 꼴: 글자꼴(낱말) })),
  })).sort((a, b) => (b.몫 ?? -1) - (a.몫 ?? -1));

  /* 전체 낱말 순위 — 매체를 합쳐 센다 */
  const 모두 = new Map();
  for (const t of 표.values()) {
    for (const [w, n] of t.낱말) 모두.set(w, (모두.get(w) || 0) + n);
  }
  return {
    날수: 날들.length,
    날들,
    제목합: 매체들.reduce((a, x) => a + x.제목수, 0),
    낱개제목합: 매체들.reduce((a, x) => a + x.낱개제목수, 0),
    로마자든제목합: 매체들.reduce((a, x) => a + x.로마자든제목, 0),
    매체들,
    으뜸낱말전체: [...모두.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
      .slice(0, 15).map(([낱말, 수]) => ({ 낱말, 수, 꼴: 글자꼴(낱말) })),
    낱말종수: 모두.size,
  };
}

/* ── 자가시험 ───────────────────────────────────────────────────────── */
export function 자가시험() {
  const 것 = []; const 재다 = (이름, 됐나) => 것.push({ 이름, 됐나 });

  재다('로마자조각: 줄임말을 꺼낸다', 로마자조각('BTS 진, 컴백')[0] === 'BTS');
  재다('로마자조각: 여러 개를 꺼낸다', 로마자조각('Netflix OTT 1위').length === 2);
  재다('🔴 로마자조각: 한 글자는 안 센다 — 「A형」·「S급」은 낱말이 아니다',
    로마자조각('A형 독감, S급 신인').length === 0);
  재다('⛔ 로마자조각: 한국어만 있으면 0개', 로마자조각('한소희 열애 인정').length === 0);
  재다('로마자조각: 앞뒤 부호를 벗긴다', 로마자조각('(NCT) 마크')[0] === 'NCT');
  재다('로마자조각: 이음줄이 든 이름을 안 쪼갠다', 로마자조각('K-pop 열풍')[0] === 'K-pop');
  재다('⛔ 로마자조각: 빈 것·없는 것은 0개',
    로마자조각('').length === 0 && 로마자조각(null).length === 0);

  재다('글자꼴: 다 대문자', 글자꼴('BTS') === '다대문자');
  재다('글자꼴: 첫 글자만 대문자', 글자꼴('Netflix') === '첫대문자');
  재다('글자꼴: 다 소문자', 글자꼴('comeback') === '다소문자');
  재다('글자꼴: 섞임', 글자꼴('iPhone') === '섞임');
  /* 🔴 시험을 먼저 「섞임」으로 적었다가 틀렸다. 이음줄을 벗기면 「Kpop」이라 첫대문자다.
     ⭐ 시험이 자를 고쳐 준 자리다 — 꼴 이름을 뜻으로 읽으면 안 된다는 뜻이기도 하다.
     「K-pop」은 «이름»인데 꼴로는 「Netflix」와 같은 칸에 들어간다. 그래서 기사에 꼴을 답으로 쓰지 않는다. */
  재다('🔴 글자꼴: 「K-pop」은 이음줄을 벗겨 「Kpop」으로 재므로 첫대문자다 — 꼴은 뜻이 아니다',
    글자꼴('K-pop') === '첫대문자');
  재다('⛔ 글자꼴: 글자가 없으면 null', 글자꼴('123') === null && 글자꼴(null) === null);

  const 하루 = (매체, 갈래, 제목들) => ({ 날: '20260911', 매체들: [{ 매체, 갈래, 제목들 }] });
  재다('재기: 제목과 로마자든제목을 센다', (() => {
    const r = 재기([하루('A', 'K컬처', ['BTS 진', '한소희 인정'])]);
    return r.제목합 === 2 && r.매체들[0].로마자든제목 === 1 && Math.abs(r.매체들[0].몫 - 0.5) < 1e-9;
  })());
  재다('🔴 재기: 한 제목에 든 조각을 다 세지만 «제목 수»는 하나로 센다', (() => {
    const r = 재기([하루('A', null, ['Netflix OTT 1위'])]);
    return r.매체들[0].로마자든제목 === 1 && r.매체들[0].조각수 === 2;
  })());
  재다('재기: 낱말 순위를 낸다', (() => {
    const r = 재기([하루('A', null, ['BTS 컴백', 'BTS 신곡', 'NCT 무대'])]);
    return r.으뜸낱말전체[0].낱말 === 'BTS' && r.으뜸낱말전체[0].수 === 2;
  })());
  재다('🔴 재기: 대소문자를 뭉개지 않는다 — MV 와 mv 는 다른 낱말이다', (() => {
    const r = 재기([하루('A', null, ['MV 공개', 'mv 공개'])]);
    return r.낱말종수 === 2;
  })());
  재다('⛔ 재기: 로마자가 하나도 없는 매체는 몫 0 이다 — «없다»가 아니다', (() => {
    const r = 재기([하루('A', null, ['한소희 인정', '김도향 별세'])]);
    return r.매체들[0].몫 === 0 && r.매체들[0].로마자든제목 === 0;
  })());
  재다('⛔ 재기: 제목이 하나도 없으면 몫은 null — 0 으로 채우지 않는다', (() => {
    const r = 재기([하루('A', null, [])]);
    return r.매체들[0].몫 === null;
  })());
  재다('⛔ 재기: 빈 날은 «날»로 세지 않는다', (() => {
    const r = 재기([{ 날: '20260911', 매체들: [] }]);
    return r.날수 === 0;
  })());
  재다('재기: 제목당 조각수를 낸다', (() => {
    const r = 재기([하루('A', null, ['Netflix OTT 1위', 'BTS 진'])]);
    return Math.abs(r.매체들[0].제목당조각 - 1.5) < 1e-9;
  })());
  재다('재기: 몫이 큰 매체가 앞에 온다', (() => {
    const r = 재기([{
      날: '20260911',
      매체들: [{ 매체: '적음', 갈래: null, 제목들: ['한글만', '한글만2'] },
        { 매체: '많음', 갈래: null, 제목들: ['BTS'] }],
    }]);
    return r.매체들[0].매체 === '많음';
  })());
  재다('🔴 재기: 같은 제목이 이튿날 또 오면 «제목-날»로 두 번, 낱개로 한 번 센다', (() => {
    const r = 재기([
      { 날: '20260910', 매체들: [{ 매체: 'A', 갈래: null, 제목들: ['GUCCI 캠페인'] }] },
      { 날: '20260911', 매체들: [{ 매체: 'A', 갈래: null, 제목들: ['GUCCI 캠페인'] }] },
    ]);
    return r.제목합 === 2 && r.낱개제목합 === 1;
  })());
  재다('🔴 제몸인가: 매체의 자기 약칭을 안다 — 매일경제의 으뜸 로마자가 「MK」 31개였다',
    제몸인가('매일경제', 'MK') === true && 제몸인가('매일경제', 'AI') === false);
  재다('⛔ 제몸인가: 남의 약칭은 제 것이 아니다', 제몸인가('동아일보', 'MK') === false);
  재다('🔴 재기: 자기 이름만 든 제목은 «제몸뺀» 셈에서 빠진다', (() => {
    const r = 재기([{ 날: '20260911', 매체들: [{ 매체: '매일경제', 갈래: null, 제목들: ['MK 단독', 'AI 투자'] }] }]);
    const o = r.매체들[0];
    return o.로마자든제목 === 2 && o.제몸뺀제목 === 1 && o.제몸조각 === 1;
  })());
  재다('⛔ 재기: 자기 이름과 다른 낱말이 함께 든 제목은 «남는다»', (() => {
    const r = 재기([{ 날: '20260911', 매체들: [{ 매체: '매일경제', 갈래: null, 제목들: ['MK AI 대담'] }] }]);
    return r.매체들[0].제몸뺀제목 === 1;
  })());
  재다('재기: 꼴을 가른다', (() => {
    const r = 재기([하루('A', null, ['BTS 와 Netflix 와 comeback'])]);
    const k = r.매체들[0].꼴;
    return k.다대문자 === 1 && k.첫대문자 === 1 && k.다소문자 === 1;
  })());

  const 실패 = 것.filter((x) => !x.됐나);
  console.log(`■ 자가시험 ${것.length - 실패.length}/${것.length}`);
  for (const x of 실패) console.log(`  🔴 ${x.이름}`);
  return 실패.length === 0;
}

