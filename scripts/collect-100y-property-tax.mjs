#!/usr/bin/env node
/**
 * collect-100y-property-tax.mjs — **재산세, 5년 사이 얼마나 늘고 줄었나 (전국·시도별)**
 *
 * ── 왜 (2026-09-06 · 2번, 콘텐트 갭 스캔) ────────────────────────
 * 오늘 archive/raw/community-desk 구글트렌드(KR)에 「재산세」가 «갈래없음»으로 잡혀
 * 있었다(유닛 자동분류가 안 걸렸을 뿐, 실제로는 3번 축과 정확히 맞는다) — 9월은
 * 재산세 2기분(주택분 절반+토지분) 고지서가 나가는 달이라 매년 이맘때 실제로 검색이
 * 뜬다. 저장소에 재산세 수집기가 아예 없어(collect-100y-*.mjs 46개 확인) 갭이었다.
 *
 * ── 표 ────────────────────────────────────────────────────────
 *   TX_11007_A645  org 110(행정안전부)  「9-1-1. 재산세 과세현황(총괄)」
 *   정부ㆍ재정 > 지방세통계 > 지방세 부과·징수 실적 > 지방세 세목별 부과실적 > 9. 재산세
 *
 * ── ⭐ 실측으로 찾은 것 ──────────────────────────────────────────
 * 전국 재산세 세액은 2022년(24.3조원) 정점을 찍고 2023년 22.5조원으로 -7.2% 줄었다가
 * 2024년 22.9조원으로 소폭(+1.6%) 반등했다 — 그런데 건수(과세 건)는 그 사이 줄곧
 * 6,000만 건 안팎으로 거의 그대로다. **건수는 그대로인데 세액만 출렁였다** — 공시가격
 * (과세표준)이 그사이 조정됐다는 뜻일 수 있으나, 이 표만으로는 원인까지는 못 잰다.
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · 「구계·시계·군계」는 실제 지역이 아니라 그 아래 구/시/군을 합산한 소계 행이다 —
 *   시도별 순위에서 반드시 빼야 한다(안 빼면 서울이 두 번 잡히는 식으로 부풀려진다)
 * · 세대·개인별 부담이 아니라 «전국 합계»다 — 한 가구가 얼마 내는지는 이 표로 못 잰다
 * · 주택분·건축물분·토지분이 합쳐진 총괄표다 — 어느 종류가 늘고 줄었는지는 못 가른다
 * · 왜 2023년에 줄었는지(공시가격 조정 등 정책 원인)는 이 표가 말해 주지 않는다 —
 *   숫자만 재고, 원인은 재산세 산정 근거(과세표준) 표를 따로 봐야 한다
 *
 * 쓰는 법  node scripts/collect-100y-property-tax.mjs [--selftest]
 */
import fs from 'node:fs';
import { 오늘 } from './_kst.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '110';
export const TBL = 'TX_11007_A645';
export const 소계행들 = ['총계', '구계', '시계', '군계'];

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/** ⭐ KOSIS 단위는 「천원」이다. 1조원 = 10^12원 = 10^9천원 — /1e9다.
 *  /1e8로 잘못 나누면 10배 부풀어 오른다(실제로 한 번 그렇게 냈다가 이 시험이 잡았다). */
export function 조원으로(천원값) {
  return 천원값 == null ? null : Number((천원값 / 1e9).toFixed(2));
}

/** ⭐ 시도별 순위에서 소계 행(총계·구계·시계·군계)을 뺀다 — 안 빼면 진짜 지역이 아닌
 *  합산 행이 순위에 끼어 서울·경기가 실제보다 낮아 보이거나 순위 자체가 뒤틀린다. */
export function 진짜지역만(행들) {
  return 행들.filter((r) => !소계행들.includes(r.지역));
}

export function 변화율(전, 후) {
  if (전 == null || 후 == null || 전 === 0) return null;
  return Number((((후 - 전) / 전) * 100).toFixed(1));
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② 쉼표 든 큰 수를 읽는다', 수로('60,956,652') === 60956652);
  본다('③ 소계행 목록에 넷 다 있다', 소계행들.length === 4 && 소계행들.includes('구계'));

  const 표본 = [
    { 지역: '총계', v: 100 }, { 지역: '서울특별시', v: 30 }, { 지역: '구계', v: 25 },
    { 지역: '경기도', v: 20 }, { 지역: '시계', v: 15 }, { 지역: '군계', v: 5 },
  ];
  const 걸러짐 = 진짜지역만(표본);
  본다('④ 소계행 넷을 다 뺀다', 걸러짐.length === 2);
  본다('⑤ 진짜 지역만 남는다(서울·경기)', 걸러짐.every((r) => ['서울특별시', '경기도'].includes(r.지역)));

  본다('⑥ 변화율 계산(-7.2%)', Math.abs(변화율(24299033206, 22545985941) - (-7.2)) < 0.05);
  본다('⑦ 0으로 나누지 않는다', 변화율(0, 100) === null);
  본다('⑧ 값이 없으면 null', 변화율(null, 100) === null);
  본다('⑨ 천원→조원 변환 — 2024년 실측값(229억 아니라 22.9조가 맞다)',
    조원으로(22911874297) === 22.91);
  본다('⑩ /1e8로 잘못 나누면 10배 부푼다 — 그 값과 다름을 확인', 조원으로(22911874297) !== 229.12);
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-property-tax.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  const j = await (await fetch(
    `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
    + `&format=json&jsonVD=Y&orgId=${ORG}&tblId=${TBL}&itmId=ALL&objL1=ALL&objL2=ALL&prdSe=Y&newEstPrdCnt=5`)).json();
  if (!Array.isArray(j)) throw new Error(`${TBL}: ${JSON.stringify(j).slice(0, 200)}`);

  const 연도들 = [...new Set(j.map((x) => x.PRD_DE))].sort();
  const 최신 = 연도들.at(-1);

  const 전국연도별 = 연도들.map((y) => {
    const 건수 = 수로(j.find((x) => x.PRD_DE === y && x.C1_NM === '총계' && x.C2_NM === '합계' && x.ITM_NM === '건수')?.DT);
    const 세액천원 = 수로(j.find((x) => x.PRD_DE === y && x.C1_NM === '총계' && x.C2_NM === '합계' && x.ITM_NM === '세액')?.DT);
    return { 연도: y, 건수, 세액조원: 조원으로(세액천원) };
  });

  const 시도별원본 = j
    .filter((x) => x.PRD_DE === 최신 && x.ITM_NM === '세액' && x.C2_NM === '합계')
    .map((x) => ({ 지역: x.C1_NM, 세액천원: 수로(x.DT) }));
  const 시도별 = 진짜지역만(시도별원본)
    .map((r) => ({ 지역: r.지역, 세액조원: 조원으로(r.세액천원) }))
    .sort((a, b) => (b.세액조원 ?? 0) - (a.세액조원 ?? 0));

  /* 🔴 자가대조 — 진짜 지역 세액 합이 «총계»와 거의 같아야 한다(소계행을 잘 뺐다면) */
  const 전국총계세액 = 전국연도별.find((r) => r.연도 === 최신)?.세액조원;
  const 지역합 = Number(시도별.reduce((a, r) => a + (r.세액조원 ?? 0), 0).toFixed(2));
  const 오차율 = 전국총계세액 ? Number((Math.abs(지역합 - 전국총계세액) / 전국총계세액 * 100).toFixed(2)) : null;
  const 자가대조 = {
    '지역 합 ≈ 전국 총계': { 전국총계세액, 지역합, 오차율, 맞나: 오차율 != null && 오차율 < 1 },
    뜻: '17개 시도 세액을 더하면 전국 총계와 거의 같아야 한다 — 소계행(구계 등)을 안 뺐으면 훨씬 커진다',
  };

  const 최근낙차 = 변화율(
    전국연도별[전국연도별.length - 2]?.세액조원,
    전국연도별[전국연도별.length - 1]?.세액조원,
  );
  const 정점대비최신 = (() => {
    const 정점 = 전국연도별.reduce((a, b) => ((b.세액조원 ?? -1) > (a.세액조원 ?? -1) ? b : a));
    return { 정점연도: 정점.연도, 정점세액조원: 정점.세액조원, 최신대비변화율: 변화율(정점.세액조원, 전국연도별.at(-1).세액조원) };
  })();

  const 낸다 = {
    무엇: '재산세, 5년 사이 얼마나 늘고 줄었나 (전국·시도별)',
    만든날: 오늘(),
    최신,
    출처: {
      기관: '행정안전부 · 지방세통계', 표: '9-1-1. 재산세 과세현황(총괄)',
      창구: 'KOSIS', orgId: ORG, tblId: TBL,
    },
    전국연도별,
    시도별_최신년도: 시도별,
    '⭐ 최근 1년 변화율': 최근낙차,
    '⭐ 정점 대비 최신': 정점대비최신,
    '⚠ 이 자료가 못 가르는 것': [
      '구계·시계·군계는 실제 지역이 아니라 그 아래 구/시/군의 합산 소계 행입니다 — 시도별 순위에서 뺐습니다.',
      '전국·시도 합계입니다 — 한 가구·한 사람이 얼마 내는지는 이 표로 못 잽니다.',
      '주택분·건축물분·토지분이 합쳐진 총괄표입니다 — 어느 종류가 늘고 줄었는지는 못 가릅니다.',
      '세액이 줄고 는 까닭(공시가격 조정 등)은 이 표가 말해 주지 않습니다 — 숫자만 잰 것입니다.',
    ],
    자가대조,
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/property-tax.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
  console.log(`   전국 세액(조원) 연도별: ${전국연도별.map((r) => `${r.연도} ${r.세액조원}`).join(' · ')}`);
  console.log(`   최근 1년 변화율: ${최근낙차}% · 정점(${정점대비최신.정점연도}) 대비: ${정점대비최신.최신대비변화율}%`);
  console.log(`   시도별 1~3위: ${시도별.slice(0, 3).map((r) => `${r.지역} ${r.세액조원}조`).join(' · ')}`);
  console.log(`   자가대조: 지역합 ${지역합}조 vs 전국총계 ${전국총계세액}조 (오차 ${오차율}%) — ${자가대조['지역 합 ≈ 전국 총계'].맞나 ? '✅ 맞음' : '🔴 안 맞음'}`);
}
