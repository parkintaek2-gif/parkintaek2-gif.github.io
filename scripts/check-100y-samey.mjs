/* ── 재는 법 ─────────────────────────────────────────────────── */

/**
 * 본문만 꺼낸다 — `</nav>` 와 `<footer>` 사이.
 * ⛔ 머리말·꼬리말을 세면 **전부 100%** 가 나온다. 그건 닮은 것이 아니라 **같은 틀**이다.
 */
export function 본문꺼내기(글) {
  const s = String(글);
  const 앞 = s.indexOf('</nav>');
  const 뒤 = s.indexOf('<footer');
  const 안 = 앞 >= 0 && 뒤 > 앞 ? s.slice(앞 + 6, 뒤) : s;
  return 안
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 문장으로 쪼개고 숫자를 지운다.
 * ⭐ 숫자를 지우는 것이 이 자의 핵심이다 — 「졸업자 247명」과 「졸업자 105명」은
 *   심사 눈에 **같은 문장**이다. 우리도 같게 본다.
 */
export function 문장들(본문) {
  return String(본문)
    .split(/(?<=[.?!。])\s+|\n+/)
    .map((s) => s.trim())
    .filter((s) => s.length >= 12) /* 너무 짧은 조각은 견줄 값이 없다 */
    .map((s) => s.replace(/[\d,]+(?:\.\d+)?/g, '#'));
}

/**
 * 갈래 하나를 잰다.
 * @param 지면들 [{이름, 문장:[…]}]
 * @param 문턱 그 문장이 갈래의 몇 배 이상에 나오면 「흔한 문장」인가 (기본 0.5 = 절반)
 */
export function 갈래재기(지면들, 문턱 = 0.5) {
  const n = 지면들.length;
  if (n < 2) return null; /* ⚠ 견줄 상대가 없다. 안 센다 */
  const 몇장에 = new Map();
  for (const p of 지면들) {
    for (const s of new Set(p.문장)) 몇장에.set(s, (몇장에.get(s) ?? 0) + 1);
  }
  /**
   * 🔴 **두 장 이상에 나와야 「흔한 문장」이다.** 자가시험 ⑧⑨ 가 이걸로 잡혔다 —
   *   장이 둘일 때는 **한 장에만 있는 문장도 `1/2 = 0.5`** 라 문턱을 넘어 버렸다.
   *   ⛔ 한 장에만 있는 문장은 정의상 **닮은 것이 아니다.** 그런데 자가 「100% 닮았다」고 냈다.
   */
  const 흔한 = new Set([...몇장에.entries()].filter(([, c]) => c >= 2 && c / n >= 문턱).map(([s]) => s));

  const 값들 = 지면들.map((p) => {
    const 총 = p.문장.reduce((a, s) => a + s.length, 0);
    if (!총) return { 이름: p.이름, 닮음: 0, 총 };
    const 같은 = p.문장.filter((s) => 흔한.has(s)).reduce((a, s) => a + s.length, 0);
    return { 이름: p.이름, 닮음: Math.round((같은 / 총) * 1000) / 10, 총 };
  });
  const 가운데 = (a) => {
    const b = [...a].sort((x, y) => x - y);
    const m = b.length >> 1;
    return b.length % 2 ? b[m] : Math.round(((b[m - 1] + b[m]) / 2) * 10) / 10;
  };
  return {
    장수: n,
    가운데닮음: 가운데(값들.map((v) => v.닮음)),
    가장닮은: [...값들].sort((a, b) => b.닮음 - a.닮음)[0],
    가장다른: [...값들].sort((a, b) => a.닮음 - b.닮음)[0],
    흔한문장수: 흔한.size,
    /** 그 갈래에서 제일 흔한 문장들 — **여기를 갈라야 값이 내려간다** */
    흔한보기: [...몇장에.entries()]
      .filter(([, c]) => c / n >= 문턱)
      .sort((a, b) => b[1] - a[1] || b[0].length - a[0].length)
      .slice(0, 5)
      .map(([s, c]) => ({ 문장: s.slice(0, 70), 몇장: c, 몫: Math.round((c / n) * 100) })),
    값들,
  };
}

