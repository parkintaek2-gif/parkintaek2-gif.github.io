/* ── 전수 재기 ───────────────────────────────────────────────── */
function 걷기(d, 모음 = []) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) 걷기(p, 모음);
    else if (f.name.endsWith('.html')) 모음.push(p);
  }
  return 모음;
}

function 전수() {
  const 것들 = 걷기(빌드);
  /* 🔴 첫 화면은 dist/100y.html — **폴더 밖이다.** 오늘 두 번 빠뜨렸다 */
  const 첫 = path.join(뿌리, 'dist', '100y.html');
  if (fs.existsSync(첫)) 것들.push(첫);

  const 갈래별 = new Map();
  for (const p of 것들) {
    const 상대 = path.relative(빌드, p).replace(/\\/g, '/');
    const 갈래 = 상대.startsWith('..') ? 'home' : (상대.includes('/') ? 상대.split('/')[0] : 상대.replace(/\.html$/, ''));
    const 문장 = 문장들(본문꺼내기(fs.readFileSync(p, 'utf8')));
    if (!갈래별.has(갈래)) 갈래별.set(갈래, []);
    갈래별.get(갈래).push({ 이름: 상대, 문장 });
  }
  return { 것들, 갈래별 };
}

