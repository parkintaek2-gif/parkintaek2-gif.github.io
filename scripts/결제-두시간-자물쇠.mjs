/** 재는 자의 출력에서 판정을 뽑는다. ⛔ 못 읽으면 «못 쟀다»이지 «멀쩡하다»가 아니다 */
export function 읽어낸다(글) {
  const s = String(글 || '');
  const m = /■ 갈무리 — (\d+) \/ (\d+) 가지가 팔린다/.exec(s);
  if (!m) return { 쟀나: false, 까닭: '갈무리 줄을 못 찾았다' };
  const 팔린다 = Number(m[1]), 모두 = Number(m[2]);
  if (!Number.isFinite(팔린다) || !Number.isFinite(모두) || modu(모두)) {
    return { 쟀나: false, 까닭: '수를 못 읽었다' };
  }
  const 줄 = (이름) => {
    const r = new RegExp('🔴 ' + 이름 + ' (\\d+) — (.+)');
    const x = r.exec(s);
    return x ? { 수: Number(x[1]), 것들: x[2].split(' · ').map((t) => t.trim()) } : { 수: 0, 것들: [] };
  };
  return {
    쟀나: true, 팔린다, 모두,
    값틀림: 줄('값이 다르다'),
    못냄: 줄('못 낸다'),
    못잼: (function () {
      const x = /⬜ 못 쟀다 (\d+) — (.+)/.exec(s);
      return x ? { 수: Number(x[1]), 것들: x[2].split(' · ').map((t) => t.trim()) } : { 수: 0, 것들: [] };
    }()),
  };
  function modu(n) { return !(n > 0); }
}

/** 알려야 하나 — ⛔ 같은 것을 되풀이해 보채지 않는다 */
export function 알릴까(이번, 지난것, 지금 = Date.now()) {
  if (!이번.쟀나) {
    /* 못 쟀다 — 두 번 잇따라 못 재면 그것도 알린다(자가 죽은 것일 수 있다) */
    const 이어서 = (지난것 && 지난것.못잰횟수 ? 지난것.못잰횟수 : 0) + 1;
    return { 보낸다: 이어서 >= 2 && !(지난것 && 지난것.못잰알림), 왜: '못쟀다', 못잰횟수: 이어서 };
  }
  const 지금열쇠 = 열쇠만들기(이번);
  if (지금열쇠 === '') {
    /* 다 팔린다 — 풀렸으면 「풀렸다」를 한 번 알리고 기억을 지운다 */
    const 막혀있었나 = !!(지난것 && 지난것.열쇠);
    return { 보낸다: 막혀있었나, 왜: '풀렸다', 못잰횟수: 0 };
  }
  /* 막혔다 — 같은 꼴이면 다시 안 보낸다. 꼴이 바뀌면(새 상품이 막히면) 다시 보낸다 */
  const 같나 = 지난것 && 지난것.열쇠 === 지금열쇠;
  return { 보낸다: !같나, 왜: '막혔다', 열쇠: 지금열쇠, 못잰횟수: 0 };
}

/** 무엇이 막혔나를 한 글자로 — 꼴이 같으면 같은 사고다 */
export function 열쇠만들기(이번) {
  if (!이번.쟀나) return '못쟀다';
  const a = (이번.값틀림 && 이번.값틀림.것들 || []).slice().sort();
  const b = (이번.못냄 && 이번.못냄.것들 || []).slice().sort();
  if (!a.length && !b.length) return '';
  return 'v:' + a.join('|') + '#p:' + b.join('|');
}

