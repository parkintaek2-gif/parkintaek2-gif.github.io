// 투자AI — ③리스크 관리자 (결정론, 독립)
// 한도를 감시하고 «멈춘다». ⛔ 매매를 못 한다. 멈추기만 한다.
// ②펀드매니저는 ③을 못 멈춘다 — 이 방향이 통제를 통제로 만든다(설계 §2-2).
// 리스크관리AI가 왜 있는가: 「그것이 틀렸을 때 무엇을 잃는가」. 셋째 자리가 회사 성격을 정한다(홍익인간 §4).

export const 기본한도 = {
  종목상한: 0.20,     // 한 종목이 전체의 20%를 못 넘는다
  섹터상한: 0.40,     // 한 섹터에 40% 넘게 몰리지 않는다
  일일손실한도: -0.03, // 하루 -3% 넘으면 그날 발주를 멈춘다
  최대낙폭한도: -0.15, // 누적 -15% 넘으면 전 포지션 정리 후 «사람이 다시 켜야» 한다(자동복구 없음)
};

// 목표비중을 한도에 맞춰 «깎는다». 위반은 기록으로 남긴다(조용히 통과시키지 않는다).
// 반환: { 승인비중, 위반[], 발주중단(bool), 낙폭잠금(bool) }
export function 심사(목표, 상태, 한도 = 기본한도, 섹터맵 = {}) {
  const 위반 = [];
  const 낙폭잠금 = (상태?.누적수익 ?? 0) <= 한도.최대낙폭한도 || 상태?.낙폭잠금 === true;
  const 발주중단 = 낙폭잠금 || (상태?.당일수익 ?? 0) <= 한도.일일손실한도;

  if (낙폭잠금) 위반.push({ 규칙: '최대낙폭한도', 값: 상태?.누적수익, 조치: '전 포지션 정리·사람이 재기동해야 함' });
  else if (발주중단) 위반.push({ 규칙: '일일손실한도', 값: 상태?.당일수익, 조치: '그날 발주 중단' });

  // 발주 중단이면 신규 목표는 전부 현금(리스크가 매매층을 멈춘 것)
  if (발주중단) return { 승인비중: {}, 위반, 발주중단: true, 낙폭잠금 };

  // 종목상한: 넘는 만큼 깎는다
  let 깎임 = {};
  for (const [코드, w] of Object.entries(목표)) {
    if (w > 한도.종목상한) { 위반.push({ 규칙: '종목상한', 종목: 코드, 값: w, 조치: `→ ${한도.종목상한}` }); 깎임[코드] = 한도.종목상한; }
    else 깎임[코드] = w;
  }
  // 섹터상한: 섹터 합이 넘으면 그 섹터 종목들을 비례 축소
  const 섹터합 = {};
  for (const [코드, w] of Object.entries(깎임)) { const sec = 섹터맵[코드] ?? '미분류'; 섹터합[sec] = (섹터합[sec] ?? 0) + w; }
  for (const [sec, tot] of Object.entries(섹터합)) {
    if (tot > 한도.섹터상한 + 1e-9) {
      const 비 = 한도.섹터상한 / tot;
      위반.push({ 규칙: '섹터상한', 섹터: sec, 값: tot, 조치: `×${비.toFixed(3)}` });
      for (const [코드] of Object.entries(깎임)) if ((섹터맵[코드] ?? '미분류') === sec) 깎임[코드] *= 비;
    }
  }
  return { 승인비중: 깎임, 위반, 발주중단: false, 낙폭잠금: false };
}
