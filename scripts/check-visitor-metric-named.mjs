/**
 * check-visitor-metric-named.mjs — **방문자 수를 «지표 이름 없이» 적은 줄을 잡는다.** (5번, 2026-09-07)
 *
 * ── 🔴 왜 이 자가 생겼나 ─────────────────────────────────────
 * 사장님이 오늘 제 보고를 보고 바로 잡으셨다. 원문 —
 *
 *   「1번 │ 12:34 매시보고 — 순방문 101명…… **페이지뷰이지? 정확하게 용어를 써라**」
 *
 * 재 보니 사장님이 맞으셨다. 그 수는 `page_views`(페이지뷰)였다.
 * ⛔ 그리고 **같은 잘못이 세 시간 뒤 또 났다** — 1번 14:34 보고가 쿠키 기준 수(89명)를
 *   「실제 순방문자」로 올렸고, 4번이 발견해 정정을 요청했다.
 *
 * ⭐ 두 번 났으면 사람이 기억해서 지킬 일이 아니다. 이 저장소의 규칙 그대로 —
 *   **「말로 하는 규칙은 잊힌다. 겪은 것은 자가시험이 달린 검사로 굳힌다.」**
 *
 * ── 왜 이것이 목표를 흔드나 ──────────────────────────────────
 * 사장님 9월 목표가 **「유닛당 하루 평균 방문자 1,000명」**이다.
 * 같은 사이트·같은 28일인데 세 수가 이렇게 벌어진다(klifemap 실측) —
 * ```
 * 순방문자(totalUsers)        99      ← 이것이 목표의 기준이다
 * 방문 횟수(sessions)        215
 * 지면 열림(screenPageViews) 670      ← 일곱 배
 * ```
 * 이름을 잘못 붙이면 **달성한 것처럼 보인다.** 나쁜 뜻이 없어도 그렇게 된다.
 *
 * ── ⛔ 이 자가 지키는 것 ────────────────────────────────────
 * ⛔ 「방문자 N명」이라 적었으면 그 줄이나 바로 옆에 «지표 이름»이 있어야 한다
 * ⛔ 쿠키·서버로그 기준이면 그렇게 적어야 한다 — 「실제」라는 말로 대신하지 않는다
 * ⚠ 이 자는 «막지» 않는다. 메모는 사람이 급히 쓰는 글이라 막으면 메모를 안 쓴다.
 *   대신 «어느 줄인지»를 집어 준다. 고칠 사람이 바로 찾게.
 *
 * 쓰는 법
 *   node scripts/check-visitor-metric-named.mjs
 *   node scripts/check-visitor-metric-named.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';

/** 우리가 쓰기로 한 이름들 — 이 가운데 하나가 붙어 있어야 한다 */
export const 옳은이름 = [
  'totalUsers', 'sessions', 'screenPageViews',
  '지면 열림', '방문 횟수', '페이지뷰', 'page_views', 'pageview',
  '쿠키기준', '쿠키 기준', '서버 요청', '로그 기준', '접근로그',
];

/** 수가 붙은 방문자 말 — 「순방문 101」·「방문자 386명」·「순방문자수 68」 */
export const 걸리는말 = /(순방문자수|순방문자|순방문|방문자)\s*[:은는이가]?\s*([0-9][0-9,]*)\s*(명|人)?/;

export function 이름이붙었나(글) {
  const s = String(글 ?? '');
  return 옳은이름.some((n) => s.includes(n));
}

/**
 * 한 줄을 본다. ⛔ 「이름이 없다」와 「방문자 말이 아예 없다」를 다른 말로 낸다.
 * @param 줄 그 줄
 * @param 이웃 앞뒤 줄을 이어 붙인 글 (이름이 옆 줄에 있을 수 있다)
 */
export function 줄재기(줄, 이웃 = '') {
  const m = 걸리는말.exec(String(줄 ?? ''));
  if (!m) return { 걸림: false };
  /* ⭐ 「2번 인계」처럼 수를 아예 안 적은 것은 걸지 않는다 — 그것은 정직한 미룸이다 */
  const 수 = Number(String(m[2]).replace(/,/g, ''));
  if (!Number.isFinite(수)) return { 걸림: false };
  if (이름이붙었나(줄) || 이름이붙었나(이웃)) return { 걸림: false, 이름있음: true };
  return {
    걸림: true, 말: m[1], 수,
    까닭: `「${m[1]} ${m[2]}」에 지표 이름이 없다 — 순방문자(totalUsers)인지 페이지뷰인지 읽는 사람이 모른다`,
  };
}

/**
 * ⭐ 이 잘못을 «이야기하는» 줄은 봐준다.
 *   첫 판을 돌리니 4번이 「그렇게 부르지 마십시오」라고 «경고한» 줄과, 제가
 *   「그 이름 그대로 옮겼습니다」라고 «반성한» 줄까지 잡혔다.
 *   ⛔ 잘못을 고치려고 쓴 글을 잘못으로 세면, 고치는 사람이 벌을 받는 셈이다.
 *   ⇒ 정정·경고·반성의 말이 같이 있으면 봐준다. 다만 «수를 새로 보고하는» 줄은 안 봐준다.
 */
export const 이야기하는말 = [
  '부르지 마', '정정', '틀렸', '잘못', '그 이름 그대로', '바로잡', '거둡니다', '과했습니다',
  '지표 이름이 없다', '페이지뷰이지', '용어를 써라',
];

export function 이야기하는줄인가(줄) {
  const t = String(줄 ?? '');
  return 이야기하는말.some((w) => t.includes(w));
}

/**
 * 「실제」로 이름을 대신한 것 — 쿠키·로그 수를 「실제」라 부르는 것이 오늘 난 사고다.
 *
 * ⭐ [고침] 처음엔 `totalUsers` 만 봐줬는데, 「89명 (실제 순방문자, 쿠키 기준 최소치)」처럼
 *   «바탕을 밝힌» 줄까지 잡혔다. 밝혔으면 벌할 것이 없다 — 위 규칙과 같게 맞춘다.
 *   ⛔ 벌할 것은 «바탕을 안 밝히고 「실제」로 갈음한» 줄이다.
 */
export function 실제라부르나(줄) {
  const s = String(줄 ?? '');
  if (!/실제\s*(순방문자|방문자)/.test(s)) return false;
  return !이름이붙었나(s);
}

/* ── 자가시험 ─────────────────────────────────────────────── */
export function 자가시험() {
  let 통 = 0; let 실 = 0;
  const 봐 = (말, 참) => { if (참) { 통++; console.log('  ✅ ' + 말); } else { 실++; console.log('  🔴 ' + 말); } };

  봐('🔴 사장님이 잡으신 그 줄을 잡는다',
    줄재기('[진행] 1번 12:34 매시보고(5번께)·순방문101·매출0').걸림 === true);
  봐('「방문자 386명」도 잡는다', 줄재기('100yearmap 방문자 386명').걸림 === true);
  봐('「순방문자수 68명」도 잡는다', 줄재기('순방문자수 68명 (오늘 누적)').걸림 === true);
  봐('쉼표가 든 수도 잡는다', 줄재기('순방문자 1,234명').수 === 1234);

  봐('✅ totalUsers 가 붙으면 안 잡는다',
    줄재기('순방문자(totalUsers) 99명').걸림 === false);
  봐('✅ 페이지뷰라 적었으면 안 잡는다',
    줄재기('순방문 103 (페이지뷰, 봇 제외)').걸림 === false);
  봐('✅ 쿠키기준이라 적었으면 안 잡는다',
    줄재기('순방문자 85명 (쿠키기준·참고용)').걸림 === false);
  봐('✅ 이름이 «옆 줄»에 있어도 안 잡는다',
    줄재기('순방문자 99명', '지표는 totalUsers 다').걸림 === false);

  봐('⛔ 수가 없으면 안 잡는다 — 「2번 인계」는 정직한 미룸이다',
    줄재기('| 순방문자 | 2번 인계 |').걸림 === false);
  봐('⛔ 방문자 말이 없는 줄은 안 잡는다', 줄재기('오늘 텍스트 6편 발행').걸림 === false);
  봐('⛔ 빈 줄에 안 터진다', 줄재기('').걸림 === false && 줄재기(null).걸림 === false);

  /* ⚠ [고침] 이 시험은 처음에 `'쿠키기준 실제 순방문자 89명'` 을 «잡아야 한다»고 적었다.
     규칙을 「바탕을 밝히면 봐준다」로 맞추면서 그 줄은 **봐주는 것이 옳아졌다** —
     「쿠키기준」이 바탕을 밝힌 말이다. 그래서 시험을 «규칙에 맞게» 고쳤다.
     ⛔ 규칙을 시험에 맞춰 되돌리지 않았다. 시험이 규칙을 따라온 것이다. */
  봐('🔴 바탕을 «안 밝히고» 「실제 순방문자」라 부른 것을 잡는다',
    실제라부르나('오늘 실제 순방문자 89명입니다') === true);
  봐('✅ 바탕(쿠키기준)을 밝혔으면 봐준다',
    실제라부르나('쿠키기준 실제 순방문자 89명') === false);
  봐('✅ totalUsers 와 함께면 「실제」를 봐준다',
    실제라부르나('실제 순방문자(totalUsers) 99명') === false);
  봐('⛔ 「실제」가 없으면 안 잡는다', 실제라부르나('순방문자 99명') === false);
  봐('⭐ 바탕을 밝힌 「실제 순방문자, 쿠키 기준」은 봐준다',
    실제라부르나('89명 (실제 순방문자, 쿠키 기준 최소치)') === false);
  봐('🔴 바탕을 안 밝힌 「실제 순방문자」만 잡는다',
    실제라부르나('실제 순방문자 89명') === true);

  봐('⭐ 「그렇게 부르지 마십시오」 같은 경고 줄은 봐준다',
    이야기하는줄인가('잠깐, 89명을 「실제 순방문자」로 부르지 마십시오') === true);
  봐('⭐ 반성하는 줄도 봐준다',
    이야기하는줄인가('제가 「순방문 101」을 그 이름 그대로 옮겼습니다') === true);
  봐('⛔ 그냥 수를 보고하는 줄은 안 봐준다',
    이야기하는줄인가('[진행] 1번 12:34 매시보고·순방문101·매출0') === false);

  봐('까닭에 두 지표 이름이 다 들어간다',
    /totalUsers/.test(줄재기('순방문 101명').까닭) && /페이지뷰/.test(줄재기('순방문 101명').까닭));

  console.log(`\n방문자 지표 이름 검사 — 자가시험 ${통}가지 통과 · ${실}가지 실패`);
  if (실) process.exit(1);
  return 통;
}

/* ── 주된 일 ─────────────────────────────────────────────── */
function 훑기() {
  const 통 = 자가시험();
  /** ⚠ 최근 것만 본다 — 옛 메모를 다 고칠 수는 없다. 「앞으로」를 지키는 자다 */
  const 최근줄수 = Number((process.argv.find((a) => a.startsWith('--최근=')) || '').split('=')[1]) || 400;
  const 볼것 = [
    { 이름: 'docs/세션간-메모.md', 길: path.join('docs', '세션간-메모.md') },
    { 이름: 'klifemap/docs/1번-4번-메모.md', 길: path.join('..', 'klifemap', 'docs', '1번-4번-메모.md') },
  ];

  let 흠 = 0;
  for (const { 이름, 길 } of 볼것) {
    if (!fs.existsSync(길)) { console.log(`\n⬜ ${이름} — 없다(못 쟀다)`); continue; }
    const 줄들 = fs.readFileSync(길, 'utf8').split(/\r?\n/);
    const 시작 = Math.max(0, 줄들.length - 최근줄수);
    const 걸린 = [];
    for (let i = 시작; i < 줄들.length; i++) {
      const 이웃 = [줄들[i - 1], 줄들[i + 1], 줄들[i + 2]].filter(Boolean).join(' ');
      if (이야기하는줄인가(줄들[i])) continue;   /* ⭐ 잘못을 고치려고 쓴 글은 벌하지 않는다 */
      const r = 줄재기(줄들[i], 이웃);
      if (r.걸림) 걸린.push({ 줄번호: i + 1, 글: 줄들[i].trim().slice(0, 110), 까닭: r.까닭 });
      else if (실제라부르나(줄들[i])) {
        걸린.push({
          줄번호: i + 1, 글: 줄들[i].trim().slice(0, 110),
          까닭: '쿠키·로그 기준 수를 「실제 순방문자」라 불렀다 — 「실제」는 지표 이름이 아니다',
        });
      }
    }
    console.log(`\n■ ${이름} — 마지막 ${최근줄수}줄 가운데`);
    if (!걸린.length) { console.log('   ✅ 지표 이름 없이 적은 방문자 수 없다'); continue; }
    for (const x of 걸린) {
      흠++;
      console.log(`   🔴 ${이름}:${x.줄번호}`);
      console.log(`      ${x.글}`);
      console.log(`      ${x.까닭}`);
    }
  }

  console.log('\n⭐ 우리가 쓰기로 한 이름 (2026-09-07 · 사장님 지적 뒤 2번·4번과 맞춤)');
  console.log('   순방문자(totalUsers)      서로 다른 사람 수 — 「하루 1,000명」의 기준');
  console.log('   방문 횟수(sessions)       몇 번 왔나');
  console.log('   지면 열림(screenPageViews) 페이지뷰');
  console.log('   쿠키기준·서버 요청 수(로그) GA4 가 아닌 것 — 이 이름으로 «따로» 적는다');
  console.log('\n⚠ 이 자는 막지 않는다. 메모는 급히 쓰는 글이라 막으면 메모를 안 쓴다.');
  if (흠) console.log(`\n🔴 이름이 빠진 줄 ${흠}개 — 위 줄번호를 고친다.`);
  else console.log('\n✅ 걸리는 줄이 없다.');
  console.log(`자가시험 ${통}가지 통과.`);
}

if (process.argv.includes('--자가시험')) 자가시험();
else 훑기();
