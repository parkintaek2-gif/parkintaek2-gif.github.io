/**
 * 앵커가 있는 줄 번호(1-base). 못 찾으면 null.
 *
 * ⚠ **색인 표 자체를 원문으로 착각하면 안 된다.**
 *   표에 요약 문구가 들어 있어서, 그냥 찾으면 표의 줄 번호(17줄·18줄…)를 가리킨다.
 *   실제로 처음에 그렇게 나왔다. 색인 구간은 건너뛴다.
 */
function 줄찾기(줄들, 앵커, 제외) {
  for (let i = 0; i < 줄들.length; i++) {
    if (제외 && i >= 제외.시작 && i <= 제외.끝) continue;
    if (줄들[i].includes(앵커)) return i + 1;
  }
  return null;
}

export function 표만들기(원문) {
  const 줄들 = 원문.split(/\r?\n/);
  const a = 줄들.findIndex((l) => l.includes(시작표시));
  const b = 줄들.findIndex((l) => l.includes(끝표시));
  const 제외 = a !== -1 && b !== -1 ? { 시작: a, 끝: b } : null;
  const 못찾음 = [];
  const 행 = 지시.map((d) => {
    if (d.파일밖) return { ...d, 위치: d.파일밖 };
    const n = 줄찾기(줄들, d.앵커, 제외);
    if (n === null) 못찾음.push(d.요약);
    return { ...d, 위치: n === null ? '⚠ 없음' : `${n}줄` };
  });
  const 표 = [
    '## 📌 사장님 지시 — 한눈에',
    '',
    '**이 표는 색인이다. 원문을 대체하지 않는다** — 판단이 필요하면 원문을 읽는다.',
    '🔴 은 어기면 사업이 흔들리는 것. 줄 번호는 `npm test` 가 확인하고 `npm run index:fix` 가 고친다.',
    '',
    '| | 지시 | 요점 | 원문 |',
    '|---|---|---|---|',
    ...행.map((r) => `| ${r.급} | **${r.요약}** | ${r.상세} | ${r.위치} |`),
  ].join('\n');
  return { 표, 못찾음 };
}

function main() {
  const 고침 = process.argv.includes('--fix');
  const 원문 = readFileSync(파일, 'utf8');

  /* 기존 색인을 떼고 나머지(=원문)를 기준으로 줄 번호를 잰다.
     ⚠ 색인 자체가 줄 수를 늘리므로, 색인을 넣은 **뒤**의 번호여야 한다.
       그래서 두 번 돌린다 — 넣고, 다시 재고, 다시 넣는다. */
  const 색인제거 = (s) => {
    const a = s.indexOf(시작표시);
    const b = s.indexOf(끝표시);
    if (a === -1 || b === -1) return s;
    return s.slice(0, a) + s.slice(b + 끝표시.length).replace(/^\n+/, '\n');
  };

  const 뼈대 = 색인제거(원문);
  const 첫줄끝 = 뼈대.indexOf('\n', 뼈대.indexOf('\n') + 1); // 제목 다음
  const 앞 = 뼈대.slice(0, 첫줄끝 + 1);
  const 뒤 = 뼈대.slice(첫줄끝 + 1);

  let 결과 = null;
  let 못찾음 = [];
  for (let i = 0; i < 3; i++) {           // 번호가 수렴할 때까지
    const 후보 = 결과 ?? `${앞}\n${시작표시}\n(자리)\n${끝표시}\n${뒤}`;
    const { 표, 못찾음: nf } = 표만들기(후보);
    못찾음 = nf;
    const 다음 = `${앞}\n${시작표시}\n${표}\n${끝표시}\n${뒤}`;
    if (다음 === 결과) break;
    결과 = 다음;
  }

  if (못찾음.length) {
    console.error('⚠ 원문에서 앵커를 못 찾았다 — 지시가 지워졌거나 문구가 바뀌었다:');
    못찾음.forEach((x) => console.error('   · ' + x));
    console.error('   scripts/claude-index.mjs 의 앵커를 원문에 맞추거나, 지시를 복구할 것.');
    process.exit(1);
  }

  if (고침) {
    if (결과 !== 원문) { writeFileSync(파일, 결과); console.log('✅ CLAUDE.md 지시 색인을 갱신했다.'); }
    else console.log('변경 없음.');
    return;
  }

  if (결과 !== 원문) {
    console.error('✕ CLAUDE.md 지시 색인이 실제와 어긋난다. `npm run index:fix` 로 고칠 것.');
    process.exit(1);
  }
  console.log(`✅ 지시 색인 ${지시.length}건 · 줄 번호 일치`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
