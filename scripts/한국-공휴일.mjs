/** ⛔ toISOString() 금지 — UTC 라 새벽에 하루가 어긋난다. 이 PC 가 이미 KST 다 */
export function 날글(d = new Date()) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return null;
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** 표에 그 해가 들어 있나. **없으면 부르는 쪽이 멈춘다** — 평일로 치지 않는다 */
export function 아는해인가(d = new Date()) {
  const 날 = 날글(d);
  return 날 !== null && Object.prototype.hasOwnProperty.call(공휴일표, 날.slice(0, 4));
}

/** 토·일인가 */
export function 주말인가(d = new Date()) {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return false;
  const w = d.getDay();
  return w === 0 || w === 6;
}

/** 공휴일 이름 — 아니면 null. ⚠ 모르는 해도 null 이다. `아는해인가()` 를 함께 본다 */
export function 공휴일이름(d = new Date()) {
  const 날 = 날글(d);
  if (날 === null) return null;
  return 공휴일표[날.slice(0, 4)]?.[날] ?? null;
}

/**
 * **쉬는 날인가** — 토·일이거나 공휴일이면 그렇다.
 * 되돌리는 값은 `{ 쉰다, 까닭, 안다 }` 셋이다.
 *   · `안다 === false` 면 **판정을 믿지 않는다.** 표에 없는 해다
 *   · `쉰다 === null` 은 「모른다」다 — ⛔ `false` 와 같이 보지 않는다
 */
export function 쉬는날인가(d = new Date()) {
  const 날 = 날글(d);
  if (날 === null) return { 쉰다: null, 까닭: '날짜를 못 읽었다', 안다: false };
  if (주말인가(d)) return { 쉰다: true, 까닭: d.getDay() === 0 ? '일요일' : '토요일', 안다: true };
  if (!아는해인가(d)) return { 쉰다: null, 까닭: `${날.slice(0, 4)}년 공휴일 표가 없다`, 안다: false };
  const 이름 = 공휴일이름(d);
  if (이름) return { 쉰다: true, 까닭: 이름, 안다: true };
  return { 쉰다: false, 까닭: '평일', 안다: true };
}

