/** 이보다 이른 설립연도는 자료 오류로 본다 */
export const 가장이른해 = 1950;
/** 해산이 기록된 팀이 이보다 적은 나라는 비율을 내지 않는다 */
export const 적어도팀 = 20;
/** 「오래갔다」로 볼 해 */
export const 오래선 = 10;

/** 연도 네 자리만 읽는다. ⛔ 못 읽으면 null — 0 으로 만들지 않는다 */
export function 해읽기(값, 올해 = new Date().getFullYear()) {
  const s = String(값 ?? '').trim();
  const m = s.match(/^(\d{4})/);
  if (!m) return null;
  const y = Number(m[1]);
  return y >= 가장이른해 && y <= 올해 ? y : null;
}

/**
 * 한 팀의 «산 해»를 낸다. ⛔ 해산 연도가 없으면 null — 그것은 0년이 아니다.
 * ⛔ 해산이 설립보다 이르면 자료 오류이므로 null 로 두고 세지 않는다.
 */
export function 산해(팀, 올해 = new Date().getFullYear()) {
  const s = 해읽기(팀?.start, 올해);
  if (s == null) return { 설립: null, 산해: null, 까닭: '설립연도를 못 읽었다' };
  const e = 해읽기(팀?.end, 올해);
  if (e == null) return { 설립: s, 산해: null, 까닭: '해산연도가 없다' };
  if (e < s) return { 설립: s, 산해: null, 까닭: '해산이 설립보다 이르다 — 자료 오류' };
  return { 설립: s, 산해: e - s, 까닭: null };
}

/** ⛔ 비면 null */
export function 가운뎃값(수들) {
  const v = (수들 ?? []).map(Number).filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  if (!v.length) return null;
  const m = Math.floor(v.length / 2);
  return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2;
}

export function 한나라재기(팀들, { 올해 = new Date().getFullYear(), 선 = 오래선 } = {}) {
  const 수명 = []; const 코호트수명 = []; const 기록된설립 = [];
  let 셀수있는팀 = 0; let 기록없음 = 0; let 자료오류 = 0; let 코호트 = 0;
  for (const 팀 of Object.values(팀들 ?? {})) {
    const r = 산해(팀, 올해);
    if (r.설립 == null) continue;
    셀수있는팀 += 1;
    const 코호트인가 = r.설립 <= 올해 - 선;
    if (코호트인가) 코호트 += 1;
    if (r.산해 == null) {
      if (r.까닭 === '해산연도가 없다') 기록없음 += 1; else 자료오류 += 1;
      continue;
    }
    수명.push(r.산해);
    /* ⭐ «해산이 기록된» 팀의 설립연도를 모은다 — 나라끼리 견줄 수 있나를 이것으로 가른다 */
    기록된설립.push(r.설립);
    if (코호트인가) 코호트수명.push(r.산해);
  }
  const 기록됨 = 수명.length;
  const 넉넉 = 기록됨 >= 적어도팀;
  const 안에끝 = (해) => 수명.filter((x) => x < 해).length;
  return {
    셀수있는팀,
    /* ⛔ 「활동 중」이라 부르지 않는다 — 조용히 멈춘 팀도 여기 든다 */
    해산기록없음: 기록없음,
    자료오류,
    해산기록됨: 기록됨,
    기록률: 셀수있는팀 > 0 ? 기록됨 / 셀수있는팀 : null,
    넉넉,
    /* ⭐ 이것이 기록률 차이를 견딘 수다 — «기록된 팀 안에서»의 비율이다 */
    십년안몫: 넉넉 ? 안에끝(선) / 기록됨 : null,
    오년안몫: 넉넉 ? 안에끝(5) / 기록됨 : null,
    십년안수: 안에끝(선),
    오년안수: 안에끝(5),
    수명가운뎃값: 넉넉 ? 가운뎃값(수명) : null,
    /* 🔴 이 수를 반드시 함께 본다 — 나라마다 다르면 위 몫을 나라끼리 견줄 수 없다 */
    설립가운뎃값: 가운뎃값(기록된설립),
    /* 설립이 오래된 코호트만 따로 — 「오래갈 기회가 있던 팀」 */
    코호트: { 팀수: 코호트, 해산기록됨: 코호트수명.length,
      십년안수: 코호트수명.filter((x) => x < 선).length },
  };
}

/** 설립연도 가운뎃값이 이보다 벌어지면 나라끼리 견주지 않는다 */
export const 견줄설립차 = 5;

/**
 * 🔴 나라끼리 견줄 수 있나. **이 자의 핵이다.**
 * 해산이 기록된 팀들의 설립연도 가운뎃값이 나라마다 크게 다르면, 견주는 것은 나라가 아니라
 * «코호트»다. 그러면 오래 살 기회 자체가 달라서 「10년 안에 끝난 몫」이 뜻을 잃는다.
 * ⇒ 그때는 못 견준다고 «적고» 비교를 내지 않는다. 2026-09-11 에 그것으로 기사 하나를 폐기했다.
 */
export function 견줄만한가(나라별, { 차선 = 견줄설립차 } = {}) {
  const 것들 = Object.entries(나라별 ?? {})
    .filter(([, v]) => v?.넉넉 && Number.isFinite(v?.설립가운뎃값));
  if (것들.length < 2) return { 견줄수있나: false, 까닭: '견줄 나라가 둘도 안 된다', 벌어짐: null };
  const 해들 = 것들.map(([, v]) => v.설립가운뎃값);
  const 벌어짐 = Math.max(...해들) - Math.min(...해들);
  if (벌어짐 > 차선) {
    return {
      견줄수있나: false,
      벌어짐,
      까닭: `해산이 기록된 팀들의 설립연도 가운뎃값이 ${벌어짐}년 벌어져 있다`
        + ` (${것들.map(([k, v]) => `${k} ${v.설립가운뎃값}`).join(' · ')}).`
        + ' 견주는 것은 나라가 아니라 코호트다 — 오래 살 기회 자체가 다르다',
    };
  }
  return { 견줄수있나: true, 벌어짐, 까닭: null };
}

export function 재기(자료, { 올해 = new Date().getFullYear() } = {}) {
  const 나라별 = {};
  for (const [나라, 팀들] of Object.entries(자료?.byCountry ?? {})) {
    나라별[나라] = 한나라재기(팀들, { 올해 });
  }
  return { 올해, 오래선, 나라별, 견줌: 견줄만한가(나라별) };
}

