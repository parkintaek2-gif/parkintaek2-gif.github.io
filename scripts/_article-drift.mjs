/**
 * **기사가 「틀린」 것인가 「낡은」 것인가를 가른다.**
 *
 * ── 왜 이 자가 생겼나 ─────────────────────────────────────────────────
 * 🔴 2026-09-07 — `npm test` 에 기사 대조 검사 다섯이 빨강이었다. 26줄이 어긋나 있었다.
 *   열어 보니 어긋난 까닭이 하나였다 —
 *```
 *     기사 dataAsOf                     2026-08-25
 *     자료 갱신(korean-cast-joined)      2026-09-06     ← 12일 뒤에 자료가 움직였다
 *```
 *   기사는 8/25 의 사실을 말하고, 검사는 9/06 자료에 댄다. 그러니 영원히 빨강이다.
 *
 * ⛔ 이 저장소가 이미 적어 둔 것 그대로다 —
 *   「보는 검사를 막는 검사로 만들면 옛 자료 때문에 늘 빨강이 되고, **그러면 아무도 안 본다.**」
 *   (`check-kcw-all.mjs`) 그리고 `check-kcw-article-numbers.mjs` 는 이 규칙을 이미 안다 —
 *   「⭐ `dataAsOf` 를 적은 기사가 그때의 수를 말하는 것은 **오류가 아니다.**」
 *
 * ⭐ 그런데 그 규칙이 «자마다» 다시 쓰여 있지 않아, 다섯 자가 낡음을 틀림으로 냈다.
 *   그래서 규칙을 한자리에 둔다. 자는 이것을 불러 쓴다.
 *
 * ── ⛔ 이 자가 «봐주는 자»가 되면 안 된다 ─────────────────────────────
 * ⛔ 「dataAsOf 가 있으면 다 넘긴다」가 아니다. 그러면 오타가 통째로 숨는다.
 *   자료가 «움직인 뒤»에만 낡음이다. 자료가 그대로인데 어긋나면 그것은 **틀림**이다.
 * ⛔ dataAsOf 가 «없는» 기사는 낡음으로 봐주지 않는다 — 언제의 사실인지 아무도 모른다.
 *   그게 더 위험하다(article-numbers 가 같은 말을 한다).
 * ⚠ 낡음이라고 «고칠 필요가 없다»는 뜻이 아니다. 고칠 순서가 뒤라는 뜻이고,
 *   그것을 사람이 «보고 나서» 정하게 하려고 가르는 것이다.
 */
import fs from 'node:fs';

/**
 * 한국어 로케일 시각(`2026. 9. 6. 오전 2:18:00`)이나 ISO 를 다 읽는다.
 * ⛔ 못 읽으면 `null` 이다 — 0 도, 지금도 아니다.
 */
export function 때읽기(값) {
  const s = String(값 ?? '').trim();
  if (!s) return null;
  const m = s.match(/^(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\.\s*(오전|오후)?\s*(\d{1,2})?:?(\d{2})?/);
  if (m) {
    let 시 = m[5] ? Number(m[5]) % 12 : 0;
    if (m[4] === '오후') 시 += 12;
    /* ⚠ 이 PC 는 KST 다. Date 로 그대로 짓는다 — 9시간을 더하지 않는다 */
    return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 시, m[6] ? Number(m[6]) : 0);
  }
  const d = new Date(s);
  return Number.isNaN(d.getTime()) ? null : d;
}

/** 기사 앞말에서 `dataAsOf` 를 읽는다. ⛔ 없으면 null 이다 */
export function 기사의때(원문) {
  const m = String(원문 ?? '').match(/^dataAsOf:\s*(.+)$/m);
  return m ? 때읽기(m[1].trim()) : null;
}

/**
 * 자료가 기사보다 «뒤에» 움직였나.
 * ⛔ 어느 한쪽을 못 읽으면 `null` — 「그렇다」도 「아니다」도 아니다.
 */
export function 자료가움직였나(기사때, 자료때) {
  if (!(기사때 instanceof Date) || !(자료때 instanceof Date)) return null;
  return 자료때.getTime() > 기사때.getTime();
}

/** 며칠 벌어졌나. 못 재면 null */
export function 벌어진날(기사때, 자료때) {
  if (!(기사때 instanceof Date) || !(자료때 instanceof Date)) return null;
  return Math.round((자료때.getTime() - 기사때.getTime()) / 864e5);
}

/**
 * 어긋난 것을 무엇으로 부를까.
 *
 * `틀림`  — 고쳐야 한다. 자료가 안 움직였는데 어긋났거나, 언제의 사실인지 안 적혀 있다
 * `낡음`  — 그때의 사실이다. 자료가 뒤에 움직였을 뿐이다
 */
export function 무엇으로부를까({ 기사때, 자료때 }) {
  if (!(기사때 instanceof Date)) {
    return { 종류: '틀림', 까닭: 'dataAsOf 가 없다 — 언제의 사실인지 알 수 없다. 이것이 더 위험하다' };
  }
  const 움 = 자료가움직였나(기사때, 자료때);
  if (움 === null) {
    return { 종류: '틀림', 까닭: '자료가 언제 갱신됐는지 못 읽었다 — 봐주지 않는다' };
  }
  if (!움) {
    return { 종류: '틀림', 까닭: '자료가 기사 뒤로 안 움직였다. 그러면 어긋난 것은 기사 쪽이다' };
  }
  const 날 = 벌어진날(기사때, 자료때);
  return { 종류: '낡음', 까닭: `기사는 그때의 사실을 말한다 — 자료가 ${날}일 뒤에 움직였다` };
}

/** 자료 파일의 `갱신` 칸을 읽는다. ⛔ 파일이나 칸이 없으면 null */
export function 자료의때(길) {
  try {
    const j = JSON.parse(fs.readFileSync(길, 'utf8'));
    return 때읽기(j.갱신 ?? j.잰때 ?? j.만든날 ?? j.generated ?? null);
  } catch { return null; }
}

