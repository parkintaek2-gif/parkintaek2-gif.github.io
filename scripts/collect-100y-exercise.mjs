#!/usr/bin/env node
/**
 * collect-100y-exercise.mjs — **몇 %가 규칙적으로 운동하나, 동호회로 하는 사람은 얼마나 되나**
 *
 * ── 왜 ─────────────────────────────────────────────────────────
 * 사장님(2026-08-22) — 「0~100세 × 다섯 분야(경제·문화·사회·예체능·교육)」 지시.
 * 예체능은 백년지도 전체에 지면이 0장이었다(docs 기획서 1장 매트릭스). 그 첫 지면.
 * ⭐ 사장님(방금): 「예체능 실기는 많은 동호회들이 활동한다. 나이들수록 더. 참조해」
 *   → 실제로 재 보니 **절반만 맞았다**. 동호회 참여율은 10대(2.2%)→50대(12.2%)까지는
 *   올라가지만 60대(11.9%)부터 다시 내려가 70대 이상(6.3%)에서는 20대보다도 낮다.
 *   "나이 들수록 계속 오른다"고 쓰면 사실과 다르다 — 사장님 말씀도 검증하고 정직하게 고친다.
 *
 * ── 표 둘, 같은 기관(문화체육관광부) ──────────────────────────────
 *   ① DT_113_STBL_1027807  규칙적 체육활동 참여 여부 및 빈도(2016~2025)
 *   ② DT_113_STBL_1027018  동호회 활동 참여 경험 여부(2021~2025) — 스포츠·문화예술 동호회를 합쳐 잰다
 *
 * ── ⚠ 이 자료가 못 가르는 것 ───────────────────────────────────
 * · 표본조사다 — 국민생활체육조사·문화향수실태조사 표본. 나이대별로 표본 크기가 다르다
 * · "동호회"는 스포츠·문화예술·취미오락을 다 합친 것이다 — 예체능 실기만 따로는 못 가른다
 * · 자기 응답이다 — 실제 운동 강도·시간을 재는 표가 아니다
 *
 * 쓰는 법  node scripts/collect-100y-exercise.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ORG = '113';
export const 표들 = { 운동: 'DT_113_STBL_1027807', 동호회: 'DT_113_STBL_1027018' };
export const 나이칸들 = ['10대', '20대', '30대', '40대', '50대', '60대', '70세 이상'];
/** ⚠ 동호회 표는 10대를 "15~19세"로, 70세 이상을 "70세이상"(붙여쓰기)으로 적는다 —
 *   같은 나이인데 표마다 이름이 다르다. 짐작하지 않고 표마다 실제 칸 이름을 그대로 쓴다 */
export const 동호회칸이름 = { '10대': '15~19세', '20대': '20대', '30대': '30대', '40대': '40대', '50대': '50대', '60대': '60대', '70세 이상': '70세이상' };

export function 수로(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s || s === '-' || s === 'X') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/** ⭐ 나이 들수록 계속 오르기만 하는가 — 사장님 가설을 있는 그대로 검증한다 */
export function 계속오르나(칸들, 키) {
  const 값들 = 칸들.map((r) => r[키]).filter((v) => v != null);
  if (값들.length < 나이칸들.length) return null;
  const 오름 = 값들.every((v, i) => i === 0 || v >= 값들[i - 1]);
  const 최고칸 = 칸들.reduce((a, b) => (b[키] > a[키] ? b : a));
  return { 오름, 최고칸: 최고칸.칸, 최고값: 최고칸[키] };
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };
  본다('① 빈칸을 0 으로 만들지 않는다', 수로('-') === null && 수로('') === null);
  본다('② 소수를 읽는다', 수로('12.2') === 12.2);
  본다('③ 계속 오르면 참', 계속오르나(
    [{ 칸: '10대', 값: 1 }, { 칸: '20대', 값: 2 }, { 칸: '30대', 값: 3 }, { 칸: '40대', 값: 4 },
      { 칸: '50대', 값: 5 }, { 칸: '60대', 값: 6 }, { 칸: '70세 이상', 값: 7 }], '값').오름 === true);
  본다('④ 중간에 내려가면 거짓', 계속오르나(
    [{ 칸: '10대', 값: 1 }, { 칸: '20대', 값: 2 }, { 칸: '30대', 값: 3 }, { 칸: '40대', 값: 4 },
      { 칸: '50대', 값: 5 }, { 칸: '60대', 값: 4 }, { 칸: '70세 이상', 값: 3 }], '값').오름 === false);
  본다('⑤ 최고칸을 찾는다', 계속오르나(
    [{ 칸: '10대', 값: 1 }, { 칸: '20대', 값: 2 }, { 칸: '30대', 값: 3 }, { 칸: '40대', 값: 4 },
      { 칸: '50대', 값: 12 }, { 칸: '60대', 값: 11 }, { 칸: '70세 이상', 값: 6 }], '값').최고칸 === '50대');
  본다('⑥ 칸이 모자라면 못 잰다', 계속오르나([{ 칸: '10대', 값: 1 }], '값') === null);
  process.exit();
}

const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'collect-100y-exercise.mjs';
if (내가직접불렸나) {
  const KEY = fs.readFileSync(path.join(뿌리, '.env'), 'utf8').match(/KOSIS_API_KEY\s*=\s*(.+)/)[1].trim();
  const 받기 = async (tbl) => {
    const j = await (await fetch(
      `https://kosis.kr/openapi/Param/statisticsParameterData.do?method=getList&apiKey=${KEY}`
      + `&format=json&jsonVD=Y&orgId=${ORG}&tblId=${tbl}&itmId=ALL&objL1=ALL&prdSe=Y&newEstPrdCnt=10`)).json();
    if (!Array.isArray(j)) throw new Error(`${tbl}: ${JSON.stringify(j).slice(0, 150)}`);
    return j;
  };

  const 운동j = await 받기(표들.운동);
  const 동호회j = await 받기(표들.동호회);

  const 운동최신 = [...new Set(운동j.map((x) => x.PRD_DE))].sort().at(-1);
  const 동호회최신 = [...new Set(동호회j.map((x) => x.PRD_DE))].sort().at(-1);
  const 운동값 = (칸, 항) => 수로(운동j.find((x) => x.PRD_DE === 운동최신 && x.C1_NM === 칸 && x.ITM_NM === 항)?.DT);
  const 동호회값 = (칸, 항) => 수로(동호회j.find((x) => x.PRD_DE === 동호회최신 && x.C1_NM === 칸 && x.ITM_NM === 항)?.DT);

  const 운동나이별 = 나이칸들.map((칸) => ({
    칸, 주1회이상: 운동값(칸, '주1회 이상'), 전혀안함: 운동값(칸, '전혀하지않는다'), 월3회이하: 운동값(칸, '월3회 이하'),
  }));
  const 동호회나이별 = 나이칸들.map((칸) => ({
    칸, 참여율: 동호회값(동호회칸이름[칸], '예'),
  }));

  /* 🔴 자가 대조 — 세 조각(전혀+주1회이상+월3회이하)을 더하면 100, 동호회는 예+아니오=100 */
  const 어긋난운동 = 운동나이별.filter((r) => {
    if (r.주1회이상 == null || r.전혀안함 == null || r.월3회이하 == null) return false;
    return Math.abs(r.주1회이상 + r.전혀안함 + r.월3회이하 - 100) > 0.5;
  });
  const 어긋난동호회 = 나이칸들.filter((칸) => {
    const 예 = 동호회값(동호회칸이름[칸], '예');
    const 아니오 = 동호회값(동호회칸이름[칸], '아니오');
    if (예 == null || 아니오 == null) return false;
    return Math.abs(예 + 아니오 - 100) > 0.5;
  });
  const 자가대조 = {
    '운동 세 조각 합 = 100': { 어긋난칸수: 어긋난운동.length, 맞나: 어긋난운동.length === 0 },
    '동호회 예+아니오 = 100': { 어긋난칸수: 어긋난동호회.length, 맞나: 어긋난동호회.length === 0 },
    뜻: '전혀안함+월3회이하+주1회이상(운동), 예+아니오(동호회)가 각각 100이어야 한다',
  };

  const 운동최고 = 계속오르나(운동나이별, '주1회이상');
  const 동호회최고 = 계속오르나(동호회나이별, '참여율');

  const 낸다 = {
    무엇: '몇 %가 규칙적으로 운동하나, 동호회로 하는 사람은 얼마나 되나',
    만든날: new Date().toISOString().slice(0, 10),
    최신: 운동최신, 동호회최신,
    출처: {
      기관: '문화체육관광부',
      표: '① 국민생활체육조사 「규칙적 체육활동 참여 여부 및 빈도」 · ② 「동호회 활동 참여 경험 여부」',
      창구: 'KOSIS', orgId: ORG, tblId: `${표들.운동} · ${표들.동호회}`,
    },
    '⛔ 사장님 가설 검증': `"동호회는 나이 들수록 더 활발하다"는 절반만 맞다 — ${동호회최고.최고칸}(${동호회최고.최고값}%)까지는 오르지만 그 뒤로는 다시 내려가, 70세 이상(${동호회나이별.find((r) => r.칸 === '70세 이상').참여율}%)은 20대보다도 낮다. 나이 들수록 «계속» 오르지는 않는다.`,
    '⚠ 이 자료가 못 가르는 것': [
      '표본조사입니다. 나이대별로 표본 크기가 달라 작은 칸일수록 오차가 큽니다.',
      '"동호회"는 스포츠·문화예술·취미오락을 다 합친 것입니다 — 예체능 실기 참여만 따로는 못 가릅니다.',
      '자기 응답입니다. 실제 운동 강도·시간을 재는 표가 아닙니다.',
    ],
    운동나이별, 동호회나이별, 운동최고, 동호회최고, 자가대조,
  };
  const 낼곳 = path.join(뿌리, 'src/data/100yearmap/exercise.json');
  fs.writeFileSync(낼곳, JSON.stringify(낸다, null, 1), 'utf8');

  console.log(`✅ ${path.relative(뿌리, 낼곳)}`);
  console.log(`   ${운동최신}년 · 주1회 이상 운동: ${운동나이별.map((r) => `${r.칸} ${r.주1회이상}%`).join(' · ')}`);
  console.log(`   ${동호회최신}년 · 동호회 참여율: ${동호회나이별.map((r) => `${r.칸} ${r.참여율}%`).join(' · ')}`);
  console.log(`   동호회 최고 나이대: ${동호회최고.최고칸}(${동호회최고.최고값}%) · 계속 오름: ${동호회최고.오름 ? '맞다' : '아니다(사장님 가설 절반만 맞음)'}`);
  console.log(`   자가대조: 운동 어긋난 칸 ${자가대조['운동 세 조각 합 = 100'].어긋난칸수}개 · 동호회 어긋난 칸 ${자가대조['동호회 예+아니오 = 100'].어긋난칸수}개`);
}
