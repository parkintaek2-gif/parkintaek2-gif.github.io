#!/usr/bin/env node
/**
 * check-title-change-cooldown.mjs — **제목을 고친 뒤 «재기 전에» 또 고치는 것을 막는다.**
 *
 * ── 왜 이 자가 생겼나 (2026-09-01, 5번) ────────────────────────────
 * 오늘 저는 「1페이지에 떠 있는데 클릭 0 인 지면이 422장·노출 1,889회」를 재고,
 * 작품 지면 133장의 제목을 바로 고치려 했습니다. 자리에 가 보니 앞선 세션이
 * 주석으로 **「9/05 전에는 이 줄을 고치지 마십시오」** 를 적어 두었더군요.
 *
 * 그 자리의 이력을 뽑아 보니 이랬습니다 —
 * ```
 *   시장 지면 제목   08-09  →  08-22  →  08-27      13일 · 5일 간격
 *   작품 지면 제목   08-22  →  08-25                 3일 간격
 * ```
 * ⛔ **효과가 자료에 쌓이기 전에 다음 손이 들어옵니다.** 그러면 두 변경이 겹쳐
 *    무엇이 들었는지 «영원히» 갈라낼 수 없습니다. 우리는 8/22·8/25·8/27 세 번을
 *    고쳐 놓고, 그중 무엇이 좋았는지 하나도 모릅니다.
 *
 * ── ⭐ 왜 «주석»이 아니라 «검사»인가 ──────────────────────────────
 * 그 금지는 이미 주석으로 있었습니다. 그런데 저는 그 파일을 열기 «전»까지 몰랐고,
 * 열지 않았다면 그냥 고쳤을 것입니다. 여섯 자리가 같은 저장소를 돌아가며 만집니다.
 * **사람이 기억해서 지키는 구조를 만들지 않습니다** (강령 ④).
 *
 * ── 무엇을 재나 ────────────────────────────────────────────────
 * ```
 *   ① 제목 줄이 마지막으로 바뀐 날      git log -L 로 그 «줄»의 이력을 뽑는다
 *   ② 그 뒤로 며칠이 지났나              오늘 - 마지막 변경일
 *   ③ 재도 되는 날까지 며칠 남았나        식은기간(기본 14일) - ②
 * ```
 * ⚠ 14일인 까닭 — Search Console 은 자료가 이틀 늦고, 구글이 새 제목을 다시 훑어
 *    스니펫에 반영하는 데 며칠이 걸립니다. 28일 창으로 재려면 그 창의 «절반» 이상이
 *    새 제목이어야 앞뒤가 갈립니다. 그것이 14일입니다.
 * ⛔ 이 수를 정확한 과학이라고 말하지 않습니다 — **고를 근거가 있는 선**이지 법칙이 아닙니다.
 *
 * ── ⛔ 이 자가 지키는 것 ────────────────────────────────────────
 * ⛔ 「고쳐도 된다」를 말하지 않습니다. **「아직 못 잰다」만 말합니다.** 고칠지는 사람이 정합니다.
 * ⛔ git 이 없거나 이력을 못 읽으면 «못 쟀다»로 끝냅니다. 통과로 적지 않습니다 (강령 ③).
 * ⚠ 제목 줄을 옮기거나 이름을 바꾸면 이 자가 그 자리를 놓칩니다. 그때는 못 쟀다고 나옵니다.
 *
 * 쓰는 법
 *   node scripts/check-title-change-cooldown.mjs
 *   node scripts/check-title-change-cooldown.mjs --자가시험
 *   node scripts/check-title-change-cooldown.mjs --날 21     식은기간을 바꾼다
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);

/** 기본 식은기간 — 위 주석의 까닭을 보십시오 */
export const 기본식은날 = 14;

/**
 * 지켜보는 자리들. **여러 장을 한 줄이 만드는 곳**만 넣습니다 —
 * 한 줄을 고치면 수백 장이 같이 바뀌므로, 겹치면 잃는 것이 큽니다.
 * ⚠ 기사처럼 한 장에 한 제목인 곳은 넣지 않습니다. 거기는 겹칠 일이 없습니다.
 */
export const 지켜볼자리 = [
  { 이름: '작품 지면', 길: 'src/pages/wikitip/title/[slug].astro', 몇장: '작품마다 한 장' },
  { 이름: '시장 지면', 길: 'src/pages/wikitip/market/[slug].astro', 몇장: '93장' },
];

/** 「YYYY-MM-DD」 두 날 사이의 날 수. ⛔ 시간대를 타지 않게 날짜만 셉니다 */
export function 며칠차이(앞, 뒤) {
  const a = Date.UTC(+앞.slice(0, 4), +앞.slice(5, 7) - 1, +앞.slice(8, 10));
  const b = Date.UTC(+뒤.slice(0, 4), +뒤.slice(5, 7) - 1, +뒤.slice(8, 10));
  return Math.round((b - a) / 86400000);
}

/** git log -L 출력에서 날짜들을 뽑습니다. ⛔ 못 읽으면 null 을 돌려줍니다(빈 배열이 아닙니다) */
export function 날짜뽑기(글) {
  if (글 == null) return null;
  const 나온것 = [...String(글).matchAll(/^(\d{4}-\d{2}-\d{2})\b/gm)].map((m) => m[1]);
  return 나온것.length ? 나온것 : null;
}

/** 한 자리의 제목 줄 이력을 읽습니다 */
function 이력읽기(상대길) {
  const 온길 = path.join(뿌리, 상대길);
  if (!fs.existsSync(온길)) return { 못잼: '파일이 없다' };
  let 글;
  try {
    글 = execFileSync(
      'git',
      ['log', '-L', `/const TITLE/,+1:${상대길}`, '--format=%ad %h %s', '--date=short'],
      { cwd: 뿌리, encoding: 'utf8', maxBuffer: 40 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] },
    );
  } catch {
    return { 못잼: 'git 이력을 못 읽었다 (줄을 옮겼거나 git 이 없다)' };
  }
  const 날들 = 날짜뽑기(글);
  if (!날들) return { 못잼: '이력에 날짜가 없다' };
  return { 날들 };
}

function 자가시험() {
  let 통과 = 0;
  let 실패 = 0;
  const 검 = (무엇, 참인가) => {
    if (참인가) { 통과 += 1; } else { 실패 += 1; console.log(`  ❌ ${무엇}`); }
  };

  검('같은 날은 0일', 며칠차이('2026-09-01', '2026-09-01') === 0);
  검('하루 뒤는 1일', 며칠차이('2026-08-31', '2026-09-01') === 1);
  검('달을 넘어도 센다', 며칠차이('2026-08-27', '2026-09-01') === 5);
  검('해를 넘어도 센다', 며칠차이('2025-12-31', '2026-01-01') === 1);
  검('거꾸로면 음수', 며칠차이('2026-09-01', '2026-08-31') === -1);

  검('날짜를 뽑는다',
    JSON.stringify(날짜뽑기('2026-08-27 abc 제목 바꿈\n2026-08-22 def 또\n')) === '["2026-08-27","2026-08-22"]');
  검('줄 첫머리가 아니면 안 뽑는다', 날짜뽑기('abc 2026-08-27 뒤에 있는 날짜') === null);
  검('빈 글은 못 쟀다(null)', 날짜뽑기('') === null);
  검('null 은 null 로', 날짜뽑기(null) === null);
  검('⛔ 빈 배열을 돌려주지 않는다', 날짜뽑기('아무 날짜 없음') !== '' && 날짜뽑기('아무 날짜 없음') === null);

  /* 🔴 이 자가 «막아야 할» 바로 그 상황을 시험합니다 —
     8/27 에 고쳤는데 9/01 에 또 고치려는 것. 5일밖에 안 지났으므로 막아야 합니다. */
  검('5일 지났으면 아직 못 잰다', 기본식은날 - 며칠차이('2026-08-27', '2026-09-01') === 9);
  검('14일 지났으면 잴 수 있다', 기본식은날 - 며칠차이('2026-08-18', '2026-09-01') === 0);
  검('20일 지났으면 넉넉하다', 기본식은날 - 며칠차이('2026-08-12', '2026-09-01') < 0);

  검('지켜볼 자리가 비어 있지 않다', 지켜볼자리.length >= 2);
  검('지켜볼 자리마다 길이 있다', 지켜볼자리.every((z) => typeof z.길 === 'string' && z.길.endsWith('.astro')));

  console.log(실패 === 0
    ? `✅ check-title-change-cooldown 자가시험 — 통과 ${통과} · 실패 0`
    : `❌ 자가시험 — 통과 ${통과} · 실패 ${실패}`);
  return 실패 === 0;
}

function main() {
  if (argv.includes('--자가시험') || argv.includes('--selftest')) {
    process.exit(자가시험() ? 0 : 1);
  }

  const i = argv.indexOf('--날');
  const 식은날 = i >= 0 ? Number(argv[i + 1]) || 기본식은날 : 기본식은날;
  const 오늘 = new Date().toISOString().slice(0, 10);

  console.log('■ 제목을 고친 뒤 «재기 전에» 또 고치려는 것은 아닌가\n');
  console.log(`   오늘 ${오늘} · 식은기간 ${식은날}일\n`);

  let 막힌곳 = 0;
  let 못잰곳 = 0;

  for (const 자리 of 지켜볼자리) {
    const r = 이력읽기(자리.길);
    if (r.못잼) {
      못잰곳 += 1;
      console.log(`   ⬜ ${자리.이름} — 못 쟀다: ${r.못잼}`);
      console.log(`      ⛔ 「통과」로 적지 않는다. 이 자리는 판단할 근거가 없다.\n`);
      continue;
    }
    const 마지막 = r.날들[0];
    const 지난날 = 며칠차이(마지막, 오늘);
    const 남은날 = 식은날 - 지난날;
    const 앞선것 = r.날들.slice(0, 4).join(' ← ');

    if (남은날 > 0) {
      막힌곳 += 1;
      console.log(`   🔴 ${자리.이름} (${자리.몇장}) — **아직 고치지 마십시오**`);
      console.log(`      마지막으로 바뀐 날 ${마지막} · ${지난날}일 지남 · ${남은날}일 더 기다립니다`);
      console.log(`      이력  ${앞선것}`);
      console.log(`      ⚠ 지금 고치면 ${마지막} 변경의 효과를 «영원히» 못 잽니다 — 두 변경이 겹칩니다.`);
      console.log(`      ⭐ 그 대신 할 것: 자물쇠가 없는 다른 갈래를 고치거나, 지면 «안»을 고칩니다`);
      console.log(`         (제목·설명이 아닌 곳은 이 자가 막지 않습니다).\n`);
    } else {
      console.log(`   ✅ ${자리.이름} (${자리.몇장}) — 재도 됩니다`);
      console.log(`      마지막으로 바뀐 날 ${마지막} · ${지난날}일 지남`);
      console.log(`      이력  ${앞선것}`);
      console.log(`      ⚠ 고치기 «전»에 지금 순위를 먼저 재서 적어 두십시오. 안 적으면 다음에도 못 갈라냅니다.\n`);
    }
  }

  console.log('⛔ 이 자는 「고쳐도 된다」를 말하지 않습니다 — **「아직 못 잰다」만 말합니다.**');
  console.log('⚠ 제목을 고칠 때는 그 자리 주석에 «언제 고쳤고 언제 다시 잴지»를 남기십시오.');

  if (막힌곳 > 0) {
    console.log(`\n🔴 아직 식지 않은 자리 ${막힌곳}곳.`);
    process.exitCode = 1;
    return;
  }
  if (못잰곳 > 0) {
    console.log(`\n⬜ 못 잰 자리 ${못잰곳}곳 — 깨진 것이 아니라 못 잰 것입니다.`);
    return;
  }
  console.log('\n✅ 지켜보는 자리가 모두 식었습니다.');
}

main();
