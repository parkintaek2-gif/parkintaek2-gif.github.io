/**
 * 말이 바뀌면 조사도 바뀐다. **양쪽 다 본다** —
 *   받침 있음 → 없음 (지면→페이지):  을→를 · 이→가 · 은→는 · 으로→로 · 과→와
 *   받침 없음 → 있음 (덩이→항목):    를→을 · 가→이 · 는→은 · 로→으로 · 와→과
 * ⚠ 자가시험이 「그 덩이를」을 「그 항목를」로 내는 것을 잡아 주어 알았다.
 *   한쪽만 넣으면 조용히 틀린 글이 나간다.
 */
/**
 * 🔴 [2026-10-22 12:5x · 5번] **괄호가 끼면 조사를 못 고쳤다.**
 *   실측 — 「까닭(제도·인식 변화 등)을」 → 「이유(제도·인식 변화 등)**을**」
 *   「까닭」은 받침이 있어 「을」이 맞았지만 「이유」는 받침이 없어 「를」이어야 한다.
 *   이 자가 바꿀 말 «바로 뒤»만 보는 탓에 괄호 뒤의 조사를 못 봤다.
 *   ⇒ 괄호(소·중·대)가 이어지면 짝이 맞는 닫는 괄호까지 건너뛰고 그 뒤의 조사를 본다.
 *   ⛔ 짝이 안 맞으면 손대지 않는다 — 어림으로 자르면 글자를 먹는다.
 */
export function 괄호건너뛰기(뒤) {
  const s = String(뒤 ?? '');
  const 짝 = { '(': ')', '（': '）', '[': ']', '{': '}', '「': '」', '〈': '〉' };
  let i = 0;
  for (;;) {
    /* 🔴 [2026-10-22] HTML 태그도 끼어든다 — 실측으로 「이름 풀이 페이지</a>은」이 나갔다.
       손님 화면에는 「페이지은」으로 보인다. 괄호와 똑같이 건너뛰고 뒤의 조사를 본다. */
    if (s[i] === '<') {
      const 끝 = s.indexOf('>', i + 1);
      if (끝 < 0) return i;
      i = 끝 + 1;
      continue;
    }
    if (짝[s[i]]) {
      const 끝 = s.indexOf(짝[s[i]], i + 1);
      if (끝 < 0) return i;      /* 짝이 없다 — 여기서 멈춘다 */
      i = 끝 + 1;
      continue;
    }
    return i;
  }
}

export function 조사맞추기(옛말, 새말, 뒤) {
  const 옛받침 = 받침있나(옛말[옛말.length - 1]);
  const 새받침 = 받침있나(새말[새말.length - 1]);
  if (옛받침 === 새받침) return { 조사: '', 먹은길이: 0 };   // 안 바뀌면 손댈 것이 없다
  const 짝 = 옛받침 ? 조사짝 : 조사짝.map(([a, b]) => [b, a]);
  const 건너뛴 = 괄호건너뛰기(뒤);
  const 볼곳 = 건너뛴 ? String(뒤 ?? '').slice(건너뛴) : String(뒤 ?? '');
  for (const [앞조사, 뒷조사] of 짝) {
    if (볼곳.startsWith(앞조사)) {
      /* 괄호를 건너뛰었으면 그 괄호째 그대로 두고 조사만 바꿔 끼운다 */
      return { 조사: String(뒤 ?? '').slice(0, 건너뛴) + 뒷조사, 먹은길이: 건너뛴 + 앞조사.length };
    }
  }
  return { 조사: '', 먹은길이: 0 };
}

const 덮 = (m) => ' '.repeat(m.length);

/**
 * 🔴🔴🔴 [2026-10-22 12:3x · 5번] **이 자는 프론트매터를 한 번도 안 덮고 있었다.**
 *   `^---\n` 로 찾는데 이 저장소 `.astro` 는 **CRLF** 라 실제로는 `---\r\n` 이다.
 *   그래서 `---` 사이의 «코드»까지 바꿔 왔다. 실측 —
 *     `자료.연금_수급_2024_갈래별.갈래`  →  `.종류별.종류`
 *   JSON 에는 `갈래` 로 들어 있으니 **빌드는 지나가고 화면에서 숫자만 사라진다.**
 *   ⛔ 「빌드가 지났다」를 「화면이 산다」로 읽지 않는다.
 *   ⚠ 다행히 라이브는 안 깨져 있었다 — 앞 세션이 이 자를 전체에 안 돌리고 손으로 골랐다.
 *
 * 🔴 JSX 표현식 `{ … }` 안도 코드다 — `<td>{r.갈래}</td>` 의 `r.갈래` 는 자료 칸 이름이다.
 *   중괄호를 세어서 덮는다. ⛔ 중첩된 `{}` 가 있으면 «안쪽까지» 덮는다 — 덜 바꾸는 쪽이 안전하다.
 *   그 안의 진짜 화면 글은 검사기가 잡고 사람이 본다.
 */
export function 중괄호속덮기(글) {
  const s = String(글 ?? '');
  const 칸 = s.split('');
  let 깊이 = 0;
  for (let i = 0; i < s.length; i += 1) {
    if (s[i] === '{') { 깊이 += 1; if (깊이 === 1) continue; }
    if (s[i] === '}') { 깊이 -= 1; if (깊이 < 0) 깊이 = 0; continue; }
    if (깊이 > 0) 칸[i] = ' ';
  }
  return 칸.join('');
}

/** 손님 눈에 안 보이는 데를 공백으로 덮는다 — 자리값이 밀리지 않게 길이를 지킨다 */
export function 안보이는곳덮기(글) {
  return 중괄호속덮기(String(글 ?? '')
    .replace(/<!--[\s\S]*?-->/g, 덮)
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, 덮)
    .replace(/<script\b[\s\S]*?<\/script>/gi, 덮)
    .replace(/<style\b[\s\S]*?<\/style>/gi, 덮)
    .replace(/<code\b[\s\S]*?<\/code>/gi, 덮)
    /* ⛔ `\r?` 를 빼지 않는다 — 이 저장소는 CRLF 다 */
    .replace(/^---\r?\n[\s\S]*?\r?\n---/, 덮));
}
/** 앞 글자가 한글이면 낱말이 아니라 활용이다 — 「정해지면」을 「지면」으로 안 센다 */
export const 낱말로있나 = (글, i) => !/[가-힣]/.test(글[i - 1] || '');

/**
 * 🔴🔴 [2026-10-22 13:0x · 5번] **이미 바뀐 말 뒤에 옛 조사가 남아 있었다.**
 *   실측 — `klifemap.ai의 이름 풀이 페이지</a>은` · `페이지</a>을` · `페이지(/x)은`
 *   손님 화면에는 **「페이지은」**으로 보인다. 23개 파일에 있었다.
 *   까닭 — 앞서 「지면」을 「페이지」로 바꿀 때 사이에 낀 태그를 못 넘어 조사를 안 고쳤고,
 *   그 뒤로는 「지면」이 없으니 이 자가 다시 찾아가지도 않았다.
 *   ⇒ **바꾼 말 자체를 다시 훑어** 뒤에 받침 조사가 붙어 있으면 바로잡는다.
 *
 * ⛔ 조사 뒤에 한글이 이어지면 손대지 않는다 — 「페이지이다」의 「이」는 조사가 아니다.
 * ⛔ 공백이 끼면 손대지 않는다 — 「페이지 은행」 같은 것을 깨뜨리지 않는다.
 */
export function 남은조사고치기(날) {
  let 글 = String(날 ?? '');
  let 수 = 0;
  const 새말들 = [...new Set(바꿀말.map((x) => x.새))].filter((w) => !받침있나(w[w.length - 1]));
  for (const 새말 of 새말들) {
    let i = -1;
    const 자리들 = [];
    while ((i = 글.indexOf(새말, i + 1)) !== -1) 자리들.push(i);
    자리들.reverse();                       /* 뒤에서부터 — 앞부터 하면 자리가 밀린다 */
    for (const 자리 of 자리들) {
      const 뒤 = 글.slice(자리 + 새말.length, 자리 + 새말.length + 200);
      const 건너뛴 = 괄호건너뛰기(뒤);
      const 볼곳 = 뒤.slice(건너뛴);
      for (const [받침조사, 민조사] of 조사짝) {
        if (!볼곳.startsWith(받침조사)) continue;
        const 조사뒤 = 볼곳[받침조사.length] || '';
        if (/[가-힣]/.test(조사뒤)) break;   /* 「페이지이다」 — 조사가 아니다 */
        글 = 글.slice(0, 자리 + 새말.length)
          + 뒤.slice(0, 건너뛴) + 민조사
          + 글.slice(자리 + 새말.length + 건너뛴 + 받침조사.length);
        수 += 1;
        break;
      }
    }
  }
  return { 글, 수 };
}

export function 바꾼글(날) {
  const 가린 = 안보이는곳덮기(날);
  const 자리들 = [];
  for (const { 날: 옛, 새 } of 바꿀말) {
    let i = -1;
    while ((i = 가린.indexOf(옛, i + 1)) !== -1) {
      if (!낱말로있나(가린, i)) continue;
      자리들.push({ i, 옛, 새 });
    }
  }
  자리들.sort((a, b) => b.i - a.i);            // 뒤에서부터 바꾼다 — 앞부터 하면 자리가 밀린다
  let 글 = 날;
  for (const { i, 옛, 새 } of 자리들) {
    /* ⚠ 4글자만 보면 괄호를 못 건너뛴다 — 「까닭(제도·인식 변화 등)을」이 그랬다.
       괄호가 없으면 맨 앞 글자만 보므로 길게 떠도 셈은 같다.
       ⛔ 괄호가 이 길이를 넘으면 짝을 못 찾아 조사를 «안» 바꾼다 — 안전한 쪽으로 실패한다. */
    const 뒤 = 글.slice(i + 옛.length, i + 옛.length + 200);
    const { 조사, 먹은길이 } = 조사맞추기(옛, 새, 뒤);
    글 = 글.slice(0, i) + 새 + 조사 + 글.slice(i + 옛.length + 먹은길이);
  }
  const 뒤처리 = 남은조사고치기(글);
  return { 글: 뒤처리.글, 수: 자리들.length + 뒤처리.수 };
}

