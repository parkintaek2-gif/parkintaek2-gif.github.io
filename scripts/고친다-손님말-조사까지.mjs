/** 받침이 있나 — 조사를 가르는 기준이다 */
export function 받침있나(글자) {
  const c = 글자.charCodeAt(0);
  if (c < 0xac00 || c > 0xd7a3) return false;
  return (c - 0xac00) % 28 !== 0;
}
