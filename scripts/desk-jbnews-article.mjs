/**
 * 사장님께 낼 «한 줄 판정» — 메일 맨 위에 세운다.
 * ⛔ 좋게 적지 않는다. 못 내는 기사는 못 낸다고 적는다.
 */
export function 한줄판정(r) {
  if (!r?.됐나) return `🔴 데스킹 실패 — ${r?.까닭 ?? '까닭 모름'} · 아래는 데스킹 «전» 원문입니다`;
  const 것 = [];
  if (r.게재보류) 것.push('🔴 지금은 못 냅니다 (게재 보류)');
  else 것.push('✅ 데스킹 통과');
  if (r.사진못찾음) 것.push('사진 못 찾음');
  if (r.자체기사미충족) 것.push('자체기사 미충족');
  return 것.join(' · ');
}

