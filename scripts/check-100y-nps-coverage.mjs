/**
 * ⚠ 처음엔 `/^\d+\s*~/` 로 넓게 잡았다가 **「1~3등 업종 맞춤」 같은 내 글에 울었다**.
 *    소음이 크면 다음 진짜 경보를 못 읽는다(3번이 오늘 같은 데서 15,489장을 겪었다).
 *    → 숫자 뒤에 **「명」이 붙은 것**만 규모로 본다.
 */
const 규모꼴 = /^\d+\s*~\s*\d*\s*명/;
export function 규모이름표긁기(자료) {
  const 나온것 = new Set();
  const 훑기 = (o) => {
    if (Array.isArray(o)) return o.forEach(훑기);
    if (!o || typeof o !== 'object') return;
    for (const [k, v] of Object.entries(o)) {
      if (규모꼴.test(k)) 나온것.add(k); // 칸 이름으로 들어간 것
      if (typeof v === 'string' && 규모꼴.test(v)) 나온것.add(v); // 값으로 들어간 것
      else 훑기(v);
    }
  };
  훑기(자료);
  return [...나온것];
}

