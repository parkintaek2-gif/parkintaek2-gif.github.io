#!/usr/bin/env node
/**
 * 국민연금에서 나온 자료가 **자기가 덮는 범위를 말하고 있나** — 8번(3번 보조)
 *
 *   node scripts/check-100y-nps-coverage.mjs
 *   node scripts/check-100y-nps-coverage.mjs --자가시험
 *
 * ## 🔴 왜 만들었나 (2026-08-08 18:3x)
 *
 *   제 자료 아홉 개를 **원본과만** 맞춰 보고 「검증 6항목 전부 통과」라고 적었다.
 *   오늘 처음으로 **공표치**와 맞춰 보니 이랬다 —
 *
 *   ```
 *   공표 사업장가입자  14,674,876명 (2026-04말)
 *   우리 파일           11,561,661명  = 78.8%
 *   원자료를 세니       0명 592 · **1명 0곳** · 2~4명 174,560
 *   ```
 *
 *   ⛔ 1인 사업장이 한 곳도 없는데 내가 붙인 칸 이름은 **「1~4명」**이었다.
 *      **없는 것을 이름표에 넣으면 읽는 사람은 있다고 믿는다.**
 *
 *   ⚠ 더 무서운 것은 **원본과는 1원도 안 틀렸다**는 점이다.
 *      원본이 이미 잘라 낸 것이면, 원본과 아무리 맞아도 맞는 게 아니다.
 *
 * ## 이 자가 보는 것 셋
 *
 *   ① 국민연금에서 나온 자료마다 `덮는범위` 와 `대조` 가 있나
 *   ② 「1~4명」처럼 **자료에 없는 것을 가리키는 이름표**가 남아 있나
 *   ③ 「전국 평균 임금」처럼 **덮는 범위를 넘겨 말하는 문구**가 있나
 *
 * ⛔ 이 자는 숫자가 맞나를 못 본다. 그건 `count-100y-nps-cap-share.mjs` 의 재현이 본다.
 *    이 자가 보는 것은 **자료가 자기 한계를 말하고 있나** 하나뿐이다.
 */
import fs from 'node:fs';
import path from 'node:path';

const 여기 = path.resolve(
  path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'),
  '..',
);
const 자료방 = path.join(여기, 'src', 'data', '100yearmap');

/** 이 자료가 국민연금에서 나온 것인가 */
export function 국민연금것인가(자료) {
  const s = JSON.stringify(자료?.출처 ?? '');
  return /15083277|국민연금/.test(s);
}

/** 자료에 없는 것을 가리키는 이름표 — 값과 함께 보고 판정한다 */
export function 없는것을가리키나(이름표, 있는최소인원) {
  if (typeof 이름표 !== 'string') return false;
  const m = 이름표.match(/^(\d+)\s*~/); // 「1~4명」 꼴만 본다
  if (!m) return false;
  if (!Number.isFinite(있는최소인원)) return false;
  return Number(m[1]) < 있는최소인원;
}

/** 덮는 범위를 넘겨 말하는 문구인가 */
export function 넘겨말하나(글) {
  if (typeof 글 !== 'string') return false;
  // ⚠ 「전국 평균 임금이라 쓰지 않는다」처럼 **하지 말라고 적은 문장**은 잡지 않는다.
  //    안 쓰겠다고 적은 말에 우는 자는 소음이다 (3번이 오늘 같은 데 걸렸다)
  if (/쓰지 않는다|안 쓴다|쓰면 안|⛔/.test(글)) return false;
  return /전국\s*평균\s*임금|우리나라\s*평균\s*임금/.test(글);
}

function 자가시험() {
  const 본보기 = [
    ['국민연금 출처를 알아본다', () => 국민연금것인가({ 출처: { 데이터셋: '15083277' } }) === true],
    ['다른 출처는 아니다', () => 국민연금것인가({ 출처: { 데이터셋: '15042211' } }) === false],
    ['출처가 없어도 안 죽는다', () => 국민연금것인가({}) === false],
    ['1~4명인데 최소가 2면 운다', () => 없는것을가리키나('1~4명', 2) === true],
    ['2~4명이면 안 운다', () => 없는것을가리키나('2~4명', 2) === false],
    ['5~9명은 안 운다', () => 없는것을가리키나('5~9명', 2) === false],
    ['「1000명 이상」은 꼴이 아니라 안 본다', () => 없는것을가리키나('1000명 이상', 2) === false],
    ['최소를 모르면 안 운다', () => 없는것을가리키나('1~4명', NaN) === false],
    ['「전국 평균 임금」은 운다', () => 넘겨말하나('전국 평균 임금은 350만원') === true],
    ['⭐ 하지 말라고 적은 말에는 안 운다', () => 넘겨말하나('⛔ 「전국 평균 임금」이라 쓰지 않는다') === false],
    ['보통 문장은 안 운다', () => 넘겨말하나('업종별 임금과 버팀') === false],
    ['글이 아니면 안 운다', () => 넘겨말하나(null) === false],
  ];
  let 진 = 0;
  for (const [이름, 재기] of 본보기) {
    let 됐나 = false;
    try { 됐나 = 재기() === true; } catch { 됐나 = false; }
    if (!됐나) { console.log(`  ⛔ 자가시험 실패 — ${이름}`); 진++; }
  }
  console.log(`자가시험 ${본보기.length}개 · 실패 ${진}개`);
  return 진;
}

if (process.argv.includes('--자가시험')) process.exit(자가시험() ? 1 : 0);
const 시험실패 = 자가시험();

/* ───────────────────── 자료를 훑는다 ───────────────────── */

/**
 * 자료 안에 **실제로 있는 가장 작은 사업장 인원**을 규모 칸 이름에서 되읽는다.
 * ⛔ 원자료(archive/)는 gitignore 라 여기서 못 읽는다. 그래서 **자료가 스스로 말한 것**만 본다.
 */
const 규모칸이름 = (자료) => (자료?.자료 ?? []).map((r) => r?.규모).filter(Boolean);

const 운다 = [];
const 파일들 = fs.readdirSync(자료방).filter((f) => f.endsWith('.json'));
let 본것 = 0;

for (const f of 파일들) {
  let j;
  try { j = JSON.parse(fs.readFileSync(path.join(자료방, f), 'utf8')); } catch { continue; }
  if (!국민연금것인가(j)) continue;
  본것++;

  if (!j.덮는범위) 운다.push(`${f} — 「덮는범위」가 없다. 이 자료가 무엇을 안 덮는지 아무도 모른다`);
  if (!j.대조) 운다.push(`${f} — 「대조」가 없다. 공표치와 맞춰 본 적이 없다는 뜻이다`);

  /* 규모 칸 이름이 자료에 없는 것을 가리키나 — 「1~4명」이 남아 있으면 운다 */
  for (const 이름 of 규모칸이름(j)) {
    if (없는것을가리키나(이름, 2)) 운다.push(`${f} — 규모 칸 「${이름}」. 이 자료에 1인 사업장은 없다`);
  }

  /* 덮는 범위를 넘겨 말하는 문구 */
  for (const [칸, 값] of Object.entries(j)) {
    if (넘겨말하나(값)) 운다.push(`${f} — 「${칸}」 칸이 덮는 범위를 넘겨 말한다: ${String(값).slice(0, 40)}`);
  }
}

if (본것 === 0) {
  console.log('⬜ 국민연금에서 나온 자료를 한 개도 못 찾았다 — **재지 못했다**');
  process.exit(2);
}

console.log(`국민연금 자료 ${본것}개를 봤다`);
if (운다.length === 0) {
  console.log('✅ 덮는범위·대조 다 있음 · 없는 것을 가리키는 이름표 0 · 넘겨 말하는 문구 0');
  console.log('⚠ 이 자는 숫자가 맞나를 못 본다. 자료가 **자기 한계를 말하고 있나**만 본다');
  process.exit(시험실패 ? 1 : 0);
}
for (const x of 운다) console.log(`⛔ ${x}`);
console.log(`\n⛔ ${운다.length}건`);
process.exit(1);
