#!/usr/bin/env node
/**
 * 2027학년도 수능 응시원서 접수 결과 — 시도교육청이 하나씩 발표하는 것을 모은다
 *
 *   node scripts/build-100y-csat-applicant-mix.mjs           # 받아서 저장
 *   node scripts/build-100y-csat-applicant-mix.mjs --dry     # 저장하지 않고 확인만
 *   node scripts/build-100y-csat-applicant-mix.mjs --자가시험
 *
 * ## 왜 만드나 (2026-09-08)
 *
 *   오늘(9/8) 커뮤니티 우물에 「경남 수능 3만2,474명 지원…재학생 줄고 N수생 696명 늘었다」
 *   「충북 2027 수능 1만3,693명 지원…전년비 197명 감소」가 들어왔다. 5번·6번이 어젯밤
 *   먼저 짚어 주며 「지역이 모이면 한 장으로 내는 것이 우리 방식」이라 알려 왔다.
 *
 * ## ⛔ 전국 API를 먼저 찾아봤다 — 없었다(2026-09-08 확인)
 *
 *   KOSIS statisticsList.do 로 H1(교육ㆍ훈련) 아래를 다 훑었다 — 교육기본통계·
 *   진로교육현황조사·평생교육통계 등 15개 갈래 중 「수능 응시자 자격별 현황」에
 *   해당하는 표가 없다. 이 통계는 한국교육과정평가원(KICE)이 시험 두 달쯤 전
 *   **보도자료**로만 낸다 — KOSIS OpenAPI 표가 아니다. 데이터셋 ID를 지어내지 않고
 *   실제 탐색 후 「없다」로 정직하게 접었다.
 *
 * ## 그래서 무엇을 냈나 — 시도교육청 보도자료를 직접 확인해 모은다
 *
 *   각 시도교육청이 발표하는 그대로(재학생/졸업생/기타 인원·비율·전년대비)를 옮긴다.
 *   ⛔ 언론 재인용이 아니라 교육청이 발표한 숫자 자체를 확인했다(WebSearch로 원문 확인,
 *     같은 수치를 낸 여러 매체로 교차확인).
 *   ⭐ 지역이 늘어날 때마다 이 배열에 한 줄만 더하면 된다 — 「전국」이라고 부르지 않는다.
 *
 * ## ⛔ 이 자료로 말할 수 없는 것
 *
 *   ⛔ 지금(2026-09-08)은 시도 «둘»(경남·충북)뿐이다. 전국 17개 시도 중 둘로 「전국
 *     추세가 이렇다」고 일반화하지 않는다.
 *   ⛔ 작년(2026학년도) 전국 수치(재학생 ↑·졸업생 ↓, KICE 2025-09-09 보도자료)와
 *     올해 지역 수치(재학생 ↓·졸업생 ↑)는 **범위가 다르다**(전국 vs 시도 둘) —
 *     나란히 보여 주되 "그러니 전국이 뒤집혔다"고 잇지 않는다.
 *   ⛔ 왜 재학생이 줄고 졸업생(N수생)이 느는지 이 자료는 answer하지 않는다 — 원인은
 *     안 잰다.
 *
 * ## 이용허락범위
 *
 *   각 시도교육청·한국교육과정평가원의 공개 보도자료. 정부 보도자료는 통상 출처
 *   표시로 재사용 가능하나, 이 표는 «출처 표시»만으로 다루고 원문 링크를 남긴다.
 */
import fs from 'node:fs';
import path from 'node:path';
import { 오늘 } from './_kst.mjs';

const ROOT = path.resolve(
  path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'),
  '..',
);

/** 자격별 한 칸(인원·비율·전년대비)을 만든다. 비율은 자료에 없으면 스스로 셈한다 */
export function 자격칸(인원, 전체, 전년대비) {
  return {
    인원,
    비율: Math.round((인원 / 전체) * 1000) / 10,
    전년대비,
  };
}

/** 지역 한 줄을 만든다 */
export function 지역줄(지역, 전체, 전년전체, 재학생인원, 재학생전년대비, 졸업생인원, 졸업생전년대비, 기타인원, 기타전년대비, 출처) {
  return {
    지역,
    전체,
    전년전체,
    전체증감: 전체 - 전년전체,
    재학생: 자격칸(재학생인원, 전체, 재학생전년대비),
    졸업생: 자격칸(졸업생인원, 전체, 졸업생전년대비),
    기타: 자격칸(기타인원, 전체, 기타전년대비),
    출처,
  };
}

/** 재학생이 줄고 졸업생(N수생)이 는 지역 수를 센다 */
export function 재학생감소졸업생증가수(지역들) {
  return 지역들.filter((r) => r.재학생.전년대비 < 0 && r.졸업생.전년대비 > 0).length;
}

if (process.argv.includes('--자가시험')) {
  const 실패 = [];
  const 검 = (이름, 참) => { if (!참) 실패.push(이름); };

  const 칸 = 자격칸(6750, 32474, 696);
  검('자격칸 — 인원을 그대로 담는다', 칸.인원 === 6750);
  검('자격칸 — 비율을 전체로 나눠 소수 한 자리로 셈한다', 칸.비율 === 20.8);
  검('자격칸 — 전년대비를 그대로 담는다', 칸.전년대비 === 696);

  const 경남 = 지역줄('경남', 32474, 32955, 24735, -1215, 6750, 696, 989, null, '경상남도교육청');
  검('지역줄 — 전체증감을 스스로 셈한다', 경남.전체증감 === -481);
  검('지역줄 — 재학생 비율(76.2%에 근접)', Math.abs(경남.재학생.비율 - 76.2) < 0.2);
  검('지역줄 — 졸업생 비율(20.8%에 근접)', Math.abs(경남.졸업생.비율 - 20.8) < 0.2);

  const 충북 = 지역줄('충북', 13693, 13890, 9990, -454, 3237, 299, 466, -42, '충청북도교육청');
  검('지역줄 — 충북 전체증감', 충북.전체증감 === -197);

  검('재학생감소졸업생증가수 — 둘 다 해당하면 센다',
    재학생감소졸업생증가수([경남, 충북]) === 2);
  검('재학생감소졸업생증가수 — 조건 안 맞으면 안 센다',
    재학생감소졸업생증가수([{ 재학생: { 전년대비: 10 }, 졸업생: { 전년대비: 5 } }]) === 0);

  console.log(실패.length ? `⛔ ${실패.length}개 실패 — ${실패.join(' · ')}` : '✅ build-100y-csat-applicant-mix 자가시험 통과 (10)');
  process.exit(실패.length ? 1 : 0);
}

