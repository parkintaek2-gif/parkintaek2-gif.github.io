/**
 * build-100y-university-employment-spread.mjs
 *
 * 이슈  2026-09-07 커뮤니티 씨앗 — 「국·공립대 취업률 1위 목포해양대, 2027 수시모집 돌입」.
 *       ⛔ 「1위」로 뭉뚱그리지 않는다 — 국공립대 43곳 취업률 분포에서 목포해양대가
 *       어디쯤 있는지를 그대로 보여 준다(줄 세우지 않는다, 사장님 강령).
 *
 * 새 API 호출 없음 — 이미 수집된 src/data/100yearmap/pages-university.json
 * (대학알리미, 377개 대학·캠퍼스, attach-employment.mjs가 붙인 취업률)을 재계산만 한다.
 *
 * 쓰는 법  node scripts/build-100y-university-employment-spread.mjs [--selftest]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const 원본길 = path.join(ROOT, 'src/data/100yearmap/pages-university.json');
const 낼길 = path.join(ROOT, 'src/data/100yearmap/university-employment-spread.json');

export function 정리(대학목록) {
  const 취업률있음 = 대학목록.filter((x) => x.취업률 && typeof x.취업률.값 === 'number');

  const 분포 = (배열) => {
    const v = 배열.map((x) => x.취업률.값).sort((a, b) => a - b);
    return {
      곳수: v.length,
      최소: v[0],
      최대: v[v.length - 1],
      중앙값: v[Math.floor(v.length / 2)],
    };
  };

  const 위치찾기 = (배열, 값) => {
    const 낮은수 = 배열.filter((x) => x.취업률.값 < 값).length;
    return { 낮은수, 전체: 배열.length, 몫: Math.round((낮은수 / 배열.length) * 1000) / 10 };
  };

  const 국공립 = 취업률있음.filter((x) => x.설립 === '국립' || x.설립 === '공립');
  const 사립 = 취업률있음.filter((x) => x.설립 === '사립');

  const 목포 = 취업률있음.find((x) => x.title.includes('목포해양'));
  if (!목포) throw new Error('국립목포해양대학교를 찾지 못했다 — 원자료가 바뀌었을 수 있다');

  const 영근처 = 취업률있음
    .filter((x) => x.취업률.값 === 0)
    .map((x) => ({ 학교: x.title, 졸업자: x.졸업자, 취업자: x.취업자, 취업대상자: x.취업대상자 }));

  return {
    출처: {
      이름: '한국대학교육협의회 대학정보공시(대학알리미) — 이미 수집된 pages-university.json 재계산',
      이용허락범위: '제한 없음',
    },
    공시연도: 취업률있음[0]?.공시연도 ?? null,
    정의: {
      취업률: '대학알리미 공시 취업률(값). 계산식은 건보DB 등록 취업자 ÷ 취업대상자(졸업자 − 진학자·입대자·제외인정자 등) × 100 — 대학알리미가 공시한 값을 그대로 옮겼다.',
    },
    전체: { ...분포(취업률있음), 전국평균참고: 취업률있음[0]?.취업률?.전국평균 ?? null },
    국공립: { ...분포(국공립), 위치_목포해양대: 위치찾기(국공립, 목포.취업률.값) },
    사립: 분포(사립),
    목포해양대: {
      전체이름: 목포.title,
      취업률: 목포.취업률.값,
      전국평균: 목포.취업률.전국평균,
      차이: 목포.취업률.차이,
      졸업자: 목포.졸업자,
      취업자: 목포.취업자,
      취업대상자: 목포.취업대상자,
    },
    영근처_특수학교: 영근처,
    덮는범위: [
      '대학알리미 취업률은 대학 하나의 평균이다 — 같은 학교 안에서도 학과별 편차가 크다(major-outcomes.json 참조).',
      '취업률이 0%인 5곳은 신학대·가톨릭대 등 특수 계열이라 취업대상자 자체가 매우 작거나 없다 — 일반 대학과 단순 비교가 안 된다.',
      '해양대는 해기사 등 특수 취업 경로가 있어 계열 구성이 다른 대학과 다르다. 「더 잘한다」로 읽지 않는다.',
    ],
    대조: '맞다 — 이 표의 모든 값은 pages-university.json에 이미 있던 대학알리미 공시치를 그대로 옮겨 분포만 다시 계산했다. 새로 받은 값이 없다.',
  };
}

/* ── 자가시험 ─────────────────────────────────────────── */
if (process.argv.includes('--selftest')) {
  const 본다 = (말, 참) => { console.log(참 ? '✅' : '🔴', 말); if (!참) process.exitCode = 1; };

  const 가짜 = [
    { title: '가짜국립대', 설립: '국립', 취업률: { 값: 70, 전국평균: 62.8, 차이: 7.2 }, 졸업자: 100, 취업자: 70, 취업대상자: 100, 공시연도: '2025' },
    { title: '국립목포해양대학교', 설립: '국립', 취업률: { 값: 79, 전국평균: 62.8, 차이: 16.2 }, 졸업자: 705, 취업자: 500, 취업대상자: 633, 공시연도: '2025' },
    { title: '가짜공립대', 설립: '공립', 취업률: { 값: 50, 전국평균: 62.8, 차이: -12.8 }, 졸업자: 50, 취업자: 25, 취업대상자: 50, 공시연도: '2025' },
    { title: '가짜사립대', 설립: '사립', 취업률: { 값: 60, 전국평균: 62.8, 차이: -2.8 }, 졸업자: 200, 취업자: 120, 취업대상자: 200, 공시연도: '2025' },
    { title: '가짜신학대', 설립: '사립', 취업률: { 값: 0, 전국평균: 62.8, 차이: -62.8 }, 졸업자: 20, 취업자: 0, 취업대상자: 0, 공시연도: '2025' },
  ];

  const 결과 = 정리(가짜);
  본다('① 목포해양대를 찾았다', 결과.목포해양대.취업률 === 79);
  본다('② 국공립 곳수가 3곳이다(가짜국립·목포·가짜공립)', 결과.국공립.곳수 === 3);
  본다('③ 국공립 안에서 목포보다 낮은 곳이 2곳이다', 결과.국공립.위치_목포해양대.낮은수 === 2);
  본다('④ 사립 곳수가 2곳이다', 결과.사립.곳수 === 2);
  본다('⑤ 0%대 특수학교를 따로 걸렀다', 결과.영근처_특수학교.length === 1 && 결과.영근처_특수학교[0].학교 === '가짜신학대');
  본다('⑥ 정의 필드가 있다(check-100y-basis 대응)', typeof 결과.정의.취업률 === 'string' && 결과.정의.취업률.length > 0);
  본다('⑦ 출처.이용허락범위가 중첩돼 있다', 결과.출처.이용허락범위 === '제한 없음');
  본다('⑧ 대조 필드가 있다', typeof 결과.대조 === 'string' && 결과.대조.length > 0);
  본다('⑨ 덮는범위가 배열이다', Array.isArray(결과.덮는범위) && 결과.덮는범위.length > 0);
  본다('⑩ 순위·등수 낱말을 안 쓴다', !JSON.stringify(결과).match(/순위|등수|랭킹|몇 위|꼴찌|1위/));

  console.log('\n실제 원자료로도 돌려 본다…');
  const 진짜자료 = JSON.parse(fs.readFileSync(원본길, 'utf8'));
  const 진짜결과 = 정리(진짜자료);
  console.log(`전체 ${진짜결과.전체.곳수}곳 · 국공립 ${진짜결과.국공립.곳수}곳 · 목포해양대 국공립 내 위치 ${진짜결과.국공립.위치_목포해양대.낮은수}/${진짜결과.국공립.위치_목포해양대.전체}(${진짜결과.국공립.위치_목포해양대.몫}%)`);
  process.exit();
}

/* 🔴 여기부터가 «부르면 도는 몸»이다 */
const 내가직접불렸나 = !!process.argv[1] && path.basename(process.argv[1]) === 'build-100y-university-employment-spread.mjs';
if (내가직접불렸나) {
  const 원자료 = JSON.parse(fs.readFileSync(원본길, 'utf8'));
  const 결과 = 정리(원자료);
  fs.writeFileSync(낼길, JSON.stringify(결과, null, 2) + '\n', 'utf8');
  console.log('✅ 썼다 →', 낼길);
  console.log(`전체 ${결과.전체.곳수}곳 · 국공립 ${결과.국공립.곳수}곳 · 목포해양대 국공립 내 위치 ${결과.국공립.위치_목포해양대.낮은수}/${결과.국공립.위치_목포해양대.전체}`);
}
